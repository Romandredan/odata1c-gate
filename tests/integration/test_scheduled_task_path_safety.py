"""`daemon.spawn_detached` на домашнем каталоге с пробелом или знаком `%` в пути (план M1d,
задача 6, раунд правок 2, находка Б.1, Critical) и доставка окружения через Планировщик заданий
(находка Б.5).

До правки раунда 2: `/tr` передавался Планировщику заданий НЕ закавыченным — путь с пробелом
разбивал командную строку задачи на программу и обрывок аргумента; путь со знаком `%` был хуже —
`cmd.exe` раскрывал `%…%` ВНУТРИ кавычек тела `.cmd`, что рвало саму команду запуска и в прогоне
ревьюера поднимало «левый» демон с искажённым `--home` на порту по умолчанию (7171). В обоих
случаях `schtasks /create`/`/run` возвращали 0 («УСПЕХ»), поэтому отката на `CreateProcess` не
было.

Задача «окно консоли»: `.cmd` из цепочки убран (он рисовал владельцу окно `cmd.exe`), задача
запускает оконный интерпретатор `pythonw.exe` с пусковым файлом на Python. Кавычки вокруг путей
в `/tr` остались нужны ровно так же; удвоение `%` ушло вместе с `cmd.exe` — раскрывать его больше
некому, и это проверяется здесь тем же способом, что и раньше, исполнением.

Настоящий Планировщик заданий — не подмена: сама суть находки в том, что код возврата `schtasks`
лжёт, эта ложь наблюдаема только на реальном вызове."""

from __future__ import annotations

import socket
import sys
import time

import pytest

from odata1c import daemon as daemon_module
from odata1c.config.home import ensure_home
from odata1c.config.writer import ensure_gate_secret
from odata1c.daemon import is_listening, spawn_detached
from odata1c.daemon import stop as daemon_stop

ПРЕДЕЛ_ГОТОВНОСТИ_С = 20
ПРЕДЕЛ_ОСТАНОВКИ_С = 10

pytestmark = pytest.mark.skipif(sys.platform != "win32", reason="Планировщик заданий — Windows")


def _свободный_порт() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as соединение:
        соединение.bind(("127.0.0.1", 0))
        return соединение.getsockname()[1]


# Сколько ждать подтверждения Планировщика заданий там, где тест требует подъёма именно через
# него. Штатные 6 с — компромисс работы (дольше ждать отката владельцу незачем); исполнитель
# GitHub Actions в них не укладывается, а проверяется здесь правильность разбора пути, а не
# скорость чужой машины.
ОЖИДАНИЕ_В_ПРОВЕРКЕ_С = 90.0


def _следить_за_путём_подъёма(monkeypatch, *, ждать_дольше: bool) -> list[bool]:
    """Записывать ответы `_spawn_via_scheduled_task`. Возвращает список ответов — по одному на
    вызов `spawn_detached`.

    `ждать_дольше` — только там, где Планировщик заданий обязан сработать сам: ему дают время
    медленной машины. Там, где проверяется как раз ОТКАТ, ожидание остаётся рабочим (6 с) —
    иначе тест ждал бы отказа полторы минуты."""
    ответы: list[bool] = []
    исходный = daemon_module._spawn_via_scheduled_task

    def обёртка(*позиционные, **именованные):
        ответ = исходный(*позиционные, **именованные)
        ответы.append(ответ)
        return ответ

    monkeypatch.setattr(daemon_module, "_spawn_via_scheduled_task", обёртка)
    if ждать_дольше:
        monkeypatch.setattr(
            daemon_module, "ОЖИДАНИЕ_ПОДТВЕРЖДЕНИЯ_SCHTASKS_S", ОЖИДАНИЕ_В_ПРОВЕРКЕ_С
        )
    return ответы


def _поднять_и_проверить(
    tmp_path, имя_каталога: str, *, через_планировщик: bool | None = None, monkeypatch=None
):
    """Поднять демон на домашнем каталоге с таким именем и убедиться, что он работает.

    `через_планировщик` — обязательное требование к ПУТИ подъёма, а не к его скорости:
    `True` — задача Планировщика заданий должна была сработать сама, без отката на
    `CreateProcess`; `None` — путь безразличен.

    Прежде это различали временем подъёма (откат добавляет `ОЖИДАНИЕ_ПОДТВЕРЖДЕНИЯ_SCHTASKS_S`
    ожидания). На своей машине порог держался, на исполнителе GitHub Actions — нет: подъём через
    сам Планировщик занимал там 6,5 и 10,5 с при пороге 6,0 с, и красным становился исправный
    код. Ответ `_spawn_via_scheduled_task` отвечает на тот же вопрос прямо, а не по косвенному
    признаку, и от скорости машины не зависит: без закавыченного `/tr` Планировщик по-прежнему не
    поднимает ничего и ответ остаётся `False`, сколько его ни жди."""
    home = tmp_path / имя_каталога
    ensure_home(home)
    порт = _свободный_порт()
    (home / "daemon.yaml").write_text(f"port: {порт}\n", encoding="utf-8")
    ensure_gate_secret(home / "daemon.yaml")
    (home / "bases.yaml").write_text("bases: {}\n", encoding="utf-8")
    ответы_планировщика = (
        _следить_за_путём_подъёма(monkeypatch, ждать_дольше=через_планировщик)
        if через_планировщик is not None
        else None
    )

    try:
        spawn_detached(home, порт)
        # Готовность — порт И pid-файл: демон пишет файл после того, как uvicorn занял порт
        # (`serve`), и на загруженной машине между этими двумя событиями успевает пройти виток
        # этого цикла. Ждать одного порта значит время от времени проверять утверждение ниже
        # раньше, чем оно вообще может стать истинным.
        pid_файл = home / "daemon.pid"
        предел = time.monotonic() + ПРЕДЕЛ_ГОТОВНОСТИ_С
        while time.monotonic() < предел:
            if is_listening(порт) and pid_файл.exists():
                break
            time.sleep(0.2)
        assert is_listening(порт), f"демон не поднялся на домашнем каталоге {имя_каталога!r}"
        # Находка Б.1: успех — не просто «порт слушается» (могло слушать что угодно, включая
        # «левого» демона на порту по умолчанию из-за искажённого --home), а именно ИЗ ЭТОГО
        # домашнего каталога — pid-файл появляется в serve() только после реального биндинга.
        assert pid_файл.exists(), (
            "порт слушается, но daemon.pid в этом домашнем каталоге не появился — "
            "порт мог занять посторонний процесс, а не наш демон"
        )
        if ответы_планировщика is not None:
            # Ключевая проверка мутационной чувствительности: без кавычек `/tr` schtasks на этом
            # пути «успешно» не поднимает НИЧЕГО, и код доходит до отката `CreateProcess` — то
            # есть даже без закавыченного `/tr` проверка выше (просто «демон поднялся») прошла бы
            # БЛАГОДАРЯ отдельной защите Б.1в (не верить коду возврата, откатываться). Здесь
            # отличается «схема заработала САМА» от «спас только откат».
            assert ответы_планировщика == [через_планировщик], (
                f"путь подъёма не тот: ответы _spawn_via_scheduled_task {ответы_планировщика}, "
                f"ожидалось [{через_планировщик}]"
            )
        return home
    finally:
        if is_listening(порт):
            daemon_stop(home)
            предел = time.monotonic() + ПРЕДЕЛ_ОСТАНОВКИ_С
            while is_listening(порт) and time.monotonic() < предел:
                time.sleep(0.2)


@pytest.mark.parametrize("имя_каталога", ["sp ace", "100%done"])
def test_демон_поднимается_через_schtasks_несмотря_на_особый_символ_в_пути(
    tmp_path, имя_каталога, monkeypatch
):
    """Пробел в пути лечится закавыченным `/tr` (Планировщик разбирает строку задачи как
    командную: без кавычек `…\\sp ace\\launch-….py` распадается на программу `…\\sp` и обрывок
    аргумента). Содержательный `%` после ухода `cmd.exe` не требует уже ничего: раскрывать его
    внутри пускового файла некому, путь доходит как есть.

    Демон обязан подняться через сам Планировщик заданий, а не через запасной откат: если бы
    разбор пути не работал, его спасал бы только откат."""
    _поднять_и_проверить(tmp_path, имя_каталога, через_планировщик=True, monkeypatch=monkeypatch)


def test_демон_поднимается_через_откат_когда_имя_каталога_это_переменная_окружения(
    tmp_path, monkeypatch
):
    """`%USERNAME%dir` — знак `%` здесь часть самого ПУТИ к пусковому файлу (значения `/tr`), а не
    его содержимого. Раскрывает такую запись сам Планировщик заданий, разбирая строку задачи, —
    до всякого интерпретатора (проверено пробой: с `pythonw.exe` и пусковым файлом на Python,
    когда никакого `cmd.exe` в цепочке уже нет, каталоги `sp ace` и `100%done` работают, а
    `%USERNAME%dir` по-прежнему не находится). Экранировать это с нашей стороны нечем.

    Ожидаемое поведение — не «магически подняться быстро», а честно распознать отказ (демон не
    появился за `ОЖИДАНИЕ_ПОДТВЕРЖДЕНИЯ_SCHTASKS_S`) и откатиться на `CreateProcess`, который
    путь с `%` в аргументах обрабатывает верно (список аргументов, не сырая командная строка).

    Прежде тест нёс `filterwarnings` на `PytestUnraisableExceptionWarning`: откат создавал
    `subprocess.Popen` отвязанного демона, которого никто не ждёт, и его финализатор сообщал
    «process still running». Подавление снято — ссылку на такой процесс теперь держит сам
    `spawn_detached` (`daemon._не_терять_ссылку`), и сообщать финализатору больше не о чем."""
    _поднять_и_проверить(
        tmp_path, "%USERNAME%dir", через_планировщик=False, monkeypatch=monkeypatch
    )


def test_журнал_демона_под_оконным_интерпретатором_читаем(tmp_path):
    """Задача «окно консоли», сторож на вывод. У `pythonw.exe` нет консоли, а значит нет и
    `sys.stdout`/`sys.stderr` — без правки любая запись туда стала бы ошибкой у пишущего, а
    строки, которые раньше уходили в консоль, пропали бы совсем.

    Проверяется настоящий поднятый демон: в журнале запуска есть строка пускового файла (её он
    пишет до импорта чего бы то ни было), в журнале демона — его собственная запись о том, что он
    слушает порт, и обе читаются как utf-8 (кириллица не превратилась в кодовую страницу ANSI)."""
    home = _поднять_и_проверить(tmp_path, "журнал")

    запуск = (home / "logs" / "daemon-launch.log").read_text(encoding="utf-8")
    assert "пусковой файл" in запуск, f"пусковой файл не отчитался в журнале запуска: {запуск!r}"

    журнал = (home / "logs" / "daemon.log").read_text(encoding="utf-8")
    assert "демон слушает" in журнал, f"демон не записал в журнал, что слушает порт: {журнал!r}"

    # Ревью M1d, раунд 4, пункт 5: в журнал попадают и ЧУЖИЕ логгеры того же процесса. Проверяется
    # на настоящем демоне, а не подстановкой записи: uvicorn по умолчанию уводит свои сообщения
    # в собственный обработчик с `propagate: False`, и увидеть их в `daemon.log` можно, только
    # если `serve()` действительно отказался от его настройки логирования.
    assert "uvicorn" in журнал, (
        f"в журнале нет ни строки от uvicorn — чужие логгеры снова немы: {журнал!r}"
    )


