# Находка Б.5: значимое окружение (прокси, корневые сертификаты) должно доходить до процесса,
# поднятого через Планировщик заданий — тот берёт окружение из профиля пользователя, а не от
# процесса-родителя.
# -------------------------------------------------------------------------------------------


def test_переменные_окружения_доходят_до_процесса_через_планировщик(tmp_path, monkeypatch):
    """Настоящий `schtasks`, настоящий дочерний процесс — не тот же самый `odata1c daemon`
    (ему незачем: проверяется механизм передачи окружения, а не сам демон), а маленький
    маркер-скрипт, дублирующий значения переменных окружения в файл. `is_listening`/`daemon.pid`
    подменены — критерий успеха `_spawn_via_scheduled_task` («порт слушается И daemon.pid
    появился») рассчитан на настоящий демон, а не на произвольный процесс; здесь достаточно
    факта, что Планировщик реально запустил пусковой файл.

    Значения нарочно те, что прежний путь через `.cmd` терял: `%` требовал удвоения, кавычка
    закрывала строку `set` и превращала остаток в отдельную команду, `!` подменялся содержимым
    посторонней переменной при включённом отложенном раскрытии — такие переменные приходилось
    молча отбрасывать. В пусковом файле на Python они доходят целыми."""
    home = tmp_path / "home"
    home.mkdir()
    (home / "logs").mkdir()
    (home / "daemon.pid").write_text("1", encoding="utf-8")
    маркер = home / "env_marker.txt"

    monkeypatch.setenv("HTTP_PROXY", "http://proxy.example.test:3128")
    monkeypatch.setenv("SSL_CERT_FILE", "C:\\ca\\100%valid.pem")
    monkeypatch.setenv("NO_PROXY", 'x" & rem !PATH!')
    monkeypatch.delenv("REQUESTS_CA_BUNDLE", raising=False)  # эту НЕ выставляем — не должна попасть

    скрипт = home / "print_env.py"
    скрипт.write_text(
        "import os, pathlib\n"
        "переменные = ['HTTP_PROXY', 'SSL_CERT_FILE', 'NO_PROXY', 'REQUESTS_CA_BUNDLE']\n"
        "строки = [имя + '=' + os.environ.get(имя, '<НЕТ>') for имя in переменные]\n"
        f"pathlib.Path(r'{маркер}').write_text(chr(10).join(строки), encoding='utf-8')\n",
        encoding="utf-8",
    )

    # `is_listening` не может быть True мгновенно: реальному Планировщику нужно время, чтобы
    # ДЕЙСТВИТЕЛЬНО начать выполнять задачу (`/run` только запускает её, не ждёт старта процесса).
    # Мгновенное True вернуло бы успех на первой же проверке и оборвало ожидание раньше, чем ОС
    # успела бы дойти до маркера. Задержка ниже имитирует естественный темп холодного старта.
    начало_ожидания = time.monotonic()
    monkeypatch.setattr(
        daemon_module,
        "is_listening",
        lambda port, timeout=0.5: time.monotonic() - начало_ожидания > 1.5,
    )
    итог = daemon_module._spawn_via_scheduled_task(
        home,
        [daemon_module._интерпретатор_без_консоли(), "-X", "utf8", str(скрипт)],
        home / "logs" / "marker.log",
        1,
    )
    assert итог is True

    предел = time.monotonic() + 10
    while not маркер.exists() and time.monotonic() < предел:
        time.sleep(0.2)
    assert маркер.exists(), "маркер-скрипт не выполнился за отведённое время"
    содержимое = маркер.read_text(encoding="utf-8")
    assert "HTTP_PROXY=http://proxy.example.test:3128" in содержимое
    assert "SSL_CERT_FILE=C:\\ca\\100%valid.pem" in содержимое
    assert 'NO_PROXY=x" & rem !PATH!' in содержимое
    assert "REQUESTS_CA_BUNDLE=<НЕТ>" in содержимое
