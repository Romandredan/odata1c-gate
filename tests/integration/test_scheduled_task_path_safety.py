"""`daemon.spawn_detached` на домашнем каталоге с пробелом или знаком `%` в пути (план M1d,
задача 6, раунд правок 2, находка Б.1, Critical).

До правки: `/tr` передавался Планировщику заданий НЕ закавыченным — путь с пробелом разбивал
командную строку задачи на программу и обрывок аргумента; путь со знаком `%` был хуже — `cmd.exe`
раскрывал `%…%` ВНУТРИ кавычек тела `.cmd`, что рвало саму команду запуска и в прогоне ревьюера
поднимало «левый» демон с искажённым `--home` на порту по умолчанию (7171). В обоих случаях
`schtasks /create`/`/run` возвращали 0 («УСПЕХ»), поэтому отката на `CreateProcess` не было.

Настоящий Планировщик заданий — не подмена: сама суть находки в том, что код возврата `schtasks`
лжёт, эта ложь наблюдаема только на реальном вызове."""

from __future__ import annotations

import socket
import sys
import time

import pytest

from odata1c import daemon as daemon_module
from odata1c.config.home import ensure_home
from odata1c.config.writer import ensure_gate_secret
from odata1c.daemon import ОЖИДАНИЕ_ПОДТВЕРЖДЕНИЯ_SCHTASKS_S, is_listening, spawn_detached
from odata1c.daemon import stop as daemon_stop

ПРЕДЕЛ_ГОТОВНОСТИ_С = 20
ПРЕДЕЛ_ОСТАНОВКИ_С = 10

pytestmark = pytest.mark.skipif(sys.platform != "win32", reason="Планировщик заданий — Windows")


def _свободный_порт() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as соединение:
        соединение.bind(("127.0.0.1", 0))
        return соединение.getsockname()[1]


def _поднять_и_проверить(tmp_path, имя_каталога: str, *, макс_время_с: float | None) -> None:
    home = tmp_path / имя_каталога
    ensure_home(home)
    порт = _свободный_порт()
    (home / "daemon.yaml").write_text(f"port: {порт}\n", encoding="utf-8")
    ensure_gate_secret(home / "daemon.yaml")
    (home / "bases.yaml").write_text("bases: {}\n", encoding="utf-8")

    try:
        начало = time.monotonic()
        spawn_detached(home, порт)
        предел = time.monotonic() + ПРЕДЕЛ_ГОТОВНОСТИ_С
        while time.monotonic() < предел:
            if is_listening(порт):
                break
            time.sleep(0.2)
        время = time.monotonic() - начало
        assert is_listening(порт), f"демон не поднялся на домашнем каталоге {имя_каталога!r}"
        # Находка Б.1: успех — не просто «порт слушается» (могло слушать что угодно, включая
        # «левого» демона на порту по умолчанию из-за искажённого --home), а именно ИЗ ЭТОГО
        # домашнего каталога — pid-файл появляется в serve() только после реального биндинга.
        assert (home / "daemon.pid").exists(), (
            "порт слушается, но daemon.pid в этом домашнем каталоге не появился — "
            "порт мог занять посторонний процесс, а не наш демон"
        )
        if макс_время_с is not None:
            # Ключевая проверка мутационной чувствительности: без кавычек `/tr`/без удвоения `%`
            # schtasks на этом пути «успешно» не поднимает НИЧЕГО за отведённое окно, и код падает
            # на откат `CreateProcess` — то есть даже без закавыченного `/tr` тест выше (просто
            # «демон поднялся») прошёл бы БЛАГОДАРЯ отдельной защите Б.1в (не верить коду возврата,
            # откатываться). Чтобы отличить «схема заработала САМА» от «спас только откат»,
            # проверяем время: путь через Планировщик заданий укладывается в разы меньше, чем
            # `ОЖИДАНИЕ_ПОДТВЕРЖДЕНИЯ_SCHTASKS_S` (6 с) — откат добавляет минимум эти 6 с
            # ожидания, прежде чем вообще начать `CreateProcess`.
            assert время < макс_время_с, (
                f"демон поднялся за {время:.1f} с — так долго, будто сработал откат на "
                f"CreateProcess (порог отката {ОЖИДАНИЕ_ПОДТВЕРЖДЕНИЯ_SCHTASKS_S} с), а не сам "
                "Планировщик заданий"
            )
    finally:
        if is_listening(порт):
            daemon_stop(home)
            предел = time.monotonic() + ПРЕДЕЛ_ОСТАНОВКИ_С
            while is_listening(порт) and time.monotonic() < предел:
                time.sleep(0.2)


@pytest.mark.parametrize("имя_каталога", ["sp ace", "100%done"])
def test_демон_поднимается_через_schtasks_несмотря_на_особый_символ_в_пути(tmp_path, имя_каталога):
    """Пробел и содержательный `%` внутри тела `.cmd` — обе причины Б.1 лечатся на уровне
    экранирования (закавыченный `/tr`, удвоенный `%`), поэтому демон обязан подняться БЫСТРО,
    через сам Планировщик заданий, а не через запасной откат: если бы экранирование не работало,
    его спасал бы только откат — а откат добавляет заведомо заметную задержку
    (`ОЖИДАНИЕ_ПОДТВЕРЖДЕНИЯ_SCHTASKS_S`), которую эта проверка и ловит."""
