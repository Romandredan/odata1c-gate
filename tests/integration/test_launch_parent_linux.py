"""Заверение родителя лаунчера на Linux — подставным родителем, на настоящем дереве процессов
(M3 задача 9; Ruling 61).

Что здесь настоящее: процессы, их дерево и `/proc`. Подменён ровно один участник — сам Claude
Code: вместо него копия исполняемого файла под именем `claude`. Так его и ставит нативный
установщик — файлом с этим именем, — и различать имя образа `родитель_заверён` обязан на настоящем
дереве, а не на списке, переданном аргументом (это проверяет `tests/unit/test_launch_parent.py`).

Цепочка обеих проверок одна и та же: верхний процесс → шим (`python3`) → лаунчер. Шим в середине
не для красоты: он проверяет, что подъём сквозь шимы работает и на Linux, а не только имя
непосредственного родителя. Отличаются проверки ровно одним — ИМЕНЕМ верхнего процесса: копия
`bash` под именем `claude` заверяется, тот же самый `bash` под своим именем — нет. Скрипт модели,
запущенный из Bash, — ровно тот случай, ради которого заверение и существует, и ответ на него
обязан быть `(False, "bash")`, а не «не удалось определить».

Почему копия `bash`, а не копия интерпретатора Python (как предполагал план): имя образа — всё,
что здесь проверяется, и одинаковый для обеих проверок файл оставляет между ними ровно одно
различие. Копия интерпретатора добавила бы к проверке постороннюю зависимость: у интерпретатора,
поставленного `uv`, своя разделяемая библиотека рядом, и копия одного файла на другом пути может
не запуститься вовсе — красный тест говорил бы о поставке Python, а не о заверении.

Копия, а не символьная ссылка: имя берётся из `/proc/<pid>/exe`, а ссылка разрешилась бы в
исходный `bash` — проверка молча потеряла бы смысл.
"""

from __future__ import annotations

import os
import pathlib
import shutil
import subprocess
import sys

import pytest

import odata1c

pytestmark = pytest.mark.skipif(sys.platform != "linux", reason="дерево процессов из /proc — Linux")

# Самый нижний процесс цепочки: печатает ответ заверения и больше ничего.
ЛАУНЧЕР = "from odata1c.launch_parent import родитель_заверён; print(родитель_заверён({'claude'}))"

# Верхний процесс (оболочка) запускает шим и ДОЖИДАЕТСЯ его: без завершающего `exit` оболочка
# заменила бы собой последнюю команду (обычная оптимизация bash), верхнего процесса в дереве не
# осталось бы вовсе и проверялось бы не то. `$0` — интерпретатор, `$1` — код шима.
СКРИПТ_ОБОЛОЧКИ = '"$0" -c "$1"; exit $?'


def _окружение() -> dict[str, str]:
    """`PYTHONPATH` на корень пакета: цепочку поднимает не `uv run`, а обычный интерпретатор, и
    своих путей у него нет. Модулю этого довольно — `launch_parent` обходится стандартной
    библиотекой. `PYTHONUTF8` — ради кириллицы в имени `родитель_заверён`: в окружении прогона
    локаль может быть `C`, и аргумент `-c` расшифровался бы не как utf-8."""
    корень_пакета = pathlib.Path(odata1c.__file__).resolve().parent.parent
    return {**os.environ, "PYTHONPATH": str(корень_пакета), "PYTHONUTF8": "1"}


def _шим(запуск: list[str]) -> str:
    """Код промежуточного процесса: запускает лаунчер и пересказывает его вывод."""
    return (
        "import subprocess, sys;"
        f"итог = subprocess.run({запуск!r}, capture_output=True, text=True);"
        "sys.stdout.write(итог.stdout); sys.stderr.write(итог.stderr);"
        "sys.exit(итог.returncode)"
    )


def _прогнать(оболочка: str) -> str:
    итог = subprocess.run(
        [
            оболочка,
            "-c",
            СКРИПТ_ОБОЛОЧКИ,
            sys.executable,
            _шим([sys.executable, "-c", ЛАУНЧЕР]),
        ],
        capture_output=True,
        text=True,
        env=_окружение(),
        timeout=60,
    )
    assert итог.returncode == 0, f"цепочка не отработала: {итог.stderr}"
    return итог.stdout.strip()


@pytest.fixture
def оболочка() -> str:
    путь = shutil.which("bash")
    if not путь:
        pytest.skip("в окружении прогона нет bash — цепочку процессов не собрать")
    return путь


def test_родитель_claude_заверяется(tmp_path, оболочка):
    """`claude` → `python3` (шим) → лаунчер: шим прозрачен, значимый предок — `claude`."""
    поддельный = tmp_path / "claude"
    shutil.copy2(оболочка, поддельный)
    поддельный.chmod(0o755)

    assert _прогнать(str(поддельный)) == "(True, 'claude')"


def test_родитель_bash_не_заверяется(оболочка):
    """Тот же файл под своим именем: `bash` — не шим и не Claude Code, заверения нет."""
    assert _прогнать(оболочка) == "(False, 'bash')"
