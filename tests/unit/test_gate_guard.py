def test_невидимые_символы_до_внутри_и_после_названия_не_мешают_замене(страж):
    """Мягкий перенос, пробел нулевой ширины и метка направления письма — не пробел ни для
    `str.isspace()`, ни для ключей словаря; обычный мусор при копировании названия с веб-страницы
    в комментарий 1С. Символы расставлены и до, и внутри, и после названия — карта позиций после
    их вырезания обязана по-прежнему указывать на верные места исходной строки, а не портить
    текст вокруг найденного совпадения (та же порча, что чинили с `İ` прошлым раундом)."""
    словарь, охрана = страж
    словарь.token_for("org", "ООО Ромашка", base="ut", entity="E", field="Description")
    невидимый_до = "​"  # пробел нулевой ширины
    мягкий_перенос = "­"
    невидимый_внутри = "​"
    метка_после = "‎"  # метка письма слева направо
    текст = (
        '{"c": "'
        + невидимый_до
        + "звонили из ООО"
        + мягкий_перенос
        + " Р"
        + невидимый_внутри
        + "омашка"
        + метка_после
        + ' вчера"}'
    )
    результат = охрана.check(текст, mode="identifiers+names")
    assert "Ромашка" not in результат.text
    assert "омашка" not in результат.text
    assert результат.text.endswith(' вчера"}')
    assert "[[org:1]]" in результат.text


