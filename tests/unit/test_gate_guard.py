# --- Ревью 2026-09-09: дыры 1-2 — названия сверяются без нормализации ---


@pytest.mark.parametrize(
    "текст",
    [
        "звонили из ООО Ромашка вчера",
        "звонили из ООО  Ромашка вчера",  # два пробела
        "звонили из ООО\xa0Ромашка вчера",  # неразрывный пробел
        "звонили из ООО «Ромашка» вчера",  # кавычки-ёлочки
    ],
)
def test_известное_название_ловится_в_разных_написаниях(страж, текст):
    словарь, охрана = страж
    словарь.token_for("org", "ООО Ромашка", base="ut", entity="E", field="Description")
    результат = охрана.check('{"комментарий": "' + текст + '"}', mode="identifiers+names")
    assert "Ромашка" not in результат.text
    assert результат.warnings == ["guard_replaced"]


def test_символ_с_удлиняющимся_регистром_не_ломает_остаток_ответа(страж):
    """`İ` (U+0130) в нижнем регистре — два знака вместо одного: полное `text.lower()` сдвинуло
    бы индексы совпадений автомата и испортило хвост ответа за найденным названием."""
    словарь, охрана = страж
    словарь.token_for("org", "ООО Ромашка", base="ut", entity="E", field="Description")
    текст = '{"a": "' + "İ" * 11 + ' звонили из ООО Ромашка вчера"}'
    результат = охрана.check(текст, mode="identifiers+names")
    assert "Ромашка" not in результат.text
    assert результат.text.endswith('вчера"}')


