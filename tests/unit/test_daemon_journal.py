"""Журнал демона ловит не только свои сообщения (ревью M1d, раунд 4, пункт 5).

Файловый обработчик висел ТОЛЬКО на логгере `odata1c`, поэтому всё, что пишут uvicorn, SDK `mcp`
и httpx, в `daemon.log` не попадало **в принципе**. Исполнитель прошлого раунда наблюдал единичный
обрыв MCP-транспорта — и следа в журнале не осталось именно поэтому. Причину обрыва ревьюер в коде
не нашёл и чинить её не просил; попросил, чтобы следующий такой случай оставил улики.

Цена ошибки в другую сторону — залитый журнал: httpx пишет строку на КАЖДЫЙ запрос к 1С на уровне
INFO, а запросов у шлюза столько же, сколько обращений модели. Поэтому уровни разведены, и это
проверяется здесь наравне с самим перехватом.
"""

from __future__ import annotations

import logging

import pytest

from odata1c.daemon import _настроить_журнал, _снять_журнал


@pytest.fixture
def журнал(tmp_path):
    """Обработчик ставится и обязательно снимается: он висит на КОРНЕВОМ логгере, и оставленный
    после теста продолжил бы писать в удалённый `tmp_path` из всех последующих тестов."""
    обработчик = _настроить_журнал(tmp_path)
    yield tmp_path / "logs" / "daemon.log"
    _снять_журнал(обработчик)


def test_своё_сообщение_уровня_info_попадает_в_журнал(журнал):
    """Своё — на INFO: демон пишет туда «демон слушает…», предупреждения о правах и отказы
    фоновой проверки, и понижать это до WARNING нельзя."""
    logging.getLogger("odata1c.проба").info("демон слушает")

    assert "демон слушает" in журнал.read_text(encoding="utf-8")


@pytest.mark.parametrize("логгер", ["uvicorn.error", "mcp.server.streamable_http", "httpx"])
def test_предупреждение_чужого_логгера_попадает_в_журнал(журнал, логгер):
    """Главное в пункте 5: чужой логгер — не наш, но процесс один и тот же, и его беда — это беда
    демона. WARNING и выше обязаны оставлять след у ЛЮБОГО логгера, а не только у `odata1c`."""
    logging.getLogger(логгер).warning("чужая беда в %s", логгер)

    assert f"чужая беда в {логгер}" in журнал.read_text(encoding="utf-8")


def test_обрыв_транспорта_оставляет_улику(журнал):
    """Тот самый случай, ради которого пункт и заведён: SDK `mcp` рассказывает о жизни
    SSE-потока на INFO. Именно эти строки в журнале и не появлялись."""
    logging.getLogger("mcp.client.streamable_http").info("SSE stream disconnected, reconnecting...")

    assert "SSE stream disconnected" in журнал.read_text(encoding="utf-8")


def test_поток_запросов_httpx_журнал_не_заливает(журнал):
    """Обратная сторона: httpx пишет на INFO строку про КАЖДЫЙ запрос к 1С («HTTP Request: GET …
    200 OK»). У шлюза таких строк столько же, сколько обращений модели, и в журнале демона они
    хоронят всё остальное. Уровень INFO поднят точечно — тем, кто рассказывает о жизни процесса,
    а не о каждом обращении."""
    logging.getLogger("httpx").info("HTTP Request: GET https://1c.example/odata/… 200 OK")
    logging.getLogger("uvicorn.access").info('127.0.0.1 - "POST /mcp HTTP/1.1" 200')

    содержимое = журнал.read_text(encoding="utf-8")
    assert "HTTP Request" not in содержимое, "поток запросов httpx залил журнал"
    assert "POST /mcp" not in содержимое, "поток обращений uvicorn.access залил журнал"


def test_журнал_видит_uvicorn_даже_если_тот_уже_настроил_логирование_под_себя(tmp_path):
    """Найдено исполнением на полном прогоне тестов. Штатная настройка логирования uvicorn
    (`dictConfig` из его `LOGGING_CONFIG`) ставит логгеру `uvicorn` `propagate: False` и уводит
    его сообщения в собственный обработчик. После этого записи `uvicorn.error` не доходят до
    корневого логгера ВООБЩЕ — и журнал демона снова нем, на каком бы логгере он ни висел.

    `serve()` эту настройку больше не запускает, но запустить её может кто угодно другой в том же
    процессе (в прогоне тестов — поддельная 1С, которая поднимает свой uvicorn раньше). Поэтому
    распространение возвращается принудительно, а при снятии журнала — как было."""
    logging.getLogger("uvicorn").propagate = False  # как после dictConfig самого uvicorn
    try:
        обработчик = _настроить_журнал(tmp_path)
        try:
            logging.getLogger("uvicorn.error").info("Uvicorn running on http://127.0.0.1:7171")
            содержимое = (tmp_path / "logs" / "daemon.log").read_text(encoding="utf-8")
        finally:
            _снять_журнал(обработчик)

        assert "Uvicorn running" in содержимое, "записи uvicorn не дошли до журнала"
        assert logging.getLogger("uvicorn").propagate is False, "чужая настройка не возвращена"
    finally:
        logging.getLogger("uvicorn").propagate = True


def test_снятие_журнала_возвращает_прежние_настройки(tmp_path):
    """Уровень и распространение чужих логгеров — общая для процесса настройка, и `serve()`,
    отработав, обязан вернуть их как было: иначе несколько `serve()` подряд в одном процессе
    (интеграционные тесты, да и сам pytest) постепенно перенастраивают чужое логирование
    под себя."""
    было = logging.getLogger("mcp").level

    обработчик = _настроить_журнал(tmp_path)
    поднято = logging.getLogger("mcp").level
    _снять_журнал(обработчик)

    assert поднято == logging.INFO
    assert logging.getLogger("mcp").level == было
    assert обработчик not in logging.getLogger().handlers, "обработчик остался на корневом логгере"


def test_повторная_настройка_не_плодит_обработчиков(tmp_path):
    """Идемпотентность (несколько `serve()` подряд на один домашний каталог в одном процессе):
    второй вызов возвращает тот же обработчик, а не вешает второй на тот же файл — иначе каждая
    строка удвоится."""
    первый = _настроить_журнал(tmp_path)
    try:
        второй = _настроить_журнал(tmp_path)
        assert первый is второй
        assert [о for о in logging.getLogger().handlers if о is первый] == [первый]
    finally:
        _снять_журнал(первый)
