# --- Ruling 99: написание названия, в котором ранний проход заменил реквизит токеном -----------

НАЗВАНИЕ_С_ИНН = 'ООО "Ромашка Плюс" ИНН 7707083893'
ПЕРЕПИСАННОЕ = 'ООО "Ромашка Плюс" ИНН [[inn:1P8RNB92FM]]'
ЗАГЛУШЕННЫЙ_КЛЮЧ = 'ооо "ромашка плюс" инн ' + "\x00" * len("[[inn:1P8RNB92FM]]")


def _токен_названия(словарь) -> str:
    return словарь.token_for(
        "org", НАЗВАНИЕ_С_ИНН, base="ut", entity="Catalog_Контрагенты", field="НаименованиеПолное"
    )


def test_переписанное_написание_становится_вариантом_названия(словарь):
    """Ключ — та же свёртка, какую слой поиска применяет к тексту: токен закрыт заглушкой той же
    длины. Дословный `[[inn:…]]` в ключе не совпал бы ни с чем — в тексте токены заглушаются до
    поиска (`overlaps.все_вхождения`)."""
    токен = _токен_названия(словарь)

    словарь.add_scrubbed_name_variant(токен, ПЕРЕПИСАННОЕ)

