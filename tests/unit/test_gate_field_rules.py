# --- Находка П1 приёмки через настоящие инструменты (2026-09-12): перечисление — не ФИО ---


@pytest.mark.parametrize(
    "сущность", ["Catalog_Контрагенты", "Catalog_Организации", "Catalog_Партнеры", "Document_X"]
)
@pytest.mark.parametrize("поле", ["ЮрФизЛицо", "ЮридическоеФизическоеЛицо"])
def test_перечисление_тип_лица_не_фио(сущность, поле):
    """`ЮрФизЛицо` — перечисление «юрлицо/физлицо» (тип контрагента), всего два значения. Правило
    `ЛИЦО_ЧАСТЬ` ловило в нём подстроку «физлицо», и модель получала `[[person:1]]`/`[[person:2]]`
    вместо единственного признака, по которому организация отличается от ИП. Сверка по полному
    `$metadata` УТ (7224 сущности, 1006 перечислений): среди строковых полей, названных как
    перечисление, класс по имени получало только это — у трёх справочников.
    `ЮридическоеФизическоеЛицо` правилом не ловится и сейчас; в сторож оно включено, чтобы
    исключение не расползлось в «не трогать ничего с физлицом»."""
    assert класс(сущность, поле) is None
    assert classify_field(сущность, поле, "Edm.String", names_for={сущность}) is None


@pytest.mark.parametrize("поле", ["Физлицо", "ФизЛицо", "ОтветственноеЛицо", "ФИОФизлица"])
def test_исключение_перечисления_не_снимает_защиту_с_лица(поле):
    """Обратный сторож: исключение закрытое и точечное (по образцу `СЛУЖЕБНЫЕ_ПОЛЯ_ИМЯ`), а не
    вширь — строковые поля, несущие ФИО, остаются защищёнными."""
    assert класс("InformationRegister_ДокументыФизическихЛиц", поле) == "person"
