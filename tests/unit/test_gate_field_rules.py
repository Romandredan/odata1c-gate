"""Классификация полей по имени: реквизиты (SPEC §6.4) и названия (SPEC §6.5)."""

import pytest

from odata1c.gate.field_rules import classify_field


def класс(сущность, поле, тип="Edm.String"):
    решение = classify_field(сущность, поле, тип)
    return решение[0] if решение else None


@pytest.mark.parametrize(
    ("поле", "ожидаемый"),
    [
        ("ИНН", "inn"),
        ("ИННКонтрагента", "inn"),
        ("КПП", "kpp"),
        ("ОГРН", "ogrn"),
        ("ОГРНИП", "ogrn"),
        ("НомерСчета", "acc"),
        ("РасчетныйСчет", "acc"),
        ("КоррСчет", "corr"),
        ("БИК", "bic"),
        ("СНИЛС", "snils"),
        ("НомерТелефона", "phone"),
        ("АдресЭП", "email"),
        ("ДатаРождения", "dob"),
        ("АдресРегистрации", "addr"),
        ("КемВыдан", "doc"),
        ("КодПодразделения", "doc"),
    ],
)
def test_реквизиты_по_имени_поля(поле, ожидаемый):
    assert класс("Catalog_Контрагенты", поле) == ожидаемый


@pytest.mark.parametrize("поле", ["АдресЭлектроннойПочты", "АдресЭлПочты"])
def test_r33_адрес_электронной_почты_это_почта_а_не_адрес(поле):
    """Проверка почты «тем же способом» (Ruling 33): в родительном падеже поле не ловилось
    правилом почты и получало класс `addr` — у документа это `keep`, открытый адрес почты."""
    assert класс("Document_ЗаявкаНаКомандировку", поле) == "email"


def test_r33_каталог_программы_почты_не_почта():
    """Обратная сторона: путь к каталогу программы почты — не адрес почты."""
    assert класс("Catalog_НастройкиОбмена", "ОбменКаталогПрограммыЭлектроннойПочты") is None


def test_счета_из_плана_счетов_не_реквизит():
    """`account` в ChartOfAccounts — это счёт учёта, а не банковский (SPEC §6.4)."""
    assert класс("ChartOfAccounts_Хозрасчетный", "Account") is None


