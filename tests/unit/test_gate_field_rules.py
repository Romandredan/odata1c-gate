"""Классификация полей по имени: реквизиты (SPEC §6.4) и названия (SPEC §6.5)."""

import pytest

from odata1c.gate.field_rules import classify_field


def класс(сущность, поле, тип="Edm.String"):
    решение = classify_field(сущность, поле, тип)
    return решение[0] if решение else None


@pytest.mark.parametrize(
    ("поле", "ожидаемый"),
    [
        ("ИНН", "inn"),
        ("ИННКонтрагента", "inn"),
        ("КПП", "kpp"),
        ("ОГРН", "ogrn"),
        ("ОГРНИП", "ogrn"),
        ("НомерСчета", "acc"),
        ("РасчетныйСчет", "acc"),
        ("КоррСчет", "corr"),
        ("БИК", "bic"),
        ("СНИЛС", "snils"),
        ("НомерТелефона", "phone"),
        ("АдресЭП", "email"),
        ("ДатаРождения", "dob"),
        ("АдресРегистрации", "addr"),
        ("КемВыдан", "doc"),
        ("КодПодразделения", "doc"),
    ],
)
def test_реквизиты_по_имени_поля(поле, ожидаемый):
    assert класс("Catalog_Контрагенты", поле) == ожидаемый


def test_счета_из_плана_счетов_не_реквизит():
    """`account` в ChartOfAccounts — это счёт учёта, а не банковский (SPEC §6.4)."""
    assert класс("ChartOfAccounts_Хозрасчетный", "Account") is None


@pytest.mark.parametrize(
    "поле",
    [
        "СуммаДокумента",
        "Количество",
        "Number",
        "Code",
        "Date",
        "КодПоОКВЭД2",
        "ОКПО",
        "Ref_Key",
        "DataVersion",
    ],
)
def test_безопасные_поля_не_классифицируются(поле):
    assert класс("Document_РеализацияТоваровУслуг", поле) is None


def test_нестроковые_поля_не_классифицируются():
    assert класс("Catalog_Контрагенты", "ИНН", "Edm.Decimal") is None


def test_описание_в_сущности_из_списка_названий():
    assert класс("Catalog_Контрагенты", "Description") == "org"
    assert класс("Catalog_ФизическиеЛица", "Description") == "person"
    assert класс("Catalog_Сотрудники", "Description") == "person"


def test_описание_вне_списка_названий_не_классифицируется():
    assert класс("Catalog_Номенклатура", "Description") is None
    assert класс("Catalog_Склады", "Description") is None


def test_код_не_классифицируется_даже_в_списке_названий():
    assert класс("Catalog_Контрагенты", "Code") is None


@pytest.mark.parametrize("поле", ["Фамилия", "Имя", "Отчество", "НаименованиеПолное"])
def test_поля_фио_и_полного_наименования_внутри_списка(поле):
    assert класс("Catalog_Контрагенты", поле) in {"org", "person"}


@pytest.mark.parametrize(
    ("поле", "ожидаемый"),
    [
        ("Руководитель", "person"),
        ("ФИОКассира", "person"),
        ("Подписант", "person"),
        ("ГлавныйБухгалтер", "person"),
        ("Грузополучатель", "org"),
        ("НаименованиеОрганизации", "org"),
        ("НаименованиеБанка", "org"),
    ],
)
def test_имена_в_чужих_сущностях_слой_два(поле, ожидаемый):
    assert класс("Document_РеализацияТоваровУслуг", поле) == ожидаемый


def test_наименование_банка_в_справочнике_банков_не_трогаем():
    assert класс("Catalog_Банки", "НаименованиеБанка") is None


@pytest.mark.parametrize("поле", ["ИмяФайла", "ИмяПользователяИБ", "ИмяПредопределенныхДанных"])
def test_ложные_срабатывания_на_слово_имя(поле):
    assert класс("Catalog_Файлы", поле) is None


def test_комментарий_не_классифицируется():
    """Свободный текст покрывает слой словаря (SPEC §6.5, слой 3), а не имя поля."""
    assert класс("Document_РеализацияТоваровУслуг", "Комментарий") is None


def test_источник_классификации_всегда_auto():
    assert classify_field("Catalog_Контрагенты", "ИНН", "Edm.String")[1] == "auto"


# Правки координатора (2026-09-09): три противоречия внутри SPEC, найденные дополнительной
# проверкой задачи 3 и подтверждённые координатором вручную. Тесты покрывают минимум из
# сообщения координатора — случаи, из-за отсутствия которых противоречия дожили до реализации.


def test_логин_пользователя_иб_не_защищается():
    """SPEC §6.5 сама приводит этот пример как ложное срабатывание — регекс должен его избегать
    даже внутри сущности из names_for (Catalog_Пользователи — сама в DEFAULT_NAMES_FOR)."""
    assert класс("Catalog_Пользователи", "ИмяПользователяИБ") is None


def test_имя_макета_не_защищается_внутри_names_for():
    """Технический реквизит `ИмяМакета`, случившийся внутри сущности из names_for, не должен
    ловиться подстрокой «имя»."""
    assert класс("Catalog_Пользователи", "ИмяМакета") is None


def test_номер_документа_не_защищается():
    """Инвариант проекта и сам раздел SPEC §6.4 тремя абзацами ниже своей же таблицы классов:
    номера документов не защищаются ни на одном уровне."""
    assert класс("Document_РеализацияТоваровУслуг", "НомерДокумента") is None


def test_номер_строки_не_защищается():
    assert класс("Document_РеализацияТоваровУслуг", "НомерСтроки") is None


def test_полное_наименование_номенклатуры_не_защищается():
    """Слой 2 SPEC §6.5 применяется к любой сущности — общая форма «наименованиеполное» ловила бы
    всю номенклатуру торговой базы как названия организаций."""
    assert класс("Catalog_Номенклатура", "НаименованиеПолное") is None
    assert класс("Catalog_Склады", "НаименованиеПолное") is None


def test_полное_наименование_контрагента_защищается():
    """Внутри names_for полное наименование по-прежнему защищается слоем 1 — там оно однозначно
    означает название организации или ФИО."""
    assert класс("Catalog_Контрагенты", "НаименованиеПолное") == "org"


@pytest.mark.parametrize("поле", ["НомерПаспорта", "КемВыдан", "КодПодразделения"])
def test_паспортные_поля_физлица_защищаются(поле):
    assert класс("Catalog_ФизическиеЛица", поле) == "doc"


def test_код_по_классификатору_не_защищается():
    assert класс("Catalog_Номенклатура", "КодПоОКПО") is None


def test_идентификатор_пользователя_не_защищается():
    assert класс("Catalog_Пользователи", "ИдентификаторПользователя") is None
