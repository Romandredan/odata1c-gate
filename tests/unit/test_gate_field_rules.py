def _номер_к_серии(серия: str) -> set[str]:
    """Имена поля номера того же документа: `СерияДиплома` → `НомерДиплома`, `АттестатСерия` →
    `АттестатНомер`, `ПредставительФЛ_СерДок` → `ПредставительФЛ_НомДок`, `Серия` → `Номер`."""
    return {серия.replace("Серия", "Номер"), серия.replace("СерДок", "НомДок")} - {серия}


# Пары «серия закрыта классом doc, номер открыт» не про документ человека: `^серия$` общего
# правила ставит doc и сериям документов о товаре (ветеринарные ВЕТИС, зерно) — лишнее
# закрытие серии, а номер товарного документа открыт по инварианту 6.
ПАРА_НЕ_О_ЧЕЛОВЕКЕ = re.compile(r"ВЕТИС|ЗЕРНО|ЕГАИС|Алко", re.IGNORECASE)


