def _похож_на_человека(имя: str, справочники: dict) -> bool:
    сущность = справочники[имя]
    поля = {поле.name for поле in сущность.fields}
    return bool(
        поля & ПОЛЯ_ЧЕЛОВЕКА
        or any("СНИЛС" in поле.upper() for поле in поля)
        or f"{имя}_ФИО" in справочники
    )


