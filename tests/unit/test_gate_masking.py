def test_фио_заменяется_на_верхнем_уровне(гейт):
    результат = гейт("identifiers+names").mask(
        {"ФИО": "Иванов Иван Иванович"}, entity="Catalog_ФизическиеЛица"
    )
    assert результат.data["ФИО"].startswith("[[person:")


def test_фио_сканируется_на_реквизиты_на_среднем_уровне(гейт):
    результат = гейт("identifiers").mask(
        {"ФИО": "Иванов Иван Иванович, СНИЛС 112-233-445 95"}, entity="Catalog_ФизическиеЛица"
    )
    assert "Иванов Иван Иванович" in результат.data["ФИО"]
