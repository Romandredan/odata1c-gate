def test_вариант_названия_не_режет_уже_поставленный_токен(гейт):
    """Хвост токена реквизита — те же символы (цифры и заглавные латинские буквы), что и
    приведённое к нижнему регистру латинское название: совпадение внутри уже выданного токена
    пропускается, а не разрезает его (ревью 2026-09-09, дыра 8)."""
    маскировщик = гейт()
    маскировщик.mask({"Description": "CAFE"}, entity="Catalog_Контрагенты")
    результат = маскировщик.mask(
        {"Комментарий": "[[acc:CAFE123456]]"}, entity="Catalog_Контрагенты"
    )
    assert результат.data["Комментарий"] == "[[acc:CAFE123456]]"


# --- Ревью 2026-09-09 (перепроверка): обход B — невидимые символы внутри названия ---


def test_невидимые_символы_до_внутри_и_после_названия_не_мешают_замене(гейт):
    """Мягкий перенос, пробел нулевой ширины и метка направления письма — не пробел ни для
    `str.isspace()`, ни для ключей словаря; обычный мусор при копировании названия организации
    с веб-страницы в комментарий 1С. Символы расставлены и до, и внутри, и после названия."""
    маскировщик = гейт()
    маскировщик.mask({"Description": "ООО Ромашка"}, entity="Catalog_Контрагенты")
    невидимый_до = "​"
    мягкий_перенос = "­"
    невидимый_внутри = "​"
    метка_после = "‎"
    текст = (
        невидимый_до
        + "звонили из ООО"
        + мягкий_перенос
        + " Р"
        + невидимый_внутри
        + "омашка"
        + метка_после
        + " вчера"
    )
    результат = маскировщик.mask({"Комментарий": текст}, entity="Catalog_Контрагенты")
    assert "Ромашка" not in результат.data["Комментарий"]
    assert "омашка" not in результат.data["Комментарий"]
    assert результат.data["Комментарий"].endswith(" вчера")
    assert "[[org:1]]" in результат.data["Комментарий"]


# --- Ревью 2026-09-09 (перепроверка): правка C — канарейка на многословное значение без короткой
# формы (короткая форма у «ООО Ромашка» находится независимо от пробелов вокруг и маскирует то,
# что сама нормализация полного варианта не проверена) ---


@pytest.mark.parametrize(
    "текст",
    [
        "звонили от Ромашка  и Партнёры вчера",  # два пробела
        "звонили от Ромашка\xa0и Партнёры вчера",  # неразрывный пробел
        "звонили от Р​омашка и Партнёры вчера",  # невидимый символ внутри слова
    ],
)
def test_многословное_название_без_короткой_формы_ловится_в_разных_написаниях(гейт, текст):
    """«Ромашка и Партнёры» не начинается с распознаваемой организационно-правовой формы
    (`dictionary.ФОРМЫ` не совпадает) — у него нет короткого варианта, и единственный способ
    поймать написание с двойным/неразрывным пробелом или невидимым символом — нормализация
    ПОЛНОГО варианта. Тест на «ООО Ромашка» этого не проверяет: у него есть независимый короткий
    вариант «ромашка», который находится в любом из четырёх написаний даже без нормализации —
    что и обнаружило повторное ревью, отключив нормализацию и не увидев ни одного упавшего теста."""
    маскировщик = гейт()
    маскировщик.mask({"Description": "Ромашка и Партнёры"}, entity="Catalog_Контрагенты")
    результат = маскировщик.mask({"Комментарий": текст}, entity="Catalog_Контрагенты")
    assert "Ромашка" not in результат.data["Комментарий"]
    assert "омашка" not in результат.data["Комментарий"]


