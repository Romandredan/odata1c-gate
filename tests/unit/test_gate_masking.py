    токен = маскировщик.mask({поле: значение}, entity="Catalog_Контрагенты").data[поле]
    assert токен.startswith(f"[[{класс}:")

    результат = маскировщик.mask({поле: токен}, entity="Catalog_Контрагенты")

    assert результат.data[поле].startswith("[[lit:")
    assert результат.data[поле] != токен
    assert результат.masked_fields == [поле]


