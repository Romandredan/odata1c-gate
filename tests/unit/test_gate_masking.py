# --- Правка 7 (Important): «Партнёр» и «Клиент» — тоже контейнер организации ---


@pytest.mark.parametrize("поле_контейнера", ["Партнер", "Клиент", "Заказчик"])
def test_раскрытый_объект_под_партнёром_и_клиентом_отдаёт_наименование_токеном(
    гейт, поле_контейнера
):
    """`Catalog_Партнеры` прямо перечислен в names_for (SPEC §6.5, слой 1), но полем-контейнером
    в документе он чаще называется «Партнёр» или «Клиент», а не «Контрагент» — узкий список слоя
    2 это раньше не ловил, и наименование раскрытого объекта уходило открытым текстом."""
    результат = гейт("identifiers+names").mask(
        {поле_контейнера: {"Description": "ООО Секрет Партнер"}},
        entity="Document_РеализацияТоваровУслуг",
    )
    assert результат.data[поле_контейнера]["Description"].startswith("[[org:")


def test_общий_термин_без_наследования_не_добавлен(гейт):
    """«Агент» намеренно не добавлен в список контейнеров организации — слишком общий термин,
    встречается и в служебных полях платформы (см. поправку в field_rules.py). Поле наименования
    под таким контейнером по-прежнему не наследует класс и остаётся открытым текстом."""
    результат = гейт("identifiers+names").mask(
        {"Агент": {"Description": "ООО Секрет Партнер"}},
        entity="Document_РеализацияТоваровУслуг",
    )
    assert результат.data["Агент"]["Description"] == "ООО Секрет Партнер"
