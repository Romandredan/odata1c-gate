def test_сообщение_об_ошибке_защищено_при_выключенном_scan_free_text(tmp_path):
    (tmp_path / "policy.yaml").write_text(
        ПОЛИТИКА_ТЕКСТ.replace("scan_free_text: true", "scan_free_text: false"),
        encoding="utf-8",
    )
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    политика = load_policy(tmp_path / "policy.yaml")
    маскировщик = Masker(словарь, политика, mode="identifiers+names", base="ut")

    текст = маскировщик.mask_text(
        "Поле ИНН 7707083893 заполнено неверно", entity="Catalog_Контрагенты", field="message"
    )
    # Обычное поле ответа по-прежнему не сканируется — настройка гасит именно поиск в полях,
    # а не сообщения об ошибках (у них отдельный, принудительный путь).
    результат = маскировщик.mask(
        {"Комментарий": "оплата, ИНН 7707083893, срочно"}, entity="Catalog_Контрагенты"
    )
    словарь.close()

    assert "7707083893" not in текст
    assert "[[inn:" in текст
    assert результат.data["Комментарий"] == "оплата, ИНН 7707083893, срочно"


