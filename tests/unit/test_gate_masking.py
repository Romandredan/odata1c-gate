# --- Правка 4 (Important): сообщения об ошибках защищены независимо от scan_free_text ---


def test_сообщение_об_ошибке_защищено_при_выключенном_scan_free_text(tmp_path):
    (tmp_path / "policy.yaml").write_text(
        ПОЛИТИКА_ТЕКСТ.replace("scan_free_text: true", "scan_free_text: false"),
        encoding="utf-8",
    )
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    политика = load_policy(tmp_path / "policy.yaml")
    маскировщик = Masker(словарь, политика, mode="identifiers+names", base="ut")

    текст = маскировщик.mask_text(
        "Поле ИНН 7707083893 заполнено неверно", entity="Catalog_Контрагенты", field="message"
    )
    # Обычное поле ответа по-прежнему не сканируется — настройка гасит именно поиск в полях,
    # а не сообщения об ошибках (у них отдельный, принудительный путь).
    результат = маскировщик.mask(
        {"Комментарий": "оплата, ИНН 7707083893, срочно"}, entity="Catalog_Контрагенты"
    )
    словарь.close()

    assert "7707083893" not in текст
    assert "[[inn:" in текст
    assert результат.data["Комментарий"] == "оплата, ИНН 7707083893, срочно"


# --- Правка 5 (Important): замена известных названий не портит индексы и детерминирована ---


def test_замена_названия_не_ломает_текст_при_расширении_регистра(гейт):
    """`str.lower()` для символа İ (U+0130) даёт два знака вместо одного (i + комбинирующая
    точка) — построение отдельной приведённой к нижнему регистру копии строки для поиска
    сдвигает индексы относительно исходной строки, если такой символ встретился раньше
    искомого названия, и портит текст рядом с найденным названием."""
    маскировщик = гейт()
    маскировщик.mask({"Description": "ООО Ромашка"}, entity="Catalog_Контрагенты")
    результат = маскировщик.mask(
        {"Комментарий": "Отель İstanbul, звонили из ООО Ромашка вчера"},
        entity="Catalog_Контрагенты",
    )
    assert "Ромашка" not in результат.data["Комментарий"]
    assert " вчера" in результат.data["Комментарий"]


def test_замена_нескольких_названий_равной_длины_в_одной_строке(гейт):
    маскировщик = гейт()
    маскировщик.mask({"Description": "Актив"}, entity="Catalog_Контрагенты")
    маскировщик.mask({"Description": "Ветер"}, entity="Catalog_Контрагенты")
    результат = маскировщик.mask(
        {"Комментарий": "звонили из актив и ветер сегодня"}, entity="Catalog_Контрагенты"
    )
    комментарий = результат.data["Комментарий"].lower()
    assert "актив" not in комментарий
    assert "ветер" not in комментарий
    assert "сегодня" in комментарий


