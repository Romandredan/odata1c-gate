    набор.note(2)
    поле_класса = набор.scrubbed("[[org:1]]", original="ООО Ромашка", hits=1)
    свободный = набор.scrubbed(
        "платёж [[org:1]] по счёту",
        original="платёж ООО Ромашка по счёту",
        hits=1,
        inserted=((7, 16),),
    )

