def навигации(entity: str, ключ: str) -> str | None:
    """Резолвер вида «сущность и ключ ответа → сущность вложенного объекта» — тот же контракт,
    что `ToolService` строит по индексу (`_навигации`)."""
    return НАВИГАЦИИ_УТ.get((entity, ключ))


