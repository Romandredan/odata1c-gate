"""Б-4 (находка I-2 ревью 7 и ревью 9, блокер M2): пересечение двух известных названий.

Слой названий искал совпадения автоматом `LeftmostLongest`: на месте длинного названия он брал
его, а название, начавшееся внутри, пропускал — и хвост второго выходил модели открытым: «Юг
Альфа Север» при известных «Юг Альфа» и «Альфа Север» → `[[org:1]] Север`. С отбором и без.
Лечение — правило вложенности Ruling 32 в самом слое названий (`gate/overlaps.py`).
"""

import json

import pytest

from odata1c.gate.dictionary import Dictionary
from odata1c.gate.guard import Guard
from odata1c.gate.masking import Masker
from odata1c.gate.overlaps import Вхождение, группы, токены_подряд, участники
from odata1c.gate.policy import load_policy
from odata1c.gate.revealed import RevealedValues

СЕКРЕТ = "секрет ровно для тестов подмены!!".encode()
КОНТРАГЕНТЫ = "Catalog_Контрагенты"
ПОЛИТИКА = f"version: 2\nauto:\n  {КОНТРАГЕНТЫ}.Description: org\n"


@pytest.fixture
def среда(tmp_path):
    (tmp_path / "policy.yaml").write_text(ПОЛИТИКА, encoding="utf-8")
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    маскировщик = Masker(
        словарь, load_policy(tmp_path / "policy.yaml"), mode="identifiers+names", base="ut"
    )

    def назвать(*названия: str) -> list[str]:
        return [
            маскировщик.mask({"Description": название}, entity=КОНТРАГЕНТЫ).data["Description"]
            for название in названия
        ]

    yield словарь, маскировщик, назвать
    словарь.close()


def _маскировщиком(маскировщик: Masker, текст: str) -> str:
    return маскировщик.mask({"Комментарий": текст}, entity=КОНТРАГЕНТЫ).data["Комментарий"]


def _стражем(словарь: Dictionary, текст: str) -> str:
    проверено = Guard(словарь).check(
        json.dumps({"Комментарий": текст}, ensure_ascii=False), mode="identifiers+names"
    )
    return json.loads(проверено.text)["Комментарий"]


@pytest.mark.parametrize("слой", ["маскировщик", "страж"])
def test_пересекающиеся_названия_оба_закрыты(среда, слой):
    словарь, маскировщик, назвать = среда
    юг, север = назвать("Юг Альфа", "Альфа Север")
    текст = "звонили из Юг Альфа Север вчера"

    итог = _маскировщиком(маскировщик, текст) if слой == "маскировщик" else _стражем(словарь, текст)

    assert итог == f"звонили из {юг}{север} вчера"


@pytest.mark.parametrize("слой", ["маскировщик", "страж"])
def test_цепочка_из_трёх_названий_и_соседний_текст(среда, слой):
    """Три названия, сцепленные попарными пересечениями, — одна группа; текст до и после неё и
    название, лишь касающееся группы концом, не задеваются."""
    словарь, маскировщик, назвать = среда
    первое, второе, третье, отдельное = назвать("Ааа Ббб", "Ббб Ввв", "Ввв Ггг", "Ддд Еее")
    текст = "до Ааа Ббб Ввв Ггг, Ддд Еее 12345 после"

    итог = _маскировщиком(маскировщик, текст) if слой == "маскировщик" else _стражем(словарь, текст)

    assert итог == f"до {первое}{второе}{третье}, {отдельное} 12345 после"


@pytest.mark.parametrize("слой", ["маскировщик", "страж"])
def test_касание_концами_не_пересечение(среда, слой):
    словарь, маскировщик, назвать = среда
    первое, второе = назвать("Юг Альфа", "Север Плюс")
    текст = "Юг Альфа Север Плюс"

    итог = _маскировщиком(маскировщик, текст) if слой == "маскировщик" else _стражем(словарь, текст)

    assert итог == f"{первое} {второе}"


@pytest.mark.parametrize("слой", ["маскировщик", "страж"])
def test_накрывающее_название_побеждает(среда, слой):
    """Длинное название, накрывающее оба пересекающихся, — один его токен, как и прежде."""
    словарь, маскировщик, назвать = среда
    _, _, целое = назвать("Юг Альфа", "Альфа Север", "Юг Альфа Север")

    итог = (
        _маскировщиком(маскировщик, "Юг Альфа Север")
        if слой == "маскировщик"
        else _стражем(словарь, "Юг Альфа Север")
    )

    assert итог == целое


def test_участники_группы():
    а = Вхождение(0, 8, "[[org:1]]", "")
    б = Вхождение(3, 14, "[[org:2]]", "")
    в = Вхождение(3, 8, "[[org:3]]", "")
    г = Вхождение(14, 20, "[[org:4]]", "")

    assert [[x.токен for x in группа] for группа in группы([г, б, в, а])] == [
        ["[[org:1]]", "[[org:2]]", "[[org:3]]"],
        ["[[org:4]]"],
    ]
    assert [x.токен for x in участники([а, б, в])] == ["[[org:1]]", "[[org:2]]"]
    # Одно название, найденное двумя пересекающимися вхождениями, — один токен, не два подряд.
    assert токены_подряд([Вхождение(0, 5, "[[org:1]]", ""), Вхождение(3, 9, "[[org:1]]", "")]) == (
        "[[org:1]]"
    )


def test_ранний_проход_берёт_всю_цепочку_названий(среда):
    """Название, сцепленное с раскрытым не напрямую, а через другое название («Гамма Дельта»
    пересекает «Бета-Гамма», та — раскрытое «Бета»), — тоже участник: иначе после раннего прохода
    от него остался бы хвост, который слой названий уже не узнает."""
    словарь, маскировщик, назвать = среда
    назвать("Альфа-Бета", "Бета-Гамма", "Гамма Дельта")
    (бета,) = назвать("Бета")
    набор = RevealedValues()
    набор.add("Бета", token=бета)
    текст = "итог: Альфа-Бета-Гамма Дельта."

    данные = Guard(словарь).scrub_revealed_json(
        json.dumps({"Комментарий": текст}, ensure_ascii=False), набор, mode="identifiers+names"
    )

    assert данные["Комментарий"] == _маскировщиком(маскировщик, текст)
    assert "Дельта" not in данные["Комментарий"]


def test_ранний_проход_видит_пересекающиеся_названия(среда):
    """Случай ревью 7: раскрыто «Бета», в тексте «Альфа-Бета-Гамма» при известных «Альфа-Бета» и
    «Бета-Гамма». Правило вложенности брало названия поиском без пересечений и видело только
    «Альфа-Бета» — «накрывающее» раскрытое, — и «-Гамма» (хвост третьего лица) выходил открытым.
    С поиском всех совпадений — токены обоих названий, как у маскировщика без отбора."""
    словарь, маскировщик, назвать = среда
    альфа_бета, бета_гамма, бета = назвать("Альфа-Бета", "Бета-Гамма", "Бета")
    набор = RevealedValues()
    набор.add("Бета", token=бета)
    тело = json.dumps({"Комментарий": "Альфа-Бета-Гамма"}, ensure_ascii=False)

    данные = Guard(словарь).scrub_revealed_json(тело, набор, mode="identifiers+names")

    assert данные["Комментарий"] == f"{альфа_бета}{бета_гамма}"
    assert данные["Комментарий"] == _маскировщиком(маскировщик, "Альфа-Бета-Гамма")


# Два раскрытых значения, пересекающиеся в тексте ответа частично (ни одно не накрывает другое).
# Класс `addr` выбран нарочно: у него нет ни детектора, ни цифровой серии, ни варианта названия —
# обрывок, пропущенный слоем раскрытого, не подберёт уже никто.
АДРЕС_А = "г. Москва, ул. Тверская"
АДРЕС_Б = "ул. Тверская, д. 7"
ТОКЕН_А = "[[addr:A60KNQH867]]"
ТОКЕН_Б = "[[addr:B71LPRJ978]]"


def _раскрыть(*пары: tuple[str, str]) -> RevealedValues:
    набор = RevealedValues()
    for значение, токен in пары:
        набор.add(значение, token=токен)
    return набор


@pytest.mark.parametrize("уровень", ["identifiers", "identifiers+names"])
@pytest.mark.parametrize("проход", ["ранний", "последний рубеж"])
def test_частично_пересекающиеся_раскрытые_закрыты_оба(среда, уровень, проход):
    """Ruling 32, случай 3, между двумя раскрытыми значениями: отбор
    `АдресРегистрации eq '[[addr:A]]' or АдресФактический eq '[[addr:B]]'` раскрывает оба, а в
    ответе стоит строка, где они сцеплены. Поиск раскрытого без пересечений брал первое, второе
    начиналось внутри него и пропускалось — «, д. 7» выходило открытым."""
    словарь, _, _ = среда
    набор = _раскрыть((АДРЕС_А, ТОКЕН_А), (АДРЕС_Б, ТОКЕН_Б))
    текст = "доставка: г. Москва, ул. Тверская, д. 7."
    тело = json.dumps({"Комментарий": текст}, ensure_ascii=False)

    if проход == "ранний":
        итог = Guard(словарь).scrub_revealed_json(тело, набор, mode=уровень)["Комментарий"]
        засчитано = набор.replacements
    else:
        проверено = Guard(словарь).check(тело, mode=уровень, revealed=набор)
        итог = json.loads(проверено.text)["Комментарий"]
        засчитано = len(проверено.replacements)

    assert итог == f"доставка: {ТОКЕН_А}{ТОКЕН_Б}."
    # Замена раскрытого засчитывается стражу (`guard_replaced`): раскрытое здесь не накрыто
    # никаким названием, маскировщик сам его не закрыл бы.
    assert засчитано == 1


def test_короткое_раскрытое_по_границам_и_при_поиске_с_пересечениями(среда):
    """Ruling 27 при поиске всех совпадений: голая «1» (раскрытый КПП) внутри номера и даты не
    заменяется, а по границам — заменяется, в том числе рядом с другим раскрытым значением."""
    словарь, _, _ = среда
    набор = _раскрыть(("1", "[[kpp:K1]]"), (АДРЕС_Б, ТОКЕН_Б))
    тело = json.dumps(
        {"Комментарий": "№ 0000-000123 от 11.01.2026, код 1; ул. Тверская, д. 7"},
        ensure_ascii=False,
    )

    итог = Guard(словарь).scrub_revealed_json(тело, набор, mode="identifiers")["Комментарий"]

    assert итог == f"№ 0000-000123 от 11.01.2026, код [[kpp:K1]]; {ТОКЕН_Б}"
