async def test_resource_policy_не_выдаёт_скрытое_дырой_в_mask_for(сервис, дом):
    """Ruling 29, вторая форма (ревью раундов 4 и 5): `defaults.addr.mask_for` в сгенерированной
    политике — всегда имена из константы `СУЩНОСТИ_ФИЗЛИЦ`, одинаковые у всех баз. Когда
    из него вычёркивалось скрытое имя, недостающее вычислялось однозначно: эталон известен из
    поставки.

    Поправка ревьюера к исходному предложению — заменять список пометкой ВСЕГДА, когда у базы есть
    скрытые, а не только при пересечении со скрытыми: иначе сама пометка сообщает, что скрыта одна
    из четырёх сущностей-физлиц. Поэтому сравниваются два запрета — пересекающийся с `mask_for` и
    посторонний: раздел `defaults.addr` ресурса обязан совпасть целиком.

    Защиту гейта это не ослабляет: `redact_policy` правит только текст ресурса для модели, гейт
    читает политику из файла, — файл после выдачи ресурса проверяется явно."""
    import yaml

    from odata1c.gate.field_rules import СУЩНОСТИ_ФИЗЛИЦ
    from odata1c.gate.service import policy_path

    путь = policy_path(дом, "ut")
    исходный = путь.read_text(encoding="utf-8")
    assert set(yaml.safe_load(исходный)["defaults"]["addr"]["mask_for"]) == СУЩНОСТИ_ФИЗЛИЦ, (
        "образец не тот: в сгенерированной политике нет эталонного mask_for"
    )

    разделы = []
    for скрыто in ("Catalog_ФизическиеЛица", "Catalog_Контрагенты"):
        путь.write_text(исходный + f"entities:\n  {скрыто}: {{hide: true}}\n", encoding="utf-8")
        сервис._gates.clear()
        текст = await сервис.resource_policy(SessionScope(), "ut")
        assert скрыто not in текст
        разделы.append(yaml.safe_load(текст)["defaults"]["addr"])

    assert разделы[0] == разделы[1], (
        f"раздел адреса выдаёт, пересекается ли запрет с mask_for: {разделы}"
    )
    assert not any(имя in str(разделы[0]) for имя in СУЩНОСТИ_ФИЗЛИЦ)
    assert isinstance(разделы[0]["mask_for"], list), "тип поля в ресурсе не должен меняться"
    # Гейт читает файл, а не ресурс: список в файле цел.
    на_диске = yaml.safe_load(путь.read_text(encoding="utf-8"))["defaults"]["addr"]["mask_for"]
    assert set(на_диске) == СУЩНОСТИ_ФИЗЛИЦ


