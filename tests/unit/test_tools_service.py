def _точная_1С(записи: list[dict]):
    def ответ(request: httpx.Request) -> httpx.Response:
        отбор = request.url.params.get("$filter", "")
        литералы = {
            литерал.replace("''", "'") for литерал in re.findall(r"ИНН eq '((?:[^']|'')*)'", отбор)
        }
        найдено = [з for з in записи if not литералы or з["ИНН"] in литералы]
        return httpx.Response(200, json={"value": найдено})

    return ответ


