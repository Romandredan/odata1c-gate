def test_общий_кавычечный_ключ_двух_организаций_неоднозначен(среда):
    """`ООО "2020"` и `АО "2020"` — разные юрлица: ключ `"2020"` у обоих, заменить его правильно
    нельзя (§6.5, поправка ⁷), и он не участвует. Полные названия и `<форма> 2020` — однозначны."""
    словарь, маскировщик, назвать = среда
    ооо = назвать('ООО "2020"')
    ао = назвать('АО "2020"')

    варианты = словарь.name_variants()

    assert '"2020"' not in варианты
    assert set(словарь.ambiguous_name_variants()['"2020"']) == {ооо, ао}
    assert _пройти("маскировщик", словарь, маскировщик, "от АО 2020 и ООО «2020»") == (
        f"от {ао} и {ооо}"
    )


def test_словарь_прежней_версии_получает_новые_ключи(tmp_path):
    """Словарь версии 2 хранит голое ядро и не знает кавычечного ключа и ключа с формой. Первое
    открытие пересчитывает варианты (`ВЕРСИЯ_СХЕМЫ`, как при свёртке кавычек): без пересчёта
    голое ядро закрывало бы числа, а без новых ключей название открылось бы (так и было на Р2-3)."""
    путь = tmp_path / "gate.sqlite"
    словарь = Dictionary(путь, СЕКРЕТ)
    токен = словарь.token_for("org", 'ООО "2020"', base="ut", entity=К, field="Description")
    словарь.close()
    соединение = sqlite3.connect(путь)
    with соединение:
        соединение.execute("DELETE FROM name_variants WHERE token = ?", (токен,))
        соединение.executemany(
            "INSERT INTO name_variants (token, variant_norm) VALUES (?, ?)",
            [(токен, 'ооо "2020"'), (токен, "2020")],
        )
        соединение.execute("PRAGMA user_version = 2")
    соединение.close()

    словарь = Dictionary(путь, СЕКРЕТ)
    try:
        assert словарь.name_variants() == {
            'ооо "2020"': токен,
            '"2020"': токен,
            "ооо 2020": токен,
            'ооо"2020"': токен,
        }
    finally:
        словарь.close()


def test_голое_число_в_таблице_вариантов_не_идёт_в_автомат(tmp_path):
    """Защита на чтении: даже если в таблице окажется голое безбуквенное ядро (словарь дописан
    прежней версией шлюза после пересчёта), в автомат оно не идёт — число остаётся числом."""
    путь = tmp_path / "gate.sqlite"
    словарь = Dictionary(путь, СЕКРЕТ)
    токен = словарь.token_for("org", 'ООО "2020"', base="ut", entity=К, field="Description")
    второй = словарь.token_for("org", 'АО "2021"', base="ut", entity=К, field="Description")
    соединение = sqlite3.connect(путь)
    with соединение:
        соединение.executemany(
            "INSERT INTO name_variants (token, variant_norm) VALUES (?, ?)",
            [(токен, "2020"), (второй, "2021"), (токен, "2021"), (второй, '"50"')],
        )
    соединение.close()
    try:
        assert "2020" not in словарь.name_variants()
        # Короткое ядро в кавычках (так писала промежуточная версия раунда 4 при той же версии
        # содержимого 3, пересчёт его не снимет) — тоже не ключ поиска (Ruling 50).
        assert '"50"' not in словарь.name_variants()
        # И в перечень неоднозначных для предупреждения — тоже: это не ключ поиска.
        assert "2021" not in словарь.ambiguous_name_variants()
    finally:
        словарь.close()


# --- Где ещё ядро могло бы открыть название или закрыть число -------------------------------------


def test_отбор_и_слой_раскрытого_по_названию_без_букв(среда):
    """Отбор `eq` по токену такого названия уходит полным написанием (не ядром), и слой
    раскрытого этого вызова ищет в ответе то, что ушло в 1С: название закрыто, число — нет."""
    словарь, _, назвать = среда
    токен = назвать('ООО "2020"')
    подмена = Unmasker(
        словарь,
        base="ut",
        field_class=lambda e, f, *, strict=False: "org" if f == "Description" else None,
        path_class=без_класса_пути,
    )
    раскрыто = RevealedValues()

    ушло = подмена.filter(f"Description eq '{токен}'", entity=К, revealed=раскрыто)
    ответ = json.dumps(
        {"Description": 'ООО "2020"', "Комментарий": "поставка 2020 года, от «2020»"},
        ensure_ascii=False,
    )
    данные = json.loads(
        Guard(словарь).check(ответ, mode="identifiers+names", revealed=раскрыто).text
    )

    assert ушло == "Description eq 'ООО \"2020\"'"
    assert данные == {"Description": токен, "Комментарий": f"поставка 2020 года, от {токен}"}


def test_запись_токена_названия_без_букв_полным_написанием(среда):
    словарь, _, назвать = среда
    токен = назвать('ООО "2020"')
