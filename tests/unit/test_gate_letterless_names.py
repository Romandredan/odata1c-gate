"""Раунд 4 блокеров M2, Р3-2 (ревью раунда 3): название без единой буквы — ни открыть его, ни
закрыть число.

История. У `ООО "2020"` вариант без формы собственности — голое `2020`, и оно закрывало каждое
отдельно стоящее число 2020 в любом тексте базы (инвариант 6). Правка Р2-3 выбросила такой вариант
из автомата — и с ним открылось всё название: `"2020"`, `«2020»`, `ООО 2020`, `ООО"2020"`, полная
форма собственности в кавычках (инвариант 1). Её откатили (`74db9b7`).

Правило раунда 4: для безбуквенного ядра `X` в автомат идут не голое `X`, а написания, по
которым видно, что это название:
- `"X"` — в кавычках; свёртка текста приводит «ёлочки» и прочие кавычки к прямой, поэтому один
  ключ закрывает `"X"`, `«X»`, `ООО"X"`, `ООО «X»` и полную форму собственности с кавычками;
- `<форма> X` — форма собственности названия без кавычек, только своя (та, которую распознал
  `dictionary.ФОРМЫ`), а не любая из списка.
Голое `X` в автомат не идёт — число остаётся числом.
"""

import json
import sqlite3

import pytest
from conftest import без_класса_пути

from odata1c.gate.dictionary import Dictionary, name_variants_of
from odata1c.gate.guard import Guard
from odata1c.gate.masking import Masker
from odata1c.gate.policy import load_policy
from odata1c.gate.revealed import RevealedValues
from odata1c.gate.unmasking import Unmasker

СЕКРЕТ = "секрет ровно для тестов подмены!!".encode()
К = "Catalog_Контрагенты"
ПОЛИТИКА = f"version: 2\nauto:\n  {К}.Description: org\n  {К}.НаименованиеПолное: org\n"

# Ядра из задания: четыре цифры (пример ревью), одна цифра, три цифры, цифры со знаками.
ЯДРА = ["2020", "1", "585", "1-2-3"]


@pytest.fixture
def среда(tmp_path):
    (tmp_path / "policy.yaml").write_text(ПОЛИТИКА, encoding="utf-8")
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    маскировщик = Masker(
        словарь, load_policy(tmp_path / "policy.yaml"), mode="identifiers+names", base="ut"
    )

    def назвать(название: str, поле: str = "Description") -> str:
        return маскировщик.mask({поле: название}, entity=К).data[поле]

    yield словарь, маскировщик, назвать
    словарь.close()


def _пройти(слой: str, словарь: Dictionary, маскировщик: Masker, текст: str) -> str:
    if слой == "маскировщик":
        return маскировщик.mask({"Комментарий": текст}, entity=К).data["Комментарий"]
    проверено = Guard(словарь).check(
        json.dumps({"Комментарий": текст}, ensure_ascii=False), mode="identifiers+names"
    )
    return json.loads(проверено.text)["Комментарий"]


# --- Воспроизведение ревьюера (scratchpad/test_m2_r3_repro.py, три параметра) ------------------


@pytest.mark.parametrize("текст", ['от "2020" вх', "от ООО 2020 вх", 'от ООО"2020" вх'])
def test_название_без_букв_в_кавычках_закрыто(tmp_path, текст):
    """`ООО "2020"`: вариант `2020` снят (Р2-3), и название в кавычках без формы, без кавычек с
    формой и без пробела открылось целиком (на a97c45f было закрыто). Число «поставка 2020 года»
    при этом должно оставаться числом — лечить кавычечным вариантом, а не голым числом."""
    (tmp_path / "policy.yaml").write_text(
        f"version: 2\nauto:\n  {К}.Description: org\n", encoding="utf-8"
    )
    с = Dictionary(tmp_path / "gate.sqlite", "секрет ревью раунда 3".encode())
    м = Masker(с, load_policy(tmp_path / "policy.yaml"), mode="identifiers+names", base="ut")
    токен = м.mask({"Description": 'ООО "2020"'}, entity=К).data["Description"]
    итог = м.mask({"Комментарий": текст}, entity=К).data["Комментарий"]
    с.close()
    assert "2020" not in итог or токен in итог, "название открыто"


# --- Все написания таблицы ревью закрыты, число — открыто ----------------------------------------


@pytest.mark.parametrize("слой", ["маскировщик", "страж"])
@pytest.mark.parametrize("ядро", ЯДРА)
@pytest.mark.parametrize(
    "шаблон",
    [
        'от ООО "{}" вх',
        "от ООО «{}» вх",
        "от ООО {} вх",
        'от "{}" вх',
        "от «{}» вх",
        'от ООО"{}" вх',
        "от ООО«{}» вх",
        'Общество с ограниченной ответственностью "{}"',
        "Общество с ограниченной ответственностью «{}»",
        "от ооо  {}, вх",
    ],
)
def test_написания_названия_без_букв_закрыты(среда, слой, ядро, шаблон):
    словарь, маскировщик, назвать = среда
    токен = назвать(f'ООО "{ядро}"')
    текст = шаблон.format(ядро)

    итог = _пройти(слой, словарь, маскировщик, текст)

    assert токен in итог
    assert ядро not in итог.replace(токен, ""), f"название открыто: {итог!r}"


@pytest.mark.parametrize("слой", ["маскировщик", "страж"])
@pytest.mark.parametrize("ядро", ЯДРА)
@pytest.mark.parametrize(
    "шаблон",
    ["договор {} года", "сумма {},00", "поставка {} руб, код {}", "{}", "№{} от 01.02.2026"],
)
def test_число_как_ядро_названия_остаётся_числом(среда, слой, ядро, шаблон):
    """Инвариант 6: отдельно стоящее число не закрывается ни на одном уровне, даже если оно —
    ядро известного названия."""
    словарь, маскировщик, назвать = среда
    назвать(f'ООО "{ядро}"')
    текст = шаблон.format(ядро, ядро)

    assert _пройти(слой, словарь, маскировщик, текст) == текст


@pytest.mark.parametrize("слой", ["маскировщик", "страж"])
def test_оба_ключа_одного_названия_дают_одну_замену(среда, слой):
    """В `ООО "2020"` совпадают два ключа одного токена — полное название и `"2020"` внутри него.
    Накрывающее название — единственный участник группы (`overlaps`): одна замена, без обрывков."""
    словарь, маскировщик, назвать = среда
    токен = назвать('ООО "2020"')

    assert _пройти(слой, словарь, маскировщик, 'от ООО "2020" вх, 2020 г.') == (
        f"от {токен} вх, 2020 г."
    )


# --- Ключи словаря ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("название", "ожидаемые"),
    [
        ('ООО "2020"', ['ооо "2020"', '"2020"', "ооо 2020"]),
        ("ООО «2020»", ['ооо "2020"', '"2020"', "ооо 2020"]),
        ("ООО 2020", ["ооо 2020", '"2020"']),
        ('ООО "1"', ['ооо "1"', '"1"', "ооо 1"]),
        ('АО "1-2-3"', ['ао "1-2-3"', '"1-2-3"', "ао 1-2-3"]),
        # Название целиком из цифр, без формы и без кавычек (все четыре безбуквенных варианта
        # словаря владельца — такие): закрывается только в кавычках.
        ("2020", ['"2020"']),
        ('"2020"', ['"2020"']),
        ("+7(916) 123-45-67", ['"+7(916) 123-45-67"']),
    ],
)
def test_ключи_названия_без_букв(название, ожидаемые):
    assert name_variants_of(название) == ожидаемые


def test_название_с_буквами_ключи_прежние():
    """Правило касается только безбуквенного ядра: у обычного названия ядро без формы остаётся
    ключом, как прежде, — и число внутри ядра его не меняет."""
    assert name_variants_of('ООО "Альфа 2"') == ['ооо "альфа 2"', "альфа 2"]
    assert name_variants_of("ИП Петров") == ["ип петров", "петров"]


def test_словарь_не_отдаёт_голое_число_в_автомат(среда):
    словарь, _, назвать = среда
    токен = назвать('ООО "2020"')

    варианты = словарь.name_variants()

    assert "2020" not in варианты
    assert варианты['"2020"'] == токен
    assert варианты["ооо 2020"] == токен
    assert варианты['ооо "2020"'] == токен


def test_общий_кавычечный_ключ_двух_организаций_неоднозначен(среда):
    """`ООО "2020"` и `АО "2020"` — разные юрлица: ключ `"2020"` у обоих, заменить его правильно
    нельзя (§6.5, поправка ⁷), и он не участвует. Полные названия и `<форма> 2020` — однозначны."""
    словарь, маскировщик, назвать = среда
    ооо = назвать('ООО "2020"')
    ао = назвать('АО "2020"')

    варианты = словарь.name_variants()

    assert '"2020"' not in варианты
    assert set(словарь.ambiguous_name_variants()['"2020"']) == {ооо, ао}
    assert _пройти("маскировщик", словарь, маскировщик, "от АО 2020 и ООО «2020»") == (
        f"от {ао} и {ооо}"
    )


def test_словарь_прежней_версии_получает_новые_ключи(tmp_path):
    """Словарь версии 2 хранит голое ядро и не знает кавычечного ключа и ключа с формой. Первое
    открытие пересчитывает варианты (`ВЕРСИЯ_СХЕМЫ`, как при свёртке кавычек): без пересчёта
    голое ядро закрывало бы числа, а без новых ключей название открылось бы (так и было на Р2-3)."""
    путь = tmp_path / "gate.sqlite"
    словарь = Dictionary(путь, СЕКРЕТ)
    токен = словарь.token_for("org", 'ООО "2020"', base="ut", entity=К, field="Description")
    словарь.close()
    соединение = sqlite3.connect(путь)
    with соединение:
        соединение.execute("DELETE FROM name_variants WHERE token = ?", (токен,))
        соединение.executemany(
            "INSERT INTO name_variants (token, variant_norm) VALUES (?, ?)",
            [(токен, 'ооо "2020"'), (токен, "2020")],
        )
        соединение.execute("PRAGMA user_version = 2")
    соединение.close()

    словарь = Dictionary(путь, СЕКРЕТ)
    try:
        assert словарь.name_variants() == {
            'ооо "2020"': токен,
            '"2020"': токен,
            "ооо 2020": токен,
        }
    finally:
        словарь.close()


def test_голое_число_в_таблице_вариантов_не_идёт_в_автомат(tmp_path):
    """Защита на чтении: даже если в таблице окажется голое безбуквенное ядро (словарь дописан
    прежней версией шлюза после пересчёта), в автомат оно не идёт — число остаётся числом."""
    путь = tmp_path / "gate.sqlite"
    словарь = Dictionary(путь, СЕКРЕТ)
    токен = словарь.token_for("org", 'ООО "2020"', base="ut", entity=К, field="Description")
    соединение = sqlite3.connect(путь)
    with соединение:
        соединение.execute(
            "INSERT INTO name_variants (token, variant_norm) VALUES (?, ?)", (токен, "2020")
        )
    соединение.close()
    try:
        assert "2020" not in словарь.name_variants()
    finally:
        словарь.close()


# --- Где ещё ядро могло бы открыть название или закрыть число -------------------------------------


def test_отбор_и_слой_раскрытого_по_названию_без_букв(среда):
    """Отбор `eq` по токену такого названия уходит полным написанием (не ядром), и слой
    раскрытого этого вызова ищет в ответе то, что ушло в 1С: название закрыто, число — нет."""
    словарь, _, назвать = среда
    токен = назвать('ООО "2020"')
    подмена = Unmasker(
        словарь,
        base="ut",
        field_class=lambda e, f, *, strict=False: "org" if f == "Description" else None,
        path_class=без_класса_пути,
    )
    раскрыто = RevealedValues()

    ушло = подмена.filter(f"Description eq '{токен}'", entity=К, revealed=раскрыто)
    ответ = json.dumps(
        {"Description": 'ООО "2020"', "Комментарий": "поставка 2020 года, от «2020»"},
        ensure_ascii=False,
    )
    данные = json.loads(
        Guard(словарь).check(ответ, mode="identifiers+names", revealed=раскрыто).text
    )

    assert ушло == "Description eq 'ООО \"2020\"'"
    assert данные == {"Description": токен, "Комментарий": f"поставка 2020 года, от {токен}"}


def test_запись_токена_названия_без_букв_полным_написанием(среда):
    словарь, _, назвать = среда
    токен = назвать('ООО "2020"')
    подмена = Unmasker(
        словарь,
        base="ut",
        field_class=lambda e, f, *, strict=False: "org" if f == "Description" else None,
        path_class=без_класса_пути,
    )

    тело = подмена.write({"Description": токен}, entity=К, current=None, revealed=RevealedValues())

    assert тело == {"Description": 'ООО "2020"'}
