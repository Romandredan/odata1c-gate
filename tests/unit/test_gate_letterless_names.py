# --- Р4-2 (ревью раунда 4): название прежней версии после пересчёта получает новые ключи ----------


def _записать_как_прежняя_версия(путь, токен: str, ключи: list[str]) -> None:
    соединение = sqlite3.connect(путь)
    with соединение:
        соединение.execute("DELETE FROM name_variants WHERE token = ?", (токен,))
        соединение.executemany(
            "INSERT INTO name_variants (token, variant_norm) VALUES (?, ?)",
            [(токен, ключ) for ключ in ключи],
        )
    соединение.close()


def test_название_без_букв_от_старой_версии_получает_ключи(tmp_path):
    """Воспроизведение ревьюера: прежняя версия шлюза записала название без букв уже ПОСЛЕ
    пересчёта (дом с двумя версиями кода) — голое ядро в `name_variants`, ключей в кавычках и с
    формой нет, версия уже 3. Пересчёт идёт и по содержимому: голое безбуквенное ядро в таблице —
    признак записи прежней версией, такие токены пересчитываются при открытии."""
    путь = tmp_path / "gate.sqlite"
    с = Dictionary(путь, СЕКРЕТ)
    токен = с.token_for("org", 'ООО "3030"', base="ut", entity=К, field="Description")
    с.close()
    _записать_как_прежняя_версия(путь, токен, ['ооо "3030"', "3030"])

    с = Dictionary(путь, СЕКРЕТ)
    try:
        итог = json.loads(
            Guard(с)
            .check(
                json.dumps({"К": 'от "3030" вх, от ООО 3030 вх'}, ensure_ascii=False),
                mode="identifiers+names",
            )
            .text
        )["К"]
        assert итог == f"от {токен} вх, от {токен} вх"
    finally:
        с.close()
    # В таблице голого ядра больше нет — следующее открытие пересчитывать нечего.
    соединение = sqlite3.connect(путь)
    try:
        остаток = соединение.execute(
            "SELECT COUNT(*) FROM name_variants WHERE variant_norm = '3030'"
        ).fetchone()
    finally:
        соединение.close()
    assert остаток == (0,)


def test_короткое_ядро_в_кавычках_от_промежуточной_версии_снимается(tmp_path):
    """Тот же пересчёт по содержимому снимает ключ `"50"` (так писала промежуточная версия раунда 4
    при той же версии содержимого 3) и добавляет недостающие ключи с формой."""
