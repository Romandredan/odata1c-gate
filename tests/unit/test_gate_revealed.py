def test_раскрытое_проверяется_раньше_цифровых_серий(страж):
    """Порядок слоёв — не вкусовщина: набор идёт ПЕРВЫМ, до цифровых серий словаря.

    Случай: внутри раскрытого адреса стоит почтовый индекс, а словарь уже знает шестизначный код
    подразделения паспорта с теми же цифрами (обе величины шестизначные, совпадение в одной базе
    вполне возможно). Если сначала отработает слой чисел, он заменит цифры ВНУТРИ раскрытого
    значения — точное вхождение больше не совпадёт, и свободнотекстовый остаток адреса («г.
    Москва, Тверская») выйдет наружу.
    """
    словарь, охрана = страж
    код = словарь.token_for("doc", "125009", base="ut", entity="E", field="КодПодразделения")
    адрес = "125009, г. Москва, Тверская, 7"
    токен = словарь.token_for("addr", адрес, base="ut", entity="E", field="АдресРегистрации")
    assert токен != код, "тест имеет смысл только на РАЗНЫХ токенах"
    набор = RevealedValues()
    набор.add(адрес, token=токен)

    результат = охрана.check(
        _ошибка_отбора("АдресРегистрации", адрес), mode="identifiers", revealed=набор
    )

    assert "Москва" not in результат.text
    assert токен in результат.text and код not in результат.text


