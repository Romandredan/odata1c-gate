def _ошибка_отбора(поле: str, значение: str) -> str:
    """Ответ тула с текстом ошибки 1С, повторяющим выражение отбора вместе с литералом."""
    return json.dumps(
        {
            "error": {
                "code": "odata_error",
                "message": f"Ошибка при разборе выражения отбора: {поле} eq '{значение}'",
                "hint": "текст выше — сообщение платформы",
            }
        },
        ensure_ascii=False,
    )


