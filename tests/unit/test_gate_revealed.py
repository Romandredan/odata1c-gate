def test_набор_хранит_первый_токен_значения():
    """Одно и то же написание, раскрытое дважды под разными токенами (классы различаются, а
    свёрнутая форма совпала), заменяется первым из них: спрятать значение обязаны оба, а
    чередование токенов сделало бы ответ невоспроизводимым."""
    набор = RevealedValues()
    набор.add("45 03 123456", token="[[doc:AAA]]")
    набор.add("45 03 123456", token="[[inn:BBB]]")
    assert набор.tokens() == {"45 03 123456": "[[doc:AAA]]"}


