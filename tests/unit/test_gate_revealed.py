# ---------------------------------------------------------------------------------------------
# Ruling 32 и правило вложенности (последний раунд M1d, находки C-1 и I-1 ревью 6)
# ---------------------------------------------------------------------------------------------


def _раскрытое_внутри_названия(страж):
    """Словарь знает «ООО Альфа-Строй Инвест» и «Альфа»; раскрыто «Альфа»."""
    словарь, охрана = страж
    длинный = словарь.token_for(
        "org", "ООО Альфа-Строй Инвест", base="ut", entity="E", field="Description"
    )
    короткий = словарь.token_for("org", "Альфа", base="ut", entity="E", field="Description")
    охрана.rebuild()
    набор = RevealedValues()
    набор.add("Альфа", token=короткий)
    return охрана, набор, длинный, короткий


def test_последний_рубеж_тоже_отдаёт_победу_накрывающему_названию(страж):
    """Правило вложенности действует и на последнем рубеже (`check`), а не только в раннем
    проходе: иначе страж, встретив раскрытое внутри неподменённого названия, оставил бы тот же
    обрывок третьего лица, который ранний проход больше не оставляет."""
    охрана, набор, длинный, _ = _раскрытое_внутри_названия(страж)
    ответ = json.dumps({"Комментарий": "субподряд: ООО Альфа-Строй Инвест"}, ensure_ascii=False)

    результат = охрана.check(ответ, mode="identifiers+names", revealed=набор)

    assert json.loads(результат.text) == {"Комментарий": f"субподряд: {длинный}"}
    assert результат.warnings == ["guard_replaced"]


def test_на_уровне_identifiers_названия_раскрытому_не_соперники(страж):
    """На уровне `identifiers` названия не защищаются (SPEC §6.2): спорить с раскрытым им нечем,
    и заменяется ровно раскрытое — как до правила вложенности."""
    охрана, набор, _, короткий = _раскрытое_внутри_названия(страж)

    результат = охрана.scrub_revealed(
        "субподряд: ООО Альфа-Строй Инвест", набор, mode="identifiers"
    )

    assert результат == f"субподряд: ООО {короткий}-Строй Инвест"


def test_замену_известного_названия_стражу_не_засчитывает(страж):
    """Раскрытое внутри известного названия или само известное как название: замену сделал бы и
    маскировщик (слой названий, `mask_text` для ошибки), и `guard_replaced` здесь был бы ложной
    тревогой — ответ без отбора молчит. Токен при совпадении отрезков — раскрытого."""
    охрана, набор, длинный, короткий = _раскрытое_внутри_названия(страж)

    накрытое = охрана.scrub_revealed("Ошибка: ООО Альфа-Строй Инвест", набор)
    совпавшее = охрана.scrub_revealed("Ошибка: Альфа", набор)

    assert накрытое == f"Ошибка: {длинный}"
    assert совпавшее == f"Ошибка: {короткий}"
    assert набор.replacements == 0


def test_раскрытое_без_названия_засчитывается_стражу(страж):
    """Обратная сторона: раскрытое, которого слой названий не знает (адрес), закрывает только
    ранний проход, и замена засчитывается — `guard_replaced` здесь правда (Ruling 25)."""
    словарь, охрана = страж
    адрес = "г. Москва, ул. Тверская, д. 7, кв. 43"
    токен = словарь.token_for("addr", адрес, base="ut", entity="E", field="АдресРегистрации")
    охрана.rebuild()
    набор = RevealedValues()
    набор.add(адрес, token=токен)

    результат = охрана.scrub_revealed(f"Ошибка: АдресРегистрации eq '{адрес}'", набор)

    assert результат == f"Ошибка: АдресРегистрации eq '{токен}'"
    assert набор.replacements == 1


def test_разбор_после_раннего_прохода_помечает_строки_по_месту(страж):
    """Ruling 32: у каждой переписанной строки — исходное значение ЕЁ места, даже если после
    замены строки одинаковы, а до неё разные (регистр, мягкий перенос). Непереписанные строки и
    ключи — обычные строки. Адрес — класс без слоя названий: каждая замена засчитана стражу, и
    число засчитанных едет в строке (`hits`), чтобы маскировщик мог снять его в поле с классом."""
    словарь, охрана = страж
    адрес = "г. Москва, ул. Тверская, д. 7"
    токен = словарь.token_for("addr", адрес, base="ut", entity="E", field="АдресРегистрации")
    набор = RevealedValues()
    набор.add(адрес, token=токен)
    с_переносом = "г. Москва, ул. Твер\u00adская, д. 7"
    заглавными = "Г. МОСКВА, УЛ. ТВЕРСКАЯ, Д. 7"
    тело = json.dumps(
        {
            "value": [
                {"АдресРегистрации": с_переносом, "Код": "001"},
                {"АдресРегистрации": заглавными, "Код": "002"},
            ]
        },
        ensure_ascii=False,
    )

    данные = охрана.scrub_revealed_json(тело, набор, mode="identifiers+names")

    первая, вторая = данные["value"]
    assert (первая["АдресРегистрации"], вторая["АдресРегистрации"]) == (токен, токен)
    assert isinstance(первая["АдресРегистрации"], ScrubbedText)
    assert первая["АдресРегистрации"].original == с_переносом
    assert вторая["АдресРегистрации"].original == заглавными
    assert (первая["АдресРегистрации"].hits, вторая["АдресРегистрации"].hits) == (1, 1)
    assert type(первая["Код"]) is str
    assert all(type(ключ) is str for ключ in первая)


def test_разбор_скалярного_ответа_помечает_его_исходным(страж):
    """Ответ `…/ИНН/$value` из одних цифр — JSON-скаляр: ранний проход проверяет его как текст и
    записывает строкой. Это тоже место со своим значением, и разбор помечает его."""
    словарь, охрана = страж
    инн = "7707083893"
    токен = словарь.token_for("inn", инн, base="ut", entity="E", field="ИНН")
    набор = RevealedValues()
    набор.add(инн, token=токен)

