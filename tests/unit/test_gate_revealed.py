def test_набор_помнит_значение_и_формы_отправки():
    """Кроме самого значения набор помнит формы, в которых его отправляет САМ шлюз: с удвоенным
    апострофом (литерал `$filter`) и процентные (строка запроса и путь). Веб-сервер перед 1С
    повторяет адрес запроса в теле своей страницы ошибки, и без процентной формы одного `unquote`
    хватало, чтобы прочитать значение целиком (N1-A ревью 2026-09-11)."""
    значение = "г. Москва, ул. О'Брайена, д. 7"
    набор = RevealedValues()
    набор.add(значение, token="[[addr:A60KNQH867]]")
    формы = набор.tokens()

    assert формы[значение.lower()] == "[[addr:A60KNQH867]]"
    assert формы[значение.replace("'", "''").lower()] == "[[addr:A60KNQH867]]"
    assert формы[urllib.parse.quote(значение, safe="").lower()] == "[[addr:A60KNQH867]]"
    assert набор


