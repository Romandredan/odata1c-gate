@pytest.fixture
def размаскировщик(tmp_path):
    словарь = Dictionary(tmp_path / "unmask.sqlite", СЕКРЕТ)

    def класс_поля(entity, field, *, strict=False):
        return {"АдресРегистрации": "addr"}.get(field.rsplit("/", 1)[-1])

    yield словарь, Unmasker(словарь, base="ut", field_class=класс_поля)
    словарь.close()


@pytest.mark.parametrize("вход", ["filter", "value", "key", "body"])
def test_каждый_вход_обратной_подмены_записывает_раскрытое(размаскировщик, вход):
    """Все четыре входа обратной подмены сходятся в `_раскрыть` — и каждый обязан отдать
    раскрытое стражу. Проверка по входам, а не по одному `filter`: `get` по составному ключу и
    тело записи раскрывают токен тем же кодом и той же дырой пользовались бы."""
    словарь, размаскирование = размаскировщик
    значение = ЗНАЧЕНИЯ_КЛАССОВ["addr"]
    токен = словарь.token_for("addr", значение, base="ut", entity="E", field="АдресРегистрации")
    набор = RevealedValues()

    if вход == "filter":
        размаскирование.filter(f"АдресРегистрации eq '{токен}'", entity="E", revealed=набор)
    elif вход == "value":
        размаскирование.value(токен, entity="E", field="АдресРегистрации", revealed=набор)
    elif вход == "key":
        размаскирование.key({"АдресРегистрации": токен}, entity="E", revealed=набор)
    else:
        размаскирование.body({"АдресРегистрации": токен}, entity="E", revealed=набор)

    assert набор.tokens()[значение.lower()] == токен


