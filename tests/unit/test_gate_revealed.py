@pytest.mark.parametrize(
    "эхо",
    [
        "Ошибка при разборе выражения отбора: КПП eq '1'",
        "Ошибка при разборе: %D0%9A%D0%9F%D0%9F%20eq%20%271%27",
        "Ошибка при разборе выражения отбора: КПП eq 1",
        "Ошибка при разборе: %D0%9A%D0%9F%D0%9F%20eq%201",
    ],
    ids=["литерал-в-кавычках", "процентная-запись", "число-без-кавычек", "процентная-без-кавычек"],
)
def test_эхо_короткого_раскрытого_ловится_во_всех_формах_возврата(короткое, эхо):
    """Инвариант 1 не уступает инварианту 6: значение, которое модель сама попросила раскрыть,
    она не должна прочитать в эхе.

    Четыре формы. Кавычечная и процентная закрываются удлинением иглы — в набор кладётся не
    «1», а обрамление, которое поставил САМ шлюз (`'1'`, `%271%27`); набор закрытый и известный,
    это записи шлюза, а не догадки о платформе (Ruling 21). Форма без кавычек (проба P7: 1С
    повторяет число как есть) обрамления не имеет — там работают границы, причём процентная
    запись `%XX` рядом обязана считаться границей: иначе в `%20eq%201` слева от единицы стоит
    цифра «0» кодировки пробела, и совпадение отбросилось бы."""
    охрана, набор, токен = короткое

    результат = охрана.scrub_revealed(эхо, набор)

    assert токен in результат
    assert набор.replacements == 1


