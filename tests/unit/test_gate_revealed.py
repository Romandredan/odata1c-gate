"""Страж видит то, что гейт раскрыл в этом же вызове (задача N1 M1d, инвариант 1).

Раскрытие токена бывает законным: токен класса `addr` в поле класса `addr` — ровно то, что
разрешает Ruling 20. Реальное значение при этом уходит в 1С — так и задумано. Но обратно оно
может вернуться: 1С повторяет выражение отбора в тексте ошибки, значение приходит данными
другого поля, попадает в подсказку. Собрать его обратно страж умел только у классов из
`detectors.SCAN_ORDER`, у цифровых серий словаря и у названий (`org`/`person`) — `addr`, `dob`
и свободнотекстовый `doc` не покрывал никто.

Здесь проверяется принцип: всё, что гейт раскрыл при обработке ОДНОГО вызова, страж ищет в
исходящем ответе того же вызова точным вхождением и заменяет обратно на токен — независимо от
класса, даже когда у класса нет ни детектора, ни цифровой серии, ни автомата названий. Набор
живёт ровно один вызов: ни между вызовами, ни между сессиями состояния нет (`BaseGate`
кэшируется на базу и делится сессиями, поэтому хранить раскрытое на нём нельзя).
"""

import json

import pytest
from conftest import ЗНАЧЕНИЯ_КЛАССОВ

from odata1c.gate.dictionary import Dictionary
from odata1c.gate.guard import Guard
from odata1c.gate.revealed import RevealedValues
from odata1c.gate.unmasking import Unmasker

СЕКРЕТ = "секрет ровно для тестов раскрытия".encode()

# Классы, у которых, кроме этого слоя, последнего рубежа нет вовсе: ни детектора в
# `detectors.SCAN_ORDER`, ни цифровой серии в словаре стража, ни автомата названий. На них и
# держится весь смысл задачи — остальные классы проверяются заодно, чтобы правило было общим.
БЕЗ_ДРУГИХ_СТРАХОВОК = ("addr", "dob")
СВОБОДНЫЙ_ТЕКСТ_DOC = "ОУФМС России по гор. Москве"


@pytest.fixture
def страж(tmp_path):
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    yield словарь, Guard(словарь)
    словарь.close()


def _ошибка_отбора(поле: str, значение: str) -> str:
    """Ответ тула с текстом ошибки 1С, повторяющим выражение отбора вместе с литералом."""
    return json.dumps(
        {
            "error": {
                "code": "odata_error",
                "message": f"Ошибка при разборе выражения отбора: {поле} eq '{значение}'",
                "hint": "текст выше — сообщение платформы",
            }
        },
        ensure_ascii=False,
    )


