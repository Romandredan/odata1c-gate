    assert токен != код, "тест имеет смысл только на РАЗНЫХ токенах"
    набор = RevealedValues()
    набор.add(адрес, token=токен)

    результат = охрана.check(
        _ошибка_отбора("АдресРегистрации", адрес), mode="identifiers", revealed=набор
    )

    assert "Москва" not in результат.text
    assert токен in результат.text and код not in результат.text


