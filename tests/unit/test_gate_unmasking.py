def test_вложенный_объект_под_полем_связи_в_теле_записи_работает(связка):
    """Контрольный положительный случай к предыдущему тесту: целый токен правильного класса во
    вложенном объекте по-прежнему успешно раскрывается реальным значением."""
    словарь, обратно = связка
