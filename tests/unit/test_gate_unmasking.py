# --- Правка E (ревью задачи 7, второй раунд): анти-оракульное правило на классе без
# контрольной суммы --------------------------------------------------------------------------
#
# Единственный существующий тест на закрытие оракула (`..._с_обрывком_отклонён`, выше) берёт
# ИНН — у него есть контрольная сумма, и обрывок «7707» отклоняется ею же, даже если само
# анти-оракульное правило выключить целиком: мутация, вырезающая правило, не роняет ни одного
# теста. Классы ниже (acc/phone/doc) в ПРОВЕРКИ не входят — единственная защита здесь именно
# правило, а не контрольная сумма. Отключение правила вручную (см. ниже) подтверждено падением
# всех трёх «негативных» тестов; после проверки код возвращён к исходному состоянию.


@pytest.mark.parametrize(
    "entity,field,класс,значение",
    [
        ("Catalog_БанковскиеСчета", "НомерСчета", "acc", "40702810900000012345"),
        ("Catalog_Контрагенты", "Телефон", "phone", "+79161234567"),
        ("Document_РеализацияТоваровУслуг", "Номер", "doc", "АА-000123"),
    ],
    ids=["acc", "phone", "doc"],
)
class TestОбходыБезКонтрольнойСуммы:
    def test_поиск_подстроки_с_обрывком_отклонён(self, связка, entity, field, класс, значение):
        """Обход A/оракул: обрывок реального значения в substringof — попытка подбора по
        символу, контрольной суммы у класса нет, единственная защита — само правило."""
        _, обратно = связка
        обрывок = значение[:4]
        with pytest.raises(GateError) as ошибка:
            обратно.filter(f"substringof('{обрывок}', {field})", entity=entity)
        assert ошибка.value.code == "filter_syntax"

    def test_поиск_подстроки_с_полным_значением_отклонён(
        self, связка, entity, field, класс, значение
    ):
        """Оракул: даже полное реальное значение (не токен) в substringof на защищаемом классе
        без исключения org/person отклоняется — модель не должна была знать его целиком."""
        _, обратно = связка
        with pytest.raises(GateError) as ошибка:
            обратно.filter(f"substringof('{значение}', {field})", entity=entity)
        assert ошибка.value.code == "filter_syntax"

    def test_упорядоченное_сравнение_с_литералом_отклонено(
        self, связка, entity, field, класс, значение
    ):
        """Обход B: gt/ge/lt/le с литералом на защищаемом классе запрещены без исключений —
        двоичным поиском значение иначе восстанавливается за десяток запросов."""
        _, обратно = связка
        with pytest.raises(GateError) as ошибка:
            обратно.filter(f"{field} ge '{значение}'", entity=entity)
        assert ошибка.value.code == "filter_syntax"

    def test_равенство_с_целым_токеном_работает(self, связка, entity, field, класс, значение):
        """Контрольный положительный случай: правило не задевает штатный путь — целый токен на
        равенстве проходит и подставляется реальным значением."""
        словарь, обратно = связка
        токен = словарь.token_for(класс, значение, base="ut", entity=entity, field=field)
        результат = обратно.filter(f"{field} eq '{токен}'", entity=entity)
        assert результат == f"{field} eq '{значение}'"


