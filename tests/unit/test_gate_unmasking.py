def test_переписывание_функции_работает_в_отрицании_и_скобках(связка):
    """Правка 3: переписывание — не «вся строка совпадает с вызовом целиком», а вызов может
    быть где угодно в выражении, включая under `not` и в скобках. Правка F: под `not`
    переписанное сравнение обёрнуто в скобки — иначе «not X eq Y» по грамматике OData
    читается как «(not X) eq Y», а не «not (X eq Y)»."""
    словарь, обратно = связка
    токен = словарь.token_for(
        "org", "ООО Ромашка", base="ut", entity="Catalog_Контрагенты", field="Description"
    )
    результат_not = обратно.filter(
        f"not substringof('{токен}', Description)", entity="Catalog_Контрагенты"
    )
    assert результат_not == "not (Description eq 'ООО Ромашка')"

    результат_скобки = обратно.filter(
        f"(substringof('{токен}', Description))", entity="Catalog_Контрагенты"
    )
    assert результат_скобки == "(Description eq 'ООО Ромашка')"


