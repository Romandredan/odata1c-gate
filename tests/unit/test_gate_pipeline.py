# --- M-5 (M3b задача 2): два прохода маскировщика, сквозь весь гейт со стражем ------------------


def _сквозь_гейт(врата: BaseGate, записи, набор: RevealedValues | None = None) -> dict:
    """Настоящая цепочка тула: `mask` → конверт → `finish` со стражем. Проверяется то, что видит
    модель, а не выход маскировщика: у стража свои слои, и «маскировщик пропустил, страж поймал»
    тоже засчитывается защитой."""
    маска = врата.mask(
        записи,
        entity="Catalog_Контрагенты",
        resolve=lambda сущность, ключ: None,
        hidden=lambda сущность: False,
        revealed=набор,
        shape=строение_неизвестно,
    )
    return json.loads(врата.finish({"items": маска.data, "warnings": []}, набор))


def test_m5_название_с_реквизитом_внутри_закрыто_и_в_свободном_тексте(врата_prod):
    """I-1 ревью задачи 2 M3b: нагруженный случай, где страж дефект НЕ закрывал. Название поля
    класса содержит ИНН, и в свободном тексте стоит то же сочетание. У маскировщика слой названий
    идёт ДО детекторов, у стража числа — ДО названий: без первого прохода комментарий обрабатывался
    с пустым автоматом, детектор заменял в нём ИНН токеном, и единственный вариант словаря
    (написание С ИНН) переставал совпадать с текстом — страж молчал, название оставалось открытым.
    """
    записи = [
        {"Комментарий": 'платёж ООО "Ромашка" ИНН 7707083893 итого'},
        {"Description": 'ООО "Ромашка" ИНН 7707083893'},
    ]

    ответ = _сквозь_гейт(врата_prod, записи)

    токен = ответ["items"][1]["Description"]
    assert TOKEN_RE.fullmatch(токен), токен
    assert "Ромашка" not in ответ["items"][0]["Комментарий"]
    assert ответ["items"][0]["Комментарий"] == f"платёж {токен} итого"


