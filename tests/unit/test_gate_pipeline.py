def _переписанное(врата: BaseGate, набор: RevealedValues, тело: dict):
    """Тело ответа 1С так, как его отдаёт клиент с ранним проходом (`Client1C.get(scrub=…)`)."""
    return врата.scrubber(набор).load(json.dumps(тело, ensure_ascii=False))


