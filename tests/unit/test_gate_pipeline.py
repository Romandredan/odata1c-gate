# --- M-7 (хвост M1d): служебный счётчик `odata.count` мимо раннего прохода ---------------------


def test_m7_счётчик_inlinecount_не_подменяется_коротким_раскрытым(врата_prod):
    """M-7 (хвост M1d). Раскрытое короткое значение (`КПП` из мусорных данных базы — «1») ищется
    ранним проходом по границам, а кавычки JSON — граница: `"odata.count": "1"` подменялся токеном
    ещё до `json.loads`, `int()` падал, тул отвечал `internal`.

    Счётчик — служебное поле шлюза, а не данные 1С (SPEC §5.1: `odata.count` вырезается из
    ответа), поэтому ранний проход его не касается. То же значение в ДАННЫХ строки по-прежнему
    закрывается."""
    набор = RevealedValues()
    набор.add("1", token="[[kpp:AAAABBBBCC]]")
    тело = '{"odata.metadata":"…","odata.count":"1","value":[{"КПП":"1","Код":"1"}]}'

    разобрано = врата_prod.scrub_revealed_json(тело, набор)

    записи, всего = items_of(разобрано)
    assert всего == 1
    assert записи[0]["КПП"] != "1"


@pytest.mark.parametrize("набор", [None, "пустой"], ids=["без набора", "пустой набор"])
def test_m7_счётчик_приходит_числом_и_без_раннего_прохода(врата_prod, набор):
    """Минор ревью задачи 3: тип счётчика не должен зависеть от того, был ли ранний проход.
    Раньше с раскрытым приходило число, а без — строка, как её отдаёт публикация 1С (проба P4);
    разбор счётчика теперь один на обе ветки."""
    тело = '{"odata.count":"1103","value":[{"Код":"7"}]}'

    разобрано = врата_prod.scrub_revealed_json(тело, None if набор is None else RevealedValues())

    assert разобрано["odata.count"] == 1103


def test_m7_счётчик_на_уровне_off_тоже_число(врата_dev):
    """Уровень `off` идёт той же веткой: гейт не маскирует, но форму ответа не меняет от базы
    к базе."""
    разобрано = врата_dev.scrub_revealed_json('{"odata.count":"5","value":[]}', RevealedValues())

    assert разобрано["odata.count"] == 5


# --- M3b §3.6: то же правило пустого литерала на пути ЗАПИСИ ------------------------------------
#
# `BaseGate.check_open_literal` — вход подготовки `update` (Ruling 45): она сравнивает тело с
# текущим состоянием и отвечает «изменений нет», то есть задаёт 1С тот же вопрос, что `eq`/`ne` на
# чтении. Правило обязано быть одним и тем же на обоих путях, а тесты `Unmasker` этого пути не
# видят: без своих тестов `литерал=value` можно снять при рефакторинге, и суд остался бы зелёным.

КИ_КОНТРАГЕНТОВ = "Catalog_Контрагенты_КонтактнаяИнформация"


def test_check_open_literal_пропускает_пустую_строку_на_контактной_информации(врата_prod):
    """Очистка поля контактной информации — «поле не заполнено», один бит, а не подбор значения."""
    врата_prod.check_open_literal(КИ_КОНТРАГЕНТОВ, "Представление", "", shape=строение_неизвестно)


def test_check_open_literal_отклоняет_литерал_из_пробелов_на_контактной_информации(врата_prod):
    """Послабление — ровно пустая строка: строка из пробелов остаётся открытым литералом."""
    with pytest.raises(GateError) as отказ:
        врата_prod.check_open_literal(
            КИ_КОНТРАГЕНТОВ, "Представление", " ", shape=строение_неизвестно
        )
    assert отказ.value.code == "filter_syntax"


def test_check_open_literal_не_пропускает_пустую_строку_на_дате_рождения(врата_prod):
    """Контроль: класс `dob` послабления не получает — очистить дату нечем, кроме пустой даты 1С
    (`0001-01-01T00:00:00`), и `литерал` его ветку не задевает."""
    with pytest.raises(GateError) as отказ:
        врата_prod.check_open_literal(
            "Catalog_ФизическиеЛица", "ДатаРождения", "", shape=строение_неизвестно
        )
    assert отказ.value.code == "filter_syntax"
