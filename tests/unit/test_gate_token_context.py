"""Ruling 20: раскрытие токена допустимо только при известном целевом поле и совпадении класса.

Ревью 2026-09-11 в роли атакующего показало, что шлюз работал универсальным дешифратором:
токен подставлялся в параметр, который ни с чем не сравнивается, проверка класса пропускалась
(`Unmasker._раскрыть` при пустом имени поля), словарь отдавал реальное значение ЛЮБОГО класса,
а построитель литерала повторял его в тексте ошибки. Адрес и дата рождения выходили открытым
текстом за один вызов, без обращения к 1С.

Прошлый сторож («раскрытое значение не выходит в тексте ошибки») был построен на ИНН —
единственном классе, у которого есть сразу три независимые страховки: детектор, контрольная
сумма и цифровая серия в страже. На классах `addr` и `dob` страховок нет ни одной, и тест бы не
покраснел. Поэтому здесь всё параметризовано ПО ВСЕМ классам гейта, а к каждому запрету
приставлен парный разрешающий случай: «отказывать всегда» — тоже сломанный шлюз, и тест,
проверяющий только отсутствие значения, такую поломку не заметит.
"""

import pytest
from conftest import без_класса_пути

from odata1c.gate.dictionary import Dictionary
from odata1c.gate.tokens import CLASSES
from odata1c.gate.unmasking import GateError, Unmasker

СЕКРЕТ = "секрет ровно для проверки контекста токена".encode()

СУЩНОСТЬ = "Catalog_Проба"
# Поле, класс которого не определён ничем: ни политикой, ни запасным классификатором по имени.
# Именно такое поле (и пустое имя поля) и делало шлюз дешифратором.
БЕЗ_КЛАССА = "Комментарий"

# Класс гейта → (поле этого класса, реальное значение). Значения — правдоподобные, но полностью
# выдуманные: тест обязан доказать, что ни одно из них не выходит наружу.
ЗНАЧЕНИЯ: dict[str, tuple[str, str]] = {
    "inn": ("ИНН", "7707083893"),
    "kpp": ("КПП", "770701001"),
    "ogrn": ("ОГРН", "1027700132195"),
    "acc": ("НомерСчета", "40702810900000012345"),
    "corr": ("КоррСчет", "30101810400000000225"),
    "bic": ("БИК", "044525225"),
    "iban": ("IBAN", "DE89370400440532013000"),
    "card": ("НомерКарты", "4111111111111111"),
    "snils": ("СНИЛС", "112-233-445 95"),
    "doc": ("НомерПаспорта", "45 03 123456"),
    "phone": ("Телефон", "+7 916 123-45-67"),
    "email": ("Email", "ivan@example.com"),
    "dob": ("ДатаРождения", "1980-05-01"),
    "addr": ("АдресРегистрации", "г. Москва, ул. Тверская, д. 7, кв. 43"),
    "org": ("Description", "ООО Ромашка"),
    "person": ("ФИО", "Иванов Иван Иванович"),
}

# Все классы гейта, кроме `keep` (он означает «не заменять вовсе», токенов такого класса не
# бывает). Проверка состава — сторож на будущее: новый класс в `tokens.CLASSES` обязан прийти
# сюда вместе с образцом значения, иначе он останется без сторожа ровно так же, как `addr`.
КЛАССЫ = sorted(ЗНАЧЕНИЯ)


def test_перечень_классов_покрыт_целиком():
    assert set(КЛАССЫ) == CLASSES - {"keep"}


@pytest.fixture
def связка(tmp_path):
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    классы = {поле: класс for класс, (поле, _) in ЗНАЧЕНИЯ.items()}

    def класс_поля(entity, field, *, strict=False):
        return классы.get(field)

    yield словарь, Unmasker(словарь, base="ut", field_class=класс_поля, path_class=без_класса_пути)
    словарь.close()


def токен(словарь: Dictionary, класс: str, *, поле: str | None = None) -> str:
    """Токен, который модель увидела бы в ответе: выдаётся словарём ровно так же, как его выдаёт
    маскировщик при обработке ответа 1С."""
    имя_поля, значение = ЗНАЧЕНИЯ[класс]
    return словарь.token_for(класс, значение, base="ut", entity=СУЩНОСТЬ, field=поле or имя_поля)


# ---------------------------------------------------------------------------------------------
# Запрет: нет контекста — нет раскрытия
# ---------------------------------------------------------------------------------------------


@pytest.mark.parametrize("класс", КЛАССЫ)
def test_токен_в_поле_без_класса_не_раскрывается(связка, класс):
    """C1/C2: поле, класс которого не определён, раскрытие отключало вовсе — и словарь отдавал
    реальное значение любого класса. Теперь это отказ, а не подстановка «на всякий случай»."""
    словарь, обратно = связка
    _, значение = ЗНАЧЕНИЯ[класс]
    with pytest.raises(GateError) as отказ:
        обратно.filter(f"{БЕЗ_КЛАССА} eq '{токен(словарь, класс)}'", entity=СУЩНОСТЬ)
    assert отказ.value.code == "token_type_mismatch"
    assert значение not in str(отказ.value)
    assert значение not in отказ.value.hint


@pytest.mark.parametrize("класс", КЛАССЫ)
def test_токен_без_имени_поля_не_раскрывается(связка, класс):
    """Тот же корень со стороны одиночного значения: параметр рецепта, который ни с чем не
    сравнивается, и простой ключ `get` приходят сюда с пустым именем поля."""
    словарь, обратно = связка
    _, значение = ЗНАЧЕНИЯ[класс]
    with pytest.raises(GateError) as отказ:
        обратно.value(токен(словарь, класс), entity=СУЩНОСТЬ, field="")
    assert отказ.value.code == "token_type_mismatch"
    assert значение not in str(отказ.value)


@pytest.mark.parametrize("класс", КЛАССЫ)
def test_токен_в_простом_ключе_не_раскрывается(связка, класс):
    """Простой ключ 1С — всегда `Ref_Key`, то есть GUID: токен там не бывает правильным
    (C2 ревью — `odata1c_get(key="[[addr:…]]")`)."""
    словарь, обратно = связка
    _, значение = ЗНАЧЕНИЯ[класс]
    with pytest.raises(GateError) as отказ:
        обратно.key(токен(словарь, класс), entity=СУЩНОСТЬ)
    assert отказ.value.code == "token_type_mismatch"
    assert значение not in str(отказ.value)


@pytest.mark.parametrize("класс", КЛАССЫ)
def test_токен_в_поле_чужого_класса_не_раскрывается(связка, класс):
    """Классы между собой тоже не взаимозаменяемы: токен подставляется только в поле своего
    класса, иначе сравнение чужих значений становится оракулом."""
    словарь, обратно = связка
    поле, значение = ЗНАЧЕНИЯ[класс]
    чужое = next(имя for имя in КЛАССЫ if имя != класс)
    чужое_поле = ЗНАЧЕНИЯ[чужое][0]
    with pytest.raises(GateError) as отказ:
        обратно.filter(f"{чужое_поле} eq '{токен(словарь, класс, поле=поле)}'", entity=СУЩНОСТЬ)
    assert отказ.value.code == "token_type_mismatch"
    assert значение not in str(отказ.value)


