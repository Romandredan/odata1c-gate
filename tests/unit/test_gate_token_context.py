@pytest.mark.parametrize("класс", КЛАССЫ)
def test_токен_в_своём_поле_раскрывается(связка, класс):
    """Парный разрешающий случай: без него «отказывать всегда» проходило бы как зелёное."""
    словарь, обратно = связка
    поле, значение = ЗНАЧЕНИЯ[класс]
    результат = обратно.filter(f"{поле} eq '{токен(словарь, класс)}'", entity=СУЩНОСТЬ)
    assert значение in результат


@pytest.mark.parametrize("класс", КЛАССЫ)
def test_токен_своего_класса_переживает_смену_класса_поля(tmp_path, класс):
    """Ruling 19: реиндекс переписывает класс поля, а выданный токен обязан продолжать работать
    в ТОМ ЖЕ поле ТОЙ ЖЕ сущности. Правило «нет совпадения класса — отказ» этого не отменяет."""
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    try:
        поле, значение = ЗНАЧЕНИЯ[класс]
        выданный = словарь.token_for(класс, значение, base="ut", entity=СУЩНОСТЬ, field=поле)

        def класс_поля(entity, field, *, strict=False):
            # Класс того же поля сменился после реиндекса — но не на класс токена.
            return "keep" if field == поле else None

        обратно = Unmasker(словарь, base="ut", field_class=класс_поля, path_class=без_класса_пути)
        assert значение in обратно.filter(f"{поле} eq '{выданный}'", entity=СУЩНОСТЬ)
    finally:
        словарь.close()


def test_послабление_привязано_к_сущности(tmp_path):
    """Пункт 8 дополнения: `issued_for` ключевался одним именем поля, и токен `org`, выданный
    для `Description` контрагента, принимался в `Description` физлица (класс `person`) —
    реальное название уходило в 1С. Ключ — пара «сущность и поле»."""
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    try:
        выданный = словарь.token_for(
            "org", "ООО Ромашка", base="ut", entity="Catalog_Контрагенты", field="Description"
        )

        def класс_поля(entity, field, *, strict=False):
            return "person" if entity == "Catalog_ФизическиеЛица" else "org"

        обратно = Unmasker(словарь, base="ut", field_class=класс_поля, path_class=без_класса_пути)
        assert "Ромашка" in обратно.filter(
            f"Description eq '{выданный}'", entity="Catalog_Контрагенты"
        )
        with pytest.raises(GateError) as отказ:
            обратно.filter(f"Description eq '{выданный}'", entity="Catalog_ФизическиеЛица")
        assert отказ.value.code == "token_type_mismatch"
        assert "Ромашка" not in str(отказ.value)
    finally:
        словарь.close()


def test_послабление_через_связанный_объект_работает_без_сущности(tmp_path):
    """Откат на пару «база и имя поля» — только для пути через связанный объект: там сущность
    в записи о выдаче — сущность родителя, и совпасть с сущностью запроса она не обязана."""
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    try:
        выданный = словарь.token_for(
            "inn", "7707083893", base="ut", entity="Catalog_Контрагенты", field="ИНН"
        )

        def класс_поля(entity, field, *, strict=False):
            return "keep" if field == "ИНН" else None

        обратно = Unmasker(словарь, base="ut", field_class=класс_поля, path_class=без_класса_пути)
        результат = обратно.filter(
            f"Контрагент/ИНН eq '{выданный}'", entity="Document_РеализацияТоваровУслуг"
        )
        assert "7707083893" in результат
    finally:
        словарь.close()


# ---------------------------------------------------------------------------------------------
# Токен, смешанный с текстом (правило I2: в `$filter` оно было, на пути значения — нет)
# ---------------------------------------------------------------------------------------------


def test_токен_смешанный_с_текстом_в_значении_отклонён(связка):
    словарь, обратно = связка
    выданный = токен(словарь, "inn")
    with pytest.raises(GateError) as отказ:
        обратно.value(f"пре{выданный}пост", entity=СУЩНОСТЬ, field="ИНН")
    assert отказ.value.code == "token_partial"
    assert "7707083893" not in str(отказ.value)


def test_токен_внутри_текста_тела_записи_по_прежнему_подставляется(связка):
    """Тело записи (`body`) — единственный путь, где токен внутри текста осмыслен: там пишется
    строка целиком, а не образец сравнения, и оракула подбора из неё не построить."""
    словарь, обратно = связка
    выданный = токен(словарь, "inn")
    результат = обратно.body({"ИНН": f"ИНН {выданный}"}, entity=СУЩНОСТЬ)
    assert результат == {"ИНН": "ИНН 7707083893"}
