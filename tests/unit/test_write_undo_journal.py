def test_маска_без_записи_словарь_не_тронут(среда):
    гейт = среда.tools._gate_for(среда.tools._config.bases["ut"])
    известный = к.токен(среда.tools, ИНН)
    известное_название = к.токен(среда.tools, НАЗВАНИЕ, поле="Description")
    до = к.строки_словаря(среда.tools)

    маска = гейт.mask(
        {
            "ИНН": ИНН,
            "КПП": ЕЩЁ_ИНН[:9],
            "Description": НАЗВАНИЕ,
            "НаименованиеПолное": НОВОЕ_НАЗВАНИЕ,
            "ДополнительнаяИнформация": f"вписано {известный} и ИНН {ЕЩЁ_ИНН}",
        },
        entity=КОНТРАГЕНТЫ,
        resolve=без_навигаций,
        hidden=ничего_не_скрыто,
        revealed=None,
        shape=строение_неизвестно,
        persist=False,
    ).data

    assert к.строки_словаря(среда.tools) == до
    # Известное значение — свой токен, как у обычной маски.
    assert маска["ИНН"] == известный and маска["Description"] == известное_название
    # Новое значение класса с хвостом — детерминированный токен без вставки.
    assert маска["КПП"].startswith("[[kpp:") and ЕЩЁ_ИНН[:9] not in маска["КПП"]
    # Название, которого словарь не знает, номера без записи не получает — пометка без хвоста.
    assert маска["НаименованиеПолное"] == "[[org]]"
    # Б-2 и детектор работают и без записи: токен шлюза в данных — `lit`, ИНН в тексте — токен.
    assert "[[lit:" in маска["ДополнительнаяИнформация"]
    assert известный not in маска["ДополнительнаяИнформация"]
    assert ЕЩЁ_ИНН not in маска["ДополнительнаяИнформация"]


