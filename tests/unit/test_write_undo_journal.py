async def test_два_отката_одного_коммита_одновременно_PATCH_один(среда, одинс):
    одинс.положить(ПУТЬ_КОНТРАГЕНТА, к.контрагент())
    коммит = await коммит_update(среда, {"ИНН": к.токен(среда.tools, НОВЫЙ_ИНН)})
    первый = await подготовить_откат(среда, коммит["commit_id"])
    второй = await подготовить_откат(среда, коммит["commit_id"])
    # Пауза в PATCH — точка, где настоящая сеть отдаёт управление (см. тест параллельных commit
    # задачи 7): без неё первый откат прошёл бы целиком раньше, чем начался второй.
    клиент = среда.tools._client_for(среда.tools._config.bases["ut"])
    настоящий_patch = клиент.patch

    async def с_паузой(path, json, *, scrub=None):
        await asyncio.sleep(0.05)
        return await настоящий_patch(path, json, scrub=scrub)

    клиент.patch = с_паузой

    итоги = await asyncio.gather(
        к.выполнить(среда, первый["pending_id"]), к.выполнить(среда, второй["pending_id"])
    )

    выполненные = [json.loads(т) for т in итоги if "commit_id" in json.loads(т)]
    отказы = [к.ошибка(т) for т in итоги if "error" in json.loads(т)]
    assert len(выполненные) == 1 and len(отказы) == 1
    assert отказы[0]["code"] == "undo_unsupported"
    assert одинс.patch.call_count == 2
    assert среда.журнал(коммит["commit_id"]).undone_by == выполненные[0]["commit_id"]


