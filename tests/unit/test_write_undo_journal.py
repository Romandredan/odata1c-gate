def записать_в_журнал(
    путь,
    *,
    commit_id: str,
    entity: str,
    op: str,
    key,
    request: dict,
    base: str = "ut",
    before=None,
    after=None,
    status: str = "committed",
    error: str | None = None,
) -> None:
    """Строка журнала без `commit`: статусы и операции, которых через поддельную 1С не
    получить (обрыв демона — `started`, запись регистра, чужая операция)."""
    операция = PendingOp(
        pending_id=f"p-{commit_id}",
        commit_id=commit_id,
        session_id="s0",
        base=base,
        role="prod",
        op=op,
        entity=entity,
        key=key,
        request=request,
        preview={},
        data_version=None,
        created_at=0.0,
        expires_at=0.0,
    )
    ж = Journal(путь)
    try:
        ж.open_commit(операция, client="claude_code", before=before)
        if status != "started":
            ж.close_commit(commit_id, after=after, status=status, error=error)
    finally:
        ж.close()


