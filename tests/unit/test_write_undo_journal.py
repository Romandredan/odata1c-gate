async def test_Н8_4_цепочка_откатов_в_журнале_и_подсказка_последнего_звена(среда, одинс):
    """C1 → откат U1 → откат отката U2: изменение C1 снова в базе, C1 и U1 «откачены».
    Журнал показывает цепочку в обе стороны, `undo(C1)` называет последнее звено — U2, и
    откатывается именно оно."""
    одинс.положить(ПУТЬ_КОНТРАГЕНТА, к.контрагент())
    c1 = await коммит_update(среда, {"ИНН": к.токен(среда.tools, НОВЫЙ_ИНН)})
    u1 = await выполнено(среда, (await подготовить_откат(среда, c1["commit_id"]))["pending_id"])
    u2 = await выполнено(среда, (await подготовить_откат(среда, u1["commit_id"]))["pending_id"])
    assert одинс.объекты[ПУТЬ_КОНТРАГЕНТА]["ИНН"] == НОВЫЙ_ИНН

    строки = {з["commit_id"]: з for з in json.loads(await журнал(среда))["entries"]}
    отказ = к.ошибка(await откатить(среда, c1["commit_id"]))

    assert (строки[c1["commit_id"]]["undo_of"], строки[c1["commit_id"]]["undone_by"]) == (
        None,
        u1["commit_id"],
    )
    assert (строки[u1["commit_id"]]["undo_of"], строки[u1["commit_id"]]["undone_by"]) == (
        c1["commit_id"],
        u2["commit_id"],
    )
    assert (строки[u2["commit_id"]]["undo_of"], строки[u2["commit_id"]]["undone_by"]) == (
        u1["commit_id"],
        None,
    )
    assert отказ["code"] == "undo_unsupported"
    assert u2["commit_id"] in отказ["hint"] and c1["commit_id"] not in json.dumps(отказ)
    последнее = await подготовить_откат(среда, u2["commit_id"])
    assert последнее["undo_of"] == u2["commit_id"]
