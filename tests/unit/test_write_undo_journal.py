async def test_откат_update_PATCH_прежними_значениями_только_полей_коммита(среда, одинс):
    одинс.положить(ПУТЬ_КОНТРАГЕНТА, к.контрагент())
    новый = к.токен(среда.tools, НОВЫЙ_ИНН)
    старый = к.токен(среда.tools, ИНН)
    коммит = await коммит_update(среда, {"ИНН": новый, "ДополнительнаяИнформация": "разовый"})

    текст = await откатить(среда, коммит["commit_id"])

    # Превью от класса данных: «станет» — маска прежних значений, а не они сами.
    к.нет_реальных_значений(текст)
    ответ = json.loads(текст)
    assert (ответ["op"], ответ["undo_of"], ответ["undo_op"]) == (
        "undo",
        коммит["commit_id"],
        "update",
    )
    assert (ответ["base"], ответ["role"], ответ["entity"]) == ("ut", "prod", КОНТРАГЕНТЫ)
    assert ответ["key"] == {"Ref_Key": ССЫЛКА}
    assert ответ["object"]["Description"].startswith("[[org:")
    строки = {строка["field"]: строка for строка in ответ["preview"]}
    assert set(строки) == {"ИНН", "ДополнительнаяИнформация"}
    assert (строки["ИНН"]["before"], строки["ИНН"]["after"]) == (новый, старый)
    assert строки["ДополнительнаяИнформация"]["after"] == "постоянный клиент"
    assert "warning" not in ответ
    assert одинс.patch.call_count == 1

    откат = await выполнено(среда, ответ["pending_id"])

    # В 1С — ровно поля исходного коммита их прежними реальными значениями, не весь `before`.
    assert одинс.patch.call_count == 2
    assert json.loads(одинс.тела_записи[1]) == {
        "ИНН": ИНН,
        "ДополнительнаяИнформация": "постоянный клиент",
    }
    assert одинс.объекты[ПУТЬ_КОНТРАГЕНТА]["ИНН"] == ИНН
    к.нет_реальных_значений(json.dumps(откат, ensure_ascii=False))
    assert откат["op"] == "update" and откат["key"] == {"Ref_Key": ССЫЛКА}
    исходная = среда.журнал(коммит["commit_id"])
    assert исходная.undone_by == откат["commit_id"] and исходная.status == "committed"
    assert среда.журнал(откат["commit_id"]).op == "update"


async def test_откат_табличной_части_update_возвращает_старый_массив(среда, одинс):
    """Проект M3b §5.2: `commit` записи табличной части заменяет её ПОЛНЫМ новым списком (P9-6);
    откат восстанавливает СТАРЫЙ список целиком — тем же путём PATCH, что и прямая запись
    (`_форма_отката` берёт «до» из журнала, куда его кладёт перечитывание `_выбор_коммита`,
    задача 6). Проверка на живом состоянии поддельной 1С, а не только на теле запроса: после
    отката объект должен реально содержать прежние строки."""
    одинс.положить(ПУТЬ_КОНТРАГЕНТА, к.контрагент())
    старый_массив = к.контрагент()["КонтактнаяИнформация"]
    новый_телефон = "+7 916 555-55-55"
    # C-1 ревью хвостов M3b: поле строки класса `contact` открытым литералом `update` отклоняет —
    # значения строки идут токенами.
    ток_телефон = к.токен(среда.tools, новый_телефон, entity=к.КИ, поле="Представление")
    ток_почта = к.токен(среда.tools, к.ПОЧТА, entity=к.КИ, поле="Представление")

    коммит = await коммит_update(
        среда,
        {
            "КонтактнаяИнформация": [
                {"LineNumber": 1, "Тип": "Телефон", "Представление": ток_телефон},
                {"LineNumber": 2, "Тип": "АдресЭлектроннойПочты", "Представление": ток_почта},
            ]
        },
    )

    # После commit — в 1С полный новый список, ровно тот, что отправила подготовка.
    assert одинс.объекты[ПУТЬ_КОНТРАГЕНТА]["КонтактнаяИнформация"] == [
        {"LineNumber": 1, "Тип": "Телефон", "Представление": новый_телефон},
        {"LineNumber": 2, "Тип": "АдресЭлектроннойПочты", "Представление": к.ПОЧТА},
    ]

    подготовка_отката = await подготовить_откат(среда, коммит["commit_id"])
    к.нет_реальных_значений(json.dumps(подготовка_отката, ensure_ascii=False))
    откат = await выполнено(среда, подготовка_отката["pending_id"])

    # Откат вернул табличную часть старым списком целиком — то, что реально лежит в 1С, а не
    # только тело последнего PATCH.
    assert одинс.объекты[ПУТЬ_КОНТРАГЕНТА]["КонтактнаяИнформация"] == старый_массив
    assert одинс.patch.call_count == 2
    assert json.loads(одинс.тела_записи[1])["КонтактнаяИнформация"] == старый_массив
    к.нет_реальных_значений(json.dumps(откат, ensure_ascii=False))


