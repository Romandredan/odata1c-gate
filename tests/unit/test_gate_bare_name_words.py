# кавычек — см. `name_variants_of`) один и тот же у ЛЮБОГО написания одного ядра под той же
# формой, с кавычками или без. `ООО Мост` и `ООО «Мост»` — разные токены (кавычки участвуют в
# `tokens.normalized`, SPEC §6.3), но оба синтезируют ключ `ооо мост`, и без поправки он уходил
# бы в неоднозначные целиком — открывая ОБА написания, включая узнаваемое по своей форме
# собственности (обязано закрываться по Ruling 115, минимальный контрпример — property-тест
# `tests/property/test_gate_differential.py::test_отбор_по_токену_не_меняет_токены_ответа`).
# Поправка в `Dictionary._ключи_названий`: ключ, совпадающий с ПОЛНЫМ нормализованным написанием
# ровно одного из токенов-претендентов (`tokens.normalized == variant_norm`), закрепляется за
# этим токеном однозначно; ключи без такого единственного полного совпадения остаются
# неоднозначными, как и раньше.
# ---------------------------------------------------------------------------------------------


def test_коллизия_форменного_ключа_решается_полным_написанием(среда):
    """Минимальный контрпример находки: `ооо аааа` — полное написание `ООО Аааа`, закрепляется
    за его токеном; `ооо "аааа"` — полное написание `ООО «Аааа»`, закрепляется за его токеном;
    ключи без единственного полного совпадения (`"аааа"`, `"аааа`, `ооо"аааа"`) остаются
    неоднозначными за обоими сразу — как и голое `аааа` до Ruling 115."""
    словарь, _, назвать = среда
    т1 = назвать("ООО Аааа")
    т2 = назвать("ООО «Аааа»")

    однозначные = словарь.name_variants()
    assert однозначные["ооо аааа"] == т1
    assert однозначные['ооо "аааа"'] == т2

    неоднозначные = словарь.ambiguous_name_variants()
    # Все прочие ключи пары общие: `"аааа"`, `"аааа`, `ооо"аааа"` и написания итогового ревью (C-1).
    assert {'"аааа"', '"аааа', 'ооо"аааа"'} <= set(неоднозначные)
    assert set(неоднозначные) == set(name_variants_of("ООО Аааа")) - {"ооо аааа", 'ооо "аааа"'}
    assert all(set(токены) == {т1, т2} for токены in неоднозначные.values())


