"""Ruling 115 (2026-09-28, решение владельца): одиночное слово без формы собственности и без
кавычек названием в свободном тексте не считается.

Название из одного слова («Мост», «Вектор», имя «Мария») почти всегда совпадает с обычным словом,
и после Ruling 106 оно закрывалось токеном в любом комментарии. Для такого ключа голое написание в
поиск не идёт; вместо него — узнаваемые написания: в кавычках (и с одной открывающей — 1С обрезает
строку без закрывающей «ёлочки») и со своей формой собственности. Название из нескольких слов, с
цифрой или дефисом, полное ФИО и значения в полях с классом закрываются как прежде.
"""

import pytest

from odata1c.gate.dictionary import name_variants_of


@pytest.mark.parametrize(
    ("название", "ожидаемые"),
    [
        ('ООО "Мост"', ['ооо "мост"', '"мост"', '"мост', "ооо мост", 'ооо"мост"']),
        ("ООО «Мост»", ['ооо "мост"', '"мост"', '"мост', "ооо мост", 'ооо"мост"']),
        ("ИП Петров", ["ип петров", '"петров"', '"петров', 'ип "петров"', 'ип"петров"']),
        ("Мост", ['"мост"', '"мост']),
        ("«Мост»", ['"мост"', '"мост']),
        ("Мария", ['"мария"', '"мария']),
        ("Alpha", ['"alpha"', '"alpha']),
        # Ядро короче минимума: в кавычках не ищется (как у безбуквенного ядра, Ruling 50),
        # с формой — да.
        ("Юла", []),
        ("ООО Юла", ["ооо юла", 'ооо "юла"', 'ооо"юла"']),
        # Не одиночное слово — ключи прежние.
        ('ООО "Торговый дом Вектор"', ['ооо "торговый дом вектор"', "торговый дом вектор"]),
        ("Альфа-Банк", ["альфа-банк"]),
        ('ООО "Альфа 2"', ['ооо "альфа 2"', "альфа 2"]),
        ("1С-Рарус", ["1с-рарус"]),
        ("Иванов Иван Иванович", ["иванов иван иванович"]),
        ("Иванов И.И.", ["иванов и.и."]),
    ],
)
def test_ключи_одиночного_слова(название, ожидаемые):
    assert name_variants_of(название) == ожидаемые
