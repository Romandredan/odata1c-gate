def test_ядро_в_ключе_на_границе_слова(название):
    """Инвариант 6, проверка по построению: в каждом ключе одиночного слова ядро стоит целым
    словом — рядом с ним в ключе не буква и не цифра. Значит, ни один ключ не заменит текст, где
    ядра целым словом нет, и новые ключи не шире голого ключа до ветки."""
    ядро = название.split()[-1].strip('"«»').lower()
    for ключ in name_variants_of(название):
        начало = ключ.rfind(ядро)
        assert начало != -1, ключ
        конец = начало + len(ядро)
        assert начало == 0 or not ключ[начало - 1].isalnum(), ключ
        assert конец == len(ключ) or not ключ[конец].isalnum(), ключ


