@pytest.fixture
def среда(tmp_path):
    (tmp_path / "policy.yaml").write_text(ПОЛИТИКА, encoding="utf-8")
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    маскировщик = Masker(
        словарь, load_policy(tmp_path / "policy.yaml"), mode="identifiers+names", base="ut"
    )

    def назвать(название: str, поле: str = "Description") -> str:
        return маскировщик.mask({поле: название}, entity=К).data[поле]

    yield словарь, маскировщик, назвать
    словарь.close()


def _пройти(слой: str, словарь: Dictionary, маскировщик: Masker, текст: str) -> str:
    if слой == "маскировщик":
        return маскировщик.mask({"Комментарий": текст}, entity=К).data["Комментарий"]
    проверено = Guard(словарь).check(
        json.dumps({"Комментарий": текст}, ensure_ascii=False), mode="identifiers+names"
    )
    return json.loads(проверено.text)["Комментарий"]


СЛОИ = pytest.mark.parametrize("слой", ["маскировщик", "страж"])


