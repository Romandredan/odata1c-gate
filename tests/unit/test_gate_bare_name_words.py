from odata1c.gate.pipeline import BaseGate
from odata1c.gate.policy import load_policy
from odata1c.gate.revealed import RevealedValues
from odata1c.gate.unmasking import Unmasker

СЕКРЕТ = "секрет ровно для тестов подмены!!".encode()
К = "Catalog_Контрагенты"
ПОЛИТИКА = f"version: 2\nauto:\n  {К}.Description: org\n  {К}.Имя: person\n"


def _кавычки(ядро: str) -> list[str]:
    """Ключи одиночного слова в кавычках других видов (итоговое ревью, C-1): апостроф, типографский
    апостроф, только закрывающая кавычка, пробел после открывающей."""
    return [f"'{ядро}'", f"'{ядро}", f"‘{ядро}’", f"‘{ядро}", f'{ядро}"', f'" {ядро}']


def _форма_знаками(форма: str, ядро: str) -> list[str]:
    """Своя форма собственности через точку и дефис (итоговое ревью, C-1)."""
    return [f"{форма}. {ядро}", f"{форма}.{ядро}", f"{форма}-{ядро}"]


def _с_формой(форма: str, ядро: str) -> list[str]:
    """Три прежних вида своей формы: через пробел, с кавычками и кавычками вплотную."""
    return [f"{форма} {ядро}", f'{форма} "{ядро}"', f'{форма}"{ядро}"']


