"""Ruling 115 (2026-09-28, решение владельца): одиночное слово без формы собственности и без
кавычек названием в свободном тексте не считается.

Название из одного слова («Мост», «Вектор», имя «Мария») почти всегда совпадает с обычным словом,
и после Ruling 106 оно закрывалось токеном в любом комментарии. Для такого ключа голое написание в
поиск не идёт; вместо него — узнаваемые написания: в кавычках (и с одной открывающей — 1С обрезает
строку без закрывающей «ёлочки») и со своей формой собственности. Название из нескольких слов, с
цифрой или дефисом, полное ФИО и значения в полях с классом закрываются как прежде.
"""

import json
import sqlite3

import pytest
from conftest import без_класса_пути

