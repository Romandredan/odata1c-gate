@pytest.fixture
def среда(tmp_path):
    (tmp_path / "policy.yaml").write_text(ПОЛИТИКА, encoding="utf-8")
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    маскировщик = Masker(
        словарь, load_policy(tmp_path / "policy.yaml"), mode="identifiers+names", base="ut"
    )

    def назвать(название: str, поле: str = "Description") -> str:
        return маскировщик.mask({поле: название}, entity=К).data[поле]

    yield словарь, маскировщик, назвать
    словарь.close()


def _пройти(слой: str, словарь: Dictionary, маскировщик: Masker, текст: str) -> str:
    if слой == "маскировщик":
        return маскировщик.mask({"Комментарий": текст}, entity=К).data["Комментарий"]
    проверено = Guard(словарь).check(
        json.dumps({"Комментарий": текст}, ensure_ascii=False), mode="identifiers+names"
    )
    return json.loads(проверено.text)["Комментарий"]


СЛОИ = pytest.mark.parametrize("слой", ["маскировщик", "страж"])


@СЛОИ
@pytest.mark.parametrize(
    ("название", "текст"),
    [
        ('ООО "Мост"', "ремонт: мост через реку, Мост просит сверку"),
        ("Вектор", "вектор скорости"),
        ("ИП Петров", "передал Петрову, звонил Петров"),
    ],
)
def test_голое_одиночное_слово_открыто(среда, слой, название, текст):
    """Ruling 115: одиночное слово без формы собственности и без кавычек названием в свободном
    тексте не считается — ни на уровне маскировщика, ни на уровне стража."""
    словарь, маскировщик, назвать = среда
    назвать(название)

    assert _пройти(слой, словарь, маскировщик, текст) == текст


def test_голое_имя_открыто(среда):
    """Ruling 115 касается и класса `person`: голое имя из поля `Имя` в свободном тексте не
    закрывается."""
    словарь, маскировщик, назвать = среда
    назвать("Мария", поле="Имя")

    assert _пройти("маскировщик", словарь, маскировщик, "звонила Мария") == "звонила Мария"


