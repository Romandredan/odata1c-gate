def test_отбор_по_текстовой_колонке_без_своих_написаний(связка):
    """Ruling 38, пункт 5: у колонки поиска своих написаний нет — в группу идут написания своего
    формата (представление, в том числе из JSON) и нормализованная форма; JSON — нет."""
    с, u = связка
    т = _телефон_из_json(с)
    набор = RevealedValues()

    ушло = u.filter(f"НомерТелефона eq '{т}'", entity=КИ, revealed=набор)

    assert ушло == f"(НомерТелефона eq '{ТЕЛ}' or НомерТелефона eq '{ТЕЛ_ЦИФРЫ}')"
    assert "{" not in "".join(набор.tokens())


def test_отбор_по_колонке_со_своими_написаниями_не_добавляет_догадок(связка):
    """Первая ступень лестницы не меняется: свои написания поля — и только они."""
