@pytest.fixture
def связка(tmp_path):
    с = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    yield (
        с,
        Unmasker(
            с,
            base="ut",
            field_class=lambda e, f, *, strict=False: КЛАССЫ.get((e, f)),
            path_class=без_класса_пути,
        ),
    )
    с.close()


def _не_молча(u, поле, токен, *, недопустимо):
    try:
        тело = u.write({поле: токен}, entity=ЗАКАЗ, current=None, revealed=RevealedValues())
    except GateError as ошибка:
        assert ошибка.code == "token_ambiguous"
        return
    assert not недопустимо(тело[поле]), f"в {поле} молча ушло значение другого формата"


def _адрес_из_json(с: Dictionary) -> str:
    return с.token_for(
        "addr", АДРЕС_JSON, base="ut", entity=ЗАКАЗ, field="АдресДоставкиЗначение", source=АДРЕС
    )


def _телефон_из_json(с: Dictionary) -> str:
    return с.token_for("phone", ТЕЛ_JSON, base="ut", entity=КИ, field="Значение", source=ТЕЛ)


def _отказ(вызов) -> GateError:
    with pytest.raises(GateError) as пойманное:
        вызов()
    assert пойманное.value.code == "token_ambiguous"
    return пойманное.value


