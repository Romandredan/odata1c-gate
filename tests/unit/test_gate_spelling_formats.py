    т = _телефон_из_json(с)
    assert с.token_for("phone", ТЕЛ_ЦИФРЫ, base="ut", entity=КИ, field="НомерТелефона") == т

    ушло = u.filter(f"НомерТелефона eq '{т}'", entity=КИ, revealed=RevealedValues())

    assert ушло == f"НомерТелефона eq '{ТЕЛ_ЦИФРЫ}'"


