"""Детекторы значений: контрольные суммы, порядок сканирования, ложные срабатывания (SPEC §6.4)."""

import pytest

from odata1c.gate.detectors import (
    inn_valid,
    luhn_valid,
    ogrn_valid,
    scan_value,
    snils_valid,
)


@pytest.mark.parametrize("инн", ["7707083893", "7736050003", "500100732259"])
def test_верный_инн(инн):
    assert inn_valid(инн) is True


@pytest.mark.parametrize("инн", ["7707083894", "1234567890", "500100732258", "770708389"])
def test_неверный_инн(инн):
    assert inn_valid(инн) is False


def test_огрн():
    assert ogrn_valid("1027700132195") is True
    assert ogrn_valid("1027700132196") is False


def test_снилс():
    assert snils_valid("11223344595") is True
    assert snils_valid("11223344596") is False


def test_luhn():
    assert luhn_valid("4111111111111111") is True
    assert luhn_valid("4111111111111112") is False


def test_поиск_инн_в_свободном_тексте_с_контекстом():
    найдено = scan_value("Оплата по договору, ИНН 7707083893, сумма 145 200,00")
    assert [(совпадение.type, совпадение.value) for совпадение in найдено] == [
        ("inn", "7707083893")
    ]


def test_десятизначный_без_контекста_не_трогаем():
    """SPEC §6.4: 10-значный ИНН требует слова «ИНН» в 20 символах — иначе это номер документа."""
    найдено = scan_value("Заказ покупателя 7707083893 от 07.09.2026")
    assert найдено == []


def test_двенадцатизначный_инн_без_контекста_находится():
    найдено = scan_value("плательщик 500100732259 оплатил")
    assert [совпадение.type for совпадение in найдено] == ["inn"]


def test_телефон():
    найдено = scan_value("звоните +7 (495) 123-45-67 в будни")
    assert [(совпадение.type, совпадение.value) for совпадение in найдено] == [
        ("phone", "+7 (495) 123-45-67")
    ]


def test_почта():
    найдено = scan_value("написать на ivan.petrov@example.com сегодня")
    assert [совпадение.type for совпадение in найдено] == ["email"]


def test_карта_по_luhn():
    найдено = scan_value("карта 4111 1111 1111 1111 списание")
    assert [совпадение.type for совпадение in найдено] == ["card"]


def test_счёт_по_префиксу():
    найдено = scan_value("р/с 40702810900000000001 в банке")
    assert [совпадение.type for совпадение in найдено] == ["acc"]


def test_паспорт_с_контекстом():
    найдено = scan_value("паспорт 45 08 123456 выдан ОВД")
    assert [совпадение.type for совпадение in найдено] == ["doc"]


def test_паспорт_без_контекста_не_трогаем():
    assert scan_value("накладная 45 08 123456 от вчера") == []


def test_суммы_и_даты_не_трогаем():
    """Инвариант 6: суммы, даты, номера документов не защищаются никогда."""
    текст = "документ №ТД-004512 от 07.09.2026 на сумму 1 450 200,00 руб, курс 92,5417"
    assert scan_value(текст) == []


def test_guid_не_трогаем():
    текст = "Ref_Key 8f1a2b3c-4d5e-6f70-8192-a3b4c5d6e7f8"
    assert scan_value(текст) == []


def test_окпо_и_оквэд_не_трогаем():
    assert scan_value("ОКПО 00242766, ОКВЭД 62.01, ОКТМО 45379000") == []


def test_несколько_совпадений_подряд():
    текст = "ИНН 7707083893, р/с 40702810900000000001, тел +7 495 123-45-67"
    классы = [совпадение.type for совпадение in scan_value(текст)]
    assert set(классы) == {"inn", "acc", "phone"}


def test_совпадения_не_перекрываются():
    """Порядок SPEC §6.4 п. 3: длинные и надёжные классы разбираются раньше коротких."""
    найдено = scan_value("счёт 40702810900000000001 ИНН 7707083893")
    отрезки = [(совпадение.start, совпадение.end) for совпадение in найдено]
    for первый, второй in zip(отрезки, отрезки[1:], strict=False):
        assert первый[1] <= второй[0]
