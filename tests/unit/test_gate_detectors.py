# --- раунд 3, I-2: 11 цифр подряд с ведущей 7/8 — телефон только при признаке номера -----------
#
# Ревью 8 (I-2): «EAN 76123456789», «Заказ №81234567890», «код 73701000001» становились
# `[[phone:…]]` — штрихкод, номер заказа и код классификатора (инвариант 6). Слитные 11 цифр
# — это ещё и форма кодов и номеров документов, поэтому признак номера нужен явный: мобильный
# код (вторая цифра 9), слово-подсказка рядом («тел», «моб», «факс», «звон…», «phone», …) или
# соседство в перечне с уже подтверждённым номером. Номер с «+», скобками или разделителями —
# как прежде: там признак номера — сама запись.


