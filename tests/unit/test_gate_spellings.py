def test_текущее_после_раннего_прохода_разворачивается_через_набор(связка):
    """`current` приходит так, как его отдал `client.get(scrub=…)`: раскрытое в этом же вызове
    значение (ключ объекта, отбор поиска) ранний проход уже заменил токеном. Исходное значение
    места лежит в наборе вызова (Б-3) — по нему и сравнивается."""
    словарь, обратно = связка
    токен = _два_написания_инн(словарь)
    набор = RevealedValues()
    текущее = {"ИНН": набор.scrubbed(токен, original=ИНН_С_ПРОБЕЛОМ, hits=1)}

    тело = обратно.write({"ИНН": токен}, entity=КОНТРАГЕНТЫ, current=текущее, revealed=набор)

    assert тело == {"ИНН": ИНН_С_ПРОБЕЛОМ}
    assert type(тело["ИНН"]) is str


