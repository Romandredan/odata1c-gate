def test_слишком_много_написаний_отказ_а_не_неполный_поиск(связка):
    """Предел числа написаний: искать часть из них — молча вернуть неполный ответ, то есть та же
    дыра, что закрывается. Отказ `token_ambiguous` с подсказкой сузить отбор другим полем."""
    словарь, обратно = связка
    токен = _токен(словарь, "inn", ИНН, поле="ИНН")
    for номер in range(1, 9):
        _токен(словарь, "inn", " " * номер + ИНН, поле="ИНН")

    with pytest.raises(GateError) as ошибка:
        обратно.filter(f"ИНН eq '{токен}'", entity=КОНТРАГЕНТЫ, revealed=RevealedValues())

    assert ошибка.value.code == "token_ambiguous"
    assert ИНН not in str(ошибка.value) + ошибка.value.hint


def test_слишком_длинная_группа_отказ(связка):
    """Предел длины: группа `or` в процентной записи (так она уйдёт в адрес запроса) не должна
    вытеснить остальной запрос за предел строки запроса веб-сервера перед 1С."""
    словарь, обратно = связка
    длинное = "ООО «" + "Ромашка и партнёры " * 12 + "»"
    токен = _токен(словарь, "org", длинное, поле="Description")
    _токен(словарь, "org", длинное.upper(), поле="Description")
    _токен(словарь, "org", длинное.replace("«", '"').replace("»", '"'), поле="Description")
    группа = " or ".join(f"Description eq '{длинное}'" for _ in range(3))
    assert len(urllib.parse.quote(группа, safe="")) > 1500, "проверка без предмета"

    with pytest.raises(GateError) as ошибка:
        обратно.filter(f"Description eq '{токен}'", entity=КОНТРАГЕНТЫ, revealed=RevealedValues())

    assert ошибка.value.code == "token_ambiguous"


