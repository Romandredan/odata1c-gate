def test_ошибка_неоднозначности_без_значений_в_ответе_тула(tmp_path, связка):
    """Текст отказа уходит модели тем же путём, что данные: в нём число написаний и токен, а не
    сами написания."""
    словарь, _ = связка
    гейт = _гейт(tmp_path, словарь, "identifiers+names")
    токен = _два_написания_инн(словарь)
    try:
        гейт.inbound_write(
            {"ИНН": токен},
            entity=КОНТРАГЕНТЫ,
            shape=lambda _: None,
            current=None,
            revealed=RevealedValues(),
        )
    except GateError as ошибка:
        текст = гейт.error(ошибка.code, str(ошибка), ошибка.hint)
    else:
        pytest.fail("ожидался отказ token_ambiguous")

    данные = json.loads(текст)
    assert данные["error"]["code"] == "token_ambiguous"
    assert "2" in данные["error"]["message"]
    assert ИНН not in текст and ИНН_С_ПРОБЕЛОМ not in текст


def test_пересекающиеся_замены_в_отборе_отказ():
    """Группа написаний заменяет тройку вместе с полем; вторая замена, задевшая то же место,
    склеилась бы в бессмыслицу — сборка отказывает, а не склеивает."""
    from odata1c.gate.unmasking import _собрать

    with pytest.raises(GateError) as ошибка:
        _собрать("'a' eq ИНН eq 'b'", [(0, 10, "(ИНН eq 1 or ИНН eq 2)"), (4, 17, "(…)")])

    assert ошибка.value.code == "filter_syntax"
    assert _собрать("ИНН eq 'a'", [(7, 10, "'b'")]) == "ИНН eq 'b'"
