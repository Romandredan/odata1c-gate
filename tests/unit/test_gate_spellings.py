def _гейт(tmp_path, словарь: Dictionary, mode: str) -> BaseGate:
    политика = tmp_path / f"policy-{mode}.yaml"
    политика.write_text(
        f"version: 2\nauto:\n  {КОНТРАГЕНТЫ}.ИНН: inn\n  {КОНТРАГЕНТЫ}.Description: org\n",
        encoding="utf-8",
    )
    return BaseGate(
        base=BaseConfig(
            name="ut",
            label="ut",
            url="http://host/base/odata/standard.odata/",
            user="agent",
            gate=GateSettings(mode=mode),
        ),
        dictionary=словарь,
        guard=Guard(словарь),
        policy_path=политика,
    )


def test_inbound_write_разрешает_токен_по_правилу_записи(tmp_path, связка):
    словарь, _ = связка
    гейт = _гейт(tmp_path, словарь, "identifiers+names")
    токен = _два_написания_инн(словарь)

    тело = гейт.inbound_write(
        {"ИНН": токен},
        entity=КОНТРАГЕНТЫ,
        shape=lambda _: None,
        current={"ИНН": ИНН_С_ПРОБЕЛОМ},
        revealed=RevealedValues(),
    )
    assert тело == {"ИНН": ИНН_С_ПРОБЕЛОМ}

    with pytest.raises(GateError) as ошибка:
        гейт.inbound_write(
            {"ИНН": токен},
            entity=КОНТРАГЕНТЫ,
            shape=lambda _: None,
            current=None,
            revealed=RevealedValues(),
        )
    assert ошибка.value.code == "token_ambiguous"


