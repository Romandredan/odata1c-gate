def test_отбор_ищет_написания_своего_поля_а_не_догадки_из_чужих(связка):
    """Лестница и в отборе: написания этого поля — всё, что ищется, пока они есть. Написание из
    другого поля — догадка (у JSON поля `Значение` контактной информации тот же токен вовсе не
    написание значения), и в группу `or` она не попадает. Написаний в этом поле нет — ищутся
    написания словаря формата поля (у текстового — текст, структура БСП — своим представлением) и
    нормализованная форма (Ruling 38, `test_gate_spelling_formats.py`)."""
    словарь, обратно = связка
    токен = _токен(словарь, "org", "ООО Ромашка", поле="Description")
    _токен(словарь, "org", "ООО  Ромашка", поле="НаименованиеПолное")
    словарь.token_for(
        "org",
        '{"value": "ООО Ромашка", "type": "Другое"}',
        base="ut",
        entity=КОНТРАГЕНТЫ,
        field="Значение",
        source="ООО Ромашка",
    )

    своё = обратно.filter(f"Description eq '{токен}'", entity=КОНТРАГЕНТЫ)
    чужое = обратно.filter(f"НаименованиеРабочее eq '{токен}'", entity=КОНТРАГЕНТЫ)

    assert своё == "Description eq 'ООО Ромашка'"
    assert чужое == (
        "(НаименованиеРабочее eq 'ООО  Ромашка' or НаименованиеРабочее eq 'ООО Ромашка'"
        " or НаименованиеРабочее eq 'ооо ромашка')"
    )


