"""Б-1 (ревью 7, блокер M2): несколько написаний одного токена.

Один токен получают разные написания одного значения — ИНН с пробелом и без, название в
«ёлочках» и в прямых кавычках, значение с краевым пробелом. 1С сравнивает строки точно, поэтому:

- отбор по токену обязан искать ВСЕ написания (`eq` раскрывается в `or`), иначе вторая запись не
  находится;
- запись по токену не имеет права выбрать одно из написаний молча: на превью пользователь видит
  токен, а не значение, и подмену написания не отличит. Правило записи — `Unmasker.write` /
  `BaseGate.inbound_write` (раздел «Интерфейс для M2» отчёта).
"""

import json
import urllib.parse

import pytest
from conftest import без_класса_пути

from odata1c.config.models import BaseConfig, GateSettings
from odata1c.gate.dictionary import Dictionary
from odata1c.gate.guard import Guard
from odata1c.gate.pipeline import BaseGate
from odata1c.gate.revealed import RevealedValues
from odata1c.gate.unmasking import GateError, Unmasker

СЕКРЕТ = "секрет ровно для обратной подмены".encode()
КОНТРАГЕНТЫ = "Catalog_Контрагенты"
ЛИЦА = "Catalog_ФизическиеЛица"
ИНН = "7707083893"
ИНН_С_ПРОБЕЛОМ = "7707 083893"
КЛАССЫ = {
    (КОНТРАГЕНТЫ, "ИНН"): "inn",
    (КОНТРАГЕНТЫ, "Description"): "org",
    (КОНТРАГЕНТЫ, "НаименованиеПолное"): "org",
    (КОНТРАГЕНТЫ, "НаименованиеРабочее"): "org",
    (КОНТРАГЕНТЫ, "Комментарий"): None,
    (ЛИЦА, "ДатаРождения"): "dob",
}


def _класс_поля(сущность, поле, *, strict=False):
    return КЛАССЫ.get((сущность, поле))


@pytest.fixture
def связка(tmp_path):
    словарь = Dictionary(tmp_path / "gate.sqlite", СЕКРЕТ)
    yield (
        словарь,
        Unmasker(словарь, base="ut", field_class=_класс_поля, path_class=без_класса_пути),
    )
    словарь.close()


def _токен(словарь: Dictionary, класс: str, значение: str, *, поле: str, base="ut", entity=None):
    return словарь.token_for(класс, значение, base=base, entity=entity or КОНТРАГЕНТЫ, field=поле)


def _два_написания_инн(словарь: Dictionary) -> str:
    токен = _токен(словарь, "inn", ИНН, поле="ИНН")
    assert _токен(словарь, "inn", ИНН_С_ПРОБЕЛОМ, поле="ИНН") == токен
    return токен


