# Ревью dc8ac38, находки 1–3: сосед-«буква», которого в словах текста нет. Экранирование JSON
# (`\n`, `\t`, `«` двумя и шестью символами — 1С хранит JSON в строках, ошибка 1С приходит
# сырым телом), невидимый разделитель, вырезанный нормализацией (ZWSP между словами), буква-
# модификатор в роли кавычки. Название там стоит отдельным словом и обязано закрываться.
ГРАНИЦЫ_НЕ_ИЗ_СЛОВА = [
    pytest.param("Звонок\\nМост просит сверку", "Звонок\\n{0} просит сверку", id="экран-n"),
    pytest.param("строка\\r\\nМост", "строка\\r\\n{0}", id="экран-rn"),
    pytest.param("a\\tМост", "a\\t{0}", id="экран-t"),
    pytest.param("\\u00abМост\\u00bb", "\\u00ab{0}\\u00bb", id="экран-u-на-букву"),
    pytest.param("\\u201cМост\\u201d", "\\u201c{0}\\u201d", id="экран-u-на-букву-c"),
    pytest.param("\\u00abAlpha Trade\\u00bb", "\\u00ab{1}\\u00bb", id="экран-u-латинское-название"),
    pytest.param("оплата​Мост", "оплата​{0}", id="zwsp"),
    pytest.param("ООО‎Мост", "ООО‎{0}", id="метка-направления"),
    pytest.param("ʼМостʼ", "ʼ{0}ʼ", id="модификатор-апостроф"),
]


@pytest.mark.parametrize("слой", ["маскировщик", "страж"])
@pytest.mark.parametrize(("текст", "ожидание"), ГРАНИЦЫ_НЕ_ИЗ_СЛОВА)
def test_сосед_не_из_слова_граница(среда, слой, текст, ожидание):
    словарь, маскировщик, назвать = среда
    мост, альфа = назвать("ООО Мост", "Alpha Trade")

    итог = _маскировщиком(маскировщик, текст) if слой == "маскировщик" else _стражем(словарь, текст)

    assert итог == ожидание.format(мост, альфа)


# Решение владельца после повторного ревью: склейки — внутри слова, путь Windows не портится.
ВНУТРИ_СЛОВА_НЕ_ТРОГАЕТСЯ = [
    pytest.param(("ООО Мост",), "Мост\u00adовой кран", id="мягкий-перенос"),
    pytest.param(("ООО Мост",), "Мост\u2060овой кран", id="word-joiner"),
    pytest.param(("ООО Мост",), "Мост\u200dовой кран", id="zwj"),
    pytest.param(("ООО Мост",), "Мост\ufeffовой кран", id="zwnbsp"),
    pytest.param(("Eport",), "C:\\report\\x", id="путь-windows-r"),
    pytest.param(("Rade",), "C:\\trade\\x", id="путь-windows-t"),
]


@pytest.mark.parametrize("слой", ["маскировщик", "страж"])
@pytest.mark.parametrize(("названия", "текст"), ВНУТРИ_СЛОВА_НЕ_ТРОГАЕТСЯ)
def test_склейки_и_пути_внутри_слова(среда, слой, названия, текст):
    """Склейки (мягкий перенос, WORD JOINER, ZWJ, ZWNBSP) по определению стоят внутри слова, а
    `\\r` и `\\t` в пути Windows — начало имени каталога: название там не заменяется."""
    словарь, маскировщик, назвать = среда
    назвать(*названия)

    итог = _маскировщиком(маскировщик, текст) if слой == "маскировщик" else _стражем(словарь, текст)

