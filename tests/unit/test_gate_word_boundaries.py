@pytest.mark.parametrize("слой", ["маскировщик", "страж"])
def test_смена_письменности_граница(среда, слой):
    """Буква латиницы рядом с буквой кириллицы — граница: так закрывается кириллическое название
    после буквенного экранирования (`\\nМост`) и в слитном «Мостbank»."""
    словарь, маскировщик, назвать = среда
    (мост,) = назвать("ООО Мост")
    текст = "Мостbank и Звонок\\nМост"

    итог = _маскировщиком(маскировщик, текст) if слой == "маскировщик" else _стражем(словарь, текст)

    assert итог == f"{мост}bank и Звонок\\n{мост}"


def test_страж_на_тексте_не_json_экранирование_граница(среда):
    """Обрезанный ответ и сырое тело ошибки 1С страж проверяет как текст целиком, без
    раскодирования: `\\n` там — два символа, и `n` не продолжение слова."""
    словарь, _, назвать = среда
    (мост,) = назвать("ООО Мост")

    итог = Guard(словарь).check('строка1\\nМост поставил "', mode="identifiers+names").text

    assert итог == f'строка1\\n{мост} поставил "'


def test_процентная_запись_рядом_граница(среда):
    """Оговорка Ruling 27 для эха адреса запроса действует и на названия: в `%2FAlpha` слева от
    названия стоит шестнадцатеричная «F» кодировки, а не буква слова."""
    словарь, _, назвать = среда
    (альфа,) = назвать("Alpha Trade")

    assert _стражем(словарь, "path%2FAlpha Trade%2F") == f"path%2F{альфа}%2F"


def test_ответ_метаданных_из_issue_без_токенов(среда):
    """Ответ `odata1c_recipe` и `odata1c_find_entity` из issue №2: имена метаданных и описание
    рецепта не содержат токенов, и `guard_replaced` не выставляется."""
    словарь, _, назвать = среда
    назвать("ООО Мост", "РУДН")
    ответ = json.dumps(
        {
            "entity": "AccumulationRegister_ВыручкаИСебестоимостьПродаж_Turnovers",
            "description": "Выручка и себестоимости продаж по периодам",
            "fields": ["ГрафикРаботыСотрудников", "Сотрудник"],
        },
        ensure_ascii=False,
    )

    проверено = Guard(словарь).check(ответ, mode="identifiers+names")

    assert проверено.text == ответ
    assert проверено.replacements == []
    assert проверено.warnings == []


def test_раскрытое_название_внутри_слова_не_заменяется(среда):
    """Отбор по токену «РУДН» раскрывает значение в набор вызова. Слой раскрытого не заменяет его
    внутри «сотрудников» — ни ранний проход, ни последний рубеж, — а отдельное слово заменяет;
    ответ совпадает с ответом без отбора (инвариант 5)."""
    словарь, маскировщик, назвать = среда
    (рудн,) = назвать("РУДН")
    набор = RevealedValues()
    набор.add("РУДН", token=рудн)
    текст = "график работы сотрудников; звонили из РУДН"
    тело = json.dumps({"Комментарий": текст}, ensure_ascii=False)
    страж = Guard(словарь)

    ранний = страж.scrub_revealed_json(тело, набор, mode="identifiers+names")["Комментарий"]
    последний = json.loads(страж.check(тело, mode="identifiers+names", revealed=набор).text)

    ожидание = f"график работы сотрудников; звонили из {рудн}"
    assert ранний == ожидание
    assert последний["Комментарий"] == ожидание
    assert ранний == _маскировщиком(маскировщик, текст)


def test_короткое_раскрытое_правило_ruling_27_не_ослаблено(среда):
    """Короткое раскрытое значение (КПП «1») по-прежнему требует неалфавитно-цифровой границы с
    обеих сторон: «УТ1» его не содержит, «код 1;» — содержит. Новое правило его не касается."""
    словарь, _, _ = среда
    набор = RevealedValues()
    набор.add("1", token="[[kpp:K1]]")
    тело = json.dumps({"Комментарий": "УТ1 и код 1; 1А"}, ensure_ascii=False)

    итог = Guard(словарь).scrub_revealed_json(тело, набор, mode="identifiers")["Комментарий"]

    assert итог == "УТ1 и код [[kpp:K1]]; 1А"
