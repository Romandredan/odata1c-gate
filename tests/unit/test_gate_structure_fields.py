# --- Правило 2: поле-брат `<Имя>Строкой` -----------------------------------------------------


def test_поле_с_братом_строкой_структурное(связка):
    """Словарь о поле ничего не знает, имя без суффикса — структурным поле делает брат
    `ПроизводственныйОбъектАдресСтрокой` в строении сущности. create с токеном, который словарь
    видел только текстом, — отказ, а не голый текст в структуре."""
    с, u = связка
    т2 = _текстом_а2(с)

    _отказ(lambda: _записать(u, ЭМИССИЯ, {АДРЕС_ОБЪЕКТА: т2}))


def test_поле_без_брата_и_без_сведений_пишется_текстом(связка):
    """Остаток, записанный в SPEC §6.8: поле, про которое ничего не известно (имя без суффикса,
    брата нет, словарь в нём структуры не видел, `current` нет), пишется текстом, как прежде."""
    с, u = связка
    т2 = _текстом_а2(с)

    assert _записать(u, ПЕРЕМЕЩЕНИЕ, {"ОтправительАдрес": т2}) == {"ОтправительАдрес": А2}


def test_брат_в_табличной_части(связка):
    """Брат ищется в строении той сущности, куда приходит путь: у строки табличной части — в
    строении табличной части."""
    с, u = связка
    т2 = _текстом_а2(с)

    _отказ(
        lambda: _записать(u, ПЕРЕМЕЩЕНИЕ, {"Товары": [{"LineNumber": "1", "АдресХранения": т2}]})
    )


def test_брат_и_в_старом_пути_body(связка):
    с, u = связка
    т2 = _текстом_а2(с)

    _отказ(lambda: u.body({АДРЕС_ОБЪЕКТА: т2}, entity=ЭМИССИЯ, revealed=RevealedValues()))


def test_без_строения_брат_не_ищется(связка):
    """Строения нет (индекс не знает сущность) — правило 2 молчит, решают остальные признаки."""
    с, u = связка
    т2 = _текстом_а2(с)
    без_строения = Unmasker(
        с,
        base="ut",
        field_class=lambda e, f, *, strict=False: КЛАССЫ.get((e, f)),
        path_class=без_класса_пути,
    )

    тело = без_строения.write(
        {АДРЕС_ОБЪЕКТА: т2}, entity=ЭМИССИЯ, current=None, revealed=RevealedValues()
    )

    assert тело == {АДРЕС_ОБЪЕКТА: А2}


# --- Правило 3: структурное написание любого токена в этом поле ---------------------------------


def test_структура_другого_токена_в_поле_делает_его_структурным(связка):
    """Брата нет, имя без суффикса, но словарь видел в `ОтправительАдрес` структуру другого адреса
    (А1): поле структурное для любого токена. Токен А2 (виден только текстом) — отказ."""
    с, u = связка
    с.token_for(
        "addr", _структура(А1), base="ut", entity=ПЕРЕМЕЩЕНИЕ, field="ОтправительАдрес", source=А1
    )
    т2 = _текстом_а2(с)

    _отказ(lambda: _записать(u, ПЕРЕМЕЩЕНИЕ, {"ОтправительАдрес": т2}))


def test_структура_в_другой_базе_поле_не_делает_структурным(связка):
    """Признак — по этой базе: структура в поле с тем же именем другой базы о формате поля этой
    базы ничего не говорит."""
    с, u = связка
    с.token_for(
        "addr", _структура(А1), base="bp", entity=ПЕРЕМЕЩЕНИЕ, field="ОтправительАдрес", source=А1
    )
    т2 = _текстом_а2(с)

    assert _записать(u, ПЕРЕМЕЩЕНИЕ, {"ОтправительАдрес": т2}) == {"ОтправительАдрес": А2}


def test_словарь_знает_структурное_поле(связка):
    с, _ = связка
    с.token_for("addr", А2, base="ut", entity=ПЕРЕМЕЩЕНИЕ, field="ОтправительАдрес")
    assert not с.structured_field(base="ut", entity=ПЕРЕМЕЩЕНИЕ, field="ОтправительАдрес")

    с.token_for(
        "addr", _структура(А1), base="ut", entity=ПЕРЕМЕЩЕНИЕ, field="ОтправительАдрес", source=А1
    )

    assert с.structured_field(base="ut", entity=ПЕРЕМЕЩЕНИЕ, field="ОтправительАдрес")
    assert not с.structured_field(base="bp", entity=ПЕРЕМЕЩЕНИЕ, field="ОтправительАдрес")
    assert not с.structured_field(base="ut", entity=ПЕРЕМЕЩЕНИЕ, field="АдресДоставки")


@pytest.mark.parametrize(
    "структура",
    [
        pytest.param(
            '<КонтактнаяИнформация xmlns="http://www.v8.1c.ru/ssl/contactinfo" '
            f'Представление="{А1}"/>',
            id="xml",
        ),
        pytest.param("\n  " + json.dumps({"value": А1}, ensure_ascii=False), id="json-с-отступом"),
    ],
)
def test_словарь_узнаёт_структуру_поля_в_любой_записи(связка, структура):
    с, _ = связка
    с.token_for("addr", структура, base="ut", entity=ПЕРЕМЕЩЕНИЕ, field="АдресПлощадки", source=А1)

    assert с.structured_field(base="ut", entity=ПЕРЕМЕЩЕНИЕ, field="АдресПлощадки")


def test_структурное_поле_с_тем_же_значением_в_current_пишет_current(связка):
    """Отказ — только без совпадения с `current` (Ruling 38, пункт 3): поле с братом, в `current`
    — структура того же адреса, записывается она дословно."""
    с, u = связка
    т2 = _текстом_а2(с)
    текущее = json.dumps({"value": А2, "type": "Адрес", "comment": "склад"}, ensure_ascii=False)

    тело = _записать(u, ЭМИССИЯ, {АДРЕС_ОБЪЕКТА: т2}, {АДРЕС_ОБЪЕКТА: текущее})

    assert тело == {АДРЕС_ОБЪЕКТА: текущее}


def test_отбор_по_структурному_полю_с_братом_не_берёт_текст(связка):
    """Чтение — тот же признак: в структурную колонку текстовые написания не идут, только
    структуры (здесь их нет) и нормализованная форма."""
    с, u = связка
    т = с.token_for(
        "addr", "г. Тула,  ул. Садовая, д. 9", base="ut", entity=ЗАКАЗ, field="АдресДоставки"
    )

    ушло = u.filter(f"{АДРЕС_ОБЪЕКТА} eq '{т}'", entity=ЭМИССИЯ, revealed=RevealedValues())

    assert ушло == f"{АДРЕС_ОБЪЕКТА} eq '{А2}'"


def test_json_без_type_в_поле_делает_его_структурным(связка):
    """Правило 3 — тем же признаком формата: структура без `type` в поле делает поле структурным."""
