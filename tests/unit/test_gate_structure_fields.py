"""Раунд 3 блокеров M2, Ruling 43 (Р2-1) и Р2-2: структурность — свойство поля, формат написания —
по тому же признаку, что основа токена.

Р2-1. Живьём на `trade_dev` `InformationRegister_НастройкиОбменаСУЗ.ПроизводственныйОбъектАдрес`
хранит структуру БСП, а имя не кончается на `…Значение`/`…ЗначенияПолей`. Признак «свои написания
поля» был потокенным: словарь видел в поле структуру адреса А1, а для токена адреса А2 (виденного
только текстом) поле считалось текстовым — в структуру уходил голый текст. Поле структурное, если
выполнено хотя бы одно:
1. имя кончается на `…Значение` или `…ЗначенияПолей`;
2. у сущности есть поле-брат `<Имя>Строкой` (ИС МП, СУЗ, ЗЕРНО: 24 поля в индексе УТ);
3. в словаре для этой базы, этой сущности (куда приходит путь) и этого имени поля есть
   структурное написание ЛЮБОГО токена (сущность в ключе — Р3-1, раунд 4,
   `test_gate_structure_entity.py`);
4. в `current` поле содержит структуру.
Поле, про которое ничего не известно, пишется текстом, как прежде (остаток — SPEC §6.8).

Р2-2. Маскировщик строит токен строки контактной информации по представлению всегда, а формат
написания для лестницы требовал `type` из перечисления: JSON `{"value": …}` без него считался
текстом и уходил в текстовое поле целиком. Теперь структура — всё, из чего извлекается
представление (и прежние структуры БСП).
"""

import json

import pytest
from conftest import без_класса_пути

from odata1c.config.models import BaseConfig, GateSettings
from odata1c.gate.contact_info import EntityShape
from odata1c.gate.dictionary import Dictionary
from odata1c.gate.guard import Guard
from odata1c.gate.pipeline import BaseGate
from odata1c.gate.revealed import RevealedValues
from odata1c.gate.unmasking import GateError, Unmasker

ЗАКАЗ = "Document_ЗаказКлиента"
СУЗ = "InformationRegister_НастройкиОбменаСУЗ"
ЭМИССИЯ = "Document_ЗаказНаЭмиссиюКодовМаркировкиСУЗ"
ПЕРЕМЕЩЕНИЕ = "Document_ПеремещениеМеждуМОДИСМП"
КИ = "Catalog_Контрагенты_КонтактнаяИнформация"
АДРЕС_ОБЪЕКТА = "ПроизводственныйОбъектАдрес"
КЛАССЫ = {
    (ЗАКАЗ, "АдресДоставки"): "addr",
    (ЗАКАЗ, "ТелефонКонтакта"): "phone",
    (СУЗ, АДРЕС_ОБЪЕКТА): "addr",
    (ЭМИССИЯ, АДРЕС_ОБЪЕКТА): "addr",
    (ПЕРЕМЕЩЕНИЕ, "ОтправительАдрес"): "addr",
    (ПЕРЕМЕЩЕНИЕ, "АдресХранения"): "addr",
    (КИ, "Значение"): "phone",
    (КИ, "НомерТелефона"): "phone",
}
СТРОЕНИЕ = {
    ЭМИССИЯ: EntityShape(fields=frozenset({АДРЕС_ОБЪЕКТА, f"{АДРЕС_ОБЪЕКТА}Строкой", "Ref_Key"})),
    ПЕРЕМЕЩЕНИЕ: EntityShape(fields=frozenset({"ОтправительАдрес", "Ref_Key", "Товары"})),
    f"{ПЕРЕМЕЩЕНИЕ}_Товары": EntityShape(
        fields=frozenset({"LineNumber", "АдресХранения", "АдресХраненияСтрокой"}),
        parent=ПЕРЕМЕЩЕНИЕ,
    ),
}
А1 = "г. Тверь, ул. Лесная, д. 5"
А2 = "г. Тула, ул. Садовая, д. 9"


def _структура(адрес: str) -> str:
    return json.dumps({"version": 4, "value": адрес, "type": "Адрес"}, ensure_ascii=False)


@pytest.fixture
def связка(tmp_path):
    с = Dictionary(tmp_path / "gate.sqlite", "секрет повторного ревью".encode())
    yield (
        с,
        Unmasker(
            с,
            base="ut",
            field_class=lambda e, f, *, strict=False: КЛАССЫ.get((e, f)),
            path_class=без_класса_пути,
            shape=СТРОЕНИЕ.get,
        ),
    )
    с.close()


def _текстом_а2(с: Dictionary) -> str:
    """Токен адреса А2, который словарь видел только текстом — в заказе."""
    return с.token_for("addr", А2, base="ut", entity=ЗАКАЗ, field="АдресДоставки")


def _отказ(вызов) -> GateError:
    with pytest.raises(GateError) as пойманное:
        вызов()
    assert пойманное.value.code == "token_ambiguous"
    return пойманное.value


def _записать(u: Unmasker, entity: str, данные: dict, current=None) -> dict:
    return u.write(данные, entity=entity, current=current, revealed=RevealedValues())


# --- Воспроизведения ревьюера (scratchpad/test_m2_r2_repro.py) -------------------------------


def _повидал_структуру_а1(с: Dictionary) -> None:
    с.token_for("addr", _структура(А1), base="ut", entity=СУЗ, field=АДРЕС_ОБЪЕКТА, source=А1)


def test_структурное_поле_без_суффикса_create(связка):
    с, u = связка
    _повидал_структуру_а1(с)
    т2 = _текстом_а2(с)
    try:
        ушло = _записать(u, ЭМИССИЯ, {АДРЕС_ОБЪЕКТА: т2})[АДРЕС_ОБЪЕКТА]
    except GateError as ошибка:
        assert ошибка.code == "token_ambiguous"
        return
    assert ушло.lstrip().startswith("{"), "в структурное поле ушёл голый текст"


def test_структурное_поле_без_суффикса_update_пустое(связка):
    с, u = связка
    _повидал_структуру_а1(с)
    т2 = _текстом_а2(с)
    try:
        ушло = _записать(u, СУЗ, {АДРЕС_ОБЪЕКТА: т2}, {АДРЕС_ОБЪЕКТА: ""})[АДРЕС_ОБЪЕКТА]
    except GateError as ошибка:
        assert ошибка.code == "token_ambiguous"
        return
    assert ушло.lstrip().startswith("{"), "в структурное поле ушёл голый текст"


