def test_гейт_передаёт_строение_обратной_подмене(tmp_path, связка):
    """Сквозь `BaseGate.inbound_write`: строение, которое слой тулов передаёт в `shape`, доходит до
    признака брата. Без передачи правило 2 молчало бы, и в структуру ушёл бы текст."""
    с, _ = связка
    политика = tmp_path / "policy.yaml"
    политика.write_text(
        f"version: 2\nauto:\n  {ЭМИССИЯ}.{АДРЕС_ОБЪЕКТА}: addr\n  {ЗАКАЗ}.АдресДоставки: addr\n",
        encoding="utf-8",
    )
    гейт = BaseGate(
        base=BaseConfig(
            name="ut",
            label="ut",
            url="http://host/base/odata/standard.odata/",
            user="agent",
            gate=GateSettings(mode="identifiers+names"),
        ),
        dictionary=с,
        guard=Guard(с),
        policy_path=политика,
    )
    т2 = _текстом_а2(с)

    def записать(строение):
        return гейт.inbound_write(
            {АДРЕС_ОБЪЕКТА: т2},
            entity=ЭМИССИЯ,
            shape=строение,
            current=None,
            revealed=RevealedValues(),
        )

    _отказ(lambda: записать(СТРОЕНИЕ.get))
    # Контроль: без брата в строении то же поле пишется текстом — отказ выше дал именно брат.
    assert записать(lambda _: None) == {АДРЕС_ОБЪЕКТА: А2}
