def json_телефона(value: str, country: str, area: str, number: str, ext: str = "") -> str:
    """JSON поля `Значение` так, как его пишет БСП (ключи и порядок — с живой базы)."""
    return json.dumps(
        {
            "version": 4,
            "value": value,
            "type": "Телефон",
            "countryCode": country,
            "areaCode": area,
            "number": number,
            "extNumber": ext,
            "comment": "",
        },
        ensure_ascii=False,
    )


def xml_телефона(value: str, country: str, area: str, number: str, ext: str = "") -> str:
    return (
        '<КонтактнаяИнформация xmlns="http://www.v8.1c.ru/ssl/contactinfo" '
        'xmlns:xs="http://www.w3.org/2001/XMLSchema" '
        'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
        f'Представление="{value}"><Состав xsi:type="НомерТелефона" КодСтраны="{country}" '
        f'КодГорода="{area}" Номер="{number}" Добавочный="{ext}"/></КонтактнаяИнформация>'
    )


def строка_телефона(value, country, area, number, ext="", *, тип="Телефон") -> dict:
    цифры = re.sub(r"\D", "", value)
    return {
        "Ref_Key": ГУИД,
        "LineNumber": "1",
        "Тип": тип,
        "Вид_Key": ГУИД_ВИДА,
        "Представление": value,
        "ЗначенияПолей": xml_телефона(value, country, area, number, ext),
        "Страна": "",
        "Регион": "",
        "Город": "",
        "АдресЭП": "",
        "ДоменноеИмяСервера": "",
        "НомерТелефона": цифры,
        "НомерТелефонаБезКодов": re.sub(r"\D", "", number),
        "ВидДляСписка_Key": "00000000-0000-0000-0000-000000000000",
        "ДействуетС": "0001-01-01T00:00:00",
        "Значение": json_телефона(value, country, area, number, ext),
    }


