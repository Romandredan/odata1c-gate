def test_тип_и_представление_из_самого_значения():
    значение = json_телефона("+7 (4912) 12-34-56", "7", "4912", "12-34-56")
    поля = xml_телефона("+7 (4912) 12-34-56", "7", "4912", "12-34-56")
    assert contact_info.self_type(значение) == "Телефон"
    assert contact_info.self_type(поля) == "Телефон"
    assert contact_info.representation(значение) == "+7 (4912) 12-34-56"
    assert contact_info.representation(поля) == "+7 (4912) 12-34-56"
    # Чужой JSON с ключом `type` — не контактная информация.
    assert contact_info.self_type('{"type": "Число", "value": "5"}') is None
    assert not contact_info.is_contact_value('{"type": "Число", "value": "5"}')
    # Текст — сам себе представление.
    assert contact_info.representation("+7 (4912) 12-34-56") == "+7 (4912) 12-34-56"


def test_xml_чужого_пространства_имён_не_контактная_информация():
    чужой = '<КонтактнаяИнформация Представление="x"><Состав/></КонтактнаяИнформация>'
    assert not contact_info.is_contact_value(чужой)
    assert contact_info.self_type(чужой) is None


