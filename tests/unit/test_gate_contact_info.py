def test_тип_строки_из_поля_тип_или_из_значения():
    строка = строка_телефона("+7 (4912) 12-34-56", "7", "4912", "12-34-56")
    assert contact_info.row_type(строка) == "Телефон"
    без_типа = {k: v for k, v in строка.items() if k != "Тип"}
    assert contact_info.row_type(без_типа) == "Телефон"
    assert contact_info.row_type({**без_типа, "Тип": ""}) == "Телефон"
    assert contact_info.row_type({"Представление": "что-то"}) is None


