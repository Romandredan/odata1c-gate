@pytest.mark.parametrize(("value", "country", "area", "number", "ext"), ФОРМЫ_НОМЕРА)
def test_ни_одной_цифры_номера_вне_токена(маскировщик, value, country, area, number, ext):
    """Сквозная проверка рубежа 1: все ключи JSON (`value`, `countryCode`, `areaCode`, `number`,
    `extNumber`), XML `ЗначенияПолей`, текст и колонки поиска — ни одной цифры номера вне токена.
    Номер строки, тип и дата действия при этом открыты (инвариант 6)."""
    строка = строка_телефона(value, country, area, number, ext)
    результат = маскировщик.mask(строка, entity=КИ_КОНТРАГЕНТОВ, resolve=навигации, shape=строение)
    данные = результат.data
    assert not re.search(r"\d", открытое(данные)), открытое(данные)
    for поле in ("Представление", "Значение", "ЗначенияПолей", "НомерТелефона"):
        assert данные[поле].startswith("[[phone:"), поле
    assert данные["Тип"] == "Телефон"
    assert данные["LineNumber"] == "1"
    assert данные["Ref_Key"] == ГУИД and данные["Вид_Key"] == ГУИД_ВИДА
    assert данные["ДействуетС"] == "0001-01-01T00:00:00"
    assert {"Представление", "Значение", "ЗначенияПолей"} <= set(результат.masked_fields)


def test_один_номер_один_токен_в_тексте_json_и_xml(маскировщик):
    """Детерминированность: номер в `Представление` (текст), `Значение` (JSON) и `ЗначенияПолей`
    (XML) — один токен, иначе модель не сопоставит поля одной строки. Колонка поиска
    `НомерТелефона` (те же цифры) — тот же токен: нормализация телефона — цифры."""
    строка = строка_телефона("+7 (4912) 12-34-56", "7", "4912", "12-34-56")
    данные = маскировщик.mask(строка, entity=КИ_КОНТРАГЕНТОВ, shape=строение).data
    assert (
        данные["Представление"]
        == данные["Значение"]
        == данные["ЗначенияПолей"]
        == данные["НомерТелефона"]
    )


def test_факс_маскируется_как_телефон(маскировщик):
    строка = строка_телефона("+7 (4912) 12-34-57", "7", "4912", "12-34-57", тип="Факс")
    данные = маскировщик.mask(строка, entity=КИ_КОНТРАГЕНТОВ, shape=строение).data
    assert данные["Представление"].startswith("[[phone:")
    assert not re.search(r"\d", открытое(данные))


def test_решение_по_всей_строке_а_не_по_порядку_ключей(маскировщик):
    """`Значение` раньше `Тип` в ответе — результат тот же: класс строки считается до обхода."""
    строка = строка_телефона("+7 (4912) 12-34-56", "7", "4912", "12-34-56")
    переставлено = dict(reversed(list(строка.items())))
    assert next(iter(переставлено)) == "Значение"
    прямо = маскировщик.mask(строка, entity=КИ_КОНТРАГЕНТОВ, shape=строение).data
    обратно = маскировщик.mask(переставлено, entity=КИ_КОНТРАГЕНТОВ, shape=строение).data
    assert прямо == обратно


def test_обратная_подмена_в_поле_значение_возвращает_json(маскировщик):
    """Написание запоминается исходное: токен поля `Значение` раскрывается в этом поле в JSON
    целиком, а не в текст из него (иначе отбор по токену искал бы в 1С не то, что там лежит)."""
    строка = строка_телефона("+7 (4912) 12-34-56", "7", "4912", "12-34-56")
    данные = маскировщик.mask(строка, entity=КИ_КОНТРАГЕНТОВ, shape=строение).data
    словарь = маскировщик._dictionary
    assert словарь.reveal(данные["Значение"], base="ut", field="Значение") == строка["Значение"]
    assert (
        словарь.reveal(данные["Представление"], base="ut", field="Представление")
        == (строка["Представление"])
    )


