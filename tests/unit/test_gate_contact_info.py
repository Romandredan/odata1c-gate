def test_строение_узнаётся_по_полям_а_не_по_имени():
    assert contact_info.is_contact_info_table(ПОЛЯ_КИ)
    assert contact_info.is_contact_info_table({"Тип", "Представление", "ЗначенияПолей"})
    # Одного `Тип` и `Значение` мало: так устроены и чужие регистры с полем «Значение».
    assert not contact_info.is_contact_info_table({"Тип", "Значение"})
    assert not contact_info.is_contact_info_table({"Представление", "Значение"})


