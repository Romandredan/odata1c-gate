def обратная(маскировщик, *, shape=строение, политика=None):
    """Обратная подмена на том же словаре, что у маскировщика, с классом входного пути — так же,
    как её собирает `BaseGate._обратная_подмена`: класс поля и класс пути (Ruling 37)."""
    from odata1c.gate.masking import inbound_field_class, inbound_path_class
    from odata1c.gate.unmasking import Unmasker

    политика = политика or маскировщик._policy
    return Unmasker(
        маскировщик._dictionary,
        base="ut",
        field_class=lambda entity, field, *, strict=False: inbound_field_class(
            политика, entity, field, mode="identifiers+names", shape=shape, strict=strict
        ),
        path_class=lambda entity, path: inbound_path_class(политика, entity, path, shape=shape),
    )


