def test_решение_по_всей_строке_а_не_по_порядку_ключей(маскировщик):
    """`Значение` раньше `Тип` в ответе — результат тот же: класс строки считается до обхода."""
    строка = строка_телефона("+7 (4912) 12-34-56", "7", "4912", "12-34-56")
    переставлено = dict(reversed(list(строка.items())))
    assert next(iter(переставлено)) == "Значение"
    прямо = маскировщик.mask(строка, entity=КИ_КОНТРАГЕНТОВ, shape=строение).data
    обратно = маскировщик.mask(переставлено, entity=КИ_КОНТРАГЕНТОВ, shape=строение).data
    assert прямо == обратно


def test_обратная_подмена_в_поле_значение_возвращает_json(маскировщик):
    """Написание запоминается исходное: токен поля `Значение` раскрывается в этом поле в JSON
    целиком, а не в текст из него (иначе отбор по токену искал бы в 1С не то, что там лежит)."""
    строка = строка_телефона("+7 (4912) 12-34-56", "7", "4912", "12-34-56")
    данные = маскировщик.mask(строка, entity=КИ_КОНТРАГЕНТОВ, shape=строение).data
    словарь = маскировщик._dictionary
    assert словарь.reveal(данные["Значение"], base="ut", field="Значение") == строка["Значение"]
    assert (
        словарь.reveal(данные["Представление"], base="ut", field="Представление")
        == (строка["Представление"])
    )


