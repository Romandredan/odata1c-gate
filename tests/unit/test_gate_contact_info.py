def открытое(данные) -> str:
    """Всё, что модель увидит в строке, кроме токенов и полей, открытых по замыслу (GUID ссылок,
    номер строки, тип, дата действия), — одной строкой."""
    части = []
    for ключ, значение in данные.items():
        if ключ in ("Ref_Key", "LineNumber", "Тип", "ДействуетС") or ключ.endswith("_Key"):
            continue
        if isinstance(значение, str):
            части.append(TOKEN_RE.sub("", значение))
    return " ".join(части)


