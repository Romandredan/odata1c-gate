"""Свойства гейта (SPEC §12): тождество подмены и отсутствие значений словаря в ответе.

Юнит-тесты проверяют модули по отдельности на нескольких примерах; здесь — связка целиком
(словарь → маскировщик → сериализация → страж; словарь → обратная подмена) на сгенерированных
данных. Каждый пример получает свежую связку во временном каталоге: словарь накапливает значения
между вызовами, и общая фикстура pytest сделала бы примеры зависимыми друг от друга (нумерация
названий, варианты написания, ревизия автомата) — поэтому не фикстура, а контекстный менеджер
внутри теста.
"""

import contextlib
import json
import pathlib
import re
import tempfile
import typing
import unicodedata

import pytest
from hypothesis import assume, given, settings
from hypothesis import strategies as st

from odata1c.gate.detectors import ВЕСА_ИНН10, inn_valid
from odata1c.gate.dictionary import Dictionary, name_variants_of, normalize_text_with_map
from odata1c.gate.guard import Guard
from odata1c.gate.masking import Masker
from odata1c.gate.policy import load_policy
from odata1c.gate.tokens import find_tokens
from odata1c.gate.unmasking import Unmasker

# Длина секрета словарём не проверяется (HMAC принимает любую); в бою это 32 случайных байта
# (config/writer.py::ensure_gate_secret) — берём столько же, ASCII-литералом.
СЕКРЕТ = b"property-tests-secret-0123456789"
СУЩНОСТЬ = "Catalog_Контрагенты"
ПОЛИТИКА_ТЕКСТ = (
    "version: 2\nscan_free_text: true\nauto:\n"
    f"  {СУЩНОСТЬ}.ИНН: inn\n"
    f"  {СУЩНОСТЬ}.Description: org\n"
)
КЛАССЫ_ПОЛЕЙ = {"ИНН": "inn", "Description": "org"}

ТОКЕН_ИНН = re.compile(r"^\[\[inn:[0-9A-Z]{10}\]\]$")
ТОКЕН_ОРГ = re.compile(r"^\[\[org:\d+\]\]$")


# --- Стратегии ---------------------------------------------------------------------------------


def _инн_из_ядра(ядро: int) -> str:
    """10-значный ИНН с верной контрольной цифрой — иначе детектор в свободном тексте его не
    подтвердит, и свойство «не выходит» проверяло бы только страж, а не связку."""
    цифры = [int(символ) for символ in f"{ядро:09d}"]
    контроль = sum(цифра * вес for цифра, вес in zip(цифры, ВЕСА_ИНН10, strict=True)) % 11 % 10
    return f"{ядро:09d}{контроль}"


ИНН = st.integers(min_value=0, max_value=10**9 - 1).map(_инн_из_ядра)


def _с_пробелами(инн: str, разрывы: list[bool]) -> str:
    """Написание ИНН с пробелами внутри — как в 1С бывает «7707 083893»."""
    куски = [
        цифра + (" " if разрыв else "") for цифра, разрыв in zip(инн[:-1], разрывы, strict=True)
    ]
    return "".join(куски) + инн[-1]


НАПИСАНИЕ_ИНН = st.builds(_с_пробелами, ИНН, st.lists(st.booleans(), min_size=9, max_size=9))

КИРИЛЛИЦА = "абвгдежзийклмнопрстуфхцчшщъыьэюя"
СЛОВО = st.text(alphabet=КИРИЛЛИЦА, min_size=3, max_size=8).map(str.capitalize)
ФОРМА = st.sampled_from(["ООО", "АО", "ЗАО", "ПАО", "ИП", ""])
НАЗВАНИЯ = st.builds(
    lambda форма, слова: " ".join(([форма] if форма else []) + слова),
    ФОРМА,
    st.lists(СЛОВО, min_size=1, max_size=3),
)
БАЗЫ = st.sampled_from(["ut", "buh", "zup"])
# Любой печатный Unicode, включая невидимые символы форматирования (Cf), пробелы всех видов,
# кавычки-ёлочки и символы с расширяющимся нижним регистром — всё то, на чём страж уже ловили.
ТЕКСТ = st.text(alphabet=st.characters(blacklist_categories=("Cs", "Cc")), max_size=80)


# --- Связка --------------------------------------------------------------------------------------


class Связка(typing.NamedTuple):
    словарь: Dictionary
    маскировщик: Masker
    обратно: Unmasker
    страж: Guard


@contextlib.contextmanager
def связка(*, base: str = "ut") -> typing.Iterator[Связка]:
    with tempfile.TemporaryDirectory() as каталог:
        путь = pathlib.Path(каталог)
        (путь / "policy.yaml").write_text(ПОЛИТИКА_ТЕКСТ, encoding="utf-8")
        словарь = Dictionary(путь / "gate.sqlite", СЕКРЕТ)
        try:
            политика = load_policy(путь / "policy.yaml")
            yield Связка(
                словарь=словарь,
                маскировщик=Masker(словарь, политика, mode="identifiers+names", base=base),
                обратно=Unmasker(
                    словарь,
                    base=base,
                    field_class=lambda сущность, поле: КЛАССЫ_ПОЛЕЙ.get(поле),
                ),
                страж=Guard(словарь),
            )
        finally:
            словарь.close()


def _цифры(текст: str) -> str:
    return "".join(str(unicodedata.digit(символ)) for символ in текст if символ.isdigit())


# --- Тождество прямой и обратной подмены ----------------------------------------------------------


@given(написание=НАПИСАНИЕ_ИНН)
@settings(max_examples=50, deadline=None)
def test_прямая_и_обратная_подмена_тождественны_для_реквизитов(написание):
    """SPEC §12: прямая подмена + обратная = тождество, причём с точностью до написания в базе
    (обратная подмена возвращает вариант этой базы и поля, а не нормализованные цифры)."""
    assert inn_valid(re.sub(r"\D", "", написание))
    with связка() as г:
        замаскировано = г.маскировщик.mask({"ИНН": написание}, entity=СУЩНОСТЬ)
        токен = замаскировано.data["ИНН"]
        assert ТОКЕН_ИНН.match(токен), токен
        assert замаскировано.masked_fields == ["ИНН"]
        восстановлено = г.обратно.body({"ИНН": токен}, entity=СУЩНОСТЬ)
    assert восстановлено["ИНН"] == написание


@given(название=НАЗВАНИЯ)
@settings(max_examples=50, deadline=None)
def test_прямая_и_обратная_подмена_тождественны_для_названий(название):
    with связка() as г:
        замаскировано = г.маскировщик.mask({"Description": название}, entity=СУЩНОСТЬ)
        токен = замаскировано.data["Description"]
        assert ТОКЕН_ОРГ.match(токен), токен
        восстановлено = г.обратно.body({"Description": токен}, entity=СУЩНОСТЬ)
    assert восстановлено["Description"] == название


# --- Ни одно значение словаря не выходит наружу ---------------------------------------------------


@given(инн=ИНН, название=НАЗВАНИЯ, шум=ТЕКСТ)
@settings(max_examples=100, deadline=None)
def test_ни_одно_значение_словаря_не_выходит(инн, название, шум):
    """SPEC §12: ни одна строка ответа не содержит значений из словаря — после маскировщика
    и стража вместе. ИНН в комментарии стоит без слова-подсказки: детектор 10-значный ИНН без
    контекста не подтверждает (SPEC §6.4), так что здесь именно страж обязан его снять.

    Название проверяется только когда у него есть хотя бы один вариант для сканера: SPEC §6.5
    (слой 3) ищет в свободном тексте варианты длиной от 4 символов, и название короче в чужой
    строке остаётся открытым по построению — контрпример этого свойства без оговорки закреплён
    ниже (`test_находка_короткое_название_в_свободном_тексте_остаётся_открытым`)."""
    with связка() as г:
        г.словарь.token_for("inn", инн, base="ut", entity=СУЩНОСТЬ, field="ИНН")
        г.словарь.token_for("org", название, base="ut", entity=СУЩНОСТЬ, field="Description")

        ответ = {"items": [{"ИНН": инн, "Description": название, "Комментарий": f"{шум} {инн}"}]}
        замаскировано = г.маскировщик.mask(ответ, entity=СУЩНОСТЬ)
        запись = замаскировано.data["items"][0]
        assert ТОКЕН_ИНН.match(запись["ИНН"]), запись["ИНН"]
        assert ТОКЕН_ОРГ.match(запись["Description"]), запись["Description"]

        сериализовано = json.dumps(замаскировано.data, ensure_ascii=False)
        проверено = г.страж.check(сериализовано, mode="identifiers+names")

    assert инн not in проверено.text
    assert инн not in _цифры(проверено.text)
    if name_variants_of(название):
        assert название.lower() not in проверено.text.lower()
    json.loads(проверено.text)  # страж не ломает структуру JSON


@pytest.mark.xfail(
    strict=True,
    reason=(
        "находка: название короче 4 символов (без ОПФ) не попадает в варианты словаря "
        "(dictionary.py::МИНИМАЛЬНАЯ_ДЛИНА_ВАРИАНТА, SPEC §6.5 слой 3), поэтому его упоминание в "
        "свободном тексте не снимают ни маскировщик, ни страж — вопреки формулировке SPEC §12 "
        "«ни одна строка ответа не содержит значений из словаря»"
    ),
)
def test_находка_короткое_название_в_свободном_тексте_остаётся_открытым():
    """Минимальный контрпример, найденный Hypothesis на свойстве выше без оговорки про длину
    варианта (2026-09-10, 2000 примеров): инн='0000000000', название='Ааа', шум='ААА'. Поле
    Description при этом токенизировано верно — течёт только упоминание в комментарии. То же
    касается коротких брендов с ОПФ: у «ООО МТС» вариант «ооо мтс» ловится, «мтс» — нет."""
    инн, название, шум = "0000000000", "Ааа", "ААА"
    with связка() as г:
        г.словарь.token_for("inn", инн, base="ut", entity=СУЩНОСТЬ, field="ИНН")
        г.словарь.token_for("org", название, base="ut", entity=СУЩНОСТЬ, field="Description")
        ответ = {"items": [{"ИНН": инн, "Description": название, "Комментарий": f"{шум} {инн}"}]}
        сериализовано = json.dumps(
            г.маскировщик.mask(ответ, entity=СУЩНОСТЬ).data, ensure_ascii=False
        )
        проверено = г.страж.check(сериализовано, mode="identifiers+names")
    assert название.lower() not in проверено.text.lower()


# --- Страж нейтрален там, где заменять нечего -----------------------------------------------------


@given(текст=ТЕКСТ)
@settings(max_examples=100, deadline=None)
def test_страж_нейтрален_на_пустом_словаре(текст):
    """На пустом словаре страж обязан вернуть текст без изменений — посимвольно, а не
    «эквивалентный JSON»."""
    сериализовано = json.dumps({"поле": текст}, ensure_ascii=False)
    with связка() as г:
        результат = г.страж.check(сериализовано, mode="identifiers+names")
    assert результат.text == сериализовано
    assert результат.replacements == []
    assert результат.warnings == []


@given(инн=ИНН, название=НАЗВАНИЯ, текст=ТЕКСТ)
@settings(max_examples=100, deadline=None)
def test_страж_нейтрален_на_тексте_без_значений_словаря(инн, название, текст):
    """Словарь непуст, но в тексте его значений нет — ни цифрами (с учётом любых разделителей
    и систем записи цифр), ни вариантом названия в нормализованной форме. Страж обязан
    вернуть исходную строку, а не нормализованную копию и не обрезок."""
    сериализовано = json.dumps({"поле": текст}, ensure_ascii=False)
    with связка() as г:
        г.словарь.token_for("inn", инн, base="ut", entity=СУЩНОСТЬ, field="ИНН")
        г.словарь.token_for("org", название, base="ut", entity=СУЩНОСТЬ, field="Description")
        assume(инн not in _цифры(сериализовано))
        нормализованный, _ = normalize_text_with_map(сериализовано)
        assume(all(вариант not in нормализованный for вариант in г.словарь.name_variants()))
        результат = г.страж.check(сериализовано, mode="identifiers+names")
    assert результат.text == сериализовано
    assert результат.replacements == []
    assert результат.warnings == []


@given(префикс=ТЕКСТ, суффикс=ТЕКСТ)
@settings(max_examples=100, deadline=None)
def test_страж_заменяет_название_не_трогая_окружение(префикс, суффикс):
    """Карта позиций (`normalize_text_with_map`) на произвольном окружении: невидимые символы,
    повторы пробелов, символы с расширяющимся нижним регистром до и после названия не должны
    сдвигать границы замены. Ожидание — ровно префикс, токен, суффикс; название отделено
    пробелами, чтобы совпадение не могло законно захватить соседние символы."""
    название = "ООО Ромашка"
    assume("ромашка" not in normalize_text_with_map(префикс + суффикс)[0])
    assume(not find_tokens(префикс) and not find_tokens(суффикс))
    исходный = json.dumps({"c": f"{префикс} {название} {суффикс}"}, ensure_ascii=False)
    with связка() as г:
        токен = г.словарь.token_for(
            "org", название, base="ut", entity=СУЩНОСТЬ, field="Description"
        )
        результат = г.страж.check(исходный, mode="identifiers+names")
    ожидаемый = json.dumps({"c": f"{префикс} {токен} {суффикс}"}, ensure_ascii=False)
    assert результат.text == ожидаемый
    assert [замена["token"] for замена in результат.replacements] == [токен]
    assert результат.warnings == ["guard_replaced"]


# --- Одно значение — один токен -------------------------------------------------------------------


@given(
    инн=ИНН,
    разрывы=st.lists(st.booleans(), min_size=9, max_size=9),
    первая_база=БАЗЫ,
    вторая_база=БАЗЫ,
)
@settings(max_examples=50, deadline=None)
def test_токен_одного_значения_всегда_один(инн, разрывы, первая_база, вторая_база):
    """Токен реквизита не зависит от базы, сущности, поля и пробелов в написании (SPEC §6.3)."""
    with связка() as г:
        первый = г.словарь.token_for("inn", инн, base=первая_база, entity="E", field="ИНН")
        второй = г.словарь.token_for(
            "inn", _с_пробелами(инн, разрывы), base=вторая_база, entity="E2", field="ИНН2"
        )
    assert ТОКЕН_ИНН.match(первый), первый
    assert первый == второй


@given(первый_инн=ИНН, второй_инн=ИНН)
@settings(max_examples=50, deadline=None)
def test_разные_значения_получают_разные_токены(первый_инн, второй_инн):
    """Обратная сторона предыдущего свойства: хвост зависит от значения, а не только от класса
    и секрета — иначе тождество на одном значении проходило бы и при вырожденном HMAC.

    Одного `первый != второй` мало: при коллизии словарь удлиняет хвост второго значения до
    16 символов (SPEC §6.3), и токены различались бы даже при хэше, не зависящем от значения.
    Поэтому оба токена обязаны быть с обычным 10-символьным хвостом — настоящая коллизия двух
    значений на свежем словаре имеет вероятность 2⁻⁵⁰ и здесь означает поломку хэша."""
    assume(первый_инн != второй_инн)
    with связка() as г:
        первый = г.словарь.token_for("inn", первый_инн, base="ut", entity="E", field="ИНН")
        второй = г.словарь.token_for("inn", второй_инн, base="ut", entity="E", field="ИНН")
        assert первый != второй
        assert ТОКЕН_ИНН.match(первый), первый
        assert ТОКЕН_ИНН.match(второй), второй
        assert г.словарь.reveal(первый) == первый_инн
        assert г.словарь.reveal(второй) == второй_инн
