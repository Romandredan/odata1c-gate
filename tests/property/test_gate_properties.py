@given(первый_инн=ИНН, второй_инн=ИНН)
@settings(max_examples=50, deadline=None)
def test_разные_значения_получают_разные_токены(первый_инн, второй_инн):
    """Обратная сторона предыдущего свойства: хвост зависит от значения, а не только от класса
    и секрета — иначе тождество на одном значении проходило бы и при вырожденном HMAC.

    Одного `первый != второй` мало: при коллизии словарь удлиняет хвост второго значения до
    16 символов (SPEC §6.3), и токены различались бы даже при хэше, не зависящем от значения.
    Поэтому оба токена обязаны быть с обычным 10-символьным хвостом — настоящая коллизия двух
    значений на свежем словаре имеет вероятность 2⁻⁵⁰ и здесь означает поломку хэша."""
    assume(первый_инн != второй_инн)
    with связка() as г:
        первый = г.словарь.token_for("inn", первый_инн, base="ut", entity="E", field="ИНН")
        второй = г.словарь.token_for("inn", второй_инн, base="ut", entity="E", field="ИНН")
        assert первый != второй
        assert ТОКЕН_ИНН.match(первый), первый
        assert ТОКЕН_ИНН.match(второй), второй
        assert г.словарь.reveal(первый) == первый_инн
        assert г.словарь.reveal(второй) == второй_инн


