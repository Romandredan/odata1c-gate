# --- Ни одно значение словаря не выходит наружу ---------------------------------------------------


@given(инн=ИНН, название=НАЗВАНИЯ, шум=ТЕКСТ, обрезать=st.booleans())
@settings(max_examples=100, deadline=None)
def test_ни_одно_значение_словаря_не_выходит(инн, название, шум, обрезать):
    """SPEC §12: ни одна строка ответа не содержит значений из словаря — после маскировщика
    и стража вместе. ИНН в комментарии стоит без слова-подсказки: детектор 10-значный ИНН без
    контекста не подтверждает (SPEC §6.4), так что здесь именно страж обязан его снять.

    Название проверяется только когда у него есть хотя бы один вариант для сканера: SPEC §6.5
    (слой 3) ищет в свободном тексте варианты длиной от 4 символов, и название короче в чужой
    строке остаётся открытым по построению — контрпример этого свойства без оговорки закреплён
    ниже (`test_находка_короткое_название_в_свободном_тексте_остаётся_открытым`).

    Название упоминается и в конце комментария — возможно, без закрывающей кавычки (раунд 2
    ревью, C1); утечка проверяется по раскодированным строкам ответа, по каждому варианту."""
    упоминание = _без_закрывающей(название, обрезать)
    with связка() as г:
        г.словарь.token_for("inn", инн, base="ut", entity=СУЩНОСТЬ, field="ИНН")
        г.словарь.token_for("org", название, base="ut", entity=СУЩНОСТЬ, field="Description")
        варианты = list(г.словарь.name_variants())

        ответ = {
            "items": [
                {"ИНН": инн, "Description": название, "Комментарий": f"{шум} {инн} {упоминание}"}
            ]
        }
        замаскировано = г.маскировщик.mask(ответ, entity=СУЩНОСТЬ)
        запись = замаскировано.data["items"][0]
        assert ТОКЕН_ИНН.match(запись["ИНН"]), запись["ИНН"]
        assert ТОКЕН_ОРГ.match(запись["Description"]), запись["Description"]

        сериализовано = json.dumps(замаскировано.data, ensure_ascii=False)
        проверено = г.страж.check(сериализовано, mode="identifiers+names")

    assert инн not in проверено.text
    assert инн not in _цифры(проверено.text)
    выход = json.loads(проверено.text)  # страж не ломает структуру JSON
    assert _остались_варианты(выход, варианты) == []


@given(название=НАЗВАНИЯ, шум=ТЕКСТ, обрезать=st.booleans(), ascii_=st.booleans())
@settings(max_examples=150, deadline=None)
def test_страж_ловит_название_в_конце_строки_и_в_кавычках(название, шум, обрезать, ascii_):
    """Раунд 2 ревью, C1 — свойство самого стража, без маскировщика впереди: название (в любых
    кавычках, возможно без закрывающей) в конце строкового значения и целиком в соседнем
    значении не остаётся ни одним вариантом ни в одной строке ответа, а ответ — валидный JSON.
    Сериализация — и с экранированием `\\uXXXX`, и без него."""
    assume(not find_tokens(шум))
    ответ = {"a": f"{шум} {_без_закрывающей(название, обрезать)}", "b": название}
    сериализовано = json.dumps(ответ, ensure_ascii=ascii_)
    with связка() as г:
        г.словарь.token_for("org", название, base="ut", entity=СУЩНОСТЬ, field="Description")
        варианты = list(г.словарь.name_variants())
        assume(варианты)
        проверено = г.страж.check(сериализовано, mode="identifiers+names")
    assert _остались_варианты(json.loads(проверено.text), варианты) == []


