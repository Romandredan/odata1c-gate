# --- Стратегии ---------------------------------------------------------------------------------


def _инн_из_ядра(ядро: int) -> str:
    """10-значный ИНН с верной контрольной цифрой — иначе детектор в свободном тексте его не
    подтвердит, и свойство «не выходит» проверяло бы только страж, а не связку."""
    цифры = [int(символ) for символ in f"{ядро:09d}"]
    контроль = sum(цифра * вес for цифра, вес in zip(цифры, ВЕСА_ИНН10, strict=True)) % 11 % 10
    return f"{ядро:09d}{контроль}"


ИНН = st.integers(min_value=0, max_value=10**9 - 1).map(_инн_из_ядра)


def _с_пробелами(инн: str, разрывы: list[bool]) -> str:
    """Написание ИНН с пробелами внутри — как в 1С бывает «7707 083893»."""
    куски = [
        цифра + (" " if разрыв else "") for цифра, разрыв in zip(инн[:-1], разрывы, strict=True)
    ]
    return "".join(куски) + инн[-1]


НАПИСАНИЕ_ИНН = st.builds(_с_пробелами, ИНН, st.lists(st.booleans(), min_size=9, max_size=9))

