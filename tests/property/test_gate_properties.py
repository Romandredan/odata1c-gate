@settings(max_examples=60, deadline=None)
def test_одно_юрлицо_в_двух_написаниях_кавычек_один_токен(слова, к1, к2):
    """C1 ревью 2026-09-10: два написания одного названия (разные кавычки, разные базы) дают ОДИН
    токен, вариант однозначен, и страж заменяет оба написания. Здесь в словарь идут ДВЕ записи на
    пример — путь к двойникам, которого не было в других свойствах."""
    ядро = " ".join(слова)
    написание1 = f"ООО {к1[0]}{ядро}{к1[1]}"
    написание2 = f"ООО {к2[0]}{ядро}{к2[1]}"
    with связка() as г:
        т1 = г.словарь.token_for("org", написание1, base="ut", entity=СУЩНОСТЬ, field="Description")
