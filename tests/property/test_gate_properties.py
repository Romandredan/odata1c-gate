ТЕКСТ = st.text(alphabet=st.characters(blacklist_categories=("Cs", "Cc")), max_size=80)


# --- Связка --------------------------------------------------------------------------------------


class Связка(typing.NamedTuple):
    словарь: Dictionary
    маскировщик: Masker
    обратно: Unmasker
    страж: Guard


@contextlib.contextmanager
def связка(*, base: str = "ut") -> typing.Iterator[Связка]:
    with tempfile.TemporaryDirectory() as каталог:
        путь = pathlib.Path(каталог)
        (путь / "policy.yaml").write_text(ПОЛИТИКА_ТЕКСТ, encoding="utf-8")
        словарь = Dictionary(путь / "gate.sqlite", СЕКРЕТ)
        try:
            политика = load_policy(путь / "policy.yaml")
            yield Связка(
                словарь=словарь,
                маскировщик=Masker(словарь, политика, mode="identifiers+names", base=base),
                обратно=Unmasker(
                    словарь,
                    base=base,
                    field_class=lambda сущность, поле, *, strict=False: КЛАССЫ_ПОЛЕЙ.get(поле),
                    path_class=lambda сущность, путь: None,
                ),
                страж=Guard(словарь),
            )
        finally:
            словарь.close()


def _цифры(текст: str) -> str:
    return "".join(str(unicodedata.digit(символ)) for символ in текст if символ.isdigit())


def _без_закрывающей(название: str, обрезать: bool) -> str:
    """Упоминание названия в свободном тексте: 1С нередко обрезает строку так, что закрывающей
    кавычки нет, и название оказывается в самом конце строки."""
    return название[:-1] if обрезать and название[-1:] in ("»", '"') else название


def _строки(данные) -> typing.Iterator[str]:
    """Все строковые значения и ключи раскодированного JSON — проверка утечки идёт по ним, а не
    по сырому тексту: там кавычка внутри названия записана как `\\"`, а кириллица может быть
    записана `\\uXXXX`, и поиск по сырому тексту дал бы ложную зелень."""
    if isinstance(данные, str):
        yield данные
    elif isinstance(данные, dict):
        for ключ, значение in данные.items():
            yield ключ
            yield from _строки(значение)
    elif isinstance(данные, list):
        for элемент in данные:
            yield from _строки(элемент)


def _одного_рода(а: str, б: str) -> bool:
    return (а.isalpha() and б.isalpha()) or (а.isdigit() and б.isdigit())


def _отдельным_словом(текст: str, вариант: str) -> bool:
    """Есть ли в тексте вхождение варианта, не приклеенное к слову или числу (Ruling 106): название
    внутри «себестоимости» названием не считается. Своя реализация, а не код гейта: оракул не
    должен повторять проверяемое."""
    начало = текст.find(вариант)
    while начало != -1:
        конец = начало + len(вариант)
        слева = начало > 0 and _одного_рода(текст[начало], текст[начало - 1])
        справа = конец < len(текст) and _одного_рода(текст[конец - 1], текст[конец])
        if not (слева or справа):
            return True
        начало = текст.find(вариант, начало + 1)
    return False


def _остались_варианты(данные, варианты) -> list[str]:
    return [
        вариант
        for строка in _строки(данные)
        for вариант in варианты
        if _отдельным_словом(normalize_text_with_map(строка)[0], вариант)
    ]


