async def детерминизм(сеанс, итог: dict) -> None:
    """Раунд 3, I-1: одно значение — один токен при любом наборе выбранных полей. Одни и те же
    строки (порядок по `Ref_Key`, `LineNumber`) выбираются четырьмя наборами полей; токены одного
    поля сравниваются попарно. Печатаются только счётчики."""
    print("\n=== 6б. Один токен при любом наборе полей (I-1) ===")
    ки = "Catalog_Контрагенты_КонтактнаяИнформация"
    наборы = {
        "Представление": ["Ref_Key", "LineNumber", "Представление"],
        "Представление+Тип": ["Ref_Key", "LineNumber", "Тип", "Представление"],
        "НомерТелефона": ["Ref_Key", "LineNumber", "НомерТелефона"],
        "НомерТелефона+Тип": ["Ref_Key", "LineNumber", "Тип", "НомерТелефона"],
        "АдресЭП": ["Ref_Key", "LineNumber", "АдресЭП"],
        "АдресЭП+Тип": ["Ref_Key", "LineNumber", "Тип", "АдресЭП"],
    }
    ответы = {}
    for имя, поля in наборы.items():
        ответ = await тул(
            сеанс,
            "odata1c_query",
            {"entity": ки, "select": поля, "orderby": "Ref_Key,LineNumber", "top": 300},
        )
        if ответ.get("error"):
            print(f"  {имя}: ошибка {ответ['error'].get('code')}")
            return
        ответы[имя] = {
            (з.get("Ref_Key"), з.get("LineNumber")): з for з in ответ.get("items") or []
        }
    результат = {}
    for поле in ("Представление", "НомерТелефона", "АдресЭП"):
        без, с_типом = ответы[поле], ответы[f"{поле}+Тип"]
        общие = [к for к in без if к in с_типом and (без[к].get(поле) or с_типом[к].get(поле))]
        расхождений = sum(1 for к in общие if без[к].get(поле) != с_типом[к].get(поле))
        тип_добавлен = sum(1 for з in без.values() if "Тип" in з)
        результат[поле] = {
            "строк": len(общие),
            "разных_токенов": расхождений,
            "Тип_в_ответе_без_запроса": тип_добавлен,
        }
        print(
            f"  {поле}: строк со значением {len(общие)}, разных токенов {расхождений}, "
            f"Тип пришёл без запроса в {тип_добавлен} из {len(без)}"
        )
    итог["детерминизм"] = результат


