async def почта(сеанс, итог: dict) -> None:
    print("\n=== 2. Почта в контактной информации ===")
    всего = {"строк": 0, "открыто": 0, "домен_открыт": 0}
    ключи = Counter()
    for сущность in СУЩНОСТИ_КИ:
        записи, ошибка, замаскированные, _ = await выборка(
            сеанс, сущность, фильтр="Тип eq 'АдресЭлектроннойПочты'", поля=ВЫБОРКА_КИ, всего=200
        )
        if ошибка:
            print(f"  {сущность}: ошибка {ошибка}")
            continue
        открытые = [открытая_почта(с) for с in записи]
        домены = sum(
            1
            for с in записи
            if isinstance(с.get("ДоменноеИмяСервера"), str)
            and без_токенов(с["ДоменноеИмяСервера"]).strip()
        )
        всего["строк"] += len(записи)
        всего["открыто"] += sum(1 for п in открытые if п)
