def собрать_дом(
    рабочий: pathlib.Path, *, адрес: str | None = None, перестроить_политику: bool = False
) -> pathlib.Path:
    """Временный домашний каталог: запись базы, индекс и политика — копией из рабочего дома;
    словарь — пустой, секрет — свой. `адрес` — адрес публикации вместо настоящего (прокси-счётчик).
    `перестроить_политику` — пересобрать раздел `auto` политики по индексу текущим кодом, как это
    сделает реиндекс владельца (Ruling 36: новые справочники людей попадают в `auto` только так).
    Уровень гейта копии принудительно `identifiers+names` — у рабочей записи уровень может быть
    любым (например, `off` по умолчанию роли `dev`), а приёмка проверяет маскировку именно на
    этом уровне."""
    дом = pathlib.Path(tempfile.mkdtemp(prefix="odata1c-ci-"))
    for имя in ("bases", "logs"):
        (дом / имя).mkdir()
    настройки = yaml.safe_load((рабочий / "bases.yaml").read_text(encoding="utf-8"))
    запись = dict(настройки["bases"][БАЗА])
    запись["gate"] = {**(запись.get("gate") or {}), "mode": "identifiers+names"}
    if адрес is not None:
        запись["url"] = адрес
    (дом / "bases.yaml").write_text(
        yaml.safe_dump({"default": БАЗА, "bases": {БАЗА: запись}}, allow_unicode=True),
        encoding="utf-8",
    )
    (дом / "daemon.yaml").write_text(
        f'port: {ПОРТ}\nreindex_check_hours: 0\ngate_secret: "{secrets.token_hex(32)}"\n',
        encoding="utf-8",
    )
    исходный = рабочий / "bases" / БАЗА
    каталог = дом / "bases" / БАЗА
    каталог.mkdir()
    # `policy.auto.yaml` — авторазметка реиндекса (ADR-0015): без неё во временном доме нет
    # ни справочников людей, ни классов полей, и раздел «люди» показывает ложные открытые ФИО.
    for имя in ("metadata.sqlite", "policy.yaml", "policy.auto.yaml", "recipes.yaml"):
        if (исходный / имя).exists():
            shutil.copy2(исходный / имя, каталог / имя)
    рецепты_путь = каталог / "recipes.yaml"
    рецепты = (
        yaml.safe_load(рецепты_путь.read_text(encoding="utf-8")) if рецепты_путь.exists() else None
    ) or {"version": 1, "recipes": {}}
    рецепты.setdefault("recipes", {})["проба_ки_по_номеру"] = РЕЦЕПТ_ПРОБЫ
    рецепты["recipes"]["проба_ки_путём"] = РЕЦЕПТ_ПРОБЫ_ПУТИ
    рецепты_путь.write_text(yaml.safe_dump(рецепты, allow_unicode=True), encoding="utf-8")
    if перестроить_политику:
        from odata1c.config.loader import load_config
        from odata1c.gate.service import refresh_policy

        refresh_policy(дом, load_config(дом).bases[БАЗА])
    return дом


def остановить_демон(дом: pathlib.Path) -> None:
    subprocess.run(  # noqa: S603 — фиксированная команда собственного пакета
        [sys.executable, "-m", "odata1c", "daemon", "stop", "--home", str(дом)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        env={**os.environ, "PYTHONUTF8": "1"},
        check=False,
    )
    time.sleep(1.5)


@contextlib.asynccontextmanager
async def сессия(дом: pathlib.Path):
    параметры = StdioServerParameters(
        command=sys.executable,
        args=["-m", "odata1c", "mcp", "--home", str(дом)],
        env={**os.environ, "PYTHONUTF8": "1", "PYTHONIOENCODING": "utf-8"},
    )
    async with stdio_client(параметры) as (чтение, запись):
        async with ClientSession(чтение, запись) as сеанс:
            await сеанс.initialize()
            yield сеанс


async def тул(сеанс: ClientSession, имя: str, аргументы: dict) -> dict:
    ответ = await сеанс.call_tool(имя, аргументы, read_timeout_seconds=ТАЙМАУТ)
    текст = "\n".join(ч.text for ч in ответ.content if getattr(ч, "text", None))
    try:
        return json.loads(текст)
    except ValueError:
        return {"error": {"code": "not_json", "message": форма(текст[:80])}}


async def выборка(сеанс, сущность: str, *, фильтр: str | None, поля: list[str], всего: int):
    """Постранично до `всего` записей; `masked_fields` и предупреждения — объединением."""
    записи: list[dict] = []
    замаскированные: set[str] = set()
    предупреждения: set[str] = set()
    пропуск = 0
    while len(записи) < всего:
        аргументы = {"entity": сущность, "select": поля, "top": min(СТРАНИЦА, всего - len(записи))}
        if фильтр:
            аргументы["filter"] = фильтр
        if пропуск:
            аргументы["skip"] = пропуск
        ответ = await тул(сеанс, "odata1c_query", аргументы)
        if "error" in ответ:
            return None, ответ["error"].get("code"), set(), set()
        записи += ответ.get("items", [])
        замаскированные |= set(ответ.get("masked_fields") or [])
        предупреждения |= {п.split(":")[0] for п in ответ.get("warnings") or []}
        if not ответ.get("has_more"):
            break
        пропуск = ответ.get("next_skip") or (пропуск + СТРАНИЦА)
    return записи, None, замаскированные, предупреждения


