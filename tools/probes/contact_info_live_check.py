def форма(текст: str) -> str:
    return re.sub(r"[^\W\d_]", "a", re.sub(r"\d", "9", текст))


def без_токенов(текст: str) -> str:
    return ТОКЕН.sub("", текст)


def строки_значения(поле: str, значение) -> list[tuple[str, str]]:
    """Все строки, которые модель видит в значении поля: для JSON — строковые значения по
    ключам (служебный `type` не в счёт), для XML — атрибуты и текст, иначе — само значение.
    Возвращает пары «путь, строка»."""
    if not isinstance(значение, str) or not значение.strip():
        return []
    текст = значение.strip()
    if ТОКЕН.fullmatch(текст):
        return []
    if текст.startswith("{"):
        try:
            документ = json.loads(текст)
        except ValueError:
            return [(поле, текст)]
        пары: list[tuple[str, str]] = []

        def обойти(x, путь):
            if isinstance(x, dict):
                for ключ, вложенное in x.items():
                    if ключ != "type":
                        обойти(вложенное, f"{путь}.{ключ}")
            elif isinstance(x, list):
                for вложенное in x:
                    обойти(вложенное, путь + "[]")
            elif isinstance(x, str) and x.strip():
                пары.append((путь, x))

        обойти(документ, поле)
        return пары
    if текст.startswith("<"):
        try:
            корень = etree.fromstring(текст.encode("utf-8"))
        except etree.XMLSyntaxError:
            return [(поле, текст)]
        пары = []
        for элемент in корень.iter():
            имя = etree.QName(элемент).localname
            for атрибут, значение_атрибута in элемент.attrib.items():
                if etree.QName(атрибут).localname == "type":
                    continue
                пары.append((f"{поле}<{имя}@{etree.QName(атрибут).localname}>", значение_атрибута))
            if элемент.text and элемент.text.strip():
                пары.append((f"{поле}<{имя}>", элемент.text))
        return пары
    return [(поле, текст)]


def открытые_цифры(строка: dict, поля=ПОЛЯ_ЗНАЧЕНИЯ) -> list[str]:
    """Пути, где вне токенов осталось две и более цифры (часть номера)."""
    пути = []
    for поле in поля:
        for путь, текст in строки_значения(поле, строка.get(поле)):
            if len(re.findall(r"\d", без_токенов(текст))) >= 2:
                пути.append(путь)
    return пути


def открытая_почта(строка: dict) -> list[str]:
    пути = []
    for поле in ("Представление", "Значение", "ЗначенияПолей", "АдресЭП"):
        for путь, текст in строки_значения(поле, строка.get(поле)):
            if "@" in без_токенов(текст):
                пути.append(путь)
    return пути


def открытый_адрес(строка: dict, поля=("Представление", "Значение", "ЗначенияПолей")) -> list[str]:
    """Пути, где открыт адрес: признак адреса в тексте или непустая адресная часть JSON."""
    пути = []
    for поле in поля:
        for путь, текст in строки_значения(поле, строка.get(поле)):
            чистый = без_токенов(текст)
            if not чистый.strip():
                continue
            хвост = путь.split(".", 1)[1] if "." in путь else ""
            ключ = re.sub(r"\[\]", "", хвост.split(".")[0]) if хвост else ""
            if ключ in КЛЮЧИ_АДРЕСА or (
                not хвост and any(р.search(чистый) for р in ПРИЗНАКИ_АДРЕСА.values())
            ):
                пути.append(re.sub(r"\[\]", "[]", путь))
            elif "<" in путь and any(р.search(чистый) for р in ПРИЗНАКИ_АДРЕСА.values()):
                пути.append(путь)
    return пути


