async def путь_владельца(сеанс, итог: dict) -> None:
    """`raw_get` путём `Catalog_Контрагенты(guid'…')/КонтактнаяИнформация`: 1С обслуживает его и
    отдаёт строки табличной части целиком (`$select` к такому пути не применяет). Табличная часть
    навигацией не приходит, и до правки сегмент оставался неразрешённым: строки маскировались как
    запись справочника, без правила строки (Ruling 33) и без правила адресов (Ruling 34)."""
    print("\n=== 4а. raw_get путём владельца: …(guid)/КонтактнаяИнформация ===")
    ки = "Catalog_Контрагенты_КонтактнаяИнформация"
    владельцы: dict[str, str] = {}
    ответ = await тул(
        сеанс,
        "odata1c_query",
        {
            "entity": "Catalog_Контрагенты",
            "select": ["Ref_Key", "ЮрФизЛицо"],
            "filter": "ЮрФизЛицо ne 'ЮрЛицо' and ЮрФизЛицо ne 'ЮрЛицоНеРезидент' and DeletionMark eq false",
            "top": 15,
        },
    )
    for запись in ответ.get("items", []):
        владельцы[запись["Ref_Key"]] = "не_юрлицо"
    for тип, предел in (("Телефон", 15), ("АдресЭлектроннойПочты", 10)):
        записи, ошибка, _, _ = await выборка(
            сеанс, ки, фильтр=f"Тип eq '{тип}'", поля=["Ref_Key"], всего=предел
        )
        for запись in записи or []:
            владельцы.setdefault(запись["Ref_Key"], "любой")

    счёт = Counter()
    сущности = Counter()
    for ключ, вид in владельцы.items():
        ответ = await тул(
            сеанс,
            "odata1c_raw_get",
            {"path": f"Catalog_Контрагенты(guid'{ключ}')/КонтактнаяИнформация"},
        )
        if "error" in ответ:
            счёт[f"ошибка {ответ['error'].get('code')}"] += 1
            continue
        сущности[ответ.get("entity")] += 1
        if any("вне индекса" in п for п in ответ.get("warnings") or []):
            счёт["предупреждение «вне индекса»"] += 1
        for строка in ответ.get("items") or []:
            тип = строка.get("Тип")
            if тип in ("Телефон", "Факс"):
                счёт["телефонов"] += 1
                счёт["телефонов открыто"] += bool(открытые_цифры(строка))
            elif тип == "АдресЭлектроннойПочты":
                счёт["почты"] += 1
                счёт["почты открыто"] += bool(открытая_почта(строка))
            elif тип == "Адрес" and вид == "не_юрлицо":
                счёт["адресов не-юрлиц"] += 1
                счёт["адресов не-юрлиц открыто"] += bool(открытый_адрес(строка))
                счёт["адресов не-юрлиц с открытыми Город/Регион"] += any(
                    без_токенов(str(строка.get(поле) or "")).strip() for поле in ("Город", "Регион")
                )
    print(f"  владельцев {len(владельцы)}, сущность в ответе {dict(сущности)}")
    for метка in (
        "телефонов",
        "телефонов открыто",
        "почты",
        "почты открыто",
        "адресов не-юрлиц",
        "адресов не-юрлиц открыто",
        "адресов не-юрлиц с открытыми Город/Регион",
        "предупреждение «вне индекса»",
    ):
        print(f"  {метка}: {счёт[метка]}")
    for метка, число in счёт.items():
        if метка.startswith("ошибка"):
            print(f"  {метка}: {число}")
    итог["путь_владельца"] = {"владельцев": len(владельцы), "сущности": dict(сущности), **счёт}


