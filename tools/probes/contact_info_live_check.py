def словарь_телефонов(дом: pathlib.Path, итог: dict) -> None:
    """Совет ревьюера: какие значения класса phone длиной от 7 цифр (игла стража) легли во
    временный словарь — только формы, чтобы увидеть мусор вида даты или номера документа."""
    print("\n=== 6. Иглы стража класса phone во временном словаре (формы) ===")
    путь = дом / "gate.sqlite"
    if not путь.exists():
        print("  словаря нет")
        return
    with contextlib.closing(sqlite3.connect(путь)) as соединение:
        строки = соединение.execute("SELECT normalized FROM tokens WHERE type = 'phone'").fetchall()
    длины = Counter()
    подозрительные = Counter()
    for (нормализованное,) in строки:
        if not нормализованное.isdigit() or len(нормализованное) < 7:
            continue
        длины[len(нормализованное)] += 1
        # Мусор: похоже на дату (20xx, 19xx в начале при длине 8 и 14) или не похоже на номер:
        # номер телефона — 7 (местный) … 15 цифр (E.164).
        if len(нормализованное) > 15 or re.fullmatch(r"(19|20)\d{6}(\d{6})?", нормализованное):
            подозрительные[форма(нормализованное)] += 1
    print(
        f"  значений phone длиной ≥ 7: {sum(длины.values())}, по длинам {dict(sorted(длины.items()))}"
    )
    print(f"  подозрительные формы: {dict(подозрительные) or 'нет'}")
    итог["иглы_phone"] = {"по_длинам": dict(длины), "подозрительные": dict(подозрительные)}


