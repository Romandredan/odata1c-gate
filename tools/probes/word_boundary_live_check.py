ТОКЕН_НАЗВАНИЯ = re.compile(r"\[\[(?:org|person):[0-9A-Z]{1,16}\]\]")
ЛЮБОЙ_ТОКЕН = re.compile(r"\[\[[a-z][a-z0-9_]*:[0-9A-Z]{1,16}\]\]")


def форма(текст: str) -> str:
    """Форма окружения без значений: буква → a, цифра → 9, токен → T."""
    текст = ЛЮБОЙ_ТОКЕН.sub("T", текст)
    return "".join("a" if с.isalpha() and с != "T" else "9" if с.isdigit() else с for с in текст)


# Окно вокруг ушедшего участка (итоговое ревью ветки, I-2): `difflib` отдаёт только сам отрезок,
# и `ООО 'Мост'`, `OOO Мост` или «Индивидуальный предприниматель Сидоров» выглядели бы в нём
# одиночным словом — форма собственности и кавычка остаются за краем отрезка.
ОКНО = 40
КАВЫЧКИ_ЛЮБЫЕ = frozenset("\"'«»“”„‟‘’‚‛‹›`<>")
# Форма собственности перед отрезком: сокращённая кириллицей или латиницей либо полная, через
# пробел, точку, дефис или кавычку.
ФОРМА_СЛЕВА = re.compile(
    r"(?:^|[^\w])(?:ооо|оао|зао|пао|ао|ип|нко|ано|фгуп|гуп|муп|тсж|снт|ooo|oao|ao"
    r"|общество с ограниченной ответственностью|индивидуальный предприниматель"
    r"|(?:публичное |закрытое |открытое )?акционерное общество)[^\w]{0,4}$"
)


def _вид_ушедшего(стало: str, слева: str, справа: str) -> str:
    """Вид ушедшего участка по окну: для одиночного слова — есть ли рядом форма собственности или
    кавычка любого вида, для прочего — форма окна (`форма`). Значения не печатаются."""
    if not _голое_слово(normalize_text_with_map(стало)[0].strip()):
        return форма(слева + стало + справа)
    слева_норм = normalize_text_with_map(слева)[0]
    if ФОРМА_СЛЕВА.search(слева_норм):
        return "одиночное слово, рядом форма собственности"
    соседи = слева.rstrip()[-1:] + справа.lstrip()[:1]
    if any(символ in КАВЫЧКИ_ЛЮБЫЕ for символ in соседи):
        return "одиночное слово, рядом кавычка"
    return "одиночное слово"


def ушедшие_из_замены(до: str, после: str) -> tuple[list[str], int]:
    """Участки, где «до» стоял токен названия, а «после» — текст; и число обратных участков.
    Вид участка определяется по окну в строке «после» (`ОКНО` символов слева и справа,
    `_вид_ушедшего`)."""
    ушли: list[str] = []
    обратных = 0
    опкоды = difflib.SequenceMatcher(None, до, после, autojunk=False).get_opcodes()
    for вид, а1, а2, б1, б2 in опкоды:
        if вид != "replace":
            continue
        было, стало = до[а1:а2], после[б1:б2]
        if ТОКЕН_НАЗВАНИЯ.fullmatch(было) and not ЛЮБОЙ_ТОКЕН.search(стало):
            слева = ЛЮБОЙ_ТОКЕН.sub("T", после[max(0, б1 - ОКНО) : б1])
            справа = ЛЮБОЙ_ТОКЕН.sub("T", после[б2 : б2 + ОКНО])
            ушли.append(_вид_ушедшего(стало, слева, справа))
        elif ТОКЕН_НАЗВАНИЯ.fullmatch(стало) and not ЛЮБОЙ_ТОКЕН.search(было):
            обратных += 1
    return ушли, обратных


def _классы_токенов(текст: str) -> list[str]:
    """Последовательность классов токенов названия (`org`/`person`) в порядке появления — основа
    для `_токен_в_токен`, а не посимвольный `diff`."""
    return [м.group(0)[2 : м.group(0).index(":")] for м in ТОКЕН_НАЗВАНИЯ.finditer(текст)]


def _токен_в_токен(до: str, после: str) -> int:
    """Число мест, где токен названия того же класса стоит в тексте и «до», и «после» — сменился
    только номер (у каждого прогона `--compare` свой секрет гейта, Ruling 115, задача 5).

    Сравнение идёт по последовательности классов (`org`/`person`), а не по участку `replace`
    посимвольного `difflib`, как в `ушедшие_из_замены`: сам токен меняет длину вместе с номером, а
    общие для обоих текстов `[[type:` и `]]` обычно и так совпадают буквально и уходят в «равные»
    участки — разный номер тогда остаётся куском без квадратных скобок, `ТОКЕН_НАЗВАНИЯ.fullmatch`
    на нём не срабатывает, и место осталось бы вообще не учтённым: ни ушедшим, ни обратным, ни
    показанным этим счётчиком."""
    опкоды = difflib.SequenceMatcher(
        None, _классы_токенов(до), _классы_токенов(после), autojunk=False
    ).get_opcodes()
    return sum(а2 - а1 for вид, а1, а2, б1, б2 in опкоды if вид == "equal")


def строки(данные):
    if isinstance(данные, str):
        yield данные
    elif isinstance(данные, dict):
        for ключ, значение in данные.items():
            yield ключ
            yield from строки(значение)
    elif isinstance(данные, list):
        for элемент in данные:
            yield from строки(элемент)


class Счёт:
    """Токены названий в ответах раздела: внутри слова и отдельным словом."""

    def __init__(self) -> None:
        self.ответов = 0
        self.строк = 0
        self.внутри = 0
        self.отдельно = 0
        self.guard_replaced = 0
        self.формы: Counter[str] = Counter()

    def учесть(self, ответ: dict) -> None:
        self.ответов += 1
        if any(str(п).startswith("guard_replaced") for п in ответ.get("warnings") or []):
            self.guard_replaced += 1
        for строка in строки(ответ):
            self.строк += 1
            for найдено in ТОКЕН_НАЗВАНИЯ.finditer(строка):
                слева = строка[найдено.start() - 1 : найдено.start()]
                справа = строка[найдено.end() : найдено.end() + 1]
                if слева.isalpha() or справа.isalpha():
                    self.внутри += 1
                    окно = строка[max(0, найдено.start() - 4) : найдено.end() + 4]
                    self.формы[форма(окно)] += 1
                else:
                    self.отдельно += 1

    def итог(self) -> dict:
        return {
            "ответов": self.ответов,
            "строк": self.строк,
            "токенов_внутри_слова": self.внутри,
            "токенов_отдельным_словом": self.отдельно,
            "ответов_с_guard_replaced": self.guard_replaced,
            "формы_внутри_слова": dict(self.формы.most_common(10)),
        }


def собрать_дом(рабочий: pathlib.Path) -> pathlib.Path:
    """Временный домашний каталог: запись базы, индекс, политика и рецепты — копией из рабочего
    дома; уровень гейта — `identifiers+names`; словарь пустой, секрет свой."""
    дом = pathlib.Path(tempfile.mkdtemp(prefix="odata1c-wb-"))
    for имя in ("bases", "logs"):
        (дом / имя).mkdir()
    настройки = yaml.safe_load((рабочий / "bases.yaml").read_text(encoding="utf-8"))
    запись = dict(настройки["bases"][БАЗА])
    запись["gate"] = {**(запись.get("gate") or {}), "mode": "identifiers+names"}
    (дом / "bases.yaml").write_text(
        yaml.safe_dump({"default": БАЗА, "bases": {БАЗА: запись}}, allow_unicode=True),
        encoding="utf-8",
    )
    (дом / "daemon.yaml").write_text(
        f'port: {ПОРТ}\nreindex_check_hours: 0\ngate_secret: "{secrets.token_hex(32)}"\n',
        encoding="utf-8",
    )
    исходный = рабочий / "bases" / БАЗА
    каталог = дом / "bases" / БАЗА
    каталог.mkdir()
    for имя in ("metadata.sqlite", "policy.yaml", "policy.auto.yaml", "recipes.yaml"):
        if (исходный / имя).exists():
            shutil.copy2(исходный / имя, каталог / имя)
    return дом


def окружение(src: str | None) -> dict[str, str]:
    env = {**os.environ, "PYTHONUTF8": "1", "PYTHONIOENCODING": "utf-8"}
    if src:
        env["PYTHONPATH"] = src + os.pathsep + env.get("PYTHONPATH", "")
    return env


def остановить_демон(дом: pathlib.Path, src: str | None) -> None:
    subprocess.run(  # noqa: S603 — фиксированная команда собственного пакета
        [sys.executable, "-m", "odata1c", "daemon", "stop", "--home", str(дом)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        env=окружение(src),
        check=False,
    )
    time.sleep(1.5)


@contextlib.asynccontextmanager
async def сессия(дом: pathlib.Path, src: str | None):
    параметры = StdioServerParameters(
        command=sys.executable,
        args=["-m", "odata1c", "mcp", "--home", str(дом)],
        env=окружение(src),
    )
    async with stdio_client(параметры) as (чтение, запись):
        async with ClientSession(чтение, запись) as сеанс:
            await сеанс.initialize()
            yield сеанс


async def тул(сеанс: ClientSession, имя: str, аргументы: dict) -> dict:
    ответ = await сеанс.call_tool(имя, аргументы, read_timeout_seconds=ТАЙМАУТ)
    текст = "\n".join(ч.text for ч in ответ.content if getattr(ч, "text", None))
    try:
        return json.loads(текст)
    except ValueError:
        return {"error": {"code": "not_json"}}


async def постранично(
    сеанс,
    сущность: str,
    поля: list[str],
    всего: int,
    счёт: Счёт | None,
    *,
    тексты: dict[tuple[str, str, str], str] | None = None,
    поле: str | None = None,
):
    """До `всего` записей страницами; каждый ответ — в `счёт`. Если передан `тексты` вместе с
    `поле` — значение этого поля каждой записи дополнительно попадает в словарь по ключу
    (сущность, поле, Ref_Key): в памяти, для сравнения до/после в режиме `--compare`, на диск
    не пишется. Возвращает число записей или код ошибки."""
    получено = 0
    пропуск = 0
    while получено < всего:
        аргументы = {"entity": сущность, "select": поля, "top": min(СТРАНИЦА, всего - получено)}
        if пропуск:
            аргументы["skip"] = пропуск
        ответ = await тул(сеанс, "odata1c_query", аргументы)
        if "error" in ответ:
            return ответ["error"].get("code") or "error"
        if счёт is not None:
            счёт.учесть(ответ)
        if тексты is not None and поле:
            for запись in ответ.get("items") or []:
                значение = запись.get(поле)
                ref = запись.get("Ref_Key")
                if isinstance(значение, str) and isinstance(ref, str):
                    тексты[(сущность, поле, ref)] = значение
        получено += len(ответ.get("items") or [])
        if not ответ.get("has_more"):
            break
        пропуск = ответ.get("next_skip") or (пропуск + СТРАНИЦА)
    return получено


async def свободный_текст(
    сеанс, тексты: dict[tuple[str, str, str], str] | None = None
) -> tuple[Счёт, dict]:
    """Раздел «свободный текст»: те же сущности и поля, что в обычном прогоне (`СВОБОДНЫЙ_ТЕКСТ`).
    С переданным `тексты` каждое значение поля дополнительно оседает в нём по ключу
    (сущность, поле, Ref_Key) — для сравнения до/после в режиме `--compare`."""
    текст = Счёт()
    по_сущностям = {}
    for сущность, поля in СВОБОДНЫЙ_ТЕКСТ:
        for поле in поля:
            по_сущностям[f"{сущность}.{поле}"] = await постранично(
                сеанс,
                сущность,
                ["Ref_Key", поле],
                СВОБОДНЫЙ_ТЕКСТ_ЗАПИСЕЙ,
                текст,
                тексты=тексты,
                поле=поле,
            )
    return текст, по_сущностям


async def прогон(сеанс, итог: dict) -> None:
    наполнение = {}
    for сущность in НАПОЛНЕНИЕ:
        наполнение[сущность] = await постранично(
            сеанс, сущность, ["Ref_Key", "Description"], НАПОЛНЕНИЕ_ЗАПИСЕЙ, None
        )
    итог["наполнение_словаря"] = наполнение
    print("словарь наполнен:", наполнение)

    рецепты = Счёт()
    ответ = await тул(сеанс, "odata1c_recipe", {})
    рецепты.учесть(ответ)
    итог["перечень_рецептов"] = {**рецепты.итог(), "ошибка": (ответ.get("error") or {}).get("code")}

    индекс = Счёт()
    for запрос in ЗАПРОСЫ_ИНДЕКСА:
        индекс.учесть(await тул(сеанс, "odata1c_find_entity", {"query": запрос, "limit": 20}))
    итог["find_entity"] = индекс.итог()

    текст, по_сущностям = await свободный_текст(сеанс)
    итог["свободный_текст"] = {**текст.итог(), "записей": по_сущностям}


async def прогон_сравнения(дом: pathlib.Path, src: str | None) -> tuple[dict, dict]:
    """Один прогон раздела «свободный текст» для режима `--compare`: наполняет словарь так же, как
    обычный прогон, затем собирает свободный текст, держа значения полей в памяти по ключу
    (сущность, поле, Ref_Key). Возвращает счётчики раздела (как в обычном прогоне) и словарь
    текстов — для сравнения со вторым прогоном; на диск текст не попадает."""
    тексты: dict[tuple[str, str, str], str] = {}
    async with сессия(дом, src) as сеанс:
        наполнение = {}
        for сущность in НАПОЛНЕНИЕ:
            наполнение[сущность] = await постранично(
                сеанс, сущность, ["Ref_Key", "Description"], НАПОЛНЕНИЕ_ЗАПИСЕЙ, None
            )
        счёт, по_сущностям = await свободный_текст(сеанс, тексты)
    return {**счёт.итог(), "наполнение_словаря": наполнение, "записей": по_сущностям}, тексты


def сравнить(
    тексты_до: dict[tuple[str, str, str], str], тексты_после: dict[tuple[str, str, str], str]
) -> dict:
    """Сравнение свободного текста «до» и «после» по одинаковым записям (сущность, поле,
    Ref_Key) — только для ключей, дошедших до обоих прогонов (номер токена в написании роли не
    играет, сопоставление идёт по значению поля). Реальные значения в результат не попадают —
    только счётчики и формы ушедших участков."""
    сопоставлено = 0
    ушло_всего = 0
    обратных_всего = 0
    токен_в_токен_всего = 0
    формы: Counter[str] = Counter()
    for ключ, до in тексты_до.items():
        после = тексты_после.get(ключ)
        if после is None:
            continue
        сопоставлено += 1
        ушли, обратных = ушедшие_из_замены(до, после)
        ушло_всего += len(ушли)
        обратных_всего += обратных
        токен_в_токен_всего += _токен_в_токен(до, после)
        формы.update(ушли)
    return {
        "сопоставлено_записей": сопоставлено,
        "не_сопоставлено_до": len(тексты_до) - сопоставлено,
        "не_сопоставлено_после": len(тексты_после) - сопоставлено,
        "ушло_из_замены": ушло_всего,
        "формы_ушедших": dict(формы.most_common(10)),
        "участков_обратного_направления": обратных_всего,
        "участков_токен_в_токен": токен_в_токен_всего,
    }


async def прогон_сравнения_с_домом(
    рабочий: pathlib.Path, src: str | None, метка: str
) -> tuple[dict, dict]:
    """`прогон_сравнения` во временном доме, который создаётся и удаляется здесь же; демон
    останавливается и дом удаляется до возврата — так второй прогон режима `--compare` не
    застаёт демон первого работающим на том же порту (`ПОРТ`)."""
    дом = собрать_дом(рабочий)
    print(f"сравнение [{метка}]: временный дом создан, порт демона {ПОРТ}")
    try:
        return await прогон_сравнения(дом, src)
    finally:
        остановить_демон(дом, src)
        shutil.rmtree(дом, ignore_errors=True)
        print(f"сравнение [{метка}]: временный дом удалён: {not дом.exists()}")


async def main() -> int:
    разбор = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    разбор.add_argument("--label", required=True, help="метка прогона: before / after")
    разбор.add_argument(
        "--home",
        default=str(pathlib.Path.home() / ".claude" / "odata1c"),
        help="рабочий домашний каталог (только чтение)",
    )
    группа = разбор.add_mutually_exclusive_group()
    группа.add_argument("--src", help="каталог src другой версии кода (через PYTHONPATH)")
    группа.add_argument(
        "--compare",
        metavar="SRC_DO",
        help=(
            "режим сравнения: два прогона раздела «свободный текст» подряд — сперва код из этого "
            "каталога, затем текущий код; сравнение попарно по (сущность, поле, Ref_Key), реальный "
            "текст на диск и в --out не попадает"
        ),
    )
    разбор.add_argument("--out", help="куда сохранить итог JSON (счётчики, без значений)")
    аргументы = разбор.parse_args()

    рабочий = pathlib.Path(аргументы.home)
    итог: dict = {"label": аргументы.label}

    if аргументы.compare:
        счёт_до, тексты_до = await прогон_сравнения_с_домом(рабочий, аргументы.compare, "до")
        счёт_после, тексты_после = await прогон_сравнения_с_домом(рабочий, None, "после")
        итог["свободный_текст_до"] = счёт_до
        итог["свободный_текст_после"] = счёт_после
        итог["сравнение"] = сравнить(тексты_до, тексты_после)
    else:
        дом = собрать_дом(рабочий)
        print(f"прогон {аргументы.label}: временный дом создан, порт демона {ПОРТ}")
        try:
            async with сессия(дом, аргументы.src) as сеанс:
                await прогон(сеанс, итог)
        finally:
            остановить_демон(дом, аргументы.src)
            shutil.rmtree(дом, ignore_errors=True)
            print(f"временный дом удалён: {not дом.exists()}")

    print(json.dumps(итог, ensure_ascii=False, indent=2))
    if аргументы.out:
        pathlib.Path(аргументы.out).write_text(
            json.dumps(итог, ensure_ascii=False, indent=2), encoding="utf-8"
        )
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
