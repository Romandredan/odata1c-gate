def _можно_удалять(хвост: str) -> bool:
    """DELETE посредник пропускает ТОЛЬКО по записи регистра штрихкодов с маркером этого
    прогона: ни по объектам (у них удаления нет вовсе — только пометка), ни по чужим записям."""
    return хвост.startswith(f"{РЕГИСТР}(") and ШТРИХКОД in хвост


def _доп_разрешено(метод: str, хвост: str) -> bool:
    """POST/PATCH записи независимого регистра сведений — сущность вне фиксированного набора
    `Посредник1С` (`Catalog_Номенклатура`/`Document_ПересчетТоваров`). Тот же приём, что у
    пробы P9 (`tools/probes/p9_write_forms.py`): POST — только создание в самом наборе регистра,
    PATCH — только по записи С МАРКЕРОМ этого прогона в ключе."""
    if метод == "POST":
        return хвост == РЕГИСТР
    if метод == "PATCH":
        return хвост.startswith(f"{РЕГИСТР}(") and ШТРИХКОД in хвост
    return False


def _литерал_ключа(поле: str, значение: str) -> str:
    if поле.endswith("_Key"):
        return f"guid'{значение}'"
    return "'" + str(значение).replace("'", "''") + "'"


ПОЛЯ_ЧАСТИ = ("LineNumber", "КодЯзыка", "НаименованиеПолное")


def _строки_для_сравнения(строки: list[dict] | None) -> list[dict]:
    """Строки табличной части «Представления» только своими полями (без служебного мусора вроде
    `Ref_Key` строки в форме 1С) — для сравнения отправленного и перечитанного массива;
    сортировка по `LineNumber` — порядок ответа 1С не гарантирован."""
    строки_к_сравнению = [
        {поле: строка.get(поле) for поле in ПОЛЯ_ЧАСТИ} for строка in (строки or [])
    ]
    for строка in строки_к_сравнению:
        # 1С отдаёт `LineNumber` строкой, шлюзу он отправляется целым — сравниваем как текст.
        строка["LineNumber"] = str(строка.get("LineNumber"))
    return sorted(строки_к_сравнению, key=lambda строка: строка["LineNumber"])


def _добавить_базу_без_удаления_регистра(дом: pathlib.Path, рабочий: pathlib.Path) -> None:
    """Четвёртая запись во временном `bases.yaml` — копия `trade_dev` с выключенным
    `independent_register_delete` (умолчание роли `dev` — `True`, здесь оно перекрыто явно).
    `собрать_дом` (m2_live_check) создаёт только три свои записи (сама база, `_ro`, `_deny`);
    у M3b другая ось отказа (разрешение на регистр, не на поле объекта), поэтому запись
    дописывается тем же приёмом, каким `собрать_дом` строит остальные три."""
    путь_настроек = дом / "bases.yaml"
    настройки = yaml.safe_load(путь_настроек.read_text(encoding="utf-8"))
    базовая = dict(настройки["bases"][БАЗА])
