# --- раздел «часть_update»: замена ТЧ целиком через update (§5.2) ------------------------------


async def _строки_объекта(к: Контекст) -> list[dict] | None:
    ответ = await к.A.вызвать(
        "odata1c_get", {"entity": СПРАВОЧНИК, "key": к.C, "select": ["Ref_Key", ЧАСТЬ]}
    )
    объект = ответ.get("item") or {}
    return объект.get(ЧАСТЬ)


async def _update_часть(к: Контекст, строки: list[dict], метка_варианта: str) -> dict:
    итог = к.итог
    подготовка = await к.A.вызвать(
        "odata1c_update",
        {"entity": СПРАВОЧНИК, "key": к.C, "data": {ЧАСТЬ: строки}},
        категория="подготовка",
    )
    итог.проверить(
        f"{метка_варианта}: подготовка → pending_id",
        "pending_id" in подготовка,
        код(подготовка) or "",
    )
    if "pending_id" not in подготовка:
        return {}
    строка_превью = next(
        (с for с in (подготовка.get("preview") or []) if с.get("field") == ЧАСТЬ), None
    )
    rows = (строка_превью or {}).get("rows") or {}
    итог.заметка(
        f"{метка_варианта}: rows changed={len(rows.get('changed', []))} "
        f"added={len(rows.get('added', []))} removed={len(rows.get('removed', []))} "
        f"before_count={rows.get('before_count')} after_count={rows.get('after_count')}"
    )
    ожидаемая_сводка = f"строк было {rows.get('before_count')}, станет {rows.get('after_count')}"
    итог.проверить(
        f"{метка_варианта}: превью несёт rows.changed/added/removed",
        {"changed", "added", "removed", "before_count", "after_count"} <= set(rows),
    )
    итог.проверить(
        f"{метка_варианта}: summary — «{ожидаемая_сводка}»",
        (строка_превью or {}).get("summary") == ожидаемая_сводка,
        str((строка_превью or {}).get("summary")),
    )
    ответ = await выполнить(к, к.A, подготовка, метка_варианта)
    if "commit_id" not in ответ:
        return ответ
    предупреждения = ответ.get("warnings") or []
    итог.проверить(
        f"{метка_варианта}: commit без предупреждений о расхождении",
        not предупреждения,
        "; ".join(предупреждения)[:160],
    )
    после = await _строки_объекта(к)
    итог.проверить(
        f"{метка_варианта}: перечитанный объект равен отправленному массиву",
        _строки_для_сравнения(после) == _строки_для_сравнения(строки),
    )
    return ответ


async def раздел_часть_update(к: Контекст) -> None:
    заголовок("2. Замена табличной части целиком через update (§5.2)")
    к.итог.раздел = "часть_update"
    итог = к.итог
    if not к.C:
        итог.проверить("есть маркерный элемент справочника (раздел «строки»)", False)
        return

    исходные = await _строки_объекта(к)
    итог.проверить(
        "исходная табличная часть — 2 строки (из раздела «строки»)", len(исходные or []) == 2
    )
    if not исходные or len(исходные) != 2:
        return

    # Шаг 1: 2 строки -> 3 строки. Строка 1 меняется, строка 2 остаётся как есть (не должна
    # попасть в rows.changed), строка 3 — новая (rows.added). При плотной сквозной нумерации
    # LineNumber 1..n (правило §5.1, RowsDiff по номеру — src/odata1c/write/rows_diff.py)
    # rows.added и rows.removed не могут быть непустыми одновременно за один вызов: новый
    # набор номеров — надмножество {1..before_count} только когда after_count > before_count
    # (тогда added — «хвост», removed — пусто), и наоборот. Это не дефект скрипта и не дефект
    # шлюза, а прямое следствие того, что RowsDiff сопоставляет строки по номеру (rows_diff.py,
    # docstring `RowsDiff`) — граница задокументирована в отчёте, а не подогнана под ожидание.
    строка_2_исходная = next((с for с in исходные if с.get("LineNumber") in (2, "2")), исходные[1])
    рост = [
        {"LineNumber": 1, "КодЯзыка": "m3", "НаименованиеПолное": f"{к.метка} строка A изменена"},
        {
            "LineNumber": 2,
            **{к2: v for к2, v in строка_2_исходная.items() if к2 != "LineNumber"},
        },
        {"LineNumber": 3, "КодЯзыка": "m3", "НаименованиеПолное": f"{к.метка} строка C добавлена"},
    ]
    ответ_роста = await _update_часть(к, рост, "часть_update: 2→3 строки (changed+added)")
    если_рост_выполнен = "commit_id" in ответ_роста

    # Шаг 2: 3 строки -> 2 строки, без изменения содержимого первых двух — чистая демонстрация
    # rows.removed (третья строка убрана целиком, ни одного изменённого поля у оставшихся).
    ответ_убыли: dict = {}
    if если_рост_выполнен:
        убыль = [dict(рост[0]), dict(рост[1])]
        ответ_убыли = await _update_часть(к, убыль, "часть_update: 3→2 строки (removed)")

    # Undo в обратном хронологическом порядке: сначала откатывается более поздняя запись.
    if "commit_id" in ответ_убыли:
        откат = await к.A.вызвать(
            "odata1c_undo", {"commit_id": ответ_убыли["commit_id"]}, категория="undo"
        )
        итог.проверить("undo (3→2): подготовлен", "pending_id" in откат, код(откат) or "")
        if "pending_id" in откат:
            await выполнить(к, к.A, откат, "undo часть_update (3→2)")

    if если_рост_выполнен:
        откат2 = await к.A.вызвать(
            "odata1c_undo", {"commit_id": ответ_роста["commit_id"]}, категория="undo"
        )
        итог.проверить("undo (2→3): подготовлен", "pending_id" in откат2, код(откат2) or "")
        if "pending_id" in откат2:
            ответ2 = await выполнить(к, к.A, откат2, "undo часть_update (2→3)")
            итог.заметка(
                "живой факт: undo нормализованных строк (LineNumber целым, без служебных "
                "полей — src/odata1c/write/service.py::_строки_отката) принят 1С — "
                f"commit_id отката {'получен' if 'commit_id' in ответ2 else 'НЕ получен'}"
            )
            if "commit_id" in ответ2:
                после_undo = await _строки_объекта(к)
                итог.проверить(
                    "после двойного undo объект равен исходному (старому) массиву",
                    _строки_для_сравнения(после_undo) == _строки_для_сравнения(исходные),
                )
    к.итог.заметка(
        "литерал класса contact/dob в поле строки табличной части: не проверено — «Представления» "
        "не несёт такого поля (КодЯзыка/НаименованиеПолное без класса гейта); второй маркерный "
        "объект ради одной проверки этот прогон не создаёт"
    )


# --- раздел «регистр»: независимый регистр сведений (§5.4) --------------------------------------


async def раздел_регистр(к: Контекст) -> None:
    заголовок("3. Независимый регистр сведений — create/update/delete_record/undo (§5.4)")
    к.итог.раздел = "регистр"
    итог = к.итог
    if not к.C:
        итог.проверить("есть маркерный элемент справочника (раздел «строки»)", False)
        return

    описание = await к.A.вызвать(
        "odata1c_describe_entity", {"entity": РЕГИСТР, "response_format": "json"}
    )
    try:
        описание = json.loads(описание) if isinstance(описание, str) else описание
    except ValueError:
        описание = {}
    ключевые_поля = list(описание.get("key_fields") or [])
    итог.проверить("у регистра есть key_fields", bool(ключевые_поля), f"{ключевые_поля}")
    к.итог.сведения["регистр_key_fields"] = ключевые_поля
    if not ключевые_поля:
        return

    значения = {
        "Штрихкод": ШТРИХКОД,
        "Номенклатура_Key": к.C,
        "Характеристика_Key": ПУСТОЙ_GUID,
        "Упаковка_Key": ПУСТОЙ_GUID,
    }
    ключ = {поле: значения[поле] for поле in ключевые_поля if поле in значения}
    итог.проверить(
        "ключ регистра собран по всем key_fields",
        len(ключ) == len(ключевые_поля),
        f"{sorted(ключ)} vs {sorted(ключевые_поля)}",
    )

    # --- живой факт I-3: прямое чтение несуществующей записи, ДО того как её создал этот прогон.
    сегменты_ключа = (f"{поле}={_литерал_ключа(поле, значения[поле])}" for поле in ключевые_поля)
    путь_ключа = f"{РЕГИСТР}({','.join(сегменты_ключа)})"
    статус_прямой, тело_прямой = к.прямой.запрос("GET", путь_ключа)
    платформенный_код = None
    if isinstance(тело_прямой, dict):
        платформенный_код = (тело_прямой.get("odata.error") or {}).get("code")
    пояснение = (
        "есть код «9» — «Экземпляр сущности не найден»"
        if платформенный_код == "9"
        else "кода «9» нет — 404 без кода платформы"
    )
    итог.заметка(
        "живой факт (I-3): прямой GET несуществующей записи регистра до создания — "
        f"HTTP {статус_прямой}, код платформы 1С в теле: {платформенный_код!r} ({пояснение})"
    )
    к.итог.сведения["регистр_i3_прямой_get"] = {
        "http": статус_прямой,
        "platform_code": платформенный_код,
    }

    # --- 1. odata1c_create → commit → odata1c_get по ключу -------------------------------------
    получено_до = к.посредник.счёт["GET"]
    подготовка = await к.A.вызвать(
        "odata1c_create", {"entity": РЕГИСТР, "data": значения}, категория="подготовка"
    )
    итог.проверить(
        "create записи регистра: подготовка → pending_id",
        "pending_id" in подготовка,
        код(подготовка) or "",
    )
    итог.проверить(
        "create записи регистра: подготовка сделала ровно один GET (проверка record_exists)",
        к.посредник.счёт["GET"] - получено_до == 1,
        f"{к.посредник.счёт['GET'] - получено_до}",
    )
    if "pending_id" not in подготовка:
        return
    ответ_create = await выполнить(к, к.A, подготовка, "create записи регистра")
    if "commit_id" not in ответ_create:
        итог.проверить("запись регистра создана", False, код(ответ_create) or "")
        return
    ключ_ответа = ответ_create.get("key") or ключ
    к.итог.сведения["регистр_создана"] = True

    прочитано = await к.A.вызвать("odata1c_get", {"entity": РЕГИСТР, "key": ключ_ответа})
    итог.проверить(
        "odata1c_get по полному ключу находит созданную запись",
        код(прочитано) is None and bool(прочитано.get("item")),
        код(прочитано) or "",
    )

    # --- 2. повторный create тем же ключом → record_exists, без роста числа записей -------------
    записей_до = к.посредник.записи()
    повтор = await к.A.вызвать("odata1c_create", {"entity": РЕГИСТР, "data": значения})
    итог.проверить(
        "повторный create тем же ключом — record_exists",
        код(повтор) == "record_exists",
        код(повтор) or "",
    )
    итог.проверить(
        "повторный create: в 1С не ушло ни одного запроса записи",
        к.посредник.записи() == записей_до,
        f"{к.посредник.записи() - записей_до}",
    )

    # --- отказы (не зависят от текущего состояния записи) --------------------------------------
    отказ_пометка = await к.A.вызвать(
        "odata1c_mark_for_deletion", {"entity": РЕГИСТР, "key": ключ_ответа}
    )
    итог.проверить(
        "mark_for_deletion записи регистра — params_invalid",
        код(отказ_пометка) == "params_invalid",
        код(отказ_пометка) or "",
    )

    отказ_флага = await к.A.вызвать(
        "odata1c_delete_record",
        {"entity": РЕГИСТР, "key": ключ_ответа, "base": БАЗА_РЕГИСТР_ЗАПРЕТ},
    )
    итог.проверить(
        "delete_record на базе с independent_register_delete: false — permission_denied",
        код(отказ_флага) == "permission_denied",
        код(отказ_флага) or "",
    )

    описание_зависимого = await к.A.вызвать(
        "odata1c_describe_entity", {"entity": ЗАВИСИМЫЙ_РЕГИСТР, "response_format": "json"}
    )
    if код(описание_зависимого) is not None:
        итог.заметка(
            f"регистр «{ЗАВИСИМЫЙ_РЕГИСТР}» не найден в индексе — проверка create в зависимый "
            "регистр пропущена (замените имя на существующий AccumulationRegister_* этой базы)"
        )
    else:
        отказ_зависимый = await к.A.вызвать(
            "odata1c_create", {"entity": ЗАВИСИМЫЙ_РЕГИСТР, "data": {}}
        )
        итог.проверить(
            f"create в зависимый регистр «{ЗАВИСИМЫЙ_РЕГИСТР}» — permission_denied",
            код(отказ_зависимый) == "permission_denied",
            код(отказ_зависимый) or "",
        )

    # --- 3. update ресурса записи → commit → перечитывание --------------------------------------
    образец = await к.A.вызвать(
        "odata1c_query",
        {
            "entity": РЕГИСТР,
            "filter": f"Характеристика_Key ne guid'{ПУСТОЙ_GUID}'",
            "select": ["Характеристика_Key"],
            "top": 1,
        },
    )
    образцы = образец.get("items") or []
    образец_характеристики = образцы[0].get("Характеристика_Key") if образцы else None
    новая_характеристика = образец_характеристики or ПУСТОЙ_GUID
    подготовка_update = await к.A.вызвать(
        "odata1c_update",
        {
            "entity": РЕГИСТР,
            "key": ключ_ответа,
            "data": {"Характеристика_Key": новая_характеристика},
        },
        категория="подготовка",
    )
    итог.проверить(
        "update ресурса записи регистра: подготовка → pending_id",
        "pending_id" in подготовка_update,
        код(подготовка_update) or "",
    )
    ответ_update: dict = {}
    if "pending_id" in подготовка_update:
        ответ_update = await выполнить(к, к.A, подготовка_update, "update ресурса регистра")
        if "commit_id" in ответ_update:
            перечитано = await к.A.вызвать("odata1c_get", {"entity": РЕГИСТР, "key": ключ_ответа})
            итог.проверить(
                "после update перечитанный ресурс изменился",
                (перечитано.get("item") or {}).get("Характеристика_Key") == новая_характеристика,
            )

    # --- 4. delete_record → commit → odata1c_get → object_not_found -----------------------------
    подготовка_delete = await к.A.вызвать(
        "odata1c_delete_record", {"entity": РЕГИСТР, "key": ключ_ответа}, категория="подготовка"
    )
    итог.проверить(
        "delete_record: подготовка → pending_id",
        "pending_id" in подготовка_delete,
        код(подготовка_delete) or "",
    )
    ответ_delete: dict = {}
    if "pending_id" in подготовка_delete:
        показ_после = (подготовка_delete.get("preview") or {}).get("after")
        итог.проверить(
            "превью delete_record: after — «записи не будет»", показ_после == "записи не будет"
        )
        ответ_delete = await выполнить(к, к.A, подготовка_delete, "delete_record")
        if "commit_id" in ответ_delete:
            проверка_get = await к.A.вызвать("odata1c_get", {"entity": РЕГИСТР, "key": ключ_ответа})
            итог.проверить(
                "после delete_record odata1c_get — object_not_found",
                код(проверка_get) == "object_not_found",
                код(проверка_get) or "запись всё ещё видна",
            )

    # --- 5. undo каждой из трёх операций, в обратном хронологическом порядке --------------------
    async def откатить_и_сверить(commit_id: str | None, метка: str) -> dict:
        if not commit_id:
            итог.проверить(f"{метка}: есть что откатывать", False)
            return {}
        откат = await к.A.вызвать("odata1c_undo", {"commit_id": commit_id}, категория="undo")
        итог.проверить(f"{метка}: undo подготовлен", "pending_id" in откат, код(откат) or "")
        if "pending_id" not in откат:
            return {}
        ответ = await выполнить(к, к.A, откат, метка)
        if "commit_id" in ответ:
            запись_журнала = к.журнал(commit_id)
            итог.проверить(
                f"{метка}: журнал отмечает исходную запись откаченной этим undo",
                bool(запись_журнала) and запись_журнала.undone_by == ответ["commit_id"],
            )
        return ответ

    await откатить_и_сверить(ответ_delete.get("commit_id"), "undo delete_record (воссоздание)")
    await откатить_и_сверить(ответ_update.get("commit_id"), "undo update (прежний ресурс)")
    финальный_undo = await откатить_и_сверить(
        ответ_create.get("commit_id"), "undo create (физическое удаление)"
    )
    if "commit_id" in финальный_undo:
        проверка_финал = await к.A.вызвать("odata1c_get", {"entity": РЕГИСТР, "key": ключ_ответа})
        итог.проверить(
            "после отката всей цепочки запись регистра снова не существует",
            код(проверка_финал) == "object_not_found",
            код(проверка_финал) or "запись видна",
        )


# --- уборка -------------------------------------------------------------------------------------


def _очистить_регистр(к: Контекст, ключевые_поля: list[str]) -> dict:
    """DELETE остатков записи регистра по штрихкоду-маркеру, напрямую через посредник (белый
    список `_можно_удалять` пропускает путь с этим маркером) — до общей уборки объектов
    (`уборка` из `m2_live_check` о регистрах ничего не знает: она чистит только
    `Catalog_Номенклатура`/`Document_ПересчетТоваров`)."""
    остатки = к.прямой.выборка(РЕГИСТР, {"$filter": f"Штрихкод eq '{ШТРИХКОД}'"}) or []
    статусы = []
    for строка in остатки:
        части_ключа = (
            f"{поле}={_литерал_ключа(поле, строка[поле])}"
            for поле in ключевые_поля
            if поле in строка
        )
        статус, _ = к.прямой.запрос("DELETE", f"{РЕГИСТР}({','.join(части_ключа)})")
        статусы.append(статус)
        print(f"  DELETE остаток регистра: HTTP {статус}", flush=True)
    if not остатки:
        print("  регистр: остатков по маркеру нет", flush=True)
    return {"остатков_было": len(остатки), "delete_статусы": статусы}


# --- прогон ---------------------------------------------------------------------------------


async def прогон(к: Контекст, нужен) -> None:
    начало = time.monotonic()
    async with через_лаунчер(к, "odata1c-m3b-acceptance") as A:
        к.A = A
        к.итог.сведения["старт_лаунчера_и_демона_с"] = round(time.monotonic() - начало, 2)
        к.итог.заметка(f"лаунчер и демон подняты за {time.monotonic() - начало:.2f} с")
        if нужен("строки") or нужен("часть_update") or нужен("регистр"):
            await раздел_строки(к)
        if нужен("часть_update"):
            await раздел_часть_update(к)
        if нужен("регистр"):
            await раздел_регистр(к)


async def main() -> int:
    разбор = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    разбор.add_argument(
        "--home",
        default=str(pathlib.Path.home() / ".claude" / "odata1c"),
        help="рабочий домашний каталог (только чтение)",
    )
    разбор.add_argument("--out", help="куда сохранить итог JSON (счётчики, без значений)")
    разбор.add_argument(
        "--only",
        help="разделы через запятую (строки, часть_update, регистр); «уборка» — только уборка",
    )
    аргументы = разбор.parse_args()
    только = set(аргументы.only.split(",")) if аргументы.only else None
    if только and "уборка" not in только:
        неизвестные = только - set(РАЗДЕЛЫ)
        if неизвестные:
            print(f"неизвестные разделы: {sorted(неизвестные)}; есть: {РАЗДЕЛЫ}")
            return 2

    def нужен(раздел: str) -> bool:
        return только is None or раздел in только

    рабочий = pathlib.Path(аргументы.home)
    все_базы = yaml.safe_load((рабочий / "bases.yaml").read_text(encoding="utf-8"))["bases"]
    запись_базы = все_базы[БАЗА]
    посредник = Посредник1С(
        адрес_odata(запись_базы["url"]),
        verify=запись_базы.get("verify_tls", True),
        удалять=_можно_удалять,
        доп_разрешено=_доп_разрешено,
    )
    # Прямой клиент указывает на ПОСРЕДНИКА, а не на 1С напрямую: и чтение для сверки, и уборка
    # регистра идут через тот же белый список, что и запись сессии приёмки (см. докстринг модуля).
    прямой = Прямой1С(
        {
            "url": посредник.адрес,
            "user": запись_базы["user"],
            "password": запись_базы["password"],
            "verify_tls": True,
        }
    )
    дом = собрать_дом(рабочий, посредник.адрес)
    _добавить_базу_без_удаления_регистра(дом, рабочий)
    метка = f"{МАРКЕР} {time.strftime('%H-%M-%S')}"
    к = Контекст(дом, прямой, посредник, метка)
    print(f"прогон «{метка}»: временный дом создан, демон {ПОРТ_ДЕМОНА}, посредник {ПОРТ_1С}")
    только_уборка = только == {"уборка"}
    try:
        if not только_уборка:
            try:
                await прогон(к, нужен)
            except Exception as сбой:  # noqa: BLE001 — итог прогона и уборка важнее трассы
                место = traceback.extract_tb(сбой.__traceback__)[-1]
                к.итог.раздел = "прогон"
                к.итог.проверить(
                    "прогон без необработанного исключения",
                    False,
                    f"{type(сбой).__name__} в строке {место.lineno} ({место.name})",
                )
    finally:
        try:
            ключевые_поля = к.итог.сведения.get("регистр_key_fields") or ["Штрихкод"]
            try:
                к.итог.сведения["уборка_регистр"] = _очистить_регистр(к, ключевые_поля)
            except Exception as сбой_уборки:  # noqa: BLE001 — уборка объектов важнее этой трассы
                print(
                    f"  уборка регистра не удалась: {type(сбой_уборки).__name__}: {сбой_уборки}",
                    flush=True,
                )
                к.итог.сведения["уборка_регистр"] = {"ошибка": type(сбой_уборки).__name__}
            к.итог.сведения["уборка"] = await asyncio.wait_for(
                уборка(к, МАРКЕР_ОБЩИЙ if только_уборка else метка), 900
            )
        finally:
            остановить_демон(дом)
            посредник.закрыть()
            прямой.close()
            shutil.rmtree(дом, ignore_errors=True)
            print(f"\nвременный дом удалён: {not дом.exists()}", flush=True)

    к.итог.раздел = "посредник"
    к.итог.проверить(
        "посредник: ни одной попытки записи вне белого списка приёмки",
        not посредник.нарушения,
        str(посредник.нарушения) if посредник.нарушения else "",
    )
    к.итог.сведения["запросы_к_1с"] = dict(посредник.счёт)
    к.итог.заметка(f"запросов к 1С через посредника: {dict(посредник.счёт)}")
    к.итог.сведения["метка"] = форма(метка)

    заголовок("Итог")
    по_разделам: dict[str, list[int]] = {}
    for п in к.итог.проверки:
        счёт = по_разделам.setdefault(п["раздел"], [0, 0])
        счёт[0] += п["ок"]
        счёт[1] += 1
    for раздел, (ок, всего) in по_разделам.items():
        print(f"  {раздел}: {ок} из {всего}")
    провалено = [п for п in к.итог.проверки if not п["ок"]]
    print(f"  всего проверок {len(к.итог.проверки)}, не пройдено {len(провалено)}")
    if аргументы.out:
        pathlib.Path(аргументы.out).write_text(
            json.dumps(
                {
                    "проверки": к.итог.проверки,
                    "созданные": к.итог.созданные,
                    "сведения": к.итог.сведения,
                },
                ensure_ascii=False,
                indent=2,
            ),
            encoding="utf-8",
        )
        print(f"\nитог записан в {аргументы.out}")
    return 1 if провалено else 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
