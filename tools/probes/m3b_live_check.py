"""Приёмка записи M3b на живой базе 1С `trade_dev` — задача 9 плана M3b (проект §5.6).

Область этого скрипта — ТРИ раздела из шести, описанных в задаче 9: `строки` (§5.1, LineNumber),
`часть_update` (§5.2, замена табличной части целиком через update) и `регистр` (§5.4, независимый
регистр сведений и `odata1c_delete_record`). Разделы `int64` (§5.3), `предел` (§5.5) и `рецепты`
(§9) в этот прогон не входят — соответствующая функциональность в этой поставке не собрана;
`--only` их не принимает.

Метод и инфраструктура — те же, что у `tools.probes.m2_live_check` (импортируются, не
копируются): временный домашний каталог со своим демоном (порт 7195) и посредником-счётчиком
перед 1С (порт 7196), настоящий лаунчер `odata1c mcp` отдельным процессом, маркер прогона в
`Description` элемента `Catalog_Номенклатура` и штрихкод-маркер записи регистра. Рабочий дом
владельца (`~/.claude/odata1c/`, демон 7171) не трогается.

Создаётся ровно два объекта этого прогона: элемент `Catalog_Номенклатура` (раздел `строки`,
переиспользуется разделами `часть_update` и `регистр`) и запись
`InformationRegister_ШтрихкодыНоменклатуры`, ссылающаяся на него (раздел `регистр`). Табличная
часть, которую правят разделы `строки`/`часть_update`, — `Представления` (тот же выбор, что у
пробы P9, `docs/probes/P9-write-forms.md`): собирается из `КодЯзыка`/`НаименованиеПолное`, без
внешней ссылки, и не несёт класса гейта — проверка «открытый литерал класса contact/dob в поле
строки отклоняется до 1С» (Ruling I-1 ревью хвостов M3b, `service.py` docstring `_подготовить`)
здесь помечается «не проверено: нет такого поля», а не подменяется другим объектом (задача не
создаёт второй маркерный объект ради одной проверки).

Реальные значения защищаемых классов в вывод не попадают: элемент и запись регистра несут только
маркеры прогона и служебные строковые поля без класса гейта, поэтому здесь нет ни `Иглы`, ни
`безопасный_текст` в том объёме, что у `m2_live_check` (контрагенты и их токены этот прогон не
трогает). Формы значений, где это уместно, — тем же приёмом (цифра → 9, буква → a).

Запуск из корня репозитория:

    PYTHONUTF8=1 uv run python tools/probes/m3b_live_check.py --out C:/Temp/m3b.json
    PYTHONUTF8=1 uv run python tools/probes/m3b_live_check.py --only строки
    PYTHONUTF8=1 uv run python tools/probes/m3b_live_check.py --only уборка
"""

