"""Проба P5 (SPEC §15.4): проверка контрольного ключа расчётного счёта по БИК.

Первоисточник алгоритма — приложение к письму Банка России от 08.09.1997 № 515
«Порядок расчета контрольного ключа в номере лицевого счета» (текст утратил статус
самостоятельного нормативного акта, но методика воспроизводится в действующих
разъяснениях; проверено по агрегаторам base.garant.ru, rulaws.ru, normativ.kontur.ru,
дата обращения 2026-09-08 — см. docs/probes/P5-account-check-key.md, раздел «Как
проверял»).

К 20 цифрам счёта слева приписывается трёхзначный префикс; получившиеся 23 цифры
взвешиваются циклом 7-1-3; счёт верен, если сумма произведений кратна 10 (остаток 0).

Префикс (это и есть исправление гипотезы из брифа — см. отчёт, раздел «Что пришлось
поправить»):
- для счёта, который сам является позицией на балансе учреждения Банка России —
  корреспондентский счёт кредитной организации (начинается на 30101 или 30125) или
  единый корреспондентский счёт (начинается на 40102) — префикс "0" + разряды 5-6 БИК
  (условный номер РКЦ/ОКЦ, обслуживающего это учреждение). Гипотеза брифа перепутала
  разряды 5-6 с разрядами 8-9 (две последние цифры БИК) — на большинстве банков это
  разные цифры;
- иначе (клиентский счёт, открытый в кредитной организации) — разряды 7-9 БИК
  (условный номер этой кредитной организации).

Проверено на 27 парах «БИК — счёт» и их испорченных вариантах (54 строки). Алгоритм с
исправленным префиксом сходится на всех счетах, которые являются балансовыми позициями
классической банковской системы Банка России — клиентские счета в кредитных
организациях (405xx — внебюджетные счета учреждений, 407xx — расчётный счёт обычной
организации), корреспондентские счета кредитных организаций (30101) и единые
корреспондентские счета (40102): 34 из 34 случаев (17 пар и их испорченные варианты).
На казначейских счетах (группа 03xxx — единый казначейский счёт ФНС и лицевые счета
бюджетных учреждений, которые ведёт Федеральное казначейство, а не Банк России)
алгоритм НЕ сходится — 9 из 10 пар дают ложное «неверно», сходится только случайно.
Подробности и решение — в отчёте.

Внутри класса `acc` (SPEC §6.4) ветка с разрядами 5-6 БИК фактически достижима только
через счёт `40102`: счета `30101`/`30125` — это отдельный класс `corr` (default `keep`,
детектор `acc` их не видит). Ветка написана и протестирована на `corr`-парах, потому что
именно на них было проще всего проверить исходный текст письма № 515, но в перенесённом
в `gate/detectors.py` виде реально сработает только на `40102`.

Побочная находка: часть проверенных БИК (`017003983`, `004525988`, `024501901`,
`015004950`, `011501101`, `019205400`, `010507002`, `014030106` — все объединённые
кассовые центры образца реформы 2024-2025) не начинается с «04», как того требует
формат SPEC §6.4 для класса `bic` (`9 цифр с 04`). Детекция по имени поля (`бик`, `bic`)
на это не влияет; под вопросом только распознавание таких БИК по значению в свободном
тексте (`НазначениеПлатежа`, сообщения об ошибках) — вне рамок этой пробы, отмечено в
отчёте.
"""

WEIGHTS = (7, 1, 3)

# Счета, которые сами являются балансовыми позициями учреждения Банка России:
# корреспондентский счёт кредитной организации (30101, 30125) и единый
# корреспондентский счёт (40102). У них префикс — условный номер РКЦ/ОКЦ.
BANK_OF_RUSSIA_BALANCE_PREFIXES = ("30101", "30125", "40102")


def prefix_for(account: str, bic: str) -> str:
    """Префикс: для счёта на балансе учреждения Банка России (30101/30125/40102) —
    "0" и разряды 5-6 БИК (условный номер РКЦ/ОКЦ); для клиентского счёта в кредитной
    организации — разряды 7-9 БИК (условный номер этой кредитной организации)."""
    if account.startswith(BANK_OF_RUSSIA_BALANCE_PREFIXES):
        return "0" + bic[4:6]
    return bic[6:9]


def account_key_valid(account: str, bic: str) -> bool:
    digits = prefix_for(account, bic) + account
    if len(digits) != 23 or not digits.isdigit():
        return False
    total = sum((int(d) * WEIGHTS[i % 3]) % 10 for i, d in enumerate(digits))
    return total % 10 == 0


