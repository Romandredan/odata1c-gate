"""Проба M-5 на живой базе 1С: название, открытое в свободном тексте рядом со своим токеном.

Дефект (хвост M1d). Маскировка ответа шла ОДНИМ рекурсивным проходом в порядке ключей JSON,
который прислала 1С. Название, впервые увиденное в поле с классом `org`/`person`, попадает в
словарь только в момент обработки этого поля — а свободный текст того же ответа, стоящий в JSON
раньше, к тому моменту уже промаскирован автоматом СТАРОГО состава и уходит модели с открытым
названием, стоящим рядом со своим же токеном в соседнем поле.

Оракул — не эвристика «похоже на название», а повтор запроса. Один и тот же запрос выполняется
дважды подряд в одной сессии: к началу второго прогона словарь уже знает всё, что выдал первый.
Фрагмент, который второй прогон закрыл токеном, а первый отдал открытым, — это ровно то, что
утекло в первом ответе; ничем другим два прогона отличаться не могут. Признак «рядом со своим
токеном» проверяется точно: закрывший токен сверяется с токеном поля класса той же записи (и,
отдельным счётчиком, с токенами полей класса других записей того же ответа — межзаписная утечка
это тот же дефект).

Почему не эвристика из плана (`_похоже_на_название`: слово с заглавной буквы длиной ≥ 4). Она
считает находкой любое такое слово в свободном тексте: «Расчётный», «Основной», «Договор». Эти
слова остаются открытыми и после правки — они не названия, — поэтому ожидание шага 11 «ни одной
находки» при ней недостижимо в принципе, и прогон «после» ничего бы не доказывал. Оракул повтора
даёт то же наблюдаемое свойство без ложных срабатываний.

Направление находки — только «открыто в первом, закрыто во втором». Обратное направление бывает
законным: короткий вариант названия, однозначный в момент первого прогона, ко второму может стать
неоднозначным (`Dictionary.name_variants` не отдаёт вариант, закреплённый за двумя токенами) и
вернуться открытым. Оно считается отдельно и находкой не является.

Что печатается. Реальные значения — никогда: только счётчики, имена сущностей и полей и формы
(цифра → 9, буква → a). Рабочий дом владельца (его `bases.yaml`, словарь, демон на 7171) не
трогается: временный дом собирает `собрать_дом` из `contact_info_live_check` — запись базы,
индекс и политика копией, словарь пустой со своим секретом, демон на порту 7191. По завершении
демон останавливается, каталог удаляется.

Запуск из корня репозитория:

    uv run python tools/probes/m5_two_pass_check.py --label до
    uv run python tools/probes/m5_two_pass_check.py --label после
    uv run python tools/probes/m5_two_pass_check.py --label после --only счета
"""

from __future__ import annotations

import argparse
import asyncio
import dataclasses
import difflib
import json
import pathlib
import shutil
import sys

from contact_info_live_check import (
    БАЗА,
    ПОРТ,
    ТОКЕН,
    остановить_демон,
    сессия,
    собрать_дом,
    тул,
    форма,
)

ПОРТ_ДЕМОНА = ПОРТ
ЗАПИСЕЙ = 200
# Сколько знаков формы фрагмента показывать: форма длинного комментария целиком в отчёте не нужна.
ДЛИНА_ФОРМЫ = 60


@dataclasses.dataclass(frozen=True)
class Кандидат:
    """Сущность, у которой название лежит и в поле с классом, и в свободном тексте.

    `поле_класса` — путь в ответе тула (`НаименованиеБанка` или `Контрагент/Description`);
    `поле_текста` — поле без класса, в котором то же название встречается открытым текстом.
    """

    имя: str
    сущность: str
    поле_текста: str
    поле_класса: str
    выборка: tuple[str, ...]
    раскрытие: tuple[str, ...] = ()
    почему: str = ""


КАНДИДАТЫ = (
    Кандидат(
        имя="счета",
        сущность="Catalog_БанковскиеСчетаКонтрагентов",
        поле_текста="Description",
        поле_класса="НаименованиеБанка",
        выборка=("Ref_Key", "Description", "НаименованиеБанка"),
        почему=(
            "наименование банка размечено классом org, а Description счёта класса не имеет и"
            " в типовой УТ содержит то же наименование; в JSON 1С Description идёт раньше"
        ),
    ),
    Кандидат(
        имя="договоры",
        сущность="Catalog_ДоговорыКонтрагентов",
        поле_текста="Description",
        поле_класса="Контрагент/Description",
        выборка=("Ref_Key", "Description", "Контрагент/Description"),
        раскрытие=("Контрагент",),
        почему=(
            "название контрагента приходит раскрытием и закрывается по политике своей сущности,"
            " а наименование договора — свободный текст той же записи, стоящий в JSON раньше"
        ),
    ),
)


def форма_фрагмента(текст: str) -> str:
    """Форма (цифра → 9, буква → a) обрезанного фрагмента: в отчёт уходит только она."""
    обрезанный = текст[:ДЛИНА_ФОРМЫ]
    хвост = "…" if len(текст) > ДЛИНА_ФОРМЫ else ""
    return форма(обрезанный) + хвост


def значение_пути(запись: dict, путь: str):
    """Значение поля по пути ответа: `НаименованиеБанка` или `Контрагент/Description`."""
    текущее = запись
    for сегмент in путь.split("/"):
        if not isinstance(текущее, dict):
            return None
        текущее = текущее.get(сегмент)
    return текущее if isinstance(текущее, str) else None


def закрытые_фрагменты(было: str, стало: str) -> list[str]:
    """Куски, которые второй прогон заменил токеном: левая сторона замены при сравнении строк."""
    куски = []
    for операция, а1, а2, б1, б2 in difflib.SequenceMatcher(
        None, было, стало, autojunk=False
    ).get_opcodes():
        if операция == "replace" and ТОКЕН.search(стало[б1:б2]):
            куски.append(было[а1:а2])
    return куски


async def прогон(сеанс, кандидат: Кандидат) -> tuple[dict[str, dict], str | None]:
    """Один запрос к сущности кандидата; записи — по ключу `Ref_Key`."""
    аргументы: dict = {
        "base": БАЗА,
        "entity": кандидат.сущность,
        "select": list(кандидат.выборка),
        "top": ЗАПИСЕЙ,
    }
    if кандидат.раскрытие:
        аргументы["expand"] = list(кандидат.раскрытие)
    ответ = await тул(сеанс, "odata1c_query", аргументы)
    if "error" in ответ:
        return {}, ответ["error"].get("code")
    записи = {
        запись["Ref_Key"]: запись
        for запись in ответ.get("items", [])
        if isinstance(запись, dict) and isinstance(запись.get("Ref_Key"), str)
    }
    return записи, None


def сравнить(первый: dict[str, dict], второй: dict[str, dict], кандидат: Кандидат) -> dict:
    """Счётчики и находки по паре прогонов одного запроса."""
    свои_токены = {
        ключ: значение_пути(запись, кандидат.поле_класса) for ключ, запись in первый.items()
    }
    токены_класса = {токен for токен in свои_токены.values() if токен and ТОКЕН.fullmatch(токен)}
    находки: list[dict] = []
    обратных = 0
    с_токеном_класса = {"первый": 0, "второй": 0}
    сверено = 0
    for ключ, запись in первый.items():
        если_второй = второй.get(ключ)
        if если_второй is None:
            continue
        сверено += 1
        было = запись.get(кандидат.поле_текста) or ""
        стало = если_второй.get(кандидат.поле_текста) or ""
        for метка, текст in (("первый", было), ("второй", стало)):
            if токены_класса & set(ТОКЕН.findall(текст)):
                с_токеном_класса[метка] += 1
        if было == стало:
            continue
        новые = set(ТОКЕН.findall(стало)) - set(ТОКЕН.findall(было))
        пропавшие = set(ТОКЕН.findall(было)) - set(ТОКЕН.findall(стало))
        утёкшие = новые & токены_класса
        if not утёкшие:
            обратных += 1 if пропавшие else 0
            continue
        куски = закрытые_фрагменты(было, стало) or [было]
        находки.append(
            {
                "поле": кандидат.поле_текста,
                "формы": sorted({форма_фрагмента(кусок) for кусок in куски if кусок.strip()}),
                "своим_токеном": свои_токены.get(ключ) in утёкшие,
            }
        )
    return {
        "сущность": кандидат.сущность,
        "поле_текста": кандидат.поле_текста,
        "поле_класса": кандидат.поле_класса,
        "почему": кандидат.почему,
        "записей_сверено": сверено,
        "полей_класса_с_токеном": len(токены_класса),
        # Положительный контроль: сколько текстов вообще упоминают известное словарю название.
        # После правки первый прогон обязан показать столько же, сколько второй, и не ноль —
        # иначе проба потеряла зубы и «находок нет» ничего не значит.
        "текстов_с_токеном_класса": с_токеном_класса,
        "находок": len(находки),
        "находок_своим_токеном": sum(1 for н in находки if н["своим_токеном"]),
        "обратных_расхождений": обратных,
        "находки": находки[:20],
    }


async def раздел_два_прохода(сеанс, кандидат: Кандидат) -> dict:
    """Один и тот же запрос дважды подряд: что закрыл второй прогон — то утекло в первом."""
    первый, ошибка = await прогон(сеанс, кандидат)
    if ошибка:
        return {"сущность": кандидат.сущность, "ошибка": ошибка}
    второй, ошибка = await прогон(сеанс, кандидат)
    if ошибка:
        return {"сущность": кандидат.сущность, "ошибка": ошибка}
    return сравнить(первый, второй, кандидат)


def напечатать(имя: str, итог: dict) -> None:
    print(f"\n--- {имя}: {итог.get('сущность')}")
    if "ошибка" in итог:
        print(f"    ошибка тула: {итог['ошибка']}")
        return
    print(f"    поле класса: {итог['поле_класса']}, свободный текст: {итог['поле_текста']}")
    print(
        f"    записей сверено: {итог['записей_сверено']},"
        f" разных токенов в поле класса: {итог['полей_класса_с_токеном']}"
    )
    контроль = итог["текстов_с_токеном_класса"]
    print(
        "    текстов с токеном названия: первый прогон"
        f" {контроль['первый']}, второй {контроль['второй']}"
    )
    print(
        f"    НАХОДОК: {итог['находок']}"
        f" (своим токеном записи: {итог['находок_своим_токеном']});"
        f" обратных расхождений: {итог['обратных_расхождений']}"
    )
    for находка in итог["находки"]:
        свой = "свой токен" if находка["своим_токеном"] else "токен другой записи"
        print(f"      открыто было ({свой}): {'; '.join(находка['формы'])}")


async def main() -> int:
    разбор = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    разбор.add_argument("--label", required=True, help="метка прогона: до / после")
    разбор.add_argument(
        "--home",
        default=str(pathlib.Path.home() / ".claude" / "odata1c"),
        help="рабочий домашний каталог (только чтение)",
    )
    разбор.add_argument("--out", help="куда сохранить итог JSON (счётчики и формы, без значений)")
    разбор.add_argument("--only", help="только перечисленные кандидаты через запятую")
    аргументы = разбор.parse_args()
    только = set(аргументы.only.split(",")) if аргументы.only else None

    дом = собрать_дом(pathlib.Path(аргументы.home))
    итог: dict = {"label": аргументы.label, "кандидаты": {}}
    print(f"прогон {аргументы.label}: временный дом создан, порт демона {ПОРТ_ДЕМОНА}")
    try:
        async with сессия(дом) as сеанс:
            for кандидат in КАНДИДАТЫ:
                if только is not None and кандидат.имя not in только:
                    continue
                итог["кандидаты"][кандидат.имя] = await раздел_два_прохода(сеанс, кандидат)
                напечатать(кандидат.имя, итог["кандидаты"][кандидат.имя])
    finally:
        остановить_демон(дом)
        shutil.rmtree(дом, ignore_errors=True)
        print(f"\nвременный дом удалён: {not дом.exists()}")
    всего = sum(раздел.get("находок", 0) for раздел in итог["кандидаты"].values())
    итог["находок_всего"] = всего
    print(f"\nитого находок: {всего}")
    if аргументы.out:
        pathlib.Path(аргументы.out).write_text(
            json.dumps(итог, ensure_ascii=False, indent=2), encoding="utf-8"
        )
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
