ФОРМА_ПОЛЕ = re.compile(r"[^\W\d_]")
ФОРМА_ЦИФРА = re.compile(r"\d")


def форма(значение: Any) -> Any:
    """Форма значения для печати: цифра -> 9, буква -> a; не-строки — тип и (для булевых и чисел
    без знаковых цифр) значение как есть — числа и булевы не защищаются ни на одном уровне
    (AGENTS.md, инвариант 6)."""
    if isinstance(значение, str):
        return ФОРМА_ПОЛЕ.sub("a", ФОРМА_ЦИФРА.sub("9", значение))
    if isinstance(значение, (int, float, bool)) or значение is None:
        return значение
    if isinstance(значение, list):
        return [форма(эл) for эл in значение]
    if isinstance(значение, dict):
        return {к: форма(з) for к, з in значение.items()}
    return f"<{type(значение).__name__}>"


def заголовок(текст: str) -> None:
    print(f"\n### {текст}", flush=True)


def _можно_удалять(хвост: str) -> bool:
    """DELETE разрешается посредником ТОЛЬКО по записи регистра штрихкодов с маркером ЭТОГО
    прогона в ключе. Ни по какому другому пути и ни по какой другой записи (Посредник1С.__init__
    без предиката DELETE не пропускает вовсе — прежнее поведение M2 не меняется)."""
    return хвост.startswith(f"{РЕГИСТР}(") and МАРКЕР_РЕГИСТРА in хвост


def _доп_разрешено(метод: str, хвост: str) -> bool:
    """POST/PATCH записи независимого регистра сведений — сущность вне фиксированного набора
    `Посредник1С` (`Catalog_Номенклатура`/`Document_ПересчетТоваров`). POST — только создание в
    самом наборе регистра (тело запроса посредник не разбирает — как и готовый ЦЕЛЬ_СОЗДАНИЯ для
    справочника/документа, доверие несёт сам скрипт: он посылает туда только маркерное тело).
    PATCH — только по записи регистра С МАРКЕРОМ этого прогона в ключе."""
    if метод == "POST":
        return хвост == РЕГИСТР
    if метод == "PATCH":
        return хвост.startswith(f"{РЕГИСТР}(") and МАРКЕР_РЕГИСТРА in хвост
    return False


def создать_маркерный_элемент(к: Прямой1С, посредник: Посредник1С) -> str:
    статус, тело = к.запрос("POST", СПРАВОЧНИК, тело={"Description": МАРКЕР_ЭЛЕМЕНТА})
    if статус >= 300 or not isinstance(тело, dict) or not тело.get("Ref_Key"):
        raise RuntimeError(f"создание маркерного элемента: HTTP {статус}, {форма(тело)}")
    ref = тело["Ref_Key"].lower()
    посредник.свои.add(ref)  # разрешает PATCH этого объекта через обычный белый список посредника
    print(f"создан элемент справочника (маркер в Description), HTTP {статус}")
    return ref


