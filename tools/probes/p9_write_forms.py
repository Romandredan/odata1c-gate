"""Проба P9 (проект M3b §4): как 1С отвечает на запись независимого регистра сведений, на PATCH
табличной части существующего объекта и на поле `Edm.Int64`.

Идёт в 1С НАПРЯМУЮ, мимо шлюза (как P8): вопрос пробы — поведение платформы 1С, а не гейта.
Пароль читается из рабочего `bases.yaml` (`load_config`), в скрипте его нет и в отчёт он не
попадает. Печатаются только коды ответов, имена полей и ФОРМЫ значений (цифра -> 9, буква -> a) —
никогда сами значения (кроме GUID и номеров: SPEC/AGENTS.md инвариант 6 их защитой не считает).

Создаётся ровно два объекта: элемент `Catalog_Номенклатура` с маркером в `Description` и запись
`InformationRegister_ШтрихкодыНоменклатуры` со штрихкодом-маркером, ссылающаяся на него. Запись
регистра убирается DELETE (единственная сущность 1С, где физическое удаление вообще
предусмотрено — CONTEXT.md, «Независимый регистр»), элемент — пометкой удаления. Порядок в
`finally` важен: сначала регистр, потом пометка элемента (пометка не мешает найти регистр по
ссылке, а обратный порядок оставил бы регистр ссылающимся на помеченный элемент дольше нужного).

Пишущие запросы идут через `tools.probes.m2_live_check.Посредник1С` — тот же прокси-счётчик и
белый список, что у приёмки M2 (порт 7196): POST/PATCH — только по объекту(-ам) этого прогона,
DELETE — только по записи регистра С МАРКЕРОМ этого прогона в ключе, PUT — никогда. Регистр вне
фиксированного набора Посредник1С (`Catalog_Номенклатура`/`Document_ПересчетТоваров`), поэтому
прогон передаёт свой предикат `_доп_разрешено` (задача 5 добавила этот параметр в
`Посредник1С.__init__` тем же приёмом, что и `удалять`).

Табличная часть элемента, которую правит проба, — `Представления` (SPEC §4 разрешает выбор):
`ДополнительныеРеквизиты` тоже приходит непустой у существующих элементов, но её строка требует
ссылку на элемент плана видов характеристик (`Свойство_Key`) — а `Представления` собирается из
двух простых строковых полей (`КодЯзыка`, `НаименованиеПолное`), без внешней ссылки.

Запуск из корня репозитория (консоль Windows — cp1251, поэтому `PYTHONUTF8=1`):

    PYTHONUTF8=1 uv run python tools/probes/p9_write_forms.py --out C:/Temp/p9.json
"""

