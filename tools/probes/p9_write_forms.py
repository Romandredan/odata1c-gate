def p9_3(к: Прямой1С, характеристика_образец: str | None) -> dict:
    """PATCH по составному ключу, меняющий ресурс записи (Характеристика_Key); перечитать и
    сказать, изменился ли."""
    заголовок("P9-3: PATCH ресурса записи регистра")
    путь = f"{РЕГИСТР}(Штрихкод='{МАРКЕР_РЕГИСТРА}')"
    if характеристика_образец is None:
        итог = {
            "вопрос": "P9-3",
            "отправлено": None,
            "patch": None,
            "изменилось": None,
            "примечание": "не нашлось образца ненулевого Характеристика_Key для замены",
        }
        print(" ", json.dumps(итог, ensure_ascii=False))
        return итог
    статус, _ = к.запрос("PATCH", путь, тело={"Характеристика_Key": характеристика_образец})
    _, после = к.запрос("GET", путь)
    изменилось = (
        isinstance(после, dict) and после.get("Характеристика_Key") == характеристика_образец
    )
    итог = {
        "вопрос": "P9-3",
        "отправлено": "PATCH регистр по ключу: Характеристика_Key=<guid другой записи>",
        "patch": статус,
        "изменилось": bool(изменилось),
    }
    print(" ", json.dumps(итог, ensure_ascii=False))
    # Возврат к пустой ссылке — не обязателен для уборки (запись всё равно удаляется в finally),
    # но так последующие вопросы не наследуют состояние этого.
    к.запрос("PATCH", путь, тело={"Характеристика_Key": ПУСТОЙ_GUID})
    return итог


