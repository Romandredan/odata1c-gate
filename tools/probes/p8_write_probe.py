def заголовок(текст: str) -> None:
    вывод(f"\n### {текст}")


def показать(метка: str, ответ: Ответ, *, эхо: Iterable[str] = ()) -> Ответ:
    """Строка факта: форма запроса, код, время, текст ошибки; эхо — есть ли метка в ответе."""
    вывод(f"  [{метка}] {ответ.кратко()[:600]}")
    if ответ.заголовки:
        вывод(f"      заголовки: {ответ.заголовки}")
    for метка_эха in эхо:
        вывод(f"      эхо {метка_эха}: {'ДА' if метка_эха in ответ.текст else 'нет'}")
    return ответ


def прочитать(п: Публикация, набор: str, ref: str) -> dict:
    ответ = п.get(ключ(набор, ref))
    if ответ.статус != 200:
        вывод(f"  !! чтение {набор} {ref}: {ответ.кратко()[:300]}")
        return {}
    return ответ.данные


def поля_данных(объект: dict) -> dict:
    """Поля объекта без служебных ссылок навигации и метаданных ответа."""
    return {к: з for к, з in объект.items() if "@" not in к and not к.startswith("odata.")}


def разница(до: dict, после: dict) -> list[str]:
    до, после = поля_данных(до), поля_данных(после)
    return sorted(к for к in set(до) | set(после) if до.get(к) != после.get(к))


def состояние(п: Публикация, набор: str, ref: str) -> str:
    объект = прочитать(п, набор, ref)
    части = [
        f"DataVersion={объект.get('DataVersion')}",
        f"DeletionMark={объект.get('DeletionMark')}",
    ]
    if "Posted" in объект:
        части.append(f"Posted={объект.get('Posted')}")
    return " ".join(части)


def блок_справочник(п: Публикация) -> str | None:
    """Вопросы 1 и 6: создание с минимумом полей и что возвращает POST."""
    заголовок("Вопрос 1 и 6: создание элемента справочника")
    группа = показать(
        "POST группа",
        создать(
            п, СПРАВОЧНИК, {"Description": f"{МАРКЕР} группа {ПРОГОН}", "IsFolder": True}, "группа"
        ),
    )
    ref_группы = (группа.данные or {}).get("Ref_Key") if группа.статус < 300 else None
    элемент_тело: dict[str, Any] = {"Description": f"{МАРКЕР} элемент {ПРОГОН}"}
    if ref_группы:
        элемент_тело["Parent_Key"] = ref_группы
    элемент = показать("POST элемент", создать(п, СПРАВОЧНИК, элемент_тело, "элемент"))
    ref = (элемент.данные or {}).get("Ref_Key") if элемент.статус < 300 else None
    for метка, ответ, ref_объекта in (("группа", группа, ref_группы), ("элемент", элемент, ref)):
        if not ref_объекта:
            continue
        тело = поля_данных(ответ.данные)
        прочитано = прочитать(п, СПРАВОЧНИК, ref_объекта)
        вывод(
            f"  ответ POST ({метка}): полей {len(тело)},"
            f" в чтении GET {len(поля_данных(прочитано))};"
            f" DataVersion={тело.get('DataVersion')!r}; Code={тело.get('Code')!r};"
            f" расхождение POST↔GET: {разница(ответ.данные, прочитано) or 'нет'}"
        )
    return ref or ref_группы


def блок_patch(п: Публикация, ref: str) -> None:
    """Вопрос 4: частичное тело, изменение DataVersion, оптимистическая блокировка."""
    заголовок("Вопрос 4: PATCH")
    путь = ключ(СПРАВОЧНИК, ref)
    чтение = п.get(путь)
    вывод(f"  GET заголовки: {чтение.заголовки}")
    до = чтение.данные
    dv0 = до["DataVersion"]

    ответ = показать("PATCH одно поле", п.patch(путь, {"Description": f"{МАРКЕР} {ПРОГОН} изм1"}))
    после = прочитать(п, СПРАВОЧНИК, ref)
    тело_ответа = ответ.данные
    вид_тела = (
        f"объект, полей {len(поля_данных(тело_ответа))}, расхождение с GET: "
        f"{разница(тело_ответа, после) or 'нет'}"
        if isinstance(тело_ответа, dict)
        else "пусто"
    )
    вывод(
        f"  тело ответа PATCH: {вид_тела};"
        f" изменились поля: {разница(до, после)}; DataVersion {dv0} → {после['DataVersion']}"
    )
    dv1 = после["DataVersion"]

    показать("PATCH то же значение", п.patch(путь, {"Description": f"{МАРКЕР} {ПРОГОН} изм1"}))
    dv2 = прочитать(п, СПРАВОЧНИК, ref)["DataVersion"]
    вывод(f"  запись без изменения значения: DataVersion {dv1} → {dv2}")

    текущая = dv2
    устаревшая = dv0
    варианты = [
        ("DataVersion устаревший в теле", {"DataVersion": устаревшая}, {}),
        ("If-Match: <устаревший>", {}, {"If-Match": устаревшая}),
        ('If-Match: "<устаревший>"', {}, {"If-Match": f'"{устаревшая}"'}),
        ('If-Match: W/"<устаревший>"', {}, {"If-Match": f'W/"{устаревшая}"'}),
    ]
    for номер, (метка, добавка, заголовки) in enumerate(варианты, start=2):
        значение = f"{МАРКЕР} {ПРОГОН} изм{номер}"
        перед = прочитать(п, СПРАВОЧНИК, ref)
        показать(метка, п.patch(путь, {"Description": значение, **добавка}, заголовки=заголовки))
        после = прочитать(п, СПРАВОЧНИК, ref)
        вывод(
            f"      применено: {'ДА' if после.get('Description') == значение else 'нет'};"
            f" DataVersion {перед['DataVersion']} → {после['DataVersion']}"
        )
        текущая = после["DataVersion"]
    показать(
        "If-Match: <текущий>",
        п.patch(путь, {"Description": f"{МАРКЕР} {ПРОГОН} изм9"}, заголовки={"If-Match": текущая}),
    )
    вывод(f"      после: {состояние(п, СПРАВОЧНИК, ref)}")

    # Длина: у наименования номенклатуры УТ 11 предел 100 символов. Молча ли 1С обрезает лишнее?
    длинное = f"{МАРКЕР} {ПРОГОН} длинное " + "Д" * 200
    показать("PATCH наименование длиннее предела", п.patch(путь, {"Description": длинное}))
    сохранено = прочитать(п, СПРАВОЧНИК, ref).get("Description", "")
    вывод(f"      отправлено {len(длинное)} символов, сохранено {len(сохранено)}")
    п.patch(путь, {"Description": до["Description"]})


