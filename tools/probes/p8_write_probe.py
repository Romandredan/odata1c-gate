def блок_ошибки(п: Публикация, ref: str) -> None:
    """Вопрос 7: ошибки записи и эхо переданного значения (метод P7 — буквенная метка)."""
    заголовок("Вопрос 7: ошибки записи и эхо")
    путь = ключ(СПРАВОЧНИК, ref)
    до = прочитать(п, СПРАВОЧНИК, ref)
    случаи = [
        ("строка в поле Guid", {"Parent_Key": "ZZP8GUID7301"}, ["ZZP8GUID7301"]),
        ("строка в поле Int64", {"СрокГодности": "ZZP8NUM7302"}, ["ZZP8NUM7302"]),
        ("строка в поле Boolean", {"ВесИспользовать": "ZZP8BOOL7303"}, ["ZZP8BOOL7303"]),
        ("массив в строковом поле", {"Описание": ["ZZP8LIST7306"]}, ["ZZP8LIST7306"]),
        (
            "несуществующее поле",
            {"ZZP8ПОЛЕ7304": "ZZP8ЗНАЧ7305"},
            ["ZZP8ПОЛЕ7304", "ZZP8ЗНАЧ7305"],
        ),
        (
            "несуществующее поле рядом с настоящим",
            {"Описание": "ZZP8ОПИС7307", "ZZP8ПОЛЕ7308": "x"},
            ["ZZP8ОПИС7307", "ZZP8ПОЛЕ7308"],
        ),
        ("битый JSON", None, ["ZZP8JSON7309"]),
    ]
    for метка, тело, метки in случаи:
        if тело is None:
            ответ = п.запрос("PATCH", путь, сырое_тело='{"Описание": "ZZP8JSON7309'.encode())
        else:
            ответ = п.patch(путь, тело)
        показать(метка, ответ, эхо=метки)
        после = прочитать(п, СПРАВОЧНИК, ref)
        вывод(f"      изменились поля: {разница(до, после) or 'нет'}")
        до = после

    # Системные поля своего объекта: ключ и версия — принимает ли 1С их в теле и что делает.
    новый_ключ = "a8a8a8a8-0000-4000-8000-00000000a8a8"
    показать("Ref_Key в теле PATCH", п.patch(путь, {"Ref_Key": новый_ключ}), эхо=[новый_ключ])
    после = прочитать(п, СПРАВОЧНИК, ref)
    вывод(f"      изменились поля: {разница(до, после) or 'нет'}")
    до = после

    # Ссылка на несуществующий объект: отвергает ли 1С «битую» ссылку или записывает её.
    висячая = "b8b8b8b8-0000-4000-8000-0000000000b8"
    исходная = до.get("ЕдиницаИзмерения_Key", ПУСТАЯ_ССЫЛКА)
    показать(
        "ссылка на несуществующий объект",
        п.patch(путь, {"ЕдиницаИзмерения_Key": висячая}),
        эхо=[висячая],
    )
    после = прочитать(п, СПРАВОЧНИК, ref)
    вывод(f"      сохранено: {после.get('ЕдиницаИзмерения_Key')}")
    if после.get("ЕдиницаИзмерения_Key") != исходная:
        показать("возврат ссылки", п.patch(путь, {"ЕдиницаИзмерения_Key": исходная}))

    # Отказ по правам: у пользователя публикации права на чтение всех проверенных наборов, и
    # платформенный отказ воспроизвести без смены прав нельзя. Ближайший доступный аналог —
    # запрет по дате запрета изменения (БСП): документ датой до общей даты запрета.
    заголовок("Вопрос 7: запись в закрытый период (дата запрета изменения)")
    показать(
        "POST документ датой в закрытом периоде",
        создать(
            п,
            ДОКУМЕНТ_ЗАПАСНОЙ,
            {"Date": "2026-03-02T10:00:00", "Комментарий": f"{МАРКЕР} ZZP8DATE7310"},
            "документ в закрытом периоде",
        ),
        эхо=["ZZP8DATE7310"],
    )


def блок_документ(п: Публикация) -> tuple[str, str] | None:
    """Вопрос 2: какой документ создаётся с минимумом полей и проводится."""
    заголовок("Вопрос 2: документ с минимумом полей")
    образец = п.get(
        ДОКУМЕНТ,
        **{
            "$filter": "Posted eq true",
            "$orderby": "Date desc",
            "$top": "1",
            "$select": "Ref_Key,Склад_Key,Статус",
        },
    ).данные["value"][0]
    вывод(f"  образец для ссылок (только чтение): {образец}")

    минимум = показать(
        "POST только комментарий",
        создать(п, ДОКУМЕНТ, {"Комментарий": f"{МАРКЕР} минимум"}, "документ: только комментарий"),
    )
    if минимум.статус < 300:
        д = минимум.данные
        вывод(
            f"  у созданного: Number={д.get('Number')!r} Date={д.get('Date')!r}"
            f" Статус={д.get('Статус')!r}"
        )
        показать("Post минимального", п.запрос("POST", f"{ключ(ДОКУМЕНТ, д['Ref_Key'])}/Post"))
        вывод(f"      после: {состояние(п, ДОКУМЕНТ, д['Ref_Key'])}")

    сейчас = datetime.datetime.now().replace(microsecond=0).isoformat()
    тело = {"Date": сейчас, "Склад_Key": образец["Склад_Key"], "Комментарий": f"{МАРКЕР} склад"}
    документ = показать("POST дата и склад", создать(п, ДОКУМЕНТ, тело, "документ: дата и склад"))
    if документ.статус < 300:
        ref = документ.данные["Ref_Key"]
        проведение = показать("Post", п.запрос("POST", f"{ключ(ДОКУМЕНТ, ref)}/Post"))
        вывод(f"      после: {состояние(п, ДОКУМЕНТ, ref)}")
        if проведение.статус < 300 and прочитать(п, ДОКУМЕНТ, ref).get("Posted"):
            return ДОКУМЕНТ, ref
    return None


def блок_действия(п: Публикация, набор: str, ref: str) -> None:
    """Вопрос 3: форма URL проведения и отмены проведения, ответ, DataVersion."""
    заголовок("Вопрос 3: формы вызова Post/Unpost")
    путь = ключ(набор, ref)
    формы = [
        ("GET", "Unpost", {}),
        ("POST", "Unpost", {}),
        ("POST", "Post", {}),
        ("POST", "Unpost()", {}),
        ("POST", "Post()", {}),
        ("POST", "Unpost", {"PostingModeOperational": "false"}),
        ("POST", "Post", {"PostingModeOperational": "false"}),
        ("POST", "Unpost", {}),
        ("POST", "Post", {"PostingModeOperational": "true"}),
        ("POST", "Post(PostingModeOperational=false)", {}),
        ("GET", "Post", {}),
    ]
    for метод, действие, params in формы:
        перед = состояние(п, набор, ref)
        ответ = п.запрос(метод, f"{путь}/{действие}", params=params)
        показать(f"{метод} …/{действие} {params or ''}", ответ)
        вывод(f"      было: {перед}; стало: {состояние(п, набор, ref)}")


def блок_проведённый(п: Публикация, набор: str, ref: str) -> None:
    """Запись проведённого документа: остаётся ли он проведённым; пометка удаления на нём."""
    заголовок("Вопрос 4–5 на проведённом документе")
    путь = ключ(набор, ref)
    if not прочитать(п, набор, ref).get("Posted"):
        показать("Post перед проверкой", п.запрос("POST", f"{путь}/Post"))
    вывод(f"  до: {состояние(п, набор, ref)}")
    показать("PATCH комментарий", п.patch(путь, {"Комментарий": f"{МАРКЕР} проведённый изм"}))
    вывод(f"      после: {состояние(п, набор, ref)}")
    # Поле Posted в теле PATCH: игнорируется, отвергается или работает как действие?
    показать("PATCH Posted=false", п.patch(путь, {"Posted": False}))
    вывод(f"      после: {состояние(п, набор, ref)}")
    показать("PATCH Posted=true", п.patch(путь, {"Posted": True}))
    вывод(f"      после: {состояние(п, набор, ref)}")
    if not прочитать(п, набор, ref).get("Posted"):
        показать("Post снова", п.запрос("POST", f"{путь}/Post"))
    показать("PATCH DeletionMark=true на проведённом", п.patch(путь, {"DeletionMark": True}))
    вывод(f"      после: {состояние(п, набор, ref)}")

    # Проведение документа с пометкой удаления — порядок операций для mark_for_deletion и action.
    показать("Unpost перед пометкой", п.запрос("POST", f"{путь}/Unpost"))
    показать("PATCH DeletionMark=true", п.patch(путь, {"DeletionMark": True}))
    показать("Post помеченного на удаление", п.запрос("POST", f"{путь}/Post"))
    вывод(f"      после: {состояние(п, набор, ref)}")


def прогон(п: Публикация, блоки: set[str]) -> None:
    вывод(f"маркер: {МАРКЕР}; журнал созданного: {ЖУРНАЛ_СОЗДАННОГО}")
    if "справочник" in блоки:
        ref = блок_справочник(п)
        if ref:
            блок_patch(п, ref)
            блок_пометка(п, ref)
            блок_ошибки(п, ref)
    if "документ" in блоки:
        найден = блок_документ(п)
        if найден:
            блок_действия(п, *найден)
            блок_проведённый(п, *найден)


