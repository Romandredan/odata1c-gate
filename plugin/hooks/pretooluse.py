"""Хук `PreToolUse` плагина odata1c — защита в глубину, не замена гейта.

Читает с stdin JSON-событие Claude Code (`tool_name`, `tool_input`, ...), печатает в stdout
`{"hookSpecificOutput": {...}}` с решением `ask`/`deny` или ничего (решения нет — тул разрешён
как обычно) и всегда завершается кодом 0 (никогда 2 — ошибка хука не должна блокировать сессию
сильнее, чем осознанный `deny`).

Правила, в этом порядке (design-doc M3 §5,
`docs/superpowers/specs/2026-09-14-m3-package-design.md` — раунд 1 (Ruling 68/72/73), раунд 2
(Ruling 77) и раунд 3 по повторному ревью (Ruling 85/86/87/88)):

1. `odata1c_commit` (обе формы имени тула — плагин и ручная регистрация MCP) → `ask`. Это
   страховка диалога разрешения Claude Code по `_meta`, а не замена: если Claude Code уже
   показывает свой вопрос на `odata1c_commit`, пользователь увидит два запроса подряд — решение,
   снимать ли это правило, за владельцем (приёмка вживую, см. отчёт задачи).
2. `Read`/`Edit`/`Write`/`MultiEdit`/`NotebookEdit`/`Grep`/`Glob` по пути внутри домашнего
   каталога шлюза → `deny`. Базовое имя пути сравнивается без учёта регистра, без хвостовых точек
   и пробелов и без хвостового потока NTFS (`::$DATA`) с защищёнными именами (`bases.yaml`,
   `daemon.yaml`, `launcher.key`, `gate.sqlite`, `journal.sqlite`) КАК ПРЕФИКС (Ruling 85, раунд 3,
   находка M2-1): имя равно защищённому целиком или начинается с него, а следующий символ — не
   буква и не цифра. Резервные копии рядом с рабочим файлом (`bases.yaml.bak-adr15`,
   `gate.sqlite-wal`, `journal.sqlite.bak-20260913.sqlite`) тоже `deny` — явные записи `-wal`/
   `-shm` в списке защищённых имён стали лишними, префиксное правило их уже покрывает. «Внутри
   дома» проверяется по ДВУМ известным домам сразу — дому этой сессии (`ODATA1C_HOME`, если
   задан, иначе `~/.claude/odata1c`) и, независимо от него, документированному дефолту
   `~/.claude/odata1c`: путь к настоящему дому владельца обязан оставаться закрытым, даже если
   сессия сконфигурирована на другой `ODATA1C_HOME`. Для `Grep`/`Glob` дополнительно запрещён путь,
   равный любому из этих домов или его предку (`~`, `~/.claude`, сам дом целиком) — один вызов с
   таким путём рекурсивно вычитывает все защищённые файлы разом; подкаталоги дома (`bases/…`,
   `recipes/…`, `logs/…`) разрешены. Для `Glob` дополнительно (Ruling 86, раунд 3, находка M2-2):
   поле `pattern` — основной аргумент тула, и проверяется наравне с `path`, а не только он —
   защищённое имя в шаблоне (в любом месте, у относительного и у абсолютного шаблона) → `deny`;
   абсолютный шаблон (после раскрытия `~`), чей каталог (всё до первого символа `*`/`?`/`[`) — дом
   шлюза или его предок, тоже `deny`. Относительный шаблон, который не называет защищённое имя и
   не абсолютен сам по себе, дальше не проверяется — это граница решения контроллера, а не пробел
   реализации (остаток находки M2-2 про комбинацию с `path` внутри разрешённого подкаталога —
   см. отчёт задачи, раздел «Раунд 3»).
3. `Bash`/`PowerShell` (оба — поле `command`) → `deny`, если команда содержит:
   - имя защищённого файла как отдельное слово (тем же префиксным правилом, что и правило 2,
     Ruling 85 — совпадение по границе слова `\b` сразу после базового имени само ловит и хвост
     вида `bases.yaml.bak-adr15`, отдельного кода на резервные копии не понадобилось);
   - либо `odata1c`/`odata1c.exe` (без учёта регистра) рядом со словом `reveal` (с пробелами/
     кавычками между);
   - либо `sqlite3` вместе с `gate.sqlite`/`journal.sqlite` в любом месте команды, включая
     разные строки многострочной;
   во всех трёх случаях причина та же, что у правила 2 (Ruling 73). Отдельно (Ruling 77, раунд 2,
   расширено Ruling 87, раунд 3, находка M2-3): `deny` с причиной «шаблон в каталоге шлюза может
   задеть файлы с паролями», если команда упоминает путь дома шлюза (буквально `.claude/odata1c`,
   любая форма подстановки `ODATA1C_HOME`, или буквальное значение переменной, если она задана) И
   символ шаблона оболочки — `*`/`?` (Ruling 77), раскрытие фигурных скобок вида `{bases,daemon}.
   yaml` (Ruling 87; распознаётся по запятой ВНУТРИ скобок, а не одним присутствием `{`/`}` —
   наивная версия дала бы `deny` на легитимный `cat ${ODATA1C_HOME}/recipes/ut.yaml`, ровно
   ловушка, которую нашло повторное ревью), или квадратный набор символов вида `[bd]ases.yaml`
   (Ruling 87). Отдельно (Ruling 88, раунд 3, находка M2-4): `deny` с причиной «чтение каталога
   шлюза целиком может задеть файлы с паролями», если путь дома шлюза упомянут КАК КОРЕНЬ (не как
   один из разрешённых подкаталогов `/recipes`, `/bases`, `/logs`, в любом написании разделителя)
   вместе с глаголом чтения, перечисления, копирования или архивации из фиксированного списка
   (`cat`, `type`, `more`, `less`, `head`, `tail`, `Get-Content`, `gc`, `Get-ChildItem`, `gci`,
   `ls`, `dir`, `find`, `grep`, `Select-String`, `rg`, `sed`, `awk`, `cp`, `copy`, `xcopy`,
   `robocopy`, `Copy-Item`, `tar`, `zip`, `7z`, `Compress-Archive`, `python`, `node`) — дешевле
   даже символа шаблона. Команды с путём дома без шаблона и без запрещённого глагола
   (`ls ~/.claude/odata1c/recipes/ut`) остаются разрешены; листинг или чтение дома целиком без
   единого символа шаблона (`ls ~/.claude/odata1c/`, `Get-ChildItem $env:ODATA1C_HOME`) начиная с
   раунда 3 тоже `deny` — намеренное расширение решения контроллера (Ruling 88), а не регрессия
   более ранних раундов.
4. Команды владельца, которые модель запускает сама (ADR-0017): `odata1c base set` с ключом,
   снижающим защиту базы, `odata1c policy open` и `odata1c policy set <база> <Сущность.Поле>
   keep|scan` (классы `keep` и `scan` снимают закрытие значения, как `open`; закрывающие классы и
   `custom:<имя>` проходят молча) → `ask`; проверяется после `deny` правила 3.
5. Иначе — молчание (тул выполняется как обычно).

Причины решений — фиксированный русский текст без значений из события, кроме двух мест:
`pending_id` (правило 1) и правило 4, чья причина называет базу и ключи с их значениями из
команды (`--gate off`, неизвестный ключ) — владельцу нужно видеть, что именно он подтверждает.
Полные пути, остальное содержимое команд и прочие значения из `tool_input` в текст причины не
попадают.

Правило 4 разбирает команду по токенам, а не одним регулярным выражением: после каждого слова
`odata1c`/`odata1c.exe` идёт текст до разделителя цепочки (`&&`, `||`, `;`, `|`, перевод строки,
одиночный `&` вне перенаправления `>&`/`&>`/`<&`); переносы `\\`/`` ` `` + перевод строки заменены
пробелом; ключи до `base`/`policy` и между ними (`--home` со значением) пропускаются; после `set`
любой ключ, кроме `--label` и `--home`, либо защитный по значению, либо считается снижением —
в том числе сокращение argparse (CLI их не принимает, `allow_abbrev=False`) и неизвестный ключ.
Раскрытие оболочки закрыто вопросом, а не разбором. Слово в позиции имени ключа, группы
(`base`/`policy`), подкоманды (`set`/`open`) или класса `policy set` либо распознано, либо целиком
состоит из букв, цифр и символов `_ . - :` (разрешительный список, раунд 2 финального ревью);
иначе — `ask` с причиной «команда odata1c не разобрана». Список закрывает разом `ba$()se`,
`s$()et`, `$'base'`, `ba${x}se`, `$s`, PowerShell ``b`ase``, `ba$('')se`, splat `@a`, `%VAR%`, `^`
и glob (`s?t`, `ba[s]e`), которые перечень запрещённых символов пропускал по одному. Для
PowerShell недостоверен любой хвост с обратной кавычкой, а присутствие `--%` где угодно в
команде, вызывающей odata1c, — тоже. В хвосте `base set` токен с `$`, обратной кавычкой, `(`, `{`,
`@` или `%` — снижение с пометкой «(раскрытие оболочки)», в том числе значение нейтрального ключа
(`--label $s`, `--label=$s`, `u$s`, `--home $s`): переменная может хранить `--gate off`; значение
`--home` с такими символами в позиции до подкоманды — «не разобрана», в `policy set` — открытие.
Класс `policy set` (третье слово) с раскрытием или glob (`ke$()ep`, `k?ep`) считается
открывающим по той же причине. Цена: лишний вопрос на `odata1c $cmd …`, на
`--home=$HOME/h base set ut --write off`, на подпись с `(`, `{`, `@` или `%`
(`--label 'УТ (розница)'`: `shlex` кавычек не помнит) и на `;`, `&`, `|` или перевод строки в
подписи (буквальный, `$'…\\n…'`, ``"…`n…"``): хвост режется по ним до разбора кавычек, команда
получает «хвост команды не разобран» до того, как CLI отказал бы в многострочной подписи.

**Обходы, которые этот хук НЕ закрывает** (см. `AGENTS.md`, раздел «Безопасность» — это
задокументированная, осознанная граница, а не упущение): `python -c "..."` и любой другой способ
прочитать файл в обход matcher'а хука; копирование защищённого файла под другим именем перед
чтением; чтение через инструмент, которого нет в списке `matcher` `hooks.json`; шаблон оболочки
или упоминание дома, разнесённые на два отдельных вызова тула (`cd ~/.claude/odata1c` одним
вызовом, `cat *` без упоминания дома — следующим; рабочий каталог тула сохраняется между
вызовами, а хук решения не хранит между ними — правила 3 видят только одну команду за раз);
относительный шаблон `Glob` (`pattern="../*.yaml"`), который заходит из разрешённого подкаталога
`path` (например, `recipes`) обратно в дом через `..`, не называя защищённое имя явно (Ruling 86
проверяет абсолютные шаблоны и присутствие защищённого имени, но не комбинацию относительного
шаблона с восходящим `path`, находка M2-2 повторного ревью); временный дом шлюза вне `.claude` и
вне значения `ODATA1C_HOME` этой сессии, на который сессия хука не настроена (скрипты приёмки
поднимают такие для тестов на живой базе); прямое обращение к демону в обход лаунчера (у хука нет
доступа к сетевым запросам модели). Пределы правила 4 (ADR-0017): косвенный вызов команды
(`$o='odata1c'; & $o base set …`, `iex` над строкой из частей, `Start-Process`,
`python -c "from odata1c.cli import main; …"`), `cmd /c …` и другие косвенные вызовы, кавычки,
экранирование или раскрытие внутри самого слова `odata1c` (`od''ata1c`, `od$()ata1c …`) хук не
видит — слово ищется буквально; glob с заранее созданными файлами (`--home /x/*`, где `*`
раскрывается в несколько слов и сдвигает позицию подкоманды) тоже предел. В позициях ключа,
группы, подкоманды и класса раскрытие закрыто вопросом (разрешительный список символов, см.
выше), внутри слова `odata1c` — предел. Слово `odata1c` с `/`, `\\` или `-` сразу за ним
(`src/odata1c/cli.py`, `odata1c-gate@0.3.0`) — путь или имя пакета, не вызов. Цена правила —
лишний `ask` на безобидной команде, в тексте которой стоит фраза `odata1c base set`,
`odata1c policy open` или `odata1c policy set … keep`
(`echo`, `grep`, `git commit -m "… odata1c base set …"`); владелец проекта принял эту цену как
плату за защиту в глубину. Хук — защита в глубину поверх инварианта 1 (реальные значения
не выходят через MCP) и разрешений Claude Code на Bash; последняя линия — они, не этот скрипт.
"""

import contextlib
import json
import os
import pathlib
import re
import shlex
import sys

# Правило 1: обе формы имени тула odata1c_commit.
_COMMIT_RE = re.compile(r"^mcp__(plugin_odata1c_gate|odata1c)__odata1c_commit$")

# Правило 2/3: базовые защищённые имена — сравниваются КАК ПРЕФИКС (Ruling 85, раунд 3, находка
# M2-1), поэтому суффиксы -wal/-shm/резервных копий перечислять отдельно не нужно: "gate.sqlite",
# за которым сразу небуквенно-нецифровой символ (`.`, `-`, конец строки), матчит и "gate.sqlite",
# и "gate.sqlite-wal", и "gate.sqlite.bak-20260913.sqlite".
_БАЗОВЫЕ_ИМЕНА = r"bases\.yaml|daemon\.yaml|launcher\.key|gate\.sqlite|journal\.sqlite"

# Правило 2: применяется к базовому имени файла (уже приведённому к виду для сравнения —
# `_базовое_имя_для_сравнения`), поэтому якорь `^` — это начало имени файла, а не всей строки.
_ИМЯ_ПРЕФИКС_RE = re.compile(rf"^(?:{_БАЗОВЫЕ_ИМЕНА})(?![a-z0-9])", re.IGNORECASE)

# Тулы правила 2 и поле их входа, где лежит путь.
_ПУТЬ_ПОЛЕ = {
    "Read": "file_path",
    "Edit": "file_path",
    "Write": "file_path",
    "MultiEdit": "file_path",
    "NotebookEdit": "notebook_path",
    "Grep": "path",
    "Glob": "path",
}
# Ruling 72 (находка M-3): для этих двух дополнительно запрещён путь на весь дом или его предка.
_КАТАЛОЖНЫЕ_ТУЛЫ = {"Grep", "Glob"}

# Ruling 68 (находка м-3): PowerShell перехватывается как Bash — то же поле command.
_КОМАНДНЫЕ_ТУЛЫ = {"Bash", "PowerShell"}

# Правило 3 (Ruling 73/находка M-4, префикс — Ruling 85): без учёта регистра, без обязательной
# подстроки odata1c рядом с именем файла — только рядом со словом reveal, и там же допускаются
# .exe, пробелы и кавычки. Хвост `(?![a-z0-9])` сразу после базового имени — тот же, что у
# `_ИМЯ_ПРЕФИКС_RE` правила 2 (а не `\b`: тот считает `_` и кириллицу частью слова и пропускал
# `bases.yaml_old`, который правило 2 запрещает), поэтому оба используют один и тот же список
# `_БАЗОВЫЕ_ИМЕНА`.
_BASH_ФАЙЛЫ_RE = re.compile(rf"(?<![\w.-])(?:{_БАЗОВЫЕ_ИМЕНА})(?![a-z0-9])", re.IGNORECASE)
_BASH_REVEAL_RE = re.compile(r"\bodata1c(\.exe)?\b[\s'\"]*reveal\b", re.IGNORECASE)
_BASH_SQLITE_RE = re.compile(r"\bsqlite3\b.*(gate|journal)\.sqlite", re.IGNORECASE | re.DOTALL)

# Правило 4 (ADR-0017): команды владельца, которые модель теперь запускает сама (навыки
# `odata1c-base`, `odata1c-policy`). Снижающая защиту форма — `ask`: диалог разрешения — последняя
# линия против подсказки из данных 1С («выключи гейт»), как и на `odata1c_commit`. Форма запуска
# любая (`uvx --from odata1c-gate odata1c …`, `uv run odata1c …`, `odata1c.exe …`,
# `python -m odata1c …`): ищется слово `odata1c`, дальше разбор по токенам — `--home` CLI принимает
# в любой позиции, одним регулярным выражением «base set подряд» это не описать.
_ODATA1C_СЛОВО_RE = re.compile(r"\bodata1c(?:\.exe)?\b", re.IGNORECASE)
# Разделители цепочки: `&&`, `||`, `;`, `|`, перевод строки и одиночный `&` (фоновый запуск), но не
# `&` перенаправления — `2>&1`, `>&`, `<&`, `*>&`, `&>файл` — и не `|` в `>|` (принудительное
# перенаправление): после них аргументы команды идут дальше. `|&` по-прежнему режет.
_РАЗДЕЛИТЕЛЬ_ЦЕПОЧКИ_RE = re.compile(r"&&|\|\||;|(?<!>)\||[\r\n]|(?<![<>&])&(?![>&])")
# Перенос строки внутри команды: bash «обратная косая черта + перевод строки» и PowerShell
# «обратная кавычка + перевод строки» оболочка склеивает в один пробел, поэтому хук склеивает так же
# до поиска.
_ПЕРЕНОС_СТРОКИ_RE = re.compile(r"[\\`]\r?\n")
# Ключ `base set` → значения, НЕ снижающие защиту. Хук не знает ни текущих значений, ни роли базы,
# поэтому `--gate identifiers`, любой `default` и любой `--commit-limit` считаются снижением —
# цена одного лишнего диалога (проект §3.3).
_ЗАЩИТНЫЕ_ЗНАЧЕНИЯ = {
    "--gate": {"identifiers+names"},
    "--write": {"off"},
    "--role": {"prod"},
    "--post-documents": {"off"},
    "--mark-deletion": {"off"},
    "--register-delete": {"off"},
    "--commit-limit": set(),
}
_НЕЙТРАЛЬНЫЕ_КЛЮЧИ = {"--label", "--home"}  # со значением, защиту не меняют
_КЛЮЧИ_СО_ЗНАЧЕНИЕМ = set(_ЗАЩИТНЫЕ_ЗНАЧЕНИЯ) | _НЕЙТРАЛЬНЫЕ_КЛЮЧИ
_КЛЮЧИ_СПРАВКИ = {"-h", "--help"}  # без значения: справка, ничего не меняет
_ПРИЧИНА_BASE_SET = (
    "odata1c base set снижает защиту базы {база}: {ключи} — подтвердите, что это просьба владельца"
)
_ПРИЧИНА_POLICY_OPEN = (
    "odata1c policy open открывает поле модели — подтвердите, что это просьба владельца"
)
_ПРИЧИНА_POLICY_SET = (
    "odata1c policy set … keep|scan открывает поле модели — подтвердите, что это просьба владельца"
)
_ПРИЧИНА_НЕ_РАЗОБРАНА = "команда odata1c не разобрана — подтвердите, что это просьба владельца"
# Классы `policy set`, которые снимают закрытие значения (`open` — это `set … keep`).
_ОТКРЫВАЮЩИЕ_КЛАССЫ = {"keep", "scan"}

# Ruling 77 (раунд 2): путь дома шлюза в команде — буквально .claude/odata1c (любой разделитель).
_HOME_PATH_RE = re.compile(r"\.claude[/\\]odata1c", re.IGNORECASE)

# Ruling 87 (раунд 3, находка M2-3): раскрытие фигурных скобок оболочки — распознаётся по запятой
# ВНУТРИ скобок, а не одним присутствием `{`/`}`; иначе `${ODATA1C_HOME}` (легитимная, разрешённая
# Ruling 77 форма — `{`/`}` там только из-за подстановки переменной, без запятой) стал бы ложным
# deny — ровно ловушка наивной правки, которую нашло повторное ревью.
_ФИГУРНЫЕ_СКОБКИ_RE = re.compile(r"\{[^{}]*,[^{}]*\}")
# Ruling 87: квадратный набор символов оболочки/глоба (`[bd]ases.yaml`).
_КВАДРАТНЫЕ_СКОБКИ_RE = re.compile(r"\[[^\[\]]+\]")

# Ruling 88 (раунд 3, находка M2-4): глаголы чтения/перечисления/копирования/архивации — массовое
# вычитывание дома целиком дешевле даже символа шаблона (Ruling 77/87).
_ГЛАГОЛЫ_ЧТЕНИЯ_RE = re.compile(
    r"\b(?:cat|type|more|less|head|tail|Get-Content|gc|Get-ChildItem|gci|ls|dir|find|grep|"
    r"Select-String|rg|sed|awk|cp|copy|xcopy|robocopy|Copy-Item|tar|zip|7z|Compress-Archive|"
    r"python|node)\b",
    re.IGNORECASE,
)
# Ruling 88: подкаталоги, для которых упоминание дома НЕ считается "корнем" — те же три, что
# разрешены правилом 2 для Grep/Glob (Ruling 72). `\b` после имени подкаталога срабатывает и на
# "/bases.yaml" (граница на точке) — не дыра: `_массовое_чтение_дома` вызывается в decide() ПОСЛЕ
# `_BASH_ФАЙЛЫ_RE`, который такую команду уже денит по имени файла раньше. Проверка зависит от
# этого порядка, а не от собственной точности регулярного выражения.
_ДОПУЩЕННЫЙ_ПОДКАТАЛОГ_RE = re.compile(r"^[/\\](recipes|bases|logs)\b", re.IGNORECASE)

_ПРИЧИНА_ФАЙЛ = (
    "файл или каталог шлюза odata1c: пароли или реальные значения; читать его модели нельзя, "
    "спросите владельца"
)
_ПРИЧИНА_ШАБЛОН = "шаблон в каталоге шлюза может задеть файлы с паролями"
_ПРИЧИНА_МАССОВОЕ_ЧТЕНИЕ = "чтение каталога шлюза целиком может задеть файлы с паролями"

# Документированный дефолт дома шлюза (SPEC §2.2) — известен независимо от ODATA1C_HOME сессии
# (находка м-2: замена ненадёжного признака "odata1c и .claude среди частей пути").
_ДЕФОЛТНЫЙ_ДОМ = "~/.claude/odata1c"

# Ruling — находка м-2: Git Bash на Windows отдаёт абсолютные пути без буквы диска (/c/Users/...).
# os.path.abspath такой путь не превращает обратно в путь с буквой диска (трактует /c как обычный
# каталог), из-за чего сравнение с домом по префиксу не совпадает ни при каком ODATA1C_HOME. Здесь
# — обратное преобразование Git Bash/MSYS. Только для Windows: на настоящем POSIX /c/... — путь от
# корня файловой системы, переписывать его нельзя.
_POSIX_ДИСК_RE = re.compile(r"^/([A-Za-z])(/.*)?$")

# Minor (раунд 3, находка м2-1): docstring `_нормализовать_путь` с раунда 1 обещал независимость от
# UNC-формы (`\\?\...`), но фактически ничего не делал с ней — realpath такую строку не разбирает,
# сравнение с домом не совпадало ни при каком ODATA1C_HOME. `\\?\UNC\` — расширенная форма сетевого
# пути, разворачивается в обычные `\\`.
_UNC_ПРЕФИКС_ДЛИНА = 4  # длина "\\?\" и "\\.\" в символах


def _ask(reason: str) -> dict:
    return {
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "ask",
            "permissionDecisionReason": reason,
        }
    }


def _deny(reason: str) -> dict:
    return {
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": reason,
        }
    }


def _снять_unc_префикс(путь: str) -> str:
    """Minor (раунд 3, находка м2-1): `\\\\?\\` и `\\\\.\\` — префиксы расширенного пути и
    пространства устройств Windows; `\\\\?\\UNC\\` — расширенная форма сетевого пути,
    разворачивается в обычные `\\\\`. Работает на сырой строке ДО замены разделителя на `/` — сам
    префикс всегда записан обратными косыми, что бы ни лежало дальше в пути."""
    голова = путь[:_UNC_ПРЕФИКС_ДЛИНА]
    if голова not in ("\\\\?\\", "\\\\.\\"):
        return путь
    остаток = путь[_UNC_ПРЕФИКС_ДЛИНА:]
    if остаток[:4].upper() == "UNC\\":
        return "\\\\" + остаток[4:]
    return остаток


def _переписать_posix_диск(путь: str) -> str:
    if os.name != "nt":
        return путь
    совпадение = _POSIX_ДИСК_RE.match(путь)
    if совпадение is None:
        return путь
    буква = совпадение.group(1)
    остаток = совпадение.group(2) or "/"
    return f"{буква}:{остаток}"


def _нормализовать_путь(значение: str) -> pathlib.Path:
    """Приводит путь к канонической форме для сравнения с домом шлюза.

    `_снять_unc_префикс` — расширенные формы Windows (находка м2-1, раунд 3) до замены
    разделителя, пока префикс ещё различим. `replace("\\\\", "/")` — единое написание разделителя
    (входные пути бывают и POSIX, и Windows вне зависимости от текущей ОС). `_переписать_posix_диск`
    — Git Bash на Windows. `expanduser` — оба написания `~` (`~/...` и после замены разделителя
    `~\\...` тоже). Дальше `os.path.realpath` вместо голого `abspath`/`normpath` (находка м-2):
    резолвит `..`, символьные ссылки и точки соединения (junction), не зависит от коротких имён
    8.3 — все они обязаны сравниться как один и тот же путь. `normcase` — сравнение без учёта
    регистра."""
    без_unc = _снять_unc_префикс(значение)
    единообразный = _переписать_posix_диск(без_unc.replace("\\", "/"))
    раскрытый = os.path.expanduser(единообразный)
    канонический = os.path.realpath(раскрытый)
    return pathlib.Path(os.path.normcase(канонический))


def _базовое_имя_для_сравнения(значение: str) -> str:
    """Базовое имя пути в виде для сравнения со списком защищённых файлов (находка M-2): без
    хвостового потока NTFS (`::$DATA` и подобные Alternate Data Streams — Windows открывает по
    нему тот же файл), без хвостовых точек и пробелов (`bases.yaml.` и `bases.yaml ` на NTFS —
    тот же файл, что `bases.yaml`), без учёта регистра (`BASES.YAML` — тот же файл)."""
    имя = pathlib.Path(значение.replace("\\", "/")).name
    имя = имя.split(":", 1)[0]
    имя = имя.rstrip(" .")
    return имя.casefold()


def _домашний_каталог() -> pathlib.Path:
    задан = os.environ.get("ODATA1C_HOME")
    if задан:
        return pathlib.Path(задан)
    return pathlib.Path(_ДЕФОЛТНЫЙ_ДОМ)


def _известные_дома(home: pathlib.Path) -> list[pathlib.Path]:
    """Дом этой сессии (`home`) и, независимо от него, документированный дефолт — оба нормализованы
    и без дублей. Замена признака "части пути" (находка м-2): тот и пропускал временный дом вне
    `.claude`, и ложно срабатывал на `src/odata1c/` этого же репозитория под
    `.claude/worktrees/…`."""
    кандидаты = [_нормализовать_путь(str(home)), _нормализовать_путь(_ДЕФОЛТНЫЙ_ДОМ)]
    уникальные: list[pathlib.Path] = []
    for дом in кандидаты:
        if дом not in уникальные:
            уникальные.append(дом)
    return уникальные


def _внутри_какого_то_дома(норм_путь: pathlib.Path, дома: list[pathlib.Path]) -> bool:
    return any(норм_путь == дом or дом in норм_путь.parents for дом in дома)


def _путь_это_дом_или_предок(норм_путь: pathlib.Path, дома: list[pathlib.Path]) -> bool:
    return any(норм_путь == дом or норм_путь in дом.parents for дом in дома)


def _домашние_формы(home: pathlib.Path) -> list[str]:
    """Все известные написания пути дома шлюза как фрагменты регулярного выражения: буквальный
    `.claude/odata1c` (любой разделитель), три формы подстановки `ODATA1C_HOME` с точным правым
    краем (`%...%`, `${...}`, голая `$ODATA1C_HOME`/`$env:ODATA1C_HOME` до границы слова), и
    фактическое значение переменной этой сессии в обоих написаниях разделителя. Minor (раунд 3,
    находка м2-3): дом берётся из параметра `home`, а НЕ заново из `os.environ` — `main` уже
    прочитал переменную один раз при вызове `_домашний_каталог`; повторное независимое чтение
    делало правила 2 и 3 проверяемыми на РАЗНЫХ домах в тесте, который задаёт `home` без
    переменной окружения (правило 2 дом получает параметром, правило 3 раньше читало окружение
    напрямую)."""
    формы = [
        _HOME_PATH_RE.pattern,
        r"%odata1c_home%",
        r"\$\{odata1c_home\}",
        r"\$(?:env:)?odata1c_home\b",
    ]
    значение = str(home)
    формы.append(re.escape(значение))
    перевёрнутое = значение.replace("\\", "/") if "\\" in значение else значение.replace("/", "\\")
    if перевёрнутое != значение:
        формы.append(re.escape(перевёрнутое))
    return формы


def _домашние_совпадения(команда: str, home: pathlib.Path) -> list[re.Match]:
    шаблон = re.compile("(?:" + "|".join(_домашние_формы(home)) + ")", re.IGNORECASE)
    return list(шаблон.finditer(команда))


def _команда_упоминает_дом_шлюза(команда: str, home: pathlib.Path) -> bool:
    """Ruling 77: путь дома шлюза в команде — буквально `.claude/odata1c` (любой разделитель),
    любая форма подстановки `ODATA1C_HOME`, или буквальное значение переменной этой сессии."""
    return bool(_домашние_совпадения(команда, home))


def _есть_шаблон_оболочки(команда: str) -> bool:
    """Ruling 77 (раунд 2) + Ruling 87 (раунд 3, находка M2-3): к `*`/`?` добавлены раскрытие
    фигурных скобок (`{bases,daemon}.yaml`) и квадратные наборы символов (`[bd]ases.yaml`) — тот же
    приём обхода, что и звёздочка, дешевле `python -c`. Фигурные скобки проверяются образцом
    «запятая внутри» — см. `_ФИГУРНЫЕ_СКОБКИ_RE`."""
    if "*" in команда or "?" in команда:
        return True
    if _ФИГУРНЫЕ_СКОБКИ_RE.search(команда):
        return True
    return bool(_КВАДРАТНЫЕ_СКОБКИ_RE.search(команда))


def _массовое_чтение_дома(команда: str, home: pathlib.Path) -> bool:
    """Ruling 88 (раунд 3, находка M2-4): путь дома шлюза упомянут как КОРЕНЬ (не как один из
    разрешённых подкаталогов `/recipes`, `/bases`, `/logs`) вместе с глаголом чтения/перечисления/
    копирования/архивации — массовое вычитывание дома целиком дешевле даже символа шаблона
    (Ruling 77/87). Листинг без единого символа шаблона (`ls ~/.claude/odata1c/`,
    `Get-ChildItem $env:ODATA1C_HOME`) — намеренное расширение раунда 3: список глаголов включает
    `ls`/`dir`/`Get-ChildItem`/`gci`, не только команды чтения содержимого файлов."""
    if not _ГЛАГОЛЫ_ЧТЕНИЯ_RE.search(команда):
        return False
    for совпадение in _домашние_совпадения(команда, home):
        остаток = команда[совпадение.end() :]
        if _ДОПУЩЕННЫЙ_ПОДКАТАЛОГ_RE.match(остаток):
            continue  # /recipes, /bases, /logs — разрешённый подкаталог, не "корень".
        return True
    return False


def _шаблон_абсолютный(шаблон: str) -> bool:
    """Ruling 86 (раунд 3): `~` (раскрывается `_нормализовать_путь` дальше по конвейеру), ведущий
    `/` (включая POSIX-запись диска Git Bash — `_переписать_posix_диск` разбирает её тоже дальше
    по конвейеру), и буква диска Windows."""
    if шаблон.startswith("~"):
        return True
    if шаблон.replace("\\", "/").startswith("/"):
        return True
    return bool(re.match(r"^[A-Za-z]:[/\\]", шаблон))


_ШАБЛОН_ГРАНИЦА_RE = re.compile(r"[*?\[]")


def _каталог_шаблона(шаблон: str) -> str:
    """Ruling 86/находка M2-2: адрес каталога шаблона — всё до первого символа-границы (`*`, `?`,
    `[` — настоящие метасимволы глоба Python, в отличие от `{}`, которые `Glob` не раскрывает),
    обрезанное до последнего разделителя, чтобы не путать незавершённый хвост сегмента с самим
    каталогом (`bases.y*` → каталог дома, а не файл `bases.y`)."""
    совпадение = _ШАБЛОН_ГРАНИЦА_RE.search(шаблон)
    голова = шаблон[: совпадение.start()] if совпадение else шаблон
    единообразная = голова.replace("\\", "/")
    if "/" in единообразная:
        return единообразная.rsplit("/", 1)[0] or "/"
    return единообразная


def _проверить_glob_шаблон(шаблон: object, дома: list[pathlib.Path]) -> dict | None:
    """Ruling 86 (раунд 3, находка M2-2): `pattern` — основной (обязательный) аргумент `Glob`, а
    правило 2/Ruling 72 проверяло только необязательный `path`, оставляя `pattern` без проверки —
    абсолютный шаблон на дом целиком (`C:/Users/.../odata1c/*`) проходил незамеченным. Защищённое
    имя в шаблоне — `deny` при любом шаблоне (относительном и абсолютном, тем же правилом, что и
    у Bash/PowerShell — `_BASH_ФАЙЛЫ_RE`, префикс включительно); абсолютный шаблон, чей каталог —
    дом шлюза или его предок, — тоже `deny`."""
    if not isinstance(шаблон, str) or not шаблон:
        return None
    if _BASH_ФАЙЛЫ_RE.search(шаблон):
        return _deny(_ПРИЧИНА_ФАЙЛ)
    if _шаблон_абсолютный(шаблон):
        норм_каталог = _нормализовать_путь(_каталог_шаблона(шаблон))
        if _путь_это_дом_или_предок(норм_каталог, дома):
            return _deny(_ПРИЧИНА_ФАЙЛ)
    return None


def _токены_хвоста(хвост: str, powershell: bool) -> tuple[list[str], bool]:
    """Токены текста после слова `odata1c` и признак «разобран». Кавычка, вплотную прилипшая к
    слову (`"odata1c" base set`), в токены не попадает. `shlex` в POSIX-режиме считает обратную
    косую черту экранированием, а PowerShell 5.1 — нет (там экранирует обратная кавычка), поэтому
    для PowerShell косая черта перед кавычкой и обратная кавычка перед кавычкой делают разбор
    недостоверным; в Bash так же действует строка `$'…'` (там апостроф экранируется обратной
    косой чертой, чего `shlex` не знает); незакрытая кавычка — тоже. Для PowerShell недостоверен
    любой хвост с обратной кавычкой: она там экранирует и склеивает слово (``b`ase``), а `shlex`
    о ней не знает. Недостоверный хвост режется
    по пробелам с УДАЛЕНИЕМ кавычек (слово `b"as"e` остаётся словом `base`), и `base set` в нём
    считается снижающим целиком.

    PowerShell 5.1 передаёт native-команде строку с буквальной двойной кавычкой без экранирования,
    и команда видит её границей аргумента: `--label 'a" --gate "off'` и `"a b"" --gate ""off"`
    оболочка превращает в `--label "a" --gate off`, а `shlex` отдаёт один токен. Поэтому для
    PowerShell недостоверен хвост с удвоенной `""` в тексте и хвост, у которого после `shlex` в
    токене осталась `"` (цена — подпись с буквальной двойной кавычкой в PowerShell)."""
    if хвост[:1] in ("'", '"'):
        хвост = хвост.lstrip("'\"")
    маркеры = ('\\"', "`", '""') if powershell else ("$'",)
    недостоверно = any(маркер in хвост for маркер in маркеры)
    if not недостоверно:
        try:
            токены = shlex.split(хвост, posix=True)
        except ValueError:
            pass
        else:
            if not (powershell and any('"' in токен for токен in токены)):
                return токены, True
    return хвост.replace('"', "").replace("'", "").split(), False


# Перенаправление в начале слова: `>`, `>>`, `2>`, `*>`, `&>`, `>|`, `<`, а также `2>&1`, `>&2`,
# `<&-` с целью-дескриптором в самом операторе.
_ОПЕРАТОР_ПЕРЕНАПРАВЛЕНИЯ_RE = re.compile(
    r">\||(?:\d+|\*|&)?>>?(?P<дескриптор>&(?:\d+|-))?|\d*<(?P<дескриптор_вход>&(?:\d+|-))?"
)


def _убрать_перенаправления(хвост: str) -> str:
    """Убирает из текста вне кавычек перенаправления вместе с целью (`2>&1`, `> файл`, `&>log`,
    `>| файл`): оболочка их уберёт, а аргументов команды они не меняют; без этого `2>&1` после
    `base set ut --write off` был бы лишним словом хвоста. Оператор распознаётся только в начале
    слова. Цель с символом раскрытия остаётся в тексте — её проверит разбор хвоста. Ошибка в
    отслеживании кавычек (экранированная кавычка Bash) даёт неразобранный хвост, то есть вопрос."""
    результат: list[str] = []
    i, n = 0, len(хвост)
    кавычка = ""
    while i < n:
        c = хвост[i]
        if кавычка:
            if c == кавычка:
                кавычка = ""
            результат.append(c)
            i += 1
            continue
        if c in "'\"":
            кавычка = c
            результат.append(c)
            i += 1
            continue
        начало_слова = i == 0 or хвост[i - 1].isspace()
        оператор = _ОПЕРАТОР_ПЕРЕНАПРАВЛЕНИЯ_RE.match(хвост, i) if начало_слова else None
        if оператор is None:
            результат.append(c)
            i += 1
            continue
        i = оператор.end()
        if оператор.group("дескриптор") or оператор.group("дескриптор_вход"):
            continue
        while i < n and хвост[i].isspace():
            i += 1
        цель_с, цель_кавычка = i, ""
        while i < n and (цель_кавычка or not хвост[i].isspace()):
            if цель_кавычка:
                цель_кавычка = "" if хвост[i] == цель_кавычка else цель_кавычка
            elif хвост[i] in "'\"":
                цель_кавычка = хвост[i]
            i += 1
        if _похоже_на_раскрытие(хвост[цель_с:i], запятая=True):
            результат.append(" " + хвост[цель_с:i])
    return "".join(результат)


# Символы, которыми оболочка собирает слово из частей или подставляет чужие аргументы: `$`
# (`$s`, `${x}`, `$(…)`, `$'…'`), обратная кавычка (подстановка Bash, экранирование PowerShell),
# скобки (`(…)`, `{…}`), `@` (splat PowerShell `@a`), `%` (`%VAR%` в `cmd`). Проверяются у
# аргументов хвоста `base set` и у значения `--home`; слова `policy set` проверяются списком ниже.
_СИМВОЛЫ_РАСКРЫТИЯ = "$`({@%"
# Разрешительный список (N2 раунда 2 финального ревью): слово в позиции имени ключа, группы
# (`base`/`policy`), подкоманды (`set`/`open`) или класса `policy set` либо распознано, либо
# целиком состоит из букв любого алфавита, цифр, `_`, `.`, `-` и `:` (`custom:<имя>`). Перечень
# запрещённых символов обходился каждый раз новым (`@a`, `%S%`, `^`, `s?t`, `ba[s]e`); список
# разрешённых закрывает их все разом. Отступление от ASCII-перечня ревью: класс `\w` без
# ASCII-ограничения пропускает кириллицу — иначе вопрос получал бы каждый
# `git commit -m "… odata1c плагин …"`, а никакое раскрытие оболочки не превратит кириллицу в
# латинское `base`; `:` нужен классу `custom:<имя>`.
_ДОПУСТИМОЕ_СЛОВО_RE = re.compile(r"[\w.:-]+")


def _похоже_на_раскрытие(токен: str, *, запятая: bool = False) -> bool:
    """Слово содержит символ раскрытия оболочки (`_СИМВОЛЫ_РАСКРЫТИЯ`), с `запятая=True`
    (PowerShell) — ещё и запятую: унарная запятая и `a,b` PowerShell раскладывает в отдельные
    аргументы native-команды (`,--gate,off`). Хук не знает, во что оболочка превратит такое
    слово."""
    символы = _СИМВОЛЫ_РАСКРЫТИЯ + ("," if запятая else "")
    return any(символ in токен for символ in символы)


def _допустимое_слово(токен: str) -> bool:
    """Слово целиком из символов разрешительного списка `_ДОПУСТИМОЕ_СЛОВО_RE`."""
    return _ДОПУСТИМОЕ_СЛОВО_RE.fullmatch(токен) is not None


# Символ сразу за словом `odata1c`, при котором слово — часть пути (`src/odata1c/cli.py`) или
# имени пакета (`odata1c-gate`), а не имя команды. Пробел, `$`, `(` и прочее — вызов
# (`odata1c$() base …`).
_ПРОДОЛЖЕНИЕ_ИМЕНИ = ("/", "\\", "-")

# Имя модуля сразу за словом `odata1c` (`.__main__`, `.cli`) — часть запуска `python -m …`.
_МОДУЛЬ_ЗАПУСКА_RE = re.compile(r"^\.\w+(?=\s|$)")

# Подкоманда, чьё слово не удалось прочитать: оболочка может выполнить `base set`, `policy open`
# или `policy set`, а хук этого не видит — вопрос владельцу (сомнение — в сторону вопроса).
_НЕ_РАЗОБРАНА = "не разобрана"


class _НеРазобрано(Exception):
    """Слово в позиции ключа, группы или подкоманды содержит раскрытие оболочки."""


def _пропустить_ключи(токены: list[str], i: int, powershell: bool = False) -> int:
    """Ключи общего вида до подкоманды (`odata1c --home C:/h base set …`, `base --home C:/h set`):
    `--home` без `=` уносит следующий токен, прочие ключи — только себя. `_НеРазобрано`: имя ключа
    не из разрешительного списка (`-$()-home`, `--ho@me`: оболочка могла собрать из него `--home`
    и сдвинуть позицию подкоманды) или значение `--home` с символом раскрытия (`--home $h`, где
    переменная хранит `<дом> set ut --gate off`; `--home=$HOME/h` — цена правила; в PowerShell —
    и с запятой: `--home C:/h,base,set,ut,--gate,off` там несколько аргументов)."""
    while i < len(токены) and токены[i].startswith("-"):
        имя, равно, значение = токены[i].partition("=")
        if not _допустимое_слово(имя):
            raise _НеРазобрано
        if имя.lower() == "--home":
            if not равно:
                значение = токены[i + 1] if i + 1 < len(токены) else ""
            if _похоже_на_раскрытие(значение, запятая=powershell):
                raise _НеРазобрано
            i += 1 if равно else 2
        else:
            i += 1
    return i


def _подкоманда_владельца(
    токены: list[str], powershell: bool = False
) -> tuple[str, list[str]] | None:
    """`("base set" | "policy open" | "policy set", токены после подкоманды)` или `None` для
    другой команды. Слово группы (`base`/`policy`) или подкоманды (`set`/`open`), которое не
    распознано и не состоит целиком из символов разрешительного списка (`ba$()se`, `s$()et`, `$s`,
    ``b`ase``, `s?t`, `ba[s]e`, `@a`, `%S%`, `s^et`), даёт `(_НЕ_РАЗОБРАНА, [])`: оболочка выполнит
    настоящую команду, а хук её названия не видит."""
    try:
        i = _пропустить_ключи(токены, 0, powershell)
        if i >= len(токены):
            return None
        if токены[i].lower() not in ("base", "policy"):
            return (_НЕ_РАЗОБРАНА, []) if not _допустимое_слово(токены[i]) else None
        группа = токены[i].lower()
        i = _пропустить_ключи(токены, i + 1, powershell)
    except _НеРазобрано:
        return _НЕ_РАЗОБРАНА, []
    if i >= len(токены):
        return None
    имя = f"{группа} {токены[i].lower()}"
    if имя in ("base set", "policy open", "policy set"):
        return имя, токены[i + 1 :]
    if not _допустимое_слово(токены[i]):
        return _НЕ_РАЗОБРАНА, []
    return None


def _снижающие_ключи(
    токены: list[str], разобран: bool = True, powershell: bool = False
) -> tuple[str, list[str]]:
    """Имя базы и ключи `base set` из токенов после `set`, снижающие защиту. Всё, что не защитное
    значение известного ключа, — снижение: неизвестный ключ (сокращение, опечатка), значение,
    которого нет в `_ЗАЩИТНЫЕ_ЗНАЧЕНИЯ`, неразобранный хвост, токен с символом раскрытия оболочки
    (`$s`, `u$s`, `--label=$s`, `@a`, `%S%`) — в том числе значение нейтрального ключа
    (`--label $s`, `--home $s`): переменная может хранить `--gate off`. Позиционное слово — одно,
    имя базы, и оно проходит разрешительный список; любое следующее — лишний аргумент (снижение:
    так закрыт и glob `odata1c base set ut *` с заранее созданными файлами). Для PowerShell запятая
    в любом токене — раскрытие: `,--gate,off` и `a,b` там раскладываются в отдельные аргументы.
    Сомнение — в сторону вопроса; цена — подпись с `(`, `{`, `@` или `%` (`--label 'УТ (розница)'`),
    а в PowerShell и с запятой, тоже даёт вопрос: `shlex` кавычек не помнит."""
    найдено: list[str] = [] if разобран else ["(хвост команды не разобран)"]
    база, i = "?", 0
    while i < len(токены):
        токен = токены[i]
        if _похоже_на_раскрытие(токен, запятая=powershell):
            найдено.append(f"{токен} (раскрытие оболочки)")
            if база == "?" and not токен.startswith("-"):
                база = токен  # слово на месте имени базы: назвать его, а не «?»
            i += 1
            continue
        if токен.startswith("--") and "=" in токен:
            ключ, значение = токен.split("=", 1)
            i += 1
        elif токен.lower() in _КЛЮЧИ_СО_ЗНАЧЕНИЕМ:
            ключ = токен
            значение = токены[i + 1] if i + 1 < len(токены) else ""
            i += 2
            if _похоже_на_раскрытие(значение, запятая=powershell):
                найдено.append(f"{значение} (раскрытие оболочки)")
                continue
        elif токен.lower() in _КЛЮЧИ_СПРАВКИ:
            i += 1
            continue
        elif токен.startswith("-"):
            найдено.append(f"{токен} (неизвестный ключ)")
            i += 1
            continue
        else:
            if база != "?":
                найдено.append(f"{токен} (лишний аргумент)")
            else:
                база = токен
                if not _допустимое_слово(токен):
                    найдено.append(f"{токен} (раскрытие оболочки)")
            i += 1
            continue
        ключ = ключ.lower()
        if ключ in _ЗАЩИТНЫЕ_ЗНАЧЕНИЯ:
            if значение.lower() not in _ЗАЩИТНЫЕ_ЗНАЧЕНИЯ[ключ]:
                найдено.append(f"{ключ} {значение}".strip())
        elif ключ not in _НЕЙТРАЛЬНЫЕ_КЛЮЧИ:
            найдено.append(f"{токен} (неизвестный ключ)")
    return база, найдено


def _set_открывает_поле(токены: list[str], разобран: bool = True, powershell: bool = False) -> bool:
    """`policy set <база> <Сущность.Поле> <класс>`: `keep` и `scan` открывают поле. Класс ищется
    среди всех позиционных токенов, а не только последнего. `--home` (со значением)
    пропускается, `-h`/`--help` ничего не меняет; неизвестный ключ, неразобранный хвост и значение
    `--home` с символом раскрытия оболочки (в PowerShell — и с запятой) — открытие (сомнение в
    сторону вопроса). Все позиционные слова обязаны целиком состоять из символов разрешительного
    списка (`custom:<имя>` проходит; `ke$()ep`, `k?ep`, `ke^ep`, в PowerShell `,Catalog_X.ИНН,keep`
    — нет), а их больше трёх — лишнее слово: открытие. Перенаправления (`2>&1`, `> файл`) до
    разбора убраны `_убрать_перенаправления`."""
    if not разобран:
        return True
    позиционные: list[str] = []
    i = 0
    while i < len(токены):
        токен = токены[i]
        нижний = токен.lower()
        if нижний == "--home":
            значение = токены[i + 1] if i + 1 < len(токены) else ""
            if _похоже_на_раскрытие(значение, запятая=powershell):
                return True
            i += 2
        elif нижний.startswith("--home="):
            if _похоже_на_раскрытие(токен.split("=", 1)[1], запятая=powershell):
                return True
            i += 1
        elif нижний in _КЛЮЧИ_СПРАВКИ:
            i += 1
        elif токен.startswith("-"):
            return True
        else:
            позиционные.append(токен)
            i += 1
    if len(позиционные) > 3 or not all(_допустимое_слово(токен) for токен in позиционные):
        return True
    return any(токен.lower() in _ОТКРЫВАЮЩИЕ_КЛАССЫ for токен in позиционные)


def _команды_владельца(команда: str, *, powershell: bool = False) -> dict | None:
    """Правило 4: `ask` на `base set` со снижением защиты (все вхождения в цепочке — один вопрос с
    объединённой причиной), на `policy open` и на `policy set … keep|scan`; остальные команды
    владельца проходят молча."""
    команда = _ПЕРЕНОС_СТРОКИ_RE.sub(" ", команда)
    базы: list[str] = []
    ключи: list[str] = []
    policy_open = False
    policy_set = False
    не_разобрана = False
    if powershell and "--%" in команда and _ODATA1C_СЛОВО_RE.search(команда):
        # `--%` — «остановить разбор»: остаток строки PowerShell передаёт как есть, раскрывая
        # `%VAR%` по правилам `cmd`; разбор хвоста недостоверен, где бы в команде токен ни стоял.
        не_разобрана = True
    for совпадение in _ODATA1C_СЛОВО_RE.finditer(команда):
        if команда[совпадение.end() : совпадение.end() + 1] in _ПРОДОЛЖЕНИЕ_ИМЕНИ:
            # `src/odata1c/…`, `odata1c-gate@…`: часть пути или имени пакета, не вызов команды.
            continue
        хвост = команда[совпадение.end() :]
        разделитель = _РАЗДЕЛИТЕЛЬ_ЦЕПОЧКИ_RE.search(хвост)
        if разделитель is not None:
            хвост = хвост[: разделитель.start()]
        # `python -m odata1c.__main__ …`, `python -m odata1c.cli …`: имя модуля — часть запуска.
        хвост = _МОДУЛЬ_ЗАПУСКА_RE.sub("", хвост, count=1)
        токены, разобран = _токены_хвоста(_убрать_перенаправления(хвост), powershell)
        найдено = _подкоманда_владельца(токены, powershell)
        if найдено is None:
            continue
        имя, остаток = найдено
        if имя == _НЕ_РАЗОБРАНА:
            не_разобрана = True
            continue
        if имя == "policy open":
            policy_open = True
            continue
        if имя == "policy set":
            policy_set = policy_set or _set_открывает_поле(остаток, разобран, powershell)
            continue
        база, снижающие = _снижающие_ключи(остаток, разобран, powershell)
        if not разобран and (база == "?" or not _допустимое_слово(база)):
            # Хвост не разобран, а базы в нём нет или «база» — не имя (тире, знак препинания) —
            # типично фраза в `git commit -m "… base set — поля"`: «защита базы —» ничего не
            # говорит владельцу, честнее назвать вопрос вопросом.
            не_разобрана = True
        elif снижающие:
            базы.append(база)
            ключи.extend(снижающие)
    причины: list[str] = []
    if ключи:
        причины.append(
            _ПРИЧИНА_BASE_SET.format(база=", ".join(dict.fromkeys(базы)), ключи=", ".join(ключи))
        )
    if policy_open:
        причины.append(_ПРИЧИНА_POLICY_OPEN)
    if policy_set:
        причины.append(_ПРИЧИНА_POLICY_SET)
    if не_разобрана:
        причины.append(_ПРИЧИНА_НЕ_РАЗОБРАНА)
    return _ask("; ".join(причины)) if причины else None


def decide(event: dict, *, home: pathlib.Path) -> dict | None:
    """Решение хука по одному событию `PreToolUse`. Используется и `main`, и тестами напрямую."""
    tool_name = event.get("tool_name")
    if not isinstance(tool_name, str):
        return None

    tool_input = event.get("tool_input")
    if not isinstance(tool_input, dict):
        tool_input = {}

    if _COMMIT_RE.match(tool_name):
        pending_id = tool_input.get("pending_id", "?")
        return _ask(
            f"запись в 1С: pending {pending_id}; подтвердите, что превью показано "
            "пользователю и он согласился"
        )

    поле = _ПУТЬ_ПОЛЕ.get(tool_name)
    if поле is not None:
        дома = _известные_дома(home)
        значение = tool_input.get(поле)
        if isinstance(значение, str) and значение:
            норм_путь = _нормализовать_путь(значение)

            if tool_name in _КАТАЛОЖНЫЕ_ТУЛЫ and _путь_это_дом_или_предок(норм_путь, дома):
                return _deny(_ПРИЧИНА_ФАЙЛ)

            имя = _базовое_имя_для_сравнения(значение)
            if _ИМЯ_ПРЕФИКС_RE.match(имя) and _внутри_какого_то_дома(норм_путь, дома):
                return _deny(_ПРИЧИНА_ФАЙЛ)

        if tool_name == "Glob":
            решение = _проверить_glob_шаблон(tool_input.get("pattern"), дома)
            if решение is not None:
                return решение

        return None

    if tool_name in _КОМАНДНЫЕ_ТУЛЫ:
        команда = tool_input.get("command")
        if isinstance(команда, str) and команда:
            если_файл = _BASH_ФАЙЛЫ_RE.search(команда)
            если_reveal = _BASH_REVEAL_RE.search(команда)
            если_sqlite = _BASH_SQLITE_RE.search(команда)
            if если_файл or если_reveal or если_sqlite:
                return _deny(_ПРИЧИНА_ФАЙЛ)
            if _есть_шаблон_оболочки(команда) and _команда_упоминает_дом_шлюза(команда, home):
                return _deny(_ПРИЧИНА_ШАБЛОН)
            if _массовое_чтение_дома(команда, home):
                return _deny(_ПРИЧИНА_МАССОВОЕ_ЧТЕНИЕ)
            решение = _команды_владельца(команда, powershell=tool_name == "PowerShell")
            if решение is not None:
                return решение
        return None

    return None


def main() -> int:
    # Домашний кодовый режим Windows-консоли не всегда UTF-8 (PEP 686 — с 3.15, наш минимум 3.12);
    # Claude Code передаёт stdin в UTF-8, а причины решений — кириллица. Без явного reconfigure
    # чтение или печать в другой кодировке может упасть исключением ещё до JSON-разбора — тогда
    # решение хука терялось бы молча вместо «код 0, решения нет». Оба потока — пайпы, не консоль,
    # reconfigure на них всегда доступен; suppress — на случай нестандартного окружения запуска.
    for поток in (sys.stdin, sys.stdout):
        with contextlib.suppress(Exception):
            поток.reconfigure(encoding="utf-8")

    try:
        событие = json.loads(sys.stdin.read())
    except Exception:
        return 0
    if not isinstance(событие, dict):
        return 0

    try:
        решение = decide(событие, home=_домашний_каталог())
    except Exception:
        # «Код возврата всегда 0» (интерфейс задачи) — сбой самого хука на неожиданном входе не
        # должен блокировать тул сильнее, чем осознанный deny; тул выполняется как обычно.
        return 0

    if решение is not None:
        # ensure_ascii=True: причина — кириллица, а печать идёт как ASCII-эскейпы (\uXXXX) —
        # валидный JSON, который декодируется одинаково в любой кодовой странице родителя.
        print(json.dumps(решение, ensure_ascii=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
