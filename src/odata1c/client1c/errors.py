"""Перевод ответов 1С в коды ошибок SPEC §5.2."""

from __future__ import annotations

import json


class OdataError(Exception):
    """Ошибка обращения к 1С. `status` — HTTP-статус ответа 1С, `platform_code` — код
    `odata.error.code` платформы; оба есть только у ошибки, которую вернула сама 1С (`map_error`),
    у сетевой ошибки и таймаута клиента — `None`/пустая строка.

    Зачем они отдельно от текста (Ruling 52, задача 7 плана M2): на записи при гейте
    `identifiers+names` текст ошибки 1С модели не отдаётся вовсе — 1С называет в нём объекты и
    пользователей, а новое название детекторы не узнают. Модель получает только статус, код
    платформы и категорию, и их нельзя доставать разбором уже замаскированного текста. Отсутствие
    статуса значит ещё и другое: 1С не ответила, и исход записи неизвестен.

    `platform_error` — тело ответа разобрано как ошибка платформы (`odata.error` или `error` с
    кодом или сообщением). 5xx без неё ответила не 1С — страница веб-сервера или посредника перед
    ней (ФП-2 ревью итоговых правок M2): запрос мог дойти до 1С и выполниться."""

    def __init__(
        self,
        code: str,
        message: str,
        hint: str = "",
        *,
        status: int | None = None,
        platform_code: str = "",
    ) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.hint = hint
        self.status = status
        self.platform_code = platform_code
        self.platform_error = False


# Код `odata.error.code`, которым платформа отвечает на объект по ключу, которого нет (живая
# база 2026-09-12): «9» — «Экземпляр сущности не найден». Неизвестная сущность — «8», «Сущность
# '…' не найдена». Различение по коду, а не по тексту: текст локализован, код — нет.
КОД_ПЛАТФОРМЫ_НЕТ_ОБЪЕКТА = "9"

# Подсказка на отсутствующий объект — одна на оба пути, где он обнаруживается: 404 на пути по
# ключу (`map_error`) и пустая выборка у `get` с `expand` (`tools/service.py`). Ни ключа, ни
# значения в ней нет: ключ мог прийти токеном, и здесь он уже раскрыт.
ПОДСКАЗКА_НЕТ_ОБЪЕКТА = (
    "проверьте ключ: сущность в базе есть, а объекта с таким ключом нет (удалён или ключ неверен); "
    "Ref_Key берите из ответа query/get как есть — реиндекс здесь не поможет"
)


def map_error(status: int, body: str) -> OdataError:
    ошибка = _map_error(status, body)
    ошибка.status = status
    код, текст = _ошибка_платформы(body)
    ошибка.platform_code = код
    ошибка.platform_error = bool(код or текст)
    return ошибка


def _map_error(status: int, body: str) -> OdataError:
    код_платформы, текст_платформы = _ошибка_платформы(body)
    текст = текст_платформы or body.strip()[:500]
    if status in (401, 403):
        return OdataError(
            "auth_failed",
            текст or "1С отклонила учётные данные",
            "проверьте user и password базы командой odata1c base test",
        )
    if status == 404 and код_платформы == КОД_ПЛАТФОРМЫ_НЕТ_ОБЪЕКТА:
        # Находка П6 приёмки через настоящие инструменты: отсутствующий объект приходил кодом
        # `entity_unknown` с советом перестроить индекс — модель послушалась бы и гоняла реиндекс
        # 16,8 МБ метаданных впустую. Сущность известна, не найден объект — свой код.
        return OdataError(
            "object_not_found", текст or "1С не нашла объект по ключу", ПОДСКАЗКА_НЕТ_ОБЪЕКТА
        )
    if status == 404:
        return OdataError(
            "entity_unknown",
            текст or "1С не нашла указанный путь",
            "если сущность точно есть, обновите индекс: odata1c reindex <база>",
        )
    if status in (408, 504):
        return OdataError(
            "timeout",
            текст or "1С не ответила вовремя",
            "сузьте выборку через $select и $top или увеличьте timeout_s базы",
        )
    return OdataError(
        "odata_error", текст or f"1С вернула HTTP {status}", "текст выше — сообщение платформы"
    )


def _ошибка_платформы(body: str) -> tuple[str, str]:
    """Из тела odata.error достать код платформы и человекочитаемое сообщение.

    Тело приходит из сети — доверять его форме нельзя. Если платформа вместо объекта
    отдала список, число или что-то ещё не-словарное (на любом уровне вложенности),
    считаем сообщение неразобранным и возвращаем пустые строки: вызывающий код (map_error)
    в этом случае берёт сырой текст тела как есть, но не падает необработанным исключением.
    """
    try:
        data = json.loads(body)
    except (ValueError, TypeError):
        return "", ""
    if not isinstance(data, dict):
        return "", ""
    ошибка = data.get("odata.error") or data.get("error") or {}
    if not isinstance(ошибка, dict):
        return "", ""
    код = ошибка.get("code")
    код = str(код) if isinstance(код, str | int) and not isinstance(код, bool) else ""
    сообщение = ошибка.get("message")
    if isinstance(сообщение, dict):
        return код, str(сообщение.get("value", ""))
    return код, str(сообщение or "")
