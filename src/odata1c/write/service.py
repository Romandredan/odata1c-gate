    """Ранний проход клиента, который запоминает сырой текст ошибки 1С до замены — для журнала.

    Клиент применяет проход к тексту ошибки ДО `map_error` (Ruling 25), и `OdataError.message`
    приходит уже с токенами на месте раскрытого. Журнал — файл владельца, в него пишется полный
    текст как есть (решение 3 контролёра). Сырой текст живёт в этом объекте до записи в журнал и
    умирает с вызовом — второго места хранения реальных значений нет."""

