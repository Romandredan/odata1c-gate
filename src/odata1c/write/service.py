def _есть_версия(описание: EntityDescription) -> bool:
    return any(поле["name"] == "DataVersion" for поле in описание.fields)


def _все_поля_записи(описание: EntityDescription) -> list[str]:
    """Все поля сущности, кроме табличных частей, — выбор чтения записи без `DataVersion`."""
    return [
        поле["name"] for поле in описание.fields if not поле["edm_type"].startswith("Collection(")
    ]


def _выбор_коммита(
    описание: EntityDescription, операция: PendingOp, представление: list[str]
) -> list[str]:
    """`$select` перечитывания в `commit` — и «до» (шаг 5), и «после» (шаг 8), одним набором.

    Запись без `DataVersion` — все поля записи, тот же набор, что при подготовке (Ruling 55:
    хэш сравним, только если поля те же). Прочие — поля, которые запись меняет (для журнала:
    откат `update` берёт их «до», SPEC §7.6), отпечаток `DataVersion` (P8: в журнале «до» и
    «после», разрыв счётчика виден), служебные поля операции и представление объекта (Ruling
    44). Табличная часть — тоже, если операция её меняет (проект M3b §5.2): без неё журнал «до» не
    нёс бы старый список, а откат такой записи (SPEC §7.6) был бы нечем строить — `_форма_отката`
    берёт прежний массив ровно отсюда."""
    if not _есть_версия(описание):
        return _все_поля_записи(описание)
    поля = {поле["name"]: поле["edm_type"] for поле in описание.fields}
    тело = операция.request.get("json")
    выбор = [имя for имя in (тело if isinstance(тело, dict) else ()) if имя in поля]
    for имя in ("DataVersion", *_СЛУЖЕБНЫЕ_КОММИТА.get(операция.op, ()), *представление):
        if имя in поля and имя not in выбор:
            выбор.append(имя)
    return выбор


def _ключ_пути(ключ: dict):
    """Ключ операции (`PendingOp.key`, реальные значения) → аргумент `build_get`: простой — GUID
    строкой, составной — словарём, как его раскрыл гейт при подготовке."""
    if list(ключ) == ["Ref_Key"]:
        return ключ["Ref_Key"]
    return dict(ключ)


def _реальные(значение, раскрытое: RevealedValues):
    """Данные 1С с реальным содержимым: строки раннего прохода (`ScrubbedText`) развёрнуты в
    исходное значение своего места (Б-3), на любой глубине. Для журнала (файл владельца: откат
    `update` пишет «было» обратно в 1С, и токен вместо значения записал бы в базу токен) и для
    отпечатка записи регистра (строки раннего прохода подготовки и `commit` иначе дали бы разный
    хэш при неизменной записи)."""
    if isinstance(значение, dict):
        return {ключ: _реальные(поле, раскрытое) for ключ, поле in значение.items()}
    if isinstance(значение, list):
        return [_реальные(элемент, раскрытое) for элемент in значение]
    if isinstance(значение, ScrubbedText):
        return str(_текущее_реальное(значение, раскрытое))
    return значение


def _для_журнала(объект: dict | None, раскрытое: RevealedValues) -> dict | None:
    if объект is None:
        return None
    return _реальные(strip_service(объект, keep_data_version=True), раскрытое)


def _отпечаток(описание: EntityDescription, текущее: dict, раскрытое: RevealedValues) -> str | None:
    """Отпечаток состояния объекта для `commit` (P8: оптимистической блокировки у OData 1С нет,
    отпечаток — единственная защита от чужой записи между превью и `commit`).

    У объекта — `DataVersion` (счётчик записей, растёт на любой записи). У записи регистра его
    нет (Ruling 55): отпечаток — SHA-256 канонического JSON (сортированные ключи) всех полей
    записи с реальными значениями. `None` — у сущности с `DataVersion` его нет в ответе: `commit`
    тогда отказывает (`pending_stale`), а не пишет вслепую."""
    if _есть_версия(описание):
        return _версия(текущее.get("DataVersion"), раскрытое)
    данные = _реальные(strip_service(текущее), раскрытое)
    канон = json.dumps(данные, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return "sha256:" + hashlib.sha256(канон.encode("utf-8")).hexdigest()


def _ключ_созданного(описание: EntityDescription, ответ, раскрытое: RevealedValues) -> dict | None:
    """Ключ созданного объекта из ответа POST (P8: 201, объект целиком). У справочника и
    документа — `Ref_Key` (проверяется форма GUID: иначе путь перечитывания строился бы из
    чего попало), у записи регистра — поля ключа. Нет ключа — `None`."""
    if not isinstance(ответ, dict):
        return None
    ключ = {}
    for поле in описание.key_fields:
        значение = ответ.get(поле)
        if значение is None:
            return None
        ключ[поле] = _реальные(значение, раскрытое)
    if описание.key_fields == ["Ref_Key"] and not (
        isinstance(ключ["Ref_Key"], str) and _GUID.match(ключ["Ref_Key"])
    ):
        return None
    return ключ


# Ответы посредника (веб-сервер, прокси перед 1С), после которых исход записи неизвестен: 408 и
# 504 — посредник не дождался 1С, 502 — ответ сверху не получен или испорчен (Т7-4 ревью). Во
# всех трёх случаях 1С могла получить запрос и выполнить его.
_ПОСРЕДНИК_ПО_ТАЙМАУТУ = frozenset({408, 502, 504})


def _исход_неизвестен(ошибка: OdataError) -> bool:
    """1С не ответила (сеть, таймаут клиента), ответил посредник (408/502/504) или пришёл 5xx
    без ошибки платформы в теле: запрос мог дойти до 1С и выполниться. Ответ 1С с её ошибкой
    (`odata.error`) — запись не выполнена.

    5xx без `odata.error` (ФП-2 ревью итоговых правок M2) — HTML-страница «Internal Server
    Error» или «Service Unavailable» веб-сервера перед 1С: её прислала не 1С, и после неё 1С
    могла зафиксировать транзакцию (обрыв связи веб-расширения с кластером). Прежде такой ответ
    давал «запись не выполнена, подготовьте заново», и у `create` это дубль. 503 — туда же: обычно
    запрос не передан, но для записи безопасная сторона — «неизвестен», лишнее чтение дешевле
    дубля. Настоящая ошибка 1С на 500 — отказ, как прежде."""
    if ошибка.status is None or ошибка.status in _ПОСРЕДНИК_ПО_ТАЙМАУТУ:
        return True
    return 500 <= ошибка.status <= 599 and not ошибка.platform_error


def _текст_для_журнала(ошибка: OdataError, сырой: str | None) -> str:
    статус = f"HTTP {ошибка.status}" if ошибка.status is not None else "без ответа 1С"
    return f"{ошибка.code} ({статус}): {сырой if сырой is not None else ошибка.message}"


def _записать_журнал(вызов, *аргументы, **поля) -> bool:
    """Запись в журнал ПОСЛЕ отправки запроса: её отказ не отменяет того, что уже произошло в 1С,
    и не должен подменять ответ модели. В журнал демона — только факт (`commit_id` и класс
    отказа), без значений. `True` — записано."""
    try:
        вызов(*аргументы, **поля)
    except (WriteError, RuntimeError, sqlite3.Error) as отказ:
        # `sqlite3.Error` — у `mark_undone` (задача 8): он, в отличие от `close_commit`, отказ
        # SQLite в `WriteError` не переводит.
        _log.error(
            "журнал записи не дописан после отправки запроса, commit_id=%s (%s)",
            аргументы[0] if аргументы else "?",
            type(отказ).__name__,
        )
        return False
    return True


def _дописать(журнал: Journal, commit_id: str, **поля) -> None:
    """Журнал «после» на пути ошибки 1С (см. `_записать_журнал`)."""
    _записать_журнал(журнал.close_commit, commit_id, **поля)


def _как_найти(операция: PendingOp, представление: list[str]) -> str:
    """Чем модели проверить объект после неизвестного исхода (Т7-5 ревью). У прямого `create`
    ключа нет — объект ищется выборкой по полям представления, со значениями из вызова
    `odata1c_create`; у прочих — чтение по ключу. Имена полей — из индекса.

    Значения для отбора — из аргументов своего вызова `odata1c_create`, а не из превью: после
    Ruling 63 литерал в превью показан пометкой «значение из запроса», и построить по нему отбор
    нельзя.

    Откат (`undo_of` не `None` — Minor 1 ревью хвостов M3b): модель звала `odata1c_undo`, а не
    `odata1c_create`, даже когда `op` совпадает с прямым путём — откат `delete_record` воссоздаёт
    запись тем же `op == "create"`. Подсказка про выборку по представлению здесь ссылалась бы на
    «ваш вызов odata1c_create», которого не было; ключ записи откату известен из журнала (он уже
    был в превью операции), поэтому читается по ключу — той же подсказкой, что у прочих операций."""
    if операция.op == "create" and операция.undo_of is None:
        поля = (
            f" с отбором по полям представления ({', '.join(представление)}) со значениями из "
            "вашего вызова odata1c_create"
            if представление
            else ""
        )
        return f"найдите объект выборкой odata1c_query по {операция.entity}{поля}"
    return "прочитайте объект по ключу (odata1c_get)"


