@dataclass
class _Ход:
    """Докуда дошёл `commit` — от этого зависит, остаётся ли операция `pending`.

    `отправлено` — запрос к 1С начат (после записи журнала «до»): с этого момента повторять его
    нельзя при любом исходе. `устарело` — отпечаток не совпал: операция устарела навсегда. Не
    потому, что отпечаток не может совпасть снова (`DataVersion` назад не идёт, но хэш записи
    регистра вернётся, если значение вернули, Ruling 55), а потому, что превью строилось на
    состоянии, которое уже менялось, а переподготовка дешева. Прочие отказы (пользователь, лимит,
    сбой чтения, журнал) запрос не начинали — операцию можно подтвердить снова."""

    отправлено: bool = False
    выполнено: bool = False
    устарело: bool = False
    # Ответ повтору на случай отмены вызова после отправки — уже через стража базы (инвариант 1).
    страховка: str | None = None

    def итог(self) -> str | None:
        if self.выполнено:
            return "committed"
        if self.отправлено or self.устарело:
            return "failed"
        return None


class _ЗапоминающийПроход:
    """Ранний проход клиента, который запоминает сырой текст ошибки 1С до замены — для журнала.

    Клиент применяет проход к тексту ошибки ДО `map_error` (Ruling 25), и `OdataError.message`
    приходит уже с токенами на месте раскрытого. Журнал — файл владельца, в него пишется полный
    текст как есть (решение 3 контролёра). Сырой текст живёт в этом объекте до записи в журнал и
    умирает с вызовом — второго места хранения реальных значений нет."""

    __slots__ = ("_проход", "сырой")

    def __init__(self, проход) -> None:
        self._проход = проход
        self.сырой: str | None = None

    def __call__(self, text: str) -> str:
        self.сырой = text
        return self._проход(text)

    def load(self, text: str):
        return self._проход.load(text)


def _есть_версия(описание: EntityDescription) -> bool:
    return any(поле["name"] == "DataVersion" for поле in описание.fields)


def _все_поля_записи(описание: EntityDescription) -> list[str]:
    """Все поля сущности, кроме табличных частей, — выбор чтения записи без `DataVersion`."""
    return [
        поле["name"] for поле in описание.fields if not поле["edm_type"].startswith("Collection(")
    ]


def _выбор_коммита(
    описание: EntityDescription, операция: PendingOp, представление: list[str]
) -> list[str]:
    """`$select` перечитывания в `commit` — и «до» (шаг 5), и «после» (шаг 8), одним набором.

    Запись без `DataVersion` — все поля записи, тот же набор, что при подготовке (Ruling 55:
    хэш сравним, только если поля те же). Прочие — поля, которые запись меняет (для журнала:
    откат `update` берёт их «до», SPEC §7.6), отпечаток `DataVersion` (P8: в журнале «до» и
    «после», разрыв счётчика виден), служебные поля операции и представление объекта (Ruling
    44). Табличные части не выбираются: результат — шапка объекта."""
    if not _есть_версия(описание):
        return _все_поля_записи(описание)
    поля = {поле["name"]: поле["edm_type"] for поле in описание.fields}
    тело = операция.request.get("json")
    выбор = [
        имя
        for имя in (тело if isinstance(тело, dict) else ())
        if имя in поля and not поля[имя].startswith("Collection(")
    ]
    for имя in ("DataVersion", *_СЛУЖЕБНЫЕ_КОММИТА.get(операция.op, ()), *представление):
        if имя in поля and имя not in выбор:
            выбор.append(имя)
    return выбор


def _ключ_пути(ключ: dict):
    """Ключ операции (`PendingOp.key`, реальные значения) → аргумент `build_get`: простой — GUID
    строкой, составной — словарём, как его раскрыл гейт при подготовке."""
    if list(ключ) == ["Ref_Key"]:
        return ключ["Ref_Key"]
    return dict(ключ)


def _реальные(значение, раскрытое: RevealedValues):
    """Данные 1С с реальным содержимым: строки раннего прохода (`ScrubbedText`) развёрнуты в
    исходное значение своего места (Б-3), на любой глубине. Для журнала (файл владельца: откат
    `update` пишет «было» обратно в 1С, и токен вместо значения записал бы в базу токен) и для
    отпечатка записи регистра (строки раннего прохода подготовки и `commit` иначе дали бы разный
    хэш при неизменной записи)."""
    if isinstance(значение, dict):
        return {ключ: _реальные(поле, раскрытое) for ключ, поле in значение.items()}
    if isinstance(значение, list):
        return [_реальные(элемент, раскрытое) for элемент in значение]
    if isinstance(значение, ScrubbedText):
        return str(_текущее_реальное(значение, раскрытое))
    return значение


def _для_журнала(объект: dict | None, раскрытое: RevealedValues) -> dict | None:
    if объект is None:
        return None
    return _реальные(strip_service(объект, keep_data_version=True), раскрытое)


def _отпечаток(описание: EntityDescription, текущее: dict, раскрытое: RevealedValues) -> str | None:
    """Отпечаток состояния объекта для `commit` (P8: оптимистической блокировки у OData 1С нет,
    отпечаток — единственная защита от чужой записи между превью и `commit`).

    У объекта — `DataVersion` (счётчик записей, растёт на любой записи). У записи регистра его
    нет (Ruling 55): отпечаток — SHA-256 канонического JSON (сортированные ключи) всех полей
    записи с реальными значениями. `None` — у сущности с `DataVersion` его нет в ответе: `commit`
    тогда отказывает (`pending_stale`), а не пишет вслепую."""
    if _есть_версия(описание):
        return _версия(текущее.get("DataVersion"), раскрытое)
    данные = _реальные(strip_service(текущее), раскрытое)
    канон = json.dumps(данные, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return "sha256:" + hashlib.sha256(канон.encode("utf-8")).hexdigest()


def _ключ_созданного(описание: EntityDescription, ответ, раскрытое: RevealedValues) -> dict | None:
    """Ключ созданного объекта из ответа POST (P8: 201, объект целиком). У справочника и
    документа — `Ref_Key` (проверяется форма GUID: иначе путь перечитывания строился бы из
    чего попало), у записи регистра — поля ключа. Нет ключа — `None`."""
    if not isinstance(ответ, dict):
        return None
    ключ = {}
    for поле in описание.key_fields:
        значение = ответ.get(поле)
        if значение is None:
            return None
        ключ[поле] = _реальные(значение, раскрытое)
    if описание.key_fields == ["Ref_Key"] and not (
        isinstance(ключ["Ref_Key"], str) and _GUID.match(ключ["Ref_Key"])
    ):
        return None
    return ключ


# Ответы посредника (веб-сервер, прокси перед 1С), после которых исход записи неизвестен: 408 и
# 504 — посредник не дождался 1С, 502 — ответ сверху не получен или испорчен (Т7-4 ревью). Во
# всех трёх случаях 1С могла получить запрос и выполнить его.
_ПОСРЕДНИК_ПО_ТАЙМАУТУ = frozenset({408, 502, 504})


def _исход_неизвестен(ошибка: OdataError) -> bool:
    """1С не ответила (сеть, таймаут клиента) или ответил посредник (408/502/504): запрос мог
    дойти до 1С и выполниться. Ответ 1С с кодом ошибки — запись не выполнена."""
    return ошибка.status is None or ошибка.status in _ПОСРЕДНИК_ПО_ТАЙМАУТУ


def _текст_для_журнала(ошибка: OdataError, сырой: str | None) -> str:
    статус = f"HTTP {ошибка.status}" if ошибка.status is not None else "без ответа 1С"
    return f"{ошибка.code} ({статус}): {сырой if сырой is not None else ошибка.message}"


def _записать_журнал(вызов, *аргументы, **поля) -> bool:
    """Запись в журнал ПОСЛЕ отправки запроса: её отказ не отменяет того, что уже произошло в 1С,
    и не должен подменять ответ модели. В журнал демона — только факт (`commit_id` и класс
    отказа), без значений. `True` — записано."""
    try:
        вызов(*аргументы, **поля)
    except (WriteError, RuntimeError) as отказ:
        _log.error(
            "журнал записи не дописан после отправки запроса, commit_id=%s (%s)",
            аргументы[0] if аргументы else "?",
            type(отказ).__name__,
        )
        return False
    return True


def _дописать(журнал: Journal, commit_id: str, **поля) -> None:
    """Журнал «после» на пути ошибки 1С (см. `_записать_журнал`)."""
    _записать_журнал(журнал.close_commit, commit_id, **поля)


def _как_найти(операция: PendingOp, представление: list[str]) -> str:
    """Чем модели проверить объект после неизвестного исхода (Т7-5 ревью). У `create` ключа нет —
    объект ищется выборкой по полям представления из превью; у прочих — чтение по ключу. Имена
    полей — из индекса."""
    if операция.op == "create":
        поля = (
            f" с отбором по полям представления ({', '.join(представление)})"
            if представление
            else ""
        )
        return f"найдите объект выборкой odata1c_query по {операция.entity}{поля} из превью"
    return "прочитайте объект по ключу (odata1c_get)"


def _ошибка_записи(
    уровень: str, ошибка: OdataError, commit_id: str, неизвестен: bool, поиск: str
) -> WriteError:
    """Ответ модели на ошибку 1С при записи (Ruling 52).

    Исход неизвестен — прямо так и сказано: повтор вслепую может записать второй раз, а
    повторный `commit` этого `pending_id` запрос не повторит. `поиск` — как проверить объект
    (`_как_найти`). На уровне `identifiers+names` текст ошибки 1С не отдаётся вовсе — только
    HTTP-статус, код платформы, категория и где полный текст; на прочих уровнях — текст как пришёл
    от клиента (ранний проход уже заменил раскрытое), дальше `gate.error` маскирует его без записи
    в словарь (Ruling 48)."""
    журнал = f"полный текст — в журнале записи, commit_id {commit_id}"
    if неизвестен:
        return WriteError(
            ошибка.code,
            "ответ 1С на запись не получен или не разобран — исход неизвестен: запрос мог "
            f"выполниться; {журнал}",
            hint=f"не готовьте операцию заново вслепую: сначала {поиск} и сравните с превью; "
            "повторный odata1c_commit этого pending_id запрос не повторит",
        )
    категория = _КАТЕГОРИИ.get(ошибка.status, "ошибка 1С при записи")
    подсказка = (
        "запись не выполнена; исправьте причину и подготовьте операцию заново"
        if "odata1c_query" in поиск
        else "запись не выполнена; прочитайте объект (odata1c_get), чтобы понять причину, и при "
        "необходимости подготовьте операцию заново"
    )
    if уровень == "identifiers+names":
        код = ошибка.platform_code if _КОД_ПЛАТФОРМЫ.fullmatch(ошибка.platform_code) else "—"
        return WriteError(
            ошибка.code,
            f"1С отказала в записи: HTTP {ошибка.status}, код ошибки платформы {код}, категория: "
            f"{категория}. Текст ошибки 1С на уровне гейта identifiers+names не показывается — "
            f"он может называть объекты и пользователей; {журнал}",
            hint=подсказка,
        )
    return WriteError(
        ошибка.code,
        f"1С отказала в записи (HTTP {ошибка.status}, категория: {категория}): {ошибка.message}. "
        f"{журнал[0].upper()}{журнал[1:]}",
        hint=подсказка,
    )


def _одинаково(отправлено, стало) -> bool:
    """Записала ли 1С отправленное: числа — по значению (1С отдаёт `1` там, где ушло `1.0`),
    GUID — без учёта регистра, прочее — точно."""
    if isinstance(отправлено, bool) or isinstance(стало, bool):
        return отправлено is стало
    if isinstance(отправлено, int | float) and isinstance(стало, int | float):
        return float(отправлено) == float(стало)
    if isinstance(отправлено, str) and isinstance(стало, str) and _GUID.match(отправлено):
        return отправлено.lower() == стало.lower()
    return отправлено == стало


def _расхождения(операция: PendingOp, после: dict) -> list[str]:
    """P8: 1С молча обрезает длину, не принимает значение неверного типа и отвечает 200 —
    видно только перечитыванием. Расхождение — предупреждение с именем поля (оно из тела,
    проверенного по индексу), без значений."""
    if операция.op == "action":
        ожидается = операция.request["path"].endswith("/Post")
        if "Posted" in после and после["Posted"] is not ожидается:
            return [
                "признак проведения после действия не тот, что ожидался — проверьте документ "
                "(odata1c_get)"
            ]
        return []
    тело = операция.request.get("json")
    if not isinstance(тело, dict):
        return []
    return [
        f"поле «{имя}»: значение в 1С после записи отличается от отправленного (обрезка длины, "
        "приведение типа или значение не принято) — сравните результат с превью"
        for имя, отправлено in тело.items()
        if имя in после
        and not isinstance(отправлено, dict | list)
        and not _одинаково(отправлено, после[имя])
    ]


def _показ(значение) -> str:
    return json.dumps(значение, ensure_ascii=False)


def _текст_подтверждения(операция: PendingOp) -> str:
    """Текст диалога elicitation по превью операции — до стража (его прогоняет `_спросить`).
    Всё, что видит пользователь, — то же, что видела модель в ответе подготовки: объект, ключ,
    строки превью."""
    превью = операция.preview
    строки = [
        f"Запись в 1С: база «{операция.base}» (роль {операция.role}), {операция.entity}, "
        f"операция {операция.op}."
    ]
    if превью.get("key") is not None:
        строки.append(f"Ключ: {_показ(превью['key'])}")
    if превью.get("object"):
        строки.append(f"Объект: {_показ(превью['object'])}")
    if "action" in превью:
        строки.append(f"Действие: {превью['action']}")
    for строка in превью.get("changes", ()):
        строки.append(
            f"• {строка['field']}: {_показ(строка['before'])} → {_показ(строка['after'])}"
        )
    for строка in превью.get("body", ()):
        строки.append(f"• {строка['field']}: {_показ(строка['value'])}")
    if превью.get("summary"):
        строки.append(превью["summary"])
    строки.append("Выполнить запись?")
    return "\n".join(строки)


def _ключ_без_гейта(ключ) -> dict | None:
    """Ключ, который можно отдать без маски: только простой `Ref_Key` формы GUID (инвариант 6)."""
    if isinstance(ключ, dict) and list(ключ) == ["Ref_Key"]:
        значение = ключ["Ref_Key"]
        if isinstance(значение, str) and _GUID.match(значение):
            return {"Ref_Key": значение}
    return None


def _через_стража(гейт, конверт: dict, раскрытое: RevealedValues, commit_id: str) -> str | None:
    """Сериализация и страж базы (`gate.finish`) для страховочного ответа. Сбой самого стража —
    `None`: вызывающий тогда отдаёт отказ без данных стражем сервиса."""
    try:
        return гейт.finish(конверт, раскрытое)
    except Exception:
        _log.error("страховочный ответ commit не прошёл стража, commit_id=%s", commit_id)
        return None


def _конверт_выполнено(операция: PendingOp, base_config, описание: EntityDescription, ключ) -> dict:
    """Ответ повтору `commit`, чей вызов отменили после ответа 1С успехом (журнал — `committed` с
    ключом): запись выполнена, результат не показан. У `create` иначе естественный шаг модели —
    подготовить заново, то есть дубль (Т7-1 ревью). Ключ — уже в токенах (`_ключ_без_после`)."""
    return {
        "commit_id": операция.commit_id,
        "base": base_config.name,
        "role": base_config.role,
        "entity": описание.name,
        "key": ключ,
        "op": операция.op,
        "result": None,
        "undo": f'odata1c_undo(commit_id="{операция.commit_id}")',
        "warnings": [
            "вызов commit прервался после ответа 1С: запись выполнена, результат не показан — "
            "прочитайте объект сами"
        ],
    }


def _конверт_прерван(операция: PendingOp, поиск: str) -> dict:
    """Ответ повтору `commit`, чей вызов отменили посреди запроса: ответа 1С не было — исход
    неизвестен, повторять запись нельзя."""
    return {
        "error": {
            "code": "internal",
            "message": "commit прерван после отправки запроса в 1С — исход неизвестен, смотрите "
            f"журнал записи, commit_id {операция.commit_id}",
            "hint": f"не повторяйте запись вслепую: сначала {поиск} и сравните с превью",
        }
    }
