def _табличные_части_тела(
    описание: EntityDescription, data, describe: Callable[[str], EntityDescription | None]
) -> dict[str, EntityDescription]:
    """Табличные части из тела `create` и `update` (проект M3b §5.2, задача 6): имя поля →
    описание сущности его строк.

    Сущность строки — `<владелец>_<поле>` среди детей владельца, тем же правилом, что у
    `ToolService._навигации` (табличная часть навигацией не приходит, проба P4), а не разбором
    `…_RowType` из типа `Collection(…)`: одно правило родства на чтение и запись.

    Поле-коллекция без сущности строки отклоняется здесь же, при разборе, — до разрешений строк
    и проверки тела (Н6r2-2 повторного ревью задачи 6): проверить строки нечем, разрешения строк
    не к чему применить. На полном УТ такие поля — `RecordSet` зависимых регистров (строки набора
    — `…_RecordType`, не ребёнок владельца), и их раньше отклоняет шаг 3 `check_write`
    (Ruling 57); здесь — второй рубеж, для любой другой коллекции без опубликованной сущности
    строки. Поля и дети владельца — из одного снимка индекса, поэтому реиндекс
    этого не меняет, и подсказки «обновите индекс» здесь нет. Имя в тексте — поле владельца,
    найденное в индексе с типом `Collection(…)`, а не ввод модели (Ruling 53)."""
    if not isinstance(data, dict):
        return {}
    типы = {поле["name"]: поле["edm_type"] for поле in описание.fields}
    части: dict[str, EntityDescription] = {}
    for имя in data:
        if not isinstance(имя, str) or not типы.get(имя, "").startswith("Collection("):
            continue
        дочерняя = f"{описание.name}_{имя}"
        описание_строки = describe(дочерняя) if дочерняя in описание.children else None
        if описание_строки is None:
            raise _отказ(
                f"поле «{имя}» сущности «{описание.name}» — коллекция без своей сущности строки: "
                "табличные части этой сущности записью не задаются",
                # Minor 3 ревью хвостов M3b: «уберите из тела» звучало бы советом потерять часть
                # (актуально и у `update`, где поле уже есть в объекте) — формулировка нейтральна
                # для обеих операций, без совета о действии со значением.
                hint=f"поле «{имя}» этой записью не задаётся: у её строк нет своей сущности в "
                "$metadata базы",
            )
        части[имя] = описание_строки
    return части


def _права_строк(data: dict, части: dict) -> tuple[tuple[str, tuple[str, ...]], ...]:
    """Аргументы проверки разрешений строк табличных частей: пара «сущность строки → имена её
    полей в теле» на каждую табличную часть, в порядке тела.

    Отдельно от самой проверки — ради перепроверки при `commit` (SPEC §7.1, поправка 2026-09-14):
    она обязана проверять то же самое, а к тому времени ни тела от модели, ни описаний из
    индекса под рукой нет. Здесь только имена — они и ложатся в `PendingOp.write_rows`.

    Имена полей дедуплицируются с сохранением порядка первого появления: `check_fields` отказывает
    на первом совпадении с `deny_fields`, и первое совпадение от дедупликации не меняется."""
    итог: list[tuple[str, tuple[str, ...]]] = []
    for имя, описание_строки in части.items():
        строки = data[имя]
        поля: tuple[str, ...] = ()
        if isinstance(строки, list):
            поля = tuple(
                dict.fromkeys(
                    поле
                    for строка in строки
                    if isinstance(строка, dict)
                    for поле in строка
                    if isinstance(поле, str)
                )
            )
        итог.append((описание_строки.name, поля))
    return tuple(итог)


def _проверить_права_строк(
    base_config, строки: tuple[tuple[str, tuple[str, ...]], ...], скрытые: frozenset[str]
) -> None:
    """Разрешения строк табличных частей — те же шаги SPEC §7.1, что у шапки, но у сущности
    строки, и в том же порядке, что у `check_write`: скрытая табличная часть → `entity_hidden`
    (шаг 1), сущность строки в `deny_entities` → `permission_denied` (шаг 5, Н6-2 ревью задачи 6),
    поле строки из `deny_fields` → `field_write_denied` (шаг 6). Иначе запрет владельца на
    табличную часть обходился бы созданием объекта с её строками. Каждый шаг — по всем табличным
    частям тела, прежде следующего: первый сработавший шаг побеждает, как у шапки.

    `строки` — выход `_права_строк`: подготовка собирает их из тела и индекса, `commit`
    перепроверяет теми же, взятыми из `PendingOp.write_rows`.

    Скрытость — по полному набору скрытых (`ToolService._скрытые`, Ruling 30): он содержит и
    потомков скрытого владельца, хотя до строк такой владелец не доходит — `_resolve_entity`
    отказал раньше. `allow_entities` к сущности строки не применяется: он перечисляет объекты, а
    не их табличные части (`check_entity_denied`)."""
    for сущность, _ in строки:
        if сущность in скрытые:
            raise WriteError("entity_hidden", f"сущность «{сущность}» скрыта политикой гейта")
    for сущность, _ in строки:
        check_entity_denied(base_config, сущность)
    for сущность, поля in строки:
        check_fields(base_config, сущность, поля)


def _раскрыть_тело(
    гейт,
    описание: EntityDescription,
    data: dict,
    части: dict,
    *,
    строение,
    раскрытое,
    current: dict | None,
) -> dict:
    """Токены тела → реальные значения по классам той сущности, чьё поле пишется (Ruling 56).
    Шапка — одним `inbound_write` от имени владельца; каждая строка табличной части — своим, от
    имени сущности строки (`<владелец>_<табличная часть>`): её политика, лестница написаний по её
    полям и признак структурности (Ruling 43) — те же, по которым строку маскирует чтение.
    Раскрытие строк от владельца (путь `ТабличнаяЧасть/Поле`) брало бы класс по имени поля на
    владельце: токен `addr` уходил в поле строки, открытое по её сущности (Н6-1), а строки с
    корнем защищаемого имени в имени табличной части отклонялись правилом пути отбора (Н6-3).

    `current` — текущее состояние объекта, как его вернул `client.get`: `None` — у `create` (нет
    объекта, нечему быть текущим), словарь — у `update` (объект уже существует, лестница 1.2
    сравнивает написание с ним). У строк табличной части `current` — не строение владельца, а
    СВОЁ: старая строка того же `LineNumber` (проект §5.2 — строки сопоставляются по номеру, как в
    `rows_diff`), у новой строки (номера не было в старом состоянии) — `None`, тот же путь, что у
    `create`. Номер сопоставления — строкой (`rows_diff._ключ`): 1С отдаёт `LineNumber` текущего
    состояния то строкой, то числом (проба P9), и без приведения строка не находила бы старую себя
    по типу несовпадающего номера.

    Нумерация токенов в отказе — общая на всё тело и по порядку тела (`number_tokens`, Ruling 54):
    номер не начинается заново в каждой строке. Место в отказе называет табличную часть и номер
    строки; гейту передаётся только номер (`row`), имя табличной части он выводит из сущности
    строки по индексу сам (Н6r2-1 повторного ревью задачи 6) — текста отсюда в отказ не идёт.

    Порядок в результате — порядок тела. Вызывается после проверки тела: у каждой табличной части
    есть сущность строки, строки — словари, уже пронумерованные правилом §5.1."""
    номера = number_tokens(data)
    шапка = {поле: значение for поле, значение in data.items() if поле not in части}
    реальная_шапка = гейт.inbound_write(
        шапка,
        entity=описание.name,
        shape=строение,
        current=current,
        revealed=раскрытое,
        numbering=номера,
    )
    реальное: dict = {}
    for поле, значение in data.items():
        if поле not in части:
            реальное[поле] = реальная_шапка[поле]
            continue
        старые_по_номеру = (
            {
                ключ_строки(старая): старая
                for старая in current.get(поле, ())
                if isinstance(старая, dict)
            }
            if isinstance(current, dict)
            else {}
        )
        реальное[поле] = [
            гейт.inbound_write(
                строка,
                entity=части[поле].name,
                shape=строение,
                current=старые_по_номеру.get(ключ_строки(строка)),
                revealed=раскрытое,
                numbering=номера,
                row=номер,
            )
            for номер, строка in enumerate(значение, start=1)
        ]
    return реальное


def _проверить_тело_create(описание: EntityDescription, data, части: dict) -> None:
    """Поля и типы тела `create` — по индексу, те же правила, что у `update` (`_поле_тела`,
    `_проверить_тип`): 1С молча принимает недопустимое (P8), превью обещало бы запись, которой не
    будет. Отличия от `update`: ключевые поля разрешены (запись регистра), табличная часть —
    список строк с проверкой по своей сущности, открытый литерал не проверяется (Ruling 47)."""
    if not isinstance(data, dict) or not data:
        raise _отказ(
            "тело записи пустое: передайте data словарём «поле: значение»",
            hint="поля сущности — odata1c_describe_entity",
        )
    if описание.is_tabular_part:
        # Строка табличной части — часть объекта-владельца (SPEC §7.3: одна операция — один
        # объект, табличные части внутри); отдельно от владельца 1С её не создаёт.
        имя_части = описание.name.removeprefix(f"{описание.parent_entity}_")
        raise _отказ(
            f"«{описание.name}» — табличная часть: её строки создаются вместе с "
            "объектом-владельцем",
            hint=f"передайте строки списком в поле «{имя_части}» тела create владельца "
            f"«{описание.parent_entity}»",
        )
    if описание.kind in _НЕ_СОЗДАЁТСЯ:
        # Предвидимый отказ 1С (дух решения 12 плана): такого объекта создать нельзя в принципе,
        # и узнавать это ответом 1С после подтверждения пользователя незачем.
        raise _отказ(
            f"«{описание.name}» не создаётся: {_НЕ_СОЗДАЁТСЯ[описание.kind]}",
            hint="создавайте объект, который туда попадает, — документ, справочник, запись "
            "регистра",
        )
    поля = {поле["name"]: поле for поле in описание.fields}
    for имя, значение in data.items():
        поле = _поле_тела(
            описание, поля, имя, запрещённые=_НЕ_ПИШЕТСЯ_В_CREATE, где="через create", ключ=False
        )
        тип = поле["edm_type"]
        if тип.startswith("Collection("):
            _проверить_строки(имя, значение, части[имя])
        else:
            _проверить_тип(имя, тип, значение)


def _проверить_строки(
    имя: str,
    строки,
    описание_строки: EntityDescription,
    проверить_литерал: _Литерал | None = None,
) -> None:
    """Строки одной табличной части `create`/`update`: список объектов, каждое поле — по сущности
    строки из индекса. Имя табличной части в текстах — поле владельца, уже найденное в индексе;
    части без сущности строки сюда не доходят (`_табличные_части_тела`).

    `проверить_литерал` — только у `update` (C-1 ревью хвостов M3b): открытый литерал в поле
    класса `dob`/`contact` строки отклоняется тем же отказом, что у поля шапки, ДО типа — тем же
    порядком, что у `_проверить_поле`. Имя сущности для класса — СВОЁ у строки
    (`описание_строки.name`), не владельца: строку контактной информации маскирует политика её
    собственной сущности (Ruling 56), и класс поля обязан искаться там же. `None` у `create`
    (Ruling 47): у нового объекта сравнивать не с чем."""
    if not isinstance(строки, list):
        raise _отказ(
            f"табличная часть «{имя}» ожидает список строк",
            hint='передайте [{"поле": значение}, …] — по объекту на строку',
        )
    поля = {поле["name"]: поле for поле in описание_строки.fields}
    for строка in строки:
        if not isinstance(строка, dict):
            raise _отказ(f"строка табличной части «{имя}» должна быть объектом «поле: значение»")
        for имя_поля, значение in строка.items():
            поле = _поле_тела(
                описание_строки,
                поля,
                имя_поля,
                запрещённые=_НЕ_ПИШЕТСЯ_В_СТРОКУ,
                где="в строке табличной части",
                ключ=False,
            )
            тип = поле["edm_type"]
            if тип.startswith("Collection("):
                # В 1С табличных частей внутри строки не бывает; индекс, в котором такое есть,
                # описывает то, чего шлюз записать не умеет.
                raise _отказ(f"поле «{имя_поля}» строки — вложенная табличная часть")
            if проверить_литерал is not None:
                проверить_литерал(описание_строки.name, имя_поля, значение)
            _проверить_тип(имя_поля, тип, значение)


# -- action: имя, параметры, предвидимые отказы ------------------------------------------------


def _проверить_действие(описание: EntityDescription, name) -> None:
    """Действие должно быть объявлено у сущности в индексе (`$metadata`) и входить в перечень
    первой поставки (`ДЕЙСТВИЯ_ПРОВЕДЕНИЯ` — тот же, по которому `check_write` проверяет флаг
    `post_documents`). Иначе `action_unknown`.

    Ruling 51, 53: имя, которое прислала модель, не повторяется ни в каком случае — даже когда оно
    совпадает с объявленным (отказ не повторяет ввод модели). Подсказка перечисляет объявленные
    действия сущности из индекса — это метаданные базы, а не ввод."""
    объявленные = [действие["name"] for действие in описание.actions]
    перечень = (
        f"действия сущности в $metadata: {', '.join(объявленные)}; в первой поставке шлюз "
        f"вызывает только {' и '.join(ДЕЙСТВИЯ_ПРОВЕДЕНИЯ)}"
        if объявленные
        else f"у сущности «{описание.name}» в $metadata нет объявленных действий; проведение "
        "(Post, Unpost) объявлено у документов"
    )
    if not isinstance(name, str) or name not in объявленные:
        raise WriteError(
            "action_unknown",
            f"действие не объявлено у сущности «{описание.name}» в $metadata",
            перечень,
        )
    if name not in ДЕЙСТВИЯ_ПРОВЕДЕНИЯ:
        raise WriteError(
            "action_unknown",
            f"действие объявлено у сущности «{описание.name}», но в первой поставке не "
            "поддерживается",
            перечень,
        )


def _проверить_параметры_действия(описание: EntityDescription, name: str, params) -> None:
    """Параметры действия в первой поставке не принимаются: P8 проверила `Post`/`Unpost` без
    них (а `PostingModeOperational` — только прямым запросом, не сквозь гейт и `commit`), и
    обязательных параметров у проведения нет. Имена от модели не повторяются (Ruling 53) —
    подсказка называет объявленные параметры из индекса."""
    if not params:
        return
    # `next`, а не распаковка: два объявления одного имени в индексе дали бы `ValueError` →
    # `internal` вместо задуманного отказа.
    объявленные = next(
        (действие.get("params") or {} for действие in описание.actions if действие["name"] == name),
        {},
    )
    raise _отказ(
        "параметры действия в этой поставке не передаются: вызовите действие без params",
        hint=(
            f"объявленные параметры действия: {', '.join(объявленные)} — все необязательные, "
            "режим проведения 1С выбирает сама"
            if объявленные
            else "у действия нет объявленных параметров"
        ),
    )


def _выбор_действия(описание: EntityDescription, представление: list[str]) -> list[str]:
    """`$select` чтения текущего состояния для действия: `Posted` и `DeletionMark` — явно, по ним
    предвидятся отказы 1С (решение 12; настоящая 1С `$select` соблюдает, и без них в `current`
    полей не будет вовсе — M-2 ревью задачи 5), отпечаток `DataVersion` и представление объекта
    (Ruling 44). Только поля, которые у сущности есть."""
    есть = {поле["name"] for поле in описание.fields}
    выбор: list[str] = []
    for имя in ("Posted", "DeletionMark", "DataVersion", *представление):
        if имя in есть and имя not in выбор:
            выбор.append(имя)
    return выбор


def _предвидеть_отказ_действия(name: str, текущее: dict) -> list[str]:
    """Решение 12 плана, факты P8 — отказ при подготовке вместо ответа 1С на `commit`, после
    подтверждения пользователя. Возвращает предупреждения превью. Поле, которого 1С не вернула
    (у сущности его нет), ничего не предвидит: гадать о состоянии шлюз не берётся."""
    if name == "Post" and текущее.get("DeletionMark") is True:
        raise _отказ(
            "документ помечен на удаление: 1С не проводит помеченный документ",
            hint="сначала снимите пометку — odata1c_mark_for_deletion(mark=false), затем "
            "повторите проведение",
        )
    if name == "Unpost" and текущее.get("Posted") is False:
        raise _отказ(
            "документ не проведён: отменять проведение нечего",
            hint="проверьте, что выбран нужный документ; запись не нужна",
        )
    if name == "Post" and текущее.get("Posted") is True:
        return [
            "повторное проведение: документ уже проведён — 1С проведёт его заново и перезапишет "
            "движения"
        ]
    return []


