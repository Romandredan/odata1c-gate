# -- undo и journal: форма отката, превью, строки журнала ---------------------------------------

# Один ответ на `commit_id` чужой базы и несуществующий (решение 9 контролёра, как
# `pending_unknown` в решении 4 плана). Текст не повторяет `commit_id` — это ввод модели
# (Ruling 51, 53): иначе ответ отличался бы от ответа на выдуманный номер хотя бы эхом.
_КОММИТ_НЕИЗВЕСТЕН = (
    "commit_unknown",
    "запись журнала с таким commit_id не найдена",
    "commit_id возвращает odata1c_commit и показывает odata1c_journal; записи баз вне видимости "
    "сессии не видны",
)

# Верхняя граница `limit` журнала: ответ — маска до ста записей с состояниями «до» и «после»,
# дальше это уже выгрузка, а не просмотр последних коммитов.
_ПРЕДЕЛ_ЖУРНАЛА = 100

# Строгость уровней гейта — для стража смешанного ответа журнала (строжайший из баз ответа).
# Неизвестный уровень считается строжайшим: отказ — в сторону защиты.
_СТРОГОСТЬ = {"off": 0, "identifiers": 1, "identifiers+names": 2}

# Строки скрытых сущностей не показываются; сколько их, не говорится — число выдало бы, что о
# скрытом что-то известно (как у `reindex`, `ПРЕДУПРЕЖДЕНИЕ_СКРЫТЫХ_РАЗБОРА`).
_ПРЕДУПРЕЖДЕНИЕ_СКРЫТЫХ_ЗАПИСЕЙ = "часть записей журнала не показана по политике гейта"

# Формат строки `error` журнала — его пишет `_текст_для_журнала` этого же модуля:
# «<код> (HTTP <статус>): <текст>» или «<код> (без ответа 1С): <текст>». Разбор своего же формата,
# а не догадка о чужом: изменится `_текст_для_журнала` — изменится и это выражение (тест журнала
# на уровне названий это ловит).
_ОШИБКА_В_ЖУРНАЛЕ = re.compile(
    r"(?P<code>[a-z_]+) \((?:HTTP (?P<status>[0-9]{3})|без ответа 1С)\): (?P<text>.*)", re.S
)


@dataclass(frozen=True)
class _Откат:
    """Операция, которая откатывает запись (таблица SPEC §7.6): `op` — для `check_write` и
    `PendingOp.op`, `тело` — прежние значения (реальные, из `before_json`), `действие` — у
    `action`.

    `части` (I-1, I-2 ревью хвостов M3b) — табличные части ТЕЛА отката (только у `op == "update"`,
    тем же именем, что `_табличные_части_тела`): поле владельца → сущность строки. Нужны
    вызывающему (`_подготовить_откат`) дважды — перепроверить права строк тем же
    `_проверить_права_строк`, что прямой путь (I-2), и положить их в `PendingOp.write_rows`, чтобы
    `commit` перепроверил их ещё раз по текущему `bases.yaml`."""

    op: Операция
    тело: dict | None = None
    действие: str | None = None
    части: dict[str, EntityDescription] = field(default_factory=dict)


def _нельзя(message: str, hint: str = "") -> WriteError:
    return WriteError("undo_unsupported", message, hint)


def _проверить_исход(запись: JournalEntry, последнее: str | None = None) -> None:
    """Можно ли откатывать запись по её исходу (решение 1 контролёра). `started` и `unknown` —
    исход неизвестен: запрос мог выполниться, и «обратная» запись по журналу могла бы как
    вернуть состояние, так и испортить его. `failed` — 1С отказала, откатывать нечего. Уже
    откаченная — повторный откат не выполняется (`undone_by`)."""
    if запись.undone_by is not None:
        # Н8-4 ревью: откат отката возвращает изменение, а эта запись остаётся «откаченной» —
        # откатывается последнее звено цепочки, и подсказка его называет (номер из журнала).
        звено = последнее or запись.undone_by
        raise _нельзя(
            "эта запись уже откачена — повторный откат не выполняется",
            hint=f"цепочка откатов этой записи заканчивается записью commit_id {звено} — "
            "откатывается только она (odata1c_undo); что сейчас в объекте — odata1c_get, "
            "цепочка — odata1c_journal",
        )
    if запись.status in ("started", "unknown"):
        raise _нельзя(
            "исход этой записи неизвестен: запрос мог выполниться, а мог и нет — откат по "
            "журналу не строится",
            hint="прочитайте объект (odata1c_get или odata1c_query) и, если запись выполнена, "
            "верните прежнее состояние обычной операцией записи",
        )
    if запись.status == "failed":
        raise _нельзя(
            "запись не выполнена — 1С отказала, откатывать нечего",
            hint="состояние объекта этой записью не менялось; причина отказа — odata1c_journal",
        )
    if запись.status != "committed":
        raise _нельзя("запись журнала в неизвестном состоянии — откат не строится")


def _строки_отката(имя: str, строки, описание_строки: EntityDescription) -> list[dict]:
    """Строки табличной части из журнала («до») — как их отдала 1С: `LineNumber` СТРОКОЙ и все
    поля строки, включая служебные (`Ref_Key` и подобное) — `_для_журнала` разворачивает строки
    раннего прохода рекурсивно, но формы полей не меняет (I-1 ревью хвостов M3b). PATCH отката
    проходит тем же путём проверки, что прямая запись (`_проставить_номера_строк`,
    `_проверить_строки`), и обязан получить на входе то же, что принял бы прямой путь: `LineNumber`
    целым, поля строки — только те, что её сущность пишет (исключения `_НЕ_ПИШЕТСЯ_В_СТРОКУ`, тот
    же список, что у `create`/`update`). Не список строк-объектов — возвращается как есть: следующая
    проверка (`_проставить_номера_строк`/`_проверить_строки` прямого пути коммита) отказывает на
    нём своим текстом, дублировать её здесь незачем."""
    if not isinstance(строки, list) or not all(isinstance(строка, dict) for строка in строки):
        return строки
    доступные = {поле["name"] for поле in описание_строки.fields} - set(_НЕ_ПИШЕТСЯ_В_СТРОКУ)
    подготовленные = []
    for строка in строки:
        новая = {поле: значение for поле, значение in строка.items() if поле in доступные}
        номер = строка.get(ПОЛЕ_НОМЕРА_СТРОКИ)
        if isinstance(номер, str) and ПОЛЕ_НОМЕРА_СТРОКИ in доступные:
            try:
                номер = int(номер)
            except ValueError:
                pass
            else:
                новая[ПОЛЕ_НОМЕРА_СТРОКИ] = номер
        подготовленные.append(новая)
    try:
        return _проставить_номера_строк(имя, подготовленные)
    except WriteError as отказ:
        # Строки журнала пришли от самой 1С (не от модели) — расхождение с правилом §5.1 здесь
        # означало бы рассинхронизацию индекса, а не плохой ввод; код и подсказка — отката, не
        # params_invalid чужого пути.
        raise _нельзя(
            f"строки табличной части «{имя}» из журнала не проходят правило номеров строк — "
            "откат не строится",
            hint="обновите индекс (odata1c_reindex) или верните прежний список обычной записью",
        ) from отказ


def _форма_отката(
    запись: JournalEntry,
    описание: EntityDescription,
    describe: Callable[[str], EntityDescription | None],
) -> _Откат:
    """Таблица SPEC §7.6. Решение 2 контролёра: у созданной записи регистра пометки удаления нет
    вовсе — откат `create` независимого регистра сведений строит физическое удаление
    (`delete_record`, задача 7 M3b), а откат `delete_record` — обратное создание (`create`) из
    «до» журнала; и то и другое требует своего разрешения (флаг проверяет `check_write` по
    `откат.op`, а не эта функция). Обратное действие выводится из пути запроса (`…/Post` ↔
    `…/Unpost`), по которому запись и ушла.

    Имена полей в отказах — поля исходного тела, проверенного по индексу при подготовке; поле,
    которого в индексе больше нет, не называется (Ruling 53).

    Табличная часть (проект M3b §5.2) идёт по тому же циклу `update`, что и поле шапки: `до[поле]`
    — полный СТАРЫЙ список строк (`_выбор_коммита` включает её в перечитывание, `_для_журнала`
    разворачивает строки раннего прохода рекурсивно), но НЕ как есть (I-1 ревью хвостов M3b) —
    `_строки_отката` приводит их к форме, которую принял бы прямой путь записи (`LineNumber` целым,
    без служебных полей строки). `describe` — тот же `репозиторий.describe`, что у прямого пути,
    для поиска сущности строки по имени поля владельца (`_табличные_части_тела`); поле-коллекция
    без своей сущности строки в индексе (реиндекс убрал её после коммита) — откат не строится."""
    запрос = запись.request if isinstance(запись.request, dict) else {}
    тело = запрос.get("json")
    if запись.op == "update":
        до = запись.before
        if not isinstance(тело, dict) or not тело or not isinstance(до, dict):
            raise _нельзя("в журнале нет состояния объекта до записи — откатывать не по чему")
        поля = {поле["name"]: поле for поле in описание.fields}
        прежнее: dict = {}
        части: dict[str, EntityDescription] = {}
        for поле in тело:
            if поле not in поля:
                raise _нельзя(
                    "поле этой записи больше не описано в индексе базы — откат не строится",
                    hint="обновите индекс (odata1c_reindex) или верните значение обычной записью",
                )
            if до.get(поле) is None:
                raise _нельзя(f"в журнале нет прежнего значения поля «{поле}» — откат не строится")
            значение = до[поле]
            if поля[поле]["edm_type"].startswith("Collection("):
                описание_строки = describe(f"{описание.name}_{поле}")
                if описание_строки is None:
                    raise _нельзя(
                        "поле этой записи больше не описано в индексе базы — откат не строится",
                        hint="обновите индекс (odata1c_reindex) или верните значение обычной "
                        "записью",
                    )
                части[поле] = описание_строки
                значение = _строки_отката(поле, значение, описание_строки)
            прежнее[поле] = значение
        return _Откат("update", тело=прежнее, части=части)
    if запись.op == "mark_for_deletion":
        пометка = тело.get("DeletionMark") if isinstance(тело, dict) else None
        if not isinstance(пометка, bool):
            raise _нельзя("в журнале нет отправленной пометки удаления — откат не строится")
        прежняя = запись.before.get("DeletionMark") if isinstance(запись.before, dict) else None
        return _Откат(
            "mark_for_deletion",
            тело={"DeletionMark": прежняя if isinstance(прежняя, bool) else not пометка},
        )
    if запись.op == "create":
        if not isinstance(запись.key, dict) or not запись.key:
            # Minor 2 ревью хвостов M3b: у записи независимого регистра нет пометки удаления
            # вовсе (Ruling 60) — подсказка «пометьте на удаление» для неё не выполнима, а
            # физическое удаление (`odata1c_delete_record`) без ключа тоже не построить, но верно
            # называет тул, которым модель искала бы запись после ручного поиска.
            if описание.is_independent_register:
                raise _нельзя(
                    "ключ созданной записи регистра в журнале не записан — откатывать не по чему",
                    hint="найдите запись выборкой odata1c_query и удалите её "
                    "(odata1c_delete_record)",
                )
            raise _нельзя(
                "ключ созданного объекта в журнале не записан — откатывать не по чему",
                hint="найдите объект выборкой odata1c_query и пометьте его на удаление "
                "(odata1c_mark_for_deletion)",
            )
        if описание.is_independent_register:
            # M3b задача 7: откат создания записи регистра — физическое удаление тем же тулом,
            # что и прямое (`delete_record`); разрешение (`independent_register_delete`)
            # перепроверяет `check_write` вызывающего по `откат.op`, здесь оно не проверяется.
            return _Откат("delete_record")
        if описание.is_tabular_part or not any(
            поле["name"] == "DeletionMark" for поле in описание.fields
        ):
            raise _нельзя(
                "у созданного объекта нет пометки удаления, и это не запись независимого "
                "регистра сведений — откатить создание нечем",
                hint="удалить объект может пользователь в 1С",
            )
        return _Откат("mark_for_deletion", тело={"DeletionMark": True})
    if запись.op == "delete_record":
        # Обратное — воссоздать запись из «до» журнала (реальные значения, как их ушли бы в 1С
        # на PATCH/POST): полный набор полей записи, а не разница, — записи для сравнения нет.
        до = запись.before
        if not isinstance(до, dict) or not до:
            raise _нельзя(
                "в журнале нет содержимого удалённой записи — откат не строится",
                hint="запись потеряна, восстановить откатом нечем",
            )
        поля = {поле["name"] for поле in описание.fields}
        тело_записи = {поле: значение for поле, значение in до.items() if поле in поля}
        if not тело_записи:
            raise _нельзя(
                "поля этой записи больше не описаны в индексе базы — откат не строится",
                hint="обновите индекс (odata1c_reindex) или создайте запись заново "
                "(odata1c_create)",
            )
        return _Откат("create", тело=тело_записи)
    if запись.op == "action":
        # Откат возвращает состояние проведения ДО коммита, а не делает противоположное действие
        # (Н8-1 ревью): повторное проведение проведённого документа (задача 6 его разрешает)
        # распроведением не откатывается — оно удалило бы движения, которые были до коммита.
        # `Posted` в `before` есть всегда: `commit` перечитывает его у действия
        # (`_СЛУЖЕБНЫЕ_КОММИТА`).
        путь = запрос.get("path")
        было = запись.before.get("Posted") if isinstance(запись.before, dict) else None
        for суффикс, обратное, прежнее in (("/Post", "Unpost", False), ("/Unpost", "Post", True)):
            if not (isinstance(путь, str) and путь.endswith(суффикс)):
                continue
            if not isinstance(было, bool):
                raise _нельзя(
                    "в журнале нет признака проведения до коммита — что восстанавливать, "
                    "неизвестно; откат не строится",
                    hint="прочитайте документ (odata1c_get) и при необходимости проведите или "
                    "распроведите его обычной операцией (odata1c_action)",
                )
            if было is not прежнее:
                raise _нельзя(
                    "состояние проведения до коммита не отличалось — откатывать нечего",
                    hint="документ был в том же состоянии проведения и до записи (повторное "
                    "проведение); прежние движения откатом не возвращаются",
                )
            return _Откат("action", действие=обратное)
        raise _нельзя("у этого действия нет обратного: откатываются только Post и Unpost")
    raise _нельзя("у этой операции нет обратной — откат не поддерживается")


def _запомнить_раскрытое(маска, реальное, раскрытое: RevealedValues) -> None:
    """Реальные значения, которые уйдут в 1С (или ушли — журнал), — в набор раскрытого с их
    токенами из маски: так ранний проход и страж закрывают эхо значения в ошибке 1С (P7) и у
    классов без детектора (адрес, дата рождения, свободный `doc`). Берутся только значения,
    которые маска закрыла целиком токеном (поле с классом); частичная маска свободного текста —
    работа детекторов, и они её сделают сами. Обход — по форме данных (табличные части `create`
    — списками строк)."""
    if isinstance(реальное, dict) and isinstance(маска, dict):
        for поле, значение in реальное.items():
            _запомнить_раскрытое(маска.get(поле), значение, раскрытое)
    elif isinstance(реальное, list) and isinstance(маска, list) and len(маска) == len(реальное):
        for замаскированное, значение in zip(маска, реальное, strict=True):
            _запомнить_раскрытое(замаскированное, значение, раскрытое)
    elif (
        isinstance(реальное, str)
        and isinstance(маска, str)
        and маска != реальное
        and parse_token(маска) is not None
    ):
        раскрытое.add(реальное, token=маска)


def _снять_невыданные(текущее: dict, выданные: dict, раскрытое: RevealedValues) -> None:
    """Замены раннего прохода в строках, которые в ответ не идут, стражу не засчитываются: их нет
    в выдаче, а `guard_replaced` значит «защищённое значение было в ответе» (тот же довод, что
    `absorb` ответа записи в `commit`). Строки, прошедшие маску, маскировщик учёл сам. Хватает
    верхнего уровня: выбор чтения отката табличных частей не содержит (`_все_поля_записи`,
    `_выбор_текущего`, `_выбор_действия`), и вложенных строк в текущем состоянии нет."""
    лишние = sum(
        значение.hits
        for поле, значение in текущее.items()
        if поле not in выданные and isinstance(значение, ScrubbedText)
    )
    if лишние:
        раскрытое.absorb(лишние)


def _изменён_после_коммита(
    описание: EntityDescription, текущее: dict, после, раскрытое: RevealedValues
) -> str | None:
    """Предупреждение превью отката, если объект менялся после коммита (SPEC §7.6, решение 8
    контролёра): откат перезапишет чужие изменения, и подтверждать его надо осознанно. Сравнение
    — отпечатком, как в `commit`: `DataVersion` у объекта (растёт на любой записи, P8), хэш полей
    у записи регистра (Ruling 55: подготовка отката читает все поля записи — тот же набор, что
    `commit` перечитал «после»). Предупреждение называет поля, но не значения."""
    if not isinstance(после, dict):
        return (
            "состояние объекта после коммита в журнале не записано — изменён ли он с тех пор, "
            "проверить не по чему; откат перезапишет текущие значения полей отката"
        )
    сейчас = _отпечаток(описание, текущее, раскрытое)
    тогда = _отпечаток(описание, после, раскрытое)
    if сейчас is not None and сейчас == тогда:
        return None
    реальное = _реальные(strip_service(текущее), раскрытое)
    поля = [
        поле
        for поле, значение in реальное.items()
        if поле in после and not _одинаково(после[поле], значение)
    ]
    перечень = (
        f"изменены поля {', '.join(поля)}"
        if поля
        else "версия данных изменилась (объект записывался — например, проводился — без правки "
        "показанных полей)"
    )
    return (
        f"объект изменён после коммита, откат перезапишет эти изменения: {перечень} — "
        "подтверждайте откат осознанно"
    )


def _версия_журнала(состояние) -> str | None:
    """`DataVersion` состояния из журнала — для показа: счётчик записей 1С, не данные (P8)."""
    if isinstance(состояние, dict) and isinstance(состояние.get("DataVersion"), str):
        return состояние["DataVersion"]
    return None


def _сведения_ошибки(строка: JournalEntry, гейт, набор: RevealedValues | None) -> dict | None:
    """Ошибка записи из журнала для модели (Ruling 52, 58). Всегда — код, HTTP-статус, код
    платформы (только число) и категория по статусу. Текст ошибки 1С — только не на уровне
    `identifiers+names` (там он может называть объекты и пользователей, и новое название
    детекторы не узнают) и только когда отправленное удалось замаскировать (`набор` — его
    значения с токенами): текст повторяет отправленное, а у адреса детектора нет. Маска текста —
    без записи в словарь (`mask_message`, Ruling 48)."""
    if строка.error is None:
        return None
    разбор = _ОШИБКА_В_ЖУРНАЛЕ.fullmatch(строка.error)
    код = разбор["code"] if разбор else None
    статус = int(разбор["status"]) if разбор and разбор["status"] else None
    текст = разбор["text"] if разбор else строка.error
    платформа = None
    if статус is not None:
        # Сырой текст ошибки — тело ответа 1С (`_ЗапоминающийПроход`): код и сообщение
        # платформы разбирает тот же `map_error`, что и клиент.
        разобрано = map_error(статус, текст)
        if _КОД_ПЛАТФОРМЫ.fullmatch(разобрано.platform_code):
            платформа = разобрано.platform_code
        текст = разобрано.message
    if строка.status == "unknown":
        # Раньше статуса: 5xx без ошибки 1С (ФП-2) — не отказ 1С, и категория 500 «1С отказала при
        # записи» здесь была бы неправдой.
        категория = "ответ 1С не получен, не разобран или пришёл не от 1С — исход неизвестен"
    elif статус is not None:
        категория = _КАТЕГОРИИ.get(статус, "ошибка 1С при записи")
    else:
        категория = "ошибка при записи"
    сведения = {
        "code": код,
        "http_status": статус,
        "platform_code": платформа,
        "category": категория,
        "text": None,
    }
    if гейт is None or набор is None:
        сведения["note"] = "текст ошибки не показан: данные записи не удалось замаскировать"
    elif гейт.mode == "identifiers+names":
        сведения["note"] = (
            "текст ошибки 1С на уровне гейта identifiers+names не показывается — он может "
            "называть объекты и пользователей; полный текст — в журнале записи у владельца"
        )
    else:
        сведения["text"] = гейт.mask_message(текст, набор)
    return сведения
