    async def delete_record(
        self,
        scope: SessionScope,
        session_id: str,
        *,
        base: str | None,
        entity: str,
        key,
    ) -> str:
        """Физическое удаление записи независимого регистра сведений (SPEC §7.1, §7.3, проект
        M3b §5.4) → `pending_id`. В 1С не пишет — только GET текущей записи; выполнение —
        `odata1c_commit` после подтверждения пользователя.

        Единственный тул шлюза, который физически удаляет что-либо: у объектов удаления нет вовсе
        (только пометка, `odata1c_mark_for_deletion`), а запись зависимого регистра снимается
        проведением или распроведением документа-регистратора (Ruling 57 этой поставкой не
        меняется). Сущность не независимый регистр сведений — `params_invalid` (для объекта
        отказ называет `odata1c_mark_for_deletion`); флаг `independent_register_delete` выключен
        — `permission_denied` раньше этого места (шаг 3 `check_write`)."""
        tools = self._tools

        async def тело(base_config, гейт, репозиторий, раскрытое):
            описание = tools._resolve_entity(репозиторий, гейт, entity)
            скрытые = tools._скрытые(репозиторий, гейт)
            check_write(base_config, описание, "delete_record", hidden=скрытые.__contains__)
            if not описание.is_independent_register:
                raise _отказ(
                    f"«{описание.name}» — не запись независимого регистра сведений: "
                    "физическое удаление доступно только для них",
                    hint="объект удаляется пометкой — odata1c_mark_for_deletion",
                )
            строение = tools._строение(репозиторий)
            реальный_ключ = гейт.inbound_key(
                key, entity=описание.name, revealed=раскрытое, shape=строение
            )
            представление = _поля_представления(описание)
            spec = build_get(
                описание,
                реальный_ключ,
                describe=репозиторий.describe,
                limits=tools._config.daemon.limits,
                select=_все_поля_записи(описание),
            )
            клиент = tools._client_for(base_config)
            try:
                сырой = await клиент.get(spec.path, spec.params, scrub=гейт.scrubber(раскрытое))
            except OdataError as ошибка:
                tools._уточнить_404(ошибка)
                raise
            [текущее] = items_of(сырой)[0]

            маска = гейт.mask(
                strip_service(текущее),
                entity=описание.name,
                resolve=tools._навигации(репозиторий),
                shape=строение,
                hidden=скрытые.__contains__,
                revealed=раскрытое,
            )
            объект = {поле: маска.data.get(поле) for поле in представление if поле in текущее}

            операция = PendingOp(
                pending_id=_новый_номер(),
                commit_id=_новый_номер(),
                session_id=session_id,
                base=base_config.name,
                role=base_config.role,
                op="delete_record",
                entity=описание.name,
                key=_ключ_операции(реальный_ключ),
                request={"method": "DELETE", "path": spec.path, "json": None},
                preview={
                    "entity": описание.name,
                    "op": "delete_record",
                    "key": key,
                    "object": объект,
                    "before": маска.data,
                    "after": "записи не будет",
                },
                data_version=_отпечаток(описание, текущее, раскрытое),
                created_at=self._clock(),
                expires_at=self._store.deadline(),
                revealed=раскрытое.carry(),
            )
            await self._store.put(операция)
            return {
                "pending_id": операция.pending_id,
                "base": base_config.name,
                "role": base_config.role,
                "entity": описание.name,
                "op": "delete_record",
                "key": key,
                "object": объект,
                "preview": {"before": маска.data, "after": "записи не будет"},
                "expires_in_s": round(self._store.remaining(операция.expires_at)),
                "next": СЛЕДУЮЩИЙ_ШАГ,
                "warnings": list(dict.fromkeys(маска.warnings)),
            }

        return await tools._run(scope, base, тело)

    async def _подготовить(
        self,
        scope: SessionScope,
        session_id: str,
        *,
        base: str | None,
        entity: str,
        key,
        data: dict,
        op: Операция,
        проверить_тело: Callable[
            [EntityDescription, dict[str, EntityDescription], dict, _Литерал], None
        ],
    ) -> str:
        tools = self._tools

        async def тело(base_config, гейт, репозиторий, раскрытое):
            # Шаги 1–3: ни одного обращения к 1С. Сущность — через `_resolve_entity`, как у
            # чтения: скрытая отвечает `entity_hidden` раньше, чем проверяется существование, —
            # иначе запись различала бы скрытую и несуществующую сущность кодом ошибки.
            описание = tools._resolve_entity(репозиторий, гейт, entity)
            скрытые = tools._скрытые(репозиторий, гейт)
            # Разрешения — до ключа и до полей: запрет базы или флага не должен зависеть от того,
            # правильно ли модель написала ключ (порядок SPEC §7.1, инвариант 4).
            поля_разрешений = _имена_полей(data)
            check_write(
                base_config,
                описание,
                op,
                fields=поля_разрешений,
                hidden=скрытые.__contains__,
            )
            строение = tools._строение(репозиторий)
            # Табличные части ТЕЛА (проект M3b §5.2) — тем же шагом, что у `create`: права строк
            # проверяются сразу за шапкой, до проверки её типов (`mark_for_deletion` табличных
            # частей не несёт, `части` для него всегда пуст). Правило §5.1 (номер строки) — до
            # прав: номер такая же проверяемая часть тела, как её поля.
            части = _табличные_части_тела(описание, data, репозиторий.describe)
            данные = _с_номерами_строк(data, части)
            права_строк = _права_строк(данные, части)
            _проверить_права_строк(base_config, права_строк, скрытые)

            # Открытый литерал в поле, которое на чтении принимает только токен (`dob`,
            # `contact`), — отказ тем же кодом и текстом, что у отбора, и до GET (Ruling 45,
            # находка I-1): иначе «изменений нет» отвечало бы на тот же вопрос, что запрещённый на
            # чтении `ДатаРождения eq datetime'…'`, — перебором дат, без единого обращения к
            # карточке. У `update` — и поля шапки, и поля СТРОК табличной части (C-1 ревью хвостов
            # M3b): решение «изменилась ли часть» тоже принимается на реальных значениях
            # (`rows_diff`), и открытый литерал в поле строки задавал бы тот же вопрос построчно —
            # оракул, который Ruling 45 закрыл для шапки. Класс поля строки ищется по сущности
            # СТРОКИ, не владельца (`entity`, параметр этой функции) — у `create` эта проверка не
            # зовётся вовсе (Ruling 47: у нового объекта сравнивать не с чем).
            def проверить_литерал(entity: str, имя: str, значение) -> None:
                гейт.check_open_literal(entity, имя, значение, shape=строение)

            проверить_тело(описание, части, данные, проверить_литерал)

            реальный_ключ = гейт.inbound_key(
                key, entity=описание.name, revealed=раскрытое, shape=строение
            )
            # Путь по ключу без `$expand` — тот же, по которому пойдёт PATCH в `commit`. Выбор —
            # поля тела (включая табличные части — их строки нужны для разницы построчно и для
            # лестницы 1.2 при раскрытии токенов строк, проект §5.2), служебные и представление
            # объекта (Ruling 44).
            представление = _поля_представления(описание)
            spec = build_get(
                описание,
                реальный_ключ,
                describe=репозиторий.describe,
                limits=tools._config.daemon.limits,
                select=_выбор_текущего(описание, данные, op, представление),
            )

            # Шаг 4: текущее состояние — с ранним проходом (ошибка 1С повторяет значения, P7).
            клиент = tools._client_for(base_config)
            try:
                сырой = await клиент.get(spec.path, spec.params, scrub=гейт.scrubber(раскрытое))
            except OdataError as ошибка:
                tools._уточнить_404(ошибка)
                raise
            # `current` — как пришло (контракт 1.2): без `strip_service` (он вырезал бы
            # `DataVersion`) и без переписывания строк раннего прохода — их гейт разворачивает сам.
            [текущее] = items_of(сырой)[0]

            # Шаг 5: токены → реальные значения по лестнице 1.2. Без табличных частей в теле —
            # прежний единственный вызов `inbound_write` (поведение scalar-only `update` не
            # меняется); с ними — `_раскрыть_тело`: шапка от владельца, строка табличной части —
            # от своей сущности, сопоставленная со старой строкой того же `LineNumber` (Ruling 56,
            # проект §5.2).
            if части:
                реальное = _раскрыть_тело(
                    гейт,
                    описание,
                    данные,
                    части,
                    строение=строение,
                    раскрытое=раскрытое,
                    current=текущее,
                )
            else:
                реальное = гейт.inbound_write(
                    данные,
                    entity=описание.name,
                    shape=строение,
                    current=текущее,
                    revealed=раскрытое,
                )
            _проверить_раскрытые_даты(описание, данные, реальное)
            for имя, описание_строки in части.items():
                for строка, реальная in zip(данные[имя], реальное[имя], strict=True):
                    _проверить_раскрытые_даты(описание_строки, строка, реальная)

            # Шаг 6: изменённость — на РЕАЛЬНЫХ значениях, не на токенах (одно значение в двух
            # написаниях — один токен, а 1С получит другую строку). Неизменённое поле в тело
            # PATCH не идёт (решение 8 плана): 1С не получает лишнего, откат точнее. Табличная
            # часть — построчно (`rows_diff` на реальных значениях, `LineNumber` исключён из
            # сравнения полей самим модулем): список, отличающийся хоть одной строкой, целиком
            # уходит в изменённые — в PATCH часть заменяется целиком, а не по полю.
            изменённые: list[str] = []
            for поле in данные:
                if поле in части:
                    старые = _строки_реальные(текущее.get(поле), раскрытое)
                    диф_реальный = rows_diff(старые, реальное[поле])
                    if диф_реальный.changed or диф_реальный.added or диф_реальный.removed:
                        изменённые.append(поле)
                    continue
                if реальное[поле] != _текущее_реальное(текущее.get(поле), раскрытое):
                    изменённые.append(поле)
            if not изменённые:
                raise _отказ(
                    "изменений нет: значения тела совпадают с текущими значениями объекта",
                    hint="проверьте, что объект и поля выбраны верно; запись не нужна",
                )
            # Предвидимый отказ 1С — после «изменений нет»: у документа, который уже в нужном
            # состоянии, подсказка «сначала Unpost» толкала бы на лишнее распроведение.
            if op == "mark_for_deletion":
                _предвидеть_отказ_пометки(текущее, данные["DeletionMark"])

            # Шаг 7 (Ruling 45, 44): ОДНА маска — сырого текущего состояния, изменённых полей и
            # полей представления объекта, той же сущностью и с тем же набором раскрытого (он
            # нужен маскировщику, чтобы строка раннего прохода получила токен по настоящему
            # содержимому, Б-3). Это данные 1С, и словарь узнаёт их так же, как при чтении
            # карточки — включая строки табличной части: `mask` уже умеет обрабатывать их по
            # политике СВОЕЙ сущности через `resolve` (то же умение, что у чтения объекта целиком
            # с табличными частями, `gate/masking.py`). «Станет» — значения `данные` без маски:
            # `реальное` в `mask` не подаётся нигде (см. докстринг модуля). Литерал модели в любом
            # поле — пометкой (Ruling 62, 63): страж заменил бы известное словарю значение тем же
            # токеном, что в чтении, неизвестное — нет, и по разнице модель сопоставляла бы
            # догадку с токеном.
            к_маске = {поле: текущее.get(поле) for поле in изменённые}
            for поле in представление:
                if поле in текущее:
                    к_маске.setdefault(поле, текущее[поле])
            маска = гейт.mask(
                к_маске,
                entity=описание.name,
                resolve=tools._навигации(репозиторий),
                shape=строение,
                hidden=скрытые.__contains__,
                revealed=раскрытое,
            )
            объект = {поле: маска.data.get(поле) for поле in представление if поле in к_маске}
            показ = _показ_тела(гейт, описание, данные, части, строение)
            # Табличная часть — не «было → станет» одного поля, а разница построчно (`rows_diff`
            # на уже показанных/маскированных строках, `rows_preview`): «было» — маска старого
            # состояния (та же, что показала бы карточка при чтении), «станет» — показ строк
            # модели (Ruling 56, 62, 63, тем же путём, что `_показ_тела` у `create`).
            превью = [
                rows_preview(поле, rows_diff(маска.data.get(поле) or [], показ[поле]))
                if поле in части
                else {"field": поле, "before": маска.data.get(поле), "after": показ[поле]}
                for поле in изменённые
            ]
            предупреждения = list(dict.fromkeys(маска.warnings))

            # Шаг 8: pending-операция. Идентификаторы — непрозрачные (uuid4), не счётчик: чужая
            # сессия прячется за одним кодом `pending_unknown` (решение 4 плана), а номер по
            # порядку позволял бы перебрать соседние операции.
            операция = PendingOp(
                pending_id=_новый_номер(),
                commit_id=_новый_номер(),
                session_id=session_id,
                base=base_config.name,
                role=base_config.role,
                op=op,
                entity=описание.name,
                key=_ключ_операции(реальный_ключ),
                request={
                    "method": "PATCH",
                    "path": spec.path,
                    # Табличная часть — ПОЛНЫЙ новый список (проект §5.2: замещение целиком, а не
                    # разница), как его вернул `_раскрыть_тело` — с каждой строкой.
                    "json": {поле: реальное[поле] for поле in изменённые},
                },
                preview=_превью_операции(описание.name, op, key, объект, превью),
                write_fields=поля_разрешений,
                write_rows=права_строк,
                # Ruling 55: у записи регистра `DataVersion` нет — отпечаток по её полям.
                data_version=_отпечаток(описание, текущее, раскрытое),
                created_at=self._clock(),
                expires_at=self._store.deadline(),
                revealed=раскрытое.carry(),
            )
            await self._store.put(операция)

            # Шаг 9: ответ — выход маскировщика, то, что прислала модель (`key`, «станет»), и
            # поля, которые шлюз составил сам. Из `текущее`/`реальное` в конверт не попадает
            # ничего напрямую: `finish` отказал бы (`internal`) на строке раннего прохода, а
            # открытая строка из 1С ушла бы к стражу — к последнему рубежу вместо основного.
            конверт = {
                "pending_id": операция.pending_id,
                "base": base_config.name,
                "role": base_config.role,
                "entity": описание.name,
                "op": op,
                "key": key,
                "object": объект,
                "preview": превью,
                **(
                    {"summary": операция.preview["summary"]}
                    if "summary" in операция.preview
                    else {}
                ),
                "expires_in_s": round(self._store.remaining(операция.expires_at)),
                "next": СЛЕДУЮЩИЙ_ШАГ,
                "warnings": предупреждения,
            }
            return конверт

        return await tools._run(scope, base, тело)

    async def create(
        self,
        scope: SessionScope,
        session_id: str,
        *,
        base: str | None,
        entity: str,
        data: dict,
    ) -> str:
        """Превью POST нового объекта (SPEC §7.3) → `pending_id`.

        В 1С не уходит ни одного запроса, даже чтения: у нового объекта нет текущего состояния, а
        всё, что можно проверить, проверяется по индексу. Табличные части — списком строк, каждая
        строка — по полям своей сущности (`<владелец>_<табличная часть>` в индексе).

        Токены раскрываются по классам той сущности, чьё поле пишется (Ruling 56): шапка — одним
        `inbound_write` от имени владельца, каждая строка табличной части — своим, от имени
        сущности строки (`_раскрыть_тело_create`). Раскрытие строк от владельца брало бы класс
        поля строки по имени на владельце (`Unmasker._класс_поля`): токен адреса доставки уходил
        бы реальным адресом в поле строки, которое по своей сущности открыто и после `commit`
        читается открытым (Н6-1 ревью задачи 6). Нумерация токенов в отказе — общая на всё тело
        (Ruling 54). Токен с несколькими написаниями без `current` выбрать не по чему —
        `token_ambiguous` (лестница 1.2 отчёта блокеров).

        Превью строится из тела модели, и `mask` не вызывается ни разу (Ruling 45): маска
        значения модели записала бы в общий словарь гейта строку, которой в 1С нет. Открытый
        литерал проходит (Ruling 47), поэтому `check_open_literal` здесь не зовётся, — но в
        превью, `object` и текст подтверждения литерал модели не повторяется ни в каком поле:
        пометка «значение из запроса», у поля защищаемого класса — с классом (Ruling 62, И-1
        итогового ревью M2; Ruling 63, ФП-1 ревью итоговых правок). Иначе страж в `gate.finish`
        заменял бы известное словарю значение тем же токеном, что модель видит в чтении, и
        ставил `guard_replaced`, а неизвестное оставлял литералом, — и модель без единого
        обращения к 1С сопоставляла бы догадку с токеном, в том числе по значению базы вне
        `--bases` сессии (в обход Ruling 35). Поля и класс строки табличной части — по её
        сущности (Ruling 56). Числа, булевы и GUID — как есть: страж в них не заменяет ничего."""
        tools = self._tools

        async def тело(base_config, гейт, репозиторий, раскрытое):
            описание = tools._resolve_entity(репозиторий, гейт, entity)
            скрытые = tools._скрытые(репозиторий, гейт)
            # Разрешения SPEC §7.1 — до полей и типов: запрет базы или флага не зависит от того,
            # верно ли модель собрала тело (инвариант 4). Строки табличных частей — сразу за
            # шапкой и тоже до проверок тела: скрытая табличная часть, запрет её сущности
            # (`deny_entities`) и её полей (`deny_fields`) — те же разрешения у сущности строки.
            поля_разрешений = _имена_полей(data)
            check_write(
                base_config,
                описание,
                "create",
                fields=поля_разрешений,
                hidden=скрытые.__contains__,
            )
            части = _табличные_части_тела(описание, data, репозиторий.describe)
            # Правило §5.1 — до прав и типов строк: номер строки такая же проверяемая часть тела,
            # как её поля, а порядок, который увидят все следующие шаги, уже согласован с 1С.
            # Отдельное имя, не `data =`: переприсваивание параметра сделало бы его локальным для
            # ВСЕЙ функции по правилам области видимости Python, и обращения к нему строкой выше
            # упали бы `UnboundLocalError`.
            данные = _с_номерами_строк(data, части)
            права_строк = _права_строк(данные, части)
            _проверить_права_строк(base_config, права_строк, скрытые)
            _проверить_тело_create(описание, данные, части)

            реальное = _раскрыть_тело(
                гейт,
                описание,
                данные,
                части,
                строение=tools._строение(репозиторий),
                раскрытое=раскрытое,
                current=None,
            )
            _проверить_раскрытые_даты(описание, данные, реальное)
            for имя, описание_строки in части.items():
                for строка, реальная in zip(данные[имя], реальное[имя], strict=True):
                    _проверить_раскрытые_даты(описание_строки, строка, реальная)

            # M3b задача 7 (проект §5.4, проба P9-2): создание записи независимого регистра
            # сведений — единственный `create`, у которого есть смысл спросить 1С «а такая запись
            # уже есть?» до POST. P9-2 показала, что повторный POST тем же ключом 1С отклоняет
            # сама (HTTP 400, ни замещения, ни дубля), но отказ 1С понятнее и происходит раньше —
            # до траты диалога подтверждения на операцию, которая всё равно не выполнится
            # (Ruling 105). Окно между этим GET и `commit` признаётся: другая сессия может
            # создать запись между ними, и тогда исход решает 1С на `commit`.
            предупреждения: list[str] = []
            if описание.is_independent_register:
                ключ_из_тела = {
                    поле: реальное[поле] for поле in описание.key_fields if поле in реальное
                }
                spec_ключа = build_get(
                    описание,
                    ключ_из_тела,
                    describe=репозиторий.describe,
                    limits=tools._config.daemon.limits,
                    select=list(описание.key_fields),
                )
                клиент = tools._client_for(base_config)
                try:
                    await клиент.get(
                        spec_ключа.path, spec_ключа.params, scrub=гейт.scrubber(раскрытое)
                    )
                except OdataError as ошибка:
                    # I-3 (страховка, ревью хвостов M3b): `map_error` даёт `object_not_found`
                    # только при 404 С кодом платформы «9» — проба P9-4 видела «GET 404» без
                    # него, и тогда код выходил `entity_unknown` («структура базы могла
                    # измениться»), хотя сущность только что нашёл `_resolve_entity` по индексу.
                    # Любой 404 по адресу УЖЕ известного регистра читается как «записи нет».
                    if ошибка.code not in ("object_not_found", "entity_unknown"):
                        tools._уточнить_404(ошибка)
                        raise
                else:
                    raise WriteError(
                        "record_exists",
                        f"запись регистра «{описание.name}» с таким ключом уже есть",
                        hint="измените её odata1c_update с этим ключом",
                    )
                if not base_config.permissions.independent_register_delete:
                    предупреждения.append(
                        "откат создания записи регистра недоступен без разрешения "
                        "independent_register_delete"
                    )

            # Ruling 44: объект называется представлением из данных модели — у нового объекта
            # других данных нет, а маска значения модели запрещена (Ruling 45). Литерал модели —
            # пометкой и здесь (Ruling 62, 63).
            показ = _показ_тела(гейт, описание, данные, части, tools._строение(репозиторий))
            объект = {поле: показ[поле] for поле in _поля_представления(описание) if поле in данные}
            превью = body_preview(показ)
            операция = PendingOp(
                pending_id=_новый_номер(),
                commit_id=_новый_номер(),
                session_id=session_id,
                base=base_config.name,
                role=base_config.role,
                op="create",
                entity=описание.name,
                key=None,
                # Набор сущности без ключа — форма P8 для создания (POST → 201, объект целиком).
                request={"method": "POST", "path": описание.name, "json": реальное},
                write_fields=поля_разрешений,
                write_rows=права_строк,
                preview={
                    "entity": описание.name,
                    "op": "create",
                    "key": None,
                    "object": объект,
                    "body": превью,
                },
                # Отпечатка нет: объекта ещё нет, и `commit` сравнивать не с чем (задача 7).
                data_version=None,
                created_at=self._clock(),
                expires_at=self._store.deadline(),
                revealed=раскрытое.carry(),
            )
            await self._store.put(операция)
            return {
                "pending_id": операция.pending_id,
                "base": base_config.name,
                "role": base_config.role,
                "entity": описание.name,
                "op": "create",
                "object": объект,
                "preview": превью,
                "expires_in_s": round(self._store.remaining(операция.expires_at)),
                "next": СЛЕДУЮЩИЙ_ШАГ,
                "warnings": предупреждения,
            }

        return await tools._run(scope, base, тело)

    async def action(
        self,
        scope: SessionScope,
        session_id: str,
        *,
        base: str | None,
        entity: str,
        key,
        name: str,
        params: dict | None = None,
    ) -> str:
        """Превью действия документа (SPEC §7.3) → `pending_id`. В первой поставке — только `Post`
        и `Unpost` (решение 6 плана), под флагом `post_documents`.

        Порядок: разрешения → имя действия и параметры по индексу → ключ → GET текущего
        состояния → предвидимые отказы 1С → превью. Разрешения раньше имени: отказ базы
        (`base_read_only`) не должен зависеть от того, какое имя прислала модель, — и неизвестное
        имя на закрытой базе получает тот же ответ. Флаг `post_documents` `check_write` проверяет
        по тому же перечню `ДЕЙСТВИЯ_ПРОВЕДЕНИЯ`, по которому здесь отказывает `action_unknown`.

        `params` не принимаются (кроме пустых): P8 проверила `Post`/`Unpost` без параметров, а
        `PostingModeOperational` в скобках пути сквозь гейт и `commit` не проверялся. Подсказка
        отказа называет объявленные параметры из индекса.

        Предвидимые отказы (решение 12 плана, факты P8) и почему они несимметричны:
        - `Post` помеченного на удаление — 1С отвечает 500: отказ «сначала снимите пометку»;
        - `Unpost` непроведённого — 1С отвечает 200, но ничего не меняет, кроме `DataVersion`:
          запись без смысла, которую пользователь подтвердил бы зря, — `params_invalid`;
        - `Post` проведённого — перепроведение, настоящая запись (движения пересчитываются,
          `DataVersion` растёт): не отказ, а превью «да → да» с предупреждением."""
        tools = self._tools

        async def тело(base_config, гейт, репозиторий, раскрытое):
            описание = tools._resolve_entity(репозиторий, гейт, entity)
            скрытые = tools._скрытые(репозиторий, гейт)
            check_write(base_config, описание, "action", action=name, hidden=скрытые.__contains__)
            _проверить_действие(описание, name)
            _проверить_параметры_действия(описание, name, params)

            строение = tools._строение(репозиторий)
            реальный_ключ = гейт.inbound_key(
                key, entity=описание.name, revealed=раскрытое, shape=строение
            )
            представление = _поля_представления(описание)
            spec = build_get(
                описание,
                реальный_ключ,
                describe=репозиторий.describe,
                limits=tools._config.daemon.limits,
                select=_выбор_действия(описание, представление),
            )
            клиент = tools._client_for(base_config)
            try:
                сырой = await клиент.get(spec.path, spec.params, scrub=гейт.scrubber(раскрытое))
            except OdataError as ошибка:
                tools._уточнить_404(ошибка)
                raise
            [текущее] = items_of(сырой)[0]

            # Решение — по сырым значениям 1С (булевы, ранний проход их не трогает), показ — из
            # маски: одна маска на вызов, тем же набором раскрытого, что у GET.
            предупреждения = _предвидеть_отказ_действия(name, текущее)
            к_маске = {
                поле: текущее[поле] for поле in (*представление, "Posted") if поле in текущее
            }
            маска = гейт.mask(
                к_маске,
                entity=описание.name,
                resolve=tools._навигации(репозиторий),
                shape=строение,
                hidden=скрытые.__contains__,
                revealed=раскрытое,
            )
            объект = {поле: маска.data.get(поле) for поле in представление if поле in к_маске}
            станет = name == "Post"
            превью = action_preview(name, объект, маска.data.get("Posted"), станет)
            итог = f"проведён: {да_нет(превью['posted']['before'])} → {да_нет(станет)}"

            операция = PendingOp(
                pending_id=_новый_номер(),
                commit_id=_новый_номер(),
                session_id=session_id,
                base=base_config.name,
                role=base_config.role,
                op="action",
                entity=описание.name,
                key=_ключ_операции(реальный_ключ),
                # Форма P8: действие — сегмент пути после ключа, без скобок и параметров; тела
                # нет вовсе (`json=None`: `Client1C.post` тогда не шлёт ни тела, ни
                # `Content-Type` — ровно как проба; `{}` ушёл бы телом, которого P8 не видела).
                # Ответ 1С — 200 с пустым телом, итог — перечитыванием `Posted` в `commit`.
                request={"method": "POST", "path": f"{spec.path}/{name}", "json": None},
                write_action=name,
                preview={
                    "entity": описание.name,
                    "op": "action",
                    "key": key,
                    **превью,
                    "summary": итог,
                },
                # P8: `DataVersion` растёт на любой записи, включая `Post`/`Unpost`, — отпечаток
                # для `commit` тот же, что у `update`.
                data_version=_версия(текущее.get("DataVersion"), раскрытое),
                created_at=self._clock(),
                expires_at=self._store.deadline(),
                revealed=раскрытое.carry(),
            )
            await self._store.put(операция)
            return {
                "pending_id": операция.pending_id,
                "base": base_config.name,
                "role": base_config.role,
                "entity": описание.name,
                "op": "action",
                "key": key,
                "object": объект,
                "preview": превью,
                "summary": итог,
                "expires_in_s": round(self._store.remaining(операция.expires_at)),
                "next": СЛЕДУЮЩИЙ_ШАГ,
                "warnings": list(dict.fromkeys([*предупреждения, *маска.warnings])),
            }

        return await tools._run(scope, base, тело)

    # -- commit -----------------------------------------------------------------------------

    async def commit(
        self,
        scope: SessionScope,
        session_id: str,
        pending_id: str,
        *,
        mechanism: Механизм,
        confirm: Confirmer | None,
    ) -> str:
        """Выполнить подготовленную операцию (SPEC §7.3): единственное место шлюза, где меняются
        данные 1С (инвариант 2).

        Порядок: операция своей сессии (выполненная — прежний ответ как есть) → механизм `deny` →
        подтверждение elicitation (текст через стража) → лимит роли → перечитывание и отпечаток →
        журнал «до» → запрос → повторный GET «после» → журнал «после» → ответ маской чтения. Лимит
        списывается после подтверждения: отказ пользователя квоту не тратит, а попытка, дошедшая
        до 1С или до отпечатка, тратит (решение 7 плана, опасение 3 задачи 3) — иначе лимит
        обходился бы повторными неудачными попытками.

        **Замок на `pending_id`** (решение 1 контролёра): у `PendingStore` нет атомарного
        захвата, и два одновременных `commit` одной операции оба увидели бы её `pending` — 1С
        получила бы два запроса. Второй ждёт первого и получает тот же ответ из стора. Замок
        именно на операцию, а не на сервис: пока пользователь думает над диалогом одной операции,
        `commit` другой не ждёт.

        После отправки запроса операция больше не бывает `pending` ни при каком исходе — ни при
        ошибке 1С, ни при отмене задачи посреди запроса (см. `finally`): повторный `commit` иначе
        выполнил бы запись второй раз. Операция, до 1С не дошедшая (отказ пользователя, лимит,
        сбой чтения, журнал), остаётся `pending` до TTL, её можно подтвердить снова.

        `scope` — видимость баз сессии, как у прочих тулов: база операции проходит через тот же
        реестр. Сверх брифа — у `_run` нет другого входа, а база известна только из операции.
        `mechanism` выбирает слой демона (`confirm.choose_mechanism`, задача 9)."""
        async with self._замок(session_id, pending_id):
            try:
                операция = await self._store.take(pending_id, session_id)
            except WriteError as отказ:
                # Базы ещё нет (она в операции), значит нет и гейта: страж сервиса на строжайшем
                # уровне. Тексты отказов стора значений не несут (решение 4 плана).
                return self._tools._guard_error(отказ.code, отказ.message, отказ.hint)
            if операция.status != "pending":
                return операция.result

            ход = _Ход()
            текст: str | None = None

            async def тело(base_config, гейт, репозиторий, раскрытое):
                return await self._выполнить(
                    операция,
                    ход,
                    base_config,
                    гейт,
                    репозиторий,
                    раскрытое,
                    mechanism=mechanism,
                    confirm=confirm,
                )

            def финиш(гейт, результат, раскрытое):
                # Н2-1 ревью: после выполненной записи ответ «internal» толкал бы модель
                # готовить её заново (у `create` — дубль). Если итоговый ответ не собрался или
                # страж на нём упал, отдаётся страховка «запись выполнена» — она уже прошла
                # стража базы. До записи — обычный путь `_run`.
                if результат is _СТРАХОВКА:
                    return self._страховка_выполнено(ход, операция)
                try:
                    return гейт.finish(результат, раскрытое)
                except Exception:
                    if not ход.выполнено:
                        raise
                    self._tools._записать_трассировку(
                        "страж итогового ответа commit упал после выполненной записи — отдан "
                        "страховочный ответ",
                        раскрытое=раскрытое,
                    )
                    return self._страховка_выполнено(ход, операция)

            try:
                текст = await self._tools._run(scope, операция.base, тело, finisher=финиш)
                итог = ход.итог()
                if итог is not None:
                    await self._store.finish(pending_id, status=итог, result=текст)
                return текст
            finally:
                # Отмена задачи (клиент отключился) посреди запроса или до `finish`: `_run`
                # отмену не ловит, и операция осталась бы `pending` при уже отправленном
                # запросе. Прямая правка полей без `await` — в `finally` отменённой задачи ждать
                # замок стора ненадёжно; объект тот же, что лежит в сторе. Срок продлевается, как
                # это делает `store.finish` (Ruling 40): обрыв связи и есть тот случай, ради
                # которого окно идемпотентности длится полный TTL от выполнения.
                if ход.отправлено and операция.status == "pending":
                    операция.status = ход.итог() or "failed"
                    # Страховочный ответ уже прошёл стража базы (`ход.страховка` строится внутри
                    # `_run`, до каждого `await`, где отмена может прервать выполнение), —
                    # инвариант 1: страж — последний проход по ответу любого тула. Его нет только
                    # при сбое самого стража — тогда отказ без данных стражем сервиса.
                    операция.result = (
                        текст
                        or ход.страховка
                        or self._tools._guard_error(
                            КОД_НЕИЗВЕСТНОГО_ИСХОДА,
                            "commit прерван после отправки запроса в 1С — исход неизвестен, "
                            f"смотрите журнал записи, commit_id {операция.commit_id}",
                            _ПОДСКАЗКА_НЕИЗВЕСТНОГО,
                        )
                    )
                    операция.expires_at = max(операция.expires_at, self._store.deadline())

    def _страховка_выполнено(self, ход: _Ход, операция: PendingOp) -> str:
        """Готовый страховочный ответ «запись выполнена» (уже через стража базы). Его нет, только
        если сбой случился раньше, чем он собран, или упал сам страж, — тогда тот же успешный
        конверт без данных 1С стражем сервиса: номер записи, операция и предупреждение.

        Успех, а не код ошибки (И-4 итогового ревью M2): запись выполнена, и вызывающий, который
        реагирует на код (агент плагина, хук), прочёл бы `internal` как «сбой, можно готовить
        заново» — у `create` это дубль. Ключа в конверте нет: он не собран, а у `create` его
        иначе и не узнать; поиск — по журналу и чтением."""
        return ход.страховка or guard_only(
            self._tools._guard,
            {
                "commit_id": операция.commit_id,
                "base": операция.base,
                "role": операция.role,
                "entity": операция.entity,
                "op": операция.op,
                "result": None,
                "undo": f'odata1c_undo(commit_id="{операция.commit_id}")',
                "warnings": [
                    "запись в 1С выполнена, но ответ не собран — не готовьте операцию заново; "
                    "прочитайте объект сами, исход — в журнале записи (odata1c_journal)"
                ],
            },
        )

    @contextlib.asynccontextmanager
    async def _замок(self, session_id: str, pending_id: str):
        """Замок операции со счётчиком ожидающих: запись удаляется, когда ждать некому, — иначе
        словарь рос бы на каждый `commit`, в том числе на выдуманный `pending_id`.

        Ключ — пара (сессия, операция), а не один `pending_id` (Т7-3 ревью): чужая сессия не
        встаёт в очередь за чужой операцией и получает `pending_unknown` сразу. Иначе задержка
        ответа отличала бы «операция есть и ждёт диалога» от «нет такой» (решение 4 плана).
        Двойной записи это не открывает: выполнить операцию может только её сессия (`take`)."""
        ключ = (session_id, pending_id)
        запись = self._замки.get(ключ)
        if запись is None:
            запись = self._замки[ключ] = _Замок()
        запись.ждут += 1
        try:
            async with запись.lock:
                yield
        finally:
            запись.ждут -= 1
            if запись.ждут == 0:
                del self._замки[ключ]

    async def _выполнить(
        self,
        операция: PendingOp,
        ход: _Ход,
        base_config,
        гейт,
        репозиторий,
        раскрытое: RevealedValues,
        *,
        mechanism: Механизм,
        confirm: Confirmer | None,
    ) -> dict:
        """Тело `commit` внутри `ToolService._run`: тот же гейт, индекс и набор раскрытого, что у
        любого тула, и тот же путь ошибок (любое исключение — текст через гейт)."""
        tools = self._tools
        # Раскрытое при подготовке уходит в 1С сейчас: ранний проход этого вызова обязан его
        # знать (`RevealedValues.carry`), иначе эхо значения в ошибке 1С шло бы мимо него.
        if операция.revealed is not None:
            раскрытое.adopt(операция.revealed)

        if mechanism not in _МЕХАНИЗМЫ:
            raise WriteError("internal", "неизвестный механизм подтверждения записи", _СООБЩИТЕ)
        if mechanism == "deny":
            raise WriteError(
                "write_unsupported_client",
                "клиент этой сессии не умеет подтверждать запись, а доверять ему без "
                "подтверждения демон не настроен — запись не выполнена",
                hint="запись доступна из Claude Code или клиента с elicitation; владелец может "
                "разрешить её этому клиенту на свою ответственность: daemon.yaml → "
                "write_confirm_fallback: trust_client",
            )
        if mechanism == "trust" and self._запасной != "trust_client":
            # Т7-6 ревью: выполнять без вопроса разрешает только владелец, настройкой демона, а не
            # вызывающий переданным литералом.
            raise WriteError(
                "write_unsupported_client",
                "выполнение записи без подтверждения пользователя настройкой демона не разрешено "
                "— запись не выполнена",
                hint="владелец может разрешить его на свою ответственность: daemon.yaml → "
                "write_confirm_fallback: trust_client",
            )
        if операция.mechanism is not None and операция.mechanism != mechanism:
            # Механизм закрепляется за операцией при первом `commit` (Т7-6): отклонённое в
            # диалоге не выполняется следующим вызовом другим механизмом.
            # Свой код, а не `permission_denied` («пользователь отклонил»): на смену механизма
            # слой демона и модель реагируют иначе, чем на отказ пользователя.
            raise WriteError(
                "confirm_mechanism_mismatch",
                "эту операцию уже подтверждали другим способом — сменить его между вызовами "
                "commit нельзя, запись не выполнена",
                hint="подтвердите операцию тем же способом, что в первый раз, или подготовьте её "
                "заново",
            )
        операция.mechanism = mechanism
        # Сущность — до вопроса пользователю: если политика скрыла её после подготовки, отказ
        # не должен ждать диалога и тратить квоту.
        описание = tools._resolve_entity(репозиторий, гейт, операция.entity)
        # Разрешения — второй раз, по `bases.yaml` на момент коммита (SPEC §7.1 и §3.1, поправки
        # 2026-09-14, ADR-0015). Файл действует без перезапуска демона, значит между подготовкой и
        # подтверждением владелец успевает закрыть запись — базу целиком, сущность или отдельное
        # поле, — и проверка при подготовке отвечала на вопрос о прежнем файле. `base_config` уже
        # перечитан (`ToolService._run` → реестр), аргументы — те же, что были у подготовки
        # (`PendingOp.write_fields`/`write_action`/`write_rows`). Раздел `permissions`
        # перепроверяется ЦЕЛИКОМ, поэтому следом идут и разрешения строк табличных частей: запрет
        # поля строки — такое же правило `deny_fields`, и пропустить его значило бы оставить
        # подготовленному `create` обход, которого нет у свежего. Отказ идёт тем же путём, что
        # `entity_hidden` строкой выше: `WriteError` до диалога, до квоты и до любого запроса — в
        # 1С не уходит ничего, операция остаётся неисполненной. Она не снимается со стора:
        # владелец, вернув разрешение, подтверждает ту же операцию, а не готовит её заново.
        скрытые_сейчас = tools._скрытые(репозиторий, гейт)
        check_write(
            base_config,
            описание,
            операция.op,
            fields=операция.write_fields,
            action=операция.write_action,
            hidden=скрытые_сейчас.__contains__,
        )
        _проверить_права_строк(base_config, операция.write_rows, скрытые_сейчас)
        if операция.undo_of is not None:
            # Откат, который уже не выполнится (исходную запись откатили другим откатом), не
            # спрашивает пользователя и не тратит квоту. Это ранняя проверка; обязательная — под
            # журналом прямо перед запросом (там же занятие отката, см. ниже).
            журнал = self._journal()
            try:
                self._проверить_цель_отката(журнал, операция, ход)
            finally:
                журнал.close()
        if mechanism == "elicitation":
            await self._спросить(гейт, операция, раскрытое, confirm)
            # Пользователь мог думать дольше срока операции. Подтверждённое превью тогда старше
            # TTL, а стор вправе убрать операцию (`purge`, Ruling 41) прямо посреди `commit` —
            # и ответ повторному вызову потерялся бы. Срок — тот же, что проверил `take`.
            if self._store.remaining(операция.expires_at) < 0:
                raise WriteError(
                    "pending_expired",
                    "pending-операция истекла, пока ждала подтверждения пользователя — запись не "
                    "выполнена",
                    hint="подготовьте операцию заново и подтвердите её в пределах срока",
                )
        self._limiter.check_and_count(операция.session_id, base_config.permissions.commit_limit)

        строение = tools._строение(репозиторий)
        скрытые = tools._скрытые(репозиторий, гейт)
        выбор = _выбор_коммита(описание, операция, _поля_представления(описание))
        клиент = tools._client_for(base_config)
        проход = гейт.scrubber(раскрытое)

        async def прочитать(ключ: dict) -> dict:
            spec = build_get(
                описание,
                _ключ_пути(ключ),
                describe=репозиторий.describe,
                limits=tools._config.daemon.limits,
                select=выбор,
            )
            try:
                сырой = await клиент.get(spec.path, spec.params, scrub=проход)
            except OdataError as ошибка:
                tools._уточнить_404(ошибка)
                raise
            [объект] = items_of(сырой)[0]
            return объект

        # Шаг 5: перечитать и сверить отпечаток. Чтение НЕ маскируется: маска пишет в словарь
        # гейта, а отказанный `commit` не должен пополнять его ничем (решение 13 плана).
        текущее = None
        if операция.op != "create":
            замен_до_чтения = раскрытое.replacements
            текущее = await прочитать(операция.key)
            # Н2-3 ревью: чтение «до» модели не выдаётся, и замены раннего прохода в нём (ключ
            # записи — токен, раскрытый при подготовке) стражу не засчитываются: `guard_replaced`
            # значит «защищённое значение было в этом ответе». Ошибка чтения (эхо) — не здесь:
            # её текст идёт модели, и замены в нём остаются.
            раскрытое.absorb(раскрытое.replacements - замен_до_чтения)
            отпечаток = _отпечаток(описание, текущее, раскрытое)
            if операция.data_version is None or отпечаток != операция.data_version:
                ход.устарело = True
                raise WriteError(
                    "pending_stale",
                    "объект изменён после превью: отпечаток не совпадает — запись не выполнена",
                    hint="подготовьте операцию заново — объект изменён после превью, новое превью "
                    "покажет его текущее состояние",
                )
        метод = операция.request.get("method")
        if метод not in ("PATCH", "POST", "DELETE"):
            raise WriteError("internal", "неизвестный метод записи в операции", _СООБЩИТЕ)
        поиск = _как_найти(операция, _поля_представления(описание))

        # Шаги 6–8. Журнал открывается на вызов; отказ открытия или записи «до» останавливает
        # запрос (`WriteError("internal")` журнала), операция остаётся `pending`.
        журнал = self._journal()
        занят_откат = False
        try:
            if операция.undo_of is not None:
                # Решение 3 контролёра: проверка «не откачена ли исходная» и занятие отката —
                # без `await` между ними и до запроса; второй откат того же коммита получает
                # отказ здесь, и в 1С уходит один PATCH.
                self._проверить_цель_отката(журнал, операция, ход)
                self._откаты.add(операция.undo_of)
                занят_откат = True
            журнал.open_commit(операция, client=mechanism, before=_для_журнала(текущее, раскрытое))
            запись_прохода = _ЗапоминающийПроход(проход)
            замен_до_записи = раскрытое.replacements
            # Ответ повтору, если отмена прервёт вызов посреди запроса: строится здесь, пока гейт
            # в руках, и проходит стража базы с набором раскрытого операции (инвариант 1).
            ход.страховка = _через_стража(
                гейт, _конверт_прерван(операция, поиск), раскрытое, операция.commit_id
            )
            ход.отправлено = True
            try:
                if метод == "PATCH":
                    ответ = await клиент.patch(
                        операция.request["path"], операция.request["json"], scrub=запись_прохода
                    )
                elif метод == "DELETE":
                    # delete_record (проект M3b §5.4) и откат create записи регистра: у ответа
                    # нет тела (Client1C.delete → None, P9-4 — 204), ниже это учитывает
                    # `_после_записи`, не перечитывая «после» для delete_record.
                    await клиент.delete(операция.request["path"], scrub=запись_прохода)
                    ответ = {}
                else:
                    # `json` действия — `None`: `Client1C.post` тогда не шлёт ни тела, ни
                    # `Content-Type`, как в пробе P8 (решение 5 контролёра).
                    ответ = await клиент.post(
                        операция.request["path"], операция.request["json"], scrub=запись_прохода
                    )
            except OdataError as ошибка:
                неизвестен = _исход_неизвестен(ошибка)
                _дописать(
                    журнал,
                    операция.commit_id,
                    after=None,
                    status="unknown" if неизвестен else "failed",
                    error=_текст_для_журнала(ошибка, запись_прохода.сырой),
                )
                raise _ошибка_записи(
                    гейт.mode, ошибка, операция.commit_id, неизвестен, поиск
                ) from None
            except Exception as сбой:
                # Т7-1 ревью: запрос ушёл, а ответ не разобран (1С записала, но тело не JSON —
                # страница посредника; сбой клиента после отправки). Исход неизвестен так же, как
                # у таймаута, а не `internal`: модель, не зная, что запись могла быть, готовила бы
                # её заново. Тело ответа модели не выдаётся — его замены раннего прохода стражу не
                # засчитываются. Отмена задачи (`CancelledError`) сюда не попадает — её закрывает
                # `finally` в `commit`.
                раскрытое.absorb(раскрытое.replacements - замен_до_записи)
                _log.error(
                    "ответ 1С на запись не разобран, commit_id=%s (%s)",
                    операция.commit_id,
                    type(сбой).__name__,
                )
                _дописать(
                    журнал,
                    операция.commit_id,
                    after=None,
                    status="unknown",
                    error=f"ответ 1С на запись не разобран: {type(сбой).__name__}",
                )
                неразобран = OdataError("odata_error", "ответ 1С на запись не разобран")
                raise _ошибка_записи(
                    гейт.mode, неразобран, операция.commit_id, True, поиск
                ) from None
            ход.выполнено = True
            # Страховка «исход неизвестен» после ответа 1С успехом больше не верна; «запись
            # выполнена» собирается в `_после_записи` до первого `await`.
            ход.страховка = None
            # Ответ записи (объект целиком, P8) модели не выдаётся — из него берётся только ключ
            # созданного объекта. Замены раннего прохода в нём не должны засчитываться стражу:
            # `guard_replaced` значит «в выдаче было защищённое значение», а его там нет.
            раскрытое.absorb(раскрытое.replacements - замен_до_записи)
            try:
                return await self._после_записи(
                    операция,
                    ход,
                    ответ,
                    журнал,
                    прочитать,
                    гейт,
                    описание,
                    репозиторий,
                    строение,
                    скрытые,
                    раскрытое,
                    base_config,
                )
            except Exception:
                # Н2-1: запись выполнена, и никакой сбой сборки ответа не должен превратиться в
                # `internal` — финишер отдаст страховку «запись выполнена».
                tools._записать_трассировку(
                    "ответ commit не собран после выполненной записи — отдан страховочный ответ",
                    раскрытое=раскрытое,
                )
                return _СТРАХОВКА
        finally:
            if занят_откат:
                self._откаты.discard(операция.undo_of)
            журнал.close()

    async def _после_записи(
        self,
        операция: PendingOp,
        ход: _Ход,
        ответ,
        журнал: Journal,
        прочитать,
        гейт,
        описание: EntityDescription,
        репозиторий,
        строение,
        скрытые: frozenset[str],
        раскрытое: RevealedValues,
        base_config,
    ) -> dict:
        """Шаги 8–9: журнал «выполнено», повторный GET «после», ответ маской чтения.

        Здесь запись в 1С уже выполнена, и ни один сбой ниже её не отменяет (Т7-1 ревью). Поэтому
        порядок такой:
        1. сразу по ответу 1С, до первого `await`, журнал получает `committed` и ключ (у `create`
           — из ответа POST): отмена вызова или сбой перечитывания не оставят выполненную запись
           `started` без ключа, и откат `create` будет знать объект;
        2. GET «после» — отдельный шаг; его сбой любого класса — предупреждение «запись
           выполнена, результат не показан», `after` в журнале пустой;
        3. `after` дописывается в журнал отдельным вызовом (`Journal.set_after`), маска «после» —
           последней, и её сбой — тоже предупреждение.
        Маска «после» — данные 1С, словарь узнаёт из неё новые значения (решение 13 плана)."""
        предупреждения: list[str] = []
        if операция.op == "create":
            # P8: ответ POST — объект целиком с ключом, которого у операции не было.
            ключ = _ключ_созданного(описание, ответ, раскрытое)
            ключ_журнала = ключ
        else:
            ключ, ключ_журнала = операция.key, None

        журнал_цел = _записать_журнал(
            журнал.close_commit,
            операция.commit_id,
            after=None,
            status="committed",
            key=ключ_журнала,
        )
        # Откат выполнен — исходная запись отмечается откаченной сразу, до первого `await`:
        # отмена вызова или сбой перечитывания не должны потерять связь (повторный откат иначе
        # прошёл бы проверку `undone_by`). Отказ записи — предупреждение, выполненного не отменяет.
        if операция.undo_of is not None and not _записать_журнал(
            журнал.mark_undone, операция.undo_of, операция.commit_id
        ):
            предупреждения.append(
                "откат выполнен, но исходная запись в журнале не отмечена откаченной — не "
                "откатывайте её повторно; сообщите владельцу"
            )
        # Ключ ответа без «после» и страховочный ответ «запись выполнена» — до первого `await`:
        # отмена во время GET «после» отдаёт повтору ответ, уже прошедший стража базы, с ключом
        # в токенах (составной ключ записи регистра — маской полей ключа из ответа POST).
        ключ_без_после = self._ключ_без_после(
            операция, описание, ключ, ответ, гейт, репозиторий, строение, скрытые, раскрытое
        )
        ход.страховка = _через_стража(
            гейт,
            _конверт_выполнено(операция, base_config, описание, ключ_без_после),
            раскрытое,
            операция.commit_id,
        )

        после = None
        if операция.op == "delete_record":
            # Проект M3b §5.4: запись физически удалена — перечитывать нечего, и 1С честно
            # ответила бы 404 (P9-4); это не сбой, поэтому предупреждения здесь нет.
            pass
        elif ключ is None:
            предупреждения.append(
                "1С не вернула ключ созданного объекта: запись выполнена, но перечитать объект "
                "не по чему — найдите его чтением (odata1c_query)"
            )
        else:
            try:
                после = await прочитать(ключ)
            except Exception as сбой:
                _log.warning(
                    "перечитать объект после записи не удалось, commit_id=%s (%s)",
                    операция.commit_id,
                    type(сбой).__name__,
                )
                предупреждения.append(
                    "запись выполнена, но перечитать объект не удалось — результат не показан; "
                    "прочитайте объект сами"
                )
        после_реальное = _для_журнала(после, раскрытое)
        if после_реальное is not None and журнал_цел:
            журнал_цел = _записать_журнал(журнал.set_after, операция.commit_id, после_реальное)
        if not журнал_цел:
            предупреждения.append(
                "запись в 1С выполнена, но журнал записи не дописан — откат этой записи по журналу "
                "может быть недоступен; сообщите владельцу"
            )
        if после_реальное is not None:
            предупреждения.extend(_расхождения(операция, после_реальное))

        результат = None
        if после is not None:
            try:
                маска = гейт.mask(
                    strip_service(после, keep_data_version=True),
                    entity=описание.name,
                    resolve=self._tools._навигации(репозиторий),
                    shape=строение,
                    hidden=скрытые.__contains__,
                    revealed=раскрытое,
                )
            except Exception:
                self._tools._записать_трассировку(
                    "маска состояния после выполненной записи не удалась — результат не показан",
                    раскрытое=раскрытое,
                )
                предупреждения.append(
                    "запись выполнена, но результат не показан (сбой шлюза); прочитайте объект сами"
                )
            else:
                результат, _ = truncate_strings(
                    маска.data, self._tools._config.daemon.limits.string_chars
                )
                предупреждения.extend(маска.warnings)

        if операция.op != "create":
            # Ключ — как его прислала модель при подготовке (оговорка инварианта 1, М-2).
            ключ_ответа = операция.preview.get("key")
        elif результат is not None:
            ключ_ответа = {поле: результат.get(поле) for поле in описание.key_fields}
        else:
            ключ_ответа = ключ_без_после
        return {
            "commit_id": операция.commit_id,
            "base": base_config.name,
            "role": base_config.role,
            "entity": описание.name,
            "key": ключ_ответа,
            "op": операция.op,
            "result": результат,
            "undo": f'odata1c_undo(commit_id="{операция.commit_id}")',
            "warnings": list(dict.fromkeys(предупреждения)),
        }

    def _ключ_без_после(
        self,
        операция: PendingOp,
        описание: EntityDescription,
        ключ,
        ответ,
        гейт,
        репозиторий,
        строение,
        скрытые: frozenset[str],
        раскрытое: RevealedValues,
    ):
        """Ключ для ответа, когда состояние «после» не прочитано: у `update`/`mark`/`action` — как
        прислала модель (М-2); у `create` — GUID из ответа POST как есть (инвариант 6), составной
        ключ записи регистра — маской полей ключа из ответа POST без записи в словарь (Н2-2
        ревью, Ruling 48): словарь учится только из GET «после» (решение 13 плана), а 201 на
        POST ещё не доказывает, что 1С записала именно это (на PATCH P8 видела успех без записи).
        Известное значение — его токеном, новое — детерминированным токеном без вставки. Маска
        не удалась или ключа нет — `None`."""
        if операция.op != "create":
            return операция.preview.get("key")
        простой = _ключ_без_гейта(ключ)
        if простой is not None or ключ is None or not isinstance(ответ, dict):
            return простой
        try:
            return гейт.mask(
                {поле: ответ.get(поле) for поле in описание.key_fields},
                entity=описание.name,
                resolve=self._tools._навигации(репозиторий),
                shape=строение,
                hidden=скрытые.__contains__,
                revealed=раскрытое,
                persist=False,
            ).data
        except Exception:
            _log.warning(
                "маска ключа созданной записи не удалась, commit_id=%s", операция.commit_id
            )
            return None

    async def _спросить(
        self,
        гейт,
        операция: PendingOp,
        раскрытое: RevealedValues,
        confirm: Confirmer | None,
    ) -> None:
        """Подтверждение elicitation (SPEC §7.2). Текст — через `gate.finish_text` (решение 4
        контролёра): в `PendingOp.preview` «станет» (токены и пометки, Ruling 62, 63) и `key` лежат
        до стража,
        а инвариант 1 распространяется и на диалог. Не `gate.error`/`mask_text`: превью уже в
        токенах, и маскировщик, получивший токен как данные, выдал бы ему свой (`lit`, Б-2) —
        пользователь подтверждал бы не те токены, что видела модель. Страж словарь не пишет.

        «Да» — только явное `True`; сбой механизма — отказ: не спросили — не выполняем."""
        if confirm is None:
            raise WriteError(
                "internal",
                "механизм elicitation без функции подтверждения — ошибка настройки демона",
                _СООБЩИТЕ,
            )
        текст = гейт.finish_text(_текст_подтверждения(операция), раскрытое)
        try:
            согласие = await confirm(текст)
        except Exception as сбой:
            _log.warning("подтверждение записи не получено: %s", type(сбой).__name__)
            согласие = False
        if согласие is not True:
            raise WriteError(
                "permission_denied",
                "пользователь отклонил запись (или подтверждение не получено) — операция не "
                "выполнена",
                hint="операция остаётся подготовленной до истечения срока: если пользователь "
                "передумает, вызовите odata1c_commit(pending_id) ещё раз",
            )

    def _проверить_цель_отката(self, журнал: Journal, операция: PendingOp, ход: _Ход) -> None:
        """Откат ещё можно выполнить: исходная запись не откачена и не откатывается прямо сейчас
        другим вызовом (решение 3 контролёра).

        Два отката одного коммита — две разные pending-операции, у каждой свой замок `commit`, и
        журнал их не упорядочивает: `mark_undone` пишется только после ответа 1С, а между
        проверкой одного отката и его PATCH второй успевает пройти ту же проверку. Поэтому
        вторая линия — занятые откаты в памяти демона (`self._откаты`): проверка и занятие идут
        без `await` между ними, то есть атомарно для цикла событий. Откачена — отказ
        окончательный (`ход.устарело`): выполниться этот откат не сможет никогда. Занята —
        отказ, но операция жива: если первый откат не выполнится, этот можно подтвердить снова.
        `mark_undone` с другим значением до этого не дойдёт (он бросил бы `RuntimeError`)."""
        исходная = журнал.get(операция.undo_of)
        if исходная is None or исходная.undone_by is not None:
            ход.устарело = True
            raise WriteError(
                "undo_unsupported",
                "исходная запись уже откачена другим откатом — этот откат не выполнен",
                hint="текущее состояние объекта — odata1c_get; история записей — odata1c_journal",
            )
        if операция.undo_of in self._откаты:
            raise WriteError(
                "undo_unsupported",
                "откат этой записи сейчас выполняется другим вызовом — этот откат не выполнен",
                hint="итог того отката покажет odata1c_journal; если он не выполнится, повторите "
                "odata1c_commit этого pending_id",
            )

    # -- undo --------------------------------------------------------------------------------

    async def undo(self, scope: SessionScope, session_id: str, *, commit_id: str) -> str:
        """Откат выполненной записи по журналу (SPEC §7.6) → `pending_id`.

        Откат — сама pending-операция (решение 9 плана): здесь только подготовка, в 1С уходит
        одно чтение текущего состояния, выполняет обычный `commit` с подтверждением. У операции
        отката `op` — та запись, которая откатывает (`update`, `mark_for_deletion`, `action`),
        а `undo_of` — исходный коммит: весь путь `commit` (выбор перечитывания, отпечаток,
        расхождения, журнал) работает без особых случаев, а `commit` отката по `undo_of` отмечает
        исходную запись откаченной (`Journal.mark_undone`).

        Видимость — по базам сессии (решение 9 контролёра): `commit_id` базы вне области
        видимости и несуществующий отвечают одним кодом `commit_unknown` и одним текстом, без
        повтора ввода (как `pending_unknown`, решение 4 плана) — иначе ответ сообщал бы, что в
        журнале есть запись чужой базы. Проверка — до `_run`: его отказ `base_unknown` назвал бы
        доступные базы и тем отличил бы чужую запись от выдуманной.

        Прежние значения (`before_json`) — реальные данные 1С, прочитанные `commit` перед
        записью: в тело PATCH они идут как есть, без токенов и `inbound_write` (значение пришло из
        самой базы и через модель не проходило). В превью «станет» — их маска, а не они сами
        (решение 4 контролёра): оговорка инварианта 1 о значениях модели здесь не действует.

        Записи отбираются по видимости баз, а не по сессии (решение контролёра, раунд 2 ревью):
        откатить коммит может любая сессия владельца, которой видна его база, — пользователь
        один, и новая сессия должна уметь откатить запись упавшей. `session_id` — сессия, которой
        будет принадлежать операция отката."""
        tools = self._tools
        try:
            запись, последнее = self._строка_журнала(commit_id)
        except WriteError as отказ:
            return tools._guard_error(отказ.code, отказ.message, отказ.hint)
        if запись is None or not self._база_видна(scope, запись.base):
            return tools._guard_error(*_КОММИТ_НЕИЗВЕСТЕН)

        async def тело(base_config, гейт, репозиторий, раскрытое):
            return await self._подготовить_откат(
                запись, последнее, session_id, base_config, гейт, репозиторий, раскрытое
            )

        return await tools._run(scope, запись.base, тело)

    def _строка_журнала(self, commit_id) -> tuple[JournalEntry | None, str | None]:
        """Строка журнала по `commit_id` (`None` — нет такой) и последнее звено цепочки её
        откатов (`None` — запись не откачена). Журнал — на вызов, как у `commit`.

        Цепочка (Н8-4 ревью): откат отката возвращает изменение, а исходная запись остаётся
        «откаченной» — откатывается только последнее звено. Отказ повторного отката называет его
        `commit_id`: это номер из журнала, а не ввод модели."""
        if not isinstance(commit_id, str) or not commit_id:
            return None, None
        журнал = self._journal()
        try:
            запись = журнал.get(commit_id)
            if запись is None or запись.undone_by is None:
                return запись, None
            звено, пройдено = запись, {запись.commit_id}
            while звено.undone_by is not None and звено.undone_by not in пройдено:
                следующее = журнал.get(звено.undone_by)
                if следующее is None:
                    return запись, звено.undone_by
                пройдено.add(следующее.commit_id)
                звено = следующее
            return запись, звено.commit_id
        except sqlite3.Error as ошибка:
            raise WriteError(
                "internal", "журнал записи недоступен для чтения", _СООБЩИТЕ
            ) from ошибка
        finally:
            журнал.close()

    def _база_видна(self, scope: SessionScope, base: str) -> bool:
        try:
            self._tools._registry.get(base, scope)
        except ConfigError:
            return False
        return True

    async def _подготовить_откат(
        self,
        запись: JournalEntry,
        последнее: str | None,
        session_id: str,
        base_config,
        гейт,
        репозиторий,
        раскрытое: RevealedValues,
    ) -> dict:
        """Тело `undo` внутри `_run`. Порядок: факты журнала (статус, откачена ли) → сущность →
        форма отката по таблице §7.6 → разрешения операции отката (решение 7 контролёра: база
        могла стать только для чтения, флаг — выключиться) → чтение текущего состояния →
        «изменений нет» и предвидимые отказы 1С → превью → операция. До GET — ни одного
        обращения к 1С, как у подготовки (инвариант 4).

        Первым — скрыта ли сущность записи (Н8-2 ревью): `journal` строку скрытой сущности не
        показывает, и `undo` по её `commit_id` отвечает так же, как по несуществующему, — а не
        `entity_hidden` с именем сущности. Отбор тот же, что у `journal`: полный набор скрытых
        по индексу и вхождение имени корня запрета (сущность, которой в индексе больше нет)."""
        tools = self._tools
        if tools._скрыта(репозиторий, гейт, запись.entity) or any(
            корень in запись.entity for корень in гейт.hidden_entities()
        ):
            raise WriteError(*_КОММИТ_НЕИЗВЕСТЕН)
        _проверить_исход(запись, последнее)
        if запись.commit_id in self._откаты:
            raise WriteError(
                "undo_unsupported",
                "откат этой записи сейчас выполняется — второй откат не готовится",
                hint="итог покажет odata1c_journal",
            )
        описание = tools._resolve_entity(репозиторий, гейт, запись.entity)
        скрытые = tools._скрытые(репозиторий, гейт)
        откат = _форма_отката(запись, описание, describe=репозиторий.describe)
        поля_разрешений = tuple(откат.тело or ())
        check_write(
            base_config,
            описание,
            откат.op,
            fields=поля_разрешений,
            action=откат.действие,
            hidden=скрытые.__contains__,
        )
        # I-2 ревью хвостов M3b: права строк табличной части — тем же шагом и той же функцией, что
        # у прямого `update` (`_проверить_права_строк`), и в `PendingOp.write_rows`: `commit`
        # перепроверит их ещё раз по текущему `bases.yaml`, как `write_fields`/`write_action`.
        # Непусто только когда `откат.op == "update"` и тело несёт табличную часть.
        права_строк = _права_строк(откат.тело, откат.части) if откат.части else ()
        if права_строк:
            _проверить_права_строк(base_config, права_строк, скрытые)
        строение = tools._строение(репозиторий)
        навигации = tools._навигации(репозиторий)
        представление = _поля_представления(описание)

        def маска(данные: dict):
            return гейт.mask(
                данные,
                entity=описание.name,
                resolve=навигации,
                shape=строение,
                hidden=скрытые.__contains__,
                revealed=раскрытое,
            )

        # M3b задача 7: откат `delete_record` — воссоздание записи (`откат.op == "create"`), а не
        # PATCH по текущему состоянию: текущего состояния НЕТ (запись физически удалена, GET дал
        # бы 404 — P9-4), сравнивать «до» не с чем. Ветка — раньше общего пути ниже, который эту
        # GET делает безусловно; после неё функция возвращает свой ответ и не продолжает.
        if откат.op == "create":
            ключ_журнала = запись.key
            ключ_ответа = _ключ_без_гейта(ключ_журнала)
            if ключ_ответа is None and isinstance(ключ_журнала, dict):
                ключ_ответа = маска(ключ_журнала).data
                _запомнить_раскрытое(ключ_ответа, ключ_журнала, раскрытое)
            станет_маска = маска(откат.тело)
            _запомнить_раскрытое(станет_маска.data, откат.тело, раскрытое)
            объект = {
                поле: станет_маска.data.get(поле) for поле in представление if поле in откат.тело
            }
            превью = body_preview(станет_маска.data)
            предупреждения = list(станет_маска.warnings)
            if not base_config.permissions.independent_register_delete:
                предупреждения.append(
                    "откат создания записи регистра недоступен без разрешения "
                    "independent_register_delete"
                )
            операция = PendingOp(
                pending_id=_новый_номер(),
                commit_id=_новый_номер(),
                session_id=session_id,
                base=base_config.name,
                role=base_config.role,
                op="create",
                entity=описание.name,
                key=None,
                request={"method": "POST", "path": описание.name, "json": откат.тело},
                write_fields=поля_разрешений,
                write_rows=права_строк,
                preview={
                    "entity": описание.name,
                    "op": "create",
                    "key": ключ_ответа,
                    "object": объект,
                    "body": превью,
                },
                data_version=None,
                created_at=self._clock(),
                expires_at=self._store.deadline(),
                undo_of=запись.commit_id,
                revealed=раскрытое.carry(),
            )
            await self._store.put(операция)
            return {
                "pending_id": операция.pending_id,
                "base": base_config.name,
                "role": base_config.role,
                "entity": описание.name,
                "op": "undo",
                "undo_of": запись.commit_id,
                "undo_op": "create",
                "key": ключ_ответа,
                "object": объект,
                "preview": превью,
                "expires_in_s": round(self._store.remaining(операция.expires_at)),
                "next": СЛЕДУЮЩИЙ_ШАГ,
                "warnings": list(dict.fromkeys(предупреждения)),
            }

        # Ключ из журнала — реальные значения (у записи регистра — значения измерений). Модель
        # его не присылала, поэтому ответ несёт маску, а ранний проход этого вызова и `commit`
        # обязаны знать его значения: эхо ключа в ошибке 1С (404 повторяет путь) иначе прошло
        # бы мимо — у адреса или даты детектора нет. Простой `Ref_Key` — GUID, как есть.
        ключ = запись.key
        ключ_ответа = _ключ_без_гейта(ключ)
        if ключ_ответа is None:
            ключ_ответа = маска(ключ).data
            _запомнить_раскрытое(ключ_ответа, ключ, раскрытое)

        выбор = (
            _выбор_действия(описание, представление)
            if откат.op == "action"
            else _выбор_текущего(описание, откат.тело, откат.op, представление)
        )
        spec = build_get(
            описание,
            _ключ_пути(ключ),
            describe=репозиторий.describe,
            limits=tools._config.daemon.limits,
            select=выбор,
        )
        клиент = tools._client_for(base_config)
        try:
            сырой = await клиент.get(spec.path, spec.params, scrub=гейт.scrubber(раскрытое))
        except OdataError as ошибка:
            tools._уточнить_404(ошибка)
            raise
        [текущее] = items_of(сырой)[0]

        предупреждения: list[str] = []
        if откат.op == "action":
            имя = откат.действие
            предупреждения.extend(_предвидеть_отказ_действия(имя, текущее))
            к_маске = {
                поле: текущее[поле] for поле in (*представление, "Posted") if поле in текущее
            }
            было = маска(к_маске)
            объект = {поле: было.data.get(поле) for поле in представление if поле in к_маске}
            станет = имя == "Post"
            превью = action_preview(имя, объект, было.data.get("Posted"), станет)
            итог = f"проведён: {да_нет(превью['posted']['before'])} → {да_нет(станет)}"
            запрос = {"method": "POST", "path": f"{spec.path}/{имя}", "json": None}
            превью_операции = {
                "entity": описание.name,
                "op": "action",
                "key": ключ_ответа,
                **превью,
                "summary": итог,
            }
        elif откат.op == "delete_record":
            # M3b задача 7: откат `create` записи регистра — физическое удаление тем же путём,
            # что прямой `delete_record` (запись ещё существует — GET выше её нашёл; отпечаток
            # ниже сверит `commit` перед DELETE, как у прямого удаления).
            к_маске = strip_service(текущее)
            было = маска(к_маске)
            объект = {поле: было.data.get(поле) for поле in представление if поле in к_маске}
            превью = {"before": было.data, "after": "записи не будет"}
            итог = None
            запрос = {"method": "DELETE", "path": spec.path, "json": None}
            превью_операции = {
                "entity": описание.name,
                "op": "delete_record",
                "key": ключ_ответа,
                "object": объект,
                "before": было.data,
                "after": "записи не будет",
            }
        else:
            прежнее_целиком = откат.тело
            # Поле, которое уже вернули к прежнему значению, в тело не идёт — как у `update`
            # (решение 8 плана); сравнение — на реальных значениях.
            изменённые = [
                поле
                for поле in прежнее_целиком
                if not _одинаково(
                    прежнее_целиком[поле], _текущее_реальное(текущее.get(поле), раскрытое)
                )
            ]
            if not изменённые:
                raise WriteError(
                    "undo_unsupported",
                    "откатывать нечего: поля записи уже имеют значения, которые были до коммита",
                    hint="проверьте объект чтением (odata1c_get); запись не нужна",
                )
            if откат.op == "mark_for_deletion":
                _предвидеть_отказ_пометки(текущее, прежнее_целиком["DeletionMark"])
            к_маске = {поле: текущее.get(поле) for поле in изменённые}
            for поле in представление:
                if поле in текущее:
                    к_маске.setdefault(поле, текущее[поле])
            # Две маски, каждая — сырых данных 1С, по одному разу (правило «маскировать один раз»):
            # «было» — текущее состояние, «станет» — прежние значения из журнала. Прежние
            # значения уйдут в 1С на `commit`, и его ранний проход обязан их знать: ошибка 1С
            # повторяет переданное значение (P7), а у адреса детектора нет.
            было = маска(к_маске)
            прежнее = {поле: прежнее_целиком[поле] for поле in изменённые}
            станет_маска = маска(прежнее)
            _запомнить_раскрытое(станет_маска.data, прежнее, раскрытое)
            объект = {поле: было.data.get(поле) for поле in представление if поле in к_маске}
            превью = diff_preview(
                {поле: было.data.get(поле) for поле in изменённые},
                {поле: станет_маска.data.get(поле) for поле in изменённые},
            )
            запрос = {"method": "PATCH", "path": spec.path, "json": прежнее}
            превью_операции = _превью_операции(описание.name, откат.op, ключ_ответа, объект, превью)
            итог = превью_операции.get("summary")
            предупреждения.extend(станет_маска.warnings)
        предупреждения.extend(было.warnings)
        # Замены раннего прохода в полях, которые в ответ не идут (служебные, прочие поля записи
        # регистра), — не выдача: `guard_replaced` значил бы «защищённое значение было в ответе».
        _снять_невыданные(текущее, к_маске, раскрытое)

        изменён = _изменён_после_коммита(описание, текущее, запись.after, раскрытое)
        if изменён is not None:
            превью_операции["warning"] = изменён
            предупреждения.insert(0, изменён)

        операция = PendingOp(
            pending_id=_новый_номер(),
            commit_id=_новый_номер(),
            session_id=session_id,
            base=base_config.name,
            role=base_config.role,
            op=откат.op,
            entity=описание.name,
            key=dict(ключ),
            request=запрос,
            write_fields=поля_разрешений,
            write_action=откат.действие,
            write_rows=права_строк,
            preview=превью_операции,
            data_version=_отпечаток(описание, текущее, раскрытое),
            created_at=self._clock(),
            expires_at=self._store.deadline(),
            undo_of=запись.commit_id,
            revealed=раскрытое.carry(),
        )
        await self._store.put(операция)
        return {
            "pending_id": операция.pending_id,
            "base": base_config.name,
            "role": base_config.role,
            "entity": описание.name,
            "op": "undo",
            # `commit_id` исходной записи — из журнала, а не ввод модели: запись найдена.
            "undo_of": запись.commit_id,
            "undo_op": откат.op,
            "key": ключ_ответа,
            "object": объект,
            "preview": превью,
            **({"summary": итог} if итог else {}),
            **({"warning": изменён} if изменён is not None else {}),
            "expires_in_s": round(self._store.remaining(операция.expires_at)),
            "next": СЛЕДУЮЩИЙ_ШАГ,
            "warnings": list(dict.fromkeys(предупреждения)),
        }

