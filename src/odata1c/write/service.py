"""Сервис записи: подготовка pending-операций (SPEC §7.3; план M2, задачи 5–8).

Первая точка, где запись встречается с гейтом: реальные значения объекта 1С (текущее состояние и
тело PATCH) и превью для модели проходят через один вызов, и ошибка здесь сразу нарушает
инвариант 1. Отсюда устройство:

- **Всё — внутри `ToolService._run`.** Та же точка входа, что у тулов чтения: тот же гейт базы,
  тот же индекс, один набор раскрытого (`RevealedValues`) на вызов — его видят и ранний проход
  клиента 1С на GET, и `inbound_write`, и маскировщик превью, и страж в `gate.finish`. Отдельная
  точка входа для записи означала бы второй набор раскрытого и второй путь ошибок, а их
  расхождение с путём чтения — ровно та утечка, от которой `_run` защищает (любое исключение —
  текст ошибки через гейт, неожиданное — `internal` без текста).
- **Порядок вызовов гейта — контракт раунда блокеров M2** (раздел 1.1 отчёта): `inbound_key` →
  `client.get(scrub=…)` → `inbound_write(current=как пришло)` → маска сырого текущего один раз →
  `finish`. Маскированное обратно в `mask` не подаётся никогда: токен шлюза, пришедший в
  маскировщик как данные, считается строкой из базы и получает свой токен (`lit`, Б-2).
- **Подготовка не пишет в общий словарь гейта ничего, чего нет в 1С** (Ruling 45, находки C-1 и
  I-1 ревью задачи 5). Маскировщик выдаёт токен через `Dictionary.token_for`, а тот СОХРАНЯЕТ
  значение — в словарь, общий для всех баз и сессий домашнего каталога. Маска «было» — данные 1С,
  как у чтения. «Станет» — значения модели КАК ЕСТЬ (токен — токеном, литерал — литералом) и в
  маску не подаются: маска значения, которое придумала модель, до подтверждения делала бы чужое
  ядро названия неоднозначным (оно уходило открытым во всех ответах), давала номеру документа класс
  телефона (инвариант 6) и лишнее написание, ломающее следующую запись токеном. Словарь узнаёт новое
  значение только после `commit` — из повторного чтения объекта обычной маской (задача 7).
- **До 1С — всё, что можно проверить без неё** (решение 3 контролёра): разрешения SPEC §7.1,
  открытый литерал в поле, которое на чтении принимает только токен (Ruling 45), поля и типы тела.
  Неверный запрос не трогает базу даже чтением. После GET остаются только проверки, которым нужно
  текущее состояние: разрешение токена по `current` (лестница 1.2), «изменений нет», предвидимый
  отказ 1С (решение 12 плана: пометка проведённого документа).

Инвариант 2: подготовка ничего не пишет в 1С — только GET текущего состояния. Тело PATCH с
реальными значениями живёт в `PendingOp.request` (память демона, решение 3 плана) до `commit`.
"""

