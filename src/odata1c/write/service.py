def _проставить_номера_строк(часть: str, строки: list[dict]) -> list[dict]:
    """Номера строк табличной части по правилу проекта M3b §5.1 (Ruling 104, проба P9-7): 1С
    принимает номера строк только ровно 1..n без пропусков и повторов — 2 и 3 вместо 1 и 2 даёт
    HTTP 400, отсутствие номера — HTTP 500 «внутренняя ошибка OData сервиса», уже ПОСЛЕ
    подтверждения пользователя (известное ограничение записи M2, `docs/probes/M2-live-check.md`).

    Три исхода: ни одна строка номера не несёт — шлюз нумерует 1..n в порядке тела; несут все —
    множество номеров обязано быть ровно `{1, …, n}` (тип, положительность, отсутствие пропусков и
    повторов проверяются одним условием), и строки переставляются по возрастанию номера — порядок
    в теле для 1С не важен, важен номер; несут не все — отказ: вставить ненумерованные строки между
    нумерованными можно несколькими способами, и любой из них шлюз выбрал бы за модель молча.

    Правило одно для `create` и `update` — вызывающий зовёт эту функцию до любой другой проверки
    тела и до обращения к 1С (SPEC §7.1: до 1С — всё, что можно проверить без неё)."""
    с_номером = [строка for строка in строки if ПОЛЕ_НОМЕРА_СТРОКИ in строка]
    if not с_номером:
        return [
            {ПОЛЕ_НОМЕРА_СТРОКИ: номер, **строка} for номер, строка in enumerate(строки, start=1)
        ]
    if len(с_номером) != len(строки):
        raise _отказ(
            f"табличная часть «{часть}»: LineNumber либо у всех строк табличной части, либо ни "
            "у одной",
            hint="уберите LineNumber везде — шлюз пронумерует строки по порядку тела",
        )
    номера = [строка[ПОЛЕ_НОМЕРА_СТРОКИ] for строка in строки]
    целые = all(isinstance(н, int) and not isinstance(н, bool) for н in номера)
    if not целые or sorted(номера) != list(range(1, len(строки) + 1)):
        raise _отказ(
            f"табличная часть «{часть}»: номера строк табличной части обязаны идти подряд с 1",
            hint="LineNumber — целые числа от 1 до количества строк без пропусков и повторов; "
            "порядок строк в теле не важен — шлюз расставит их по номеру",
        )
    return sorted(строки, key=lambda строка: строка[ПОЛЕ_НОМЕРА_СТРОКИ])


def _с_номерами_строк(data: dict, части: dict[str, EntityDescription]) -> dict:
    """Тело записи с проставленными номерами строк каждой табличной части (правило §5.1) — копия
    `data`, без изменения исходного словаря вызывающего. Строится до любой другой проверки тела:
    количество и порядок строк, которые видят все следующие шаги (права, типы, раскрытие, показ,
    PATCH), уже согласованы с 1С.

    Значение не-списком трогать нечем: `_проверить_строки`/`_проверить_тело_update` отказывают на
    нём своим текстом («ожидает список строк»), и здесь для него нет отдельной проверки — как и
    для списка, где не все строки объекты (то же самое «не список строк», только глубже)."""
    if not части:
        return data
    итог = dict(data)
    for имя in части:
        строки = итог.get(имя)
        if isinstance(строки, list) and all(isinstance(строка, dict) for строка in строки):
            итог[имя] = _проставить_номера_строк(имя, строки)
    return итог


