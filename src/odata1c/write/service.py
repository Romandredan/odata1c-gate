def _текущее_реальное(значение, раскрытое: RevealedValues):
    """Значение поля текущего состояния с реальным содержимым — для сравнения «изменилось ли»
    (шаг 6). Строка, переписанная ранним проходом (`ScrubbedText`), несёт на месте раскрытого
    значения токен; её исходное значение знает только набор этого вызова (Б-3). Та же развёртка,
    что `unmasking._развернуть` делает для `inbound_write`, — иначе поле, чьё значение гейт
    раскрыл в этом же вызове, считалось бы изменённым всегда: токен в строке ≠ реальное значение.
    Исходное неизвестно — строка сравнивается как есть и выйдет изменённой: сторона безопасная
    (лишнее поле в превью), а не молчаливая (пропущенное изменение)."""
    if isinstance(значение, ScrubbedText):
        исходное = раскрытое.original_of(значение)
        return значение if исходное is None else исходное
    return значение


class WriteService:
    """Пишущие тулы шлюза (SPEC §5, §7): подготовка pending-операций, `commit`, `undo`, журнал.

    Задача 5 — `update` и `mark_for_deletion`, задача 6 — `create` и `action`. `journal` и
    `limiter` принимаются уже здесь, чтобы сигнатура не менялась в задачах 7–8: подготовка не
    пишет журнал (в 1С ещё ничего не отправлено) и не тратит лимит коммитов (решение 7 плана: лимит
    считается в `commit`).

    `clock` — настенные часы для `PendingOp.created_at` (журнал хранит время как дату, SPEC §7.5).
    Срок жизни операции — НЕ от них: `expires_at` берётся только из `store.deadline()`, а остаток
    для ответа — из `store.remaining()`: у стора свои (монотонные) часы, и два источника времени
    для одного TTL дали бы операцию, которая истекает мгновенно или никогда (см.
    `PendingStore.deadline`).

    `journal` — фабрика журнала, а не открытый журнал (задача 7): `commit` открывает
    `journal.sqlite` на один вызов и закрывает в `finally`, как индекс и словарь, — на Windows
    открытое соединение SQLite держит файл, и домашний каталог нельзя было бы ни перенести, ни
    почистить, пока жив демон (см. докстринг `write/journal.py`). Демону — `lambda:
    Journal(путь)`.

    `confirm_fallback` — `write_confirm_fallback` демона (`daemon.yaml`, SPEC §7.2): механизм
    `trust` допустим только при `trust_client` (Т7-6 ревью задачи 7). Не передан — берётся из
    настроек `ToolService`, то есть из того же `daemon.yaml`: механизм выбирает вызывающий, а
    разрешение выполнять без вопроса — только владелец.
    """

    def __init__(
        self,
        tools: ToolService,
        store: PendingStore,
        journal: Callable[[], Journal],
        limiter: CommitLimiter,
        *,
        clock: Callable[[], float] = time.time,
        confirm_fallback: Literal["deny", "trust_client"] | None = None,
    ) -> None:
        self._tools = tools
        self._store = store
        self._journal = journal
        self._limiter = limiter
        self._clock = clock
        self._запасной = confirm_fallback or tools._config.daemon.write_confirm_fallback
        # Замки `commit` по паре (сессия, операция) (решение 1 контролёра, Т7-3): запись и
        # счётчик ожидающих, чтобы словарь не рос на каждый `commit`.
        self._замки: dict[tuple[str, str], _Замок] = {}

    # -- подготовка ------------------------------------------------------------------------

    async def update(
        self,
        scope: SessionScope,
        session_id: str,
        *,
        base: str | None,
        entity: str,
        key,
        data: dict,
    ) -> str:
        """Превью PATCH с разницей «поле: было → станет» (SPEC §7.3) → `pending_id`.

        `session_id` — ключ MCP-сессии, которой принадлежит операция; откуда он берётся
        (заголовок `mcp-session-id`), решает слой демона (задача 9)."""

        def проверить_тело(описание: EntityDescription, проверить_литерал: _Литерал) -> None:
            _проверить_тело_update(описание, data, проверить_литерал)

        return await self._подготовить(
            scope,
            session_id,
            base=base,
            entity=entity,
            key=key,
            data=data,
            op="update",
            проверить_тело=проверить_тело,
        )

    async def mark_for_deletion(
        self,
        scope: SessionScope,
        session_id: str,
        *,
        base: str | None,
        entity: str,
        key,
        mark: bool = True,
    ) -> str:
        """Превью PATCH `DeletionMark` (SPEC §7.3) → `pending_id`. `mark=False` — снять пометку.

        Тот же путь, что `update`, но со своим входом: `DeletionMark` запрещён для `update`
        (решение 11 плана) и разрешён только здесь, под флагом `mark_deletion` (шаг 3 SPEC §7.1).
        Физического удаления объектов в шлюзе нет (инвариант 3) — это единственный способ убрать
        объект."""

        def проверить_тело(описание: EntityDescription, _проверить_литерал: _Литерал) -> None:
            # `DeletionMark` — `bool`, открытым литералом защищаемого класса быть не может.
            _проверить_пометку(описание, mark)

        return await self._подготовить(
            scope,
            session_id,
            base=base,
            entity=entity,
            key=key,
            data={"DeletionMark": mark},
            op="mark_for_deletion",
            проверить_тело=проверить_тело,
        )

    async def _подготовить(
        self,
        scope: SessionScope,
        session_id: str,
        *,
        base: str | None,
        entity: str,
        key,
        data: dict,
        op: Операция,
        проверить_тело: Callable[[EntityDescription, _Литерал], None],
    ) -> str:
        tools = self._tools

        async def тело(base_config, гейт, репозиторий, раскрытое):
            # Шаги 1–3: ни одного обращения к 1С. Сущность — через `_resolve_entity`, как у
            # чтения: скрытая отвечает `entity_hidden` раньше, чем проверяется существование, —
            # иначе запись различала бы скрытую и несуществующую сущность кодом ошибки.
            описание = tools._resolve_entity(репозиторий, гейт, entity)
            скрытые = tools._скрытые(репозиторий, гейт)
            # Разрешения — до ключа и до полей: запрет базы или флага не должен зависеть от того,
            # правильно ли модель написала ключ (порядок SPEC §7.1, инвариант 4).
            check_write(
                base_config,
                описание,
                op,
                fields=_имена_полей(data),
                hidden=скрытые.__contains__,
            )
            строение = tools._строение(репозиторий)

            # Открытый литерал в поле, которое на чтении принимает только токен (`dob`), — отказ
            # тем же кодом и текстом, что у отбора, и до GET (Ruling 45, находка I-1): иначе
            # «изменений нет» отвечало бы на тот же вопрос, что запрещённый на чтении
            # `ДатаРождения eq datetime'…'`, — перебором дат, без единого обращения к карточке.
            def проверить_литерал(имя: str, значение) -> None:
                гейт.check_open_literal(описание.name, имя, значение, shape=строение)

            проверить_тело(описание, проверить_литерал)

            реальный_ключ = гейт.inbound_key(
                key, entity=описание.name, revealed=раскрытое, shape=строение
            )
            # Путь по ключу без `$expand` — тот же, по которому пойдёт PATCH в `commit`. Выбор —
            # поля тела, служебные и представление объекта (Ruling 44): объект целиком
            # (табличные части с контактной информацией) подготовке не нужен, а каждое лишнее
            # поле — лишнее реальное значение в памяти.
            представление = _поля_представления(описание)
            spec = build_get(
                описание,
                реальный_ключ,
                describe=репозиторий.describe,
                limits=tools._config.daemon.limits,
                select=_выбор_текущего(описание, data, op, представление),
            )

            # Шаг 4: текущее состояние — с ранним проходом (ошибка 1С повторяет значения, P7).
            клиент = tools._client_for(base_config)
            try:
                сырой = await клиент.get(spec.path, spec.params, scrub=гейт.scrubber(раскрытое))
            except OdataError as ошибка:
                tools._уточнить_404(ошибка)
                raise
            # `current` — как пришло (контракт 1.2): без `strip_service` (он вырезал бы
            # `DataVersion`) и без переписывания строк раннего прохода — их гейт разворачивает сам.
            [текущее] = items_of(сырой)[0]

            # Шаг 5: токены → реальные значения по лестнице 1.2; `inbound_write`, а не `body`.
            реальное = гейт.inbound_write(
                data, entity=описание.name, shape=строение, current=текущее, revealed=раскрытое
            )
            _проверить_раскрытые_даты(описание, data, реальное)

            # Шаг 6: изменённость — на РЕАЛЬНЫХ значениях, не на токенах (одно значение в двух
            # написаниях — один токен, а 1С получит другую строку). Неизменённое поле в тело
            # PATCH не идёт (решение 8 плана): 1С не получает лишнего, откат точнее.
            изменённые = [
                поле
                for поле in data
                if реальное[поле] != _текущее_реальное(текущее.get(поле), раскрытое)
            ]
            if not изменённые:
                raise _отказ(
                    "изменений нет: значения тела совпадают с текущими значениями объекта",
                    hint="проверьте, что объект и поля выбраны верно; запись не нужна",
                )
            # Предвидимый отказ 1С — после «изменений нет»: у документа, который уже в нужном
            # состоянии, подсказка «сначала Unpost» толкала бы на лишнее распроведение.
            if op == "mark_for_deletion":
                _предвидеть_отказ_пометки(текущее, data["DeletionMark"])

            # Шаг 7 (Ruling 45, 44): ОДНА маска — сырого текущего состояния, изменённых полей и
            # полей представления объекта, той же сущностью и с тем же набором раскрытого (он
            # нужен маскировщику, чтобы строка раннего прохода получила токен по настоящему
            # содержимому, Б-3). Это данные 1С, и словарь узнаёт их так же, как при чтении
            # карточки. «Станет» — значения `data` как прислала модель, без маски: `реальное` в
            # `mask` не подаётся нигде (см. докстринг модуля). Литерал модели, совпавший со
            # значением словаря, заменит токеном страж в `gate.finish` — тот же оракул, что `eq`
            # с открытым литералом на чтении, принятый Ruling 45.
            к_маске = {поле: текущее.get(поле) for поле in изменённые}
            for поле in представление:
                if поле in текущее:
                    к_маске.setdefault(поле, текущее[поле])
            маска = гейт.mask(
                к_маске,
                entity=описание.name,
                resolve=tools._навигации(репозиторий),
                shape=строение,
                hidden=скрытые.__contains__,
                revealed=раскрытое,
            )
            объект = {поле: маска.data.get(поле) for поле in представление if поле in к_маске}
            превью = diff_preview(
                {поле: маска.data.get(поле) for поле in изменённые},
                {поле: data[поле] for поле in изменённые},
            )
            предупреждения = list(dict.fromkeys(маска.warnings))

            # Шаг 8: pending-операция. Идентификаторы — непрозрачные (uuid4), не счётчик: чужая
            # сессия прячется за одним кодом `pending_unknown` (решение 4 плана), а номер по
            # порядку позволял бы перебрать соседние операции.
            операция = PendingOp(
                pending_id=uuid.uuid4().hex,
                commit_id=uuid.uuid4().hex,
                session_id=session_id,
                base=base_config.name,
                role=base_config.role,
                op=op,
                entity=описание.name,
                key=_ключ_операции(реальный_ключ),
                request={
                    "method": "PATCH",
                    "path": spec.path,
                    "json": {поле: реальное[поле] for поле in изменённые},
                },
                preview=_превью_операции(описание.name, op, key, объект, превью),
                # Ruling 55: у записи регистра `DataVersion` нет — отпечаток по её полям.
                data_version=_отпечаток(описание, текущее, раскрытое),
                created_at=self._clock(),
                expires_at=self._store.deadline(),
                revealed=раскрытое.carry(),
            )
            await self._store.put(операция)

            # Шаг 9: ответ — выход маскировщика, то, что прислала модель (`key`, «станет»), и
            # поля, которые шлюз составил сам. Из `текущее`/`реальное` в конверт не попадает
            # ничего напрямую: `finish` отказал бы (`internal`) на строке раннего прохода, а
            # открытая строка из 1С ушла бы к стражу — к последнему рубежу вместо основного.
            конверт = {
                "pending_id": операция.pending_id,
                "base": base_config.name,
                "role": base_config.role,
                "entity": описание.name,
                "op": op,
                "key": key,
                "object": объект,
                "preview": превью,
                **(
                    {"summary": операция.preview["summary"]}
                    if "summary" in операция.preview
                    else {}
                ),
                "expires_in_s": round(self._store.remaining(операция.expires_at)),
                "next": СЛЕДУЮЩИЙ_ШАГ,
                "warnings": предупреждения,
            }
            return конверт

        return await tools._run(scope, base, тело)

    async def create(
        self,
        scope: SessionScope,
        session_id: str,
        *,
        base: str | None,
        entity: str,
        data: dict,
    ) -> str:
        """Превью POST нового объекта (SPEC §7.3) → `pending_id`.

        В 1С не уходит ни одного запроса, даже чтения: у нового объекта нет текущего состояния, а
        всё, что можно проверить, проверяется по индексу. Табличные части — списком строк, каждая
        строка — по полям своей сущности (`<владелец>_<табличная часть>` в индексе).

        Токены раскрываются по классам той сущности, чьё поле пишется (Ruling 56): шапка — одним
        `inbound_write` от имени владельца, каждая строка табличной части — своим, от имени
        сущности строки (`_раскрыть_тело_create`). Раскрытие строк от владельца брало бы класс
        поля строки по имени на владельце (`Unmasker._класс_поля`): токен адреса доставки уходил
        бы реальным адресом в поле строки, которое по своей сущности открыто и после `commit`
        читается открытым (Н6-1 ревью задачи 6). Нумерация токенов в отказе — общая на всё тело
        (Ruling 54). Токен с несколькими написаниями без `current` выбрать не по чему —
        `token_ambiguous` (лестница 1.2 отчёта блокеров).

        Превью — тело как прислала модель, и `mask` не вызывается ни разу (Ruling 45): маска
        значения модели записала бы в общий словарь гейта строку, которой в 1С нет. Открытый
        литерал проходит (Ruling 47), поэтому `check_open_literal` здесь не зовётся."""
        tools = self._tools

        async def тело(base_config, гейт, репозиторий, раскрытое):
            описание = tools._resolve_entity(репозиторий, гейт, entity)
            скрытые = tools._скрытые(репозиторий, гейт)
            # Разрешения SPEC §7.1 — до полей и типов: запрет базы или флага не зависит от того,
            # верно ли модель собрала тело (инвариант 4). Строки табличных частей — сразу за
            # шапкой и тоже до проверок тела: скрытая табличная часть, запрет её сущности
            # (`deny_entities`) и её полей (`deny_fields`) — те же разрешения у сущности строки.
            check_write(
                base_config,
                описание,
                "create",
                fields=_имена_полей(data),
                hidden=скрытые.__contains__,
            )
            части = _табличные_части_тела(описание, data, репозиторий.describe)
            _проверить_права_строк(base_config, data, части, скрытые)
            _проверить_тело_create(описание, data, части)

            реальное = _раскрыть_тело_create(
                гейт,
                описание,
                data,
                части,
                строение=tools._строение(репозиторий),
                раскрытое=раскрытое,
            )
            _проверить_раскрытые_даты(описание, data, реальное)
            for имя, описание_строки in части.items():
                for строка, реальная in zip(data[имя], реальное[имя], strict=True):
                    _проверить_раскрытые_даты(описание_строки, строка, реальная)

            # Ruling 44: объект называется представлением из данных модели как есть — у нового
            # объекта других данных нет, а маска значения модели запрещена (Ruling 45).
            объект = {поле: data[поле] for поле in _поля_представления(описание) if поле in data}
            превью = body_preview(data)
            операция = PendingOp(
                pending_id=uuid.uuid4().hex,
                commit_id=uuid.uuid4().hex,
                session_id=session_id,
                base=base_config.name,
                role=base_config.role,
                op="create",
                entity=описание.name,
                key=None,
                # Набор сущности без ключа — форма P8 для создания (POST → 201, объект целиком).
                request={"method": "POST", "path": описание.name, "json": реальное},
                preview={
                    "entity": описание.name,
                    "op": "create",
                    "key": None,
                    "object": объект,
                    "body": превью,
                },
                # Отпечатка нет: объекта ещё нет, и `commit` сравнивать не с чем (задача 7).
                data_version=None,
                created_at=self._clock(),
                expires_at=self._store.deadline(),
                revealed=раскрытое.carry(),
            )
            await self._store.put(операция)
            return {
                "pending_id": операция.pending_id,
                "base": base_config.name,
                "role": base_config.role,
                "entity": описание.name,
                "op": "create",
                "object": объект,
                "preview": превью,
                "expires_in_s": round(self._store.remaining(операция.expires_at)),
                "next": СЛЕДУЮЩИЙ_ШАГ,
                "warnings": [],
            }

        return await tools._run(scope, base, тело)

    async def action(
        self,
        scope: SessionScope,
        session_id: str,
        *,
        base: str | None,
        entity: str,
        key,
        name: str,
        params: dict | None = None,
    ) -> str:
        """Превью действия документа (SPEC §7.3) → `pending_id`. В первой поставке — только `Post`
        и `Unpost` (решение 6 плана), под флагом `post_documents`.

        Порядок: разрешения → имя действия и параметры по индексу → ключ → GET текущего
        состояния → предвидимые отказы 1С → превью. Разрешения раньше имени: отказ базы
        (`base_read_only`) не должен зависеть от того, какое имя прислала модель, — и неизвестное
        имя на закрытой базе получает тот же ответ. Флаг `post_documents` `check_write` проверяет
        по тому же перечню `ДЕЙСТВИЯ_ПРОВЕДЕНИЯ`, по которому здесь отказывает `action_unknown`.

        `params` не принимаются (кроме пустых): P8 проверила `Post`/`Unpost` без параметров, а
        `PostingModeOperational` в скобках пути сквозь гейт и `commit` не проверялся. Подсказка
        отказа называет объявленные параметры из индекса.

        Предвидимые отказы (решение 12 плана, факты P8) и почему они несимметричны:
        - `Post` помеченного на удаление — 1С отвечает 500: отказ «сначала снимите пометку»;
        - `Unpost` непроведённого — 1С отвечает 200, но ничего не меняет, кроме `DataVersion`:
          запись без смысла, которую пользователь подтвердил бы зря, — `params_invalid`;
        - `Post` проведённого — перепроведение, настоящая запись (движения пересчитываются,
          `DataVersion` растёт): не отказ, а превью «да → да» с предупреждением."""
        tools = self._tools

        async def тело(base_config, гейт, репозиторий, раскрытое):
            описание = tools._resolve_entity(репозиторий, гейт, entity)
            скрытые = tools._скрытые(репозиторий, гейт)
            check_write(base_config, описание, "action", action=name, hidden=скрытые.__contains__)
            _проверить_действие(описание, name)
            _проверить_параметры_действия(описание, name, params)

            строение = tools._строение(репозиторий)
            реальный_ключ = гейт.inbound_key(
                key, entity=описание.name, revealed=раскрытое, shape=строение
            )
            представление = _поля_представления(описание)
            spec = build_get(
                описание,
                реальный_ключ,
                describe=репозиторий.describe,
                limits=tools._config.daemon.limits,
                select=_выбор_действия(описание, представление),
            )
            клиент = tools._client_for(base_config)
            try:
                сырой = await клиент.get(spec.path, spec.params, scrub=гейт.scrubber(раскрытое))
            except OdataError as ошибка:
                tools._уточнить_404(ошибка)
                raise
            [текущее] = items_of(сырой)[0]

            # Решение — по сырым значениям 1С (булевы, ранний проход их не трогает), показ — из
            # маски: одна маска на вызов, тем же набором раскрытого, что у GET.
            предупреждения = _предвидеть_отказ_действия(name, текущее)
            к_маске = {
                поле: текущее[поле] for поле in (*представление, "Posted") if поле in текущее
            }
            маска = гейт.mask(
                к_маске,
                entity=описание.name,
                resolve=tools._навигации(репозиторий),
                shape=строение,
                hidden=скрытые.__contains__,
                revealed=раскрытое,
            )
            объект = {поле: маска.data.get(поле) for поле in представление if поле in к_маске}
            станет = name == "Post"
            превью = action_preview(name, объект, маска.data.get("Posted"), станет)
            итог = f"проведён: {да_нет(превью['posted']['before'])} → {да_нет(станет)}"

            операция = PendingOp(
                pending_id=uuid.uuid4().hex,
                commit_id=uuid.uuid4().hex,
                session_id=session_id,
                base=base_config.name,
                role=base_config.role,
                op="action",
                entity=описание.name,
                key=_ключ_операции(реальный_ключ),
                # Форма P8: действие — сегмент пути после ключа, без скобок и параметров; тела
                # нет вовсе (`json=None`: `Client1C.post` тогда не шлёт ни тела, ни
                # `Content-Type` — ровно как проба; `{}` ушёл бы телом, которого P8 не видела).
                # Ответ 1С — 200 с пустым телом, итог — перечитыванием `Posted` в `commit`.
                request={"method": "POST", "path": f"{spec.path}/{name}", "json": None},
                preview={
                    "entity": описание.name,
                    "op": "action",
                    "key": key,
                    **превью,
                    "summary": итог,
                },
                # P8: `DataVersion` растёт на любой записи, включая `Post`/`Unpost`, — отпечаток
                # для `commit` тот же, что у `update`.
                data_version=_версия(текущее.get("DataVersion"), раскрытое),
                created_at=self._clock(),
                expires_at=self._store.deadline(),
                revealed=раскрытое.carry(),
            )
            await self._store.put(операция)
            return {
                "pending_id": операция.pending_id,
                "base": base_config.name,
                "role": base_config.role,
                "entity": описание.name,
                "op": "action",
                "key": key,
                "object": объект,
                "preview": превью,
                "summary": итог,
                "expires_in_s": round(self._store.remaining(операция.expires_at)),
                "next": СЛЕДУЮЩИЙ_ШАГ,
                "warnings": list(dict.fromkeys([*предупреждения, *маска.warnings])),
            }

        return await tools._run(scope, base, тело)

    # -- commit -----------------------------------------------------------------------------

    async def commit(
        self,
        scope: SessionScope,
        session_id: str,
        pending_id: str,
        *,
        mechanism: Механизм,
        confirm: Confirmer | None,
    ) -> str:
        """Выполнить подготовленную операцию (SPEC §7.3): единственное место шлюза, где меняются
        данные 1С (инвариант 2).

        Порядок: операция своей сессии (выполненная — прежний ответ как есть) → механизм `deny` →
        подтверждение elicitation (текст через стража) → лимит роли → перечитывание и отпечаток →
        журнал «до» → запрос → повторный GET «после» → журнал «после» → ответ маской чтения. Лимит
        списывается после подтверждения: отказ пользователя квоту не тратит, а попытка, дошедшая
        до 1С или до отпечатка, тратит (решение 7 плана, опасение 3 задачи 3) — иначе лимит
        обходился бы повторными неудачными попытками.

        **Замок на `pending_id`** (решение 1 контролёра): у `PendingStore` нет атомарного
        захвата, и два одновременных `commit` одной операции оба увидели бы её `pending` — 1С
        получила бы два запроса. Второй ждёт первого и получает тот же ответ из стора. Замок
        именно на операцию, а не на сервис: пока пользователь думает над диалогом одной операции,
        `commit` другой не ждёт.

        После отправки запроса операция больше не бывает `pending` ни при каком исходе — ни при
        ошибке 1С, ни при отмене задачи посреди запроса (см. `finally`): повторный `commit` иначе
        выполнил бы запись второй раз. Операция, до 1С не дошедшая (отказ пользователя, лимит,
        сбой чтения, журнал), остаётся `pending` до TTL, её можно подтвердить снова.

        `scope` — видимость баз сессии, как у прочих тулов: база операции проходит через тот же
        реестр. Сверх брифа — у `_run` нет другого входа, а база известна только из операции.
        `mechanism` выбирает слой демона (`confirm.choose_mechanism`, задача 9)."""
        async with self._замок(session_id, pending_id):
            try:
                операция = await self._store.take(pending_id, session_id)
            except WriteError as отказ:
                # Базы ещё нет (она в операции), значит нет и гейта: страж сервиса на строжайшем
                # уровне. Тексты отказов стора значений не несут (решение 4 плана).
                return self._tools._guard_error(отказ.code, отказ.message, отказ.hint)
            if операция.status != "pending":
                return операция.result

            ход = _Ход()
            текст: str | None = None

            async def тело(base_config, гейт, репозиторий, раскрытое):
                return await self._выполнить(
                    операция,
                    ход,
                    base_config,
                    гейт,
                    репозиторий,
                    раскрытое,
                    mechanism=mechanism,
                    confirm=confirm,
                )

            try:
                текст = await self._tools._run(scope, операция.base, тело)
                итог = ход.итог()
                if итог is not None:
                    await self._store.finish(pending_id, status=итог, result=текст)
                return текст
            finally:
                # Отмена задачи (клиент отключился) посреди запроса или до `finish`: `_run`
                # отмену не ловит, и операция осталась бы `pending` при уже отправленном
                # запросе. Прямая правка полей без `await` — в `finally` отменённой задачи ждать
                # замок стора ненадёжно; объект тот же, что лежит в сторе. Срок продлевается, как
                # это делает `store.finish` (Ruling 40): обрыв связи и есть тот случай, ради
                # которого окно идемпотентности длится полный TTL от выполнения.
                if ход.отправлено and операция.status == "pending":
                    операция.status = ход.итог() or "failed"
                    # Страховочный ответ уже прошёл стража базы (`ход.страховка` строится внутри
                    # `_run`, до каждого `await`, где отмена может прервать выполнение), —
                    # инвариант 1: страж — последний проход по ответу любого тула. Его нет только
                    # при сбое самого стража — тогда отказ без данных стражем сервиса.
                    операция.result = (
                        текст
                        or ход.страховка
                        or self._tools._guard_error(
                            "internal", "commit прерван после отправки запроса в 1С", _СООБЩИТЕ
                        )
                    )
                    операция.expires_at = max(операция.expires_at, self._store.deadline())

    @contextlib.asynccontextmanager
    async def _замок(self, session_id: str, pending_id: str):
        """Замок операции со счётчиком ожидающих: запись удаляется, когда ждать некому, — иначе
        словарь рос бы на каждый `commit`, в том числе на выдуманный `pending_id`.

        Ключ — пара (сессия, операция), а не один `pending_id` (Т7-3 ревью): чужая сессия не
        встаёт в очередь за чужой операцией и получает `pending_unknown` сразу. Иначе задержка
        ответа отличала бы «операция есть и ждёт диалога» от «нет такой» (решение 4 плана).
        Двойной записи это не открывает: выполнить операцию может только её сессия (`take`)."""
        ключ = (session_id, pending_id)
        запись = self._замки.get(ключ)
        if запись is None:
            запись = self._замки[ключ] = _Замок()
        запись.ждут += 1
        try:
            async with запись.lock:
                yield
        finally:
            запись.ждут -= 1
            if запись.ждут == 0:
                del self._замки[ключ]

    async def _выполнить(
        self,
        операция: PendingOp,
        ход: _Ход,
        base_config,
        гейт,
        репозиторий,
        раскрытое: RevealedValues,
        *,
        mechanism: Механизм,
        confirm: Confirmer | None,
    ) -> dict:
        """Тело `commit` внутри `ToolService._run`: тот же гейт, индекс и набор раскрытого, что у
        любого тула, и тот же путь ошибок (любое исключение — текст через гейт)."""
        tools = self._tools
        # Раскрытое при подготовке уходит в 1С сейчас: ранний проход этого вызова обязан его
        # знать (`RevealedValues.carry`), иначе эхо значения в ошибке 1С шло бы мимо него.
        if операция.revealed is not None:
            раскрытое.adopt(операция.revealed)

        if mechanism not in _МЕХАНИЗМЫ:
            raise WriteError("internal", "неизвестный механизм подтверждения записи", _СООБЩИТЕ)
        if mechanism == "deny":
            raise WriteError(
                "write_unsupported_client",
                "клиент этой сессии не умеет подтверждать запись, а доверять ему без "
                "подтверждения демон не настроен — запись не выполнена",
                hint="запись доступна из Claude Code или клиента с elicitation; владелец может "
                "разрешить её этому клиенту на свою ответственность: daemon.yaml → "
                "write_confirm_fallback: trust_client",
            )
        if mechanism == "trust" and self._запасной != "trust_client":
            # Т7-6 ревью: выполнять без вопроса разрешает только владелец, настройкой демона, а не
            # вызывающий переданным литералом.
            raise WriteError(
                "write_unsupported_client",
                "выполнение записи без подтверждения пользователя настройкой демона не разрешено "
                "— запись не выполнена",
                hint="владелец может разрешить его на свою ответственность: daemon.yaml → "
                "write_confirm_fallback: trust_client",
            )
        if операция.mechanism is not None and операция.mechanism != mechanism:
            # Механизм закрепляется за операцией при первом `commit` (Т7-6): отклонённое в
            # диалоге не выполняется следующим вызовом другим механизмом.
            # Свой код, а не `permission_denied` («пользователь отклонил»): на смену механизма
            # слой демона и модель реагируют иначе, чем на отказ пользователя.
            raise WriteError(
                "confirm_mechanism_mismatch",
                "эту операцию уже подтверждали другим способом — сменить его между вызовами "
                "commit нельзя, запись не выполнена",
                hint="подтвердите операцию тем же способом, что в первый раз, или подготовьте её "
                "заново",
            )
        операция.mechanism = mechanism
        # Сущность — до вопроса пользователю: если политика скрыла её после подготовки, отказ
        # не должен ждать диалога и тратить квоту.
        описание = tools._resolve_entity(репозиторий, гейт, операция.entity)
        if mechanism == "elicitation":
            await self._спросить(гейт, операция, раскрытое, confirm)
            # Пользователь мог думать дольше срока операции. Подтверждённое превью тогда старше
            # TTL, а стор вправе убрать операцию (`purge`, Ruling 41) прямо посреди `commit` —
            # и ответ повторному вызову потерялся бы. Срок — тот же, что проверил `take`.
            if self._store.remaining(операция.expires_at) < 0:
                raise WriteError(
                    "pending_expired",
                    "pending-операция истекла, пока ждала подтверждения пользователя — запись не "
                    "выполнена",
                    hint="подготовьте операцию заново и подтвердите её в пределах срока",
                )
        self._limiter.check_and_count(операция.session_id, base_config.permissions.commit_limit)

        строение = tools._строение(репозиторий)
        скрытые = tools._скрытые(репозиторий, гейт)
        выбор = _выбор_коммита(описание, операция, _поля_представления(описание))
        клиент = tools._client_for(base_config)
        проход = гейт.scrubber(раскрытое)

        async def прочитать(ключ: dict) -> dict:
            spec = build_get(
                описание,
                _ключ_пути(ключ),
                describe=репозиторий.describe,
                limits=tools._config.daemon.limits,
                select=выбор,
            )
            try:
                сырой = await клиент.get(spec.path, spec.params, scrub=проход)
            except OdataError as ошибка:
                tools._уточнить_404(ошибка)
                raise
            [объект] = items_of(сырой)[0]
            return объект

        # Шаг 5: перечитать и сверить отпечаток. Чтение НЕ маскируется: маска пишет в словарь
        # гейта, а отказанный `commit` не должен пополнять его ничем (решение 13 плана).
        текущее = None
        if операция.op != "create":
            текущее = await прочитать(операция.key)
            отпечаток = _отпечаток(описание, текущее, раскрытое)
            if операция.data_version is None or отпечаток != операция.data_version:
                ход.устарело = True
                raise WriteError(
                    "pending_stale",
                    "объект изменён после превью: отпечаток не совпадает — запись не выполнена",
                    hint="подготовьте операцию заново — объект изменён после превью, новое превью "
                    "покажет его текущее состояние",
                )
        метод = операция.request.get("method")
        if метод not in ("PATCH", "POST"):
            raise WriteError("internal", "неизвестный метод записи в операции", _СООБЩИТЕ)
        поиск = _как_найти(операция, _поля_представления(описание))

        # Шаги 6–8. Журнал открывается на вызов; отказ открытия или записи «до» останавливает
        # запрос (`WriteError("internal")` журнала), операция остаётся `pending`.
        журнал = self._journal()
        try:
            журнал.open_commit(операция, client=mechanism, before=_для_журнала(текущее, раскрытое))
            запись_прохода = _ЗапоминающийПроход(проход)
            замен_до_записи = раскрытое.replacements
            # Ответ повтору, если отмена прервёт вызов посреди запроса: строится здесь, пока гейт
            # в руках, и проходит стража базы с набором раскрытого операции (инвариант 1).
            ход.страховка = _через_стража(
                гейт, _конверт_прерван(операция, поиск), раскрытое, операция.commit_id
            )
            ход.отправлено = True
            try:
                if метод == "PATCH":
                    ответ = await клиент.patch(
                        операция.request["path"], операция.request["json"], scrub=запись_прохода
                    )
                else:
                    # `json` действия — `None`: `Client1C.post` тогда не шлёт ни тела, ни
                    # `Content-Type`, как в пробе P8 (решение 5 контролёра).
                    ответ = await клиент.post(
                        операция.request["path"], операция.request["json"], scrub=запись_прохода
                    )
            except OdataError as ошибка:
                неизвестен = _исход_неизвестен(ошибка)
                _дописать(
                    журнал,
                    операция.commit_id,
                    after=None,
                    status="unknown" if неизвестен else "failed",
                    error=_текст_для_журнала(ошибка, запись_прохода.сырой),
                )
                raise _ошибка_записи(
                    гейт.mode, ошибка, операция.commit_id, неизвестен, поиск
                ) from None
            except Exception as сбой:
                # Т7-1 ревью: запрос ушёл, а ответ не разобран (1С записала, но тело не JSON —
                # страница посредника; сбой клиента после отправки). Исход неизвестен так же, как
                # у таймаута, а не `internal`: модель, не зная, что запись могла быть, готовила бы
                # её заново. Тело ответа модели не выдаётся — его замены раннего прохода стражу не
                # засчитываются. Отмена задачи (`CancelledError`) сюда не попадает — её закрывает
                # `finally` в `commit`.
                раскрытое.absorb(раскрытое.replacements - замен_до_записи)
                _log.error(
                    "ответ 1С на запись не разобран, commit_id=%s (%s)",
                    операция.commit_id,
                    type(сбой).__name__,
                )
                _дописать(
                    журнал,
                    операция.commit_id,
                    after=None,
                    status="unknown",
                    error=f"ответ 1С на запись не разобран: {type(сбой).__name__}",
                )
                неразобран = OdataError("odata_error", "ответ 1С на запись не разобран")
                raise _ошибка_записи(
                    гейт.mode, неразобран, операция.commit_id, True, поиск
                ) from None
            ход.выполнено = True
            # Ответ записи (объект целиком, P8) модели не выдаётся — из него берётся только ключ
            # созданного объекта. Замены раннего прохода в нём не должны засчитываться стражу:
            # `guard_replaced` значит «в выдаче было защищённое значение», а его там нет.
            раскрытое.absorb(раскрытое.replacements - замен_до_записи)
            return await self._после_записи(
                операция,
                ход,
                ответ,
                журнал,
                прочитать,
                гейт,
                описание,
                репозиторий,
                строение,
                скрытые,
                раскрытое,
                base_config,
            )
        finally:
            журнал.close()

    async def _после_записи(
        self,
        операция: PendingOp,
        ход: _Ход,
        ответ,
        журнал: Journal,
        прочитать,
        гейт,
        описание: EntityDescription,
        репозиторий,
        строение,
        скрытые: frozenset[str],
        раскрытое: RevealedValues,
        base_config,
    ) -> dict:
        """Шаги 8–9: журнал «выполнено», повторный GET «после», ответ маской чтения.

        Здесь запись в 1С уже выполнена, и ни один сбой ниже её не отменяет (Т7-1 ревью). Поэтому
        порядок такой:
        1. сразу по ответу 1С, до первого `await`, журнал получает `committed` и ключ (у `create`
           — из ответа POST): отмена вызова или сбой перечитывания не оставят выполненную запись
           `started` без ключа, и откат `create` будет знать объект;
        2. GET «после» — отдельный шаг; его сбой любого класса — предупреждение «запись
           выполнена, результат не показан», `after` в журнале пустой;
        3. `after` дописывается в журнал отдельным вызовом (`Journal.set_after`), маска «после» —
           последней, и её сбой — тоже предупреждение.
        Маска «после» — данные 1С, словарь узнаёт из неё новые значения (решение 13 плана)."""
        предупреждения: list[str] = []
        if операция.op == "create":
            # P8: ответ POST — объект целиком с ключом, которого у операции не было.
            ключ = _ключ_созданного(описание, ответ, раскрытое)
            ключ_журнала = ключ
        else:
            ключ, ключ_журнала = операция.key, None

        журнал_цел = _записать_журнал(
            журнал.close_commit,
            операция.commit_id,
            after=None,
            status="committed",
            key=ключ_журнала,
        )
        # Ключ ответа без «после» и страховочный ответ «запись выполнена» — до первого `await`:
        # отмена во время GET «после» отдаёт повтору ответ, уже прошедший стража базы, с ключом
        # в токенах (составной ключ записи регистра — маской полей ключа из ответа POST).
        ключ_без_после = self._ключ_без_после(
            операция, описание, ключ, ответ, гейт, репозиторий, строение, скрытые, раскрытое
        )
        ход.страховка = _через_стража(
            гейт,
            _конверт_выполнено(операция, base_config, описание, ключ_без_после),
            раскрытое,
            операция.commit_id,
        )

        после = None
        if ключ is None:
            предупреждения.append(
                "1С не вернула ключ созданного объекта: запись выполнена, но перечитать объект "
                "не по чему — найдите его чтением (odata1c_query)"
            )
        else:
            try:
                после = await прочитать(ключ)
            except Exception as сбой:
                _log.warning(
                    "перечитать объект после записи не удалось, commit_id=%s (%s)",
                    операция.commit_id,
                    type(сбой).__name__,
                )
                предупреждения.append(
                    "запись выполнена, но перечитать объект не удалось — результат не показан; "
                    "прочитайте объект сами"
                )
        после_реальное = _для_журнала(после, раскрытое)
        if после_реальное is not None and журнал_цел:
            журнал_цел = _записать_журнал(журнал.set_after, операция.commit_id, после_реальное)
        if not журнал_цел:
            предупреждения.append(
                "запись в 1С выполнена, но журнал записи не дописан — откат этой записи по журналу "
                "может быть недоступен; сообщите владельцу"
            )
        if после_реальное is not None:
            предупреждения.extend(_расхождения(операция, после_реальное))

        результат = None
        if после is not None:
            try:
                маска = гейт.mask(
                    strip_service(после, keep_data_version=True),
                    entity=описание.name,
                    resolve=self._tools._навигации(репозиторий),
                    shape=строение,
                    hidden=скрытые.__contains__,
                    revealed=раскрытое,
                )
            except Exception:
                self._tools._записать_трассировку(
                    "маска состояния после выполненной записи не удалась — результат не показан",
                    раскрытое=раскрытое,
                )
                предупреждения.append(
                    "запись выполнена, но результат не показан (сбой шлюза); прочитайте объект сами"
                )
            else:
                результат, _ = truncate_strings(
                    маска.data, self._tools._config.daemon.limits.string_chars
                )
                предупреждения.extend(маска.warnings)

        if операция.op != "create":
            # Ключ — как его прислала модель при подготовке (оговорка инварианта 1, М-2).
            ключ_ответа = операция.preview.get("key")
        elif результат is not None:
            ключ_ответа = {поле: результат.get(поле) for поле in описание.key_fields}
        else:
            ключ_ответа = ключ_без_после
        return {
            "commit_id": операция.commit_id,
            "base": base_config.name,
            "role": base_config.role,
            "entity": описание.name,
            "key": ключ_ответа,
            "op": операция.op,
            "result": результат,
            "undo": f'odata1c_undo(commit_id="{операция.commit_id}")',
            "warnings": list(dict.fromkeys(предупреждения)),
        }

    def _ключ_без_после(
        self,
        операция: PendingOp,
        описание: EntityDescription,
        ключ,
        ответ,
        гейт,
        репозиторий,
        строение,
        скрытые: frozenset[str],
        раскрытое: RevealedValues,
    ):
        """Ключ для ответа, когда состояние «после» не прочитано: у `update`/`mark`/`action` — как
        прислала модель (М-2); у `create` — GUID из ответа POST как есть (инвариант 6), составной
        ключ записи регистра — маской полей ключа из ответа POST (данные 1С, после выполненной
        записи словарь вправе их узнать). Маска не удалась или ключа нет — `None`."""
        if операция.op != "create":
            return операция.preview.get("key")
        простой = _ключ_без_гейта(ключ)
        if простой is not None or ключ is None or not isinstance(ответ, dict):
            return простой
        try:
            return гейт.mask(
                {поле: ответ.get(поле) for поле in описание.key_fields},
                entity=описание.name,
                resolve=self._tools._навигации(репозиторий),
                shape=строение,
                hidden=скрытые.__contains__,
                revealed=раскрытое,
            ).data
        except Exception:
            _log.warning(
                "маска ключа созданной записи не удалась, commit_id=%s", операция.commit_id
            )
            return None

    async def _спросить(
        self,
        гейт,
        операция: PendingOp,
        раскрытое: RevealedValues,
        confirm: Confirmer | None,
    ) -> None:
        """Подтверждение elicitation (SPEC §7.2). Текст — через `gate.finish_text` (решение 4
        контролёра): в `PendingOp.preview` «станет» и `key` лежат как прислала модель, до стража,
        а инвариант 1 распространяется и на диалог. Не `gate.error`/`mask_text`: превью уже в
        токенах, и маскировщик, получивший токен как данные, выдал бы ему свой (`lit`, Б-2) —
        пользователь подтверждал бы не те токены, что видела модель. Страж словарь не пишет.

        «Да» — только явное `True`; сбой механизма — отказ: не спросили — не выполняем."""
        if confirm is None:
            raise WriteError(
                "internal",
                "механизм elicitation без функции подтверждения — ошибка настройки демона",
                _СООБЩИТЕ,
            )
        текст = гейт.finish_text(_текст_подтверждения(операция), раскрытое)
        try:
            согласие = await confirm(текст)
        except Exception as сбой:
            _log.warning("подтверждение записи не получено: %s", type(сбой).__name__)
            согласие = False
        if согласие is not True:
            raise WriteError(
                "permission_denied",
                "пользователь отклонил запись (или подтверждение не получено) — операция не "
                "выполнена",
                hint="операция остаётся подготовленной до истечения срока: если пользователь "
                "передумает, вызовите odata1c_commit(pending_id) ещё раз",
            )


# -- проверки тела до обращения к 1С -----------------------------------------------------------


def _имена_полей(data) -> tuple[str, ...]:
    """Имена полей тела для `check_write` (шаг 6 SPEC §7.1). Тело не словарём — пустой набор:
    отказ по форме тела даст `_проверить_тело_update` сразу после разрешений, а разрешения базы и
    флага от формы тела не зависят."""
    if not isinstance(data, dict):
        return ()
    return tuple(имя for имя in data if isinstance(имя, str))


def _проверить_тело_update(описание: EntityDescription, data, проверить_литерал: _Литерал) -> None:
    """Шаг 3 брифа: поля и типы тела `update` — по индексу, до обращения к 1С.

    Проверка обязательна, а не вежлива (факт P8): 1С молча принимает недопустимое — несуществующее
    поле и `Ref_Key` в теле отвечают 200 без записи, строка в `Edm.Int64` не записывается, ссылка на
    несуществующий объект записывается. Превью обещало бы запись, которой не будет.

    Текст отказа называет поле и ожидаемый тип, но не значение (Ruling 20, пункт 2, как у
    `odata_literal`): значение от модели может быть уже реальным, а ошибка уходит тем же путём,
    что данные."""
    if not isinstance(data, dict) or not data:
        raise _отказ(
            "тело записи пустое: передайте data словарём «поле: новое значение»",
            hint="поля сущности — odata1c_describe_entity",
        )
    if описание.is_tabular_part:
        # Строка табличной части — часть объекта-владельца (SPEC §7.3: одна операция — один
        # объект); изменение табличных частей — вне первой поставки.
        raise _отказ(
            f"«{описание.name}» — табличная часть: изменение строк табличных частей в этой "
            "поставке не поддерживается",
            hint=f"изменяйте поля шапки владельца «{описание.parent_entity}»",
        )
    поля = {поле["name"]: поле for поле in описание.fields}
    for имя, значение in data.items():
        _проверить_поле(описание, поля, имя, значение, проверить_литерал)


def _проверить_поле(
    описание: EntityDescription, поля: dict, имя, значение, проверить_литерал: _Литерал
) -> None:
    """Порядок: устройство тела (имя, запрещённые и ключевые поля, существование, табличная
    часть) → открытый литерал защищаемого класса (Ruling 45) → тип. Литерал — раньше типа: на
    дату рождения без времени подсказка о формате толкала бы повторить ту же догадку в годной
    форме, а отказ по классу поля отвечает сразу и одинаково на любую."""
    поле = _поле_тела(
        описание, поля, имя, запрещённые=_НЕ_ПИШЕТСЯ_В_UPDATE, где="через update", ключ=True
    )
    тип = поле["edm_type"]
    if тип.startswith("Collection("):
        raise _отказ(
            f"поле «{имя}» — табличная часть: изменение табличных частей в этой поставке не "
            "поддерживается",
            hint="изменяйте поля шапки объекта",
        )
    проверить_литерал(имя, значение)
    _проверить_тип(имя, тип, значение)


def _поле_тела(
    описание: EntityDescription,
    поля: dict,
    имя,
    *,
    запрещённые: dict[str, str],
    где: str,
    ключ: bool,
) -> dict:
    """Устройство одного поля тела — общее для `update`, `create` и строки табличной части:
    имя — строка, не из запрещённых (с подсказкой, что делать вместо), не ключевое (`ключ=True`,
    только `update`), есть у сущности в индексе. Возвращает описание поля — тип проверяет
    вызывающий: у `update` и `create` по-разному устроена табличная часть.

    `create` ключевые поля пишет: у записи регистра аргумента `key` нет, измерения и период — её
    данные, а у строки табличной части `LineNumber` — порядок строки. Ссылка (`Ref_Key`) закрыта
    перечнем запрещённых и там, и там.

    Ruling 53: имя, которого нет в индексе, не повторяется — только имя сущности и подсказки из
    индекса. Имена в прочих отказах — из закрытого перечня или из индекса."""
    if not isinstance(имя, str):
        raise _отказ("имя поля в теле записи должно быть строкой")
    if имя in запрещённые:
        raise _отказ(f"поле «{имя}» не записывается {где}", hint=запрещённые[имя])
    if ключ and имя in описание.key_fields:
        raise _отказ(
            f"поле «{имя}» — часть ключа «{описание.name}», его значение запись не меняет",
            hint="ключ объекта передаётся аргументом key",
        )
    поле = поля.get(имя)
    if поле is None:
        raise _отказ(
            f"у сущности «{описание.name}» нет поля из тела записи — список полей в "
            "odata1c_describe_entity",
            hint=_подсказка_поля(поля, имя),
        )
    return поле


def _подсказка_поля(поля: dict, имя: str) -> str:
    """Самый частый промах — имя навигации вместо ссылочного поля: `Контрагент` вместо
    `Контрагент_Key` (так связь выглядит в `$expand`). 1С ссылку пишет только полем `…_Key` с
    GUID; поле без суффикса она молча проигнорировала бы (P8).

    Ruling 53: имя от модели в подсказке не повторяется — только имена полей ИЗ индекса:
    ссылочное `…_Key` (оно есть у сущности) или похожие по написанию."""
    if f"{имя}_Key" in поля:
        return f"ссылочное поле пишется как «{имя}_Key» со значением GUID (Ref_Key объекта)"
    похожие = difflib.get_close_matches(имя, list(поля), n=3, cutoff=0.75)
    if похожие:
        return "похожие поля сущности: " + ", ".join(похожие)
    return "поля сущности — odata1c_describe_entity"


def _проверить_тип(имя: str, тип: str, значение) -> None:
    """Значение тела против `Edm.*` поля. Без молчаливого приведения: строка «1500» в числовом
    поле — отказ, а не 1500. 1С несовпадение типа не запишет и ответит 200 (P8), а приведение
    шлюзом сделало бы превью лживым — показано одно, записано другое.

    `Edm.DateTime` с целым токеном — единственное исключение из проверки до 1С: дата бывает
    защищаемым значением (класс `dob`, `ДатаРождения`), и формат её реального значения известен
    только после раскрытия — его проверяет `_проверить_раскрытые_даты` сразу за `inbound_write`,
    всё ещё до создания операции."""
    ожидается = f"поле «{имя}» ожидает {тип}"
    if значение is None:
        raise _отказ(
            f"{ожидается}, передано пустое значение (null)",
            hint=f'пустое значение: для строки — "", для ссылки — {_ПУСТОЙ_GUID}, для числа — 0, '
            "для даты — 0001-01-01T00:00:00",
        )
    if тип == "Edm.String":
        годно = isinstance(значение, str)
    elif тип == "Edm.Guid":
        годно = isinstance(значение, str) and bool(_GUID.fullmatch(значение))
    elif тип == "Edm.Boolean":
        годно = isinstance(значение, bool)
    elif тип in _ЦЕЛЫЕ:
        годно = isinstance(значение, int) and not isinstance(значение, bool)
    elif тип in _ДРОБНЫЕ:
        # `NaN`/`Infinity` pydantic разбирает из JSON вызова MCP, а `json.dumps` пишет их в тело
        # PATCH как невалидный JSON (M-1 ревью задачи 5): отказ пришёл бы от 1С на `commit`.
        годно = (
            isinstance(значение, int | float)
            and not isinstance(значение, bool)
            and math.isfinite(значение)
        )
    elif тип == "Edm.DateTime":
        годно = isinstance(значение, str) and (
            bool(_ДАТА_ВРЕМЯ.fullmatch(значение)) or parse_token(значение) is not None
        )
    else:
        raise _отказ(f"поле «{имя}» типа {тип}: запись полей этого типа не поддерживается")
    if not годно:
        raise _отказ(
            f"{ожидается}: значение этого типа не соответствует", hint=_ФОРМА_ТИПА.get(тип, "")
        )


_ФОРМА_ТИПА = {
    "Edm.String": "строка в кавычках JSON",
    "Edm.Guid": "GUID вида xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx без обёртки guid'…' — Ref_Key "
    "связанного объекта из ответа query/get",
    "Edm.Boolean": "true или false без кавычек",
    "Edm.DateTime": "строка YYYY-MM-DDTHH:MM:SS",
    **{тип: "целое число без кавычек" for тип in _ЦЕЛЫЕ},
    **{тип: "число без кавычек" for тип in _ДРОБНЫЕ},
}


def _проверить_раскрытые_даты(описание: EntityDescription, data: dict, реальное: dict) -> None:
    """Дата, переданная токеном (см. `_проверить_тип`), после раскрытия обязана быть датой в
    формате записи. Иначе в 1С ушла бы строка, которую она молча не запишет (P8). Текст отказа
    — без значения: оно уже реальное."""
    типы = {поле["name"]: поле["edm_type"] for поле in описание.fields}
    for имя, значение in data.items():
        if типы.get(имя) != "Edm.DateTime" or not isinstance(значение, str):
            continue
        if parse_token(значение) is None:
            continue
        итог = реальное.get(имя)
        if not (isinstance(итог, str) and _ДАТА_ВРЕМЯ.fullmatch(итог)):
            raise _отказ(
                f"поле «{имя}» ожидает Edm.DateTime, а значение токена — не дата в формате записи",
                hint=_ФОРМА_ТИПА["Edm.DateTime"],
            )


def _проверить_пометку(описание: EntityDescription, mark) -> None:
    """Годность сущности для пометки удаления — по индексу: есть ли у неё поле `DeletionMark`.
    Одна проверка закрывает записи регистров (у них пометки нет вовсе, SPEC §7.1), строки
    табличных частей, константы и журналы документов. Виртуальные таблицы до сюда не доходят —
    их отказывает `check_write` (шаг 4 SPEC §7.1)."""
    if not isinstance(mark, bool):
        raise _отказ("mark ожидает true или false", hint="true — пометить, false — снять пометку")
    if описание.is_tabular_part or not any(
        поле["name"] == "DeletionMark" for поле in описание.fields
    ):
        raise _отказ(
            f"у «{описание.name}» нет пометки удаления: пометить можно справочник, документ и "
            "другие объекты, но не запись регистра и не строку табличной части",
            hint="запись регистра меняется через документ-регистратор",
        )


def _поля_представления(описание: EntityDescription) -> list[str]:
    """Чем превью называет объект (Ruling 44): справочник — `Description` и `Code`, документ —
    `Number` и `Date` (те из них, что у сущности есть), запись регистра — поля ключа: своего
    наименования у неё нет, а ключ и есть то, что отличает её от соседних."""
    if "Register" in описание.kind:
        return list(описание.key_fields)
    есть = {поле["name"] for поле in описание.fields}
    return [имя for имя in _ПОЛЯ_ПРЕДСТАВЛЕНИЯ if имя in есть]


def _выбор_текущего(
    описание: EntityDescription, data: dict, op: Операция, представление: list[str]
) -> list[str]:
    """`$select` чтения текущего состояния: поля тела, отпечаток `DataVersion` (если он у
    сущности есть: у записей регистров его нет), для пометки удаления — `Posted`, чтобы
    предвидеть отказ 1С (решение 12 плана), и поля представления объекта (Ruling 44).
    Настоящая 1С `$select` соблюдает: чего здесь нет, того в `current` не будет вовсе.

    Сущность без `DataVersion` (запись регистра) читается всеми полями записи (Ruling 55): её
    отпечаток — хэш полей, и `commit` обязан перечитать ровно тот же набор. Набор «поля тела»
    `commit` не восстановит (в операции только изменённые поля), а «все поля записи» — по
    индексу; к тому же отпечаток по полям тела пропустил бы чужую правку соседнего ресурса."""
    if not _есть_версия(описание):
        return _все_поля_записи(описание)
    есть = {поле["name"] for поле in описание.fields}
    выбор = list(data)
    служебные = ("DataVersion", "Posted") if op == "mark_for_deletion" else ("DataVersion",)
    for имя in (*служебные, *представление):
        if имя in есть and имя not in выбор:
            выбор.append(имя)
    return выбор


def _предвидеть_отказ_пометки(текущее: dict, mark: bool) -> None:
    """Решение 12 плана, факт P8: пометку удаления проведённого документа 1С отклоняет 500. Отказ
    здесь, при подготовке, с подсказкой — а не 500 от 1С уже на `commit`, после того как
    пользователь подтвердил превью."""
    if mark and текущее.get("Posted") is True:
        raise _отказ(
            "документ проведён: 1С не ставит пометку удаления на проведённый документ",
            hint="сначала отмените проведение — odata1c_action(name='Unpost'), затем повторите "
            "пометку удаления",
        )


def _ключ_операции(реальный_ключ) -> dict:
    """Ключ для `PendingOp.key` и журнала: простой ключ — `{"Ref_Key": GUID}` без обёртки
    `guid'…'` (модель вправе прислать ключ в синтаксисе OData, П5), составной — как раскрыл гейт.
    Путь запроса строит не отсюда, а `build_get`: здесь только запись о том, что изменено."""
    if isinstance(реальный_ключ, dict):
        return dict(реальный_ключ)
    литерал = odata_literal("Edm.Guid", реальный_ключ, name="key")
    return {"Ref_Key": литерал[len("guid'") : -1]}


def _версия(значение, раскрытое: RevealedValues) -> str | None:
    """`DataVersion` текущего состояния — отпечаток для `commit` (P8: оптимистической блокировки у
    OData 1С нет, отпечаток — единственная защита). Строкой: `ScrubbedText` в операции означал бы
    строку раннего прохода, лежащую рядом с реальными значениями, — хранится исходная строка."""
    if значение is None:
        return None
    return str(_текущее_реальное(значение, раскрытое))


def _превью_операции(entity: str, op: str, key, объект: dict, строки: list[dict]) -> dict:
    """Превью в самой операции — для текста подтверждения в `commit` (elicitation, задача 7).
    Словарь, а не список строк ответа (`PendingOp.preview: dict`): туда же ложатся ключ и
    представление объекта (Ruling 44) и `summary` пометки удаления. «Было» и объект — из маски,
    «станет» и `key` — как прислала модель; страж по этому словарю ещё не проходил, поэтому текст
    подтверждения задача 7 обязана пропустить через гейт заново."""
    превью: dict = {"entity": entity, "op": op, "key": key, "object": объект, "changes": строки}
    if op == "mark_for_deletion":
        [строка] = строки
        превью["summary"] = (
            f"пометка удаления: {да_нет(строка['before'])} → {да_нет(строка['after'])}"
        )
    return превью


# -- create: табличные части и тело ------------------------------------------------------------


def _табличные_части_тела(
    описание: EntityDescription, data, describe: Callable[[str], EntityDescription | None]
) -> dict[str, EntityDescription]:
    """Табличные части из тела `create`: имя поля → описание сущности его строк.

    Сущность строки — `<владелец>_<поле>` среди детей владельца, тем же правилом, что у
    `ToolService._навигации` (табличная часть навигацией не приходит, проба P4), а не разбором
    `…_RowType` из типа `Collection(…)`: одно правило родства на чтение и запись.

    Поле-коллекция без сущности строки отклоняется здесь же, при разборе, — до разрешений строк
    и проверки тела (Н6r2-2 повторного ревью задачи 6). На полном УТ это `RecordSet` регистров
    (строки набора — `…_RecordType`, не ребёнок владельца): проверить строки нечем, разрешения
    строк не к чему применить. Поля и дети владельца — из одного снимка индекса, поэтому реиндекс
    этого не меняет, и подсказки «обновите индекс» здесь нет. Имя в тексте — поле владельца,
    найденное в индексе с типом `Collection(…)`, а не ввод модели (Ruling 53)."""
    if not isinstance(data, dict):
        return {}
    типы = {поле["name"]: поле["edm_type"] for поле in описание.fields}
    части: dict[str, EntityDescription] = {}
    for имя in data:
        if not isinstance(имя, str) or not типы.get(имя, "").startswith("Collection("):
            continue
        дочерняя = f"{описание.name}_{имя}"
        описание_строки = describe(дочерняя) if дочерняя in описание.children else None
        if описание_строки is None:
            raise _отказ(
                f"поле «{имя}» сущности «{описание.name}» — коллекция без своей сущности строки: "
                "табличные части этой сущности через create не задаются",
                hint=f"уберите «{имя}» из тела: у её строк нет своей сущности в $metadata базы"
                + (
                    "; набор записей регистра через create этой поставкой не записывается"
                    if описание.kind.endswith("Register")
                    else ""
                ),
            )
        части[имя] = описание_строки
    return части


def _проверить_права_строк(base_config, data: dict, части: dict, скрытые: frozenset[str]) -> None:
    """Разрешения строк табличных частей — те же шаги SPEC §7.1, что у шапки, но у сущности
    строки, и в том же порядке, что у `check_write`: скрытая табличная часть → `entity_hidden`
    (шаг 1), сущность строки в `deny_entities` → `permission_denied` (шаг 5, Н6-2 ревью задачи 6),
    поле строки из `deny_fields` → `field_write_denied` (шаг 6). Иначе запрет владельца на
    табличную часть обходился бы созданием объекта с её строками. Каждый шаг — по всем табличным
    частям тела, прежде следующего: первый сработавший шаг побеждает, как у шапки.

    Скрытость — по полному набору скрытых (`ToolService._скрытые`, Ruling 30): он содержит и
    потомков скрытого владельца, хотя до строк такой владелец не доходит — `_resolve_entity`
    отказал раньше. `allow_entities` к сущности строки не применяется: он перечисляет объекты, а
    не их табличные части (`check_entity_denied`)."""
    описания = list(части.items())
    for _, описание_строки in описания:
        if описание_строки.name in скрытые:
            raise WriteError(
                "entity_hidden", f"сущность «{описание_строки.name}» скрыта политикой гейта"
            )
    for _, описание_строки in описания:
        check_entity_denied(base_config, описание_строки.name)
    for имя, описание_строки in описания:
        строки = data[имя]
        if isinstance(строки, list):
            check_fields(
                base_config,
                описание_строки.name,
                (
                    поле
                    for строка in строки
                    if isinstance(строка, dict)
                    for поле in строка
                    if isinstance(поле, str)
                ),
            )


def _раскрыть_тело_create(
    гейт, описание: EntityDescription, data: dict, части: dict, *, строение, раскрытое
) -> dict:
    """Токены тела `create` → реальные значения по классам той сущности, чьё поле пишется
    (Ruling 56). Шапка — одним `inbound_write` от имени владельца, без табличных частей; каждая
    строка — своим `inbound_write` от имени сущности строки (`<владелец>_<табличная часть>`): её
    политика, лестница написаний по её полям и признак структурности (Ruling 43) — те же, по
    которым строку маскирует чтение. Раскрытие строк от владельца (путь `ТабличнаяЧасть/Поле`)
    брало бы класс по имени поля на владельце: токен `addr` уходил в поле строки, открытое по её
    сущности (Н6-1), а строки с корнем защищаемого имени в имени табличной части отклонялись
    правилом пути отбора (Н6-3).

    Нумерация токенов в отказе — общая на всё тело и по порядку тела (`number_tokens`, Ruling 54):
    номер не начинается заново в каждой строке. Место в отказе называет табличную часть и номер
    строки; гейту передаётся только номер (`row`), имя табличной части он выводит из сущности
    строки по индексу сам (Н6r2-1 повторного ревью задачи 6) — текста отсюда в отказ не идёт.

    Порядок в результате — порядок тела. Вызывается после проверки тела: у каждой табличной части
    есть сущность строки, строки — словари."""
    номера = number_tokens(data)
    шапка = {поле: значение for поле, значение in data.items() if поле not in части}
    реальная_шапка = гейт.inbound_write(
        шапка,
        entity=описание.name,
        shape=строение,
        current=None,
        revealed=раскрытое,
        numbering=номера,
    )
    реальное: dict = {}
    for поле, значение in data.items():
        if поле not in части:
            реальное[поле] = реальная_шапка[поле]
            continue
        реальное[поле] = [
            гейт.inbound_write(
                строка,
                entity=части[поле].name,
                shape=строение,
                current=None,
                revealed=раскрытое,
                numbering=номера,
                row=номер,
            )
            for номер, строка in enumerate(значение, start=1)
        ]
    return реальное


def _проверить_тело_create(описание: EntityDescription, data, части: dict) -> None:
    """Поля и типы тела `create` — по индексу, те же правила, что у `update` (`_поле_тела`,
    `_проверить_тип`): 1С молча принимает недопустимое (P8), превью обещало бы запись, которой не
    будет. Отличия от `update`: ключевые поля разрешены (запись регистра), табличная часть —
    список строк с проверкой по своей сущности, открытый литерал не проверяется (Ruling 47)."""
    if not isinstance(data, dict) or not data:
        raise _отказ(
            "тело записи пустое: передайте data словарём «поле: значение»",
            hint="поля сущности — odata1c_describe_entity",
        )
    if описание.is_tabular_part:
        # Строка табличной части — часть объекта-владельца (SPEC §7.3: одна операция — один
        # объект, табличные части внутри); отдельно от владельца 1С её не создаёт.
        имя_части = описание.name.removeprefix(f"{описание.parent_entity}_")
        raise _отказ(
            f"«{описание.name}» — табличная часть: её строки создаются вместе с "
            "объектом-владельцем",
            hint=f"передайте строки списком в поле «{имя_части}» тела create владельца "
            f"«{описание.parent_entity}»",
        )
    if описание.kind in _НЕ_СОЗДАЁТСЯ:
        # Предвидимый отказ 1С (дух решения 12 плана): такого объекта создать нельзя в принципе,
        # и узнавать это ответом 1С после подтверждения пользователя незачем.
        raise _отказ(
            f"«{описание.name}» не создаётся: {_НЕ_СОЗДАЁТСЯ[описание.kind]}",
            hint="создавайте объект, который туда попадает, — документ, справочник, запись "
            "регистра",
        )
    поля = {поле["name"]: поле for поле in описание.fields}
    for имя, значение in data.items():
        поле = _поле_тела(
            описание, поля, имя, запрещённые=_НЕ_ПИШЕТСЯ_В_CREATE, где="через create", ключ=False
        )
        тип = поле["edm_type"]
        if тип.startswith("Collection("):
            _проверить_строки(имя, значение, части[имя])
        else:
            _проверить_тип(имя, тип, значение)


def _проверить_строки(имя: str, строки, описание_строки: EntityDescription) -> None:
    """Строки одной табличной части `create`: список объектов, каждое поле — по сущности строки
    из индекса. Имя табличной части в текстах — поле владельца, уже найденное в индексе; части
    без сущности строки сюда не доходят (`_табличные_части_тела`)."""
    if not isinstance(строки, list):
        raise _отказ(
            f"табличная часть «{имя}» ожидает список строк",
            hint='передайте [{"поле": значение}, …] — по объекту на строку',
        )
    поля = {поле["name"]: поле for поле in описание_строки.fields}
    for строка in строки:
        if not isinstance(строка, dict):
            raise _отказ(f"строка табличной части «{имя}» должна быть объектом «поле: значение»")
        for имя_поля, значение in строка.items():
            поле = _поле_тела(
                описание_строки,
                поля,
                имя_поля,
                запрещённые=_НЕ_ПИШЕТСЯ_В_СТРОКУ,
                где="в строке табличной части",
                ключ=False,
            )
            тип = поле["edm_type"]
            if тип.startswith("Collection("):
                # В 1С табличных частей внутри строки не бывает; индекс, в котором такое есть,
                # описывает то, чего шлюз записать не умеет.
                raise _отказ(f"поле «{имя_поля}» строки — вложенная табличная часть")
            _проверить_тип(имя_поля, тип, значение)


