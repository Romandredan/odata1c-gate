@dataclass
class _Ход:
    """Докуда дошёл `commit` — от этого зависит, остаётся ли операция `pending`.

    `отправлено` — запрос к 1С начат (после записи журнала «до»): с этого момента повторять его
    нельзя при любом исходе. `устарело` — отпечаток не совпал: операция устарела навсегда. Не
    потому, что отпечаток не может совпасть снова (`DataVersion` назад не идёт, но хэш записи
    регистра вернётся, если значение вернули, Ruling 55), а потому, что превью строилось на
    состоянии, которое уже менялось, а переподготовка дешева. Прочие отказы (пользователь, лимит,
    сбой чтения, журнал) запрос не начинали — операцию можно подтвердить снова."""

    отправлено: bool = False
    выполнено: bool = False
    устарело: bool = False
    # Ответ повтору на случай отмены вызова после отправки — уже через стража базы (инвариант 1).
    страховка: str | None = None

    def итог(self) -> str | None:
        if self.выполнено:
            return "committed"
        if self.отправлено or self.устарело:
            return "failed"
        return None


