"""Сервис записи: подготовка pending-операций (SPEC §7.3; план M2, задачи 5–8).

Первая точка, где запись встречается с гейтом: реальные значения объекта 1С (текущее состояние и
тело PATCH) и превью для модели проходят через один вызов, и ошибка здесь сразу нарушает
инвариант 1. Отсюда устройство:

- **Всё — внутри `ToolService._run`.** Та же точка входа, что у тулов чтения: тот же гейт базы,
  тот же индекс, один набор раскрытого (`RevealedValues`) на вызов — его видят и ранний проход
  клиента 1С на GET, и `inbound_write`, и маскировщик превью, и страж в `gate.finish`. Отдельная
  точка входа для записи означала бы второй набор раскрытого и второй путь ошибок, а их
  расхождение с путём чтения — ровно та утечка, от которой `_run` защищает (любое исключение —
  текст ошибки через гейт, неожиданное — `internal` без текста).
- **Порядок вызовов гейта — контракт раунда блокеров M2** (раздел 1.1 отчёта): `inbound_key` →
  `client.get(scrub=…)` → `inbound_write(current=как пришло)` → маска сырого текущего один раз →
  `finish`. Маскированное обратно в `mask` не подаётся никогда: токен шлюза, пришедший в
  маскировщик как данные, считается строкой из базы и получает свой токен (`lit`, Б-2).
- **Подготовка не пишет в общий словарь гейта ничего, чего нет в 1С** (Ruling 45, находки C-1 и
  I-1 ревью задачи 5). Маскировщик выдаёт токен через `Dictionary.token_for`, а тот СОХРАНЯЕТ
  значение — в словарь, общий для всех баз и сессий домашнего каталога. Маска «было» — данные 1С,
  как у чтения. «Станет» — значения модели КАК ЕСТЬ (токен — токеном, литерал — литералом) и в
  маску не подаются: маска значения, которое придумала модель, до подтверждения делала бы чужое
  ядро названия неоднозначным (оно уходило открытым во всех ответах), давала номеру документа класс
  телефона (инвариант 6) и лишнее написание, ломающее следующую запись токеном. Словарь узнаёт новое
  значение только после `commit` — из повторного чтения объекта обычной маской (задача 7). Путь
  отказа тоже: эхо литерала модели в тексте отказа гейт маскирует токеном без записи (Ruling 48,
  `Masker.mask_text`).
- **До 1С — всё, что можно проверить без неё** (решение 3 контролёра): разрешения SPEC §7.1,
  открытый литерал в поле, которое на чтении принимает только токен (Ruling 45), поля и типы тела.
  Неверный запрос не трогает базу даже чтением. После GET остаются только проверки, которым нужно
  текущее состояние: разрешение токена по `current` (лестница 1.2), «изменений нет», предвидимый
  отказ 1С (решение 12 плана: пометка проведённого документа).

Инвариант 2: подготовка ничего не пишет в 1С — только GET текущего состояния. Тело PATCH с
реальными значениями живёт в `PendingOp.request` (память демона, решение 3 плана) до `commit`.

Задача 6 добавляет две подготовки рядом, а не внутри `_подготовить` (тот построен вокруг ключа,
текущего состояния и тела и остаётся путём `update`/`mark_for_deletion`):

- **`create`** не обращается к 1С вовсе — у нового объекта нет текущего состояния. Разрешения и
  проверки тела по индексу (табличные части — строками своей сущности) → `inbound_write` с
  `current=None`: шапка — от владельца, каждая строка — от своей сущности (Ruling 56) → превью:
  тело как прислала модель (Ruling 45), без единого вызова `mask`.
  Открытый литерал не отклоняется (Ruling 47): отказ `update` защищает ответ «изменений нет» от
  роли оракула, а у нового объекта сравнивать не с чем — продиктованное пользователем значение,
  в том числе контактная информация (Ruling 38), проходит.
- **`action`** — `Post`/`Unpost` (решение 6 плана, флаг `post_documents`): разрешения и имя
  действия по индексу до 1С, затем один GET текущего состояния; предвидимые отказы 1С (решение 12)
  — при подготовке; превью — объект маской текущего состояния (Ruling 44) и `Posted` до и после.
  Запрос — форма пробы P8: `POST Сущность(guid'…')/Post` без скобок, параметров и тела.

Задача 7 — **`commit`**, единственное место шлюза, где меняются данные 1С. Выполнение идёт тем
же `ToolService._run`, но набор раскрытого у него свой, а значения тела и ключа раскрыл вызов
подготовки: операция несёт перенос его написаний (`RevealedValues.carry`), и ранний проход
`commit` закрывает эхо раскрытого в ошибке и ответе 1С. Отпечаток (`DataVersion` или хэш полей
записи регистра, Ruling 55) сверяется перечитыванием — у OData 1С нет оптимистической блокировки
(P8). Журнал «до» — строго до запроса; после отправки операция не бывает `pending` ни при каком
исходе. Словарь пополняется только маской «после» выполненной записи (решение 13), текст ошибки
1С на уровне `identifiers+names` модели не отдаётся (Ruling 52), текст подтверждения — через
стража (`finish_text`).

Журнал синхронный и пишется прямо на цикле событий, не через `asyncio.to_thread` (решение 8
контролёра): соединение SQLite открыто без `check_same_thread=False` и в другом потоке упало бы
`ProgrammingError`; две короткие записи на `commit` за диалогом подтверждения и лимитом 20–50
коммитов в 10 минут цикл не задерживают заметно; и порядок «журнал «до» закончен — запрос начат»
без потока держится сам, без окна, где отмена задачи оставила бы запись в журнале без запроса или
наоборот. Так же синхронно работают словарь гейта и индекс.
"""

