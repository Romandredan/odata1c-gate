"""Построчная разница табличной части при замещении целиком (проект M3b §5.2; SPEC §7.3).

`odata1c_update` заменяет табличную часть целиком: модель присылает ВСЕ строки, которые должны
остаться (включая непереименованные), а не только изменённые. Строки сопоставляются по
`LineNumber` — номер проставлен раньше, до вызова этого модуля (правило §5.1, `service.py`):
строки без номера сюда не доходят ни в «было», ни в «станет».

Модуль не знает о гейте, о 1С и о словаре — та же граница, что у `preview.py`: чистая функция над
двумя списками словарей. Вызывающий (`WriteService`) решает, какие значения в них попадают —
реальные (для решения «изменилось ли») или уже показанные/маскированные (для превью пользователю);
`rows_diff` одинаково пригоден для обоих, ему всё равно, что лежит в полях.
"""

from __future__ import annotations

import dataclasses

ПОЛЕ_НОМЕРА_СТРОКИ = "LineNumber"


@dataclasses.dataclass(slots=True, frozen=True)
class RowsDiff:
    """Разница табличной части построчно.

    `changed` — строки, у которых нашёлся тот же номер в обоих списках и хотя бы одно поле «станет»
    отличается от «было»; сравниваются только поля, которые есть в «станет» (модель прислала —
    модель и сравнивает, как у полей шапки). `added` — номера только в «станет», `removed` —
    только в «было»; их поля показывают все поля строки, а не только изменившиеся, — строки в
    диффе не было, показывать нечего кроме содержимого целиком."""

    changed: list[dict]
    added: list[dict]
    removed: list[dict]
    before_count: int
    after_count: int


def ключ_строки(строка: dict) -> str:
    """Номер строки как ключ сопоставления — строкой, а не как он пришёл.

    1С отдаёт `LineNumber` то числом (свежепронумерованные строки — правило §5.1, `int`), то
    строкой в JSON текущего состояния (проба P9: реальный ответ отдаёт номер строки строкой) —
    без приведения к одному виду строка с тем же номером в разных представлениях не совпала бы
    вовсе, и вся табличная часть выглядела бы как «удалено всё, добавлено всё» при любом
    прикосновении к ней. Публичная (не `_`): та же нормализация нужна `service._раскрыть_тело` —
    сопоставить старую строку с новой по номеру ДО этого модуля, при раскрытии токенов."""
    return str(строка.get(ПОЛЕ_НОМЕРА_СТРОКИ))


def _номер(ключ: str) -> int | str:
    """Ключ сопоставления обратно в число для поля `line` результата — тест и вызывающий код
    сравнивают номера строк как числа, а не как их строковое представление."""
    try:
        return int(ключ)
    except ValueError:
        return ключ


def rows_diff(было: list[dict], станет: list[dict]) -> RowsDiff:
    """Разница по `LineNumber`. Строка без номера в любом списке не сопоставляется вовсе (только
    номерованные строки несут смысл «та же строка» — SPEC §7.3): без номера её нельзя было бы
    отличить от новой при следующем сравнении."""
    до = {
        ключ_строки(строка): строка
        for строка in было
        if isinstance(строка, dict) and ПОЛЕ_НОМЕРА_СТРОКИ in строка
    }
    после = {
        ключ_строки(строка): строка
        for строка in станет
        if isinstance(строка, dict) and ПОЛЕ_НОМЕРА_СТРОКИ in строка
    }
    ключи_до, ключи_после = set(до), set(после)

    changed: list[dict] = []
    for ключ in sorted(ключи_до & ключи_после, key=_номер):
        старая, новая = до[ключ], после[ключ]
        поля = [
            {"field": поле, "before": старая.get(поле), "after": значение}
            for поле, значение in новая.items()
            if поле != ПОЛЕ_НОМЕРА_СТРОКИ and старая.get(поле) != значение
        ]
        if поля:
            changed.append({"line": _номер(ключ), "fields": поля})

    added = [
        {
            "line": _номер(ключ),
            "fields": [
                {"field": поле, "value": значение}
                for поле, значение in после[ключ].items()
                if поле != ПОЛЕ_НОМЕРА_СТРОКИ
            ],
        }
        for ключ in sorted(ключи_после - ключи_до, key=_номер)
    ]
    removed = [
        {
            "line": _номер(ключ),
            "fields": [
                {"field": поле, "value": значение}
                for поле, значение in до[ключ].items()
                if поле != ПОЛЕ_НОМЕРА_СТРОКИ
            ],
        }
        for ключ in sorted(ключи_до - ключи_после, key=_номер)
    ]
    return RowsDiff(
        changed=changed,
        added=added,
        removed=removed,
        before_count=len(было),
        after_count=len(станет),
    )
