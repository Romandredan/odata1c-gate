"""Превью пишущих тулов (SPEC §7.3, шаг 3; план M2, задачи 5–6).

Превью — то, что пользователь подтверждает перед `odata1c_commit`, и оно целиком в токенах
(инвариант 1): реального значения защищаемого поля пользователь не видит ни в превью, ни в диалоге
подтверждения. Функции этого модуля получают значения УЖЕ после маски гейта и сами гейт не
вызывают — модуль ничего не знает о словаре, политике и 1С, поэтому ни открыть значение, ни
замаскировать его повторно (правило «маскировать один раз», раздел 1.5 отчёта блокеров M2) он не
может по построению.
"""

from __future__ import annotations

# Пометка строки превью, у которой «было» и «станет» — один и тот же токен. Один токен — одно
# значение (инвариант 5), но у значения бывают разные написания: ИНН с пробелом и без, название в
# «ёлочках» и в прямых кавычках. Пользователь, увидевший «X → X» без пометки, счёл бы строку
# ошибкой превью или отсутствием изменения, а 1С получит другую строку. Текст без самих написаний
# и без их числа — это метаданные о данных (M-1 ревью блокеров M2).
ПОМЕТКА_НАПИСАНИЯ = (
    "значение то же, меняется только написание (пробелы, регистр, кавычки): "
    "1С получит строку в новом написании"
)


def diff_preview(before_masked: dict, after_masked: dict) -> list[dict]:
    """[{"field", "before", "after"}] только по изменённым полям, значения — уже в токенах.

    Какие поля изменены, решает вызывающий (`WriteService`, шаг 6 задачи 5) на РЕАЛЬНЫХ
    значениях и передаёт сюда только их: равенство токенов не есть равенство значений — одно
    значение в двух написаниях получает один токен, а в 1С уйдёт другая строка. Поэтому здесь поле
    с одинаковыми «было» и «станет» не выбрасывается, а получает пометку `note`: выбросить его из
    превью, оставив в теле PATCH, значило бы показать пользователю не всё, что будет записано.

    Порядок строк — порядок ключей `after_masked` (тело записи в том порядке, в каком его прислала
    модель). Поле, которого нет в `before_masked` (1С не вернула его в текущем состоянии), идёт с
    `before: None`."""
    строки = []
    for поле, станет in after_masked.items():
        было = before_masked.get(поле)
        строка = {"field": поле, "before": было, "after": станет}
        if было == станет:
            строка["note"] = ПОМЕТКА_НАПИСАНИЯ
        строки.append(строка)
    return строки
