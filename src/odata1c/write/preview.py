"""Превью пишущих тулов (SPEC §7.3, шаг 3; план M2, задачи 5–6).

Превью — то, что пользователь подтверждает перед `odata1c_commit`. «Было» — текущее состояние
объекта из 1С, уже после маски гейта (инвариант 1): реального значения защищаемого поля
пользователь не видит. «Станет» — значения тела модели без маски (Ruling 45): токен — токеном;
маска значения модели записала бы его в общий словарь гейта до подтверждения. Литерал модели в
любом поле вызывающий заменяет пометкой «значение из запроса» (у поля с классом — «(класс …)») ещё
до этого модуля (Ruling 62, 63, `service._показ_значения`): тип и класс поля знают индекс и
политика, а сюда они не приходят. Числа, булевы и GUID идут как есть. Функции этого модуля гейт
не вызывают и ничего не знают о словаре, политике и 1С, поэтому ни открыть значение, ни
замаскировать его (повторно или впервые) не могут по построению.

Три формы по операциям: `update` — разница «было → станет» (`diff_preview`), `create` — тело в
показе вызывающего (`body_preview`: «было» у нового объекта нет, и строка `before: None` читалась
бы как «поле было пустым»), `action` — действие и признак проведения до и после (`action_preview`).

Четвёртая — `rows_preview` (проект M3b §5.2): табличная часть в теле `update` заменяется целиком, и
разница «было → станет» по одному значению поля здесь не подходит — нужна разница построчно по
`LineNumber` (`rows_diff.RowsDiff`, вычисляет вызывающий на уже показанных/маскированных строках).
"""

from __future__ import annotations

from odata1c.write.rows_diff import RowsDiff


def diff_preview(before_masked: dict, after_as_sent: dict) -> list[dict]:
    """[{"field", "before", "after"}] только по изменённым полям: `before` — маска текущего
    состояния, `after` — показ значения из тела модели (токен, пометка литерала, число).

    Какие поля изменены, решает вызывающий (`WriteService`, шаг 6 задачи 5) на РЕАЛЬНЫХ
    значениях и передаёт сюда только их. Поле с одинаковыми «было» и «станет» здесь не
    выбрасывается: равенство показанного не есть равенство записываемого (токен с
    несколькими написаниями показан тем же токеном, что «было», а 1С получит другое написание;
    литерал модели показан пометкой, Ruling 63) — выбросить строку из превью, оставив поле в теле
    PATCH, значило бы показать пользователю не всё, что будет записано.

    Порядок строк — порядок ключей `after_as_sent` (тело записи в том порядке, в каком его
    прислала модель). Поля, которого нет в `before_masked` (1С не вернула его в текущем
    состоянии), идёт с `before: None`."""
    return [
        {"field": поле, "before": before_masked.get(поле), "after": станет}
        for поле, станет in after_as_sent.items()
    ]


def body_preview(data_as_sent: dict) -> list[dict]:
    """[{"field", "value"}] — тело `create` в показе вызывающего (Ruling 45, 62, 63), в порядке
    ключей тела. Табличная часть — одной строкой превью со списком строк: строки проверены по
    полям своей сущности, но не маскируются — маска значения модели записала бы его в общий
    словарь до подтверждения, а данных 1С в новом объекте нет."""
    return [{"field": поле, "value": значение} for поле, значение in data_as_sent.items()]


def action_preview(name: str, объект: dict, posted_before, posted_after: bool) -> dict:
    """Превью действия документа (SPEC §7.3): объект (представление маской текущего состояния),
    имя действия и `Posted` до и после. `posted_before` — из маски текущего состояния (`None`, если
    1С поля не вернула), `posted_after` — чем станет признак, если 1С выполнит действие: `Post` →
    `True`, `Unpost` → `False` (P8: итог действия виден только перечитыванием, его делает
    `commit`)."""
    return {
        "object": объект,
        "action": name,
        "posted": {"before": posted_before, "after": posted_after},
    }


def rows_preview(имя: str, diff: RowsDiff) -> dict:
    """Строка превью `update` для табличной части, вместо `{"field", "before", "after"}` —
    `{"field", "rows", "summary"}`: одно значение поля разницу построчно не несёт. `rows` — тело
    `RowsDiff` как словарь (`changed`/`added`/`removed`/`before_count`/`after_count`), `summary` —
    короткая строка счёта для текста подтверждения, как у пометки удаления (`да_нет`)."""
    return {
        "field": имя,
        "rows": {
            "changed": diff.changed,
            "added": diff.added,
            "removed": diff.removed,
            "before_count": diff.before_count,
            "after_count": diff.after_count,
        },
        "summary": f"строк было {diff.before_count}, станет {diff.after_count}",
    }


def да_нет(значение) -> str:
    """Признак для строки итога (`summary`): «да» только для `True`; `None` (признака нет) и
    `False` — «нет», как 1С показывает непроведённый и непомеченный объект."""
    return "да" if значение is True else "нет"
