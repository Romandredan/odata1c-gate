def _скаляр(value: str) -> str:
    """YAML-представление одного значения решает библиотека, а не подстановка в строку-шаблон:
    кавычка, двоеточие, решётка или апостроф в значении (пароль, подпись, адрес, имя пользователя)
    иначе ломают разметку файла — и следующее чтение настроек падает с текстом самого значения
    (например, пароля) внутри сообщения об ошибке YAML."""
    строка = yaml.safe_dump({"значение": value}, allow_unicode=True, default_flow_style=False)
    return строка[len("значение: ") :].rstrip("\n")


def render_base(name: str, values: dict) -> str:
    write = values.get("write")
    write_line = (
        "    write: true                    # разрешить пишущие тулы"
        if write
        else "    # write: false                 # разрешить пишущие тулы"
    )
    return ШАБЛОН_ЗАПИСИ.format(
        name=name,
        label=_скаляр(values.get("label", name)),
        url=_скаляр(values["url"]),
        user=_скаляр(values.get("user", "")),
        password=_скаляр(values.get("password", "")),
        role=values.get("role", "prod"),
        write_line=write_line,
    )


def append_base(path: pathlib.Path, name: str, values: dict) -> None:
    """Дописать базу в конец файла bases.yaml, сохранив комментарии остального файла.

    Запись добавляется в конец файла, а не строго в конец раздела bases: если после этого
    раздела в файле стоит ещё один ключ верхнего уровня (например, default, дописанный туда
    вручную), новая запись окажется под этим ключом и файл перестанет разбираться. От этого
    класса ошибок не защититься само́й вставкой — вместо этого результат проверяется: файл
    читается заново и разбирается как YAML, и только если он разбирается и новая база в нём
    действительно появилась, изменение считается успешным. Иначе исходное содержимое
    восстанавливается и поднимается ConfigError — файл с учётными данными остаётся
    нетронутым, а не тихо портится.
    """
    исходный_текст = path.read_text(encoding="utf-8") if path.exists() else None
    текст = исходный_текст or ""
    if "bases:" not in текст:
        текст = (текст + "\n" if текст and not текст.endswith("\n") else текст) + "bases:\n"
    if not текст.endswith("\n"):
        текст += "\n"
    path.write_text(текст + "\n" + render_base(name, values), encoding="utf-8")

    испорчен = False
    try:
        данные = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(данные, dict) or name not in (данные.get("bases") or {}):
            испорчен = True
    except yaml.YAMLError:
        испорчен = True

    if испорчен:
        if исходный_текст is None:
            path.unlink()
        else:
            path.write_text(исходный_текст, encoding="utf-8")
        raise ConfigError(
            f"не удалось дописать базу «{name}» в {path}: файл оставлен нетронутым",
            hint="после раздела bases в файле стоит ещё один ключ верхнего уровня — "
            "перенесите его выше bases или допишите запись вручную",
        )


# Раунд правок 3, пункт 2 (находка Б.1 ревьюера): два РАЗНЫХ срока, которые прежний код смешивал
# в один. `ТАЙМАУТ_ЗАМКА_С` — сколько ждать своей очереди, прежде чем отказать команде;
# `ПРОТУХАНИЕ_ЗАМКА_С` — с какого возраста считать брошенным замок, в котором НЕ УДАЛОСЬ прочитать
# pid держателя (единственный случай, когда судим по времени, а не по владельцу). Пороги разведены
# осознанно: пока это был один срок, замок, брошенный ВО ВРЕМЯ ожидания, не снимался вовсе, а
# уравнивание «жду 10 с» и «протух за 10 с» на нагруженной машине выдавало бы живого, но медленного
# держателя за мёртвого.
ТАЙМАУТ_ЗАМКА_С = 10.0
ПРОТУХАНИЕ_ЗАМКА_С = 60.0

# Windows API для проверки «существует ли процесс с таким номером». `os.kill(pid, 0)` для этого
# не годится: на Windows CPython реализует `os.kill` через `TerminateProcess`, и сигнал 0 не
# проверка, а завершение процесса с кодом 0 — проверка живости убивала бы то, что проверяет.
_PROCESS_QUERY_LIMITED_INFORMATION = 0x1000
_STILL_ACTIVE = 259
_ERROR_ACCESS_DENIED = 5


def процесс_жив(pid: int) -> bool:
    """Существует ли в системе процесс с таким номером.

    Имя без подчёркивания: кроме замка этого модуля, тем же вопросом задаётся `daemon.stop()` —
    «сняли мы демон или только попытались» (ревью M1d, раунд 4, пункт 4). Механизм один и тот же,
    вместе с оговоркой про код выхода `259` ниже, и разводить две его копии незачем.

    Сомнение трактуется в пользу «жив»: не смогли выяснить (нет прав, API отказал) — считаем
    процесс живым и замок не снимаем. Ошибка в эту сторону стоит ожидания и понятного отказа,
    ошибка в другую — двух одновременных писателей `gate_secret` (инвариант 5 проекта: токены
    гейта детерминированы от секрета, расхождение секрета рвёт совпадение старых токенов с новыми).

    Известная неточность Windows: процесс, завершившийся с кодом ровно 259 (`STILL_ACTIVE`),
    неотличим от работающего. Это опять же сомнение в пользу «жив» — сам демон завершается кодами
    0 и 1, а последствие ошибки — ожидание, а не потеря секрета.
    """
    if pid <= 0:
        return False
    if os.name != "nt":
        try:
            os.kill(pid, 0)
        except ProcessLookupError:
            return False
        except OSError:
            # PermissionError — процесс есть, он чужой; прочие OSError — выяснить не удалось.
            return True
        return True

    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel32.OpenProcess.argtypes = (ctypes.c_uint32, ctypes.c_int, ctypes.c_uint32)
    kernel32.OpenProcess.restype = ctypes.c_void_p
    kernel32.GetExitCodeProcess.argtypes = (ctypes.c_void_p, ctypes.POINTER(ctypes.c_uint32))
    kernel32.GetExitCodeProcess.restype = ctypes.c_int
    kernel32.CloseHandle.argtypes = (ctypes.c_void_p,)
    kernel32.CloseHandle.restype = ctypes.c_int

    дескриптор = kernel32.OpenProcess(_PROCESS_QUERY_LIMITED_INFORMATION, 0, pid)
    if not дескриптор:
        # Процесса с таким номером нет (`ERROR_INVALID_PARAMETER`) — либо он есть, но чужой и
        # недоступен (`ERROR_ACCESS_DENIED`), и тогда он именно что жив.
        return ctypes.get_last_error() == _ERROR_ACCESS_DENIED
    try:
        код_выхода = ctypes.c_uint32()
        if not kernel32.GetExitCodeProcess(дескриптор, ctypes.byref(код_выхода)):
            return True
        return код_выхода.value == _STILL_ACTIVE
    finally:
        kernel32.CloseHandle(дескриптор)


def _владелец_замка(lock_path: pathlib.Path) -> int | None:
    """pid держателя из файла замка; `None` — файла нет, он пуст или содержит не число (замок
    прежней версии шлюза, куда pid не писался вовсе, либо авария между созданием файла и записью
    номера — окно в микросекунды)."""
    try:
        текст = lock_path.read_text(encoding="ascii").strip()
    except (OSError, UnicodeDecodeError):
        return None
    try:
        return int(текст)
    except ValueError:
        return None


def _замок_брошен(lock_path: pathlib.Path, протухание: float) -> bool:
    """Держатель замка мёртв — файл можно снимать.

    Решает ВЛАДЕЛЕЦ, а не возраст: замок брошен, если процесса с записанным в нём pid в системе
    нет. Возраст остаётся запасным правилом ровно для замка без читаемого pid — это либо файл,
    созданный прежней версией шлюза (она pid не писала), либо авария в микросекундном промежутке
    между `O_EXCL` и записью номера. Свежий замок без pid — почти наверняка держатель, который
    прямо сейчас записывает свой номер; трогать его нельзя.
    """
    pid = _владелец_замка(lock_path)
    if pid is None:
        try:
            возраст = time.time() - lock_path.stat().st_mtime
        except OSError:
            return False
        return возраст > протухание
    return not процесс_жив(pid)


def _снять_замок(lock_path: pathlib.Path) -> bool:
    """Убрать файл брошенного замка. `False` — снять не удалось, ждём дальше.

    На Windows отказ здесь — не сбой, а вторая линия защиты: держатель держит файл замка ОТКРЫТЫМ
    всё время, пока владеет им, а открытый через `os.open` файл ОС удалить не даёт
    (`PermissionError`, WinError 32). То есть живой замок на целевой ОС невозможно снять в принципе
    — даже если проверка владельца ошиблась.
    """
    try:
        lock_path.unlink()
    except FileNotFoundError:
        return True  # кто-то снял раньше нас — цель достигнута, можно бороться за `O_EXCL`
    except OSError:
        return False
    return True


@contextlib.contextmanager
def _межпроцессный_замок(
    lock_path: pathlib.Path,
    *,
    таймаут: float | None = None,
    интервал: float = 0.05,
    протухание: float | None = None,
):
    """Простой межпроцессный замок на файловой системе: `O_CREAT | O_EXCL` атомарен и на
    Windows, и на POSIX (в отличие от «проверить существование, потом создать» — та же болезнь
    TOCTOU, которую замок и лечит в `ensure_gate_secret`, раунд правок 2, находка Б.3).

    Дескриптор файла остаётся ОТКРЫТЫМ на всё время владения (закрывается в `finally` перед
    удалением файла) — это не небрежность, а сам механизм защиты: на Windows файл, открытый через
    `os.open`, другому процессу удалить нельзя, значит живой замок не снимет никто, как бы ни
    ошиблась проверка владельца. Прочитать номер держателя это не мешает — режим совместного
    доступа CRT запрещает только удаление и переименование.

    Замок брошенного держателя (процесс упал, не убрав файл) снимается по ВЛАДЕЛЬЦУ — см.
    `_замок_брошен`. Раунд правок 3, пункт 2: прежний код сравнивал `st_mtime` (шкала epoch) с
    `time.monotonic()` (время с загрузки системы), то есть условие снятия было ложно всегда и
    ветка снятия была мёртвым кодом — первый же брошенный замок выводил домашний каталог из строя
    навсегда, а починить его средствами шлюза было нечем. Чинить одной лишь шкалой времени нельзя:
    ожившее снятие по возрасту само стало бы гонкой (A снимает замок, который B уже перезахватил →
    два писателя `gate_secret` → расхождение секрета, инвариант 5).
    """
    таймаут = ТАЙМАУТ_ЗАМКА_С if таймаут is None else таймаут
    протухание = ПРОТУХАНИЕ_ЗАМКА_С if протухание is None else протухание
    предел = time.monotonic() + таймаут
    while True:
        try:
            fd = os.open(lock_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        except FileExistsError:
            if _замок_брошен(lock_path, протухание) and _снять_замок(lock_path):
                continue
            if time.monotonic() > предел:
                raise _замок_занят(lock_path, таймаут) from None
            time.sleep(интервал)
            continue
        break
    try:
        # Номер держателя пишется сразу после захвата: по нему ждущие процессы отличают живой
        # замок от брошенного. `os.write` — прямой системный вызов без буфера, значение видно
        # другому процессу немедленно.
        os.write(fd, str(os.getpid()).encode("ascii"))
        yield
    finally:
        os.close(fd)
        _освободить_замок(lock_path)


def _освободить_замок(lock_path: pathlib.Path, *, попыток: int = 50, пауза: float = 0.02) -> None:
    """Убрать СВОЙ файл замка, отпуская владение.

    Удаление повторяется, а не делается один раз: на Windows ждущий своей очереди процесс в этот
    самый миг может читать номер держателя, а файл, открытый для чтения обычными средствами
    (`_SH_DENYNO` в CRT), ОС удалить не даёт — `PermissionError`, WinError 32. Хендл читателя живёт
    микросекунды, поэтому следующая попытка проходит; а вот не убранный вовсе файл замка означал бы
    прямо обратное тому, ради чего замок заводился: держатель ушёл, а все следующие процессы ждут
    его до самого таймаута и получают отказ (воспроизведено на
    `tests/unit/test_writer_concurrency.py` — шесть одновременных процессов, из них один
    задерживался ровно на этом).
    """
    for _ in range(попыток):
        try:
            lock_path.unlink()
        except FileNotFoundError:
            return
        except OSError:
            time.sleep(пауза)
        else:
            return
    # Все попытки исчерпаны — файл остался на диске с номером ЖИВОГО процесса (нашим), и снять
    # его по владельцу теперь нельзя: следующие запуски на этом домашнем каталоге будут ждать
    # полный таймаут и получать отказ. Случай исчезающе редкий, но молчать о нём нельзя — иначе
    # причина отказа не восстанавливается вообще ничем.
    _log.warning(
        "не удалось убрать файл замка %s: он остался на диске, и следующий запуск шлюза будет "
        "ждать его полный таймаут — удалите файл, если ни один процесс шлюза не запущен",
        lock_path,
    )


def _замок_занят(lock_path: pathlib.Path, таймаут: float) -> ConfigError:
    """Отказ по замку — обычная ошибка настроек с кодом и подсказкой, а не голый `TimeoutError`.

    Раунд правок 3, пункт 2: `TimeoutError` не попадал в общий перехват `cli.main`, и команды
    `init` и `daemon` падали трассировкой стека. Код `config_invalid` — существующий код SPEC §5.2
    для отказа на локальных файлах настроек (`daemon.yaml`), нового кода этот отказ не заводит.
    Подсказка называет файл: `doctor` в командной строке ещё нет, и без имени файла каталог
    чинить нечем.
    """
    pid = _владелец_замка(lock_path)
    держатель = (
        f"его держит процесс {pid}" if pid is not None else "номер держателя в файле не записан"
    )
    return ConfigError(
        f"не удалось получить замок {lock_path} за {таймаут:.0f} с: {держатель}",
        hint=(
            f"замок нужен только на время записи gate_secret и живёт миллисекунды; если ни один "
            f"процесс шлюза сейчас не запущен, удалите файл {lock_path} вручную"
        ),
    )


def ensure_gate_secret(path: pathlib.Path) -> str:
    """Обеспечить непустой gate_secret в daemon.yaml: создать команда создания домашнего
    каталога (SPEC §6.3), не чтение настроек — см. odata1c.config.loader._load_daemon.

    Если секрет уже есть — вернуть его, не трогая файл (идемпотентность: повторный вызов
    ничего не меняет). Если файла нет или в нём нет секрета — дописать ровно одну строку
    через временный файл и os.replace, не трогая остальное содержимое (комментарии шаблона,
    ранее заданные параметры демона). После записи секрет читается заново с диска: если эту
    функцию вызвали одновременно два процесса, оба должны увидеть и вернуть то значение,
    которое реально осталось на диске, а не то, что каждый из них сам сгенерировал.

    Раунд правок 2, находка Б.3: первая проверка «секрет уже есть?» и запись — раздельные
    операции, между ними был зазор (TOCTOU), в который умещались два процесса, оба не видевшие
    чужого секрета и оба дописывавшие свой — `daemon.yaml` получал 2-3 строки `gate_secret`
    (YAML переживает дубликат ключа молча, «последний выигрывает»), а цена ошибки прямая:
    токены гейта детерминированы от секрета (инвариант 5), расхождение после следующего
    перезапуска демона рвёт совпадение старых токенов с новыми. Тот же временный файл
    (`daemon.yaml.tmp`, общее ИМЯ для всех процессов на этом доме) при этом мог одновременно
    писаться двумя процессами — `os.replace` одного натыкался на ещё не закрытый хендл другого
    (`WinError 32`), что и обрушивало сессию, а не только плодило лишние строки секрета
    (воспроизведено `rv_probe_two_launchers.py` ревьюера — сбой на третьей из трёх параллельных
    попыток).

    Вся критическая секция (повторная проверка + запись) теперь идёт под межпроцессным замком
    (`_межпроцессный_замок`, файл `daemon.yaml.lock` рядом) — единственный писатель побеждает
    гонку, остальные ждут своей очереди и, войдя в замок, видят уже записанный секрет на
    ПЕРВОЙ же (повторной) проверке и ничего не пишут.

    Замок, брошенный аварийно упавшим держателем, снимается по владельцу (раунд правок 3,
    пункт 2). Если снять его нельзя (держатель жив, но непривычно долго не отпускает) — отказ
    приходит обычной `ConfigError` с кодом и подсказкой, а не голым `TimeoutError`."""
    текущий = _прочитать_секрет(path)
    if текущий:
        return текущий

    with _межпроцессный_замок(path.with_name(path.name + ".lock")):
        # Конкурент мог успеть дописать секрет и снять замок, пока мы его ждали — перечитать
        # ПОД замком, а не доверять проверке снаружи (та и есть исходный TOCTOU).
        текущий = _прочитать_секрет(path)
        if текущий:
            return текущий

        секрет = base64.b64encode(secrets.token_bytes(32)).decode("ascii")
        текст = path.read_text(encoding="utf-8") if path.exists() else ""
        if текст and not текст.endswith("\n"):
            текст += "\n"
        текст += f'gate_secret: "{секрет}"\n'

        временный = path.with_name(path.name + f".tmp-{os.getpid()}")
        временный.write_text(текст, encoding="utf-8")
        os.replace(временный, path)
        if os.name != "nt":
            # На Windows chmod не управляет ACL — правами файла управляет NTFS, а не биты POSIX;
            # реальная защита закрывается на уровне всего домашнего каталога через icacls
            # в odata1c.config.home.ensure_home.
            path.chmod(0o600)

    return _прочитать_секрет(path) or секрет


LAUNCHER_KEY_FILE = "launcher.key"
_ДЛИНА_КЛЮЧА_ЛАУНЧЕРА = 32


def ensure_launcher_key(home: pathlib.Path) -> bytes:
    """Ключ лаунчера (Ruling 59): 32 случайных байта в `launcher.key` домашнего каталога. Им
    лаунчер подписывает заголовки своего клиента, а демон по подписи отличает настоящий лаунчер
    от любого локального процесса, назвавшегося Claude Code (`daemon.client_signature`).

    Отдельный файл, а не строка `daemon.yaml` и не `gate_secret`: назначения не смешиваются (смена
    ключа лаунчера не должна менять токены гейта, инвариант 5), а `daemon.yaml` владелец правит
    руками. Файл — ровно 32 байта без разметки: читать нечего, кроме длины, и повреждённый файл
    отличается от целого одной проверкой.

    Создаётся лаунчером при запуске и командой `odata1c init`, если его нет или он повреждён
    (длина не 32), — тем же порядком, что `gate_secret`: межпроцессный замок, повторная проверка
    под ним, запись через временный файл и `os.replace` (два лаунчера на первом запуске не
    получат разных ключей). Права — как у `daemon.yaml`: на Windows ACL наследуется от домашнего
    каталога (`ensure_home`, `icacls`), в остальных ОС — `0600`."""
    текущий = read_launcher_key(home)
    if текущий is not None:
        return текущий
    путь = home / LAUNCHER_KEY_FILE
    try:
        with _межпроцессный_замок(путь.with_name(путь.name + ".lock")):
            текущий = read_launcher_key(home)
            if текущий is not None:
                return текущий
            временный = путь.with_name(путь.name + f".tmp-{os.getpid()}")
            временный.write_bytes(secrets.token_bytes(_ДЛИНА_КЛЮЧА_ЛАУНЧЕРА))
            if os.name != "nt":
                временный.chmod(0o600)
            os.replace(временный, путь)
    except OSError as ошибка:
        raise _ключ_не_создан(
            home, f"нет прав на запись или диск недоступен ({type(ошибка).__name__})"
        ) from None
    except ConfigError:
        # Замок создания занят живым процессом дольше таймаута (`_замок_занят`): его текст
        # называет файл замка и говорит о `gate_secret` — здесь это не та подсказка.
        raise _ключ_не_создан(
            home,
            "замок создания ключа занят другим процессом шлюза; если ни один процесс шлюза не "
            "запущен, удалите в этом каталоге файл замка ключа лаунчера (оканчивается на .lock)",
        ) from None
    ключ = read_launcher_key(home)
    if ключ is None:  # файл заменили между записью и чтением — не молчать, это не штатно
        raise _ключ_не_создан(home, "ключ не читается сразу после создания")
    return ключ


def _ключ_не_создан(home: pathlib.Path, причина: str) -> ConfigError:
    """Отказ создать ключ лаунчера (вопрос 6 ревью Ruling 59). Лаунчер без ключа не стартует, и в
    Claude Code это видно как «сломался MCP-сервер» — поэтому текст называет причину, каталог и
    починку. Путь домашнего каталога — не данные 1С, его называть можно; имени файла ключа и
    ключа в тексте нет (Ruling 59, п. 5), текст исходного `OSError` с путём файла не цепляется."""
    return ConfigError(
        f"не удалось создать ключ лаунчера в домашнем каталоге {home}: {причина}",
        code="config_invalid",
        hint=(
            f"проверьте, что текущий пользователь может писать в {home} (права на каталог), и "
            f"выполните `odata1c init --home {home}`; без ключа лаунчер не запускается"
        ),
    )


def read_launcher_key(home: pathlib.Path) -> bytes | None:
    """Ключ лаунчера или `None`, если файла нет, он не читается или длина не 32 байта. Демон и
    лаунчер читают его один раз, при старте: смена ключа — перезапуск."""
    try:
        данные = (home / LAUNCHER_KEY_FILE).read_bytes()
    except OSError:
        return None
    return данные if len(данные) == _ДЛИНА_КЛЮЧА_ЛАУНЧЕРА else None


def _прочитать_секрет(path: pathlib.Path) -> str | None:
    if not path.exists():
        return None
    текст = path.read_text(encoding="utf-8")
    if not текст.strip():
        return None
    try:
        данные = yaml.safe_load(текст)
    except yaml.YAMLError:
        return None
    if isinstance(данные, dict):
        return данные.get("gate_secret") or None
    return None
