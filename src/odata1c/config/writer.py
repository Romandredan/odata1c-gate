# Общее для `cmd_init` и лаунчера (`odata1c mcp` на чистой машине — SPEC §2.1 п. 1, план M1d,
# задача 6, раунд правок 1, находка 3а): оба должны уметь досоздать то, чего не хватает домашнему
# каталогу, одним и тем же способом.
ШАБЛОНЫ = {"bases.yaml": "bases.example.yaml", "daemon.yaml": "daemon.example.yaml"}


def ensure_templates(home: pathlib.Path) -> None:
    """Скопировать шаблоны настроек, которых ещё нет — идемпотентно, существующие файлы не
    трогает. Не пишет в лог и не печатает — вызывающий код (`cmd_init`, `run_launcher`) сам
    решает, что и куда сообщать."""
    for имя_файла, имя_шаблона in ШАБЛОНЫ.items():
        назначение = home / имя_файла
        if назначение.exists():
            continue
        шаблон = importlib.resources.files("odata1c.templates").joinpath(имя_шаблона)
        назначение.write_text(шаблон.read_text(encoding="utf-8"), encoding="utf-8")
        закрыть_права_файла(назначение)


def закрыть_права_файла(path: pathlib.Path) -> None:
    """Оставить файлу права только владельца (`0600`) — в остальных ОС, кроме Windows.

    Зачем: `bases.yaml` хранит пароли 1С открытым текстом (SPEC §2.3), а новый файл получает права
    по умолчанию из `umask` — на обычной Linux-машине это `0644`, то есть «читают все». Домашний
    каталог закрыт (`ensure_home` → `0700`), но проверка прав (`check_file_permissions`) смотрит на
    сам файл и предупреждает владельца именно о нём.

    На Windows `chmod` правами не управляет — там доступ задают списки ACL самого NTFS, и закрывает
    их `icacls` на весь домашний каталог (`odata1c.config.home.ensure_home`)."""
    if os.name != "nt":
        path.chmod(0o600)


def ensure_policy_template(home: pathlib.Path, base_name: str) -> bool:
    """Файл владельца `bases/<база>/policy.yaml` из шаблона (ADR-0015, план 2026-09-13, задача 3);
    существующий не трогает никогда — ни при повторном вызове, ни при реиндексе. `True` — файл
    создан этим вызовом, `False` — уже был.

    Отдельная функция, а не запись в `ШАБЛОНЫ` (`ensure_templates`): та копирует шаблоны домашнего
    каталога по фиксированному имени, а здесь путь зависит от имени базы (`base_dir`) и каталога
    базы может ещё не быть — создаём его сами. Плейсхолдер `{{base}}` шаблона заменяется именем
    базы, чтобы шапка файла (`odata1c policy show <база>` и т. п.) называла настоящую команду, а
    не образец."""
    назначение = base_dir(home, base_name) / "policy.yaml"
    if назначение.exists():
        return False
    назначение.parent.mkdir(parents=True, exist_ok=True)
    шаблон = importlib.resources.files("odata1c.templates").joinpath("policy.example.yaml")
    назначение.write_text(
        шаблон.read_text(encoding="utf-8").replace("{{base}}", base_name), encoding="utf-8"
    )
    return True


