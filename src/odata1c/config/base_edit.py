class _МногострочноеЗначение(Exception):
    """Значение в кавычках не закрыто в своей строке: скаляр перенесён на следующие строки (так
    писала подпись прежняя версия `base add`, пока `_скаляр` ограничивал ширину строки). Правка
    одной строки оставила бы хвост с кавычкой; текст ошибки без значения строится выше, там, где
    известно имя базы (`set_base_fields`)."""


def _разделить(rest: str) -> tuple[str, str | None]:
    """`rest` — всё после двоеточия строки записи: значение и, возможно, комментарий справа.
    Кавычки учитываются: `#` внутри `'…'` или `"…"` — часть значения (подпись `УТ #1`, которую
    `_скаляр` заключил в кавычки), а не начало комментария. В двойных кавычках обратная косая черта
    экранирует следующий символ целиком: после пары косых черт кавычка закрывает значение, а
    после одиночной — нет. Не закрытая в этой строке кавычка — `_МногострочноеЗначение`."""
    s = rest.strip()
    if not s:
        return "", None
    if s[0] in "'\"":
        кавычка, i, закрыта = s[0], 1, False
        while i < len(s):
            c = s[i]
            if кавычка == '"' and c == "\\":
                i += 2
                continue
            if c == кавычка:
                if кавычка == "'" and s[i + 1 : i + 2] == "'":
                    i += 2
                    continue
                закрыта = True
                break
            i += 1
        if not закрыта:
            raise _МногострочноеЗначение
        значение, хвост = s[: i + 1], s[i + 1 :].strip()
    else:
        m = re.search(r"\s#", s)
        значение, хвост = (s[: m.start()].rstrip(), s[m.start() :].strip()) if m else (s, "")
    комментарий = хвост[1:].strip() if хвост.startswith("#") else None
    return значение, комментарий


def _собрать(код: str, комментарий: str | None) -> str:
    return _с_комментарием(код, комментарий) if комментарий else код


def _разобрать_строку(строка: str, номер: int) -> re.Match:
    m = _КЛЮЧ_RE.match(строка)
    if m is None:
        # Без текста строки: в ней может быть значение поля.
        raise ConfigError(f"строка {номер + 1} записи базы не разбирается — поправьте файл вручную")
    return m


def _код(отступ: int, ключ: str, текст_значения: str) -> str:
    return " " * отступ + (f"{ключ}: {текст_значения}" if текст_значения else f"{ключ}:")


def _переписать_значение(строка: str, текст_значения: str, номер: int = 0) -> str:
    """Та же строка с новым значением: отступ, решётка образца (если была), ключ и комментарий
    справа сохраняются. Для активной строки — правка по месту, для образца — перерисовка умолчания
    (смена роли, задача 6)."""
    m = _разобрать_строку(строка, номер)
    _, комментарий = _разделить(m.group("rest"))
    код = (
        m.group("indent")
        + (m.group("comm") or "")
        + (f"{m.group('key')}: {текст_значения}" if текст_значения else f"{m.group('key')}:")
    )
    return _собрать(код, комментарий)


def _активировать(
    строка: str, текст_значения: str | None = None, номер: int = 0, отступ: int | None = None
) -> str:
    """Образец становится действующей строкой: решётка снимается, комментарий справа остаётся.
    `текст_значения=None` — значение образца сохраняется (так активируется родитель `# gate:`).

    `отступ` — колонка, на которую встаёт ключ: её определяет место поля в записи (поле записи —
    колонка записи, вложенное — колонка детей родителя), а не число пробелов после решётки образца
    (`#   mode: x` с тремя пробелами правит владелец вручную, и отступ вышел бы другим). Без
    `отступ` — прежнее правило: отступ решётки плюс её хвост без двух символов `# `."""
    m = _разобрать_строку(строка, номер)
    текущее, комментарий = _разделить(m.group("rest"))
    if отступ is None:
        comm = m.group("comm") or ""
        отступ = len(m.group("indent")) + max(len(comm) - 2, 0)
    return _собрать(
        _код(отступ, m.group("key"), текущее if текст_значения is None else текст_значения),
        комментарий,
    )


def _закомментировать(строка: str, номер: int = 0) -> str:
    """Активная строка родителя (`    gate:`) снова становится образцом (`    # gate:`)."""
    m = _разобрать_строку(строка, номер)
    return m.group("indent") + "# " + строка[len(m.group("indent")) :]


def _найти_образец(
    строки: list[str], з: _Запись, поле: str, диапазон: tuple[int, int] | None = None
) -> int | None:
    """Закомментированная строка ключа внутри записи с решёткой в колонке записи. Имена ключей не
    пересекаются между уровнями (`mode` только у `gate`, флаги только у `permissions`), поэтому
    вложенность по отступу после решётки не проверяется. `диапазон` (от, до) сужает поиск: при
    активном родителе образец ребёнка берётся только из блока родителя — образец выше или ниже
    блока при активации оказался бы вне раздела."""
    ключ = поле.rsplit(".", 1)[-1]
    от, до = диапазон if диапазон else (з.начало + 1, з.конец)
    for n in range(от, до):
        m = _КЛЮЧ_RE.match(строки[n])
        if m and m.group("comm") and m.group("key") == ключ and len(m.group("indent")) == з.отступ:
            return n
    return None


def _блок_родителя(строки: list[str], з: _Запись, родитель: str) -> tuple[int, int]:
    """Строки раздела `gate` / `permissions`: от строки после ключа раздела до первой активной
    строки на колонке записи (следующий ключ записи) или до конца записи. Комментарии между ними —
    часть блока."""
    от = з.родители[родитель] + 1
    for n in range(от, min(з.конец, len(строки))):
        m = _КЛЮЧ_RE.match(строки[n])
        if m and not m.group("comm") and len(m.group("indent")) <= з.отступ:
            return от, n
    return от, min(з.конец, len(строки))


def _отступ_детей(строки: list[str], з: _Запись, родитель: str) -> int:
    """Колонка, на которой стоят дети активного раздела (у `base add` — на два пробела глубже
    записи; у рукописного файла может быть иной отступ, и новая строка должна встать вровень)."""
    for поле, n in з.активные.items():
        if поле.startswith(родитель + "."):
            return len(строки[n]) - len(строки[n].lstrip(" "))
    return з.отступ + 2


def _место_вставки(з: _Запись) -> int:
    """Куда вставить поле, которого нет ни строкой, ни образцом: после `role`, если он есть, иначе
    после последней из строк `label`, `url`, `user`, `password` (в файле, который писали руками,
    их порядок любой — первая по приоритету могла бы оказаться выше остальных)."""
    главный, прочие = _ПОСЛЕ_КАКИХ[0], _ПОСЛЕ_КАКИХ[1:]
    if главный in з.активные:
        return з.активные[главный] + 1
    номера = [з.активные[ключ] for ключ in прочие if ключ in з.активные]
    return max(номера) + 1 if номера else з.начало + 1


def _установить(строки: list[str], з: _Запись, *, поле: str, текст: str) -> None:
    """Одно правило на все поля (проект §3.2, п. 4–5): активная строка переписывается; образец
    раскомментируется; нет ни того ни другого — вставка после `role`. Вложенное поле сначала
    активирует родителя; прочие дети родителя остаются образцами.

    Колонка новой строки зависит от структуры, а не от текста образца: поле записи — колонка
    записи; ребёнок активного раздела — колонка его прежних детей; ребёнок раздела, который
    активируется сейчас, — на два пробела глубже записи."""
    if поле in з.активные:
        n = з.активные[поле]
        строки[n] = _переписать_значение(строки[n], текст, n)
        return
    родитель = поле.split(".")[0] if "." in поле else None
    раздел_активен = родитель is not None and родитель in з.родители
    if родитель is None:
        отступ = з.отступ
    elif раздел_активен:
        отступ = _отступ_детей(строки, з, родитель)
    else:
        отступ = з.отступ + 2
    диапазон = _блок_родителя(строки, з, родитель) if раздел_активен else None
    n = _найти_образец(строки, з, поле, диапазон)
    if n is not None:
        строки[n] = _активировать(строки[n], текст, n, отступ)
        if родитель and not раздел_активен:
            p = _найти_образец(строки, з, родитель)
            if p is not None and p < n:
                строки[p] = _активировать(строки[p], None, p, з.отступ)
            else:
                строки.insert(n, " " * з.отступ + f"{родитель}:")
        return
    новая = строка_записи(отступ - (2 if родитель else 0), поле, текст, активна=True)
    if родитель is None:
        строки.insert(_место_вставки(з), новая)
        return
    if раздел_активен:
        строки.insert(з.родители[родитель] + 1, новая)
        return
    p = _найти_образец(строки, з, родитель)
    if p is not None:
        строки[p] = _активировать(строки[p], None, p, з.отступ)
        строки.insert(p + 1, новая)
        return
    место = _место_вставки(з)
    строки[место:место] = [" " * з.отступ + f"{родитель}:", новая]


# --- значения -------------------------------------------------------------------------------


def _умолчание_роли(роль: str, поле: str) -> object:
    узел: object = УМОЛЧАНИЯ_РОЛЕЙ[роль]
    for часть in поле.split("."):
        узел = узел[часть]
    return узел


def _текст_значения(поле: str, значение: object) -> str:
    """YAML-текст значения для строки записи. Подпись идёт через `_скаляр` (кавычки, если в ней
    `#`, двоеточие или апостроф); `role` и `gate.mode` — слова без кавычек, как пишет `base add`
    (`mode: off` без кавычек — форма документации, модель принимает `false` как `off`)."""
    if isinstance(значение, bool):
        return "true" if значение else "false"
    if isinstance(значение, int):
        return str(значение)
    return _скаляр(str(значение)) if поле == "label" else str(значение)


def _значение(данные: dict, поле: str) -> tuple[object, str]:
    """Значение поля записи и его источник: `явно` / `по роли <роль>`; у `label` источника нет."""
    роль = данные.get("role", "prod")
    if поле == "label":
        return данные.get("label", ""), ""
    if поле == "role":
        return роль, "явно" if "role" in данные else "по умолчанию"
    узел: object = данные
    for часть in поле.split("."):
        if not isinstance(узел, dict) or часть not in узел:
            return _умолчание_роли(роль, поле), f"по роли {роль}"
        узел = узел[часть]
    if поле == "gate.mode" and узел is False:
        узел = "off"
    return узел, "явно"


def _действующие(данные: dict) -> dict:
    итог = apply_role(данные.get("role", "prod"), данные)
    гейт = итог["gate"]["mode"]
    return {
        "role": итог["role"],
        "gate": "off" if гейт is False else гейт,
        "write": итог["write"],
        "permissions": {
            флаг: итог["permissions"][флаг]
            for флаг in (
                "post_documents",
                "mark_deletion",
                "independent_register_delete",
                "commit_limit",
            )
        },
    }


