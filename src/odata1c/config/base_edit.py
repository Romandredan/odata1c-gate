def _снять_поле(строки: list[str], з: _Запись, *, поле: str, роль: str) -> None:
    """Активная строка поля становится образцом с умолчанием роли и стандартным комментарием —
    той же строкой, которую пишет `render_base`, поэтому `gate off` и следом `default` возвращают
    файл к исходному. Родитель без активных детей тоже становится образцом: `gate:` без детей —
    пустой ключ (`null`), загрузка такую запись отклонила бы."""
    if поле not in з.активные:
        return
    строки[з.активные[поле]] = строка_записи(
        з.отступ, поле, _текст_значения(поле, _умолчание_роли(роль, поле)), активна=False
    )
    if "." not in поле:
        return
    родитель = поле.split(".")[0]
    if any(к.startswith(родитель + ".") and к != поле for к in з.активные):
        return
    p = з.родители[родитель]
    строки[p] = _закомментировать(строки[p], p)


def _снять(текст: str, name: str, поле: str) -> str:
    """`--<ключ> default`: явное поле снимается, действует умолчание роли (проект §3.2, п. 6)."""
    роль = yaml.safe_load(текст)["bases"][name].get("role", "prod")
    return _правка(текст, name, functools.partial(_снять_поле, поле=поле, роль=роль))


