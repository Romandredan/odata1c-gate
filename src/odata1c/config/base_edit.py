# --- строки записи -------------------------------------------------------------------------


def _разделить(rest: str) -> tuple[str, str | None]:
    """`rest` — всё после двоеточия строки записи: значение и, возможно, комментарий справа.
    Кавычки учитываются: `#` внутри `'…'` или `"…"` — часть значения (подпись `УТ #1`, которую
    `_скаляр` заключил в кавычки), а не начало комментария."""
    s = rest.strip()
    if not s:
        return "", None
    if s[0] in "'\"":
        кавычка, i = s[0], 1
        while i < len(s):
            if s[i] == кавычка:
                if кавычка == "'" and s[i + 1 : i + 2] == "'":
                    i += 2
                    continue
                if кавычка == '"' and s[i - 1] == "\\":
                    i += 1
                    continue
                break
            i += 1
        значение, хвост = s[: i + 1], s[i + 1 :].strip()
    else:
        m = re.search(r"\s#", s)
        значение, хвост = (s[: m.start()].rstrip(), s[m.start() :].strip()) if m else (s, "")
    комментарий = хвост[1:].strip() if хвост.startswith("#") else None
    return значение, комментарий


def _собрать(код: str, комментарий: str | None) -> str:
    return _с_комментарием(код, комментарий) if комментарий else код


def _разобрать_строку(строка: str, номер: int) -> re.Match:
    m = _КЛЮЧ_RE.match(строка)
    if m is None:
        # Без текста строки: в ней может быть значение поля.
        raise ConfigError(f"строка {номер + 1} записи базы не разбирается — поправьте файл вручную")
    return m


def _код(отступ: int, ключ: str, текст_значения: str) -> str:
    return " " * отступ + (f"{ключ}: {текст_значения}" if текст_значения else f"{ключ}:")


def _переписать_значение(строка: str, текст_значения: str, номер: int = 0) -> str:
    """Та же строка с новым значением: отступ, решётка образца (если была), ключ и комментарий
    справа сохраняются. Для активной строки — правка по месту, для образца — перерисовка умолчания
    (смена роли, задача 6)."""
    m = _разобрать_строку(строка, номер)
    _, комментарий = _разделить(m.group("rest"))
    код = (
        m.group("indent")
        + (m.group("comm") or "")
        + (f"{m.group('key')}: {текст_значения}" if текст_значения else f"{m.group('key')}:")
    )
    return _собрать(код, комментарий)


def _активировать(строка: str, текст_значения: str | None = None, номер: int = 0) -> str:
    """Образец становится действующей строкой: решётка снимается, вложенный ключ встаёт на два
    пробела глубже колонки записи (`    #   mode: x` → `      mode: x`), комментарий справа
    остаётся. `текст_значения=None` — значение образца сохраняется (так активируется родитель
    `# gate:`)."""
    m = _разобрать_строку(строка, номер)
    текущее, комментарий = _разделить(m.group("rest"))
    comm = m.group("comm") or ""
    отступ = len(m.group("indent")) + max(len(comm) - 2, 0)
    return _собрать(
        _код(отступ, m.group("key"), текущее if текст_значения is None else текст_значения),
        комментарий,
    )


def _закомментировать(строка: str, номер: int = 0) -> str:
    """Активная строка родителя (`    gate:`) снова становится образцом (`    # gate:`)."""
    m = _разобрать_строку(строка, номер)
    return m.group("indent") + "# " + строка[len(m.group("indent")) :]


def _найти_образец(строки: list[str], з: _Запись, поле: str) -> int | None:
    """Закомментированная строка ключа внутри записи с решёткой в колонке записи. Имена ключей не
    пересекаются между уровнями (`mode` только у `gate`, флаги только у `permissions`), поэтому
    вложенность по отступу после решётки не проверяется."""
    ключ = поле.rsplit(".", 1)[-1]
    for n in range(з.начало + 1, з.конец):
        m = _КЛЮЧ_RE.match(строки[n])
        if m and m.group("comm") and m.group("key") == ключ and len(m.group("indent")) == з.отступ:
            return n
    return None


def _место_вставки(з: _Запись) -> int:
    for ключ in _ПОСЛЕ_КАКИХ:
        if ключ in з.активные:
            return з.активные[ключ] + 1
    return з.начало + 1


def _установить(строки: list[str], з: _Запись, *, поле: str, текст: str) -> None:
    """Одно правило на все поля (проект §3.2, п. 4–5): активная строка переписывается; образец
    раскомментируется; нет ни того ни другого — вставка после `role`. Вложенное поле сначала
    активирует родителя; прочие дети родителя остаются образцами."""
    if поле in з.активные:
        n = з.активные[поле]
        строки[n] = _переписать_значение(строки[n], текст, n)
        return
    родитель = поле.split(".")[0] if "." in поле else None
    n = _найти_образец(строки, з, поле)
    if n is not None:
        строки[n] = _активировать(строки[n], текст, n)
        if родитель and родитель not in з.родители:
            p = _найти_образец(строки, з, родитель)
            if p is not None and p < n:
                строки[p] = _активировать(строки[p], None, p)
            else:
                строки.insert(n, " " * з.отступ + f"{родитель}:")
        return
    новая = строка_записи(з.отступ, поле, текст, активна=True)
    if родитель is None:
        строки.insert(_место_вставки(з), новая)
        return
    if родитель in з.родители:
        строки.insert(з.родители[родитель] + 1, новая)
        return
    p = _найти_образец(строки, з, родитель)
    if p is not None:
        строки[p] = _активировать(строки[p], None, p)
        строки.insert(p + 1, новая)
        return
    место = _место_вставки(з)
    строки[место:место] = [" " * з.отступ + f"{родитель}:", новая]


# --- значения -------------------------------------------------------------------------------


def _умолчание_роли(роль: str, поле: str) -> object:
    узел: object = УМОЛЧАНИЯ_РОЛЕЙ[роль]
    for часть in поле.split("."):
        узел = узел[часть]
    return узел


def _текст_значения(поле: str, значение: object) -> str:
    """YAML-текст значения для строки записи. Подпись идёт через `_скаляр` (кавычки, если в ней
    `#`, двоеточие или апостроф); `role` и `gate.mode` — слова без кавычек, как пишет `base add`
    (`mode: off` без кавычек — форма документации, модель принимает `false` как `off`)."""
    if isinstance(значение, bool):
        return "true" if значение else "false"
    if isinstance(значение, int):
        return str(значение)
    return _скаляр(str(значение)) if поле == "label" else str(значение)


def _значение(данные: dict, поле: str) -> tuple[object, str]:
    """Значение поля записи и его источник: `явно` / `по роли <роль>`; у `label` источника нет."""
    роль = данные.get("role", "prod")
    if поле == "label":
        return данные.get("label", ""), ""
    if поле == "role":
        return роль, "явно" if "role" in данные else "по умолчанию"
    узел: object = данные
    for часть in поле.split("."):
        if not isinstance(узел, dict) or часть not in узел:
            return _умолчание_роли(роль, поле), f"по роли {роль}"
        узел = узел[часть]
    if поле == "gate.mode" and узел is False:
        узел = "off"
    return узел, "явно"


def _действующие(данные: dict) -> dict:
    итог = apply_role(данные.get("role", "prod"), данные)
    гейт = итог["gate"]["mode"]
    return {
        "role": итог["role"],
        "gate": "off" if гейт is False else гейт,
        "write": итог["write"],
        "permissions": {
            флаг: итог["permissions"][флаг]
            for флаг in (
                "post_documents",
                "mark_deletion",
                "independent_register_delete",
                "commit_limit",
            )
        },
    }


