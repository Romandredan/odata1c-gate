def _уже_так(данные: dict, поле: str, значение: object) -> bool:
    """Поле записи уже стоит так, как запрошено: то же значение и тот же источник (для установки —
    `явно`, для `default` — уже `по роли …`). Такое поле не переписывается: правка строки
    выровняла бы комментарий владельца по колонке 45 и не изменила бы ни одного значения."""
    было, источник = _значение(данные, поле)
    if значение is ПО_РОЛИ:
        return источник.startswith("по роли")
    if поле == "label":
        return "label" in данные and было == значение
    return источник == "явно" and type(было) is type(значение) and было == значение


def _заменить(
    временный: pathlib.Path, path: pathlib.Path, *, попыток: int = 10, пауза: float = 0.02
):
    """`os.replace` с повторами: на Windows замена падает `PermissionError`, пока файл открыт
    другим процессом (демон перечитывает файл баз перед вызовом тула), а хендл читателя живёт
    микросекунды — как в `daemon._записать_pid_файл`. Окончательный отказ — `ConfigError` без
    значений из файла; временный файл убирает вызывающий код."""
    for попытка in range(попыток):
        try:
            os.replace(временный, path)
            return
        except PermissionError:
            if попытка == попыток - 1:
                raise ConfigError(
                    f"не удалось записать файл баз: {path} занят другим процессом — "
                    "повторите команду",
                    hint="закройте программы, которые держат файл открытым, и повторите команду",
                ) from None
            time.sleep(пауза)


def set_base_fields(path: pathlib.Path, name: str, changes: dict[str, object]) -> SetResult:
    """Применить изменения к записи базы `name` в файле `path` (проект §3.2).

    Все отказы — до правки: неизвестное поле (ошибка вызывающего кода, `ValueError`), файл не
    найден, запись не найдена или в нестандартной форме, исходный файл, который отверг бы и демон
    (`parse_bases`). Правки применяются по одной (каждая — между двумя разборами, `_правка`); затем
    новый текст проверяется той же моделью настроек, что читает демон (`parse_bases`, без обращения
    к хранилищу ОС), — до вычисления результата, потому что `_значение` и `_действующие`
    рассчитывают на проверенные данные, — и только после этого ложится на место исходного файла
    атомарно. «Изменений нет» — когда у каждого запрошенного поля совпали и значение, и источник:
    явное значение, равное умолчанию роли, — тоже изменение (как у `base add --gate`), файл при
    «изменений нет» не трогается. Ни один текст ошибки не содержит значений из файла."""
    for поле, значение in changes.items():
        if поле not in ПОЛЯ:
            raise ValueError(f"неизвестное поле записи базы: {поле}")
        if значение is ПО_РОЛИ and поле in ("label", "role"):
            raise ValueError(f"у поля {поле} нет умолчания роли")
    if not path.exists():
        raise ConfigError(
            f"файл баз не найден: {path}", hint=f"выполните: odata1c init --home {path.parent}"
        )
    try:
        исходный = path.read_bytes().decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ConfigError(f"файл баз не в кодировке UTF-8: {path}") from exc
    # Окончания строк — по первой строке файла (проект §3.2, п. 1): на Windows
    # `pathlib.write_text` пишет `\r\n`, и файл владельца почти наверняка такой; правка не должна
    # смешивать `\n` и `\r\n`. Файл со смешанными окончаниями приводится к первому.
    nl = "\r\n" if исходный.split("\n", 1)[0].endswith("\r") else "\n"
    текст = исходный.replace("\r\n", "\n")
    _найти_запись(текст, name, текст.count("\n") + 1)
    try:
        данные = yaml.safe_load(текст)
    except yaml.YAMLError as exc:
        # `compose` проходит тег без конструктора (`password: !x`), `safe_load` — нет, а в тексте
        # его ошибки PyYAML вклеивает строку файла. `from None`: цепочка с исходным исключением
        # попала бы в трассировку вместе с этим текстом.
        raise _ошибка_yaml(exc) from None
    parse_bases(данные, path, [], resolve_keyring=False)
    до = данные["bases"][name]

    новый = текст
    try:
        for поле, значение in changes.items():
            if _уже_так(yaml.safe_load(новый)["bases"][name], поле, значение):
                continue
            if поле == "role":
                новый = _применить_роль(новый, name, str(значение))
            elif значение is ПО_РОЛИ:
                новый = _снять(новый, name, поле)
            else:
                новый = _правка(
                    новый,
                    name,
                    functools.partial(
                        _установить, поле=поле, текст=_текст_значения(поле, значение)
                    ),
                )
        данные_после = yaml.safe_load(новый)
    except yaml.YAMLError:
        raise ConfigError(
            f"база «{name}»: правка дала неразбираемый файл — файл оставлен нетронутым, "
            "поправьте запись вручную"
        ) from None
    except _МногострочноеЗначение:
        raise ConfigError(
            f"база «{name}»: подпись в файле занимает несколько строк — поправьте файл вручную"
        ) from None
    parse_bases(данные_после, path, [], resolve_keyring=False)
    после = данные_после["bases"][name]
    # Контрольное чтение: каждое установленное поле читается из нового текста ровно так, как
    # запрошено; для `default` — читается по роли, а не явно. Строка, которую правка переписала,
    # могла оказаться началом многострочного скаляра без кавычек (`label: очень длинная` + строка
    # `  подпись`): хвост остался бы, YAML склеил бы строки, а `parse_bases` склеенное значение
    # принимает. Закрывает и прочие раскладки, которых правка по строкам не предусмотрела.
    for поле, значение in changes.items():
        if поле != "role" and not _уже_так(после, поле, значение):
            raise ConfigError(
                f"база «{name}»: после правки поле {поле} читается не так, как задано — файл "
                "оставлен нетронутым, поправьте запись вручную"
            )

    изменения = [Изменение(п, *_значение(до, п), *_значение(после, п)) for п in changes]
    результат = SetResult(
        label=str(после.get("label", name)),
        изменено=any(и.есть for и in изменения),
        изменения=изменения,
        действует=_действующие(после),
        явные_поля=[
            п for п in ПОЛЯ if п not in ("label", "role") and _значение(после, п)[1] == "явно"
        ],
    )
    if not результат.изменено:
        return результат
    временный = path.with_suffix(".yaml.new")
    try:
        временный.write_bytes((новый.replace("\n", nl) if nl != "\n" else новый).encode("utf-8"))
        _заменить(временный, path)
    except BaseException:
        with contextlib.suppress(OSError):
            временный.unlink(missing_ok=True)
        raise
    закрыть_права_файла(path)
    return результат
