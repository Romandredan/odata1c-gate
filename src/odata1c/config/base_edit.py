def set_base_fields(path: pathlib.Path, name: str, changes: dict[str, object]) -> SetResult:
    """Применить изменения к записи базы `name` в файле `path` (проект §3.2).

    Все отказы — до правки: неизвестное поле (ошибка вызывающего кода, `ValueError`), файл не
    найден, запись не найдена или в нестандартной форме. Правки применяются по одной (каждая —
    между двумя разборами, `_правка`); затем новый текст проверяется той же моделью настроек, что
    читает демон (`parse_bases`, без обращения к хранилищу ОС), и только после этого ложится на
    место исходного файла атомарно. «Изменений нет» — когда у каждого запрошенного поля совпали и
    значение, и источник: явное значение, равное умолчанию роли, — тоже изменение (как у
    `base add --gate`), файл при «изменений нет» не трогается."""
    for поле, значение in changes.items():
        if поле not in ПОЛЯ:
            raise ValueError(f"неизвестное поле записи базы: {поле}")
        if значение is ПО_РОЛИ and поле in ("label", "role"):
            raise ValueError(f"у поля {поле} нет умолчания роли")
    if not path.exists():
        raise ConfigError(
            f"файл баз не найден: {path}", hint=f"выполните: odata1c init --home {path.parent}"
        )
    try:
        исходный = path.read_bytes().decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ConfigError(f"файл баз не в кодировке UTF-8: {path}") from exc
    # Окончания строк сохраняются как были: на Windows `pathlib.write_text` пишет `\r\n`, и файл
    # владельца почти наверняка такой; правка не должна смешивать `\n` и `\r\n`.
    nl = "\r\n" if "\r\n" in исходный else "\n"
    текст = исходный.replace("\r\n", "\n")
    _найти_запись(текст, name, текст.count("\n") + 1)
    до = yaml.safe_load(текст)["bases"][name]

    новый = текст
    try:
        for поле, значение in changes.items():
            if поле == "role":
                новый = _применить_роль(новый, name, str(значение))
            elif значение is ПО_РОЛИ:
                новый = _снять(новый, name, поле)
            else:
                новый = _правка(
                    новый,
                    name,
                    functools.partial(
                        _установить, поле=поле, текст=_текст_значения(поле, значение)
                    ),
                )
        после = yaml.safe_load(новый)["bases"][name]
    except yaml.YAMLError as exc:
        raise ConfigError(
            f"база «{name}»: правка дала неразбираемый файл — файл оставлен нетронутым, "
            "поправьте запись вручную"
        ) from exc

    изменения = [Изменение(п, *_значение(до, п), *_значение(после, п)) for п in changes]
    результат = SetResult(
        label=str(после.get("label", name)),
        изменено=any(и.есть for и in изменения),
        изменения=изменения,
        действует=_действующие(после),
        явные_поля=[
            п for п in ПОЛЯ if п not in ("label", "role") and _значение(после, п)[1] == "явно"
        ],
    )
    if not результат.изменено:
        return результат
    parse_bases(yaml.safe_load(новый), path, [], resolve_keyring=False)
    временный = path.with_suffix(".yaml.new")
    временный.write_bytes((новый.replace("\n", nl) if nl != "\n" else новый).encode("utf-8"))
    os.replace(временный, path)
    закрыть_права_файла(path)
    return результат
