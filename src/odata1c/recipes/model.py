"""Модель рецептов и чтение `recipes.yaml` (SPEC §8, план M1d задача 8).

Рецепт — именованный параметризованный запрос к одной сущности базы: имя регистра, набор полей,
условия и объявленные параметры. Это ДАННЫЕ, а не код: ни одно выражение из файла не исполняется,
значения параметров попадают в запрос только литералами OData (`render` в `recipes/render.py`),
а подстановка `{имя}` разрешена лишь там, где в готовом запросе стоит литерал. Всё остальное —
имя сущности, список полей, порядок сортировки — параметризации не подлежит: иначе рецепт стал бы
способом подставить в запрос произвольное имя поля мимо построителя и гейта.

Проверки этого модуля выполняются ОДИН РАЗ при чтении файла, а не при каждом вызове тула: файл
пишет владелец машины, и ошибка в нём должна быть видна целиком и сразу, а не всплывать на
отдельном сочетании параметров.
"""

from __future__ import annotations

import importlib.resources
import logging
import pathlib
import re
from typing import Literal

import pydantic
import yaml
from pydantic import BaseModel, ConfigDict, Field, PrivateAttr, model_validator

from odata1c.config.home import base_dir
from odata1c.config.loader import format_validation_error
from odata1c.config.models import BaseConfig

_log = logging.getLogger(__name__)

ParamType = Literal["datetime", "date", "guid", "string", "int", "decimal", "bool"]

# Имя рецепта библиотеки — оно же имя файла без расширения (`<имя>.yaml`): буква в начале,
# дальше строчные латинские буквы, цифры и подчёркивание, не длиннее 64 символов (SPEC §8,
# ADR-0011, поправка 2026-09-14). Отдельный от `ИМЯ_БАЗЫ` (config/models.py) регекс: имя базы
# короче (32 символа) и это разные словари имён — совпадение длины было бы случайным.
ИМЯ_РЕЦЕПТА = re.compile(r"^[a-z][a-z0-9_]{0,63}$")

# Ключи книги рецептов (`RecipeBook`), которым нет места в файле ОДНОГО рецепта библиотеки:
# увидев любой из них в корне файла, читатель понял бы файл как книгу, а не как рецепт, и это
# самая частая ошибка при переносе рецепта из старого `recipes.yaml` в библиотеку — забыть
# убрать обёртку.
_КОРНЕВЫЕ_КЛЮЧИ_КНИГИ = frozenset({"recipes", "version"})

# Тип параметра рецепта → тип EDM, по которому `odata_literal` строит литерал (SPEC §8).
# `date` и `datetime` дают один тип EDM: в OData 1С отдельного типа даты нет, а `odata_literal`
# сам дописывает `T00:00:00` к значению вида `ГГГГ-ММ-ДД`. Разница между ними — только в описании,
# которое видит модель: «дата» и «дата с временем» подсказывают разный формат значения.
ТИПЫ_EDM: dict[str, str] = {
    "datetime": "Edm.DateTime",
    "date": "Edm.DateTime",
    "guid": "Edm.Guid",
    "string": "Edm.String",
    "int": "Edm.Int64",
    "decimal": "Edm.Decimal",
    "bool": "Edm.Boolean",
}

# Параметр виртуальной таблицы, который несёт ВЫРАЖЕНИЕ отбора, а не одно значение: только он
# собирается из списка условий и склеивается через `and`. Остальные параметры виртуальной таблицы
# (`Period`, `StartPeriod`, `EndPeriod`, `Dimensions`) — одно значение каждый.
УСЛОВИЕ = "Condition"

_ПЛЕЙСХОЛДЕР = re.compile(r"\{([^{}]*)\}")
_ИМЯ_ПАРАМЕТРА = re.compile(r"^[^\W\d]\w*$")

# Как параметр сравнивается с полем: равенство, сравнение по величине, поиск вхождения. Сами
# анти-оракульные правила по этому виду сравнения применяет разбор `$filter` гейта, а не рецепт
# (Ruling 20, пункт 3); здесь вид сравнения нужен, чтобы отловить при чтении файла параметр,
# который в разных условиях сравнивается по-разному, — у полей разные классы и разные правила.
РАВЕНСТВО = "eq"
ПО_ВЕЛИЧИНЕ = "ordered"
ВХОЖДЕНИЕ = "substring"

_УПОРЯДОЧЕННЫЕ_ОПЕРАТОРЫ = frozenset({"gt", "ge", "lt", "le"})
_ФУНКЦИИ_ПОИСКА = "substringof|startswith|endswith"

# Поле слева от подстановки: «Склад_Key eq {warehouse}». Имя поля может быть путём через
# связанный объект («Контрагент/ИНН») — отсюда «всё, кроме пробелов, скобок и запятых».
_ПОЛЕ_СЛЕВА = re.compile(r"([^\s(),]+)\s+(eq|ne|gt|ge|lt|le)\s+$", re.IGNORECASE)
# Поле слева внутри вызова поиска: «startswith(Наименование, {q})».
_ПОЛЕ_В_ВЫЗОВЕ_СЛЕВА = re.compile(
    rf"\b(?:{_ФУНКЦИИ_ПОИСКА})\s*\(\s*([^\s(),]+)\s*,\s*$", re.IGNORECASE
)
# Поле справа от подстановки внутри вызова поиска: «substringof({q}, Наименование)».
_ПОЛЕ_В_ВЫЗОВЕ_СПРАВА = re.compile(r"^\s*,\s*([^\s(),]+)\s*\)")

# Символы, между которыми подстановка стоит В ПОЗИЦИИ ЛИТЕРАЛА: начало/конец условия, пробел,
# скобка, запятая. Кавычка в этот набор не входит намеренно — `guid'{organization}'` из примера
# SPEC §8 отклоняется: значение вставляется УЖЕ литералом (`guid'…'`), и обёртка в файле дала бы
# двойную обёртку, а разрешение подставлять «внутрь литерала» вернуло бы строковую интерполяцию,
# то есть внедрение условия через значение параметра.
_СЛЕВА_ОТ_ЛИТЕРАЛА = frozenset(" (,")
_СПРАВА_ОТ_ЛИТЕРАЛА = frozenset(" ),")


class RecipeError(Exception):
    """Ошибка рецепта: неизвестное имя (`recipe_unknown`), негодные параметры вызова
    (`recipe_param`) или неверно описанный файл рецептов (`config_invalid`). Тот же протокол
    атрибутов (code, message, hint), что у остальных ошибок слоя тулов."""

    def __init__(self, code: str, message: str, hint: str = "") -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.hint = hint


class Param(BaseModel):
    """Объявление параметра рецепта: тип литерала, обязательность и описание для модели."""

    model_config = ConfigDict(extra="forbid")

    type: ParamType = "string"
    required: bool = False
    description: str = ""


class Recipe(BaseModel):
    model_config = ConfigDict(extra="forbid")

    title: str = ""
    description: str = ""
    entity: str
    params: dict[str, Param] = Field(default_factory=dict)
    virtual: dict[str, str | list[str]] = Field(default_factory=dict)
    select: list[str] = Field(default_factory=list)
    filter: str | list[str] = Field(default_factory=list)
    orderby: str | None = None
    top: int | None = None

    # Имя параметра → (поле, вид сравнения) в условиях. Считается один раз при чтении файла
    # (`_проверить`), потому что тем же проходом проверяется и однозначность пары.
    _поля_параметров: dict[str, tuple[str, str]] = PrivateAttr(default_factory=dict)

    @property
    def conditions(self) -> list[str]:
        """Условия отбора результата (`filter`) — всегда списком, как их видит `render`."""
        return [self.filter] if isinstance(self.filter, str) else list(self.filter)

    @property
    def virtual_conditions(self) -> list[str]:
        """Условия внутри виртуальной таблицы (`virtual.Condition`) — всегда списком."""
        значение = self.virtual.get(УСЛОВИЕ)
        if значение is None:
            return []
        return [значение] if isinstance(значение, str) else list(значение)

    @property
    def virtual_values(self) -> dict[str, str]:
        """Параметры виртуальной таблицы, кроме `Condition`: имя → шаблон одного значения."""
        return {
            имя: значение
            for имя, значение in self.virtual.items()
            if имя != УСЛОВИЕ and isinstance(значение, str)
        }

    @model_validator(mode="after")
    def _проверить(self) -> Recipe:
        for имя in self.params:
            if not _ИМЯ_ПАРАМЕТРА.match(имя):
                raise ValueError(
                    f"имя параметра «{имя}» не годится: буква или подчёркивание в начале, "
                    "дальше буквы, цифры и подчёркивание"
                )
        if self.top is not None and self.top <= 0:
            raise ValueError(f"top должен быть положительным, получено {self.top}")

        # Подстановка запрещена всюду, кроме условий и значений параметров виртуальной таблицы:
        # в `entity`, `select` и `orderby` стоят ИМЕНА, а имя не литерал — значение параметра там
        # прошло бы в запрос текстом, мимо `odata_literal`.
        for место, текст in (
            ("entity", self.entity),
            ("orderby", self.orderby or ""),
            *(("select", поле) for поле in self.select),
        ):
            if _ПЛЕЙСХОЛДЕР.search(текст):
                raise ValueError(
                    f"подстановка параметра в «{место}» недопустима: там имя, а не значение"
                )

        for имя, значение in self.virtual.items():
            if имя != УСЛОВИЕ and имя.casefold().endswith("condition"):
                # Н-6 ревью Ruling 54: `AccountCondition`, `BalancedAccountCondition` (регистры
                # бухгалтерии БП) несут выражение отбора, а рецепт передаёт такой параметр одним
                # значением — шаблон `{условие}` отдал бы значение модели целым выражением мимо
                # разбора гейта. Отбор внутри таблицы рецепт задаёт только в `Condition`: его
                # условия проходят тот же разбор, что `filter` (`recipes.render.probe`).
                raise ValueError(
                    f"параметр виртуальной таблицы «{имя}» несёт выражение отбора: в рецепте "
                    f"отбор внутри таблицы задаётся только в {УСЛОВИЕ}"
                )
            if имя != УСЛОВИЕ and not isinstance(значение, str):
                raise ValueError(
                    f"параметр виртуальной таблицы «{имя}» — одно значение, а не список"
                )

        for шаблон in self.virtual_values.values():
            места = _ПЛЕЙСХОЛДЕР.findall(шаблон)
            if места and шаблон.strip() != "{" + места[0] + "}":
                raise ValueError(
                    f"значение параметра виртуальной таблицы «{шаблон}» должно быть либо целиком "
                    "подстановкой «{имя}», либо постоянным значением без подстановок"
                )

        поля: dict[str, tuple[str, str]] = {}
        for условие in (*self.conditions, *self.virtual_conditions):
            self._проверить_условие(условие, поля)

        неизвестные = {
            имя
            for условие in (*self.conditions, *self.virtual_conditions)
            for имя in _ПЛЕЙСХОЛДЕР.findall(условие)
        } | set(_ПЛЕЙСХОЛДЕР.findall(" ".join(self.virtual_values.values())))
        неизвестные -= set(self.params)
        if неизвестные:
            raise ValueError(
                f"подстановка необъявленных параметров: {', '.join(sorted(неизвестные))}"
            )
        self._поля_параметров = поля
        return self

    def _проверить_условие(self, условие: str, поля: dict[str, tuple[str, str]]) -> None:
        """Проверить одно условие: подстановки стоят в позиции литерала, поле и вид сравнения
        определяются, и один параметр сравнивается всегда с одним и тем же полем одинаково.

        Имя поля нужно гейту: по нему берётся класс защиты, а от совпадения класса зависит право
        раскрыть токен (Ruling 20, пункт 1). Вид сравнения запросу тоже не нужен — сами
        анти-оракульные правила применяет разбор `$filter` к готовому условию (Ruling 20,
        пункт 3), — но пара «поле и вид» ловит здесь параметр, который в разных условиях
        сравнивается по-разному: у полей свои классы и свои правила, и один параметр на два
        разных сравнения — ошибка файла. Условие, в котором поле определить нельзя, отклоняется
        при чтении: иначе параметр молча получил бы раскрытие без известного поля.
        """
        for совпадение in _ПЛЕЙСХОЛДЕР.finditer(условие):
            имя = совпадение.group(1)
            слева = условие[: совпадение.start()]
            справа = условие[совпадение.end() :]
            if (слева and слева[-1] not in _СЛЕВА_ОТ_ЛИТЕРАЛА) or (
                справа and справа[0] not in _СПРАВА_ОТ_ЛИТЕРАЛА
            ):
                raise ValueError(
                    f"подстановка «{{{имя}}}» в условии «{условие}» стоит не в позиции литерала: "
                    "значение подставляется уже готовым литералом, кавычки и обёртку "
                    "«guid'…'» вокруг подстановки писать не нужно"
                )
            сравнение = _ПОЛЕ_СЛЕВА.search(слева)
            вызов_слева = _ПОЛЕ_В_ВЫЗОВЕ_СЛЕВА.search(слева)
            вызов_справа = _ПОЛЕ_В_ВЫЗОВЕ_СПРАВА.match(справа)
            if сравнение is not None:
                оператор = сравнение.group(2).lower()
                опознано = (
                    сравнение.group(1),
                    ПО_ВЕЛИЧИНЕ if оператор in _УПОРЯДОЧЕННЫЕ_ОПЕРАТОРЫ else РАВЕНСТВО,
                )
            elif вызов_слева is not None:
                опознано = (вызов_слева.group(1), ВХОЖДЕНИЕ)
            elif вызов_справа is not None:
                опознано = (вызов_справа.group(1), ВХОЖДЕНИЕ)
            else:
                raise ValueError(
                    f"в условии «{условие}» не видно поля, с которым сравнивается «{{{имя}}}»: "
                    "пишите «Поле eq {имя}», «substringof({имя}, Поле)» или "
                    "«startswith(Поле, {имя})»"
                )
            прежнее = поля.setdefault(имя, опознано)
            if прежнее != опознано:
                raise ValueError(
                    f"параметр «{имя}» сравнивается по-разному ({прежнее[0]} {прежнее[1]} и "
                    f"{опознано[0]} {опознано[1]}): у поля свой класс защиты и свои правила "
                    "сравнения, заведите отдельный параметр на каждое"
                )

    def param_field(self, name: str) -> str:
        """Поле, с которым сравнивается параметр, — для `gate.inbound_value` (по имени поля
        берётся класс защиты). Пустая строка, если параметр в условиях не используется вовсе
        (только как значение параметра виртуальной таблицы — `Period` и подобные): токен в таком
        параметре раскрыт не будет, потому что раскрывать его не с чем сверить."""
        return self._поля_параметров.get(name, ("", РАВЕНСТВО))[0]

    def param_comparison(self, name: str) -> str:
        """Вид сравнения параметра с полем: `eq` (равенство/неравенство), `ordered` (по величине)
        или `substring` (поиск вхождения). Используется проверкой файла (`_проверить_условие`):
        один параметр не должен сравниваться в разных условиях по-разному."""
        return self._поля_параметров.get(name, ("", РАВЕНСТВО))[1]


class RecipeBook(BaseModel):
    model_config = ConfigDict(extra="forbid")

    version: int = 1
    recipes: dict[str, Recipe] = Field(default_factory=dict)


def recipes_path(home: pathlib.Path, base: BaseConfig) -> pathlib.Path:
    """Путь к файлу СОБСТВЕННЫХ рецептов базы: `recipes` из `bases.yaml` (относительно домашнего
    каталога, абсолютный — как есть) либо `bases/<имя>/recipes.yaml` по умолчанию.

    Это верхний (самый сильный) слой `load_layered`: правки владельца конкретной базы,
    перекрывающие и шаблон пакета, и библиотеку конфигурации. Умолчание обязательно, а не
    «удобно»: `odata1c base add --recipes ut` кладёт шаблон именно сюда (design §4b — команда
    сохранила прежнее поведение, копирует файл, а не только называет `config`), но ключ `recipes`
    в `bases.yaml` не дописывает (он там показан закомментированным) — без запасного пути
    скопированные рецепты не нашёл бы никто."""
    указанный = base.recipes
    if not указанный:
        return base_dir(home, base.name) / "recipes.yaml"
    путь = pathlib.Path(указанный)
    return путь if путь.is_absolute() else home / путь


def template_hint(path: pathlib.Path) -> str:
    """Как положить в файл рецептов базы шаблон поставки — одна подсказка на все случаи, когда
    рецептов нет: файла нет, файл пуст, рецепт с таким именем не описан в пустой книге (находка
    П4 приёмки через настоящие инструменты, 2026-09-12).

    С ADR-0011 (поправка 2026-09-14) у базы с `config` шаблон пакета и без этой подсказки виден
    сам, нижним слоем `load_layered` — но подсказка остаётся нужна файлу СОБСТВЕННЫХ рецептов
    базы (верхний слой), который `config` не подключает: путь каталога шаблонов берётся у самого
    пакета, а не собирается вручную, — при запуске через `uvx` он лежит в кэше `uv`, и угадать
    его владелец не сможет."""
    каталог = importlib.resources.files("odata1c.templates.recipes")
    return (
        f"положите в {path} шаблон поставки: скопируйте туда ut.yaml, bp.yaml или zup.yaml "
        f"(УТ, БП, ЗУП) из {каталог}; новой базе то же делает odata1c base add <имя> "
        "--recipes ut|bp|zup"
    )


def load_recipes(path: pathlib.Path) -> RecipeBook:
    """Прочитать `recipes.yaml`. Любая ошибка файла — `RecipeError` с кодом `config_invalid`
    (SPEC §5.2, поправка 2026-09-08: код для ошибок файлов настроек)."""
    путь = pathlib.Path(path)
    if not путь.exists():
        raise RecipeError(
            "config_invalid",
            f"файл рецептов не найден: {путь}",
            template_hint(путь),
        )
    try:
        данные = yaml.safe_load(путь.read_text(encoding="utf-8"))
    except yaml.YAMLError as ошибка:
        # Из исключения PyYAML берётся только позиция, но не его текст: библиотека вклеивает
        # в сообщение фрагмент самого файла (тот же приём, что в config/loader.py).
        отметка = getattr(ошибка, "problem_mark", None)
        место = (
            f"строка {отметка.line + 1}, колонка {отметка.column + 1}"
            if отметка is not None
            else "точное место в файле не определено"
        )
        raise RecipeError(
            "config_invalid",
            f"файл рецептов {путь.name} не разбирается как YAML: {место}",
            f"проверьте синтаксис файла {путь}",
        ) from ошибка
    except OSError as ошибка:
        raise RecipeError("config_invalid", f"файл рецептов {путь} не читается") from ошибка

    if данные is None:
        данные = {}
    if not isinstance(данные, dict):
        raise RecipeError(
            "config_invalid",
            f"файл рецептов {путь.name} должен быть набором полей version/recipes",
        )
    try:
        return RecipeBook(**данные)
    except pydantic.ValidationError as ошибка:
        raise RecipeError(
            "config_invalid",
            f"рецепты в {путь.name} описаны неверно: {format_validation_error(ошибка)}",
        ) from ошибка


# -- библиотека рецептов по конфигурации (SPEC §8, ADR-0011, поправка 2026-09-14) ----------------
#
# Прежде рецепты жили одним файлом на базу (`recipes.yaml`, выше), а типовые заводились
# копированием шаблона пакета (`base add --recipes`) — копия расходилась с пакетом сразу после
# копирования и правки пользователя ничем не были отделены от того, что принёс шаблон. Библиотека
# устроена иначе: рецепт — один файл (`<имя>.yaml`, корень файла — сами поля рецепта, без обёртки
# `recipes:`/`version:`), рецепты копятся в каталоге конфигурации по мере того, как оказываются
# полезны в задачах, а не поставляются одним списком сразу. Слоёв три, слабый снизу: шаблон пакета
# (стартовая точка) ← библиотека конфигурации (`~/.claude/odata1c/recipes/<config>/`, общая на все
# базы этой конфигурации) ← файл базы (`recipes_path`, правка одной базы). Совпадение имени —
# верхний слой побеждает целиком, слияния полей одного рецепта из разных слоёв нет.


def library_dir(home: pathlib.Path, config: str) -> pathlib.Path:
    """Каталог библиотеки рецептов конфигурации: `<home>/recipes/<config>/`, один файл — один
    рецепт. Общий для всех баз с этим `config` (`BaseConfig.config`, config/models.py) — база
    только называет, какую библиотеку она видит, сами файлы от имени базы не зависят."""
    return home / "recipes" / config


def load_recipe_file(path: pathlib.Path) -> Recipe:
    """Прочитать один файл библиотеки: корень файла — отображение полей `Recipe` (`entity`,
    `select`, `params`, …), а не книга. Имя рецепта — не поле файла, а имя файла без расширения
    (`path.stem`): так рецепт остаётся идентифицируемым по каталогу без открытия файла, и два
    файла не могут молча описать один и тот же рецепт под разными именами.

    Ошибка файла — всегда `RecipeError` с кодом `config_invalid` (тот же код и протокол, что у
    `load_recipes`), с путём файла в тексте: `recipe check` печатает находки построчно, и без
    пути в самом тексте владелец не узнал бы, какой из файлов каталога правит."""
    путь = pathlib.Path(path)
    try:
        данные = yaml.safe_load(путь.read_text(encoding="utf-8"))
    except yaml.YAMLError as ошибка:
        отметка = getattr(ошибка, "problem_mark", None)
        место = (
            f"строка {отметка.line + 1}, колонка {отметка.column + 1}"
            if отметка is not None
            else "точное место в файле не определено"
        )
        raise RecipeError(
            "config_invalid",
            f"{путь}: файл рецепта не разбирается как YAML ({место})",
            f"проверьте синтаксис файла {путь}",
        ) from ошибка
    except OSError as ошибка:
        raise RecipeError("config_invalid", f"{путь}: файл рецепта не читается") from ошибка

    if данные is None:
        данные = {}
    if not isinstance(данные, dict):
        raise RecipeError(
            "config_invalid",
            f"{путь}: файл рецепта должен быть набором полей рецепта (entity, select, …)",
        )
    лишние = _КОРНЕВЫЕ_КЛЮЧИ_КНИГИ & set(данные)
    if лишние:
        raise RecipeError(
            "config_invalid",
            f"{путь}: один рецепт на файл — здесь не нужен ключ «{sorted(лишние)[0]}» книги "
            "рецептов; корень файла библиотеки — это сами поля рецепта (entity, select, …)",
        )
    if not ИМЯ_РЕЦЕПТА.match(путь.stem):
        raise RecipeError(
            "config_invalid",
            f"{путь}: имя файла «{путь.stem}» не годится как имя рецепта — строчная латинская "
            "буква в начале, дальше строчные латинские буквы, цифры и подчёркивание, "
            "не длиннее 64 символов",
        )
    try:
        return Recipe(**данные)
    except pydantic.ValidationError as ошибка:
        raise RecipeError(
            "config_invalid",
            f"{путь}: рецепт описан неверно: {format_validation_error(ошибка)}",
        ) from ошибка


def scan_library(
    каталог: pathlib.Path,
) -> tuple[dict[str, pathlib.Path], dict[str, list[pathlib.Path]], list[pathlib.Path]]:
    """Кандидаты файлов библиотеки одного каталога — общая часть `load_library` и
    `cli.cmd_recipe_check` (Ruling 79, ревью задачи 3): расширение приведено к нижнему регистру
    ЯВНО, а не через `pathlib.Path.glob("*.yaml")` — тот на Windows (регистронезависимая ФС)
    матчит и `.YAML`, а на Linux (регистрозависимая, туда целится CI задачи 9) — нет; при целевой
    ОС Windows (SPEC §15) поведение должно быть одним и тем же на обеих, а не расходиться по ОС,
    на которой запущен демон.

    Возвращает три списка: (1) стем имени → путь, для файлов, у которых на этот стем ровно один
    файл с расширением `.yaml`/`.YAML`/… (регистр расширения не важен); (2) стем → все пути,
    если на этот стем таких файлов НЕСКОЛЬКО (`stock.yaml` и `stock.YAML` рядом — тоже дубликат
    имени, даже с одинаковым стемом и просто разным регистром расширения); (3) файлы с
    расширением `.yml` — демон их не читает нигде (ни здесь, ни `load_recipe_file`), но и не
    должен пропускать молча: такой файл — рецепт, который владелец считает существующим, а он не
    существует ни для одного слоя."""
    по_стему: dict[str, list[pathlib.Path]] = {}
    yml_файлы: list[pathlib.Path] = []
    if not каталог.is_dir():
        return {}, {}, []
    for файл in sorted(каталог.iterdir()):
        if not файл.is_file():
            continue
        расширение = файл.suffix.lower()
        if расширение == ".yml":
            yml_файлы.append(файл)
        elif расширение == ".yaml":
            по_стему.setdefault(файл.stem, []).append(файл)
    кандидаты = {стем: пути[0] for стем, пути in по_стему.items() if len(пути) == 1}
    дубликаты = {стем: пути for стем, пути in по_стему.items() if len(пути) > 1}
    return кандидаты, дубликаты, yml_файлы


def load_library(home: pathlib.Path, config: str) -> dict[str, Recipe]:
    """Все рецепты библиотеки конфигурации: имя файла (без расширения) → рецепт, по алфавиту
    имени. Каталога нет вовсе — пустой словарь, это не ошибка: библиотека необязательна, как и
    файл рецептов базы. Без кэша — каталог маленький, а новый файл должен быть виден сразу же,
    без перезапуска демона (та же причина, что у `ToolService._книга_рецептов`).

    Один негодный файл или дубликат имени НЕ закрывает библиотеку целиком (Ruling 79, ревью
    задачи 3, Major 2): до этой правки первый же `RecipeError` внутри включения словаря уходил
    наверх через `load_layered` → `ToolService._книга_рецептов` → `_run`, где превращался в отказ
    `config_invalid`, — и один файл с опечаткой в имени (например, `Stock.YAML` — на Windows его
    матчил бы прежний `glob("*.yaml")`) выключал `odata1c_recipe` у ВСЕХ баз этой конфигурации и
    всех сессий разом. Негодный файл рецепта утечки вызвать не может — каждый рецепт всё равно
    идёт через гейт на исполнении, — поэтому мягкая деградация здесь безопасна. Пропущенный файл
    попадает в журнал демона (WARNING, путь без содержимого файла — сообщение `RecipeError` и так
    не содержит значений данных, SPEC §3.1); громкий канал для владельца и навыка —
    `odata1c recipe check`, которая те же файлы и дубликаты печатает строкой `error`."""
    кандидаты, дубликаты, _yml = scan_library(library_dir(home, config))
    результат: dict[str, Recipe] = {}
    for имя, файл in sorted(кандидаты.items()):
        try:
            результат[имя] = load_recipe_file(файл)
        except RecipeError as ошибка:
            _log.warning("рецепт библиотеки пропущен, файл не читается: %s (%s)", файл, ошибка.code)
    for имя, файлы in sorted(дубликаты.items()):
        _log.warning(
            "рецепт библиотеки пропущен, дубликат имени «%s»: %s",
            имя,
            ", ".join(str(ф) for ф in файлы),
        )
    return результат


def load_template(config: str) -> dict[str, Recipe]:
    """Шаблон рецептов конфигурации из пакета (`templates/recipes/<config>.yaml`) — тот же файл,
    что и прежде копирует `base add --recipes` в `recipes.yaml` базы (это поведение сохранено,
    design §4b), только здесь читаемый на лету как нижний слой `load_layered`: так правку пакета
    видит сразу ЛЮБАЯ база с этим `config`, а не только та, что получила копию через `base add`.
    Файла нет (неизвестная или доработанная с нуля конфигурация) — пустой словарь, а не ошибка."""
    ресурс = importlib.resources.files("odata1c.templates.recipes").joinpath(f"{config}.yaml")
    if not ресурс.is_file():
        return {}
    данные = yaml.safe_load(ресурс.read_text(encoding="utf-8")) or {}
    if not isinstance(данные, dict):
        raise RecipeError(
            "config_invalid",
            f"шаблон рецептов пакета {config}.yaml должен быть набором полей version/recipes",
        )
    try:
        книга = RecipeBook(**данные)
    except pydantic.ValidationError as ошибка:
        raise RecipeError(
            "config_invalid",
            f"шаблон рецептов пакета {config}.yaml описан неверно: "
            f"{format_validation_error(ошибка)}",
        ) from ошибка
    return dict(книга.recipes)


# Источник строки объединённого перечня рецептов (`ToolService._список_рецептов`,
# `odata1c recipe list`) — тот же слой, что победил в `load_layered`.
Layered = tuple[RecipeBook, dict[str, Literal["base", "library", "template"]]]


def load_layered(home: pathlib.Path, base: BaseConfig) -> Layered | None:
    """Слои рецептов базы, собранные в один `RecipeBook`, вместе с источником каждого имени:
    шаблон пакета ← библиотека конфигурации ← файл базы (SPEC §8, ADR-0011, поправка 2026-09-14).
    Слабый слой снизу — при совпадении имени сильный побеждает целиком, слияния полей одного
    рецепта из разных слоёв нет.

    `None` — рецептов показать неоткуда: у базы нет ни `config` (библиотеку и шаблон подключать
    нечем), ни собственного файла рецептов. Это тот же случай, что раньше означало `RecipeBook |
    None` равный `None` у `ToolService._книга_рецептов` — отсутствие рецептов не ошибка.

    Без `config` собственный файл базы, если он есть, читается как раньше — базе не обязательно
    быть УТ, БП или ЗУП, чтобы держать свои рецепты (`test_база_без_config_видит_только_свой_файл`
    брифа задачи 3)."""
    путь_базы = recipes_path(home, base)
    файл_базы_есть = путь_базы.exists()
    if not файл_базы_есть and not base.config:
        return None

    шаблон = load_template(base.config) if base.config else {}
    библиотека = load_library(home, base.config) if base.config else {}
    книга_базы = load_recipes(путь_базы) if файл_базы_есть else RecipeBook(recipes={})

    источники: dict[str, Literal["base", "library", "template"]] = {}
    источники.update(dict.fromkeys(шаблон, "template"))
    источники.update(dict.fromkeys(библиотека, "library"))
    источники.update(dict.fromkeys(книга_базы.recipes, "base"))

    книга = RecipeBook(recipes={**шаблон, **библиотека, **книга_базы.recipes})
    return книга, источники
