"""Рендеринг рецепта в аргументы выборки (SPEC §8, план M1d задача 8).

Чистые функции: ни сети, ни гейта, ни индекса. На вход — рецепт (`recipes/model.py`) и значения
параметров, УЖЕ прошедшие обратную подмену гейта (`gate.inbound_value`: токен → реальное
значение); на выход — `QueryArgs`, то есть ровно те аргументы, с которыми `ToolService` вызывает
обычную выборку.

Три правила, из которых складывается безопасность подстановки:

1. Значение параметра попадает в условие ТОЛЬКО литералом OData (`odata_literal` задачи 2):
   строка берётся в кавычки с удвоением внутренних, GUID и дата проверяются на формат, число —
   на то, что это число. Поэтому значение вида `' or 1 eq 1` становится одним строковым
   литералом, а не вторым условием.
2. Подстановка идёт ОДНИМ проходом (`re.sub` с функцией замены): вставленный литерал больше не
   просматривается. Последовательная замена «параметр за параметром» этим свойством не обладает —
   значение, содержащее `{другой_параметр}`, при ней подставилось бы второй раз.
3. Место подстановки проверено при чтении файла (`Recipe._проверить_условие`): только позиция
   литерала, только объявленные параметры, и никогда — имя сущности, поля или сортировки.
"""

from __future__ import annotations

import dataclasses
import re

from odata1c.recipes.model import ТИПЫ_EDM, Recipe, RecipeError
from odata1c.tools.odata_query import QueryError, odata_literal

_ПЛЕЙСХОЛДЕР = re.compile(r"\{([^{}]*)\}")


@dataclasses.dataclass(slots=True)
class QueryArgs:
    """Аргументы выборки, полученные из рецепта, — подмножество аргументов `ToolService.query`."""

    entity: str
    select: list[str]
    filter: str | None
    orderby: str | None
    top: int | None
    params: dict[str, object] | None
    """Параметры виртуальной таблицы. Значения здесь СЫРЫЕ, не литералы: литерал из них строит
    сам `odata_query._путь_виртуальной_таблицы` по типу параметра из `$metadata`. Исключение —
    `Condition`: это готовое выражение отбора, и построитель возьмёт его как строковый литерал,
    ровно так же, как условие, пришедшее в `params` обычного `query`."""


def render(recipe: Recipe, values: dict) -> QueryArgs:
    """Собрать аргументы выборки по рецепту и значениям параметров.

    `values` — значения ПОСЛЕ обратной подмены гейта. Параметр со значением `None` считается
    незаданным: условия, где он встречается, из запроса исчезают (SPEC §8), а параметр
    виртуальной таблицы с таким шаблоном не передаётся вовсе. Пустая строка незаданностью НЕ
    считается — это осознанно переданное значение.
    """
    заданные = {имя: значение for имя, значение in values.items() if значение is not None}

    неизвестные = sorted(set(заданные) - set(recipe.params))
    if неизвестные:
        raise RecipeError(
            "recipe_param",
            f"рецепт не принимает часть переданных параметров: {len(неизвестные)}",
            f"параметры рецепта: {', '.join(recipe.params) or 'нет'}",
        )
    недостающие = sorted(
        имя for имя, параметр in recipe.params.items() if параметр.required and имя not in заданные
    )
    if недостающие:
        raise RecipeError(
            "recipe_param",
            f"не заданы обязательные параметры рецепта: {', '.join(недостающие)}",
            _подсказка_параметров(recipe, недостающие),
        )

    литералы = {имя: _литерал(recipe, имя, значение) for имя, значение in заданные.items()}

    условия_результата = _собрать_условия(recipe.conditions, литералы)
    условия_таблицы = _собрать_условия(recipe.virtual_conditions, литералы)

    параметры: dict[str, object] = {}
    for имя, шаблон in recipe.virtual_values.items():
        места = _ПЛЕЙСХОЛДЕР.findall(шаблон)
        if not места:
            параметры[имя] = шаблон
        elif места[0] in заданные:
            # Сырое значение, а не литерал: параметр виртуальной таблицы построитель запроса
            # оформляет сам, по типу из `$metadata`. Проверка формата уже сделана выше
            # (`_литерал`) — её результат здесь отброшен намеренно, нужен был только отказ.
            параметры[имя] = заданные[места[0]]
    if условия_таблицы:
        параметры["Condition"] = " and ".join(условия_таблицы)

    return QueryArgs(
        entity=recipe.entity,
        select=list(recipe.select),
        filter=" and ".join(условия_результата) or None,
        orderby=recipe.orderby,
        top=recipe.top,
        params=параметры or None,
    )


def probe(recipe: Recipe, values: dict) -> tuple[str | None, str | None]:
    """Те же два выражения отбора, что соберёт `render`, но с СЫРЫМИ значениями параметров
    (токены как есть) и всегда строковыми литералами — не для запроса, а для проверки гейтом.

    Ruling 20, пункт 3: анти-оракульные правила `$filter` существуют в одной реализации —
    в разборе выражения (`gate/unmasking.py`). Рецепт не повторяет их своим списком (два списка
    безопасности расходятся, и они разошлись: из пяти правил в рецепте работали три, и те не
    срабатывали на поле через связанный объект), а прогоняет через тот же разбор своё готовое
    условие. Отсюда два следствия:

    - значения подставляются ДО обратной подмены: разбор сам увидит токен, сам решит, можно ли
      его раскрыть в этом поле, и сам применит правила по классу поля и виду сравнения;
    - литерал всегда строковый, даже когда параметр объявлен датой или GUID. Расхождение с
      настоящим рендерингом (`render` строит литерал по типу) осознанное и безвредное: правила
      смотрят на класс поля и на то, является ли литерал целым токеном, а не на тип EDM.
      Проверку типа делает сам `render` — своим отказом и на своём месте.

    Результат разбора (выражение с подставленными реальными значениями) вызывающий ОТБРАСЫВАЕТ:
    запрос строит `render`, потому что 1С нужны типизированные литералы (`guid'…'`,
    `datetime'…'`), которых разбор `$filter` не восстанавливает.
    """
    заданные = {
        имя: значение
        for имя, значение in values.items()
        if значение is not None and имя in recipe.params
    }
    литералы = {имя: _строковый_литерал(значение) for имя, значение in заданные.items()}
    результат = _собрать_условия(recipe.conditions, литералы)
    таблица = _собрать_условия(recipe.virtual_conditions, литералы)
    return (" and ".join(результат) or None, " and ".join(таблица) or None)


def _строковый_литерал(значение) -> str:
    return "'" + str(значение).replace("'", "''") + "'"


def _собрать_условия(шаблоны: list[str], литералы: dict[str, str]) -> list[str]:
    """Условия с подставленными литералами; условие с незаданным параметром выбрасывается
    целиком (SPEC §8)."""
    готовые = []
    for шаблон in шаблоны:
        места = _ПЛЕЙСХОЛДЕР.findall(шаблон)
        if any(имя not in литералы for имя in места):
            continue
        готовые.append(_ПЛЕЙСХОЛДЕР.sub(lambda м: литералы[м.group(1)], шаблон))
    return готовые


def _литерал(recipe: Recipe, имя: str, значение) -> str:
    """Значение параметра как литерал OData по объявленному типу.

    Ruling 20, пункт 2 (ревью 2026-09-11): текст отказа строится из ИМЕНИ параметра и ожидаемого
    типа и никогда не повторяет значение. Прежнее решение («„7707083893“ не похоже на GUID», код
    задачи 8) ставило инвариант 1 в зависимость от того, умеет ли страж собрать конкретный класс
    обратно, — а значение здесь уже раскрытое, и у `addr`/`dob` последнего рубежа нет вовсе:
    ровно так шлюз и работал универсальным дешифратором. Само `odata_literal` значения тоже
    больше не повторяет; своё сообщение здесь остаётся, чтобы отказ называл параметр РЕЦЕПТА, а
    не аргумент построителя запроса.
    """
    edm = ТИПЫ_EDM[recipe.params[имя].type]
    try:
        return odata_literal(edm, значение, name=имя)
    except QueryError as ошибка:
        raise RecipeError(
            "recipe_param",
            f"значение параметра «{имя}» рецепта не годится как {recipe.params[имя].type} ({edm})",
            ошибка.hint or f"ожидается значение типа {recipe.params[имя].type}",
        ) from ошибка


def _подсказка_параметров(recipe: Recipe, имена: list[str]) -> str:
    части = []
    for имя in имена:
        параметр = recipe.params[имя]
        описание = f" — {параметр.description}" if параметр.description else ""
        части.append(f"{имя} ({параметр.type}){описание}")
    return "; ".join(части)
