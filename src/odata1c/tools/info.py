"""Справочник тула `odata1c_info` (SPEC §5, план M1d задача 7): короткие темы о том, как
устроен OData 1С и чем он отличается от «обычного» OData, — то, чего модель не выведет из
описаний тулов и из `describe_entity`.

Тексты — константы модуля. Это не оговорка, а условие: ответ `info` не содержит и не может
содержать ни байта данных 1С, поэтому он единственный из ответов тулов НЕ проходит страж утечек
(см. `ToolService.info` — там же обоснование и ссылка на тот же приём в `ToolService.bases`).
Константа, собранная при импорте, доказывает это самим своим существованием; текст, собранный из
чего-то ещё, такого доказательства не даёт — поэтому ничего динамического здесь появляться не
должно.

Факты ниже — из проб P4/P5 (`docs/probes/`) и поправок SPEC §4.2, §9: виртуальные таблицы
регистров опубликованы действиями, `$expand` молчит без навигационного поля в `$select`,
`odata.count` приходит строкой, `Condition` — текст отбора внутри аргумента виртуальной таблицы,
составное поле идёт парой `Поле` + `Поле_Type`.
"""

