# Ruling 26 (приёмка на живой базе владельца, задача 9 M1d). Разделены две разные вещи, которые
# были слиты в одну: замена значения в поле с объявленным классом делается ВСЕГДА (владелец
# назначил полю класс — это не обсуждается), а в множество для поиска по СВОБОДНОМУ ТЕКСТУ
# значение попадает, только если его осмысленно искать. Значение короче формы своего класса
# искать негде: цифра «1» в номере документа — не КПП контрагента.
#
# Повод: у контрагента рабочей базы КПП записан одной цифрой. Гейт выдал ей токен, положил в
# множество для поиска — и страж начал заменять единицу везде: `00УТ-180814` →
# `00УТ-[[kpp:…]]808[[kpp:…]]4`, `2026-08-26T19:30:11` → решето, `09226071` → потерянная цифра.
# Инвариант 6 нарушен прямо, причём словарь один на домашний каталог, поэтому портиться начали
# ответы и по другой базе, к которой запрос не имел отношения.
#
# Минимум задан ПО КЛАССУ, а не одним числом на всех, потому что у классов есть известная форма
# (та же, что у детекторов `gate/detectors.py`): ИНН — 10 или 12 цифр, КПП — 9, ОГРН — 13 (15 у
