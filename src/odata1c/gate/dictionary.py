def _поле_не_название(поле: str) -> bool:
    """Поле, которое классификатор явно не считает ни ФИО, ни названием: член перечисления
    (`ПЕРЕЧИСЛЕНИЯ_ТИПА_ЛИЦА`, находка П1) или правило каталога поставки `names: <поле>: scan`
    (ADR-0016) — в том числе поля, снятые с `person` разведкой БП (`СотрудникПол`,
    `ТипЗаявкиКабинетСотрудника`; ревью атакующим ветки bp-gate, находка 6). Токены `org`/`person`,
    все написания которых пришли из таких полей, выданы по ошибке прежних версий."""
    if ПЕРЕЧИСЛЕНИЯ_ТИПА_ЛИЦА.fullmatch(поле):
        return True
    return package_rules().name_rule(поле) == БЕЗ_КЛАССА


def searchable(type_: str, normalized: str) -> bool:
    """Стоит ли искать это значение в свободном тексте (Ruling 26, см. `МИНИМАЛЬНАЯ_ДЛИНА_ПОИСКА`).

    Проверка сделана на ЧТЕНИИ множества, а не на записи токена, и это осознанно: словари,
    которые уже успели набрать коротких значений (у владельца их нашлось 56), лечатся первым же
    запуском, без миграции и без ручной чистки. Сам токен, запись в `tokens` и написание в
    `variants` не трогаются — обратная подмена и `reveal` обязаны работать для любого значения,
    каким бы коротким оно ни было."""
    return len(normalized) >= МИНИМАЛЬНАЯ_ДЛИНА_ПОИСКА.get(type_, МИНИМАЛЬНАЯ_ДЛИНА_ВАРИАНТА)


ФОРМЫ = re.compile(r'^(ооо|оао|зао|пао|ао|ип|нко|ано|фгуп|гуп|муп|тсж|снт)[\s"«]+', re.IGNORECASE)
# Посимвольная свёртка названий — та же таблица, что при выдаче токена (`tokens.normalize_value`
# для org/person): кавычки любого вида к прямой; «ё» к «е» (SPEC §6.3, поправка ¹⁰). Общая на три
# места (нормализация значения, варианты названий, проверяемый текст) — иначе `normalized` и
# вариант расходятся (C1 ревью 2026-09-10). Замена символ на символ: длина строки и карта позиций
# не меняются.
СВЁРТКА = СВЁРТКА_НАЗВАНИЙ
# Только для проверяемого текста, не для ключей словаря (они хранятся, и U+FFFD в ключе не совпал
# бы ни с чем настоящим): одиночная суррогатная половина — JSON допускает `\ud800` без пары, и
# после раскодирования такая строка не кодируется в UTF-8, а автомат `ahocorasick_rs` принимает
# только корректный UTF-8 и падал `UnicodeEncodeError` (Ruling 21 M1c, хвост 1). На время поиска
# половина заменяется на U+FFFD — символ на символ, карта позиций цела; в выход идёт исходная
# строка, то есть исходный символ. В Python-строке любой код D800–DFFF — одиночная половина:
# пару `json.loads` склеивает в один символ.
_СВЁРТКА_ДЛЯ_ПОИСКА = {**СВЁРТКА, **{код: 0xFFFD for код in range(0xD800, 0xE000)}}


def _есть_буква(текст: str) -> bool:
    """Есть ли в строке хоть одна буква (знаки препинания и цифры буквами не считаются)."""
    return any(символ.isalpha() for символ in текст)


def _в_кавычках(вариант: str) -> bool:
    """Ключ в прямых кавычках целиком — `"2020"` (кавычки других видов свёртка уже привела к
    прямой)."""
    return len(вариант) >= 3 and вариант[0] == '"' and вариант[-1] == '"'


def _годится_в_поиск(вариант: str) -> bool:
    """Можно ли искать ключ в свободном тексте: в нём есть буква или он в кавычках, а ядро в
    кавычках не короче общего минимума (Ruling 50). Голое безбуквенное ядро — нет: в тексте оно
    неотличимо от числа (Р3-2, инвариант 6)."""
    return _есть_буква(вариант) or (
        _в_кавычках(вариант) and len(вариант) - 2 >= МИНИМАЛЬНАЯ_ДЛИНА_ВАРИАНТА
    )


# Одиночное слово (Ruling 115): ключ целиком из букв — без пробелов, дефисов, цифр и прочих знаков.
ОДИНОЧНОЕ_СЛОВО = re.compile(r"[^\W\d_]+")


def _письменность(буква: str) -> str:
    """Письменность буквы по её имени в Unicode: `CYRILLIC`, `LATIN`, `GREEK` и так далее."""
    return unicodedata.name(буква, "").split(" ", 1)[0]


def _голое_слово(ключ: str) -> bool:
    """Ключ — одно слово из букв одной письменности (Ruling 115). Такое слово в свободном тексте
    неотличимо от обычного слова или имени («мост», «мария»), и искать его голым нельзя:
    закрывается только в узнаваемых написаниях (`name_variants_of`).

    Слово из букв двух письменностей (`ТехноNIKOL`, `ВкусVill`) обычным словом не бывает — смешение
    письменностей само признак названия (итоговое ревью ветки, находка I-1), и такой ключ
    остаётся голым, как до Ruling 115."""
    return (
        ОДИНОЧНОЕ_СЛОВО.fullmatch(ключ) is not None
        and len({_письменность(буква) for буква in ключ}) == 1
    )


# Полная запись формы собственности (итоговое ревью ветки, C-1): «Общество с ограниченной
# ответственностью Мост» — то же название, что `ООО "Мост"`. Форма вне карты полных ключей не
# получает.
ПОЛНЫЕ_ФОРМЫ = {
    "ооо": "общество с ограниченной ответственностью",
    "ип": "индивидуальный предприниматель",
    "ао": "акционерное общество",
    "пао": "публичное акционерное общество",
    "зао": "закрытое акционерное общество",
    "оао": "открытое акционерное общество",
}
# Латинские двойники кириллических букв формы: `OOO Мост` набирают в латинской раскладке. Ключ
# получает только форма целиком из таких букв (`ооо`, `оао`, `ао`).
_ЛАТИНСКИЕ_ДВОЙНИКИ = {"а": "a", "о": "o"}


def _написания_одиночного_слова(ядро: str, своя: str | None) -> list[str]:
    """Ключи одиночного слова сверх `"ядро"`, `"ядро` и трёх видов своей формы (итоговое ревью
    ветки, C-1). До Ruling 115 эти написания закрывал голый ключ, и без своих ключей они открылись
    бы. Каждый ключ содержит ядро целым словом — рядом с ним в ключе пробел или знак, — поэтому
    ключ срабатывает только там, где ядро стоит отдельным словом, то есть там, где срабатывал
    голый ключ до ветки (инвариант 6). Протяжённость замены у ключа с кавычкой больше: кавычка
    уходит под токен вместе с ядром.

    - кавычки других видов: апостроф (`'ядро'`, `'ядро`), типографский апостроф (`‘ядро’`,
      `‘ядро`) и правый апостроф с обеих сторон (`’ядро’`, `’ядро` — так ставит автозамена;
      свёртка `СВЁРТКА` ни тот, ни другой не трогает), только закрывающая кавычка (`ядро"` —
      после свёртки и `ядро»`; цена — поглощает закрывающую кавычку фразы, кончающейся ядром:
      `"через мост" и` → `"через [[org:N]] и`), пробел внутри кавычек (`" ядро"`, `" ядро "`; в
      тексте пробелы схлопнуты, и ключи закрывают `« Мост»` и `« Мост »`). Ключа `" ядро` без
      закрывающей кавычки нет: после свёртки открывающая и закрывающая неразличимы, и он
      поглощал закрывающую кавычку соседней фразы вместе с голым словом после неё
      (`«Альфа» мост` → `«Альфа[[org:N]]`). Обрезанное `« Мост` без закрывающей поэтому открыто
      («Остаток Ruling 115»);
    - своя форма через точку и дефис: `<форма>. ядро`, `<форма>.ядро`, `<форма>-ядро`;
    - латинский двойник своей формы, если она целиком из букв-двойников: `ooo ядро`,
      `ooo "ядро"`, `ooo"ядро"`;
    - полная запись своей формы по `ПОЛНЫЕ_ФОРМЫ`: `<полная> ядро`, `<полная> "ядро"`.

    Расширить свёртку текста на эти виды кавычек нельзя: `СВЁРТКА` входит в HMAC токенов, а
    таблица поиска (`_СВЁРТКА_ДЛЯ_ПОИСКА`) — ещё и в ключи `add_scrubbed_name_variant` и слоя
    раскрытого; свёрнутый ими ключ разошёлся бы с `tokens.normalized`, на равенстве с которым
    стоит правило приоритета полного написания (`_ключи_названий`)."""
    варианты = [
        f"'{ядро}'",
        f"'{ядро}",
        f"‘{ядро}’",
        f"‘{ядро}",
        f"’{ядро}’",
        f"’{ядро}",
        f'{ядро}"',
        f'" {ядро}"',
        f'" {ядро} "',
    ]
    if своя:
        варианты += [f"{своя}. {ядро}", f"{своя}.{ядро}", f"{своя}-{ядро}"]
        if set(своя) <= set(_ЛАТИНСКИЕ_ДВОЙНИКИ):
            латинская = "".join(_ЛАТИНСКИЕ_ДВОЙНИКИ[буква] for буква in своя)
            варианты += [f"{латинская} {ядро}", f'{латинская} "{ядро}"', f'{латинская}"{ядро}"']
        if своя in ПОЛНЫЕ_ФОРМЫ:
            полная = ПОЛНЫЕ_ФОРМЫ[своя]
            варианты += [f"{полная} {ядро}", f'{полная} "{ядро}"']
    return варианты


def name_variants_of(value: str) -> list[str]:
    """Варианты названия для сканера: как есть, без формы собственности, а для ядра, которое голым
    искать нельзя, — узнаваемые написания.

    Ядро, которое голым искать нельзя, — это либо название целиком из цифр (`ООО "2020"`,
    `ООО "1-2-3"`, Р3-2 ревью раунда 3 блокеров M2), либо одиночное слово из одних букв («Мост»,
    «Вектор», имя «Мария», Ruling 115, 2026-09-28). Число `2020` в тексте неотличимо от обычного
    числа и закрывало бы каждое отдельно стоящее 2020 в любом тексте базы (инвариант 6); одиночное
    слово неотличимо от обычного слова того же написания и закрывало бы его в любом комментарии.
    Без ключа совсем название открылось бы во всех написаниях, кроме полного (инвариант 1, так
    вышло на правке Р2-3). Поэтому вместо голого ядра — написания, по которым видно, что это
    название:

    - `"ядро"` в кавычках — только если само ядро не короче общего минимума
      (`МИНИМАЛЬНАЯ_ДЛИНА_ВАРИАНТА`, Ruling 50): `"1"`, `"50"` в кавычках — обычная запись в
      комментариях 1С («приоритет "1"», «код "50"»), и замена её токеном организации по всем базам
      нарушала бы инвариант 6, а название из одной-трёх цифр или букв само по себе ничего не
      раскрывает. Свёртка текста приводит «ёлочки» и прочие кавычки к прямой, и один ключ закрывает
      `"2020"`, `«2020»`, `ООО"2020"`, `ООО «2020»` и полную форму собственности с кавычками (как
      подстроку). Для одиночного слова добавляется ещё ключ с одной открывающей кавычкой
      (`"мост`) — 1С обрезает строку без закрывающей «ёлочки» (`ООО «Мост` в конце строки), и
      граница слова справа не даёт ему сработать на продолжении слова (`"мостовой`);
    - `<форма> ядро`, `<форма> "ядро"`, `<форма>"ядро"` — своя форма собственности в тех видах,
      которые распознаёт `ФОРМЫ` (пробел или кавычка после формы), при любой длине ядра: с формой
      ключ однозначно название (`ооо 1`, `ооо мост`). Только своя форма: другая — скорее другое
      юрлицо, а все формы подряд были бы выдуманными написаниями. Минимум длины у этих ключей
      проверяется как у всех (короче четырёх символов ключ с формой не бывает);
    - для одиночного слова не короче минимума — ещё частые написания, которые до Ruling 115
      закрывал голый ключ: апострофы, только закрывающая кавычка, пробел внутри кавычек, своя
      форма через точку и дефис, латинский двойник и полная запись своей формы
      (`_написания_одиночного_слова`, итоговое ревью ветки, C-1). Редкие написания —
      угловые кавычки `‹›` и `<<>>`, обратный апостроф, чужая форма — ключей не получают
      («Остаток Ruling 115», SPEC §6.5).

    Ядро без формы и короче минимума (`"50"`, `1`, «Юла») ключей не получает вовсе: оно закрывается
    только в полях с классом."""
    очищенное = " ".join(value.translate(СВЁРТКА).split())
    как_есть = очищенное.lower()
    форма = ФОРМЫ.match(очищенное)
    без_формы = ФОРМЫ.sub("", очищенное).strip(' "').strip().lower()
    варианты = [как_есть]
    if без_формы and без_формы != как_есть:
        варианты.append(без_формы)
    if без_формы and (not _есть_буква(без_формы) or _голое_слово(без_формы)):
        # Ядро, которое голым искать нельзя: число (Р3-2) или одиночное слово (Ruling 115). Из
        # прежних ключей остаются только написания, по которым видно название.
        варианты = [
            вариант for вариант in варианты if _есть_буква(вариант) and not _голое_слово(вариант)
        ]
        if len(без_формы) >= МИНИМАЛЬНАЯ_ДЛИНА_ВАРИАНТА:
            варианты.append(f'"{без_формы}"')
            if _голое_слово(без_формы):
                # 1С обрезает строку без закрывающей кавычки: «ООО «Мост» в конце строки.
                варианты.append(f'"{без_формы}')
        своя = форма.group(1).lower() if форма else None
        if своя:
            варианты += [f"{своя} {без_формы}", f'{своя} "{без_формы}"', f'{своя}"{без_формы}"']
        if _голое_слово(без_формы) and len(без_формы) >= МИНИМАЛЬНАЯ_ДЛИНА_ВАРИАНТА:
            варианты += _написания_одиночного_слова(без_формы, своя)
    варианты = [вариант for вариант in варианты if len(вариант) >= МИНИМАЛЬНАЯ_ДЛИНА_ВАРИАНТА]
    # NUL — заглушка, которой страж и маскировщик закрывают токены и GUID перед поиском названий
    # (`tokens.blank_tokens`). Название, содержащее NUL (в данных 1С его практически не бывает, но
    # значение приходит от базы), даёт вариант из NUL, который затем совпал бы с любой заглушкой и
    # заменил бы токен/GUID «названием» из NUL (M2 ревью 2026-09-10). Такие варианты не хранятся.
    return [вариант for вариант in dict.fromkeys(варианты) if ЗАГЛУШКА_ТОКЕНА not in вариант]


_ПРОБЕЛЬНЫЙ_ПОВТОР = re.compile(r"\s+")


def _невидимые_символы() -> str:
    """Символы категории Unicode Cf («Format») — не пробел с точки зрения `str.isspace()`, но и
    не видны в тексте: мягкий перенос (U+00AD), пробелы нулевой ширины (U+200B и соседи), метки
    направления письма (U+200E/U+200F и управляющие вставки/изоляты 202A-202E, 2066-2069), BOM
    он же ZERO WIDTH NO-BREAK SPACE (U+FEFF) и подобные (ревью 2026-09-09, обход B). Категория,
    а не перечисление конкретных символов — по требованию ревью: список пришлось бы дополнять
    при каждой новой находке, категория ловит их все разом, включая те, что не пришли в голову.
    Вычисляется один раз при импорте модуля (около 170 символов во всём диапазоне Unicode)."""
    return "".join(
        chr(код) for код in range(sys.maxunicode + 1) if unicodedata.category(chr(код)) == "Cf"
    )


_НЕВИДИМЫЕ_СИМВОЛЫ = frozenset(_невидимые_символы())
# Пробел любого вида ИЛИ невидимый символ форматирования — один проход обоих случаев разом: гэп,
# целиком составленный из невидимых символов (например, между слогами внутри слова), схлопывается
# в ничто; гэп, содержащий хотя бы один настоящий пробел (в том числе вперемешку с невидимыми —
# они могли встретиться и до, и после, и внутри пробельного разрыва), схлопывается в один пробел,
# как и раньше. Раздельная обработка (сперва вырезать невидимые, потом отдельно схлопнуть пробелы)
# рисковала оставить в тексте два пробела вместо одного там, где невидимый символ раньше разделял
# два настоящих пробела, — а ключ словаря после такого разрыва не восстанавливается (та же дыра 1,
# что чинили прошлым раундом, только с другим триггером).
_ПРОБЕЛ_ИЛИ_НЕВИДИМЫЙ = re.compile(rf"[\s{re.escape(_невидимые_символы())}]+")


class _КартаПозиций:
    """Ленивое отображение индекса нормализованной строки в диапазон `[start, end)` исходной —
    без материализации отдельной записи `(start, end)` на каждый символ текста, как раньше
    (замер ревью 2026-09-09: на ответе в сто тысяч символов список из ста тысяч кортежей и
    столько же вызовов `str.lower()`/`str.isspace()` по одному символу — главная статья времени
    прохода стража, около 95% от общего). Достаточно запомнить точки, где нормализация меняет
    длину строки — схлопнутые повторы пробелов и вырезанные невидимые символы, — а обычный (не
    схлопнутый) символ пересчитывается арифметикой по накопленному сдвигу перед ближайшей
    предыдущей такой точкой, без явного перебора: количество точек равно числу пробельных и
    невидимых пропусков в тексте, а не числу символов.

    Два вида точек различаются тем, занимают ли они позицию в НОРМАЛИЗОВАННОЙ строке: пробельный
    повтор занимает — он схлопывается в один пробел, и запрос именно этой позиции обязан вернуть
    диапазон всего повтора целиком (`тип == "space"`, точное совпадение позиций — особый случай).
    Невидимый повтор не оставляет по себе никакого символа вовсе — автомат никогда не сможет
    спросить его позицию напрямую (там просто нечему быть найденным), только позиции ПОСЛЕ него
    (`тип == "invisible"`, сдвиг без особого случая)."""

    __slots__ = ("_позиции", "_начала", "_концы", "_типы", "_длина")

    def __init__(self, события: list[tuple[int, int, int, str]], длина: int) -> None:
        # события — по одной записи (норм_позиция, ориг_начало, ориг_конец, тип) на каждый
        # схлопнутый/вырезанный повтор, по возрастанию норм_позиции (порядок гарантирован
        # построением — события находятся проходом слева направо по regex-совпадениям).
        self._позиции = [норм_позиция for норм_позиция, _, _, _ in события]
        self._начала = [ориг_начало for _, ориг_начало, _, _ in события]
        self._концы = [ориг_конец for _, _, ориг_конец, _ in события]
        self._типы = [тип for _, _, _, тип in события]
        self._длина = длина

    def __len__(self) -> int:
        return self._длина

    def __getitem__(self, норм_индекс: int) -> tuple[int, int]:
        i = bisect.bisect_right(self._позиции, норм_индекс) - 1
        if i < 0:
            return (норм_индекс, норм_индекс + 1)
        событие_поз = self._позиции[i]
        конец = self._концы[i]
        if self._типы[i] == "space":
            if норм_индекс == событие_поз:
                return (self._начала[i], конец)
            сдвиг = конец - событие_поз - 1
        else:  # "invisible" — не занимает позицию в нормализованной строке вообще
            сдвиг = конец - событие_поз
        return (норм_индекс + сдвиг, норм_индекс + сдвиг + 1)


def normalize_text_with_map(текст: str) -> tuple[str, _КартаПозиций | list[tuple[int, int]]]:
    """Нормализация произвольного текста для поиска автоматом Aho-Corasick по известным
    названиям (SPEC §6.5, слой 3; §6.8 — страж), с картой позиций к исходной строке.

    Ключи автомата (варианты названий, `name_variants_of` выше) нормализованы: кавычки любого
    вида приведены к прямой, «ё» — к «е» (`СВЁРТКА`, SPEC §6.3, поправка 2026-09-10), пробелы
    любого вида схлопнуты в один, регистр — к нижнему. Текст
    ответа до правки (ревью 2026-09-09, дыры 1 и 2) сверялся с этими ключами КАК ЕСТЬ — двойной
    пробел, неразрывный пробел (U+00A0) или кавычки-ёлочки внутри названия не совпадали ни с
    одним ключом, хотя написание то же самое; полное `текст.lower()` для регистра само по себе
    другая дыра — символ, у которого нижний регистр разворачивается в несколько знаков (например,
    `İ`, U+0130 → «i» плюс комбинирующая точка), сдвигает длину строки и вместе с ней — индексы
    совпадений автомата относительно исходной строки. Ещё одна дыра того же раунда, найденная
    позже (обход B): невидимые символы форматирования (мягкий перенос, пробел нулевой ширины,
    метки направления письма — обычный мусор при копировании названия организации с веб-страницы
    в комментарий 1С) не пробел ни для `str.isspace()`, ни для ключей словаря, поэтому ни
    схлопывание, ни автомат их не замечали — название «Р<ZWSP>омашка» не совпадало с ключом
    «ромашка».

    Возвращает нормализованную строку и объект, отвечающий на `карта[индекс]` парой
    `(начало, конец)` в исходной строке — для каждого индекса нормализованной строки диапазон
    символов исходной, из которых он получен (интерфейс — как у списка кортежей, вызывающему
    коду, guard.py/masking.py, не важно, список это или ленивая карта). Схлопнутый повтор
    пробелов отображается в диапазон, охватывающий весь повтор целиком, а не один из его
    символов, — поэтому совпадение автомата, зацепившее такую позицию, при обратном отображении
    в исходную строку забирает весь повтор, а не часть его. Невидимый повтор без единого
    настоящего пробела внутри вырезается целиком — в нормализованной строке для него вообще нет
    символа, а следующий за ним обычный символ просто продолжает счёт с учётом сдвига.

    Быстрый путь (подавляющее большинство текста: не содержит символов, у которых `str.lower()`
    разворачивается в несколько знаков) строит карту через `_КартаПозиций` — регулярным
    выражением по пробельным/невидимым повторам (реализация на C), без цикла по символам на
    Python. Медленный путь — посимвольный, как раньше, с откатом к исходному символу там, где
    нижний регистр разворачивается в несколько знаков; используется только когда такой символ в
    тексте действительно есть (проверяется одним сравнением длин, тоже без цикла на Python) — для
    защищаемых в проекте алфавитов (кириллица, латиница ASCII) это не потеря, а компромисс ценой
    того, что такие редкие символы не могут быть частью названия в словаре.
    """
    приведённый = текст.translate(_СВЁРТКА_ДЛЯ_ПОИСКА)
    нижний = приведённый.lower()
    if len(нижний) == len(приведённый):
        # Проверка множеством (C-уровень, доли миллисекунды даже на сто тысяч символов) —
        # есть ли в тексте вообще хоть один невидимый символ — быстрее, чем сканирование regex-ом
        # с расширенным классом на весь текст: замер (ревью 2026-09-09, третий раунд) — большой
        # рассеянный по кодовым точкам класс (~170 символов формата) почти в десять раз медленнее
        # простого `\s+` при сканировании текста, где совпадений класса нет вовсе (обычный текст
        # без невидимых символов — подавляющее большинство ответов). Регэксп с расширенным классом
        # используется только тогда, когда невидимые символы в тексте действительно есть.
        поиск = _ПРОБЕЛ_ИЛИ_НЕВИДИМЫЙ if set(нижний) & _НЕВИДИМЫЕ_СИМВОЛЫ else _ПРОБЕЛЬНЫЙ_ПОВТОР
        # Сдвиг — чистая арифметика по границам regex-совпадения (`начало`, `конец`), без
        # вычисления длины уже собранного вывода на каждом шаге (та же экономия, что и до этой
        # правки, распространённая на два вида точек вместо одного): нормализованная позиция
        # события — это позиция начала повтора в исходном тексте минус сдвиг, накопленный
        # ПРЕДЫДУЩИМИ повторами, а собственный вклад повтора в сдвиг зависит только от того, есть
        # ли внутри настоящий пробел (see `_КартаПозиций`). Совпадение `_ПРОБЕЛЬНЫЙ_ПОВТОР` всегда
        # состоит из настоящих пробелов, поэтому `содержит_пробел` ниже для него всегда истинно —
        # ветка "invisible" для него просто никогда не срабатывает, код общий для обоих regex.
        события: list[tuple[int, int, int, str]] = []
        куски: list[str] = []
        позиция = 0
        сдвиг = 0
        for совпадение in поиск.finditer(нижний):
            начало, конец = совпадение.span()
            куски.append(нижний[позиция:начало])
            содержит_пробел = any(символ.isspace() for символ in совпадение.group())
            норм_поз = начало - сдвиг
            if содержит_пробел:
                события.append((норм_поз, начало, конец, "space"))
                сдвиг += (конец - начало) - 1
                куски.append(" ")
            else:
                события.append((норм_поз, начало, конец, "invisible"))
                сдвиг += конец - начало
            позиция = конец
        куски.append(нижний[позиция:])
        нормализовано = "".join(куски)
        return нормализовано, _КартаПозиций(события, len(нормализовано))

    нормализовано_части: list[str] = []
    карта_список: list[tuple[int, int]] = []
    n = len(приведённый)
    i = 0
    while i < n:
        символ = приведённый[i]
        if символ.isspace() or символ in _НЕВИДИМЫЕ_СИМВОЛЫ:
            начало = i
            содержит_пробел = символ.isspace()
            i += 1
            while i < n and (приведённый[i].isspace() or приведённый[i] in _НЕВИДИМЫЕ_СИМВОЛЫ):
                if приведённый[i].isspace():
                    содержит_пробел = True
                i += 1
            if содержит_пробел:
                нормализовано_части.append(" ")
                карта_список.append((начало, i))
            continue
        ниж = символ.lower()
        if len(ниж) != 1:
            ниж = символ
        нормализовано_части.append(ниж)
        карта_список.append((i, i + 1))
        i += 1
    return "".join(нормализовано_части), карта_список


def _след_токена(тип: str, написание: str) -> bool:
    """Написание — след двойной маскировки, то есть признак мусорного токена (`Dictionary.
    _порождённые_токенами`): в нём стоит целый токен шлюза, а у цифрового класса вдобавок ВНЕ
    токенов нет ни одной цифры (Б-5, находка M-3 ревью 6).

    Почему у цифровых классов оговорка. Их нормализация оставляет от строки одни цифры, и цифры
    соседнего значения неотличимы от цифр хвоста токена: `7707083893 [[inn:ABCDEFGHJK]]` (хвост
    без цифр) сводится к настоящему ИНН. Без оговорки такой токен объявлялся мусором и выпадал из
    цифрового слоя стража — и настоящий ИНН, встреченный только рядом с вписанным токеном, выходил
    по свободному тексту открытым. Цифры вне токенов могли прийти только из самого значения —
    значит, это не след, и токен остаётся в поиске. Если же все цифры — из хвостов токенов, это
    ровно находка П2 (цифры хвоста, принятые за значение), и признак срабатывает, как прежде.

    У остальных классов (названия, адреса) — прежний признак «в написании стоит токен»: цифр их
    нормализация не выделяет, и спутать нечего."""
    if not TOKEN_RE.search(написание):
        return False
    if тип in ТОЛЬКО_ЦИФРЫ:
        return not any(символ.isdigit() for символ in TOKEN_RE.sub("", написание))
    return True


# Ruling 49: написания, которые путь не-данных записал до Ruling 48, — `(entity, field)` его
# записей. Путь был один за всю историю: `BaseGate.error` → `Masker.mask_text(entity="",
# field="error")` → `token_for` (сообщение и подсказка отказа, эхо значения модели или 1С). Строки
# в файле остаются — файл владельца не трогаем, миграции нет; шлюз их не учитывает НИГДЕ, как
# будто их нет, и отсекает при чтении `variants` одним условием (`_ИЗ_ДАННЫХ`). Иначе второе
# написание из эха делало запись токеном `token_ambiguous` (B4), попадало в `or` отбора, а токен,
# известный только из эха, раскрывался и держал номер документа в множестве стража (B2).
_ПУТЬ_НЕ_ДАННЫХ: tuple[tuple[str, str], ...] = (("", "error"),)


# SQL-условие «строка `variants` — написание из данных 1С». Значения — константы модуля, не ввод:
# подстановка в текст запроса безопасна.
_ИЗ_ДАННЫХ = " AND ".join(
    f"NOT (entity = '{сущность}' AND field = '{поле}')" for сущность, поле in _ПУТЬ_НЕ_ДАННЫХ
)


class DictionaryCorruptError(Exception):
    """Файл словаря — не SQLite-база или повреждён (тот же набор атрибутов, что у OdataError,
    ConfigError и IndexCorruptError: SPEC §5.2 — code, message, hint; см.
    index/repository.py::IndexCorruptError — тот же дефект и то же решение, перенесённое сюда
    по итогам ревью, 2026-09-09)."""

    def __init__(self, path: pathlib.Path, детали: str) -> None:
        message = f"словарь гейта повреждён или недоступен: {path}"
        super().__init__(message)
        self.code = "dictionary_corrupt"
        self.message = message
        self.hint = (
            f"словарь — единственное место, где хранится связь токена со значением: "
            f"восстановить его нельзя, только начать заново. Переместите повреждённый файл "
            f"{path} в сторону и запустите ещё раз — новый словарь начнёт накапливаться с нуля, "
            f"но токены, выданные до сих пор, перестанут раскрываться ({детали})"
        )


class DictionaryBusyError(Exception):
    """Словарь занят другим процессом или временно недоступен на чтение-запись (Р4-3 ревью
    раунда 4 блокеров M2). Прежде это тоже был `dictionary_corrupt` — с советом переместить файл в
    сторону, то есть потерять все выданные токены, хотя с файлом всё в порядке: чужая пишущая
    транзакция (второй процесс шлюза, перестройка словаря при открытии, CLI `reveal`) держит его
    дольше, чем открытие ждёт блокировку. Протокол атрибутов тот же (code, message, hint)."""

    def __init__(self, path: pathlib.Path, детали: str) -> None:
        message = f"словарь гейта занят другим процессом или временно недоступен: {path}"
        super().__init__(message)
        self.code = "dictionary_busy"
        self.message = message
        self.hint = (
            "файл не повреждён и трогать его не нужно: повторите; если не проходит — проверьте, "
            "не работает ли второй процесс шлюза (демон, `odata1c reveal`, `reindex`) с тем же "
            f"домашним каталогом, и нет ли ошибок диска ({детали})"
        )


# Сколько открытие словаря ждёт чужую блокировку, секунд (умолчание `sqlite3.connect`). Имя —
# чтобы тест занятого словаря не ждал по-настоящему.
ОЖИДАНИЕ_БЛОКИРОВКИ = 5.0
# Коды SQLite, при которых файл цел, а словарь занят или диск временно не ответил: повторить.
_ЗАНЯТ = ("SQLITE_BUSY", "SQLITE_LOCKED", "SQLITE_IOERR")


def _словарь_занят(ошибка: sqlite3.DatabaseError) -> bool:
    """Занят (или ошибка ввода-вывода), а не повреждён: по коду ошибки SQLite
    (`sqlite_errorname`, в том числе расширенному — `SQLITE_BUSY_SNAPSHOT`, `SQLITE_IOERR_READ`).
    Без кода — по тексту сообщения, тем же признакам."""
    имя = getattr(ошибка, "sqlite_errorname", "") or ""
    if имя:
        return имя.startswith(_ЗАНЯТ)
    текст = str(ошибка).lower()
    return "locked" in текст or "busy" in текст or "disk i/o" in текст


class Dictionary:
    def __init__(self, path: pathlib.Path, secret: bytes) -> None:
        self.path = pathlib.Path(path)
        self._secret = secret
        self.path.parent.mkdir(parents=True, exist_ok=True)
        # Управление транзакциями — штатное (isolation_level по умолчанию, без ручного
        # autocommit), как в index/schema.py: connect(). В отключённом режиме
        # (isolation_level=None) `with соединение:` по всему хранилищу выглядит как транзакция,
        # но ею не является — каждая запись фиксируется отдельно и при WAL это обращение к диску
        # на каждую вставку (см. пояснение в schema.py: ~40 мс на запись вместо долей мс).
        # Для словаря это критично вдвойне: он пишется на каждом ответе базы и единственный
        # хранит связь токена со значением — потеря половины записи при сбое посреди неё
        # означает токены, которые невозможно раскрыть. При штатном управлении первая же
        # DML-команда открывает транзакцию неявно, и `with self._connection:` в _создать()
        # и _запомнить_вариант() действительно фиксирует или откатывает её целиком.
        self._connection = sqlite3.connect(self.path, timeout=ОЖИДАНИЕ_БЛОКИРОВКИ)
        self._connection.row_factory = sqlite3.Row
        # Если файл существует, но не является SQLite-базой (или повреждён), sqlite3 узнаёт об
        # этом не на connect(), а только на первой операции — здесь на PRAGMA/executescript.
        # Соединение к этому моменту уже открыто и держит файловый дескриптор; не закрыв его
        # перед тем, как исключение уйдёт наверх, получаем недостижимый, но не закрытый
        # sqlite3.Connection — на сборке мусора ResourceWarning (в тестах — ошибка сессии
        # pytest, см. filterwarnings=["error"]). Решение и формулировка — по образцу
        # index/schema.py::connect() + index/repository.py::IndexRepository.__init__ (тот же
        # дефект уже находили и чинили там; перенесено сюда по итогам ревью, 2026-09-09).
        try:
            self._connection.execute("PRAGMA journal_mode=WAL")
            self._connection.execute("PRAGMA foreign_keys=ON")
            # synchronous=NORMAL при журнале WAL — штатная и безопасная комбинация (документация
            # SQLite): повреждения базы она не допускает, checkpoint всё равно синхронизируется
            # полностью. Риск ограничен потерей нескольких последних зафиксированных транзакций
            # при внезапном отказе ОС или питания (не при обычном сбое процесса — commit
            # остаётся atomic). Для словаря этот риск приемлем, а не просто дешевле: токены
            # реквизитов (ИНН, счета, телефоны) вычисляются из значения и секретного ключа, а не
            # читаются из словаря — потерянная запись сама восстановится при следующей встрече
            # того же значения. Токены названий и ФИО при потере получат новые порядковые
            # номера — старые перестанут раскрываться в уже закрытых чатах, но это неудобство
            # истории переписки, а не потеря данных базы. Против этого — цена полной
            # синхронизации на каждом ответе 1С, которую иначе платил бы каждый запрос модели
            # (решение координатора, 2026-09-09).
            self._connection.execute("PRAGMA synchronous=NORMAL")
            self._connection.executescript(СХЕМА)
            # Внутри того же try: сбой пересчёта обязан закрыть соединение так же, как сбой
            # открытия (см. комментарий выше).
            self._перестроить_ключ_написаний()
            self._пересчитать_названия()
        except sqlite3.DatabaseError as ошибка:
            self._connection.close()
            # Занят — не повреждён (Р4-3): совет «переместите в сторону» стоил бы всех токенов.
            if _словарь_занят(ошибка):
                raise DictionaryBusyError(self.path, str(ошибка)) from ошибка
            raise DictionaryCorruptError(self.path, str(ошибка)) from ошибка
        self._revision = self._count()
        # Кэш `_мусорные_токены` на ревизию словаря (находки П2 и П1).
        self._мусор: set[str] = set()
        self._мусор_ревизия = -1

    def _перестроить_ключ_написаний(self) -> None:
        """Однократная перестройка таблицы `variants` словаря, заведённого до сущности в ключе
        (Р3-1, раунд 4 блокеров M2). SQLite не меняет первичный ключ на месте — таблица
        переписывается целиком в одной транзакции: новая таблица, копия строк, старая удаляется,
        новая получает её имя, индексы строятся заново. Строки и их `seen_at` сохраняются как
        есть; написания, которые прежний ключ потерял во второй сущности, лягут при следующей
        встрече значения. Признак — сам ключ таблицы (`PRAGMA table_info`), а не версия: проверка
        одна и та же при любом пути, которым словарь дошёл до этой версии."""
        ключ = {
            строка["name"]
            for строка in self._connection.execute("PRAGMA table_info(variants)").fetchall()
            if строка["pk"]
        }
        if "entity" in ключ:
            return
        try:
            self._connection.executescript(
                """
                BEGIN;
                CREATE TABLE variants_new (
                    token TEXT NOT NULL REFERENCES tokens(token) ON DELETE CASCADE,
                    base TEXT NOT NULL,
                    entity TEXT NOT NULL,
                    field TEXT NOT NULL,
                    raw_value TEXT NOT NULL,
                    seen_at TEXT NOT NULL,
                    PRIMARY KEY (token, base, entity, field, raw_value)
                );
                INSERT INTO variants_new (token, base, entity, field, raw_value, seen_at)
                    SELECT token, base, entity, field, raw_value, seen_at FROM variants;
                DROP TABLE variants;
                ALTER TABLE variants_new RENAME TO variants;
                CREATE INDEX idx_variants_lookup ON variants(token, base, field);
                CREATE INDEX idx_variants_field ON variants(base, entity, field);
                COMMIT;
                """
            )
        except sqlite3.DatabaseError:
            if self._connection.in_transaction:
                self._connection.rollback()
            raise

    def _пересчитать_названия(self) -> None:
        """Однократный пересчёт названий словаря, записанного прежней версией: до свёртки кавычек
        и «ё» (SPEC §6.3, поправка ¹⁰), до ключей названия без букв (`name_variants_of`, Р3-2
        раунда 4 блокеров M2: голое ядро `2020` снимается, ядро в кавычках и с формой собственности
        добавляются) и до ключей одиночного слова (Ruling 115: голое `мост` снимается, ключи в
        кавычках и со своей формой собственности добавляются). Признак пройденного пересчёта —
        `PRAGMA user_version` (см. `ВЕРСИЯ_СХЕМЫ`):
        любое изменение правила вариантов поднимает версию, и варианты всех названий строятся
        заново тем же `name_variants_of`, что при выдаче токена.

        Почему пересчёт при открытии, а не сверка по свёрнутой форме при поиске. Нормализованы и
        хранятся два ключа: `tokens.normalized` (по нему `token_for` находит токен) и
        `name_variants.variant_norm` (ключи автомата стража и слоя 3). Сверка при поиске
        потребовала бы свёртки внутри SQL-условия `token_for` — полный перебор записей класса
        вместо уникального индекса на каждой выдаче токена — и всё равно оставила бы двойников:
        одно название, записанное прежней версией дважды (через «ё» и «е» или ёлочки и прямые
        кавычки), это два токена, чьи свёрнутые варианты совпадают и становятся неоднозначными —
        страж перестал бы заменять оба написания. Пересчёт решает это один раз и в одной
        транзакции.

        Делается на Python (а не SQL с `replace`) — та же таблица `СВЁРТКА`, что у `normalize_value`
        и `name_variants_of`, без риска, что нанизанные `replace` в SQL разойдутся с ней при
        следующем символе. Двойники: если свёрнутое `normalized` уже занято другим токеном —
        текущий токен остаётся с прежним `normalized` и без вариантов (в подмене не участвует, но
        `variants` и сам токен не трогаются: раскрытие в старых чатах работает). Уцелевший токен
        получает варианты, пересчитанные от свёрнутого `normalized`. Для словаря, созданного этой
        версией, пересчёт — пустой проход.

        Кроме версии — пересчёт по содержимому (Р4-2 ревью раунда 4): если прежняя версия шлюза
        дописала название без букв уже ПОСЛЕ пересчёта (дом, где работали две версии кода), в
        таблице лежит голое безбуквенное ядро, а ключей в кавычках и с формой у названия нет —
        версия уже текущая, и без этой проверки они не появились бы никогда. Такие токены
        (`_токены_с_устаревшими_ключами`) пересчитываются при каждом открытии, где они есть.

        Та же страховка защищает от голого одиночного слова (Ruling 115): демон плагина 0.2.x
        и демон рабочей копии поочерёдно открывают один `gate.sqlite`, старый код пересчёт по
        версии пропускает и пишет новым токенам голый ключ уже при `user_version` 4 —
        `_токены_с_устаревшими_ключами` находит и его."""
        if self._connection.execute("PRAGMA user_version").fetchone()[0] >= ВЕРСИЯ_СХЕМЫ:
            устаревшие = self._токены_с_устаревшими_ключами()
            if устаревшие:
                with self._connection:
                    for токен, нормализованное in устаревшие:
                        self._connection.execute(
                            "DELETE FROM name_variants WHERE token = ?", (токен,)
                        )
                        self._connection.executemany(
                            "INSERT OR IGNORE INTO name_variants (token, variant_norm)"
                            " VALUES (?, ?)",
                            [(токен, вариант) for вариант in name_variants_of(нормализованное)],
                        )
            return
        with self._connection:
            строки = self._connection.execute(
                "SELECT token, type, normalized FROM tokens WHERE type IN ('org', 'person')"
            ).fetchall()
            for строка in строки:
                токен, тип, старое = строка["token"], строка["type"], строка["normalized"]
                новое = старое.translate(СВЁРТКА)
                # Варианты токена пересчитываются заново от свёрнутого значения — снимаем старые.
                self._connection.execute("DELETE FROM name_variants WHERE token = ?", (токен,))
                if новое != старое:
                    занято = self._connection.execute(
                        "SELECT 1 FROM tokens WHERE type = ? AND normalized = ? AND token <> ?",
                        (тип, новое, токен),
                    ).fetchone()
                    if занято:
                        continue  # двойник: остаётся с прежним normalized, без вариантов
                    self._connection.execute(
                        "UPDATE tokens SET normalized = ? WHERE token = ?", (новое, токен)
                    )
                    старое = новое
                self._connection.executemany(
                    "INSERT OR IGNORE INTO name_variants (token, variant_norm) VALUES (?, ?)",
                    [(токен, вариант) for вариант in name_variants_of(старое)],
                )
            self._connection.execute(f"PRAGMA user_version = {ВЕРСИЯ_СХЕМЫ}")

    def _токены_с_устаревшими_ключами(self) -> list[tuple[str, str]]:
        """Токены названий, у которых в `name_variants` есть ключ, не годный для поиска
        (`_годится_в_поиск`): голое безбуквенное ядро (так пишет версия до раунда 4), ядро короче
        минимума в кавычках (промежуточная версия раунда 4) или голое одиночное слово (так пишет
        версия до Ruling 115). Признак записи прежней версией после пересчёта (Р4-2). Кандидаты
        отбираются в SQL двумя условиями (дёшево на каждом открытии, точная проверка — здесь):
        ключ вовсе без буквы кириллицы или латиницы (безбуквенное ядро) или ключ из одних таких
        букв без единого иного символа (кандидат в голое одиночное слово — SQL-класс символов
        ограничен двумя алфавитами, в отличие от `ОДИНОЧНОЕ_СЛОВО`, который средствами Python
        распознаёт букву любой письменности). Слово из букв другой письменности (например,
        греческой) этот SQL-отбор не найдёт и как кандидата не предложит — но такой ключ отсекает
        при чтении `_ключи_названий` (там проверка через `_голое_слово`, а не через SQL), так что
        в подмену он не уходит; пересборка здесь для него просто не срабатывает, и он остаётся в
        таблице неиспользуемым — это записано и в докстринге `name_variants`. Слово из кириллицы
        и латиницы вперемешку (`техноnikol`, находка I-1 итогового ревью) SQL-отбор кандидатом
        предлагает, но `_голое_слово` его не считает голым — это обычный ключ текущей версии, и
        пересборки при каждом открытии он не вызывает. Ключи одиночного слова текущей версии
        (`_написания_одиночного_слова`) под отбор не попадают вовсе: в каждом есть буква и знак
        кроме буквы. Возвращает токен и его `normalized`, от которого варианты строятся
        заново."""
        кандидаты = self._connection.execute(
            "SELECT DISTINCT nv.token, nv.variant_norm, t.normalized FROM name_variants nv"
            " JOIN tokens t ON t.token = nv.token"
            " WHERE nv.variant_norm NOT GLOB '*[a-zA-Zа-яА-ЯёЁ]*'"
            " OR nv.variant_norm NOT GLOB '*[^a-zA-Zа-яА-ЯёЁ]*'"
        ).fetchall()
        return list(
            dict.fromkeys(
                (строка["token"], строка["normalized"])
                for строка in кандидаты
                if not _годится_в_поиск(строка["variant_norm"])
                or _голое_слово(строка["variant_norm"])
            )
        )

    def close(self) -> None:
        self._connection.close()

    def revision(self) -> int:
        return self._revision

    def token_for(
        self,
        type_: str,
        raw_value: str,
        *,
        base: str,
        entity: str,
        field: str,
        source: str | None = None,
        persist: bool = True,
    ) -> str:
        """Токен значения поля объявленного класса (SPEC §6.3).

        `persist=False` — токен без записи (Ruling 48): текст ошибки или отказа не данные 1С, и
        словарь из него не пополняется — ни новым значением, ни новым написанием известного
        (второе написание делает запись токеном `token_ambiguous`, B4 ревью задачи 5 M2).
        Известное значение получает свой токен. Новое — тот токен, что запись выдала бы в этот
        момент: расчёт тот же (`_свободный_токен`, занятость хвоста проверяется только чтением),
        поэтому форма одна. Токен не бронируется: если позже словарь запишет другое значение с
        тем же 10-символьным хвостом (коллизия HMAC), это значение возьмёт короткий хвост, а
        прежний сухой токен станет означать его; без записи такой токен не раскрывается, и
        отбор по нему даёт `token_unknown`. Номер названия (`org`, `person`) без вставки не
        выдать — следующий номер получило бы и другое значение; на пути текста ошибки названий
        нет (детекторы их не ищут, известные названия заменяет автомат без `token_for`), и
        новое название здесь — `ValueError`, а не выдуманный токен.

        Ruling 20, пункт 4 (C3 ревью 2026-09-11): пустое нормализованное значение — НЕ повод
        отдать исходное. `normalize_value` для «только цифровых» классов оставляет от значения
        одни цифры, а поле класса `doc` (`КемВыдан` — «ОУФМС России по гор. Москве…») сплошь и
        рядом свободный текст без единой цифры: нормализованное пустое, значение возвращалось
        КАК ЕСТЬ, и при этом поле числилось в `masked_fields`. Ответ говорил «замаскировано», а
        реальное значение стояло в нём открытым — хуже эха из ошибки, потому что хватает одного
        обычного `odata1c_query`.

        Решение: токен строится по СЫРОМУ значению (свёрнутому по пробелам), а не заглушкой.
        Заглушка необратима — обратная подмена вернула бы не то, что лежит в базе, и отбор по
        такому полю сломался бы, — а инвариант 5 требует детерминированного токена, который
        `reveal` умеет развернуть обратно. Единственный случай, когда возвращается исходная
        строка, — когда в ней нет ничего, кроме пробелов: защищать там нечего, и токен на пустоту
        только засорил бы словарь. Вызывающий (`masking._обработать_строку`) обязан считать поле
        замаскированным ПО ФАКТУ замены, а не до неё.

        `source` — строка, по которой строится нормализованное значение (и значит, токен), если
        она не совпадает с содержимым поля (Ruling 33): поле `Значение` контактной информации —
        JSON, а токен ему положен тот же, что `Представление` той же строки, поэтому основой
        служит представление значения из JSON (`contact_info.representation`). Написание при
        этом запоминается ИСХОДНОЕ (`raw_value`): обратная подмена токена в этом поле обязана
        вернуть то, что в поле лежит, — JSON целиком, а не текст из него.
        """
        основа = source if source is not None and source.strip() else raw_value
        нормализованное = normalize_value(type_, основа)
        if not нормализованное:
            нормализованное = " ".join(основа.split())
        if not нормализованное:
            нормализованное = " ".join(raw_value.split())
        if not нормализованное:
            return raw_value

        строка = self._connection.execute(
            "SELECT token FROM tokens WHERE type = ? AND normalized = ?",
            (type_, нормализованное),
        ).fetchone()
        if not persist:
            if строка is not None:
                return строка["token"]
            if type_ in НУМЕРУЕМЫЕ:
                raise ValueError(f"токен нового значения класса {type_} без записи не выдаётся")
            return self._свободный_токен(type_, нормализованное)
        новое_значение = строка is None
        # Одна транзакция на всю выдачу токена: запись о токене (_создать) и вариант написания
        # (_запомнить_вариант) фиксируются вместе одним commit'ом, а не двумя раздельными. Вариант
        # написания без самой записи о токене бессмыслен, а половинчатое состояние между двумя
        # отдельными фиксациями — ровно то, от чего уходили штатным управлением транзакциями
        # (см. комментарий в __init__): при сбое посреди пары commit'ов возможен был токен без
        # варианта или (при повторном INSERT) конфликт уникальности. При исключении внутри блока
        # `with` откатывается вся пара разом. Побочный эффект — тот же прирост скорости, что и
        # у корректности: один fsync на новое значение вместо двух (решение координатора,
        # 2026-09-09, по итогам замера в задаче 4).
        with self._connection:
            токен = (
                строка["token"]
                if строка
                else self._создать(type_, нормализованное, base, entity, field)
            )
            self._запомнить_вариант(токен, base, entity, field, raw_value)
        if новое_значение:
            self._revision += 1
        return токен

    def reveal(
        self, token: str, *, base: str | None = None, field: str | None = None
    ) -> str | None:
        строка = self._connection.execute(
            "SELECT normalized FROM tokens WHERE token = ?", (token,)
        ).fetchone()
        if строка is None or self._только_не_данные(token):
            return None
        if base and field:
            вариант = self._connection.execute(
                "SELECT raw_value FROM variants WHERE token = ? AND base = ? AND field = ?"
                f" AND {_ИЗ_ДАННЫХ} ORDER BY seen_at DESC LIMIT 1",
                (token, base, field),
            ).fetchone()
            if вариант:
                return вариант["raw_value"]
        return строка["normalized"]

    def _только_не_данные(self, token: str) -> bool:
        """Все написания токена — с пути не-данных (Ruling 49): токен ведёт себя как неизвестный,
        как токен эха по Ruling 48, которого словарь не записал. Токен без единого написания
        сюда не относится — у него прежнее поведение."""
        строка = self._connection.execute(
            "SELECT EXISTS(SELECT 1 FROM variants WHERE token = ?) AS есть,"
            f" EXISTS(SELECT 1 FROM variants WHERE token = ? AND {_ИЗ_ДАННЫХ}) AS из_данных",
            (token, token),
        ).fetchone()
        return bool(строка["есть"]) and not строка["из_данных"]

    def spellings(
        self, token: str, *, base: str | None = None, field: str | None = None
    ) -> list[str]:
        """Все сохранённые написания значения токена (Б-1, ревью 7) — для базы и имени поля, если
        они заданы, иначе по всему словарю. Без повторов (одно написание в двух базах — одно) и в
        постоянном порядке (по строке, а не по времени встречи): отбор по токену обязан уходить в
        1С одним и тем же текстом, иначе один вопрос давал бы разные запросы.

        Зачем, если есть `reveal`. `reveal` отдаёт ОДНО написание — самое свежее. Одно значение
        бывает записано по-разному (ИНН с пробелом и без, название в «ёлочках» и в прямых
        кавычках, краевой пробел), а 1С сравнивает строки точно: отбор по одному написанию не
        находит записей с другим, запись одного написания вместо другого меняет данные так, что
        превью на токенах этого не покажет. Решение — у вызывающего (`Unmasker`): отбор ищет все,
        запись без однозначного кандидата отказывает.

        Не считается написанием строка, в которой стоит токен шлюза, если в самом значении токена
        его нет: это след раннего прохода до правки П2 (такие строки лежат в словарях, заведённых
        раньше), в 1С такой строки нет — ни искать, ни записывать её нельзя."""
        строка = self._connection.execute(
            "SELECT normalized FROM tokens WHERE token = ?", (token,)
        ).fetchone()
        if строка is None:
            return []
        условия, параметры = ["token = ?", _ИЗ_ДАННЫХ], [token]
        if base is not None:
            условия.append("base = ?")
            параметры.append(base)
        if field is not None:
            условия.append("field = ?")
            параметры.append(field)
        написания = sorted(
            {
                вариант["raw_value"]
                for вариант in self._connection.execute(
                    f"SELECT raw_value FROM variants WHERE {' AND '.join(условия)}", параметры
                )
            }
        )
        if TOKEN_RE.search(строка["normalized"]):
            return написания
        return [написание for написание in написания if not TOKEN_RE.search(написание)]

    def structured_field(self, *, base: str, entity: str, field: str) -> bool:
        """Видел ли словарь в этой базе, в этой сущности и в поле с этим именем структуру
        (`contact_info.is_structure`) ЛЮБОГО значения — признак 3 структурного поля (Ruling 43,
        `Unmasker._поле_структурное`). Признак полевой, а не потокенный: адрес, который словарь
        видел только текстом, пишется в то же поле, что и адрес, виденный структурой, — формат у
        поля один.

        Ключ — база, сущность и имя поля (Р3-1 ревью раунда 3, раунд 4 блокеров M2). Прежде
        сущности в ключе не было, и одноимённое поле другой сущности засчитывалось: структура,
        прочитанная в `ЗаявкаНаВыпускКиЗГИСМ.АдресДоставки`, делала структурным текстовое
        `ЗаказКлиента.АдресДоставки` по всей базе и навсегда — одно значение уходило в 1С JSON-ом
        чужой строки, рабочий отбор и запись адреса в заказ отказывали. `entity` — сущность, в
        которую приходит путь (у строки табличной части — сама табличная часть): так же её
        записывает маскировщик (`variants.entity`). Кандидаты отбираются в SQL по первому
        значащему символу (`{` или `<`), содержимое проверяется уже здесь — у текстового поля с
        тысячами написаний разбирать нечего.

        Структурой засчитывается написание, которое структура и для своего токена
        (`structure_of`): JSON без `type` в поле с классом вне контактной информации маскировщик
        кладёт в токен целиком, и для этого токена он текст, а не структура."""
        for строка in self._connection.execute(
            "SELECT v.raw_value, t.type, t.normalized FROM variants v"
            " JOIN tokens t ON t.token = v.token"
            " WHERE v.base = ? AND v.entity = ? AND v.field = ?"
            f" AND {_ИЗ_ДАННЫХ}"
            " AND substr(ltrim(v.raw_value, ' ' || char(9, 10, 13)), 1, 1) IN ('{', '<')",
            (base, entity, field),
        ):
            if _структура_для(строка["raw_value"], строка["type"], строка["normalized"]):
                return True
        return False

    def structure_of(self, token: str, text: str) -> bool:
        """Структура ли написание `text` для ЭТОГО токена — формат тем же признаком, что основа
        токена (Р2-2 и его обратная сторона). Основа зависит не только от строки, но и от места,
        где маскировщик её встретил: в строке контактной информации представление извлекается
        всегда, в поле с классом вне её — только из значения БСП с `type`
        (`Masker._класс_самоописанного_значения`). JSON `{"value": …}` без `type` из такого поля
        — токен целиком: для этого токена он текст и в текстовое поле идёт дословно, а тот же JSON
        из строки контактной информации — структура, и в текстовое поле идёт представление.
        Подробнее — `_структура_для`."""
        строка = self._connection.execute(
            "SELECT type, normalized FROM tokens WHERE token = ?", (token,)
        ).fetchone()
        if строка is None:
            return contact_info.is_structure(text)
        return _структура_для(text, строка["type"], строка["normalized"])

    def matches(self, token: str, text: str) -> bool:
        """Написание ли `text` значения этого токена: сохранённое словарём написание или строка
        с той же нормализованной формой (`normalize_value`, свёртка та же, что у `token_for`).

        Вторая половина нужна записи (`Unmasker.write`): в поле объекта значение могло лежать в
        написании, которого словарь ещё не видел (объект не читался через шлюз), — токен одного
        значения по нормализованной форме однозначен и тогда.

        Строка с токеном шлюза внутри узнаётся только дословно: цифры вписанного токена не делают
        её написанием ИНН (свёртка цифрового класса оставила бы цифры хвоста — та же ошибка, что
        у признака мусорного токена, Б-5).

        Структура контактной информации (JSON или XML БСП) сравнивается по представлению — той же
        основе, по которой `token_for(source=…)` строит её токен (Ruling 33 и Ruling 38, пункт 3):
        JSON адреса в поле заказа — написание значения, даже если словарь видел этот адрес только
        текстом или JSON другой записи с другим `comment`. Строка целиком сравнивается тоже:
        токен JSON без `type` из поля вне контактной информации построен по нему самому
        (`structure_of`)."""
        строка = self._connection.execute(
            "SELECT type, normalized FROM tokens WHERE token = ?", (token,)
        ).fetchone()
        if строка is None or self._только_не_данные(token):
            return False
        if text in self.spellings(token):
            return True
        основы = [text]
        if contact_info.is_structure(text):
            основы.append(contact_info.representation(text))
        for основа in основы:
            if TOKEN_RE.search(основа) and not TOKEN_RE.search(строка["normalized"]):
                continue
            if _свёртка(строка["type"], основа) == строка["normalized"]:
                return True
        return False

    def issued_for(self, token: str, *, base: str, field: str, entity: str | None = None) -> bool:
        """Выдавался ли ЭТОТ токен этой базой для этого поля (Ruling 19, раунд правок 1
        задачи 7 M1d).

        Класс поля входит в подпись токена (`tokens.make_token`), поэтому смена класса при
        реиндексе меняет токен того же значения: модель, получившая `[[org:1]]` десять минут
        назад, после реиндекса подставляет его в отбор и получает `token_type_mismatch` — отказ
        на токен, который выдал ей сам шлюз. Отменять проверку класса целиком нельзя: она и есть
        защита от оракула сравнения («возьму токен из поля ИНН и поперебираю им Description»).
        Поэтому послабление именное: токен работает там, где был выдан, и только там. Запись
        о выдаче — строка `variants`, её пишет `_запомнить_вариант` при каждой маскировке.

        Пункт 8 дополнения к раунду правок 1 задачи 8: ключом была пара «база и имя поля», хотя
        в `variants` есть и сущность. Имя `Description` носят поля РАЗНЫХ классов (`org` у
        контрагента, `person` у физлица) — токен названия организации принимался в поле ФИО, и
        реальное название уходило в 1С. То есть послабление снимало проверку ровно на той паре
        классов, ради разделения которых она и существует. Теперь ключ — четвёрка с сущностью;
        `entity=None` (откат на тройку) допустим только для пути через связанный объект, где
        сущность в записи о выдаче — сущность родителя и совпасть с сущностью запроса не может
        по построению.
        """
        if entity is None:
            строка = self._connection.execute(
                "SELECT 1 FROM variants WHERE token = ? AND base = ? AND field = ?"
                f" AND {_ИЗ_ДАННЫХ} LIMIT 1",
                (token, base, field),
            ).fetchone()
        else:
            строка = self._connection.execute(
                "SELECT 1 FROM variants WHERE token = ? AND base = ? AND entity = ? AND field = ?"
                f" AND {_ИЗ_ДАННЫХ} LIMIT 1",
                (token, base, entity, field),
            ).fetchone()
        return строка is not None

    def knows(self, token: str) -> bool:
        """Выдан ли этот токен словарём (находка П2 приёмки, 2026-09-12). Маскировщик по нему
        отличает уже замаскированное значение от строки 1С, которая лишь похожа на токен: первое
        не маскируется повторно, второе — обычное значение поля (в хвосте такой строки вполне
        могут стоять настоящие цифры, и пропускать её как «уже токен» нельзя).

        Токен, все написания которого — с пути не-данных (Ruling 49), словарю не известен: на
        нём обратная подмена отвечает `token_unknown`."""
        return self._connection.execute(
            "SELECT 1 FROM tokens WHERE token = ?", (token,)
        ).fetchone() is not None and not self._только_не_данные(token)

    def any_variant(self, token: str) -> str | None:
        """Любое сохранённое исходное написание токена, без выбора конкретной базы/поля.

        Для локального раскрытия владельцем базы (`odata1c reveal` без --base/--field, SPEC
        §6.3, §14.5): владелец имеет право видеть значение так, как оно записано в его данных
        («ООО «Ромашка»»), а не нормализованную форму («ооо ромашка»), даже когда не указывает,
        в какой базе и поле оно встретилось. Берётся самый свежий по времени вариант — среди
        нескольких написаний одного значения (регистр, кавычки) он ближе всего к тому, что
        владелец видел последним. `None`, если у токена вообще нет ни одного варианта в
        `variants` (сам токен при этом мог существовать в `tokens` — тогда вызывающий код
        показывает нормализованное значение как запасной вариант)."""
        строка = self._connection.execute(
            f"SELECT raw_value FROM variants WHERE token = ? AND {_ИЗ_ДАННЫХ}"
            " ORDER BY seen_at DESC LIMIT 1",
            (token,),
        ).fetchone()
        return строка["raw_value"] if строка else None

    def number_tokens(self) -> dict[str, str]:
        """Цифровые значения словаря и их токены: с этим множеством сверяется страж (SPEC §6.8).

        Значения короче формы своего класса сюда не попадают (Ruling 26, см. `searchable`): их
        поиск в чужом тексте рвёт инвариант 6, а защищает ноль — однозначный КПП в номере
        документа не значит ничего.

        Не попадают и мусорные токены (`_мусорные_токены`, находки П2 и П1).

        Только цифровые классы (`ТОЛЬКО_ЦИФРЫ`; Р4-1 ревью раунда 4 блокеров M2). Название,
        которое целиком число (организация «1406»), здесь было бы числом среди чисел: цифровой
        слой ищет сквозь разделители и внутри длинных чисел, и страж закрывал токеном организации
        дату «14.06» в назначении платежа (живьём на словаре владельца — 28 из 11 941 текста).
        Название-число закрывает слой названий — в кавычках и со своей формой собственности
        (`name_variants_of`); без них в тексте оно — число (инвариант 6, тот же размен, что
        Ruling 50)."""
        мусор = self._мусорные_токены()
        классы = ",".join("?" * len(ТОЛЬКО_ЦИФРЫ))
        return {
            строка["normalized"]: строка["token"]
            for строка in self._connection.execute(
                "SELECT normalized, token, type FROM tokens"
                f" WHERE type IN ({классы}) AND normalized GLOB '[0-9]*'",
                ТОЛЬКО_ЦИФРЫ,
            ).fetchall()
            if строка["normalized"].isdigit()
            and searchable(строка["type"], строка["normalized"])
            and строка["token"] not in мусор
        }

    def _мусорные_токены(self) -> set[str]:
        """Токены, которые словарь выдал по ошибке прежних версий, — в множества поиска стража и
        слоя названий они не попадают. Три признака, все «по ВСЕМ написаниям токена» (третий —
        написания только с пути не-данных, Ruling 49, `_порождённые_не_данными`):

        1. Написание содержит целый токен — след двойной маскировки (находка П2, подробно ниже).
        2. Токен названия (`org`/`person`), выданный значению поля-перечисления
           (`field_rules.ПЕРЕЧИСЛЕНИЯ_ТИПА_ЛИЦА`, находка П1). Пока `ЮрФизЛицо` считалось ФИО,
           члены перечисления «ЮрЛицо»/«ФизЛицо» получили токены `person` и варианты «юрлицо»/
           «физлицо». Правка классификатора поле открывает, но слой названий заменял бы эти слова
           в любой строке ответа, начиная с самого поля, — живой прогон после правки так и
           показал: `[[person:1]]` на месте. Словарь владельца в том же состоянии.

        «По всем написаниям» — не формальность: одно написание из настоящего поля (то же слово —
        и правда чьё-то название, то же число — и правда чей-то реквизит) возвращает токен в
        поиск. Выкинуть из поиска настоящее значение значило бы открыть дыру в инварианте 1.

        Результат кэшируется на ревизию словаря — ту же, по которой пересобираются страж и
        автомат названий маскировщика: оба зовут `number_tokens`/`name_variants` только при её
        смене, и держать признак свежее своих потребителей незачем."""
        if self._мусор_ревизия == self._revision:
            return self._мусор
        мусор = (
            self._порождённые_токенами()
            | self._порождённые_перечислениями()
            | self._порождённые_не_данными()
        )
        self._мусор, self._мусор_ревизия = мусор, self._revision
        return мусор

    def _порождённые_не_данными(self) -> set[str]:
        """Признак 3 `_мусорных_токенов` (Ruling 49): ВСЕ написания токена — с пути не-данных
        (эхо в тексте ошибки, записанное до Ruling 48). Такой токен словарю не известен (`knows`),
        и в множествах поиска ему не место: цифры эха держали бы номер документа токеном `inn` в
        чужих ответах (B2 повторного ревью задачи 5 M2). Написания из ошибок признаки 1 и 2 тоже
        не считают — «все написания» там только написания из данных."""
        return {
            строка["token"]
            for строка in self._connection.execute(
                "SELECT token FROM variants GROUP BY token"
                f" HAVING SUM(CASE WHEN {_ИЗ_ДАННЫХ} THEN 1 ELSE 0 END) = 0"
            )
        }

    def _порождённые_перечислениями(self) -> set[str]:
        """Признак 2 `_мусорных_токенов`. Поля берутся из тех же источников, что исключают их из
        классификации (`_поле_не_название`: член перечисления `field_rules.ПЕРЕЧИСЛЕНИЯ_ТИПА_ЛИЦА`
        или правило каталога поставки `scan`), — одно место правды, расширяется каталогом. Отбор
        кандидатов идёт по списку различных имён полей (их сотни, не тысячи), а не по всем
        написаниям."""
        поля = [
            строка["field"]
            for строка in self._connection.execute(
                f"SELECT DISTINCT field FROM variants WHERE {_ИЗ_ДАННЫХ}"
            )
            if _поле_не_название(строка["field"])
        ]
        if not поля:
            return set()
        метки = ",".join("?" * len(поля))
        кандидаты = {
            строка["token"]
            for строка in self._connection.execute(
                f"SELECT DISTINCT v.token FROM variants v JOIN tokens t ON t.token = v.token"
                f" WHERE v.field IN ({метки}) AND t.type IN ('org', 'person') AND {_ИЗ_ДАННЫХ}",
                поля,
            )
        }
        return {
            токен
            for токен in кандидаты
            if all(
                _поле_не_название(строка["field"])
                for строка in self._connection.execute(
                    f"SELECT field FROM variants WHERE token = ? AND {_ИЗ_ДАННЫХ}", (токен,)
                )
            )
        }

    def _порождённые_токенами(self) -> set[str]:
        """Признак 1 `_мусорных_токенов`: КАЖДОЕ написание токена содержит целый токен — след
        двойной маскировки (находка П2 приёмки через настоящие инструменты, 2026-09-12).

        До правки маскировщик принимал токен, подставленный ранним проходом раскрытого, за
        значение поля: у цифровых классов от него оставались цифры хвоста («6R1669KTWC» →
        «61669»), и этой «цифровой серии» выдавался свой токен. В словаре владельца такой токен
        уже есть (`[[inn:CSGNCRYVH2]]`, «ИНН длиной 5»). От поиска его отсекал только минимум длины
        класса (Ruling 26), но это совпадение, а не защита: у телефона минимум семь цифр, в хвосте
        из десяти знаков их бывает и семь, а строка с токеном внутри несёт и собственные цифры
        поля. Такая серия попала бы в множество стража и заменялась бы в номерах документов и
        датах любой базы домашнего каталога — ровно дефект Ruling 26, только с другого входа.

        Отсекается ПРИ ЧТЕНИИ, как и у Ruling 26: записи в `tokens`/`variants` не трогаются
        (`reveal` обязан работать для любого выданного токена), словари, уже набравшие мусора,
        лечатся первым же запуском без миграции и без ручной чистки. Признак строгий — не «есть
        квадратные скобки», а целый токен по грамматике (`TOKEN_RE`), и у ВСЕХ написаний: одно
        настоящее написание (то же значение пришло и из обычного поля) оставляет токен в поиске.
        Нестрогий признак выкинул бы из поиска настоящее значение — это была бы дыра в
        инварианте 1, то есть лечение хуже болезни. `LIKE` в запросе — только предварительный
        отбор кандидатов, решение принимается проверкой в Python.

        Слой названий этим признаком тоже пользуется (`name_variants`), хотя там вред меньше:
        варианты с токеном внутри совпасть с текстом не могут — страж закрывает токены в тексте
        заглушкой до поиска (`tokens.blank_tokens`). Отсекаются они для единообразия: мусорное
        название не должно числиться «известным» ни в одном множестве стража."""
        кандидаты = {
            строка["token"]: строка["type"]
            for строка in self._connection.execute(
                "SELECT DISTINCT v.token, t.type FROM variants v JOIN tokens t ON t.token = v.token"
                f" WHERE v.raw_value LIKE '%[[%' AND {_ИЗ_ДАННЫХ}"
            ).fetchall()
        }
        мусор: set[str] = set()
        for токен, тип in кандидаты.items():
            написания = [
                строка["raw_value"]
                for строка in self._connection.execute(
                    f"SELECT raw_value FROM variants WHERE token = ? AND {_ИЗ_ДАННЫХ}", (токен,)
                ).fetchall()
            ]
            if написания and all(_след_токена(тип, написание) for написание in написания):
                мусор.add(токен)
        return мусор

    def add_scrubbed_name_variant(self, token: str, text: str) -> None:
        """Ещё один вариант названия — написание, в котором ранний проход раскрытого заменил
        реквизит токеном (Ruling 99, находка C-1 ревью задачи 2 M3b).

        Случай. Модель отобрала по токену реквизита (ИНН), ранний проход (Ruling 25/32) заменил
        раскрытое значение токеном в СЫРОМ теле ответа — и внутри поля класса `org`/`person`, если
        название содержит этот реквизит (`НаименованиеПолное` = `ООО "Ромашка Плюс" ИНН
        7707083893`), и внутри свободного текста той же выборки. Маскировщик выдаёт полю токен по
        настоящему содержимому (`RevealedValues.original_of`), и словарь узнаёт написание С
        реквизитом. Но в свободном тексте на месте реквизита уже стоит токен: ни один вариант с
        таким текстом не совпадает — ни у маскировщика, ни у стража, — и название уходило
        открытым.

        Ключ — та же свёртка, какую слой поиска применяет к тексту (`overlaps.все_вхождения`):
        целые токены закрыты заглушкой той же длины (`blank_tokens`), затем общая нормализация.
        Иначе ключ не совпал бы НИКОГДА: токен в тексте до поиска заглушается, а ключ с дословным
        `[[inn:…]]` сравнивать не с чем. Ключ с заглушкой — единственное исключение из правила
        `name_variants_of` «варианты с NUL не хранятся»: там запрет был про название, СОСТОЯЩЕЕ из
        NUL (совпало бы с любым токеном или GUID и заменило бы его), здесь заглушка — хвост или
        середина длинного написания с буквами, и совпадение накрывает название вместе со стоящим
        в нём токеном. Токены детерминированы (HMAC от `gate_secret`), поэтому ключ стабилен между
        ответами.

        Условия записи (каждое — не косметика):

        - класс токена — из `НУМЕРУЕМЫЕ`: слой названий работает только с `org`/`person`, токену
          реквизита или `lit` вариант названия не положен;
        - в ключе есть заглушка: обычное написание кладёт `_создать` через `name_variants_of`, и
          дублировать его здесь незачем;
        - в написании нет GUID (C-1 ревью задачи 3): `blank_tokens` закрывает заглушкой не только
          токены, но и GUID, и ключ с прогоном из 36 заглушек совпал бы с ЛЮБЫМ `Ref_Key` в том же
          обрамлении — ровно та дыра, которую закрывала гарантия I2 (ревью 2026-09-10). Признак —
          сравнение двух свёрток: с заглушками GUID и без них;
        - самый длинный ЛИТЕРАЛЬНЫЙ отрезок ключа (кусок между заглушками) годится в поиск
          (`_годится_в_поиск`) и не короче минимума (C-1 ревью задачи 3). Мерить длину всего ключа
          бесполезно: сам прогон заглушек длиннее минимума всегда (`[[org:1]]` — 9 символов, токен
          реквизита — 18), и единственным заслоном оставалась одна буква в любом месте. Тогда поле
          класса, от написания которого после раннего прохода осталась одна подпись
          (`ИНН 7707083893` → `инн ` + заглушки), давало ключ-джокер: он совпадал с ЛЮБЫМ текстом
          «ИНН <токен той же длины>», и комментарий про ЧУЖУЮ организацию закрывался токеном этой.
          Отрезок, а не сумма всех кусков: `№ <токен> от <токен>` даёт в сумме те же четыре
          символа, но ни одного осмысленного куска — такой ключ тоже джокер, только по форме
          записи. Вырожденный случай «ранний проход заменил всё содержимое» тот же отсев
          закрывает заодно: ключ без единой буквы `_токены_с_устаревшими_ключами` считает следом
          прежней версии и при КАЖДОМ открытии словаря удаляет и пересобирает варианты этого
          токена.

        Остаточная цена (осознанная, C-1 ревью задачи 3): то же написание, в котором на месте
        реквизита стоит токен ДРУГОГО значения, закроется этим же токеном названия — до тех пор,
        пока словарь не выучит второй такой ключ; тогда ключ становится неоднозначным
        (`ambiguous_name_variants`) и из подмены выпадает. Утечки нет — закрывается название
        названием, — но подмена может назвать не то юридическое лицо.

        Ревизия поднимается только при настоящей вставке: по ней маскировщик и страж пересобирают
        автомат известных названий (`_обновить_автомат_названий`), а `token_for` на уже известном
        значении её не двигает — без этого новый ключ не дошёл бы до автомата вовсе."""
        разобран = parse_token(token)
        if разобран is None or разобран[0] not in НУМЕРУЕМЫЕ:
            return
        if ЗАГЛУШКА_ТОКЕНА in text:
            # NUL в самих данных 1С дал бы прогон заглушек любой длины в обход отсева GUID ниже;
            # `name_variants_of` отбрасывает такие написания по той же причине.
            return
        if blank_tokens(text, guids=False) != blank_tokens(text):
            return
        ключ = normalize_text_with_map(blank_tokens(text))[0].strip()
        if ЗАГЛУШКА_ТОКЕНА not in ключ:
            return
        отрезки = [кусок.strip() for кусок in ключ.split(ЗАГЛУШКА_ТОКЕНА)]
        литеральный = max(отрезки, key=len)
        if len(литеральный) < МИНИМАЛЬНАЯ_ДЛИНА_ВАРИАНТА or not _годится_в_поиск(литеральный):
            return
        if not _годится_в_поиск(ключ):
            # Годен обязан быть и целый ключ: иначе `_ключи_названий` отсеет его на чтении, а
            # `_токены_с_устаревшими_ключами` сочтёт следом прежней версии и пересоберёт все
            # варианты токена при следующем открытии словаря (повторное ревью задачи 3).
            return
        with self._connection:
            курсор = self._connection.execute(
                "INSERT OR IGNORE INTO name_variants (token, variant_norm) VALUES (?,?)",
                (token, ключ),
            )
        if курсор.rowcount:
            self._revision += 1

    def name_variants(self) -> dict[str, str]:
        """Однозначные варианты названий: с этим множеством сверяется страж (SPEC §6.5, слой 3).

        Вариант, закреплённый более чем за одним токеном (короткая форма совпала у разных
        организаций/физлиц — например, «Ромашка» у ООО «Ромашка» и АО «Ромашка»), сюда не
        попадает. Заменить такой вариант правильно невозможно — неизвестно, к какому из токенов
        он относится в конкретном тексте, — а неправильная подмена подставит одно юридическое
        лицо вместо другого, что хуже отсутствия подмены. Полное название каждой организации
        (со своей организационно-правовой формой) при этом по-прежнему однозначно и остаётся
        здесь — коллизия задевает только общую сокращённую часть (поправка ревью, 2026-09-09).

        Мусорные токены сюда не попадают (`_мусорные_токены`, находки П2 и П1).

        Голое безбуквенное ядро (`2020` от `ООО "2020"`) — тоже (Р3-2, инвариант 6): ключи такого
        названия — ядро в кавычках и со своей формой собственности (`name_variants_of`), а голое
        число в тексте неотличимо от числа. Словари прежних версий пересчитываются при открытии
        (`ВЕРСИЯ_СХЕМЫ`); проверка здесь — страховка на случай строки, дописанной прежней версией
        шлюза уже после пересчёта: число остаётся числом при любом содержимом таблицы.

        Голое одиночное слово (`мост` от `ООО "Мост"`) — та же история (Ruling 115): ключи —
        в кавычках и со своей формой собственности, а голое слово в тексте неотличимо от обычного
        слова того же написания. Страховка та же: демон прежней версии (0.2.x), открывший тот же
        `gate.sqlite` после пересчёта рабочей копии, дописывает новым токенам голый ключ заново —
        `_ключи_названий` отсекает его при чтении независимо от того, прошёл ли пересчёт. Слово из
        букв другой письменности (например, греческой) эта же проверка отсекает при чтении и без
        пересчёта: `_токены_с_устаревшими_ключами` такой ключ кандидатом не считает (SQL ограничен
        кириллицей и латиницей), но в подмену он всё равно не идёт.

        Однозначность считается только среди токенов вне мусора (Р4-4 ревью раунда 4, сведение с
        задачей 5): прежде мусорный токен выпадал уже ПОСЛЕ подсчёта, и токен эха (все написания —
        путь ошибки до Ruling 48, Ruling 49 велит не учитывать их нигде) с тем же коротким ключом
        делал ключ настоящей организации неоднозначным — название уходило открытым. То же для
        остальных признаков мусора: такой токен не название ни одной организации, и ключ, общий с
        ним, однозначен.

        Ruling 115, находка задачи 4, раунд правок 1 (полное написание — приоритет, ПРАВИЛО
        ОБЩЕЕ): любой ключ с несколькими претендентами, ДОСЛОВНО совпадающий с полным
        нормализованным значением поля РОВНО ОДНОГО из них (`tokens.normalized == variant_norm`),
        закрепляется за этим токеном однозначно — правило не ограничено форменным ключом голого
        ядра Ruling 115, оно общее для любой коллизии ключей `_ключи_названий`. Это ПЕРЕСМАТРИВАЕТ
        правило SPEC §6.5 «неоднозначный вариант не подменяется ни одним токеном» для такого рода
        ключей, а не восстанавливает какой-то прежний паритет: до поправки такой ключ был
        неоднозначен и оставался открытым независимо от происхождения коллизии.

        Пример происхождения Ruling 115 (голое ядро под формой): `ООО Мост` и `ООО «Мост»` —
        разные токены (кавычки участвуют в `tokens.normalized`, SPEC §6.3), но оба синтезируют
        форменный ключ `ооо мост` (`<форма> <ядро>`, без кавычек — см. `name_variants_of`); ключ
        достаётся токену `ООО Мост` (его точное написание), `ооо "мост"` — токену `ООО «Мост»`.

        Пример БЕЗ Ruling 115 вовсе (обычный безформенный вариант, ветвь `name_variants_of`
        старше одиночного слова): `Альфа Групп` (без формы собственности) и `ООО "Альфа Групп"`
        (с формой) синтезируют общий безформенный ключ `альфа групп`; до поправки он был
        неоднозначен, и упоминание «Альфа Групп» в свободном тексте оставалось открытым. После
        поправки `альфа групп` — ПОЛНОЕ написание токена `Альфа Групп` (его `tokens.normalized`
        ровно этому ключу и равен) — закрепляется за ним, а `ооо "альфа групп"` остаётся отдельным
        однозначным ключом токена `ООО "Альфа Групп"`.

        Довод: привязка буквальная — текст, попавший под замену, дословно равен настоящему
        значению поля именно того токена, за которым ключ закрепился, а не выдуман; смещение в
        сторону закрытости (инвариант 1 важнее точной атрибуции), реальное значение ни в каком
        случае не раскрывается. Цена: если в свободном тексте на самом деле имелось в виду ДРУГОЕ
        юридическое лицо (то, что записано с формой), а текст назвал его тем же голым словом, что
        и полное значение первого, — подстановка уйдёт под токен первого, а не второго. Решение
        владельца, задача 4, раунд правок 1. Ключи без единственного полного совпадения (`"мост"`,
        `"мост`, `ооо"мост"` у пары `ООО Мост`/`ООО «Мост»`) остаются неоднозначными, как и голое
        `мост` до Ruling 115."""
        return {ключ: токены[0] for ключ, токены in self._ключи_названий(однозначные=True).items()}

    def _ключи_названий(self, *, однозначные: bool) -> dict[str, list[str]]:
        """Ключи названий, годные для поиска (`_годится_в_поиск`) и не являющиеся голым одиночным
        словом (`_голое_слово`, Ruling 115), с токенами — однозначные (ровно один токен) или
        неоднозначные (больше одного). Голый ключ отсекается здесь отдельным предикатом, а не
        правкой `_годится_в_поиск`: тот же `_годится_в_поиск` проверяет литеральный отрезок в
        `add_scrubbed_name_variant`, и отрезок `ромашка` у ключа `ромашка <заглушки>` перестал бы
        проходить. Это защита на чтении — на случай, если голый ключ попал в таблицу мимо
        `name_variants_of` (прежняя версия шлюза до Ruling 115, в том числе версия, дописавшая его
        уже после пересчёта рабочей копии): пересчёт снимает такие ключи при открытии, а фильтр
        здесь не даёт им уйти в подмену, даже если пересчёт ещё не прошёл. Токены мусора
        (`_мусорные_токены`: эхо ошибки
        по Ruling 49, след двойной маскировки, члены перечислений) исключаются ДО подсчёта (Р4-4):
        множество передаётся в SQL одним параметром через `json_each`; группировка — там же, одним
        проходом (токены ключа — `group_concat` через разделитель, которого в токене не бывает).

        Ruling 115, находка задачи 4, раунд правок 1 (полное написание — приоритет, ПРАВИЛО ОБЩЕЕ
        — см. `name_variants`): у ЛЮБОГО ключа с несколькими претендентами, независимо от
        происхождения ключа (форменный ключ голого ядра Ruling 115, обычный безформенный вариант
        старше и вне Ruling 115 — см. пример «Альфа Групп» в `name_variants`), дополнительно
        считается, у скольких из них `tokens.normalized` побайтово равен самому ключу
        (`t.normalized = nv.variant_norm`, `LEFT JOIN` с `tokens`) — общее написание не отличает
        «своего» претендента от «чужого» по одной подстроке. Ровно один такой претендент делает
        ключ однозначным В ЕГО ПОЛЬЗУ, даже если ключ синтезировали и другие токены; ни одного или
        больше одного (второе теоретически невозможно при `UNIQUE (type, normalized)` таблицы
        `tokens` для одного класса, кроме как между разными классами) — ключ, как и раньше,
        неоднозначен целиком. Однозначный «ровно один претендент вообще» (без коллизии) под это же
        правило подпадает тривиально и отдельно не считается. `LEFT JOIN`, а не `JOIN`: ключ,
        которому (гипотетически, при нарушенной ссылочной целостности) не нашлось строки в
        `tokens`, — просто не «полный» ни для какого претендента, а не пропадает из подсчёта
        претендентов вовсе."""
        мусор = json.dumps(sorted(self._мусорные_токены()))
        результат: dict[str, list[str]] = {}
        for строка in self._connection.execute(
            "SELECT nv.variant_norm AS ключ,"
            " group_concat(nv.token, char(31)) AS претенденты,"
            " group_concat(CASE WHEN t.normalized = nv.variant_norm THEN nv.token END, char(31))"
            "   AS полные"
            " FROM name_variants nv LEFT JOIN tokens t ON t.token = nv.token"
            " WHERE nv.token NOT IN (SELECT value FROM json_each(?))"
            " GROUP BY nv.variant_norm",
            (мусор,),
        ).fetchall():
            ключ = строка["ключ"]
            if not (_годится_в_поиск(ключ) and not _голое_слово(ключ)):
                continue
            претенденты = строка["претенденты"].split("\x1f")
            полные = строка["полные"].split("\x1f") if строка["полные"] else []
            победитель = претенденты[0] if len(претенденты) == 1 else None
            if победитель is None and len(полные) == 1:
                победитель = полные[0]
            if однозначные:
                if победитель is not None:
                    результат[ключ] = [победитель]
            elif победитель is None and len(претенденты) > 1:
                результат[ключ] = sorted(претенденты)
        return результат

    def ambiguous_name_variants(self) -> dict[str, list[str]]:
        """Варианты названий, закреплённые более чем за одним токеном (см. name_variants()).

        Не участвуют в подмене — нужны, чтобы предупредить пользователя: короткая форма
        встретилась у нескольких организаций/физлиц, и страж сознательно не подменяет её ни
        одним из токенов (поправка ревью, 2026-09-09).

        Голое безбуквенное ядро, дописанное прежней версией, сюда не попадает — та же страховка,
        что в `name_variants`: это не ключ поиска, предупреждать о нём не о чем (Р3-2). Токены
        мусора (эхо ошибки и прочие) неоднозначности не создают — считаются без них (Р4-4).

        Ruling 115, находка задачи 4, раунд правок 1 (полное написание — приоритет, ПРАВИЛО ОБЩЕЕ
        — см. `name_variants`): ключ, у которого ровно один из претендентов написан ПОЛНОСТЬЮ как
        этот ключ (`tokens.normalized == variant_norm`), сюда не попадает вовсе — он однозначен в
        пользу этого токена, независимо от происхождения ключа (не только форменный ключ голого
        ядра Ruling 115 — см. пример «Альфа Групп»/«ООО "Альфа Групп"» в `name_variants`). Здесь
        остаются только ключи без такого единственного полного совпадения — например, `"мост"`,
        `"мост`, `ооо"мост"` у пары `ООО Мост`/`ООО «Мост»`, когда ни то, ни другое написание не
        совпадает с ключом побайтово.
        """
        return self._ключи_названий(однозначные=False)

    def _создать(self, type_: str, нормализованное: str, base: str, entity: str, field: str) -> str:
        """Вставки без собственной транзакции — вызывающий (token_for) держит одну на всё."""
        момент = datetime.datetime.now(datetime.UTC).isoformat(timespec="seconds")
        if type_ in НУМЕРУЕМЫЕ:
            номер = self._следующий_номер(type_)
            токен = f"[[{type_}:{номер}]]"
        else:
            номер = None
            токен = self._свободный_токен(type_, нормализованное)

        self._connection.execute(
            "INSERT INTO tokens (token, type, normalized, seq, first_seen_at, first_base,"
            " first_entity, first_field) VALUES (?,?,?,?,?,?,?,?)",
            (токен, type_, нормализованное, номер, момент, base, entity, field),
        )
        if type_ in НУМЕРУЕМЫЕ:
            self._connection.executemany(
                "INSERT OR IGNORE INTO name_variants (token, variant_norm) VALUES (?,?)",
                [(токен, вариант) for вариант in name_variants_of(нормализованное)],
            )
        return токен

    def _свободный_токен(self, type_: str, нормализованное: str) -> str:
        """Коллизия — другое значение с тем же токеном: хвост удлиняется до 16 (SPEC §6.3)."""
        for длина in (10, 16):
            кандидат = make_token(self._secret, type_, нормализованное, tail_length=длина)
            занято = self._connection.execute(
                "SELECT normalized FROM tokens WHERE token = ?", (кандидат,)
            ).fetchone()
            if занято is None or занято["normalized"] == нормализованное:
                return кандидат
        raise RuntimeError(f"не удалось выдать токен класса {type_}: коллизия и на 16 символах")

    def _следующий_номер(self, type_: str) -> int:
        строка = self._connection.execute(
            "SELECT COALESCE(MAX(seq), 0) + 1 AS следующий FROM tokens WHERE type = ?", (type_,)
        ).fetchone()
        return int(строка["следующий"])

    def _запомнить_вариант(
        self, токен: str, base: str, entity: str, field: str, raw_value: str
    ) -> None:
        """Вставка без собственной транзакции — вызывающий (token_for) держит одну на всё."""
        self._connection.execute(
            "INSERT OR IGNORE INTO variants (token, base, entity, field, raw_value, seen_at)"
            " VALUES (?,?,?,?,?,?)",
            (
                токен,
                base,
                entity,
                field,
                raw_value,
                datetime.datetime.now(datetime.UTC).isoformat(timespec="seconds"),
            ),
        )

    def _count(self) -> int:
        return int(
            self._connection.execute("SELECT COUNT(*) AS всего FROM tokens").fetchone()["всего"]
        )


def _свёртка(type_: str, основа: str) -> str:
    """Нормализованная форма, по которой написание сравнивается со значением токена, — та же
    свёртка, что у `token_for` (без запасного шага по `raw_value`: здесь основа и есть строка)."""
    return normalize_value(type_, основа) or " ".join(основа.split())


def _структура_для(text: str, type_: str, normalized: str) -> bool:
    """Структура ли написание для токена с нормализованной формой `normalized`.

    Значение БСП (`contact_info.is_contact_value`) — структура всегда: маскировщик строит его
    токен по представлению, а без представления (JSON без `value`) подставить из него в текст
    нечего (Ruling 38). Строка, из которой представление не извлекается, — текст. Остаётся JSON
    `{"value": …}` без `type`: он текст, только если токен построен по нему целиком (свёртка
    строки совпала со значением токена, а свёртка представления — нет). Совпали обе — у класса с
    цифровой свёрткой (телефон без других цифр в JSON) токен от места не зависит, и написание
    считается структурой: в текстовое поле идёт представление с тем же значением."""
    if contact_info.is_contact_value(text):
        return True
    представление = contact_info.representation(text)
    if представление == text:
        return False
    return not (
        _свёртка(type_, text) == normalized and _свёртка(type_, представление) != normalized
    )
