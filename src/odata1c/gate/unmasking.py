class GateError(Exception):
    def __init__(self, code: str, message: str, hint: str = "") -> None:
        super().__init__(message)
        self.code = code
        self.hint = hint


class Unmasker:
    """Обратная подмена и ЕДИНСТВЕННАЯ реализация анти-оракульных правил отбора (Ruling 20,
    пункт 3). Рецепты (`recipes/`) не повторяют правила своим списком — они прогоняют условие с
    подставленными значениями через `filter()`, поэтому одинаковое условие получает одинаковый
    вердикт, каким бы тулом ни пришло.

    `field_class` — эффективный класс поля по политике базы; вызывается с ключевым `strict`
    (Ruling 18: путь, не разрешённый по индексу, толкуется строго, см. `masking`).

    `path_class` — класс ПУТИ целиком (`Контрагент/КонтактнаяИнформация/Представление`), когда
    его определяет не последний сегмент, а сущность, в которую путь приходит (Ruling 37,
    `masking.inbound_path_class`). Отвечает `None`, если путь такому правилу не подлежит, — и
    тогда класс ищется прежним порядком по последнему сегменту (`_класс_поля`). Обязателен
    намеренно, как `shape` у `BaseGate.inbound_*`: `Unmasker` без него снова открыл бы оракул
    через путь к табличной части контактной информации, и забыть его пишущему тулу M2 не даст
    ошибка вызова. Гейт передаёт его в `BaseGate._обратная_подмена`.

    `shape` — строение сущностей по индексу, то же, что у `BaseGate.inbound_*`. Нужно одному
    признаку структурного поля — полю-брату `<Имя>Строкой` (Ruling 43, `_поле_структурное`).
    Необязателен: без строения этот признак молчит, остальные работают."""

    def __init__(
        self,
        dictionary: Dictionary,
        *,
        base: str,
        field_class: Callable[..., str | None],
        path_class: Callable[[str, str], str | None],
        shape: contact_info.Shape | None = None,
    ) -> None:
        self._dictionary = dictionary
        self._base = base
        self._field_class = field_class
        self._path_class = path_class
        self._shape = shape

    def filter(
        self,
        expression: str,
        *,
        entity: str,
        revealed: RevealedValues | None = None,
        strict: bool = False,
    ) -> str:
        значимые = [лексема for лексема in lex_filter(expression) if лексема.kind != "space"]
        # _вызовы_функций проверяет форму каждого вызова (ровно два простых аргумента) и
        # отказывает сразу же, до вычисления "занято" ниже — неоднозначный вызов не должен
        # успеть пометить свой диапазон обработанным, минуя общую проверку (Обход A).
        вызовы = self._вызовы_функций(значимые)

        занято: set[int] = set()
        for вызов in вызовы:
            занято.update(range(вызов["start"], вызов["close"] + 1))

        поля_сравнений = self._поля_сравнений(значимые, занято)

        сегменты: list[tuple[int, int, str]] = []
        for вызов in вызовы:
            сегмент = self._обработать_вызов(
                вызов, значимые, entity=entity, strict=strict, revealed=revealed
            )
            if сегмент is not None:
                сегменты.append(сегмент)

        for индекс, (поле, оператор, индекс_поля) in поля_сравнений.items():
            сегмент = self._обработать_сравнение(
                значимые[индекс],
                поле,
                оператор,
                entity=entity,
                strict=strict,
                revealed=revealed,
                токен_поля=значимые[индекс_поля],
            )
            if сегмент is not None:
                сегменты.append(сегмент)

        # F1 итогового ревью: специфичные отказы выше (упорядоченное сравнение, чужой класс
        # токена, обрывок) уже отработали и дали точное сообщение; здесь — общее правило по
        # каждому вхождению защищаемого поля, какой бы формой его ни обернули.
        части = _части_условий(значимые)
        защищаемые = self._проверить_вхождения_полей(
            значимые, вызовы, поля_сравнений, части, entity, strict=strict
        )

        обработанные = {вызов["literal_idx"] for вызов in вызовы}
        обработанные |= set(поля_сравнений)
        for индекс, токен in enumerate(значимые):
            if токен.kind not in ЛИТЕРАЛЬНЫЕ_ВИДЫ or индекс in обработанные or индекс in занято:
                continue
            if токен.kind == "string":
                raise GateError(
                    "filter_syntax",
                    f"не удалось определить поле для литерала «{токен.text}»: структура "
                    "сравнения не распознана",
                    "сравнивайте литерал с полем через eq/ne/gt/ge/lt/le или через substringof/"
                    "startswith/endswith",
                )
            # Ruling 16 для литералов любого вида (F1 итогового ревью): число, дата или guid,
            # не привязанные к полю тройкой, раньше проходили молча — отказ касался только строк,
            # и `year(ДатаРождения) gt 1980` уходил в 1С. Строка без поля отклоняется всегда (в
            # ней может быть токен); нестроковый литерал — когда в том же условии между and/or
            # есть защищаемое поле. Это вторая линия за правилом вхождений выше: если в разборе
            # границ тройки найдётся дыра, оракул с числом или датой всё равно не пройдёт.
            #
            # Раунд 2 ревью (I1): вторая линия действовала на всё выражение и отклоняла законные
            # комбинации (`ИНН eq '[[…]]' and year(Date) eq 2026`). Через and/or от защищаемого
            # поля к соседнему условию проходит только булев результат, поэтому литерал без поля
            # в соседнем условии о значении поля ничего не говорит — проверяется только условие,
            # где поле стоит (см. `_части_условий`).
            защищаемое = защищаемые.get(части[индекс])
            if защищаемое is not None:
                raise GateError(
                    "filter_syntax",
                    f"литерал «{токен.text}» не привязан к полю сравнением, а в том же условии "
                    f"есть защищаемое поле «{защищаемое}»",
                    "сравнивайте литерал непосредственно с полем через eq/ne/gt/ge/lt/le — "
                    "например, «Date ge datetime'2026-01-01' and Date lt datetime'2027-01-01'» "
                    "вместо «year(Date) eq 2026»",
                )

        return _собрать(expression, сегменты)

    def value(
        self,
        text: str,
        *,
        entity: str,
        field: str,
        revealed: RevealedValues | None = None,
        strict: bool = False,
        allow_mixed: bool = False,
    ) -> str:
        """Одно значение: параметр рецепта, элемент ключа, аргумент действия.

        `allow_mixed` — разрешить токен ВНУТРИ текста. Правда только для тела записи (`body`):
        там пишется строка целиком, и токен в ней — законная часть текста. Для значения, которое
        станет операндом сравнения, это правило `$filter` «токен смешан с текстом» (I2 ревью
        2026-09-11): раскрытое значение можно обрамить текстом и вынести наружу тем же эхом,
        а образец сравнения из части токена — оракул подбора."""
        if not isinstance(text, str):
            return text
        целиком = parse_token(text)
        if целиком:
            if allow_mixed:
                # Тело записи старым путём (`body`): шаг 2а правила записи (Ruling 38) — в
                # структурное поле контактной информации JSON другой записи не подставляется.
                self._не_в_структуру(целиком, entity=entity, field=field, strict=strict)
            return self._раскрыть(
                целиком, entity=entity, field=field, strict=strict, revealed=revealed
            )
        if is_partial_token(text):
            raise GateError(
                "token_partial",
                "в значении обрезанный токен; передайте токен целиком",
                "токены непрозрачны: их нельзя достраивать и обрезать",
            )
        if find_tokens(text):
            if not allow_mixed:
                raise GateError(
                    "token_partial",
                    "в значении токен смешан с текстом",
                    "передайте токен целиком и сравнивайте через eq",
                )
            return self._подставить_внутри_текста(
                text, entity=entity, field=field, strict=strict, revealed=revealed
            )
        # Ruling 35: значение, которое станет операндом сравнения с полем контактной информации
        # (параметр рецепта, элемент ключа), — только целый токен. Тело записи (`allow_mixed`)
        # правило не задевает: там пишется новое значение, а не подбирается существующее.
        if (
            not allow_mixed
            and text
            and self._класс_поля(entity, field, strict=strict) == contact_info.КЛАСС_НА_ВХОДЕ
        ):
            raise _открытая_контактная_информация(field)
        self._проверить_реальное_значение(text, entity=entity, field=field, strict=strict)
        return text

    def body(self, data, *, entity: str, revealed: RevealedValues | None = None, field: str = ""):
        """`field` — путь-префикс, накопленный при спуске во вложенный объект (третий раунд
        ревью, «путь записи»): раньше при обходе вложенного словаря под полем связи
        (`{"Контрагент": {"ИНН": токен}}`) рекурсивный вызов `self.body(значение, entity=entity)`
        терял имя поля-контейнера вовсе — вложенные поля проверялись как «ИНН» на корневой
        сущности документа, а не как «Контрагент/ИНН», и получали ту же дыру, что и путь через
        `/` в `$filter` (Обход 4). Теперь `_обойти_значение` передаёт составленный путь дальше
        (см. там же), а `_класс_поля` умеет резолвить класс по последнему сегменту такого пути."""
        if isinstance(data, dict):
            return {
                ключ: self._обойти_значение(
                    значение, entity=entity, field=_путь(field, ключ), revealed=revealed
                )
                for ключ, значение in data.items()
            }
        # Верхний уровень без словаря (голая строка или список — например, список значений
        # табличной части без обёртки-объекта) обходится тем же путём, что и вложенное значение
        # под пустым именем поля: раньше здесь была отдельная ветка для list, которая рекурсивно
        # звала body() для каждого элемента, а body() строку саму по себе не обрабатывал вовсе —
        # токен в такой строке уходил в 1С дословно, обрезанный не отклонялся (Правка 4, ревью
        # задачи 7). `_обойти_значение` уже умеет строку/словарь/список/прочее в одном месте.
        # Имя поля здесь неизбежно пустое только на самом верхнем уровне без обёртки-ключа —
        # обратное чтение вернёт нормализованное значение, а не вариант по базе/полю, и проверка
        # класса не сработает (нечем проверять). Для значения под конкретным ключом
        # (`body({"ИНН": ...})`) или элемента списка под ключом (`body({"Учредители": [...]})`)
        # имя поля (или составленный путь) есть и используется — degradация касается только
        # по-настоящему безымянного верхнего уровня (Правка D, зафиксировано как принятое
        # ограничение интерфейса `body(data, *, entity)` без параметра поля на самом верхнем
        # вызове).
        return self._обойти_значение(data, entity=entity, field=field, revealed=revealed)

    def key(
        self, value, *, entity: str, revealed: RevealedValues | None = None, strict: bool = False
    ):
        if isinstance(value, dict):
            результат = {}
            for ключ, часть in value.items():
                # Испорченный токен, случайно оказавшийся в ИМЕНИ поля составного ключа —
                # подставлять там нечего (это не значение), но он всё равно обязан вызвать
                # отказ, а не пройти незамеченным (Правка 5, ревью задачи 7).
                if is_partial_token(ключ):
                    raise GateError(
                        "token_partial",
                        f"в имени поля составного ключа «{ключ}» обрезанный токен",
                        "токены непрозрачны: их нельзя достраивать и обрезать",
                    )
                результат[ключ] = (
                    self.value(часть, entity=entity, field=ключ, strict=strict, revealed=revealed)
                    if isinstance(часть, str)
                    else часть
                )
            return результат
        # Простой ключ 1С в OData — всегда `Ref_Key`, то есть GUID: имя поля здесь известно и
        # передаётся явно, а не пустой строкой (C2 ревью 2026-09-11). Ref_Key не защищается ни на
        # одном уровне (инвариант 6), поэтому токен в простом ключе — всегда ошибка, и отказывает
        # общее правило `_раскрыть` («нет совпадения класса — нет раскрытия»), а не отдельная
        # проверка здесь.
        if isinstance(value, str):
            return self.value(
                value, entity=entity, field="Ref_Key", strict=strict, revealed=revealed
            )
        return value

    def write(
        self,
        data: dict,
        *,
        entity: str,
        current: dict | None,
        revealed: RevealedValues | None,
        strict: bool = False,
    ) -> dict:
        """Тело PATCH/POST от пишущего тула M2: токены → реальные значения без молчаливого выбора
        написания (Б-1, раздел «Интерфейс для M2» отчёта о блокерах).

        Почему отдельная функция, а не `body`. На записи пользователь подтверждает превью на
        токенах и реального значения не видит (инвариант 1). Если у токена несколько написаний, а
        гейт подставит любое из них, в базу ляжет не то, что было в записи, — и по превью это не
        отличить. `body` раскрывает токен по полю и базе и отказывает при нескольких написаниях;
        здесь вдобавок есть `current` — текущее состояние объекта (update), единственный
        источник, который знает, как значение записано В ЭТОМ поле ЭТОГО объекта.

        Правило для целого токена в строке по пути `P`:
        1. право на раскрытие — как у всех путей (класс поля, выдача для поля, Ruling 19/20/35);
           проверяется первым, до взгляда на написания и на `current`;
        2. `current[P]` — написание значения этого токена (сохранённое словарём или с той же
           нормализованной формой; структура БСП — по своему представлению, Ruling 38) →
           записывается `current[P]` дословно;
        3. поле структурное (`_структурное`: JSON/XML контактной информации — по имени, по
           `current[P]` или по своим написаниям) → `token_ambiguous`: структуру, которую словарь
           видел в другой записи, в этот объект не переносим (Ruling 38, пункт 4);
        4. иначе — написания этой базы и этого поля: ровно одно → оно;
        5. их нет вовсе — написания словаря текстом, структура — своим представлением: ровно
           одно → оно;
        6. иначе `token_ambiguous`: в тексте токен и «несколько написаний» — ни написаний, ни их
           числа (M-1).

        Токен внутри текста — шаги 1, 3–6, и между 4–6 и отказом ещё один: из нескольких
        написаний ровно одно стоит в тексте `current[P]` → оно (то же основание, что у шага 2).
        Строка без токена — как в `body`: открытое значение, продиктованное пользователем,
        проходит с проверкой контрольной суммы класса поля.

        `current` — как его вернул `client.get(..., scrub=gate.scrubber(revealed))`. Строки,
        переписанные ранним проходом (`ScrubbedText`), разворачиваются в исходное значение места
        через тот же `revealed` (Б-3). Табличные части сопоставляются по `LineNumber`; строка без
        номера сопоставления не получает (соседняя строка того же значения в другом написании —
        чужое написание, а не текущее значение этой строки). Для create `current` — `None`."""
        return self._записать(
            data, entity=entity, field="", текущее=current, revealed=revealed, strict=strict
        )

    def _записать(
        self,
        значение,
        *,
        entity: str,
        field: str,
        текущее,
        revealed: RevealedValues | None,
        strict: bool,
    ):
        if isinstance(значение, dict):
            своё = текущее if isinstance(текущее, dict) else {}
            return {
                ключ: self._записать(
                    вложенное,
                    entity=entity,
                    field=_путь(field, ключ),
                    текущее=своё.get(ключ),
                    revealed=revealed,
                    strict=strict,
                )
                for ключ, вложенное in значение.items()
            }
        if isinstance(значение, list):
            строки = _строки_по_номеру(текущее)
            return [
                self._записать(
                    элемент,
                    entity=entity,
                    field=field,
                    текущее=строки.get(_номер_строки(элемент)),
                    revealed=revealed,
                    strict=strict,
                )
                for элемент in значение
            ]
        if isinstance(значение, str):
            return self._строка_записи(
                значение,
                entity=entity,
                field=field,
                текущее=_развернуть(текущее, revealed),
                revealed=revealed,
                strict=strict,
            )
        return значение

    def _строка_записи(
        self,
        текст: str,
        *,
        entity: str,
        field: str,
        текущее: str | None,
        revealed: RevealedValues | None,
        strict: bool,
    ) -> str:
        целиком = parse_token(текст)
        if целиком:
            токен, сегмент = self._проверить_право(
                целиком, entity=entity, field=field, strict=strict
            )
            if текущее is not None and self._dictionary.matches(токен, текущее):
                реальное = текущее
            elif self._поле_структурное(entity, field, текущее):
                raise _структура_не_по_токену(токен, field)
            else:
                реальное = self._написание_для_записи(токен, сегмент, в_тексте=None)
            if revealed is not None:
                revealed.add(реальное, token=токен)
            return реальное
        if is_partial_token(текст) or not find_tokens(текст):
            # Обрезанный токен — тот же отказ, что у `value`; строка без токенов — открытое
            # значение, путь `body` без изменений (контрольная сумма класса поля).
            return self.value(
                текст,
                entity=entity,
                field=field,
                revealed=revealed,
                strict=strict,
                allow_mixed=True,
            )
        куски, позиция = [], 0
        for начало, конец, класс, хвост in find_tokens(текст):
            токен, сегмент = self._проверить_право(
                (класс, хвост), entity=entity, field=field, strict=strict
            )
            if self._поле_структурное(entity, field, текущее):
                raise _структура_не_по_токену(токен, field)
            реальное = self._написание_для_записи(токен, сегмент, в_тексте=текущее)
            if revealed is not None:
                revealed.add(реальное, token=токен)
            куски.append(текст[позиция:начало])
            куски.append(реальное)
            позиция = конец
        куски.append(текст[позиция:])
        return "".join(куски)

    def _написание_для_записи(self, токен: str, сегмент: str, *, в_тексте: str | None) -> str:
        """Шаги 4–6 правила записи (см. `write`), только для текстового поля: в структурное поле
        без совпадения с `current` вызывающий уже отказал (Ruling 38, пункт 4). С обеих ступеней
        лестницы берутся написания текстом, из структуры — её представление (`_текстом`). Первая
        ступень — тоже (раунд 4): она ищет по базе и ИМЕНИ поля, без сущности, и структура,
        виденная в одноимённом поле другой сущности (`ЗаявкаНаВыпускКиЗГИСМ.АдресДоставки`),
        иначе ушла бы JSON-ом в текстовое `ЗаказКлиента.АдресДоставки`. Структура в поле ЭТОЙ
        сущности сюда не доходит: она делает поле структурным (признак 3), и вызывающий отказал.

        Нормализованная форма, в отличие от отбора (`_написания`), здесь не берётся никогда: у
        названий она в нижнем регистре со свёрнутыми кавычками, у телефона — голые цифры, и запись
        её вместо написания из базы изменила бы данные."""
        написания = (
            self._формата_поля(
                токен,
                self._dictionary.spellings(токен, base=self._base, field=сегмент),
                структурное=False,
            )
            if сегмент
            else []
        )
        if not написания:
            написания = self._формата_поля(
                токен, self._dictionary.spellings(токен), структурное=False
            )
        if len(написания) == 1:
            return написания[0]
        if в_тексте is not None and len(написания) > 1:
            в_поле = [написание for написание in написания if написание in в_тексте]
            if len(в_поле) == 1:
                return в_поле[0]
        if not написания:
            raise GateError(
                "token_ambiguous",
                f"у значения токена {токен} в словаре нет сохранённого написания: записать его в "
                "том виде, в каком оно лежит в базе, нельзя",
                ПОДСКАЗКА_ЗНАЧЕНИЯ,
            )
        raise _неоднозначный(токен, ПОДСКАЗКА_ЗНАЧЕНИЯ)

    def _поле_структурное(self, entity: str, field: str, текущее: str | None = None) -> bool:
        """Хранит ли целевое поле значение структурой (JSON/XML контактной информации БСП,
        `contact_info.is_structure`) — свойство ПОЛЯ, а не токена, который в него пишут
        (Ruling 43, Р2-1 повторного ревью блокеров M2). Хотя бы один признак:

        1. имя кончается на `…Значение` или `…ЗначенияПолей` (`contact_info.is_structure_field`);
        2. у сущности, куда приходит путь, есть поле-брат `<Имя>Строкой` — схема ИС МП, СУЗ,
           ЗЕРНО: `ПроизводственныйОбъектАдрес` — структура, `ПроизводственныйОбъектАдресСтрокой`
           — её текст (24 поля в индексе УТ). По строению из индекса на лету, без реиндекса;
        3. словарь видел в этой базе, в сущности, куда приходит путь, в поле с этим именем
           структуру ЛЮБОГО значения (`Dictionary.structured_field`). Прежде признак был
           потокенным — «свои написания этого значения», — и для токена, виденного только
           текстом, структурное поле `ПроизводственныйОбъектАдрес` считалось текстовым: в
           структуру уходил голый текст. Сущность в ключе — Р3-1 (раунд 4): без неё структура
           одноимённого поля другой сущности (`ЗаявкаНаВыпускКиЗГИСМ.АдресДоставки`) делала
           структурным текстовое `ЗаказКлиента.АдресДоставки`, и отбор, одно значение и запись
           меняли формат операнда или отказывали. Ключ один на чтение и запись: формат у поля
           один;
        4. в `current` поле содержит структуру.

        Поле, про которое ничего не известно (имя без суффикса, брата нет или строения нет,
        словарь в этой сущности структуры в нём не видел, `current` нет), — текстовое, как
        прежде: остаток записан в SPEC §6.8."""
        сегмент = _сегмент_поля(field)
        if текущее is not None and contact_info.is_structure(текущее):
            return True
        if not сегмент:
            return False
        if contact_info.is_structure_field(сегмент):
            return True
        сущность = self._сущность_пути(entity, field)
        if self._есть_брат_строкой(сущность, сегмент):
            return True
        return self._dictionary.structured_field(base=self._base, entity=сущность, field=сегмент)

    def _сущность_пути(self, entity: str, field: str) -> str:
        """Сущность, в которую приходит путь `field` от `entity` (`contact_info.entity_of_path`):
        у строки табличной части — сама табличная часть, через навигацию — цель по строению. Без
        строения звенья толкуются как табличные части — то же имя `<владелец>_<звено>`, которым
        маскировщик записывает строки табличных частей в словарь."""
        *звенья, _ = field.split("/")
        return contact_info.entity_of_path(entity, звенья, self._shape)

    def _есть_брат_строкой(self, сущность: str, сегмент: str) -> bool:
        """Признак 2 `_поле_структурное`: поле `<Имя>Строкой` в строении сущности, куда приходит
        путь (`_сущность_пути`). Строения нет — признак молчит."""
        if self._shape is None:
            return False
        строение = self._shape(сущность)
        return строение is not None and f"{сегмент}{СУФФИКС_БРАТА}" in строение.fields

    def _обойти_значение(
        self, значение, *, entity: str, field: str, revealed: RevealedValues | None
    ):
        if isinstance(значение, str):
            return self.value(
                значение, entity=entity, field=field, allow_mixed=True, revealed=revealed
            )
        if isinstance(значение, dict):
            # `field` здесь — уже составленный путь до этого вложенного объекта (пустой на
            # самом верхнем уровне) — передаётся в `body()` как префикс, а не отбрасывается
            # (см. docstring `body`, «путь записи», третий раунд ревью).
            return self.body(значение, entity=entity, field=field, revealed=revealed)
        if isinstance(значение, list):
            return [
                self._обойти_значение(элемент, entity=entity, field=field, revealed=revealed)
                for элемент in значение
            ]
        return значение

    # ------------------------------------------------------------------
    # Разбор структуры $filter (Правки 1, 3 и обходы A–C — ревью задачи 7)
    # ------------------------------------------------------------------

    def _вызовы_функций(self, значимые: list[Token]) -> list[dict]:
        """Найти вызовы substringof/startswith/endswith и сразу проверить их форму: ровно два
        простых аргумента (один — идентификатор поля, другой — строковый образец), независимо
        от порядка. Любая неоднозначность — отказ здесь же, до дальнейшей обработки (Обход A):
        `substringof('7707', concat(ИНН, ''))` не должен молча пройти как «поле не найдено»."""
        вызовы: list[dict] = []
        i, n = 0, len(значимые)
        while i < n:
            токен = значимые[i]
            if (
                токен.kind == "identifier"
                and токен.text.lower() in ФУНКЦИИ_ПОДСТРОКИ
                and i + 1 < n
                and значимые[i + 1].kind == "paren"
                and значимые[i + 1].text == "("
            ):
                открывающая = i + 1
                закрывающая = self._найти_закрывающую(значимые, открывающая)
                literal_idx, field_idx = self._разобрать_аргументы(
                    значимые, открывающая, закрывающая, имя=токен.text.lower()
                )
                вызовы.append(
                    {
                        "name": токен.text.lower(),
                        "start": i,
                        "close": закрывающая,
                        "literal_idx": literal_idx,
                        "field_idx": field_idx,
                        # Под отрицанием "not" переписанное сравнение нужно взять в скобки —
                        # иначе "not X eq Y" по правилам OData свяжется как "(not X) eq Y", а
                        # не "not (X eq Y)" (Правка F). "not" — единственный оператор OData v3,
                        # который связывает сильнее сравнения; and/or связывают слабее, поэтому
                        # непосредственно перед ними скобки не нужны.
                        "under_not": i > 0
                        and значимые[i - 1].kind == "operator"
                        and значимые[i - 1].text.lower() == "not",
                    }
                )
                i = закрывающая + 1
                continue
            i += 1
        return вызовы

    def _найти_закрывающую(self, значимые: list[Token], открывающая: int) -> int:
        глубина = 1
        j, n = открывающая + 1, len(значимые)
        while j < n and глубина > 0:
            if значимые[j].kind == "paren":
                глубина += 1 if значимые[j].text == "(" else -1
            j += 1
        if глубина != 0:
            raise GateError(
                "filter_syntax",
                "непарные скобки в вызове функции поиска подстроки",
                "проверьте выражение отбора",
            )
        return j - 1

    def _разбить_аргументы(
        self, значимые: list[Token], открывающая: int, закрывающая: int
    ) -> list[list[int]]:
        """Индексы токенов каждого аргумента верхнего уровня вызова (запятые внутри вложенных
        скобок аргумент не разделяют)."""
        аргументы: list[list[int]] = []
        текущий: list[int] = []
        глубина = 0
        for idx in range(открывающая + 1, закрывающая):
            токен = значимые[idx]
            if токен.kind == "paren":
                глубина += 1 if токен.text == "(" else -1
                текущий.append(idx)
                continue
            if токен.kind == "comma" and глубина == 0:
                аргументы.append(текущий)
                текущий = []
                continue
            текущий.append(idx)
        аргументы.append(текущий)
        return аргументы

    def _разобрать_аргументы(
        self, значимые: list[Token], открывающая: int, закрывающая: int, *, имя: str
    ) -> tuple[int, int]:
        """Ровно два аргумента, один — простой идентификатор, другой — простая строка. Любое
        отклонение от этой формы (не два аргумента, вложенный вызов, оба одного вида) — отказ,
        а не попытка угадать, что имелось в виду (Обход A)."""
        аргументы = self._разбить_аргументы(значимые, открывающая, закрывающая)
        роли: list[tuple[str, int | None]] = []
        for arg in аргументы:
            if len(arg) == 1 and значимые[arg[0]].kind in ("string", "identifier"):
                роли.append((значимые[arg[0]].kind, arg[0]))
            else:
                роли.append(("complex", None))
        виды = sorted(вид for вид, _ in роли)
        if len(аргументы) != 2 or виды != ["identifier", "string"]:
            raise GateError(
                "filter_syntax",
                f"не удалось однозначно определить поле и образец для {имя}(...)",
                "функция поиска подстроки сравнивает простой строковый образец с простым "
                "полем-идентификатором, без вложенных выражений",
            )
        literal_idx = next(idx for вид, idx in роли if вид == "string")
        field_idx = next(idx for вид, idx in роли if вид == "identifier")
        return literal_idx, field_idx

    def _поля_сравнений(
        self, значимые: list[Token], занято: set[int]
    ) -> dict[int, tuple[str, str, int]]:
        """Поле, оператор и индекс поля для литерала в бинарном сравнении: идентификатор по
        другую сторону оператора от литерала, в любом порядке (Правка 1). Литерал — любого из
        `ЛИТЕРАЛЬНЫЕ_ВИДЫ` (Обход 5): число и дата тоже должны попасть под проверку класса поля,
        а не только строка — иначе `ИНН ge 7707` (без кавычек) структурно не находился вовсе.

        F1 итогового ревью: полем тройки не может быть имя функции — идентификатор, за которым
        сразу идёт «(». Раньше `'7707' eq substring(ИНН, 0, 4)` находил тройку «литерал eq
        substring», принимал `substring` за поле без класса и отпускал литерал как привязанный:
        префикс ИНН подбирался посимвольно, стоило поставить литерал слева. Ключевые слова
        null/true/false — законный литерал тройки (`ИНН eq null`), но не поле."""
        поля: dict[int, tuple[str, str, int]] = {}
        for i in range(len(значимые) - 2):
            if i in занято or i + 1 in занято or i + 2 in занято:
                continue
            оператор = значимые[i + 1]
            if оператор.kind != "operator" or оператор.text.lower() not in СРАВНЕНИЯ:
                continue
            оп = оператор.text.lower()
            if _поле(значимые, i) and _литерал(значимые[i + 2]):
                поля[i + 2] = (значимые[i].text, оп, i)
            elif _литерал(значимые[i]) and _поле(значимые, i + 2):
                поля[i] = (значимые[i + 2].text, оп, i + 2)
        return поля

    def _проверить_вхождения_полей(
        self,
        значимые: list[Token],
        вызовы: list[dict],
        поля_сравнений: dict[int, tuple[str, str, int]],
        части: list[int],
        entity: str,
        *,
        strict: bool = False,
    ) -> dict[int, str]:
        """Структурное анти-оракульное правило (F1 итогового ревью M1c): КАЖДОЕ вхождение поля
        защищаемого класса обязано стоять в разрешённой форме, иначе отказ. Возвращает для
        каждого условия между and/or (номер из `части`), где есть защищаемое поле, имя первого
        такого поля — для правила висячего литерала.

        Разрешённые формы — ровно две, обе уже существовавшие:
        1. поле-аргумент проверенного вызова substringof/startswith/endswith (`_вызовы_функций`
           уже убедился, что там строго «строка + простой идентификатор»);
        2. поле в тройке «поле eq|ne литерал» (в любом порядке операндов), причём тройка
           обособлена: по обе стороны от неё — граница выражения (начало/конец, and/or, not,
           группирующая скобка, «:» лямбды), а не оператор, который связывает сильнее сравнения.

        Всё прочее отклоняется без перечня функций: `year(F)`, `length(F)`, `round(...)`,
        функция, которой нет в OData, арифметика вокруг поля или литерала, сравнение поля с
        другим полем, упорядоченное сравнение. Почему не перечень имён: правило, действующее
        для одной синтаксической формы, обходится соседней (Ruling 18) — обёртка `year(...)`
        обошла тройку так же, как до неё обходили перестановкой операндов и `concat`. Допуск
        ведётся по индексу вхождения, а не по имени поля: `year(ИНН) gt 1 and ИНН eq '[[…]]'`
        отклоняется, хотя второе вхождение законно.

        Цена (осознанная): сравнение защищаемого поля с другим полем (`ИНН eq КПП`) и функции
        над таким полем становятся недоступны даже в честных сценариях. Над непрозрачным
        значением функции бессмысленны, а сравнение «поле с полем» — оракул, если второе поле
        видно модели открытым (`ДатаРождения lt ДатаПриема`).

        Классифицируется каждый идентификатор-поле, а не только операнды троек: `_класс_поля`
        может отказать (путь внутрь контрагента к неизвестному полю, Правка 7) и там, где раньше
        класс не спрашивали вовсе — в аргументах функций и в теле лямбды. Направление безопасное.
        Имена функций (идентификатор перед «(») не классифицируются: иначе заголовок лямбды
        `Сотрудники/any(...)` дал бы отказ по контейнеру «Сотрудники».
        """
        допущенные = {вызов["field_idx"] for вызов in вызовы}
        for индекс_литерала, (_, оп, индекс_поля) in поля_сравнений.items():
            начало, конец = sorted((индекс_литерала, индекс_поля))
            if оп in РАВЕНСТВА and _тройка_обособлена(значимые, начало, конец):
                допущенные.add(индекс_поля)

        найденные: dict[int, str] = {}
        for индекс in range(len(значимые)):
            if not _поле(значимые, индекс):
                continue
            поле = значимые[индекс].text
            класс = self._класс_поля(entity, поле, strict=strict)
            if not класс or класс in ("keep", "scan"):
                continue
            if индекс not in допущенные:
                if класс == contact_info.КЛАСС_НА_ВХОДЕ:
                    raise _открытая_контактная_информация(поле)
                raise GateError(
                    "filter_syntax",
                    f"поле «{поле}» класса {класс} допускается в отборе только целиком: "
                    "сравнение с литералом через eq/ne или substringof/startswith/endswith; "
                    "функции, арифметика и сравнение с другим полем по защищаемому полю "
                    "запрещены — по различию ответов значение подбирается перебором",
                    f"сравнивайте поле целиком: «{поле} eq '<токен>'»",
                )
            найденные.setdefault(части[индекс], поле)
        return найденные

    def _обработать_вызов(
        self,
        вызов: dict,
        значимые: list[Token],
        *,
        entity: str,
        revealed: RevealedValues | None,
        strict: bool = False,
    ) -> tuple[int, int, str] | None:
        литерал = значимые[вызов["literal_idx"]]
        поле = значимые[вызов["field_idx"]].text
        содержимое = _снять_кавычки(литерал.text)
        целиком = parse_token(содержимое)
        if целиком:
            литералы = self._литералы_отбора(
                целиком, entity=entity, field=поле, strict=strict, revealed=revealed
            )
            замена = _группа(поле, "eq", литералы)
            if вызов["under_not"] and len(литералы) == 1:
                замена = f"({замена})"
            return (значимые[вызов["start"]].start, значимые[вызов["close"]].end, замена)
        self._проверить_литерал_текстом(
            содержимое, entity=entity, field=поле, оракул=True, strict=strict
        )
        return None  # реальный текст на разрешённом классе — вызов остаётся как есть

    def _обработать_сравнение(
        self,
        литерал: Token,
        поле: str,
        оператор: str,
        *,
        entity: str,
        revealed: RevealedValues | None,
        strict: bool = False,
        токен_поля: Token | None = None,
    ) -> tuple[int, int, str] | None:
        """`токен_поля` — лексема поля этой тройки: если у токена несколько написаний, заменяется
        вся тройка «поле оператор литерал» (группа `or`/`and`, Б-1), а не один литерал."""
        # Упорядоченное сравнение с литералом на защищаемом классе — отдельный ход в обход
        # анти-оракульного правила (Обход B): нет исключения для org/person — сортировать и
        # сравнивать по величине непрозрачные значения бессмысленно в любом случае. Проверка —
        # до parse_token: даже валидный токен, подставленный не через eq/ne, не имеет смысла.
        класс = self._класс_поля(entity, поле, strict=strict)
        if оператор in УПОРЯДОЧЕННЫЕ and класс and класс not in ("keep", "scan"):
            raise GateError(
                "filter_syntax",
                f"упорядоченное сравнение («{оператор}») запрещено для поля «{поле}» класса "
                f"{класс}: сортировать и сравнивать по величине непрозрачные значения "
                "бессмысленно",
                ПОДСКАЗКА_КОНТАКТНОЙ_ИНФОРМАЦИИ
                if класс == contact_info.КЛАСС_НА_ВХОДЕ
                else "сравнивайте защищённое поле только на равенство или неравенство (eq/ne)",
            )
        if литерал.kind != "string":
            # Обход 5: нестроковый литерал (число, дата, guid) не в кавычках — токен внутри
            # него быть не может, подставлять нечего. Отказ по упорядоченному сравнению уже
            # проверен выше и не зависит от вида литерала; на равенстве/неравенстве такой
            # литерал не проверяется дальше — задача этой ветки только не дать нестроковому
            # виду обойти проверку выше молча, а не подменить в нём значение. Ключевые слова
            # null/true/false сюда тоже попадают и допустимы на любом классе.
            if литерал.kind in ЛИТЕРАЛЬНЫЕ_ВИДЫ and (
                отказ := open_literal_refusal(класс, поле, литерал.text)
            ):
                raise отказ
            return None
        содержимое = _снять_кавычки(литерал.text)
        целиком = parse_token(содержимое)
        if целиком:
            литералы = self._литералы_отбора(
                целиком, entity=entity, field=поле, strict=strict, revealed=revealed
            )
            if len(литералы) == 1:
                return (литерал.start, литерал.end, литералы[0])
            # Несколько написаний. Упорядоченное сравнение по защищаемому классу отклонено выше;
            # сюда оно доходит только у полей `keep`/`scan` (токен выдан шлюзом для этого поля,
            # Ruling 19), и «больше какого из написаний» — вопрос без ответа.
            if оператор not in РАВЕНСТВА or токен_поля is None:
                raise _неоднозначный(f"[[{целиком[0]}:{целиком[1]}]]", ПОДСКАЗКА_ЗНАЧЕНИЯ)
            начало = min(литерал.start, токен_поля.start)
            конец = max(литерал.end, токен_поля.end)
            return (начало, конец, _группа(поле, оператор, литералы))
        # Обрезанный или смешанный с текстом токен — здесь, до отказа по дате рождения ниже:
        # точный код token_partial важнее общего отказа.
        self._проверить_литерал_текстом(
            содержимое, entity=entity, field=поле, оракул=False, strict=strict
        )
        if (отказ := open_literal_refusal(класс, поле, литерал.text)) is not None:
            raise отказ
        return None

    def _литерал_фильтра(
        self, entity: str, поле: str, реальное: str, *, strict: bool = False
    ) -> str:
        """Реальное значение токена как литерал OData `$filter` (I1 ревью 2026-09-10).

        Для класса `dob` с реальным значением-датой — `datetime'…'`, а не строка `'…'`: поле даты
        рождения на реальной УТ имеет тип `Edm.DateTime` (`ДатаРождения`, проба P4), и 1С отвергает
        строковый литерал `'1980-05-01'` при сравнении с ним. Значение хранится в ISO; если время
        не задано — дополняется `T00:00:00`.

        Но класс `dob` авто-классификация ставит любому строковому полю, чьё имя содержит
        `birth`/`датарождения` — в том числе `Birthplace`/`МестоРождения` (свободный текст, не
        дата). Раскрытое значение такого поля (`St. John's`, `г. Москва`) в `datetime'…'` — двойная
        поломка (N1 ревью 2026-09-10): апостроф выходит из литерала (инъекция в `$filter`, литерал
        `datetime'…'` не поддерживает удвоение кавычки), а нестрока-дата вообще невалидна. Поэтому
        `datetime'…'` — только когда раскрытое значение действительно ISO-дата/датавремя; иначе
        поле классифицировано как dob ложно, и значение возвращается обычным строковым литералом с
        экранированием, как прочие классы. Запрет ОТКРЫТОГО литерала даты для dob
        (`_открытая_дата_рождения`) это не трогает — он про литерал от модели, а не про раскрытый
        токен."""
        if self._класс_поля(entity, поле, strict=strict) == "dob" and _ISO_ДАТА.fullmatch(реальное):
            дата = реальное if "T" in реальное else f"{реальное}T00:00:00"
            return f"datetime'{дата}'"
        return f"'{_экранировать(реальное)}'"

    def _литералы_отбора(
        self,
        разобранный: tuple[str, str],
        *,
        entity: str,
        field: str,
        revealed: RevealedValues | None,
        strict: bool = False,
    ) -> list[str]:
        """Токен в отборе → литералы OData всех его написаний (Б-1): `eq` по токену обязан найти
        запись в любом написании значения, 1С сравнивает строки точно. Одинаковые литералы
        (дата рождения с временем и без уходит одним `datetime'…'`) не повторяются.

        Каждое написание — в набор вызова (`revealed.add`): все они уходят в 1С, и эхо любого
        страж обязан узнать. Оракулом раскрытие в `or` не становится: список написаний модель не
        видит, запрос возвращает записи — те же, что вернул бы `eq` по каждому написанию.

        Пределы — число написаний (`МАКС_НАПИСАНИЙ_В_ОТБОРЕ`) и длина группы в процентной записи
        (`МАКС_ДЛИНА_ГРУППЫ`). Сверх предела — отказ `token_ambiguous`, а не поиск по части
        написаний: неполный ответ без предупреждения и есть та дыра, которую правка закрывает."""
        токен, сегмент = self._проверить_право(
            разобранный, entity=entity, field=field, strict=strict
        )
        написания = self._написания(
            токен, сегмент, отбор=True, структурное=self._поле_структурное(entity, field)
        )
        литералы = list(
            dict.fromkeys(
                self._литерал_фильтра(entity, field, написание, strict=strict)
                for написание in написания
            )
        )
        if len(литералы) > МАКС_НАПИСАНИЙ_В_ОТБОРЕ or (
            len(литералы) > 1
            and len(urllib.parse.quote(_группа(field, "eq", литералы), safe="")) > МАКС_ДЛИНА_ГРУППЫ
        ):
            raise _неоднозначный(токен, ПОДСКАЗКА_ОТБОРА)
        if revealed is not None:
            for написание in написания:
                revealed.add(написание, token=токен)
        return литералы

    def _проверить_литерал_текстом(
        self, содержимое: str, *, entity: str, field: str, оракул: bool, strict: bool = False
    ) -> None:
        """Литерал — не целый токен: закрыть смешение токена с текстом и (внутри функции
        поиска подстроки на защищаемом классе, кроме org/person) закрыть оракул подбора по
        символу (Правка 1)."""
        if (отказ := token_fragment_refusal(содержимое)) is not None:
            raise отказ
        if оракул:
            класс = self._класс_поля(entity, field, strict=strict)
            if класс == contact_info.КЛАСС_НА_ВХОДЕ:
                raise _открытая_контактная_информация(field)
            if класс and класс not in ("keep", "scan") and класс not in ИМЕНОВАННЫЕ_КЛАССЫ:
                raise GateError(
                    "filter_syntax",
                    f"поиск по вхождению подстроки запрещён для поля «{field}» класса "
                    f"{класс}: образец не является токеном целиком",
                    "модель не знает защищённое значение — передайте токен целиком, запрос "
                    "перепишется в точное сравнение",
                )
        self._проверить_реальное_значение(содержимое, entity=entity, field=field, strict=strict)

    def _подставить_внутри_текста(
        self,
        текст: str,
        *,
        entity: str,
        field: str,
        revealed: RevealedValues | None,
        strict: bool = False,
    ) -> str:
        """Токены внутри текста тела записи старым путём (`body`, единственный вызывающий)."""
        куски, позиция = [], 0
        for начало, конец, класс, хвост in find_tokens(текст):
            self._не_в_структуру((класс, хвост), entity=entity, field=field, strict=strict)
            куски.append(текст[позиция:начало])
            куски.append(
                self._раскрыть(
                    (класс, хвост), entity=entity, field=field, strict=strict, revealed=revealed
                )
            )
            позиция = конец
        куски.append(текст[позиция:])
        return "".join(куски)

    def _не_в_структуру(
        self, разобранный: tuple[str, str], *, entity: str, field: str, strict: bool
    ) -> None:
        """Шаг 2а правила записи для старого пути `body` (у него нет `current`, поэтому шаг 2 не
        спасает): токен в структурное поле контактной информации — отказ. Право проверяется
        первым, как везде: ответ «структурное / нет» не должен стать оракулом для токена чужого
        класса."""
        токен, _ = self._проверить_право(разобранный, entity=entity, field=field, strict=strict)
        if self._поле_структурное(entity, field):
            raise _структура_не_по_токену(токен, field)

    def _раскрыть(
        self,
        разобранный: tuple[str, str],
        *,
        entity: str,
        field: str,
        revealed: RevealedValues | None,
        strict: bool = False,
    ) -> str:
        """Токен → реальное значение. Ruling 20, пункт 1: раскрытие допустимо ТОЛЬКО при
        известном целевом поле и совпадении класса; нет контекста — отказ, а не подстановка «на
        всякий случай».

        До этой правки проверка класса включалась лишь тогда, когда класс поля удалось
        определить: пустое имя поля (параметр рецепта, ни с чем не сравниваемый; простой ключ
        `get`) и поле без класса (`Валюта_Key` — GUID по инварианту 6, `Комментарий`) её
        отключали. Словарь отдавал реальное значение ЛЮБОГО класса, а построитель литерала
        повторял его в тексте ошибки — шлюз работал универсальным дешифратором: адрес и дата
        рождения выходили открытым текстом за один вызов, без обращения к 1С (C1/C2 ревью
        2026-09-11). Классы `addr` и `dob` не ловит ни маскировщик, ни страж — там нет ни
        детектора, ни цифровой серии, ни автомата названий, — то есть последнего рубежа у них
        нет вовсе.

        Единственное послабление — именное (Ruling 19): токен, который шлюз сам выдал для ЭТОГО
        поля ЭТОЙ сущности этой базы, продолжает работать и после того, как реиндекс переписал
        класс поля."""
        токен, сегмент = self._проверить_право(
            разобранный, entity=entity, field=field, strict=strict
        )
        написания = self._написания(
            токен, сегмент, структурное=self._поле_структурное(entity, field)
        )
        if len(написания) > 1:
            raise _неоднозначный(токен, ПОДСКАЗКА_ЗНАЧЕНИЯ)
        реальное = написания[0]
        # Единственная точка, где реальное значение появляется на свет: отсюда оно уходит в 1С,
        # и отсюда же попадает в набор вызова, чтобы страж узнал его на обратном пути (задача N1
        # M1d, инвариант 1). У классов `addr`, `dob` и свободнотекстового `doc` другого рубежа
        # нет: ни детектора, ни цифровой серии, ни варианта названия.
        if revealed is not None:
            # Формы, в которых значение уйдёт в 1С (экранирование литерала, процентная запись
            # в пути и в строке запроса), набор добавляет сам — см. `revealed.RevealedValues.add`.
            revealed.add(реальное, token=токен)
        return реальное

    def _проверить_право(
        self, разобранный: tuple[str, str], *, entity: str, field: str, strict: bool = False
    ) -> tuple[str, str]:
        """Право раскрыть токен в этом поле (Ruling 19/20/35) и само существование токена в
        словаре — общая часть всех путей раскрытия: значения, отбора и записи. Возвращает токен
        и последний сегмент пути, по которому ищутся написания. Анти-оракульная проверка идёт
        ПЕРВОЙ, раньше любого взгляда на написания и на текущее значение объекта: иначе ответ
        «однозначно / неоднозначно» сам стал бы оракулом для токена чужого класса."""
        класс, хвост = разобранный
        токен = f"[[{класс}:{хвост}]]"
        # Вариант написания ищется по последнему сегменту пути через связанный объект
        # («Контрагент/ИНН» — это ИНН контрагента, тот же приём, что у простого поля «ИНН»;
        # Обход C). Полный путь при этом остаётся в выходном тексте сравнения без изменений —
        # заменяется только сам литерал. Ожидаемый класс — через `_класс_поля` (Обход 4: раньше
        # здесь стоял прямой вызов `self._field_class(entity, сегмент)` на КОРНЕВОЙ сущности
        # запроса, а класс поля «ИНН» объявлен на сущности контрагента — для документа такого
        # поля в политике нет, `ожидаемый` был `None`, и проверка типа токена отключалась).
        сегмент = _сегмент_поля(field)
        ожидаемый = self._класс_поля(entity, field, strict=strict) if сегмент else None
        подходит = ожидаемый == класс and ожидаемый not in (None, "keep", "scan")
        # Ruling 35: у поля контактной информации на входе класс общий (`contact`), а токены
        # маскировщик выдал классами строки — телефона, почты, адреса. Любой из них раскрывается
        # в этом поле; сам класс `contact` в словаре не бывает, и токен `[[contact:…]]` здесь
        # не узнаётся (на нём отказывает `reveal` — такого токена нет).
        if ожидаемый == contact_info.КЛАСС_НА_ВХОДЕ and класс in contact_info.КЛАССЫ_ТОКЕНОВ:
            подходит = True
        # Ruling 19 (ревью 2026-09-11): класс поля входит в подпись токена, а реиндекс из тула и
        # фоновая проверка переписывают раздел `auto` политики — класс того же поля меняется
        # посреди сессии и без ведома модели. Токен, который шлюз сам выдал для ЭТОГО поля этой
        # сущности этой базы, обязан продолжать работать (инвариант 5). Сущность в ключе —
        # пункт 8 дополнения: под общим именем `Description` сходятся классы `org` и `person`.
        # Для пути через связанный объект («Контрагент/ИНН») сущность в записи о выдаче — это
        # сущность контрагента, а запрос идёт от документа, и совпасть они не могут; там ключ
        # остаётся тройкой «база, имя поля, токен».
        if not подходит and not self._dictionary.issued_for(
            токен,
            base=self._base,
            entity=None if "/" in field else entity,
            field=сегмент,
        ):
            raise GateError("token_type_mismatch", *_нет_контекста(класс, field, ожидаемый))
        if not self._dictionary.knows(токен):
            raise GateError(
                "token_unknown",
                f"токен {токен} не найден в словаре",
                "токены непрозрачны: используйте только те, что пришли в ответах",
            )
        return токен, сегмент

    def _написания(
        self, токен: str, сегмент: str, *, структурное: bool, отбор: bool = False
    ) -> list[str]:
        """Написания значения токена для чтения — лестница из двух ступеней, общая для отбора и
        одного значения (запись — `_написание_для_записи`); «несколько» считается на первой
        непустой (Б-1):

        1. написания этой базы и этого имени поля — та же область, в которой прежде искал
           написание `reveal`, — ФОРМАТА ЦЕЛЕВОГО ПОЛЯ, как на второй ступени (раунд 4). Ключ
           ступени — имя поля без сущности: написание, виденное в одноимённом поле ДРУГОЙ сущности,
           — чужой формат (структура из `ЗаявкаНаВыпускКиЗГИСМ.АдресДоставки` для текстового
           `ЗаказКлиента.АдресДоставки`, текст заказа — для структурного поля заявки). Написание
           своей сущности фильтр не отсекает: структура в поле этой сущности делает поле
           структурным (признак 3), текст в поле без признаков — текстовым. Остались написания
           после фильтра — берутся они, «несколько» считается уже по ним;
        2. если их нет вовсе (токен пришёл из другого поля или другой базы) — написания словаря
           ФОРМАТА ЦЕЛЕВОГО ПОЛЯ (Ruling 38): в структурное поле — только структуры БСП, в
           текстовое — написания текстом и представления структур (`_текстом`). JSON поля
           `Значение` в текстовую колонку не идёт: колонка поиска телефона хранит цифры, и отбор
           JSON-ом не находил ничего (живьём 1 из 10 против 5 из 10 до написаний, Н-1). Для отбора
           (`отбор=True`) на этой ступени к группе добавляется нормализованная форма — то, чем
           искал шлюз до написаний: у колонки поиска телефона это и есть её содержимое.

        Почему лестница, а не объединение всех написаний словаря даже для отбора, где лишнее
        условие `or` ничего не ломает. Написание из другого поля — догадка, а не знание: у
        телефона в табличной части контактной информации одно значение лежит и в `Представление`
        («+7 (4912) …»), и цифрами в соседней колонке, у JSON поля `Значение` тот же токен вовсе не
        написание значения. Объединение раздувало бы группу `or` такими догадками до предела длины
        запроса и превращало бы рабочий отбор в отказ; а запись, которую ищут, лежит в этом поле в
        написании, которое словарь видел В ЭТОМ поле, — ради этого случая правка и делается.

        Второе написание в чужом поле неоднозначности в этом поле не создаёт. Написаний формата
        поля нет нигде (словарь, заведённый до хранения написаний, или значение, виденное только
        в другом формате) — нормализованная форма, как прежде: для значения, которое станет
        операндом сравнения, другого способа нет. Запись её не берёт — см.
        `_написание_для_записи`.

        `структурное` — признак поля (`_поле_структурное`, Ruling 43) без `current`: у отбора и
        одного значения текущего значения нет. Тот же признак, что у записи: колонка
        `ПроизводственныйОбъектАдрес` хранит структуру, и текстовое написание в ней не найдёт
        ничего — пустой отбор в M2 значил бы «объекта нет»."""
        if сегмент:
            свои = self._формата_поля(
                токен,
                self._dictionary.spellings(токен, base=self._base, field=сегмент),
                структурное=структурное,
            )
            if свои:
                return свои
        кандидаты = self._формата_поля(
            токен, self._dictionary.spellings(токен), структурное=структурное
        )
        нормализованное = self._dictionary.reveal(токен)
        if (отбор or not кандидаты) and нормализованное is not None:
            кандидаты = list(dict.fromkeys([*кандидаты, нормализованное]))
        return кандидаты

    def _формата_поля(self, токен: str, написания: list[str], *, структурное: bool) -> list[str]:
        """Написания в формате целевого поля (Ruling 38): в структурное — только структуры
        (`contact_info.is_structure`), в текстовое — текст как есть и представления структур
        (`_текстом`, формат — по основе токена, `Dictionary.structure_of`)."""
        if структурное:
            return [написание for написание in написания if contact_info.is_structure(написание)]
        return _текстом(
            написания, lambda написание: self._dictionary.structure_of(токен, написание)
        )

    def _класс_поля(self, entity: str, field: str, *, strict: bool = False) -> str | None:
        """Класс по имени поля (Обход C — путь через связанный объект берётся по последнему
        сегменту) с двумя усилениями третьего раунда ревью.

        Обход 4 (Critical): `field_class(entity, сегмент)` ищет класс в политике ПО ПАРЕ
        «корневая сущность запроса + имя поля» — а для пути через связанный объект
        («Контрагент/ИНН» от документа) поле «ИНН» зарегистрировано в политике на сущности
        контрагента, а не документа: `field_class("Document_...", "ИНН")` закономерно не находит
        ничего, и разом отключаются все три проверки (контрольная сумма, оракул подстроки,
        упорядоченное сравнение). Если политика по корневой сущности ничего не дала — спрашиваем
        `classify_field` (тот же классификатор, что размечает секцию auto при реиндексе): его
        первый слой (СНИЛС/ИНН/КПП/счета/телефоны/...) целиком по имени поля, без привязки к
        сущности — «ИНН» для него ИНН независимо от того, где он лежит. Тот же приём уже
        применяется в прямой подмене для раскрытых вложенных объектов (`masking.py`,
        `_базовый_класс_поля`) — `names_for=set()` отключает третий (сущность-зависимый) слой
        классификатора по той же причине, что и там: сущность на этом уровне обхода — корневая
        сущность запроса, а не настоящая сущность связанного объекта, и слой Description/ФИО по
        принадлежности к `names_for` для чужой сущности даст неверный ответ.

        Правка 7 (Minor): если и `classify_field` по имени последнего сегмента ничего не нашёл —
        для ПРОСТОГО имени поля (без «/») это законный ответ «поле не защищено» (комментарий,
        сумма, обычный текст) и остаётся им. Но для ПУТИ через связанный объект, где сегмент
        перед последним сам распознаётся классификатором как ссылка на контрагента/физлицо
        («Контрагент», «ФизЛицо», ...) — то есть мы точно знаем, что находимся внутри объекта,
        несущего защищаемые данные, а имя конкретного поля внутри него классификатору незнакомо —
        тихий пропуск и есть та самая дыра: отказываем, а не проверяем «повезёт — не повезёт».
        Путь к контейнеру, который сам не похож на ссылку на контрагента/физлицо (например,
        «Склад/Наименование»), под это исключение не попадает и продолжает работать как обычное
        незащищённое поле — это отдельно проверено тестом.
        """
        сегменты = field.split("/") if field else []
        if not сегменты:
            return None
        # Ruling 37: путь, пришедший в табличную часть контактной информации, получает класс по
        # сущности, в которую пришёл, а не по последнему сегменту на корне — у корня поля
        # `Представление` нет, и прежний поиск ниже его не находил (оракул C-1 ревью 8). `None` —
        # путь правилу не подлежит, дальше прежний порядок без изменений.
        if len(сегменты) > 1:
            класс = self._path_class(entity, field)
            if класс is not None:
                return класс
        сегмент = сегменты[-1]
        класс = self._field_class(entity, сегмент, strict=strict)
        # Раунд 2 ревью (I2): запасной классификатор получает тип "Edm.String" вслепую и видит
        # «сотрудник»/«физлицо»/«руководител» в `Сотрудник_Key` — а это GUID ссылки, который не
        # защищается ни на одном уровне (инвариант 6). Ключи ссылок и их типы запасной
        # классификации не подлежат; явный класс из политики (`field_class`) по-прежнему главный.
        if класс is None and not _ссылочный_ключ(сегмент):
            найдено = classify_field(entity, сегмент, "Edm.String", names_for=set())
            класс = найдено[0] if найдено is not None else None
        if класс is not None:
            return класс
        if len(сегменты) < 2:
            return None
        контейнер = сегменты[-2]
        if classify_field(entity, контейнер, "Edm.String", names_for=set()) is not None:
            raise GateError(
                "filter_syntax",
                f"класс поля «{field}» не определён: сегмент пути «{контейнер}» указывает на "
                "связанный объект, содержащий защищаемые данные, а имя конечного поля "
                "классификатору не известно",
                "используйте известное имя поля или проверьте написание пути",
            )
        return None

    def _проверить_реальное_значение(
        self, значение: str, *, entity: str, field: str, strict: bool = False
    ) -> None:
        """Реальное значение от модели (ИНН из промпта) проходит контрольную сумму (SPEC §6.7).

        Код ошибки — filter_syntax: отдельного кода для «значение не прошло контрольную сумму»
        в перечне SPEC §5.2 нет, а новые коды заводятся только через ADR с правкой §5.2.
        Смысл сохранён: запрос от модели синтаксически неприемлем и в 1С не уходит. Тот же код
        переиспользован для «поле не определено», «оракул подбора» и «упорядоченное сравнение
        по защищаемому полю» (Правка 1, обходы A и B) — по той же причине: это не новый смысл
        ошибки, а тот же самый «запрос от модели неприемлем».
        """
        класс = self._класс_поля(entity, field, strict=strict)
        проверка = ПРОВЕРКИ.get(класс or "")
        if проверка is None or not значение:
            return
        цифры = re.sub(r"\D", "", значение)
        if цифры and not проверка(цифры):
            raise GateError(
                "filter_syntax",
                f"значение «{значение}» не проходит контрольную сумму класса {класс}",
                "проверьте значение, полученное от пользователя",
            )


def _нет_контекста(класс: str, поле: str, ожидаемый: str | None) -> tuple[str, str]:
    """Сообщение и подсказка отказа в раскрытии (Ruling 20, пункты 1 и 2). Строятся из КЛАССА
    токена и ИМЕНИ ПОЛЯ — самого значения в тексте отказа нет и быть не может: текст ошибки идёт
    наружу тем же путём, что и данные, а у половины классов последнего рубежа нет вовсе."""
    if not _сегмент_поля(поле):
        return (
            f"токен класса {класс} подставлен туда, где целевое поле неизвестно",
            "токен раскрывается только там, где он сравнивается с полем своего класса",
        )
    if ожидаемый in (None, "keep", "scan"):
        return (
            f"токен класса {класс} подставлен в поле «{поле}», которое шлюз не защищает: "
            "раскрывать его здесь не для чего",
            "сравнивайте токен с тем полем, из которого он пришёл",
        )
    return (
        f"токен класса {класс} подставлен в поле «{поле}» класса {ожидаемый}",
        "проверьте, из какого поля взят токен",
    )


ПОДСКАЗКА_КОНТАКТНОЙ_ИНФОРМАЦИИ = (
    "отбор по контактной информации — только токеном из ответа: «Представление eq '<токен>'»; "
    "строки по виду отбирайте полем Тип (Тип eq 'Телефон'), по владельцу — Ref_Key"
)


def _открытая_контактная_информация(поле: str) -> GateError:
    """Отказ по открытому литералу в отборе по полю контактной информации (Ruling 35).

    Правило то же, что у даты рождения (`_открытая_дата_рождения`), и по той же причине: равенство
    с открытым литералом, поиск подстроки и сравнение по величине — это оракул членства, по ответам
    «есть / нет» номер телефона или адрес почты подбирается перебором, ни разу не показанный модели.
    Самого литерала в тексте отказа нет: его написала модель, но это может быть продиктованный
    пользователем номер, и повторять его в ответе незачем. Цена: отобрать «все телефоны с кодом
    495» или строку по номеру, названному в промпте, нельзя — отбор по `Тип`, ссылкам и виду
    контактной информации остаётся."""
    return GateError(
        "filter_syntax",
        f"поле «{поле}» — контактная информация: в отборе допустим только целый токен из ответа, "
        "открытый литерал, поиск подстроки и сравнение по величине не принимаются — по ответам "
        "«есть / нет» значение подбирается перебором",
        ПОДСКАЗКА_КОНТАКТНОЙ_ИНФОРМАЦИИ,
    )


def token_fragment_refusal(содержимое: str) -> GateError | None:
    """`token_partial`, если литерал — не целый токен, но несёт токен или его обрезок внутри.

    Общий предикат отбора на чтении (`_проверить_литерал_текстом`) и пишущего тула на поле,
    которое принимает только токен (`BaseGate.check_open_literal`): точный код важнее общего
    отказа по открытому литералу, и запись отвечает на такой литерал тем же, что чтение."""
    if is_partial_token(содержимое) or (
        TOKEN_RE.search(содержимое) and содержимое.strip() != содержимое
    ):
        return GateError(
            "token_partial",
            f"в литерале «{содержимое}» токен использован как часть строки",
            "передайте токен целиком и сравнивайте через eq",
        )
    if find_tokens(содержимое):
        return GateError(
            "token_partial",
            f"в литерале «{содержимое}» токен смешан с текстом",
            "передайте токен целиком и сравнивайте через eq",
        )
    return None


def open_literal_refusal(класс: str | None, поле: str, литерал: str) -> GateError | None:
    """Отказ по открытому литералу для поля, которое на входе принимает ТОЛЬКО целый токен, —
    или `None`, если класс поля открытый литерал допускает.

    Одно место для правила, которое раньше было записано прямо в разборе отбора: `dob` (Ruling
    21) и `contact` (Ruling 35) — классы, где равенство с открытым литералом становится оракулом
    членства (мало значений или подбор по «есть / нет»). Вынесено ради записи (Ruling 45, находка
    I-1 ревью задачи 5 M2): подготовка `update` сравнивает тело с текущим состоянием и отвечает
    «изменений нет» — тот же вопрос «равно ли поле этому литералу», что `eq` на чтении. Правило
    обязано быть одним и тем же на обоих путях, а не двумя списками классов, которые разойдутся
    при следующей правке."""
    if класс == "dob":
        return _открытая_дата_рождения(поле, литерал)
    if класс == contact_info.КЛАСС_НА_ВХОДЕ:
        return _открытая_контактная_информация(поле)
    return None


def _открытая_дата_рождения(поле: str, литерал: str) -> GateError:
    """Отказ по открытому литералу в сравнении с полем класса dob (Ruling 21 M1c, SPEC §6.7).

    Равенство разрешено защищаемым классам ради поиска по значению, названному пользователем
    (ИНН из промпта проходит контрольную сумму), но у даты рождения пространство значений мало:
    ~36,5 тыс. дат за сто лет, и цепочка `ДатаРождения eq datetime'…' or …` из десятков равенств
    перебирает его за сотни запросов — оракул членства. Поэтому для dob в `$filter` допустим
    только целый токен из ответа; прочие классы правило не задевает. Цена: пользователь не может
    отобрать по дате рождения, названной в промпте, — случай редкий."""
    return GateError(
        "filter_syntax",
        f"поле «{поле}» класса dob сравнивается с открытым литералом «{литерал}»: перебором "
        "равенств дата рождения подбирается за сотни запросов",
        "дату рождения в отборе можно задать только токеном из ответа",
    )


def _литерал(токен: Token) -> bool:
    """Операнд-литерал тройки сравнения: литерал лексера или ключевое слово null/true/false."""
    if токен.kind in ЛИТЕРАЛЬНЫЕ_ВИДЫ:
        return True
    return токен.kind == "identifier" and токен.text.lower() in КЛЮЧЕВЫЕ_ЛИТЕРАЛЫ


def _поле(значимые: list[Token], индекс: int) -> bool:
    """Идентификатор-поле: не ключевое слово и не имя функции (за ним нет «(»)."""
    токен = значимые[индекс]
    if токен.kind != "identifier" or токен.text.lower() in КЛЮЧЕВЫЕ_ЛИТЕРАЛЫ:
        return False
    следующий = значимые[индекс + 1] if индекс + 1 < len(значимые) else None
    return not (следующий is not None and следующий.kind == "paren" and следующий.text == "(")


def _тройка_обособлена(значимые: list[Token], начало: int, конец: int) -> bool:
    """Тройка `значимые[начало..конец]` — сравнение целиком, а не операнд более тесной операции.

    Слева допустимы: начало выражения, and/or/not, «:» лямбды и группирующая «(» (перед ней не
    идентификатор — иначе это скобка вызова функции, и тройка оказалась бы её аргументом).
    Справа: конец выражения, and/or и «)». Закрывающая скобка безопасна при любой левой границе:
    если тройка и лежит внутри вызова (`f(a and ИНН eq '…')`), функции достаётся только булев
    результат сравнения, а не значение поля. Всё остальное — не граница (см. `ЛЕВЫЕ_ГРАНИЦЫ`)."""
    if not _левая_граница(значимые, начало - 1):
        return False
    if конец + 1 < len(значимые):
        справа = значимые[конец + 1]
        if справа.kind == "paren":
            return справа.text == ")"
        return справа.kind == "operator" and справа.text.lower() in ПРАВЫЕ_ГРАНИЦЫ
    return True


def _ссылочный_ключ(поле: str) -> bool:
    """Поле ссылки 1С в OData: `Ref_Key`, `<Реквизит>_Key` (GUID) и `<Реквизит>_Type` (имя
    типа составной ссылки). Значение — идентификатор, а не реквизит (инвариант 6)."""
    return поле == "Ref_Key" or поле.endswith(("_Key", "_Type"))


def _левая_граница(значимые: list[Token], индекс: int) -> bool:
    """Токен `значимые[индекс]` (или начало выражения при отрицательном индексе) — левая граница
    обособленной тройки. `not` — граница, только если граница стоит перед ним самим (раунд 2
    ревью, M1): в `Сумма add not ИНН eq '…'` отрицание — операнд сложения, и поле попадает под
    арифметику, хотя соседний с тройкой токен — `not`."""
    while индекс >= 0:
        токен = значимые[индекс]
        if токен.kind == "paren":
            if токен.text != "(":
                return False
            return not (индекс > 0 and значимые[индекс - 1].kind == "identifier")
        if токен.kind != "operator":
            return False
        оп = токен.text.lower()
        if оп != "not":
            return оп in ЛЕВЫЕ_ГРАНИЦЫ
        индекс -= 1
    return True


def _части_условий(значимые: list[Token]) -> list[int]:
    """Номер условия между and/or для каждого токена — на любой глубине скобок (раунд 2 ревью,
    I1). and/or связывают слабее любых других операторов OData, поэтому литерал и поле из разных
    частей не могут быть операндами одной операции сравнения или арифметики: от одной части к
    другой проходит только булев результат. Разбиение идёт и внутри скобок, без разбора
    грамматики: мельче, чем по грамматике, оно режет только там, где and/or стоит внутри операнда
    арифметики или сравнения (`ИНН add (x or 5) gt 3`), — а в такой форме защищаемое поле уже не
    в обособленной тройке, и её отклоняет первая линия, правило вхождений."""
    части: list[int] = []
    номер = 0
    for токен in значимые:
        if токен.kind == "operator" and токен.text.lower() in СОЮЗЫ:
            номер += 1
        части.append(номер)
    return части


def _снять_кавычки(литерал: str) -> str:
    return литерал[1:-1].replace("''", "'") if литерал.startswith("'") else литерал


def _экранировать(значение: str) -> str:
    return значение.replace("'", "''")


def _путь(префикс: str, ключ: str) -> str:
    """Составить путь-имя поля при спуске в тело записи: пустой префикс — ключ как есть,
    иначе `префикс/ключ` — та же нотация, что и путь через связанный объект в `$filter`
    (`_сегмент_поля` берёт из неё последний сегмент для класса и варианта написания)."""
    return f"{префикс}/{ключ}" if префикс else ключ


def _сегмент_поля(поле: str) -> str:
    """Последний сегмент пути через связанный объект: «Контрагент/ИНН» → «ИНН» (Обход C, ревью
    задачи 7). Простое имя поля без «/» возвращается как есть."""
    return поле.rsplit("/", 1)[-1] if поле else ""


def _группа(поле: str, оператор: str, литералы: list[str]) -> str:
    """Сравнение поля с несколькими литералами (Б-1): `eq` — любое из написаний (`or`), `ne` — ни
    одно (`and`). Скобки обязательны: группа встаёт на место одной тройки внутри чужого выражения
    (`A and X eq t` → `A and (X eq a or X eq b)`), и без скобок `and` соседнего условия связал бы
    только первое написание. Одно написание — обычная тройка без скобок, как было до правки."""
    if len(литералы) == 1:
        return f"{поле} {оператор} {литералы[0]}"
    связка = " or " if оператор == "eq" else " and "
    return "(" + связка.join(f"{поле} {оператор} {литерал}" for литерал in литералы) + ")"


def _номер_строки(строка) -> str | None:
    """`LineNumber` строки табличной части как строка (1С отдаёт его и строкой, и числом)."""
    if isinstance(строка, dict) and строка.get("LineNumber") is not None:
        return str(строка["LineNumber"])
    return None


def _строки_по_номеру(текущее) -> dict[str, dict]:
    """Строки табличной части текущего состояния объекта по `LineNumber` (см. `Unmasker.write`)."""
    if not isinstance(текущее, list):
        return {}
    return {номер: строка for строка in текущее if (номер := _номер_строки(строка)) is not None}


def _развернуть(текущее, revealed: RevealedValues | None) -> str | None:
    """Текущее значение поля как строка с реальным содержимым. Строка, переписанная ранним
    проходом (`ScrubbedText`), разворачивается в исходное значение своего места через набор
    вызова (Б-3); чужой вызов исходного не знает — тогда текущего значения для правила записи
    нет. Не строка (число, `null`, вложенный объект) — тоже нет."""
    if isinstance(текущее, ScrubbedText):
        return revealed.original_of(текущее) if revealed is not None else None
    return текущее if isinstance(текущее, str) else None


def _текстом(написания: list[str], структура: Callable[[str], bool]) -> list[str]:
    """Написания для текстового поля (Ruling 38, пункт 2): текст — как есть, структура
    (`contact_info.is_structure`: из неё извлекается представление, с `type` из перечисления или
    без, Р2-2) — её представлением, той же основой, по которой построен токен. Без повторов и по
    порядку: текст «+7 (495) …» из `Представление` и JSON с тем же `value` из `Значение` — одно
    написание, а не два. Структура без представления (JSON БСП без `value`) в текстовое поле не
    идёт вовсе: подставить из неё нечего.

    `структура` — формат написания для этого токена (`Dictionary.structure_of`): JSON без
    `type`, по которому токен построен целиком (поле с классом вне контактной информации), —
    само значение, а не структура с ним, и идёт как есть."""
    результат: set[str] = set()
    for написание in написания:
        if not структура(написание):
            результат.add(написание)
            continue
        представление = contact_info.representation(написание)
        if представление != написание:
            результат.add(представление)
    return sorted(результат)


ПОДСКАЗКА_СТРУКТУРЫ = (
    "новое значение контактной информации передайте открытым значением, которое продиктовал "
    "пользователь: собирать структуру БСП (JSON/XML) по токену шлюз не берётся"
)


def _структура_не_по_токену(токен: str, поле: str) -> GateError:
    """Отказ записи токена в структурное поле контактной информации (Ruling 38, пункт 4): в поле
    объекта этого значения нет, а подставить JSON/XML, который словарь видел в другой записи,
    значит молча перенести её данные (`comment`, индекс, добавочный номер) — превью покажет тот же
    токен. Код — `token_ambiguous`: однозначного написания для этого поля у шлюза нет."""
    return GateError(
        "token_ambiguous",
        f"поле «{поле}» хранит значение контактной информации структурой БСП, а значения токена "
        f"{токен} в этом поле объекта нет: какую структуру записать, однозначно не определить",
        ПОДСКАЗКА_СТРУКТУРЫ,
    )


def _неоднозначный(токен: str, подсказка: str) -> GateError:
    """Отказ `token_ambiguous` (Б-1). В тексте — токен и слово «несколько»: ни самих написаний,
    ни их числа. Текст ошибки уходит модели тем же путём, что данные (Ruling 20, пункт 2), а
    сколько разных написаний у значения в базе — метаданные о данных, для работы модели не нужные
    (M-1 ревью блокеров M2)."""
    return GateError(
        "token_ambiguous",
        f"у значения токена {токен} в словаре несколько написаний (разный регистр, кавычки, "
        "пробелы), и какое из них подставить, однозначно не определить",
        подсказка,
    )


def _собрать(expression: str, сегменты: list[tuple[int, int, str]]) -> str:
    """Склеить исходное выражение с точечными заменами (Правка 3): вне сегментов текст остаётся
    посимвольно как был — переписывание одного вызова не должно задевать соседние условия.

    Пересечение сегментов — отказ, а не склейка (Б-1): группа написаний заменяет тройку целиком
    вместе с полем, и вторая замена, задевшая то же поле (`'t' eq ИНН eq 't'`), склеилась бы в
    бессмыслицу. Правило вхождений такую форму для защищаемых полей уже отклоняет; здесь —
    страховка для всех остальных."""
    куски: list[str] = []
    позиция = 0
    for начало, конец, замена in sorted(сегменты, key=lambda сегмент: сегмент[0]):
        if начало < позиция:
            raise GateError(
                "filter_syntax",
                "структура сравнения не распознана: одно поле участвует в двух сравнениях подряд",
                "запишите каждое сравнение отдельно и соедините их через and/or",
            )
        куски.append(expression[позиция:начало])
        куски.append(замена)
        позиция = конец
    куски.append(expression[позиция:])
    return "".join(куски)
