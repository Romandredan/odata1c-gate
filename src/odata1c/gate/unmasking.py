"""Обратная подмена: токены модели → реальные значения перед отправкой в 1С (SPEC §6.7).

Точки входа: $filter, ключи в URL, params виртуальных таблиц и рецептов, тела create/update,
params действий, query у raw_get. Обратимость существует только внутри гейта.

Ревью задачи 7 (2026-09-09): поле, к которому относится строковый литерал внутри `$filter`,
определяется по СТРУКТУРЕ сравнения (что стоит по другую сторону оператора или какой аргумент
функции — идентификатор), а не по близости («последний идентификатор левее литерала» обходился
перестановкой операндов и открывал оракул подбора через `substringof`). Если поле определить не
удалось — запрос отклоняется, а не уходит в 1С непроверенным (Правка 1).

Второй раунд ревью (2026-09-09) нашёл три работающих обхода анти-оракульного правила:
неоднозначный аргумент функции поиска (вложенный вызов вроде `concat(ИНН, '')`) молча пропускал
проверки; упорядоченное сравнение (`gt`/`ge`/`lt`/`le`) вообще не проходило через анти-оракульную
проверку, только через контрольную сумму, которой нет у большинства классов; путь через связанный
объект («Контрагент/ИНН») не находил класс вовсе, потому что классификатор ищет по точному имени
поля. Все три закрыты: форма вызова функции проверяется целиком (ровно два простых аргумента —
строка и идентификатор, без вложенных выражений) до какой-либо пометки диапазона обработанным;
упорядоченное сравнение с литералом на защищаемом классе отклоняется без исключений (SPEC не
разрешает диапазонный поиск по непрозрачным значениям, в отличие от точного поиска по названию);
класс ищется по последнему сегменту пути.
"""

from __future__ import annotations

import re
from collections.abc import Callable

from odata1c.gate.detectors import inn_valid, ogrn_valid, snils_valid
from odata1c.gate.dictionary import НУМЕРУЕМЫЕ, Dictionary
from odata1c.gate.filter_lexer import Token, lex_filter
from odata1c.gate.tokens import TOKEN_RE, find_tokens, is_partial_token, parse_token

ФУНКЦИИ_ПОДСТРОКИ = ("substringof", "startswith", "endswith")
ПРОВЕРКИ = {"inn": inn_valid, "ogrn": ogrn_valid, "snils": snils_valid}
СРАВНЕНИЯ = frozenset({"eq", "ne", "gt", "ge", "lt", "le"})
УПОРЯДОЧЕННЫЕ = frozenset({"gt", "ge", "lt", "le"})
# org/person — пользователь называет их сам, поиск по вхождению текста, который он написал,
# разрешён без токена (SPEC §6.5). Для остальных защищаемых классов (номера, коды, документы)
# модель никогда не видит реальное значение и не может знать, что искать частью строки —
# единственная причина такого запроса — подбор по символу (Правка 1, «закрыть оракул»). У
# упорядоченного сравнения (Обход B) исключения для org/person НЕТ — SPEC не даёт основания
# для диапазонного/бинарного поиска по названию, в отличие от точного поиска по подстроке.
ИМЕНОВАННЫЕ_КЛАССЫ = frozenset(НУМЕРУЕМЫЕ)


class GateError(Exception):
    def __init__(self, code: str, message: str, hint: str = "") -> None:
        super().__init__(message)
        self.code = code
        self.hint = hint


class Unmasker:
    def __init__(
        self, dictionary: Dictionary, *, base: str, field_class: Callable[[str, str], str | None]
    ) -> None:
        self._dictionary = dictionary
        self._base = base
        self._field_class = field_class

    def filter(self, expression: str, *, entity: str) -> str:
        значимые = [лексема for лексема in lex_filter(expression) if лексема.kind != "space"]
        # _вызовы_функций проверяет форму каждого вызова (ровно два простых аргумента) и
        # отказывает сразу же, до вычисления "занято" ниже — неоднозначный вызов не должен
        # успеть пометить свой диапазон обработанным, минуя общую проверку (Обход A).
        вызовы = self._вызовы_функций(значимые)

        занято: set[int] = set()
        for вызов in вызовы:
            занято.update(range(вызов["start"], вызов["close"] + 1))

        поля_сравнений = self._поля_сравнений(значимые, занято)

        сегменты: list[tuple[int, int, str]] = []
        for вызов in вызовы:
            сегмент = self._обработать_вызов(вызов, значимые, entity=entity)
            if сегмент is not None:
                сегменты.append(сегмент)

        for индекс, (поле, оператор) in поля_сравнений.items():
            сегмент = self._обработать_сравнение(значимые[индекс], поле, оператор, entity=entity)
            if сегмент is not None:
                сегменты.append(сегмент)

        обработанные = {вызов["literal_idx"] for вызов in вызовы}
        обработанные |= set(поля_сравнений)
        for индекс, токен in enumerate(значимые):
            if токен.kind != "string" or индекс in обработанные or индекс in занято:
                continue
            raise GateError(
                "filter_syntax",
                f"не удалось определить поле для литерала «{токен.text}»: структура сравнения "
                "не распознана",
                "сравнивайте литерал с полем через eq/ne/gt/ge/lt/le или через substringof/"
                "startswith/endswith",
            )

        return _собрать(expression, сегменты)

    def value(self, text: str, *, entity: str, field: str) -> str:
        """Одно значение: параметр рецепта, элемент ключа, аргумент действия."""
        if not isinstance(text, str):
            return text
        целиком = parse_token(text)
        if целиком:
            return self._раскрыть(целиком, entity=entity, field=field)
        if is_partial_token(text):
            raise GateError(
                "token_partial",
                "в значении обрезанный токен; передайте токен целиком",
                "токены непрозрачны: их нельзя достраивать и обрезать",
            )
        if find_tokens(text):
            return self._подставить_внутри_текста(text, entity=entity, field=field)
        self._проверить_реальное_значение(text, entity=entity, field=field)
        return text

    def body(self, data, *, entity: str):
        if isinstance(data, dict):
            return {
                ключ: self._обойти_значение(значение, entity=entity, field=ключ)
                for ключ, значение in data.items()
            }
        # Верхний уровень без словаря (голая строка или список — например, список значений
        # табличной части без обёртки-объекта) обходится тем же путём, что и вложенное значение
        # под пустым именем поля: раньше здесь была отдельная ветка для list, которая рекурсивно
        # звала body() для каждого элемента, а body() строку саму по себе не обрабатывал вовсе —
        # токен в такой строке уходил в 1С дословно, обрезанный не отклонялся (Правка 4, ревью
        # задачи 7). `_обойти_значение` уже умеет строку/словарь/список/прочее в одном месте.
        # Имя поля здесь неизбежно пустое (это верхний уровень — ключа, под которым лежало бы
        # значение, попросту нет) — обратное чтение вернёт нормализованное значение, а не
        # вариант по базе/полю, и проверка класса не сработает (нечем проверять). Для значения
        # под конкретным ключом (`body({"ИНН": ...})`) или элемента списка под ключом
        # (`body({"Учредители": [...]})`) имя поля есть и используется — degradация касается
        # только по-настоящему безымянного верхнего уровня (Правка D, зафиксировано как принятое
        # ограничение интерфейса `body(data, *, entity)` без параметра поля).
        return self._обойти_значение(data, entity=entity, field="")

    def key(self, value, *, entity: str):
        if isinstance(value, dict):
            результат = {}
            for ключ, часть in value.items():
                # Испорченный токен, случайно оказавшийся в ИМЕНИ поля составного ключа —
                # подставлять там нечего (это не значение), но он всё равно обязан вызвать
                # отказ, а не пройти незамеченным (Правка 5, ревью задачи 7).
                if is_partial_token(ключ):
                    raise GateError(
                        "token_partial",
                        f"в имени поля составного ключа «{ключ}» обрезанный токен",
                        "токены непрозрачны: их нельзя достраивать и обрезать",
                    )
                результат[ключ] = (
                    self.value(часть, entity=entity, field=ключ)
                    if isinstance(часть, str)
                    else часть
                )
            return результат
        return self.value(value, entity=entity, field="") if isinstance(value, str) else value

    def _обойти_значение(self, значение, *, entity: str, field: str):
        if isinstance(значение, str):
            return self.value(значение, entity=entity, field=field)
        if isinstance(значение, dict):
            return self.body(значение, entity=entity)
        if isinstance(значение, list):
            return [
                self._обойти_значение(элемент, entity=entity, field=field) for элемент in значение
            ]
        return значение

    # ------------------------------------------------------------------
    # Разбор структуры $filter (Правки 1, 3 и обходы A–C — ревью задачи 7)
    # ------------------------------------------------------------------

    def _вызовы_функций(self, значимые: list[Token]) -> list[dict]:
        """Найти вызовы substringof/startswith/endswith и сразу проверить их форму: ровно два
        простых аргумента (один — идентификатор поля, другой — строковый образец), независимо
        от порядка. Любая неоднозначность — отказ здесь же, до дальнейшей обработки (Обход A):
        `substringof('7707', concat(ИНН, ''))` не должен молча пройти как «поле не найдено»."""
        вызовы: list[dict] = []
        i, n = 0, len(значимые)
        while i < n:
            токен = значимые[i]
            if (
                токен.kind == "identifier"
                and токен.text.lower() in ФУНКЦИИ_ПОДСТРОКИ
                and i + 1 < n
                and значимые[i + 1].kind == "paren"
                and значимые[i + 1].text == "("
            ):
                открывающая = i + 1
                закрывающая = self._найти_закрывающую(значимые, открывающая)
                literal_idx, field_idx = self._разобрать_аргументы(
                    значимые, открывающая, закрывающая, имя=токен.text.lower()
                )
                вызовы.append(
                    {
                        "name": токен.text.lower(),
                        "start": i,
                        "close": закрывающая,
                        "literal_idx": literal_idx,
                        "field_idx": field_idx,
                        # Под отрицанием "not" переписанное сравнение нужно взять в скобки —
                        # иначе "not X eq Y" по правилам OData свяжется как "(not X) eq Y", а
                        # не "not (X eq Y)" (Правка F). "not" — единственный оператор OData v3,
                        # который связывает сильнее сравнения; and/or связывают слабее, поэтому
                        # непосредственно перед ними скобки не нужны.
                        "under_not": i > 0
                        and значимые[i - 1].kind == "operator"
                        and значимые[i - 1].text.lower() == "not",
                    }
                )
                i = закрывающая + 1
                continue
            i += 1
        return вызовы

    def _найти_закрывающую(self, значимые: list[Token], открывающая: int) -> int:
        глубина = 1
        j, n = открывающая + 1, len(значимые)
        while j < n and глубина > 0:
            if значимые[j].kind == "paren":
                глубина += 1 if значимые[j].text == "(" else -1
            j += 1
        if глубина != 0:
            raise GateError(
                "filter_syntax",
                "непарные скобки в вызове функции поиска подстроки",
                "проверьте выражение отбора",
            )
        return j - 1

    def _разбить_аргументы(
        self, значимые: list[Token], открывающая: int, закрывающая: int
    ) -> list[list[int]]:
        """Индексы токенов каждого аргумента верхнего уровня вызова (запятые внутри вложенных
        скобок аргумент не разделяют)."""
        аргументы: list[list[int]] = []
        текущий: list[int] = []
        глубина = 0
        for idx in range(открывающая + 1, закрывающая):
            токен = значимые[idx]
            if токен.kind == "paren":
                глубина += 1 if токен.text == "(" else -1
                текущий.append(idx)
                continue
            if токен.kind == "comma" and глубина == 0:
                аргументы.append(текущий)
                текущий = []
                continue
            текущий.append(idx)
        аргументы.append(текущий)
        return аргументы

    def _разобрать_аргументы(
        self, значимые: list[Token], открывающая: int, закрывающая: int, *, имя: str
    ) -> tuple[int, int]:
        """Ровно два аргумента, один — простой идентификатор, другой — простая строка. Любое
        отклонение от этой формы (не два аргумента, вложенный вызов, оба одного вида) — отказ,
        а не попытка угадать, что имелось в виду (Обход A)."""
        аргументы = self._разбить_аргументы(значимые, открывающая, закрывающая)
        роли: list[tuple[str, int | None]] = []
        for arg in аргументы:
            if len(arg) == 1 and значимые[arg[0]].kind in ("string", "identifier"):
                роли.append((значимые[arg[0]].kind, arg[0]))
            else:
                роли.append(("complex", None))
        виды = sorted(вид for вид, _ in роли)
        if len(аргументы) != 2 or виды != ["identifier", "string"]:
            raise GateError(
                "filter_syntax",
                f"не удалось однозначно определить поле и образец для {имя}(...)",
                "функция поиска подстроки сравнивает простой строковый образец с простым "
                "полем-идентификатором, без вложенных выражений",
            )
        literal_idx = next(idx for вид, idx in роли if вид == "string")
        field_idx = next(idx for вид, idx in роли if вид == "identifier")
        return literal_idx, field_idx

    def _поля_сравнений(
        self, значимые: list[Token], занято: set[int]
    ) -> dict[int, tuple[str, str]]:
        """Поле и оператор для литерала в бинарном сравнении: идентификатор по другую сторону
        оператора от литерала, в любом порядке (Правка 1)."""
        поля: dict[int, tuple[str, str]] = {}
        for i in range(len(значимые) - 2):
            if i in занято or i + 1 in занято or i + 2 in занято:
                continue
            левый, оператор, правый = значимые[i], значимые[i + 1], значимые[i + 2]
            if оператор.kind != "operator" or оператор.text.lower() not in СРАВНЕНИЯ:
                continue
            оп = оператор.text.lower()
            if левый.kind == "identifier" and правый.kind == "string":
                поля[i + 2] = (левый.text, оп)
            elif левый.kind == "string" and правый.kind == "identifier":
                поля[i] = (правый.text, оп)
        return поля

    def _обработать_вызов(
        self, вызов: dict, значимые: list[Token], *, entity: str
    ) -> tuple[int, int, str] | None:
        литерал = значимые[вызов["literal_idx"]]
        поле = значимые[вызов["field_idx"]].text
        содержимое = _снять_кавычки(литерал.text)
        целиком = parse_token(содержимое)
        if целиком:
            реальное = self._раскрыть(целиком, entity=entity, field=поле)
            замена = f"{поле} eq '{_экранировать(реальное)}'"
            if вызов["under_not"]:
                замена = f"({замена})"
            return (значимые[вызов["start"]].start, значимые[вызов["close"]].end, замена)
        self._проверить_литерал_текстом(содержимое, entity=entity, field=поле, оракул=True)
        return None  # реальный текст на разрешённом классе — вызов остаётся как есть

    def _обработать_сравнение(
        self, литерал: Token, поле: str, оператор: str, *, entity: str
    ) -> tuple[int, int, str] | None:
        # Упорядоченное сравнение с литералом на защищаемом классе — отдельный ход в обход
        # анти-оракульного правила (Обход B): нет исключения для org/person — сортировать и
        # сравнивать по величине непрозрачные значения бессмысленно в любом случае. Проверка —
        # до parse_token: даже валидный токен, подставленный не через eq/ne, не имеет смысла.
        класс = self._класс_поля(entity, поле)
        if оператор in УПОРЯДОЧЕННЫЕ and класс and класс not in ("keep", "scan"):
            raise GateError(
                "filter_syntax",
                f"упорядоченное сравнение («{оператор}») запрещено для поля «{поле}» класса "
                f"{класс}: сортировать и сравнивать по величине непрозрачные значения "
                "бессмысленно",
                "сравнивайте защищённое поле только на равенство или неравенство (eq/ne)",
            )
        содержимое = _снять_кавычки(литерал.text)
        целиком = parse_token(содержимое)
        if целиком:
            замена = f"'{_экранировать(self._раскрыть(целиком, entity=entity, field=поле))}'"
            return (литерал.start, литерал.end, замена)
        self._проверить_литерал_текстом(содержимое, entity=entity, field=поле, оракул=False)
        return None

    def _проверить_литерал_текстом(
        self, содержимое: str, *, entity: str, field: str, оракул: bool
    ) -> None:
        """Литерал — не целый токен: закрыть смешение токена с текстом и (внутри функции
        поиска подстроки на защищаемом классе, кроме org/person) закрыть оракул подбора по
        символу (Правка 1)."""
        if is_partial_token(содержимое) or (
            TOKEN_RE.search(содержимое) and содержимое.strip() != содержимое
        ):
            raise GateError(
                "token_partial",
                f"в литерале «{содержимое}» токен использован как часть строки",
                "передайте токен целиком и сравнивайте через eq",
            )
        if find_tokens(содержимое):
            raise GateError(
                "token_partial",
                f"в литерале «{содержимое}» токен смешан с текстом",
                "передайте токен целиком и сравнивайте через eq",
            )
        if оракул:
            класс = self._класс_поля(entity, field)
            if класс and класс not in ("keep", "scan") and класс not in ИМЕНОВАННЫЕ_КЛАССЫ:
                raise GateError(
                    "filter_syntax",
                    f"поиск по вхождению подстроки запрещён для поля «{field}» класса "
                    f"{класс}: образец не является токеном целиком",
                    "модель не знает защищённое значение — передайте токен целиком, запрос "
                    "перепишется в точное сравнение",
                )
        self._проверить_реальное_значение(содержимое, entity=entity, field=field)

    def _подставить_внутри_текста(self, текст: str, *, entity: str, field: str) -> str:
        куски, позиция = [], 0
        for начало, конец, класс, хвост in find_tokens(текст):
            куски.append(текст[позиция:начало])
            куски.append(self._раскрыть((класс, хвост), entity=entity, field=field))
            позиция = конец
        куски.append(текст[позиция:])
        return "".join(куски)

    def _раскрыть(self, разобранный: tuple[str, str], *, entity: str, field: str) -> str:
        класс, хвост = разобранный
        токен = f"[[{класс}:{хвост}]]"
        # Класс и вариант написания ищутся по одному и тому же имени — последнему сегменту
        # пути через связанный объект («Контрагент/ИНН» — это ИНН контрагента, тот же класс,
        # что у простого поля «ИНН»; Обход C). Полный путь при этом остаётся в выходном тексте
        # сравнения без изменений — заменяется только сам литерал.
        сегмент = _сегмент_поля(field)
        ожидаемый = self._field_class(entity, сегмент) if сегмент else None
        if ожидаемый and ожидаемый not in ("keep", "scan") and ожидаемый != класс:
            raise GateError(
                "token_type_mismatch",
                f"токен класса {класс} подставлен в поле {field} класса {ожидаемый}",
                "проверьте, из какого поля взят токен",
            )
        реальное = self._dictionary.reveal(токен, base=self._base, field=сегмент or None)
        if реальное is None:
            raise GateError(
                "token_unknown",
                f"токен {токен} не найден в словаре",
                "токены непрозрачны: используйте только те, что пришли в ответах",
            )
        return реальное

    def _класс_поля(self, entity: str, field: str) -> str | None:
        """Класс по имени поля; путь через связанный объект — по последнему сегменту (Обход C).
        Используется везде, кроме `_раскрыть` (там нужен ещё и сам сегмент — для варианта
        написания, поэтому он вычисляется на месте тем же способом)."""
        сегмент = _сегмент_поля(field)
        return self._field_class(entity, сегмент) if сегмент else None

    def _проверить_реальное_значение(self, значение: str, *, entity: str, field: str) -> None:
        """Реальное значение от модели (ИНН из промпта) проходит контрольную сумму (SPEC §6.7).

        Код ошибки — filter_syntax: отдельного кода для «значение не прошло контрольную сумму»
        в перечне SPEC §5.2 нет, а новые коды заводятся только через ADR с правкой §5.2.
        Смысл сохранён: запрос от модели синтаксически неприемлем и в 1С не уходит. Тот же код
        переиспользован для «поле не определено», «оракул подбора» и «упорядоченное сравнение
        по защищаемому полю» (Правка 1, обходы A и B) — по той же причине: это не новый смысл
        ошибки, а тот же самый «запрос от модели неприемлем».
        """
        класс = self._класс_поля(entity, field)
        проверка = ПРОВЕРКИ.get(класс or "")
        if проверка is None or not значение:
            return
        цифры = re.sub(r"\D", "", значение)
        if цифры and not проверка(цифры):
            raise GateError(
                "filter_syntax",
                f"значение «{значение}» не проходит контрольную сумму класса {класс}",
                "проверьте значение, полученное от пользователя",
            )


def _снять_кавычки(литерал: str) -> str:
    return литерал[1:-1].replace("''", "'") if литерал.startswith("'") else литерал


def _экранировать(значение: str) -> str:
    return значение.replace("'", "''")


def _сегмент_поля(поле: str) -> str:
    """Последний сегмент пути через связанный объект: «Контрагент/ИНН» → «ИНН» (Обход C, ревью
    задачи 7). Простое имя поля без «/» возвращается как есть."""
    return поле.rsplit("/", 1)[-1] if поле else ""


def _собрать(expression: str, сегменты: list[tuple[int, int, str]]) -> str:
    """Склеить исходное выражение с точечными заменами (Правка 3): вне сегментов текст остаётся
    посимвольно как был — переписывание одного вызова не должно задевать соседние условия."""
    куски: list[str] = []
    позиция = 0
    for начало, конец, замена in sorted(сегменты, key=lambda сегмент: сегмент[0]):
        куски.append(expression[позиция:начало])
        куски.append(замена)
        позиция = конец
    куски.append(expression[позиция:])
    return "".join(куски)
