"""Пересекающиеся совпадения поиска по тексту — общий код слоя названий маскировщика, слоя
названий стража, слоя раскрытого и правила вложенности раннего прохода (Ruling 32, Б-4 ревью 9).

Зачем отдельный поиск с пересечениями. Автомат `MatchKind.LeftmostLongest` отдаёт совпадения,
не пересекающиеся между собой: на месте, где начинается длинное название, он берёт его, а
название, начавшееся внутри него, пропускает. Если два известных названия перекрываются в тексте
(«Юг Альфа Север» при известных «Юг Альфа» и «Альфа Север»), второе остаётся недоделанным: его
хвост («Север») выходит модели открытым — обрывок названия третьего лица (находка I-2 ревью 7,
блокер Б-4). Порядок поиска не спасает ни в одну сторону: какое бы название ни было заменено
первым, от другого останется кусок.

Решение — то же правило вложенности, что у раннего прохода (Ruling 32): ищутся ВСЕ совпадения
(`MatchKind.Standard`, `overlapping=True`), сцепленные пересечениями совпадения — одна группа, и
группа заменяется целиком:

- совпадение, накрывающее всю группу, — его токен (длинное название с короткими вариантами внутри
  — обычный случай, ровно то, что делал и прежний поиск);
- иначе — токены «участников» подряд: совпадений, которые не лежат внутри другого совпадения
  группы. Уступить одному значит открыть остаток другого; токены подряд не открывают ничего,
  ценой того, что общая часть в тексте не повторена. Инвариант 1 важнее буквальности текста.

Касание концами пересечением не считается: «Альфа» и сразу за ней «Бета» — две группы, текст
между и вокруг них не трогается.
"""

from __future__ import annotations

import dataclasses
import string

from ahocorasick_rs import AhoCorasick

from odata1c.gate.dictionary import normalize_text_with_map
from odata1c.gate.tokens import blank_tokens


@dataclasses.dataclass(slots=True, frozen=True)
class Вхождение:
    """Совпадение слоя поиска в координатах ИСХОДНОГО текста: `[начало, конец)`."""

    начало: int
    конец: int
    токен: str
    # Подсказка для записи о замене — не длиннее нескольких символов и с конца значения, а не с
    # начала (ревью 2026-09-09, дыра 7): журнал не должен получать защищённое значение целиком.
    подсказка: str
    раскрытое: bool = False


def пересекаются(первое: Вхождение, второе: Вхождение) -> bool:
    return первое.начало < второе.конец and второе.начало < первое.конец


def группы(вхождения: list[Вхождение]) -> list[list[Вхождение]]:
    """Вхождения, сцепленные пересечениями, — одна группа на отрезок текста, который заменяется
    целиком. Касание концами пересечением не считается. Порядок входа не важен."""
    результат: list[list[Вхождение]] = []
    конец_группы = -1
    for вхождение in sorted(вхождения, key=lambda в: (в.начало, -в.конец)):
        if результат and вхождение.начало < конец_группы:
            результат[-1].append(вхождение)
            конец_группы = max(конец_группы, вхождение.конец)
        else:
            результат.append([вхождение])
            конец_группы = вхождение.конец
    return результат


def внутри(вхождение: Вхождение, другое: Вхождение) -> bool:
    """Лежит ли `вхождение` внутри `другое` (совпадение отрезков тоже считается)."""
    return другое.начало <= вхождение.начало and вхождение.конец <= другое.конец


def участники(группа: list[Вхождение]) -> list[Вхождение]:
    """Совпадения группы, которые не лежат внутри другого совпадения группы, — по возрастанию
    начала. Из двух совпадений с одним отрезком остаётся первое (у одного отрезка названий один
    вариант и один токен; равенство отрезков раскрытого и названия решает вызывающий)."""
    упорядоченные = sorted(группа, key=lambda в: (в.начало, -в.конец))
    результат: list[Вхождение] = []
    for номер, вхождение in enumerate(упорядоченные):
        поглощено = any(
            внутри(вхождение, другое)
            and (
                (другое.начало, другое.конец) != (вхождение.начало, вхождение.конец)
                or другой_номер < номер
            )
            for другой_номер, другое in enumerate(упорядоченные)
            if другой_номер != номер
        )
        if not поглощено:
            результат.append(вхождение)
    return результат


def токены_подряд(вхождения: list[Вхождение]) -> str:
    """Токены участников подряд, без повторов соседних (одно название, найденное двумя
    вариантами рядом, не должно дать два одинаковых токена)."""
    токены: list[str] = []
    for вхождение in вхождения:
        if not токены or токены[-1] != вхождение.токен:
            токены.append(вхождение.токен)
    return "".join(токены)


def все_вхождения(
    текст: str,
    автомат: AhoCorasick,
    варианты: dict[str, str],
    *,
    границы: frozenset[str] = frozenset(),
    заглушать_guid: bool = True,
    раскрытое: bool = False,
    не_рвать_числа: bool = True,
) -> list[Вхождение]:
    """Все совпадения вариантов в тексте, в том числе пересекающиеся и вложенные, — общий поиск
    слоя названий (словарь, автомат на процесс) и слоя раскрытого (набор вызова, автомат на
    вызов): правила совпадения, свёртки и обратного отображения позиций у них одни и те же, и
    расходиться им нельзя. `автомат` — `MatchKind.Standard` (только он умеет `overlapping=True`).

    Пересечения нужны обоим слоям. Слою названий — Б-4 (см. докстринг модуля). Слою раскрытого —
    тот же случай между двумя раскрытыми значениями: отбор по двум токенам `addr` раскрывает оба,
    и если в ответе они сцеплены («г. Москва, ул. Тверская, д. 7» при раскрытых «г. Москва, ул.
    Тверская» и «ул. Тверская, д. 7»), поиск без пересечений брал первое, а второе, начавшееся
    внутри него, пропускал — «, д. 7» выходило открытым. У `addr` другого рубежа нет.

    Поиск идёт по свёрнутой копии, где уже стоящие токены (из ответа, от слоя раскрытого и от
    замены чисел) закрыты заглушкой той же длины (`tokens.blank_tokens`; Ruling 21 M1c, хвост 2):
    совпасть с токеном нечему. Координаты — исходного текста, по карте позиций
    (`dictionary.normalize_text_with_map`), поэтому написание в ответе (кавычки, регистр,
    неразрывные пробелы) роли не играет, а вхождения двух слоёв можно сравнивать между собой
    (правило вложенности, `guard._заменить_раскрытое`).

    `границы` — написания, которые засчитываются только при границах с обеих сторон (Ruling 27,
    короткое раскрытое значение: см. `revealed.RevealedValues.bounded`). Для слоя названий
    множество пустое — там короткие варианты отсекает сам словарь. Проверка идёт на каждом
    совпадении отдельно: при поиске с пересечениями голая «1» находится и внутри номеров и дат, и
    отбрасывается здесь же.

    `заглушать_guid=False` — для слоя раскрытого: там ключ содержит GUID дословно (см.
    `tokens.blank_tokens`). `раскрытое=True` помечает вхождения слоя раскрытого: по пометке
    правило вложенности отличает их от названий.

    `не_рвать_числа` — цифровая граница слоя названий (M-2 ревью блокеров M2, инвариант 6):
    совпадение, чья крайняя цифра примыкает к цифре текста, — не совпадение. Название «Альфа 2»
    внутри «Альфа 2026-08-26» иначе забирало первую цифру года (`[[org:N]]026-08-26`). Граница
    только цифровая: буквы, приклеенные к названию («СуперАльфа», «Альфабанк»), данных не портят, а
    требование границы слова оставило бы известное словарю название в ответе открытым (инвариант
    1). Слой раскрытого передаёт `False`: у него своё правило для коротких значений (Ruling 27), а
    длинное раскрытое значение модель сама попросила использовать, и прятать его обязательно."""
    нормализованный, карта = normalize_text_with_map(blank_tokens(текст, guids=заглушать_guid))
    найдено: list[Вхождение] = []
    for _, начало, конец in автомат.find_matches_as_indexes(нормализованный, overlapping=True):
        вариант = нормализованный[начало:конец]
        токен = варианты.get(вариант)
        if токен is None:
            continue
        if не_рвать_числа and _рвёт_число(нормализованный, начало, конец):
            continue
        if вариант in границы and not (
            _граница_слева(нормализованный, начало) and _граница_справа(нормализованный, конец)
        ):
            continue
        найдено.append(
            Вхождение(
                начало=карта[начало][0],
                конец=карта[конец - 1][1],
                токен=токен,
                подсказка=f"…{вариант[-4:]}",
                раскрытое=раскрытое,
            )
        )
    return найдено


def _рвёт_число(текст: str, начало: int, конец: int) -> bool:
    """Разрезало бы совпадение `[начало, конец)` цифровую серию текста: первая его цифра стоит
    сразу за цифрой или последняя — сразу перед цифрой (см. `не_рвать_числа`)."""
    слева = начало > 0 and текст[начало].isdigit() and текст[начало - 1].isdigit()
    справа = конец < len(текст) and текст[конец - 1].isdigit() and текст[конец].isdigit()
    return слева or справа


def _граница_слева(текст: str, начало: int) -> bool:
    if начало == 0 or not текст[начало - 1].isalnum():
        return True
    return _процентная_запись(текст, начало - 2) or _процентная_запись(текст, начало - 3)


def _граница_справа(текст: str, конец: int) -> bool:
    if конец >= len(текст) or not текст[конец].isalnum():
        return True
    return _процентная_запись(текст, конец - 1) or _процентная_запись(текст, конец - 2)


def _процентная_запись(текст: str, начало: int) -> bool:
    """Стоит ли по этому смещению процентная запись `%XX` (Ruling 27).

    Шестнадцатеричные цифры кодировки — не «соседний символ значения», а служебная запись самого
    адреса: в `…%20eq%20%271%27` слева от единицы стоит `7` из `%27`, и без этой оговорки правило
    границ отбросило бы совпадение ровно на той форме, ради которой слой раскрытого переносили на
    сырой текст (форма N1-A, Ruling 25)."""
    if начало < 0 or начало + 3 > len(текст) or текст[начало] != "%":
        return False
    return all(символ in string.hexdigits for символ in текст[начало + 1 : начало + 3])


def заменить_названия(
    текст: str, автомат: AhoCorasick, варианты: dict[str, str]
) -> tuple[str, list[list[Вхождение]]]:
    """Слой названий с правилом пересечений (см. докстринг модуля). Возвращает текст и группы —
    по записи о замене на группу у стража."""
    найденные = группы(все_вхождения(текст, автомат, варианты))
    if not найденные:
        return текст, []
    куски: list[str] = []
    позиция = 0
    for группа in найденные:
        начало = min(в.начало for в in группа)
        конец = max(в.конец for в in группа)
        куски.append(текст[позиция:начало])
        куски.append(токены_подряд(участники(группа)))
        позиция = конец
    куски.append(текст[позиция:])
    return "".join(куски), найденные
