"""Токены гейта: единая грамматика [[type:tail]], нормализация, детерминированный хвост.

SPEC §6.3. Для реквизитов хвост — HMAC-SHA256 от секрета и нормализованного значения,
записанный в Crockford base32 (без I, L, O, U — не спутать с цифрами). Для названий и ФИО хвост —
порядковый номер из словаря, его выдаёт словарь (задача 3), а не этот модуль.
"""

from __future__ import annotations

import hmac
import re

# Crockford base32: цифры и буквы без I, L, O, U.
АЛФАВИТ = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"

CLASSES = frozenset(
    {
        "inn",
        "kpp",
        "ogrn",
        "acc",
        "corr",
        "bic",
        "iban",
        "card",
        "snils",
        "doc",
        "phone",
        "email",
        "dob",
        "addr",
        "org",
        "person",
        "keep",
    }
)

TOKEN_RE = re.compile(r"\[\[(?P<type>[a-z][a-z0-9_:]{0,31}):(?P<tail>[0-9A-Z]{1,16})\]\]")
_ЦЕЛИКОМ = re.compile(rf"^{TOKEN_RE.pattern}$")
_ОБРЕЗОК = re.compile(
    r"\[\[[a-z0-9_:]*:?[0-9A-Z]*$"
    r"|^[a-zA-Z0-9_:]*\]\]"
    r"|\[\[[a-z0-9_:]*:\]\]"
    r"|\[\[:"
    # Испорченный токен: хвост длиннее допустимых 16 символов — TOKEN_RE такой не берёт ни
    # целиком, ни частично, а такое значение обязано вызывать отказ, а не проходить молча.
    r"|\[\[[a-z][a-z0-9_:]*:[0-9A-Z]{17,}\]\]"
)

ТОЛЬКО_ЦИФРЫ = ("inn", "kpp", "ogrn", "acc", "corr", "bic", "snils", "card", "phone", "doc")


def normalize_value(type_: str, value: str) -> str:
    """Нормализация перед хэшированием (SPEC §6.3).

    Поправка (amended, 2026-09-09): для `org`/`person` нормализация приводит и к нижнему
    регистру, а не только схлопывает пробелы — иначе «ООО Ромашка» и «ооо ромашка» (одно и то
    же юридическое лицо) получали два разных токена, что нарушает основное свойство словаря:
    одно значение с разным написанием — один токен. Написание с исходным регистром при этом не
    теряется: словарь (`gate/dictionary.py`) хранит его отдельно, в вариантах по базе и полю, и
    именно его возвращает `reveal()` при обратной подмене.

    Поправка 2026-09-10 (M1b-fix, задача 4): для `org`/`person` «ё» приравнивается к «е». В
    тексте «ё» часто пишут как «е»; без свёртки «ООО Василёк» и «ООО Василек» получали два
    токена, их варианты для стража после свёртки совпадали, становились неоднозначными
    (`Dictionary.name_variants`) — и страж не заменял ни одно написание.
    """
    if type_ in ТОЛЬКО_ЦИФРЫ:
        return re.sub(r"\D", "", value)
    if type_ == "email":
        return value.strip().lower()
    if type_ == "iban":
        return re.sub(r"\s", "", value).upper()
    if type_ == "dob":
        return value.strip()[:10]
    if type_ == "addr":
        return " ".join(value.split())
    if type_ in ("org", "person"):
        return " ".join(value.split()).lower().replace("ё", "е")
    return value.strip()


def make_token(secret: bytes, type_: str, normalized: str, tail_length: int = 10) -> str:
    """Токен реквизита: тип, нулевой байт, нормализованное значение под HMAC (SPEC §6.3)."""
    подпись = hmac.new(
        secret, type_.encode("utf-8") + b"\x00" + normalized.encode("utf-8"), "sha256"
    ).digest()
    return f"[[{type_}:{_в_base32(подпись, tail_length)}]]"


def parse_token(text: str) -> tuple[str, str] | None:
    """Класс и хвост, если строка целиком является токеном.

    Пробелы вокруг токена не срезаются (Правка 6, ревью задачи 7, 2026-09-09): пробел рядом
    с токеном — признак смешения с текстом, а не безобидный хвост, который можно молча
    отбросить. Раньше `text.strip()` перед разбором превращал ` [[inn:XXXX]] ` в «целый токен»,
    из-за чего защита от смешения токена с текстом (в `gate/unmasking.py`) никогда не
    срабатывала именно для этого случая — литерал с пробелами вокруг токена вёл себя
    непредсказуемо, тихо теряя пробелы вместо явного отказа."""
    совпадение = _ЦЕЛИКОМ.match(text)
    return (совпадение["type"], совпадение["tail"]) if совпадение else None


def find_tokens(text: str) -> list[tuple[int, int, str, str]]:
    """Вхождения токенов: начало, конец, класс, хвост."""
    return [
        (совпадение.start(), совпадение.end(), совпадение["type"], совпадение["tail"])
        for совпадение in TOKEN_RE.finditer(text)
    ]


ЗАГЛУШКА_ТОКЕНА = "\x00"


def blank_tokens(text: str) -> str:
    """Копия текста для поиска названий, в которой каждый целый токен заменён заглушкой той же
    длины (`ЗАГЛУШКА_ТОКЕНА` на каждый символ): индексы копии совпадают с индексами исходного
    текста, поэтому замену по-прежнему режут из исходного.

    Зачем (SPEC §6.8; ревью гейта 2026-09-09, дыра 8, и Ruling 21 M1c, хвост 2). Хвост токена
    реквизита — Crockford base32, те же символы, что и приведённое к нижнему регистру латинское
    название, а скобки токена могут оказаться краем варианта (`]ооо "ромашка"` — контрагент,
    записанный через запись с «]» в начале). Прежде совпадение, пересекающее токен, отбрасывалось
    ПОСЛЕ поиска — но автомат LeftmostLongest к этому моменту уже подавил более короткий вариант
    того же места, и название рядом с токеном выходило открытым. С заглушкой совпадение с
    токеном невозможно по построению: NUL (категория Cc) — не пробел и не невидимый символ
    формата, нормализация его не схлопывает и не выбрасывает, и ни в одном варианте названия его
    нет."""
    return TOKEN_RE.sub(lambda токен: ЗАГЛУШКА_ТОКЕНА * len(токен.group()), text)


def is_partial_token(text: str) -> bool:
    """Признак обрезанного или испорченного токена: модель не должна их достраивать (SPEC §6.7).

    Целый токен в строке не отменяет проверку остальной строки: сначала из текста удаляются
    все найденные целые токены, и на обрезок проверяется то, что осталось. Иначе строка из
    целого и обрезанного токена (например, в выражении отбора из нескольких условий) прошла бы
    как чистая — целый токен «прикрывал» бы остаток строки.

    Общий признак (Правка 2, ревью задачи 7, 2026-09-09): если в остатке встречаются два
    квадратных скобки подряд («[[» или «]]»), а целым токеном (после вычитания настоящих целых
    токенов) он не является — это испорченный токен, а не случайный текст. Раньше отдельные
    regex-формы `_ОБРЕЗОК` ловили только обрыв токена с одного края строки; неверный регистр
    класса (`[[INN:...]]`), пробел внутри скобок (`[[inn: ...]]`) и непарные скобки
    (`[[inn:...]` — одна закрывающая вместо двух) не совпадали ни с одной формой и в полях без
    контрольной суммы уходили в 1С дословно. Одиночная непарная скобка (`[текущий]`, без
    удвоения) — обычный текст, не токен, и под этот признак не попадает.
    """
    остаток = TOKEN_RE.sub("", text)
    if "[[" in остаток or "]]" in остаток:
        return True
    return bool(_ОБРЕЗОК.search(остаток))


def _в_base32(данные: bytes, длина: int) -> str:
    число = int.from_bytes(данные, "big")
    символы = []
    for _ in range(длина):
        символы.append(АЛФАВИТ[число % 32])
        число //= 32
    return "".join(reversed(символы))
