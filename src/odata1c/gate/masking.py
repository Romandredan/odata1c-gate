def _ссылочный_ключ(поле: str) -> bool:
    """Поле ссылки 1С в OData: `Ref_Key`, `<Реквизит>_Key` (GUID) и `<Реквизит>_Type` (имя
    типа составной ссылки) — идентификатор, а не реквизит (инвариант 6). Та же проверка есть в
    `unmasking.py`; в `field_rules.py` не вынесена, чтобы не задевать классификатор реиндекса,
    где такие поля и так отсекаются по настоящему типу Edm."""
    return поле == "Ref_Key" or поле.endswith(("_Key", "_Type"))


def _базовый_класс_поля_политики(
    policy: Policy, entity: str, field: str, *, strict: bool = False
) -> str | None:
    """Класс поля до понижения по уровню (SPEC §6.4): ручной/авто-раздел политики, затем свой
    класс по имени поля, затем запасная классификация по имени поля независимо от сущности —
    тело перенесено из `Masker._базовый_класс_поля` без изменений (M1d, задача 1), чтобы им же
    пользовалась и обратная подмена через `effective_field_class`.

    `strict=True` — сущность, о которой политика ничего не знает и знать не может: путь
    `raw_get` не разрешился по индексу (Ruling 18, раунд правок 1 задачи 7 M1d). Тогда слой
    «наименование/ФИО у сущности из `names_for`» включается для ЭТОЙ сущности, вместо того чтобы
    быть выключенным (`names_for=set()`, см. длинное обоснование ниже). Неизвестность трактуется
    в строгую сторону: пока сущность не в индексе, отличить «Description склада» от «Description
    контрагента» нечем, и открывать название дороже, чем замаскировать лишнее. Ручные разделы
    политики при этом главнее (`sensitivity_of` спрашивается раньше и `keep` возвращает как
    есть), а инвариант 6 держит сам `classify_field`: ссылки, коды, номера и нестроковые типы он
    не классифицирует ни при каком `names_for`."""
    класс = policy.sensitivity_of(entity, field)
    if класс is None:
        класс = policy.custom_fields().get(field)
    if класс is None and not _ссылочный_ключ(field):
        # Раунд 2 итогового ревью M1c (I2): ключи ссылок (`Сотрудник_Key`, `ФизЛицо_Key`) и
        # типы составных ссылок (`…_Type`) — GUID и имя типа, а не реквизит (инвариант 6);
        # запасной классификатор с типом "Edm.String" вслепую дал бы им класс person по
        # подстроке «сотрудник»/«физлицо» и заменил GUID токеном.
        #
        # Запасная классификация по имени поля (правка ревью, Critical): `sensitivity_of`
        # ищет класс по паре «сущность и поле» и ничего не находит для раскрытого вложенного
        # объекта — сущность, известная на этом уровне обхода, это сущность родителя
        # (документа), а не настоящая сущность раскрытого объекта (например, контрагента).
        # `classify_field` — тот же классификатор, что размечает секцию auto при реиндексе —
        # и два его слоя действительно не зависят от сущности: реквизиты по имени поля
        # (СНИЛС, ИНН, КПП, ...) и признаки ФИО/названия по характерному имени поля в чужой
        # сущности («Контрагент», «Организация», ...). Третий слой (Description/ФИО у
        # сущности из names_for) — ровно противоположное, целиком завязан на настоящую
        # сущность: поле «Представление» у строки табличной части «КонтактнаяИнформация»
        # (телефон) совпало бы с тем же полем «Представление» верхнего уровня Catalog_
        # Контрагенты (название) и подменилось бы неверно. Поэтому слой имени/сущности
        # запасной классификацией сознательно не пользуется — `names_for=set()` делает
        # проверку принадлежности сущности к names_for заведомо ложной и отключает только
        # этот слой, не два первых.
        #
        # Ровно это выключение и стало дырой в `raw_get` (Critical ревью 2026-09-11): когда
        # сущности нет в индексе, первые два слоя оставляют ИНН защищённым, а третий, то есть
        # единственный, который защищает `Description`/`НаименованиеПолное`/ФИО, выключен —
        # и название организации уходило открытым текстом при `masked_fields: ["ИНН"]`.
        # Оговорка про «Представление» выше остаётся верной для ИЗВЕСТНОЙ сущности (там
        # разметка полей есть и запасной слой не нужен), поэтому включается он только под
        # `strict`.
        найдено = classify_field(
            entity, field, "Edm.String", names_for={entity} if strict else set()
        )
        if найдено is not None:
            класс = найдено[0]
    return класс


def _понизить_класс_названия_по_уровню(класс: str | None, *, mode: str) -> str | None:
    if класс in КЛАССЫ_НАЗВАНИЙ and mode != "identifiers+names":
        # Названия защищаются только на верхнем уровне (SPEC §6.2), но поле всё равно
        # сканируется: None ведёт к сканированию, keep отключил бы и его. В Description
        # контрагента вполне может лежать ИНН, и на уровне identifiers он обязан быть заменён.
        return None
    return класс


def effective_field_class(
    policy: Policy, entity: str, field: str, *, mode: str, strict: bool = False
) -> str | None:
    """Эффективный класс поля с учётом понижения классов названий ниже верхнего уровня защиты
    (SPEC §6.2, §6.4) — ровно логика нынешних `Masker._базовый_класс_поля` + `Masker._класс_поля`
    (M1d, задача 1). Общая точка правды для прямой подмены (`Masker`), обратной (`Unmasker` через
    `pipeline.BaseGate.refresh`) и вопроса «поле защищено?» (`BaseGate.is_protected`).

    `strict` — см. `_базовый_класс_поля_политики`. Понижение по уровню применяется и в строгом
    режиме: на `identifiers` названия не защищаются по замыслу (SPEC §6.2), и строгость касается
    неизвестности сущности, а не выбранного владельцем уровня."""
    класс = _базовый_класс_поля_политики(policy, entity, field, strict=strict)
    if класс in ("keep", None, "scan"):
        return класс
    return _понизить_класс_названия_по_уровню(класс, mode=mode)


def inbound_field_class(
    policy: Policy,
    entity: str,
    field: str,
    *,
    mode: str,
    shape: Shape | None,
    strict: bool = False,
) -> str | None:
    """Класс поля на ВХОДНОМ пути — для обратной подмены и анти-оракульных правил отбора, для
    вопроса «поле защищено?» (`$orderby`) и для класса в `describe_entity` (Ruling 35).

    Отличие от `effective_field_class` одно: поле значения табличной части контактной информации
    (`contact_info.is_contact_info_entity` + `is_value_field`) получает класс
    `contact_info.КЛАСС_НА_ВХОДЕ` независимо от политики. На выходе такое поле закрывает правило
    строки по её `Тип` (Ruling 33), но на входе строки нет: отбор `Представление eq '…'` не знает,
    телефон это или адрес, и у поля `Представление` в политике класса нет вовсе. Без этого правила
    открытый литерал в сравнении и `substringof('495', Представление)` уходили в 1С, и по ответам
    «есть / нет» номер подбирался перебором, ни разу не показанный модели.

    Порядок источников — как у правила строки на выходе (раунд 1): ручное `keep` владельца —
    единственное «не защищать» и главнее всего; раздел `auto` (`НомерТелефона: phone`) уступает —
    иначе у колонок поиска остался бы класс, разрешающий равенство с открытым литералом, то есть
    тот же оракул; ручной `scan` уступает, как на выходе. Ручной класс, отличный от `keep`,
    правило тоже не отменяет: поле остаётся полем контактной информации, и отбор по нему — только
    токеном (токен ручного класса раскрывается по записи о выдаче, Ruling 19).

    `shape` — строение по индексу; нет строения — запасной признак по суффиксу имени (см.
    `is_contact_info_entity`). Слой тулов передаёт его обязательно (`BaseGate.inbound_*`)."""
    if contact_info.is_value_field(field) and contact_info.is_contact_info_entity(entity, shape):
        if policy.manual_sensitivity_of(entity, field) == "keep":
            return "keep"
        return contact_info.КЛАСС_НА_ВХОДЕ
    return effective_field_class(policy, entity, field, mode=mode, strict=strict)


def inbound_path_class(
    policy: Policy, entity: str, path: str, *, shape: Shape | None
) -> str | None:
    """Класс ПУТИ на входном пути, когда его задаёт сущность, в которую путь приходит (Ruling 37).

    Ruling 35 закрыл отбор по полю значения контактной информации, если запрос идёт прямо в
    табличную часть. Ревью 8 (C-1) нашло тот же оракул через путь от владельца:
    `substringof('495', КонтактнаяИнформация/Представление)` к `Catalog_Контрагенты`,
    `substringof('9', Контрагент/КонтактнаяИнформация/Представление)` к документу. Обратная
    подмена искала класс пути по ПОСЛЕДНЕМУ сегменту на КОРНЕВОЙ сущности (`Unmasker._класс_поля`),
    а у корня поля `Представление` нет, и запасной классификатор по имени его тоже не знает, —
    сравнение уходило в 1С без проверки.

    Здесь путь проходит звенья до поля (`contact_info.entity_of_path`: навигация — по строению из
    индекса, табличная часть — дочерняя сущность `<владелец>_<звено>`), и сущность, в которую он
    пришёл, спрашивается тем же правилом, что при прямом запросе (`inbound_field_class`): поле
    значения табличной части контактной информации — `contact`, ручное `keep` владельца на этом
    поле этой табличной части — `keep`. Любая длина пути, любое сочетание звеньев.

    `None` — путь правилу не подлежит (пришёл не в контактную информацию, конечное поле — тип,
    номер строки, ссылка): класс ищется прежним порядком по последнему сегменту, без изменений."""
    *звенья, поле = path.split("/")
    if not звенья or not contact_info.is_value_field(поле):
        return None
    цель = contact_info.entity_of_path(entity, звенья, shape)
    if not contact_info.is_contact_info_entity(цель, shape):
        return None
    if policy.manual_sensitivity_of(цель, поле) == "keep":
        return "keep"
    return contact_info.КЛАСС_НА_ВХОДЕ


@dataclasses.dataclass(slots=True)
class MaskResult:
    """`masked_fields` — поля, в которых КАЖДОЕ значение ответа заменено токеном целиком: реального
    содержимого в них нет. `partially_masked_fields` — поля, где замаскирована часть значений или
    часть текста значения (найденный реквизит внутри комментария): остальное открыто как есть.
    См. `УчётПолей`. Гарантия — на этот ответ, а не на поле вообще."""

    data: object
    masked_fields: list[str]
    warnings: list[str]
    partially_masked_fields: list[str] = dataclasses.field(default_factory=list)


@dataclasses.dataclass(slots=True)
class УчётПолей:
    """Счёт значений по полям за один ответ — чтобы `masked_fields` не врал (раунд 2 правки
    контактной информации, находка координатора на `Catalog_КонтактныеЛицаПартнеров`).

    Раньше поле попадало в `masked_fields`, если замаскировано хотя бы одно его значение: из 30
    записей в двух детектор нашёл телефон внутри `Description`, и список говорил «Description
    замаскирован», хотя 23 ФИО стояли открытыми. Модель по такому списку решает, что имена
    закрыты. Ruling 20, пункт 4 требует обратного: поле в списке — значит реального значения в
    ответе нет. Поэтому поле числится в `masked_fields`, только когда КАЖДОЕ его значение заменено
    токеном ЦЕЛИКОМ, а всё остальное, где замаскировано хоть что-то, — отдельным списком
    `partially_masked_fields`: «часть закрыта, остальное открыто как есть». Частичное — это и
    часть значений поля, и часть текста значения: реквизит, найденный детектором внутри
    комментария, заменён, а сам комментарий открыт, — поле со свободным текстом «замаскированным»
    назвать нельзя. Прятать частичные поля совсем тоже нельзя — модель должна знать, что в поле
    бывает защищённое.

    Знаменатель — значения, которые маскировщик взвешивал (`_обработать_строку`): непустая
    строка, не GUID. Пустые строки и GUID не считаются вовсе — маскировать в них нечего по
    замыслу (инвариант 6), и они не делают поле «частичным». Имена полей (ключи словаря ответа
    проверяются тем же путём) не считаются. Значение поля `keep` считается: оно открыто, и если в
    том же поле ранний проход закрыл другое значение, поле честно частичное.

    `append` — отметить замаскированное значение: имя сохранено от прежнего списка, чтобы места
    отметки остались теми же; `целиком=False` — замаскирована часть текста значения."""

    целиком: dict[str, int] = dataclasses.field(default_factory=dict)
    частями: set[str] = dataclasses.field(default_factory=set)
    просмотрено: dict[str, int] = dataclasses.field(default_factory=dict)

    def append(self, поле: str, *, целиком: bool = True) -> None:
        if целиком:
            self.целиком[поле] = self.целиком.get(поле, 0) + 1
        else:
            self.частями.add(поле)

    def увидено(self, поле: str) -> None:
        self.просмотрено[поле] = self.просмотрено.get(поле, 0) + 1

    def полностью(self) -> list[str]:
        return sorted(
            поле
            for поле, число in self.целиком.items()
            if поле not in self.частями and число >= self.просмотрено.get(поле, 0)
        )

    def частично(self) -> list[str]:
        полные = set(self.полностью())
        return sorted((set(self.целиком) | self.частями) - полные)


class Masker:
    def __init__(self, dictionary: Dictionary, policy: Policy, *, mode: str, base: str) -> None:
        self._dictionary = dictionary
        self._policy = policy
        self._mode = mode
        self._base = base
        # Автомат известных названий (слой 3, SPEC §6.5) и его ревизия словаря, на которой он
        # собран — пересобирается лениво при изменении словаря, как в guard.py (перенос поиска
        # с линейного re.search на ahocorasick_rs, задача 8 M1c: словарь названий может вырасти
        # до десятков тысяч записей, и re.search по каждому варианту на каждую строку ответа не
        # масштабируется так, как один проход автомата).
        self._названия_ревизия = -1
        self._названия_автомат: AhoCorasick | None = None
        self._названия_варианты: dict[str, str] = {}

    def mask(
        self,
        data,
        *,
        entity: str,
        resolve: Resolve | None = None,
        hidden: Callable[[str], bool] | None = None,
        strict: bool = False,
        revealed: RevealedValues | None = None,
        shape: Shape | None = None,
        persist: bool = True,
    ) -> MaskResult:
        """`shape` — строение сущностей по индексу (`contact_info.EntityShape`, Ruling 33): по нему
        строка табличной части контактной информации узнаётся, даже когда в ответе нет поля
        `Тип` (модель выбрала только `Представление` — проверено на живой базе, 1С отдаёт такие
        строки). `None` — индекса нет (тесты маскировщика): строка узнаётся только по своим
        ключам, когда в ней есть все три поля строения.

        `strict=True` — сущность не подтверждена индексом (путь `raw_get` не разрешился,
        Ruling 18): включается слой названий/ФИО для этой сущности и принудительный поиск
        реквизитов по значению, независимо от `scan_free_text` политики. Разметки полей у такой
        сущности нет вовсе, и отключать вдобавок поиск по значению значит остаться совсем без
        защиты.

        `resolve` — резолвер «сущность и ключ ответа → сущность вложенного объекта» (итоговое
        ревью M1d, C1): раскрытый через `$expand` объект и строка табличной части обрабатываются
        по политике СВОЕЙ сущности (SPEC §6.5), а не той, что наверху. Строит его слой тулов по
        индексу метаданных — `EntityDescription.navigations` знает цель навигации точно.

        `None` — индекса навигаций нет (тесты самого маскировщика): вложенный объект остаётся на
        политике родителя, и единственная его защита — наследование класса от поля-контейнера.
        Это заведомо более слабый путь, поэтому у `pipeline.BaseGate.mask` аргумент обязателен
        (отказ типа, как у `revealed` в задаче N1) — в продукте резолвер есть всегда.

        `hidden` — скрыта ли сущность политикой (`entities.hide`, SPEC §6.9). Вложенный объект
        скрытой сущности изымается из ответа целиком, и это не дубль обрезки `$expand` в запросе,
        а второй рубеж для того, что 1С отдаёт БЕЗ спроса: табличные части приходят списками
        словарей сами по себе (проба P4), никакого `$expand` для них не требуется, — и запрет
        владельца на них обрезкой запроса не закрывается в принципе.

        `revealed` — набор раскрытого в этом вызове (находка П2 приёмки через настоящие
        инструменты): ранний проход (Ruling 25) уже заменил раскрытые значения в сыром теле
        токенами, и поле с классом маскировщик должен токенизировать по НАСТОЯЩЕМУ содержимому, а
        не по токену, стоящему на его месте, — см. `_обработать_строку`. `None` — вызов ничего не
        раскрывал (или тест самого маскировщика).

        `persist=False` — маска без записи в словарь (Ruling 58, тул `odata1c_journal`): данные
        журнала — не ответ 1С этого вызова, а `request` неудачного `commit` несёт значения,
        которых в 1С нет вовсе (Ruling 48: словарь пополняется только телом ответа 1С с
        данными). Известное значение получает свой токен, новое — детерминированный токен без
        вставки (`Dictionary.token_for(persist=False)`), неизвестное название или ФИО —
        `МЕТКА_БЕЗ_ЗАПИСИ`. Остальное — как у обычной маски: классы, `lit` для токена шлюза в
        строке данных (Б-2), слой известных названий, поиск реквизитов."""
        замаскированные = УчётПолей()
        предупреждения: list[str] = []
        if self._mode == "off":
            return MaskResult(data=data, masked_fields=[], warnings=[])
        изъятое: list[str] = []
        неразрешённое: list[str] = []
        строгие_ки: list[str] = []
        # SPEC §6.6: маскировка одного ответа идёт В ДВА ПРОХОДА, и это инвариант маскировщика,
        # а не следствие порядка ключей в JSON 1С (M-5, хвост M1d). Первый проход обходит ВСЕ
        # поля с объявленным классом во всех записях ответа: словарь получает новые написания
        # названий, а автомат известных названий — их варианты. Второй (ниже, обычный) обходит
        # ответ целиком, и свободный текст маскируется автоматом, который уже знает всё, что
        # выдал первый. Результат первого прохода выбрасывается: единственное, ради чего он
        # делается, — состояние словаря; поля с классом второй проход токенизирует заново, и
        # `Dictionary.token_for` на известном значении возвращает тот же токен, не двигая
        # `revision()`.
        #
        # `revealed=None` здесь — не упрощение, а условие безопасности. Строку, переписанную
        # ранним проходом (Ruling 25/32), первый проход возвращает как есть: без набора вызова
        # `_заменить_по_классу` не знает исходного значения места и выходит, не тронув словарь и
        # не позвав `RevealedValues.absorb`. Настоящее значение такой строки словарь УЖЕ знает —
        # токен в неё поставил сам ранний проход по словарю, — поэтому автомату названий она
        # ничего не добавляет. Передать сюда `revealed` значило бы позвать `absorb` дважды на
        # одних и тех же заменах и испортить счётчик `guard_replaced`.
        #
        # `persist=False` (тул `odata1c_journal`, Ruling 58) первого прохода не получает вовсе:
        # словарь при нём не пополняется, и учить автомат нечему. А вот по уровню проход не
        # разделяется, хотя на `identifiers` названия не маскируются и польза от него нулевая:
        # условие по уровню сделало бы порядок проходов, записанный в SPEC §6.6 инвариантом,
        # частным случаем одного уровня. Цена — лишний обход ответа и повторный поиск токена по
        # словарю у полей с классом.
        if persist:
            self._обойти(
                data,
                entity=entity,
                замаскированные=УчётПолей(),
                resolve=resolve,
                hidden=hidden,
                изъятое=[],
                неразрешённое=[],
                strict=strict,
                revealed=None,
                shape=shape,
                строгие_ки=[],
                persist=True,
                только_классы=True,
            )
        результат = self._обойти(
            data,
            entity=entity,
            замаскированные=замаскированные,
            resolve=resolve,
            hidden=hidden,
            изъятое=изъятое,
            неразрешённое=неразрешённое,
            strict=strict,
            revealed=revealed,
            shape=shape,
            строгие_ки=строгие_ки,
            persist=persist,
        )
        if изъятое:
            предупреждения.append(ПРЕДУПРЕЖДЕНИЕ_СКРЫТОЙ_СВЯЗИ)
        if неразрешённое:
            предупреждения.append(ПРЕДУПРЕЖДЕНИЕ_ВНЕ_ИНДЕКСА)
        if строгие_ки:
            предупреждения.append(ПРЕДУПРЕЖДЕНИЕ_КОНТАКТНОЙ_ИНФОРМАЦИИ)
        return MaskResult(
            data=результат,
            masked_fields=замаскированные.полностью(),
            warnings=предупреждения,
            partially_masked_fields=замаскированные.частично(),
        )

    def mask_text(self, text: str, *, entity: str, field: str) -> str:
        """Подмена внутри произвольной строки: ошибки 1С, превью, сообщения (инвариант 1).

        Настройка `scan_free_text` про поиск в полях ответа, а не про ошибки платформы (правка
        ревью, 2026-09-09): SPEC прямо перечисляет сообщения об ошибках среди того, что покрывает
        поиск по значению, а инвариант защиты исключений по настройкам не имеет — поэтому здесь
        сканирование включено принудительно (`force_scan=True`), независимо от политики базы.

        Словарь отсюда не пополняется (Ruling 48): текст ошибки или отказа — не данные 1С, в нём
        эхо значения модели (отказ гейта повторяет литерал, 1С — выражение отбора, P7). Реквизит,
        найденный детектором, получает токен без записи (`Dictionary.token_for(persist=False)`):
        известное значение — свой токен, новое — тот, что выдала бы запись. Иначе отказанный
        вызов, не дошедший до 1С, клал бы литерал модели в общий словарь: номер документа
        становился бы `inn` в чужих ответах, лишнее написание делало бы запись токеном
        `token_ambiguous` (B2, B4 повторного ревью задачи 5 M2). Названия здесь заменяет только
        автомат известных вариантов — он словарь не пишет.
        """
        if self._mode == "off":
            return text
        return self._обработать_строку(
            text,
            entity=entity,
            field=field,
            класс=None,
            замаскированные=УчётПолей(),
            force_scan=True,
            из_ответа=False,
        )

    @staticmethod
    def _вставки(
        переписано: ScrubbedText | None, revealed: RevealedValues | None
    ) -> tuple[tuple[int, int], ...]:
        """Места токенов, которые поставил ранний проход в эту строку (Б-2). Обычная строка —
        мест нет: ранний проход её не трогал, и все токены в ней пришли из 1С."""
        if переписано is None or revealed is None:
            return ()
        return revealed.inserted_of(переписано)

    def _обойти(
        self,
        значение,
        *,
        entity: str,
        замаскированные: УчётПолей,
        field: str = "",
        класс_контейнера: str | None = None,
        resolve: Resolve | None = None,
        hidden: Callable[[str], bool] | None = None,
        изъятое: list[str] | None = None,
        неразрешённое: list[str] | None = None,
        strict: bool = False,
        revealed: RevealedValues | None = None,
        shape: Shape | None = None,
        строгие_ки: list[str] | None = None,
        вид_лица: tuple[str, str | None] | None = None,
        persist: bool = True,
        только_классы: bool = False,
    ):
        """`только_классы` — первый из двух проходов маскировки ответа (SPEC §6.6, см. `mask`):
        обход трогает только поля с ОБЪЯВЛЕННЫМ классом, а свободный текст, поля класса `scan` и
        поиск реквизитов по значению оставляет второму проходу. Дерево ответа обходится при этом
        целиком и по тем же правилам: те же скрытые связи, те же цели навигаций, тот же строгий
        режим, — иначе словарь после первого прохода знал бы не то же самое, что увидит второй.

        `вид_лица` — что известно о виде лица записи-владельца (Ruling 34, пункт 2): сущность
        записи и значение её поля `ЮрФизЛицо` (`None` — поля в записи нет). Адрес в табличной части
        лежит отдельно от вида лица, и узнать вид можно только из того же ответа — у родительской
        записи, внутри которой пришла табличная часть. Запрос к 1С за видом маскировщик не делает:
        гейт не читает базу сам, ответ не должен зависеть от второго запроса и его ошибок.

        `класс_контейнера` — класс родительского поля-контейнера, если это org/person
        (правка ревью, 2026-09-09): раскрытый вложенный объект под полем «Контрагент» — это и
        есть организация, под полем «ФизЛицо»/«ОтветственноеЛицо» — физическое лицо, и поля
        наименования/ФИО внутри такого объекта наследуют класс поля-контейнера (см.
        `_класс_вложенного_поля`). Для прочих контейнеров (например, «КонтактнаяИнформация» —
        не название) остаётся `None`, и внутри работает обычная классификация по паре
        «сущность и поле», без наследования. С резолвером навигаций наследование стало запасным
        путём: класс берётся из политики настоящей сущности вложенного объекта, а наследуется
        только там, где политика о поле молчит.

        Спускаясь в непримитивное значение, обход переключает `entity` на цель навигации
        (итоговое ревью M1d, C1): до этого он шёл по всему дереву ответа с сущностью верхнего
        уровня, и классы полей раскрытого объекта искались под чужим ключом `сущность.поле`.

        Строка контактной информации (Ruling 33) решается ЦЕЛИКОМ до обхода её полей
        (`_строка_контактной_информации`): тип строки и её класс берутся из всей строки, а не из
        того поля, до которого обход дошёл первым, — иначе защита зависела бы от порядка ключей
        в ответе 1С."""
        if isinstance(значение, dict):
            # Вид лица ЭТОЙ записи — для её собственных полей и для её табличных частей ниже.
            # Запись без поля вида передаёт вниз «вид неизвестен», а не вид своего родителя:
            # табличная часть принадлежит ей, а не тому, кто её раскрыл.
            вид = значение.get(contact_info.ПОЛЕ_ВИДА_ЛИЦА)
            своё = (entity, вид if isinstance(вид, str) else None)
            контекст = своё if contact_info.ПОЛЕ_ВИДА_ЛИЦА in значение else вид_лица
            ки = self._строка_контактной_информации(
                entity, значение, shape=shape, вид_лица=контекст
            )
            if ки is not None and ки.строго and строгие_ки is not None:
                строгие_ки.append(entity)
            результат = {}
            for ключ, вложенное in значение.items():
                if ключ in СЛУЖЕБНЫЕ_ПОЛЯ or any(
                    ключ.endswith(суффикс) for суффикс in ДВОИЧНЫЕ_СУФФИКСЫ
                ):
                    continue
                # Значение может оказаться и в самом ключе словаря, а не только в значении
                # (правка ревью, защитный случай: штатный ответ платформы такой формы не отдаёт,
                # но раз ключ — тоже строка, реквизит в нём ищется точно так же, как в значении).
                новый_ключ = self._обработать_строку(
                    ключ,
                    entity=entity,
                    field=ключ,
                    класс=None,
                    замаскированные=замаскированные,
                    strict=strict,
                    значение_поля=False,
                    persist=persist,
                    только_классы=только_классы,
                )
                if isinstance(вложенное, str):
                    извлечь = None
                    if (
                        ки is not None
                        and ки.класс is not None
                        and contact_info.is_value_field(ключ)
                    ):
                        класс = self._класс_поля_контактной_информации(entity, ключ, ки.класс)
                        извлечь = contact_info.representation
                    else:
                        класс = self._класс_вложенного_поля(
                            entity, ключ, класс_контейнера, strict=strict
                        )
                        класс, извлечь = self._класс_самоописанного_значения(
                            entity,
                            вложенное,
                            класс,
                            shape=shape,
                            вид_лица=контекст,
                            строгие_ки=строгие_ки,
                        )
                    результат[новый_ключ] = self._обработать_строку(
                        вложенное,
                        entity=entity,
                        field=ключ,
                        класс=класс,
                        замаскированные=замаскированные,
                        strict=strict,
                        revealed=revealed,
                        извлечь=извлечь,
                        persist=persist,
                        только_классы=только_классы,
                    )
                else:
                    цель = resolve(entity, ключ) if resolve is not None else None
                    if цель is not None and hidden is not None and hidden(цель):
                        # Скрытая сущность скрыта и через связь: объект изымается целиком, а не
                        # маскируется, — иначе модель увидела бы и состав записи, и сам факт её
                        # существования. Имя ключа в предупреждение не попадает.
                        if изъятое is not None:
                            изъятое.append(ключ)
                        continue
                    # Индекс о ключе промолчал (C3 итогового ревью M1d, раунд 2): раньше обход
                    # просто оставался на политике РОДИТЕЛЯ — ровно то состояние, которое было
                    # дефектом C1, — и строгий режим не включался, потому что он привязан к
                    # разрешимости ПУТИ, а не цели раскрытия. Неизвестность трактуется в строгую
                    # сторону (Ruling 18, уже применённый к неразрешённому сегменту пути): вниз
                    # идём строго, а ответ получает то же предупреждение, что и неразрешённый
                    # путь `raw_get`. Само отсутствие резолвера (`resolve is None`) строгим
                    # режимом не считается: это «индекса нет вовсе», а не «индекс промолчал».
                    #
                    # «Промолчал» записывается только для КОНТЕЙНЕРА (I3 итогового ревью M1d,
                    # раунд 3): сюда, в ветку «не строка», попадают и числа, и булевы, и `null`,
                    # а у скаляра никакой цели раскрытия нет — спрашивать про сущность под ключом
                    # `СуммаДокумента` бессмысленно, и ответ «не знаю» на такой вопрос ничего не
                    # значит. Числовое или булево поле есть почти в каждом ответе 1С, поэтому
                    # предупреждение стояло практически всегда и обесценивало единственный случай,
                    # ради которого заведено. Ограничивается именно ЗАПИСЬ, а не сам вызов
                    # резолвера: `цель` нужна проверке `hidden` строкой выше, и без неё
                    # `"Контрагент": null` под скрытой навигацией перестал бы изыматься — а это
                    # оракул «ссылка пуста» против «ссылка скрыта» (вариант проверен ревьюером и
                    # отброшен). Резолвер кэширован, лишний вызов стоит ноль.
                    промолчал = (
                        isinstance(вложенное, dict | list) and resolve is not None and цель is None
                    )
                    if промолчал and неразрешённое is not None:
                        неразрешённое.append(ключ)
                    результат[новый_ключ] = self._обойти(
                        вложенное,
                        entity=цель or entity,
                        замаскированные=замаскированные,
                        field=ключ,
                        класс_контейнера=self._базовый_класс_названия(entity, ключ, strict=strict),
                        resolve=resolve,
                        hidden=hidden,
                        изъятое=изъятое,
                        неразрешённое=неразрешённое,
                        strict=strict or промолчал,
                        revealed=revealed,
                        shape=shape,
                        строгие_ки=строгие_ки,
                        вид_лица=своё,
                        persist=persist,
                        только_классы=только_классы,
                    )
            return результат
        if isinstance(значение, list):
            return [
                self._обойти(
                    элемент,
                    entity=entity,
                    замаскированные=замаскированные,
                    field=field,
                    класс_контейнера=класс_контейнера,
                    resolve=resolve,
                    hidden=hidden,
                    изъятое=изъятое,
                    неразрешённое=неразрешённое,
                    strict=strict,
                    revealed=revealed,
                    shape=shape,
                    строгие_ки=строгие_ки,
                    вид_лица=вид_лица,
                    persist=persist,
                    только_классы=только_классы,
                )
                for элемент in значение
            ]
        if isinstance(значение, str):
            # Строка без собственного ключа — элемент табличной части без объекта-обёртки, либо
            # голый ответ/элемент списка верхнего уровня, где имени поля нет вовсе (`field=""`).
            # Раньше такая строка проходила насквозь без проверки (правка ревью, критично: слой
            # тулов будет вызывать `mask()` и для таких форм ответа тоже, тихо возвращать
            # незащищённые данные нельзя).
            класс = self._класс_вложенного_поля(entity, field, класс_контейнера, strict=strict)
            класс, извлечь = self._класс_самоописанного_значения(
                entity,
                значение,
                класс,
                shape=shape,
                вид_лица=вид_лица,
                строгие_ки=строгие_ки,
            )
            return self._обработать_строку(
                значение,
                entity=entity,
                field=field,
                класс=класс,
                замаскированные=замаскированные,
                strict=strict,
                revealed=revealed,
                извлечь=извлечь,
                persist=persist,
                только_классы=только_классы,
            )
        return значение

    def _строка_контактной_информации(
        self,
        entity: str,
        строка: dict,
        *,
        shape: Shape | None,
        вид_лица: tuple[str, str | None] | None = None,
    ) -> _СтрокаКИ | None:
        """Строка табличной части контактной информации и класс её полей значения (Ruling 33).

        Узнаётся строка по строению (`contact_info.is_contact_info_table`): сперва по индексу —
        он знает все поля сущности, и строка узнаётся, даже если модель выбрала одно
        `Представление`; без индекса (`shape is None` или сущность ему не известна) — по суффиксу
        имени `_КонтактнаяИнформация` либо по ключам самой строки, и тогда нужны все три поля
        строения, иначе чужая сущность с полями `Тип` и `Значение` получила бы маскировку, которой
        не заслужила (инвариант 6). Правило — `contact_info.is_contact_info_entity`, общее со
        входным путём (Ruling 35).

        Класс — по типу строки (`contact_info.row_type`: поле `Тип`, а без него — тип, записанный
        в самом значении). Тип неизвестен или «прочий» (`ВебСтраница`, `Skype`, `Другое`) —
        маскировать всё равно, классом по содержимому (`класс_по_содержимому`); у неизвестного
        это ещё и повод предупредить модель. Адрес открыт или закрыт по правилам адресов
        (`_адрес_закрыт`, Ruling 34): у юрлица открытый адрес — строка идёт обычным путём."""
        # Без строения — ещё и суффикс имени (опасение 9 раунда 1, решение координатора): индекс
        # устарел, модель выбрала одно `Представление` — ни строения, ни `Тип`, ни `Значение`, и
        # адрес на уровне `identifiers` уходил открытым. Правило общее со входным путём.
        if not contact_info.is_contact_info_entity(entity, shape, строка.keys()):
            return None
        тип = contact_info.row_type(строка)
        класс = contact_info.КЛАСС_ПО_ТИПУ.get(тип) if тип else None
        if класс is None:
            основа = next(
                (
                    строка[поле]
                    for поле in (contact_info.ПОЛЕ_ПРЕДСТАВЛЕНИЯ, *contact_info.ПОЛЯ_СТРУКТУРЫ)
                    if isinstance(строка.get(поле), str) and строка[поле].strip()
                ),
                "",
            )
            return _СтрокаКИ(
                класс=contact_info.класс_по_содержимому(основа),
                строго=тип not in contact_info.ТИПЫ_ПЕРЕЧИСЛЕНИЯ,
            )
        if класс == "addr":
            закрыт, вид_неизвестен = self._адрес_закрыт(entity, shape=shape, вид_лица=вид_лица)
            if not закрыт:
                return _СтрокаКИ(класс=None)
            return _СтрокаКИ(класс=класс, строго=вид_неизвестен)
        return _СтрокаКИ(класс=класс)

    def _класс_самоописанного_значения(
        self,
        entity: str,
        текст: str,
        класс: str | None,
        *,
        shape: Shape | None = None,
        вид_лица: tuple[str, str | None] | None = None,
        строгие_ки: list[str] | None = None,
    ) -> tuple[str | None, Callable[[str], str] | None]:
        """Значение контактной информации ВНЕ её табличной части (Ruling 33): JSON или XML, в
        котором записан собственный тип (`contact_info.is_contact_value`), — в поле без класса
        (`None`/`scan`; `scan` владельца уступает, как в `_класс_поля_контактной_информации`: он
        просит искать реквизиты, а не оставить их открытыми). Так значение закрыто, даже когда
        строение сущности неизвестно (путь
        `raw_get` вне индекса, `$select` из одного `Значение`): по частям — `areaCode`, `number`,
        `street`, `apartments` — его не собрал бы ни один детектор. Поле с классом из политики
        (в том числе `keep`) не трогается: там решение уже принято, — меняется только основа
        токена: `АдресДоставкиЗначение` (JSON) получает тот же токен, что `АдресДоставки` (текст)
        того же документа, как `Значение` и `Представление` строки контактной информации."""
        if класс == "keep" or not contact_info.is_contact_value(текст):
            return класс, None
        if класс not in (None, "scan"):
            return класс, contact_info.representation
        тип = contact_info.self_type(текст)
        свой = contact_info.КЛАСС_ПО_ТИПУ.get(тип) if тип else None
        if свой is None:
            свой = contact_info.класс_по_содержимому(текст)
        if свой == "addr" and тип == "Адрес":
            закрыт, вид_неизвестен = self._адрес_закрыт(entity, shape=shape, вид_лица=вид_лица)
            if not закрыт:
                return класс, None
            if вид_неизвестен and строгие_ки is not None:
                строгие_ки.append(entity)
        return свой, contact_info.representation

    def _адрес_закрыт(
        self,
        entity: str,
        *,
        shape: Shape | None,
        вид_лица: tuple[str, str | None] | None,
    ) -> tuple[bool, bool]:
        """Закрыт ли почтовый адрес контактной информации этой сущности, и закрыт ли он ТОЛЬКО
        потому, что вид лица неизвестен (тогда модель предупреждается, как получить точный ответ).

        1. Правило адресов политики (`Policy.addr_masked`): адрес физлица — и в табличной части
           его справочника (Ruling 34, пункт 1), адрес доставки — всегда (пункт 3).
        2. Иначе — вид лица (Ruling 34, пункт 2). Чей это адрес: для табличной части — её
           владельца (родитель по индексу), для записи — её самой. У лица, для которого вид не
           ведётся вовсе (склад: поля `ЮрФизЛицо` у сущности нет), решает одно правило 1 — адрес
           открыт. У лица с видом адрес открыт только при ЯВНО юридическом виде
           (`contact_info.ВИДЫ_ЮРЛИЦ`), взятом из того же ответа (`вид_лица`, см. `_обойти`).

        Неизвестность — в строгую сторону (Ruling 18): сущность или её владелец вне индекса,
        строения нет вовсе (`shape is None`), вид в ответе не пришёл — адрес закрыт. Выборка
        табличной части контрагентов напрямую поэтому закрывает и адреса юрлиц: вида владельца в
        ней нет, а открытый адрес юрлица модель получает из карточки контрагента (`get`), где
        табличная часть приходит рядом с полем `ЮрФизЛицо`."""
        if self._policy.addr_masked(entity):
            return True, False
        строение = shape(entity) if shape is not None else None
        if строение is None:
            return True, True
        лицо = строение.parent or entity
        строение_лица = строение if лицо == entity else shape(лицо)
        if строение_лица is None:
            return True, True
        if contact_info.ПОЛЕ_ВИДА_ЛИЦА not in строение_лица.fields:
            return False, False
        вид = вид_лица[1] if вид_лица is not None and вид_лица[0] == лицо else None
        if вид in contact_info.ВИДЫ_ЮРЛИЦ:
            return False, False
        return True, вид is None

    def _класс_поля_контактной_информации(
        self, entity: str, field: str, класс_строки: str
    ) -> str | None:
        """Класс поля значения в строке контактной информации: класс строки — если владелец не
        написал для поля своего правила рукой (`Policy.manual_sensitivity_of`). Раздел `auto`
        правилу строки уступает: он размечает поля по имени (`НомерТелефона` → phone), а тип
        строки знает о значении больше. Ручное правило, наоборот, главнее (итоговое ревью M1d,
        C1): объявленный владельцем `keep` строкой не отменяется; названия по уровню понижаются,
        как везде.

        Исключение — ручной `scan`: он значит «ищи реквизиты в этом тексте», а не «не маскируй»,
        и цели владельца (защитить поле) правило строки служит лучше — номер, разнесённый по
        `areaCode` и `number` JSON, сканер не соберёт, и цифры ушли бы открытыми. Поэтому `scan`
        уступает правилу строки, как `auto`; единственное ручное «не защищать» — `keep`. То же
        правило — у значения вне табличной части (`_класс_самоописанного_значения`)."""
        ручной = self._policy.manual_sensitivity_of(entity, field)
        if ручной is not None and ручной != "scan":
            return self._понизить_класс_названия(ручной)
        return класс_строки

    def _класс_вложенного_поля(
        self, entity: str, field: str, класс_контейнера: str | None, *, strict: bool = False
    ) -> str | None:
        """Класс строкового поля с учётом наследования от контейнера (см. `_обойти`): внутри
        объекта, лежащего под полем-организацией/лицом, поле наименования/представления/ФИО
        получает класс контейнера вместо собственной (обычно пустой) классификации — но так же,
        как и обычное поле названия, понижается до сканирования не на верхнем уровне защиты
        (правка ревью: раскрытие названия/ФИО не должно обходить понижение уровня).

        Порядок источников (итоговое ревью M1d, C1): СНАЧАЛА политика своей сущности, и только
        если она о поле молчит — наследование от контейнера. Раньше было наоборот, и это ломало
        два случая сразу: правило, написанное владельцем рукой (`fields`), молча заменялось
        унаследованным `org` и вместе с ним понижалось уровнем, а объявленный владельцем `keep`
        отменялся наследованием. Когда политика молчит (нет резолвера, сущность вне индекса),
        наследование работает как работало — это его единственная задача."""
        свой = self._класс_поля(entity, field, strict=strict)
        if свой is not None:
            return свой
        if класс_контейнера is not None and is_naming_field(field):
            return self._понизить_класс_названия(класс_контейнера)
        return None

    def _базовый_класс_названия(
        self, entity: str, field: str, *, strict: bool = False
    ) -> str | None:
        """Класс поля-контейнера без понижения по уровню — только если это org/person; иначе
        `None` (наследовать нечего). Вычисляется тем же путём, что и `_класс_поля`, но до
        понижения — понижение при наследовании применяется отдельно, к вложенному полю."""
        класс = self._базовый_класс_поля(entity, field, strict=strict)
        return класс if класс in КЛАССЫ_НАЗВАНИЙ else None

    def _базовый_класс_поля(self, entity: str, field: str, *, strict: bool = False) -> str | None:
        """Тело вынесено в модульную `_базовый_класс_поля_политики` (M1d, задача 1) — используется
        и здесь, и в `effective_field_class` для обратной подмены."""
        return _базовый_класс_поля_политики(self._policy, entity, field, strict=strict)

    def _класс_поля(self, entity: str, field: str, *, strict: bool = False) -> str | None:
        """Тело — `effective_field_class` (M1d, задача 1): тот же эффективный класс, которым
        пользуется `pipeline.BaseGate` для `is_protected` и для `Unmasker`."""
        return effective_field_class(self._policy, entity, field, mode=self._mode, strict=strict)

    def _понизить_класс_названия(self, класс: str | None) -> str | None:
        return _понизить_класс_названия_по_уровню(класс, mode=self._mode)

    def _обработать_строку(
        self,
        текст: str,
        *,
        entity: str,
        field: str,
        класс: str | None,
        замаскированные: УчётПолей,
        force_scan: bool = False,
        strict: bool = False,
        revealed: RevealedValues | None = None,
        извлечь: Callable[[str], str] | None = None,
        значение_поля: bool = True,
        из_ответа: bool = True,
        persist: bool = True,
        только_классы: bool = False,
    ) -> str:
        """`из_ответа=False` — строка не данные ответа 1С, а текст ошибки или подсказки
        (`mask_text`): токены в ней пишет сам шлюз, и в `lit` они не превращаются (Б-2).

        `извлечь` — как получить из значения поля основу токена (`Dictionary.token_for`,
        аргумент `source`), если поле замаскировано целиком по классу и основа — не всё
        содержимое: у значения контактной информации это его представление
        (`contact_info.representation`, Ruling 33).

        `значение_поля=False` — строка не значение, а ИМЯ поля (ключ словаря ответа проверяется
        тем же путём, см. `_обойти`): в знаменатель `masked_fields` оно не входит, иначе каждое
        значение считалось бы дважды и ни одно поле не оказалось бы замаскированным полностью."""
        # Строку переписал ранний проход (Ruling 32): исходное значение её места — реальное — лежит
        # в наборе вызова (Б-3). Всё, что отсюда уходит, — обычная строка (это проверяет сторож
        # `BaseGate.finish`), а исходное читает только ветка поля с классом.
        переписано: ScrubbedText | None = None
        if isinstance(текст, ScrubbedText):
            переписано, текст = текст, str(текст)
        if not текст:
            return текст
        # SPEC §6.4, сноска ⁴; инвариант 6: GUID не защищается. `.strip()` — GUID фиксированной
        # длины в строковом поле 1С приходит с хвостовыми пробелами (M1 ревью 2026-09-10); без
        # него `" cc52…"` проваливался мимо и попадал в словарь как «название организации».
        if GUID_RE.fullmatch(текст.strip()):
            return текст
        # Знаменатель `masked_fields` (см. `УчётПолей`): значение, которое маскировщик взвешивает.
        if значение_поля:
            замаскированные.увидено(field)
        # Б-2: токен шлюза в строке ДАННЫХ 1С — не токен, а текст, и выдаётся токеном `lit`, в
        # том числе в поле, открытом владельцем (`keep` открывает значение, а не право выдать
        # строку из 1С за токен шлюза). Имена полей и тексты ошибок (`из_ответа=False`) не
        # трогаются: в сообщениях токены пишет сам шлюз.
        строка_данных = из_ответа and значение_поля
        if класс == "keep":
            if переписано is not None:
                замаскированные.append(field, целиком=bool(parse_token(текст)))
            if строка_данных:
                return self._заменить_строки_с_токенами(
                    текст,
                    entity=entity,
                    field=field,
                    вставки=self._вставки(переписано, revealed),
                    persist=persist,
                )
            return текст
        if класс and класс not in ("scan",) and (класс in CLASSES or класс.startswith("custom:")):
            return self._заменить_по_классу(
                текст,
                класс=класс,
                entity=entity,
                field=field,
                замаскированные=замаскированные,
                revealed=revealed,
                переписано=переписано,
                извлечь=извлечь,
                persist=persist,
            )
        # Первый проход (SPEC §6.6, см. `mask`): свободный текст, поля класса `scan` и поиск
        # реквизитов по значению — работа второго прохода. Здесь строка возвращается как есть, и в
        # `замаскированные` ничего не добавляется: учёт первого прохода выбрасывается вместе с его
        # результатом.
        #
        # Ветка `keep` выше первым проходом выполняется как обычно — отдельное условие ради неё
        # было бы лишней веткой и лишним тестом. Словарь она при этом ВСЁ ЖЕ может задеть: у
        # строки, переписанной ранним проходом, `revealed=None` первого прохода оставляет
        # `вставки` пустыми, и `_заменить_строки_с_токенами` выдаёт токену, который поставил сам
        # ранний проход, токен `lit`. Запись остаётся мёртвой: результат первого прохода выброшен,
        # второй проход с настоящим набором эту вставку не трогает, а стражу значение класса `lit`
        # не видно — ни среди чисел (`number_tokens`), ни среди вариантов названий
        # (`name_variants`: класс не из названий, а написание с `[[` отсеивают `_мусорные_токены`).
        if только_классы:
            return текст

        обработанное = текст
        if строка_данных:
            обработанное = self._заменить_строки_с_токенами(
                обработанное,
                entity=entity,
                field=field,
                вставки=self._вставки(переписано, revealed),
                persist=persist,
            )
        обработанное = self._заменить_известные_названия(обработанное, entity=entity, field=field)
        # Ruling 48: словарь пополняется только данными ответа 1С; текст ошибки (`mask_text`) —
        # токенами без записи.
        обработанное = self._заменить_найденные_реквизиты(
            обработанное,
            entity=entity,
            field=field,
            force=force_scan or strict,
            persist=из_ответа and persist,
        )
        # Поле, где значение заменил только ранний проход, — тоже без реального значения в ответе
        # (находка M-2 ревью 6; Ruling 20, пункт 4: список говорит правду ПО ФАКТУ). Исходное здесь
        # не подставляется и не перемаскируется: для поля без класса это путь дефекта N1-B.
        if обработанное != текст or переписано is not None:
            # Токен на всё значение — значение закрыто целиком; замена внутри текста — частично
            # (`УчётПолей`): остальной текст открыт, и назвать поле замаскированным нельзя.
            замаскированные.append(field, целиком=bool(parse_token(обработанное)))
        return обработанное

    def _заменить_по_классу(
        self,
        текст: str,
        *,
        класс: str,
        entity: str,
        field: str,
        замаскированные: УчётПолей,
        revealed: RevealedValues | None,
        переписано: ScrubbedText | None = None,
        извлечь: Callable[[str], str] | None = None,
        persist: bool = True,
    ) -> str:
        """Поле с объявленным классом — целиком одним токеном (SPEC §6.4). Два случая, когда в
        строке УЖЕ стоит токен (находка П2 приёмки через настоящие инструменты, 2026-09-12):

        1. Токен этого вызова, подставленный ранним проходом раскрытого (Ruling 25): `ИНН eq
           '[[inn:6R1669KTWC]]'` находит запись, и ещё до разбора ответа её `ИНН` в сыром теле
           заменён этим токеном. Прежде маскировщик нормализовал сам токен как ИНН (оставлял
           цифры хвоста, «61669») и выдавал «значению» новый токен — одна запись в двух запросах
           приходила разными токенами (инвариант 5), повторный отбор по новому токену искал в 1С
           число, которого там нет, а в словарь ложился мусорный реквизит. То же — с токеном
           ВНУТРИ строки: `Description` контрагента входит в его `НаименованиеПолное` (одна
           запись из сорока на живой базе). Токен выдаётся тому, что стояло в ЭТОМ поле до
           раннего прохода (`RevealedValues.original_of`, Ruling 32: по месту, а не по токену и
           не по порядку обхода; Б-3: исходное хранит набор вызова, а не строка), — ровно тот
           же, что в ответе без отбора, и словарь не получает чужого написания. Наружу при этом
           не уходит ничего нового: результат — по-прежнему один токен на всё поле. Набор не
           знает этой строки (она переписана в другом вызове) — исходного нет, и поле остаётся
           тем, что сделал ранний проход.

           Замены раннего прохода, пришедшиеся на поле с классом, снимаются со счётчика
           `guard_replaced` (`RevealedValues.absorb`): это поле маскировщик закрыл бы и сам, а
           «страж поймал то, что пропустил маскировщик» на каждом отборе по токену было бы
           неправдой.

           Исходное значение наружу не отдаётся НИКОГДА — правило структурное, а не по случаю:
           если словарь не дал ему токена (`token_for` возвращает строку как есть, когда в ней
           одни пробелы), поле остаётся тем, что сделал ранний проход, и его замены остаются
           засчитанными стражу.

        2. Строка — обычная (ранний проход её не трогал), и в ней стоит токен шлюза: это данные
           1С — вписанная человеком или подложенная строка `[[inn:…]]` (Б-2, находка M-1 ревью 6).
           Прежде целый токен, выданный словарём, пропускался как «уже замаскированный», и модель
           видела у записи R токен значения S — два значения под одним токеном. Уже
           замаскированное шлюзом значение приходит сюда только строкой раннего прохода (случай
           1), поэтому обычная строка с токеном — всегда данные: она получает токен класса `lit`
           (`tokens.КЛАСС_СТРОКИ_С_ТОКЕНОМ`) по дословному содержимому. То же — исходное значение
           места в случае 1, если в нём самом стоит токен. Токен настоящего значения такая
           строка не получает никогда: ИНН рядом с вписанным токеном (`7707083893 [[inn:…]]`)
           нормализация класса свела бы к цифрам — это была находка M-3.

        `masked_fields` заполняется ПО ФАКТУ (Ruling 20, пункт 4): поле в списке — значит
        реального значения в ответе нет. В обоих случаях выше его нет, и поле числится
        замаскированным так же, как в ответе без отбора.

        `извлечь` — основа токена, отличная от содержимого поля (см. `_обработать_строку`);
        берётся из ИСХОДНОГО значения места, а не из переписанного ранним проходом."""
        if переписано is not None:
            замаскированные.append(field)
            исходное = revealed.original_of(переписано) if revealed is not None else None
            if исходное is None:
                return текст
            замена = self._токен_поля(
                класс, исходное, entity=entity, field=field, извлечь=извлечь, persist=persist
            )
            if замена == исходное:
                return текст
            if revealed is not None:
                revealed.absorb(переписано.hits)
            return замена
        замена = self._токен_поля(
            класс, текст, entity=entity, field=field, извлечь=извлечь, persist=persist
        )
        if замена != текст:
            замаскированные.append(field)
        return замена

    def _токен_поля(
        self,
        класс: str,
        значение: str,
        *,
        entity: str,
        field: str,
        извлечь: Callable[[str], str] | None,
        persist: bool = True,
    ) -> str:
        """Токен значения поля с классом; строка с токеном шлюза внутри — токен `lit` (Б-2).

        `persist=False` — маска без записи в словарь (Ruling 58: тул `odata1c_journal`). Название
        и ФИО, которых словарь не знает, номера без записи не получают (`Dictionary.token_for`
        отказывает `ValueError`: следующий номер получило бы и другое значение), и значение
        закрывается непрозрачной пометкой класса без хвоста (`МЕТКА_БЕЗ_ЗАПИСИ`). Она нарочно
        не токен (`TOKEN_RE` её не узнаёт): раскрывать её нечем, и в отбор или тело записи она
        не годится — это пометка «здесь было название», а не адрес значения."""
        if TOKEN_RE.search(значение):
            return self._dictionary.token_for(
                КЛАСС_СТРОКИ_С_ТОКЕНОМ,
                значение,
                base=self._base,
                entity=entity,
                field=field,
                persist=persist,
            )
        try:
            return self._dictionary.token_for(
                класс,
                значение,
                base=self._base,
                entity=entity,
                field=field,
                source=извлечь(значение) if извлечь is not None else None,
                persist=persist,
            )
        except ValueError:
            if persist:
                raise
            return МЕТКА_БЕЗ_ЗАПИСИ.format(класс=класс)

    def _заменить_строки_с_токенами(
        self,
        текст: str,
        *,
        entity: str,
        field: str,
        вставки: tuple[tuple[int, int], ...],
        persist: bool = True,
    ) -> str:
        """Токены шлюза внутри строки данных 1С — токенами `lit` (Б-2). Кроме тех, что поставил
        сам ранний проход этого вызова: они стоят в `вставки` (`RevealedValues.inserted_of`), и
        отличить их от вписанного в 1С того же токена можно только по месту — текст одинаков."""
        найдено = find_tokens(текст)
        if not найдено:
            return текст
        куски: list[str] = []
        позиция = 0
        for начало, конец, _, _ in найдено:
            if any(слева <= начало and конец <= справа for слева, справа in вставки):
                continue
            куски.append(текст[позиция:начало])
            куски.append(
                self._dictionary.token_for(
                    КЛАСС_СТРОКИ_С_ТОКЕНОМ,
                    текст[начало:конец],
                    base=self._base,
                    entity=entity,
                    field=field,
                    persist=persist,
                )
            )
            позиция = конец
        куски.append(текст[позиция:])
        return "".join(куски)

    def _заменить_найденные_реквизиты(
        self, текст: str, *, entity: str, field: str, persist: bool, force: bool = False
    ) -> str:
        """`persist` обязателен: пополнять ли словарь найденным — решение вызывающего, по тому,
        данные ли это 1С (Ruling 48), а не умолчание."""
        if not force and not self._policy.scan_free_text:
            return текст
        # Имя поля — естественная подсказка для детектора контекста: строка «ИНН 7707083893»
        # распознаётся, а голое «7707083893» — нет (правка ревью, Critical: раскрытый контрагент
        # внутри документа приходит без слова-подсказки рядом со значением). Подсказка участвует
        # только в поиске — в результат должен попасть подменённым лишь исходный фрагмент, поэтому
        # совпадения целиком или частично внутри подсказки отбрасываются (`начало < 0`).
        подсказка = f"{field} " if field else ""
        совпадения = scan_value(подсказка + текст)
        if not совпадения:
            return текст
        смещение = len(подсказка)
        куски, позиция = [], 0
        for совпадение in совпадения:
            начало, конец = совпадение.start - смещение, совпадение.end - смещение
            if начало < 0:
                continue
            куски.append(текст[позиция:начало])
            куски.append(
                self._dictionary.token_for(
                    совпадение.type,
                    совпадение.value,
                    base=self._base,
                    entity=entity,
                    field=field,
                    persist=persist,
                )
            )
            позиция = конец
        куски.append(текст[позиция:])
        return "".join(куски)

    def _обновить_автомат_названий(self) -> None:
        """Пересобрать автомат и множество вариантов, если словарь изменился с прошлой сборки
        (номер ревизии — тот же признак, что использует guard.py). Сборка на словаре в сто тысяч
        значений — около семидесяти пяти мс (docs/probes/P6-guard-performance.md), поэтому лениво
        по ревизии, а не на каждый вызов."""
        if self._названия_ревизия == self._dictionary.revision():
            return
        self._названия_варианты = self._dictionary.name_variants()
        ключи = list(self._названия_варианты)
        # `Standard`, а не `LeftmostLongest`: нужны ВСЕ совпадения, в том числе пересекающиеся
        # (Б-4, `gate/overlaps.py`) — только этот вид автомата умеет `overlapping=True`.
        self._названия_автомат = AhoCorasick(ключи, matchkind=MatchKind.Standard) if ключи else None
        self._названия_ревизия = self._dictionary.revision()

    def _заменить_известные_названия(self, текст: str, *, entity: str, field: str) -> str:
        """Слой 3 SPEC §6.5: известные варианты названий в любой строке.

        Поиск — автоматом Aho-Corasick (ahocorasick_rs) по нормализованной копии строки, а не
        линейным перебором `re.search` по каждому варианту (перенос по задаче 8 M1c: словарь
        названий может вырасти на порядки, и перебор вариантов на каждую строку ответа не
        масштабируется так, как один проход автомата).

        Нормализация — та же, что и у ключей автомата (`dictionary.normalize_text_with_map`,
        та же, которой словарь строит варианты в `name_variants_of`): кавычки любого вида к
        прямой, пробелы любого вида схлопнуты в один, регистр — к нижнему посимвольно, с картой
        позиций к исходной строке. До этого (ревью 2026-09-09, дыры 1 и 2) строка сверялась с
        нормализованными ключами КАК ЕСТЬ — двойной пробел, неразрывный пробел или кавычки-ёлочки
        внутри названия (обычная запись в 1С) не совпадали ни с одним ключом; а `текст.lower()`
        целиком вместо посимвольного приведения сдвигал(бы) индексы совпадений относительно
        исходной строки на символах, чей нижний регистр разворачивается в несколько знаков
        (например, `İ`, U+0130) — с картой позиций обе проблемы решены одним приёмом.

        Уже стоящие в строке токены закрываются заглушкой той же длины до поиска
        (`tokens.blank_tokens`): хвост токена реквизита набран из тех же символов, что и
        приведённое к нижнему регистру латинское название, и вариант мог бы разрезать токен
        (ревью 2026-09-09, дыра 8), а вариант, зацепивший скобку токена, подавлял более короткий
        вариант названия рядом (Ruling 21 M1c, хвост 2) — с заглушкой совпасть с токеном нечему.

        Пересекающиеся названия (Б-4, находка I-2 ревью 7): ищутся все совпадения, и сцепленные
        пересечениями заменяются одной группой — накрывающим названием или токенами всех
        участников подряд (`gate/overlaps.py`). Прежний поиск без пересечений брал первое и
        оставлял хвост второго открытым: «Юг Альфа Север» → `[[org:1]] Север`.
        """
        if self._mode != "identifiers+names":
            return текст
        self._обновить_автомат_названий()
        if self._названия_автомат is None:
            return текст
        заменено, _ = заменить_названия(текст, self._названия_автомат, self._названия_варианты)
        return заменено
