# SPEC §6.5, слой 2: имена в строковых реквизитах любой сущности.
ЛИЦО_ТОЧНО = re.compile(
    r"^(имя|фамилия|отчество|фио|кассир|подписант|представитель|исполнитель|менеджер|автор)$",
    re.IGNORECASE,
)
# Разведка БП (2026-09-24, `docs/probes/BP-recon.md`): части ФИО в составных именах форматов ФНС
# и СФР (`РебенокФамилия`, `ДоверительФЛ_Отчество`, `ФЛ_Имя`, `ФамилияПолучателя`) — `фамили`,
# `отчеств`, `имялатиниц` и `…Имя` в конце имени поля, кроме служебных (`ИМЯ_НЕ_ЛИЦА`).
# «Сотрудник» — только всё поле целиком (`Сотрудник`, `Сотрудники`, `…Сотрудник`,
# `СотрудникСтрокой`): подстрокой он метил `ТипЗаявкиКабинетСотрудника`, `КатегорияСотрудника`,
# `РольСотрудника` и ещё девять полей БП, чьё значение — перечисление или служебный текст.
ЛИЦО_ЧАСТЬ = re.compile(
    r"фио|ответственн(ое|ый)лицо|руководител|бухгалтер|контактноелицо|физлицо"
    r"|сотрудник(и|строкой)?$|сотрудниковстрокой"
    r"|фамили|отчеств|имялатиниц",
    re.IGNORECASE,
)
ИМЯ_В_КОНЦЕ = re.compile(r"имя$", re.IGNORECASE)
# Служебные поля, чьё имя кончается на «Имя», а значение — не имя человека (сверено по полным
# `$metadata` УТ и БП): имя входящего файла, полное имя объекта метаданных, имя табличной части.
ИМЯ_НЕ_ЛИЦА = re.compile(r"файлимя|полноеимя|табличнаячастьимя", re.IGNORECASE)
# Поля-перечисления, чьё имя содержит признак лица, но значение — член перечисления, а не ФИО
# (находка П1 приёмки через настоящие инструменты, 2026-09-12). `ЮрФизЛицо` — тип контрагента,
# организации или партнёра, два значения («ЮрЛицо»/«ФизЛицо»): `ЛИЦО_ЧАСТЬ` ловил подстроку
# «физлицо», и модель получала `[[person:1]]`/`[[person:2]]` — теряла единственный признак, по
# которому организация отличается от ИП. Ложное срабатывание — дефект по духу инварианта 6.
#
# Классификатор это поле не метит по правилу каталога (`common.yaml`, `names: ЮрФизЛицо: scan`);
# регулярное выражение здесь нужно словарю — признаку мусорных токенов, выданных до правки
# (`Dictionary._порождённые_перечислениями`). Сверка по полному `$metadata` УТ (7224 сущности,
# 1006 перечислений): среди строковых полей, названных как перечисление, класс по имени получало
# ровно это поле, у трёх справочников.
#
# Почему не индекс, хотя таблица `enums` в нём есть. 1С отдаёт поле-перечисление как `Edm.String`
# и в `$metadata` не связывает его с `EnumType` (проверено по `ut-real.edmx`: `ЮрФизЛицо`
# объявлено `Edm.String`), поэтому индекс может только угадать по совпадению имени поля с именем
# перечисления — то же сравнение имён, только менее явное. Второе и решающее: классификатор нужен
# не только реиндексу, но и маскировщику как запасной путь без индекса
# (`masking._базовый_класс_поля_политики`), — исключение, выведенное из индекса, до него не
# дошло бы, и поле, выпавшее из раздела `auto`, запасной путь снова пометил бы как ФИО.
ПЕРЕЧИСЛЕНИЯ_ТИПА_ЛИЦА = re.compile(r"юрфизлицо", re.IGNORECASE)
# Поля, чьё имя содержит признак лица, но значение — ссылка на график, договор, должность или
# решение, а не имя человека (проект M3b §3.4), — правила каталога `names: …: scan` (ADR-0016),
# полными именами: подстрока «руководител» законно метит ФИО в `ФИОРуководителяКонтрагента`, и
# ослаблять саму эвристику нельзя.
ОРГ_ТОЧНО = re.compile(
    r"^(организация|контрагент|партнер|клиент|заказчик|подрядчик|субподрядчик|комитент"
    r"|комиссионер|принципал|дебитор|кредитор|плательщик|получатель|поставщик|покупатель"
    r"|грузополучатель|грузоотправитель)$",
    re.IGNORECASE,
)
# Правка координатора (2026-09-09, второй раунд): список дополнен терминами, однозначно
# означающими юридическое лицо или предпринимателя в конфигурациях 1С — «Партнёр» (SPEC §6.5,
# слой 1: Catalog_Партнеры прямо в names_for, но слой 2 его не ловил), «Клиент», «Заказчик»,
# «Подрядчик», «Субподрядчик», «Комитент», «Комиссионер», «Принципал», «Дебитор», «Кредитор» —
# в торговых конфигурациях поля документов чаще названы партнёром, чем контрагентом, и
# наименование раскрытого объекта под этим полем уходило открытым текстом (найдено ревью задачи 6
# плана M1c). Сознательно не добавлены «агент» и «представитель» — слишком общие, встречаются в
# служебных полях платформы; «лицо» — тем более, пересеклось бы с классом person.
# Правка координатора (2026-09-09, первый раунд): убраны общие «наименованиеполное»/
# «полноенаименование» — в чужой сущности (вне names_for) это поле встречается у номенклатуры,
# складов, договоров и защищало бы их поголовно как названия организаций. Внутри names_for полное
# наименование по-прежнему защищается слоем 1 через NAME_FIELD_RE — там оно однозначно.
ОРГ_ЧАСТЬ = re.compile(
    # `наиморг` — сокращение форматов ФНС (`ДоверительЮЛ_НаимОрг` машиночитаемых доверенностей).
    r"наименованиеорганизации|наименованиеконтрагента|наименованиебанка|наиморг",
    re.IGNORECASE,
)


def is_naming_field(field: str) -> bool:
    """Поле само по себе — наименование или ФИО, без привязки к сущности (тот же признак, что
    даёт слою 1 право сработать в `classify_field`, вынесен отдельно): `Description` — общее
    техническое имя представления любого объекта платформы, остальное — по
    `_фио_или_наименование`. Используется в `gate/masking.py`, чтобы поле раскрытого вложенного
    объекта (contragent/физлицо внутри документа) наследовало класс родительского поля-контейнера
    (SPEC §6.5, поправка 2026-09-09)."""
    return field == "Description" or _фио_или_наименование(field)


def classify_field(
    entity: str,
    field: str,
    edm_type: str,
    *,
    names_for: set[str] | None = None,
    rules: RuleCatalog | None = None,
    strict: bool = False,
) -> tuple[str, str] | None:
    """Класс строкового поля по имени — вход авторазметки (SPEC §4.3) и запасной путь
    маскировщика и обратной подмены. Порядок: служебное поле → правило каталога на поле одной
    сущности (`fields`) → правило каталога на имя поля (`names`) → реквизиты по имени поля →
    слой 1 (`Description` и ФИО справочника из `names_for`) → слой 2 (ФИО и названия в чужой
    сущности). Правило каталога `scan` — «по имени не классифицировать», то есть `None`.

    `rules` — действующий каталог правил базы (поставка и владелец, `rules.load_rules`); без него
    — каталог поставки. `names_for` по умолчанию — справочники людей и организаций каталога.
    `strict` — сущность индексу не известна (строгий режим, Ruling 18): правило `fields` каталога
    действует и на сущность, чьё имя после канонизации совпадает с именем правила
    (`RuleCatalog.field_rule_canonical`: точка в конце, невидимый символ, регистр)."""
    if edm_type not in СТРОКОВЫЕ_ТИПЫ:
        return None
    if field in ("Ref_Key", "Code", "Number", "DataVersion") or field.endswith("_Type"):
        return None

    # Счёт учёта в плане счетов — не банковский счёт (SPEC §6.4, оговорка про chartofaccounts).
    # То же у регистра бухгалтерии: `Account` его записей и виртуальных таблиц — навигация к плану
    # счетов (приёмка рецептов БП, 2026-09-25: отбор `Account/Code eq '51'` отклонялся как путь
    # через банковский счёт). `AccountDr`, `BalancedAccount` правилом `^account$` не ловятся и так.
    if entity.startswith(("ChartOfAccounts", "AccountingRegister")) and re.fullmatch(
        r"account|счет", field, re.IGNORECASE
    ):
        return None

    каталог = rules if rules is not None else package_rules()
    правило = каталог.field_rule(entity, field)
    if правило is None and strict:
        правило = каталог.field_rule_canonical(entity, field)
    if правило is None:
        правило = каталог.name_rule(field)
    if правило is not None:
        return None if правило == БЕЗ_КЛАССА else (правило, "auto")

    for класс, шаблон in ПРАВИЛА_РЕКВИЗИТОВ:
        if шаблон.search(field):
            return (класс, "auto")

    список = names_for if names_for is not None else set(каталог.names_for)
    if entity in список and is_naming_field(field):
        класс = "person" if entity in каталог.people else "org"
        return (класс, "auto")

    имя_класса = _имя_в_чужой_сущности(entity, field)
    return (имя_класса, "auto") if имя_класса else None


def _имя_в_чужой_сущности(entity: str, field: str) -> str | None:
    """Слой 2 SPEC §6.5: строковый реквизит, несущий имя открытым текстом. Исключения полными
    именами полей (член перечисления `ЮрФизЛицо`, ссылки на график, договор, должность) — правила
    каталога `names: …: scan`, они срабатывают раньше."""
    if entity == "Catalog_Банки" and ОРГ_ЧАСТЬ.search(field):
        return None  # названия банков не защищаются (SPEC §6.4)
    if (
        ЛИЦО_ТОЧНО.fullmatch(field)
        or ЛИЦО_ЧАСТЬ.search(field)
        or (ИМЯ_В_КОНЦЕ.search(field) and not ИМЯ_НЕ_ЛИЦА.search(field))
    ):
        return "person"
    if ОРГ_ТОЧНО.fullmatch(field) or ОРГ_ЧАСТЬ.search(field):
        return "org"
    return None
