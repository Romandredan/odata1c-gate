"""Классификация полей по имени при реиндексе (SPEC §6.4 слой имени, §6.5 слои 1 и 2).

Результат ложится в секцию auto политики базы; ложные срабатывания пользователь переводит
в keep вручную. Классифицируются только строковые поля.
"""

from __future__ import annotations

import re

СТРОКОВЫЕ_ТИПЫ = ("Edm.String",)

# Справочники, описывающие людей (Ruling 36, 2026-09-12): их `Description` — ФИО (класс `person`),
# и их адрес — адрес физлица (`defaults.addr.mask_for` новой политики, SPEC §6.9).
#
# Список ЯВНЫЙ и сверен с полным `$metadata` УТ 11 (`tests/fixtures/edmx/probe.full.edmx`) и с
# данными живой базы, а не написан по памяти: прежний список держал `Catalog_КонтактныеЛица`,
# которого в УТ нет, — справочник там называется `Catalog_КонтактныеЛицаПартнеров`, и ФИО
# контактных лиц клиентов уходили модели открытыми. Эвристика по полям (Фамилия, Отчество,
# ДатаРождения, Пол, СНИЛС) — сторож в тестах (`test_gate_field_rules.py`), а не механизм:
# `ОтветственныеЛицаОрганизаций` и `Пользователи` признаков человека в полях не несут, а у
# `Партнеры` они есть, хотя это чаще компания.
#
# `Catalog_Сотрудники` и `Catalog_КонтактныеЛица` в УТ 11 нет — они из других конфигураций (ЗУП,
# БП) и оставлены намеренно: список общий на все базы, а лишнее имя ничего не открывает.
СУЩНОСТИ_ФИЗЛИЦ = frozenset(
    {
        "Catalog_ФизическиеЛица",
        "Catalog_Сотрудники",
        "Catalog_КонтактныеЛица",
        "Catalog_Пользователи",
        # Ruling 36 — найдены сверкой с индексом УТ 11:
        "Catalog_КонтактныеЛицаПартнеров",
        "Catalog_ОтветственныеЛицаОрганизаций",
        "Catalog_ПодписантыОрганизацийЕИС",
        "Catalog_ПодписантыСервисаМобильнойПодписи",
        "Catalog_ПользователиВЕТИС",
        "Catalog_СертификатыКлючейЭлектроннойПодписиИШифрования",
        "Catalog_УдалитьСертификатыЭП",
    }
)
# SPEC §6.5, слой 1: сущности, в которых Description и поля ФИО заменяются — все справочники
# людей и справочники организаций (у них класс `org`).
DEFAULT_NAMES_FOR = СУЩНОСТИ_ФИЗЛИЦ | frozenset(
    {
        "Catalog_Контрагенты",
        "Catalog_Партнеры",
        "Catalog_Организации",
    }
)
# Правка координатора (2026-09-09, второй раунд): «фамилия», «отчество», «фио» и формы полного
# наименования/представления не имеют служебных омонимов на платформе — матчатся вхождением, как
# исходно. Только «имя» ловит служебные поля платформы (ИмяФайла, ИмяПользователяИБ и т. п.) —
# для него нужна не полная анкеровка (первый раунд правки защитил от служебных полей ценой того,
# что перестал ловить локализованные реквизиты вида ФамилияРусская, ИмяПриРождении), а вхождение
# с явным списком служебных исключений (см. СЛУЖЕБНЫЕ_ПОЛЯ_ИМЯ ниже).
NAME_FIELD_RE = re.compile(
    r"фамилия|отчество|фио|наименованиеполное|полноенаименование|представление", re.IGNORECASE
)
ИМЯ_ПОЛЕ_RE = re.compile(r"имя", re.IGNORECASE)
# Служебные поля платформы 1С, содержащие подстроку «имя», но не являющиеся ФИО: техническое имя
# пользователя/файла/макета/предопределённых данных, имя колонки/реквизита/таблицы в описаниях
# метаданных (универсальные отчёты, правила обмена и т. п.). Список закрытый и точечный —
# расширять только под конкретный подтверждённый случай, не вширь.
СЛУЖЕБНЫЕ_ПОЛЯ_ИМЯ = re.compile(
    r"имяпользователя|имяфайла|имямакета|имяпредопределенныхданных|имяколонки|имяреквизита"
    r"|имятаблицы",
    re.IGNORECASE,
)


def _фио_или_наименование(field: str) -> bool:
    """Слой 1 SPEC §6.5: «фамилия»/«отчество»/«фио»/наименование — вхождением без исключений;
    «имя» — вхождением, но не для служебных полей платформы (СЛУЖЕБНЫЕ_ПОЛЯ_ИМЯ)."""
    if NAME_FIELD_RE.search(field):
        return True
    return bool(ИМЯ_ПОЛЕ_RE.search(field) and not СЛУЖЕБНЫЕ_ПОЛЯ_ИМЯ.search(field))


# SPEC §6.4: реквизиты по имени поля. Порядок важен: doc проверяется раньше общего «номер».
ПРАВИЛА_РЕКВИЗИТОВ: tuple[tuple[str, re.Pattern], ...] = (
    # `адресэл(ектронной)?почт` — Ruling 33, проверка почты «тем же способом»: поле
    # `АдресЭлектроннойПочты` (родительный падеж, не «электронная почта») не ловилось правилом
    # почты и доставалось правилу адреса (`^адрес`) — класс `addr`, а у документов и справочников
    # вне `mask_for` это `keep`, то есть открытый адрес почты. Сверка по полному `$metadata` УТ:
    # новое правило добавляет ровно `АдресЭлектроннойПочты` (5 сущностей) и `АдресЭлПочты` (1) —
    # общая форма «электроннойпочты» зацепила бы ещё `ОбменКаталогПрограммыЭлектроннойПочты`
    # (путь к каталогу, не адрес). Класс по имени поля ложится в раздел `auto` — до базы владельца
    # правка доходит после реиндекса.
    (
        "email",
        re.compile(
            r"^email$|эл(ектронная)?почта|адресэп|адресэл(ектронной)?почт|^email", re.IGNORECASE
        ),
    ),
    ("phone", re.compile(r"телефон|^phone$|номертелефона|мобильный", re.IGNORECASE)),
    ("snils", re.compile(r"снилс|^snils$", re.IGNORECASE)),
    ("iban", re.compile(r"^iban$", re.IGNORECASE)),
    ("card", re.compile(r"номеркарты|^card$", re.IGNORECASE)),
    ("corr", re.compile(r"коррсчет|корреспондентскийсчет", re.IGNORECASE)),
    ("bic", re.compile(r"^бик$|^bic$", re.IGNORECASE)),
    (
        # SPEC §6.4, сноска ⁴ (проба P4, docs/probes/P4-real-metadata.md): `номерсчета` без
        # исключения ловил номера счетов-фактур (`НомерСчетаФактуры`, `…НаАванс`,
        # `…Комиссионера`) — номера документов, не защищаемые по инварианту 6.
        "acc",
        re.compile(
            r"номерсчета(?!фактур)|расчетныйсчет|счет(получателя|плательщика)|лицевойсчет"
            r"|^account$",
            re.IGNORECASE,
        ),
    ),
    ("ogrn", re.compile(r"огрн(ип)?|^ogrn$", re.IGNORECASE)),
    ("kpp", re.compile(r"кпп|^kpp$", re.IGNORECASE)),
    ("inn", re.compile(r"^инн$|инн(организации|контрагента|физлица)?|^inn$", re.IGNORECASE)),
    ("dob", re.compile(r"датарождения|birth|^dob$", re.IGNORECASE)),
    (
        # Правка координатора (2026-09-09): убрана общая форма «номер документа» — она ловила
        # любой НомерДокумента, а SPEC §6.4 в этом же разделе прямо исключает номера документов
        # из защиты («не защищаем и не сканируем... номера документов»), инвариант проекта 6
        # того же требует. Остаются только паспортные формы.
        "doc",
        # `датавыдачи` убрано (C2 финального ревью 2026-09-10): дата выдачи — дата, а даты не
        # защищаются (инвариант 6); на реальной УТ поле и так `Edm.DateTime`, но по имени класс
        # ставиться не должен.
        re.compile(
            r"^серия$|номерпаспорта|документсерия|документномер|кемвыдан|кодподразделения",
            re.IGNORECASE,
        ),
    ),
    (
        "addr",
        re.compile(
            r"^адрес|адрес(регистрации|проживания|фактический|юридический)?$"
            r"|^address$",
            re.IGNORECASE,
        ),
    ),
)

# SPEC §6.5, слой 2: имена в строковых реквизитах любой сущности.
ЛИЦО_ТОЧНО = re.compile(
    r"^(имя|фамилия|отчество|фио|кассир|подписант|представитель|исполнитель|менеджер|автор)$",
    re.IGNORECASE,
)
ЛИЦО_ЧАСТЬ = re.compile(
    r"фио|ответственн(ое|ый)лицо|руководител|бухгалтер|контактноелицо|физлицо|сотрудник",
    re.IGNORECASE,
)
# Поля-перечисления, чьё имя содержит признак лица, но значение — член перечисления, а не ФИО
# (находка П1 приёмки через настоящие инструменты, 2026-09-12). `ЮрФизЛицо` — тип контрагента,
# организации или партнёра, два значения («ЮрЛицо»/«ФизЛицо»): `ЛИЦО_ЧАСТЬ` ловил подстроку
# «физлицо», и модель получала `[[person:1]]`/`[[person:2]]` — теряла единственный признак, по
# которому организация отличается от ИП. Ложное срабатывание — дефект по духу инварианта 6.
#
# Список закрытый, как `СЛУЖЕБНЫЕ_ПОЛЯ_ИМЯ`: расширять под подтверждённый случай, не вширь. Сверка
# по полному `$metadata` УТ (7224 сущности, 1006 перечислений): среди строковых полей, названных
# как перечисление, класс по имени получало ровно это поле, у трёх справочников.
#
# Почему не индекс, хотя таблица `enums` в нём есть. 1С отдаёт поле-перечисление как `Edm.String`
# и в `$metadata` не связывает его с `EnumType` (проверено по `ut-real.edmx`: `ЮрФизЛицо`
# объявлено `Edm.String`), поэтому индекс может только угадать по совпадению имени поля с именем
# перечисления — то же сравнение имён, только менее явное. Второе и решающее: классификатор нужен
# не только реиндексу, но и маскировщику как запасной путь без индекса
# (`masking._базовый_класс_поля_политики`), — исключение, выведенное из индекса, до него не
# дошло бы, и поле, выпавшее из раздела `auto`, запасной путь снова пометил бы как ФИО.
ПЕРЕЧИСЛЕНИЯ_ТИПА_ЛИЦА = re.compile(r"юрфизлицо", re.IGNORECASE)
# Поля, чьё имя содержит признак лица, но значение — ссылка на график, договор, должность или
# решение, а не имя человека (проект M3b §3.4). Список закрытый и по ПОЛНЫМ именам, как
# `ПЕРЕЧИСЛЕНИЯ_ТИПА_ЛИЦА`: подстрока «руководител» законно метит ФИО в
# `ФИОРуководителяКонтрагента`, и ослаблять саму эвристику нельзя. Сравнение без учёта
# регистра — имя поля приходит из `$metadata` как есть, и регистр в нём не гарантирован.
НЕ_ЛИЦО_ПОЛНЫМ_ИМЕНЕМ = frozenset(
    имя.casefold()
    for имя in (
        "ГрафикРаботыСотрудников",
        "ДоговорЗаймаСотруднику",
        "ДолжностьРуководителя",
        "РешениеРуководителя",
    )
)
ОРГ_ТОЧНО = re.compile(
    r"^(организация|контрагент|партнер|клиент|заказчик|подрядчик|субподрядчик|комитент"
    r"|комиссионер|принципал|дебитор|кредитор|плательщик|получатель|поставщик|покупатель"
    r"|грузополучатель|грузоотправитель)$",
    re.IGNORECASE,
)
# Правка координатора (2026-09-09, второй раунд): список дополнен терминами, однозначно
# означающими юридическое лицо или предпринимателя в конфигурациях 1С — «Партнёр» (SPEC §6.5,
# слой 1: Catalog_Партнеры прямо в names_for, но слой 2 его не ловил), «Клиент», «Заказчик»,
# «Подрядчик», «Субподрядчик», «Комитент», «Комиссионер», «Принципал», «Дебитор», «Кредитор» —
# в торговых конфигурациях поля документов чаще названы партнёром, чем контрагентом, и
# наименование раскрытого объекта под этим полем уходило открытым текстом (найдено ревью задачи 6
# плана M1c). Сознательно не добавлены «агент» и «представитель» — слишком общие, встречаются в
# служебных полях платформы; «лицо» — тем более, пересеклось бы с классом person.
# Правка координатора (2026-09-09, первый раунд): убраны общие «наименованиеполное»/
# «полноенаименование» — в чужой сущности (вне names_for) это поле встречается у номенклатуры,
# складов, договоров и защищало бы их поголовно как названия организаций. Внутри names_for полное
# наименование по-прежнему защищается слоем 1 через NAME_FIELD_RE — там оно однозначно.
ОРГ_ЧАСТЬ = re.compile(
    r"наименованиеорганизации|наименованиеконтрагента|наименованиебанка",
    re.IGNORECASE,
)


def is_naming_field(field: str) -> bool:
    """Поле само по себе — наименование или ФИО, без привязки к сущности (тот же признак, что
    даёт слою 1 право сработать в `classify_field`, вынесен отдельно): `Description` — общее
    техническое имя представления любого объекта платформы, остальное — по
    `_фио_или_наименование`. Используется в `gate/masking.py`, чтобы поле раскрытого вложенного
    объекта (contragent/физлицо внутри документа) наследовало класс родительского поля-контейнера
    (SPEC §6.5, поправка 2026-09-09)."""
    return field == "Description" or _фио_или_наименование(field)


def classify_field(
    entity: str, field: str, edm_type: str, *, names_for: set[str] | None = None
) -> tuple[str, str] | None:
    if edm_type not in СТРОКОВЫЕ_ТИПЫ:
        return None
    if field in ("Ref_Key", "Code", "Number", "DataVersion") or field.endswith("_Type"):
        return None

    # Счёт учёта в плане счетов — не банковский счёт (SPEC §6.4, оговорка про chartofaccounts).
    if entity.startswith("ChartOfAccounts") and re.fullmatch(r"account|счет", field, re.IGNORECASE):
        return None

    for класс, шаблон in ПРАВИЛА_РЕКВИЗИТОВ:
        if шаблон.search(field):
            return (класс, "auto")

    список = names_for if names_for is not None else set(DEFAULT_NAMES_FOR)
    if entity in список and is_naming_field(field):
        класс = "person" if entity in СУЩНОСТИ_ФИЗЛИЦ else "org"
        return (класс, "auto")

    имя_класса = _имя_в_чужой_сущности(entity, field)
    return (имя_класса, "auto") if имя_класса else None


def _имя_в_чужой_сущности(entity: str, field: str) -> str | None:
    """Слой 2 SPEC §6.5: строковый реквизит, несущий имя открытым текстом."""
    if entity == "Catalog_Банки" and ОРГ_ЧАСТЬ.search(field):
        return None  # названия банков не защищаются (SPEC §6.4)
    if ПЕРЕЧИСЛЕНИЯ_ТИПА_ЛИЦА.fullmatch(field):
        return None  # член перечисления, а не ФИО (находка П1)
    if field.casefold() in НЕ_ЛИЦО_ПОЛНЫМ_ИМЕНЕМ:
        return None  # ссылка на график, договор, должность, решение — не имя (проект M3b §3.4)
    if ЛИЦО_ТОЧНО.fullmatch(field) or ЛИЦО_ЧАСТЬ.search(field):
        return "person"
    if ОРГ_ТОЧНО.fullmatch(field) or ОРГ_ЧАСТЬ.search(field):
        return "org"
    return None
