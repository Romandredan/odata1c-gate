"""Значения, раскрытые гейтом в пределах ОДНОГО вызова тула (задача N1 M1d, инвариант 1).

Зачем. Раскрытие токена бывает законным: токен класса `addr` в поле класса `addr` — ровно то,
что разрешает Ruling 20, и реальное значение при этом уходит в 1С, так и задумано. Обратно оно
может вернуться чем угодно: 1С повторяет выражение отбора в тексте ошибки, значение приходит
данными соседнего поля, попадает в подсказку. Собрать его обратно страж умеет только у классов
с детектором (`detectors.SCAN_ORDER`), у цифровых серий словаря и у названий (`org`/`person`) —
у `addr`, `dob` и свободнотекстового `doc` последнего рубежа нет вовсе. Набор закрывает дыру
принципиально, не перечислением классов: страж обязан видеть ВСЁ, что гейт раскрыл в этом
вызове, каким бы ни был класс.

Почему отдельный объект, а не поле гейта. `BaseGate` кэшируется на базу и делится между
сессиями (`ToolService._gate_for`), поэтому «что раскрыли» на нём хранить нельзя: получилось бы
пересечение сессий — утечка данных одной сессии в другую, лекарство хуже болезни. Набор
создаётся на вызов (`ToolService._run`), протаскивается через вызов и умирает вместе с ним.

Что хранится. Свёрнутое написание значения → токен, которым его заменят обратно. Свёртка —
та же, что у слоя названий (`dictionary.normalize_text_with_map`: регистр, кавычки, «ё», любые
пробелы, невидимые символы форматирования), поэтому значение узнаётся и в другом написании,
чем ушло в 1С. Ищется оно потом точным вхождением свёрнутой формы, а не эвристикой — суммы,
даты, GUID, коды и номера документов не задеваются (инвариант 6).
"""

from __future__ import annotations

from odata1c.gate.dictionary import normalize_text_with_map
from odata1c.gate.tokens import ЗАГЛУШКА_ТОКЕНА


class RevealedValues:
    """Раскрытое в одном вызове: `add` при каждом раскрытии, `tokens` — стражу перед выдачей."""

    __slots__ = ("_по_написанию",)

    def __init__(self) -> None:
        self._по_написанию: dict[str, str] = {}

    def add(self, value: str, *, token: str) -> None:
        """Запомнить, что вместо `token` в 1С ушло `value`.

        Не запоминается: не строка (раскрытие отдаёт строку, но вход обратной подмены общий на
        любые значения тела записи); строка, в которой после свёртки не остаётся ничего, кроме
        пустоты, — пустой или однопробельный ключ совпал бы с любым пробелом ответа, то есть
        превратил бы поиск в замену всего подряд; строка с заглушкой токенов внутри (страж ищет
        по копии, где токены и GUID закрыты `ЗАГЛУШКА_ТОКЕНА`, — такой ключ совпал бы с любой
        заглушкой и испортил бы чужой токен; та же оговорка, что у `dictionary.name_variants_of`).

        Нижней границы длины нет сознательно: короткий хвост значения модель видит так же, как
        длинный, и отказ инварианта делается в сторону защиты. Одно и то же написание,
        раскрытое дважды под разными токенами, остаётся за первым: спрятать значение обязаны
        оба, а чередование токенов сделало бы ответ невоспроизводимым.
        """
        if not isinstance(value, str):
            return
        ключ = normalize_text_with_map(value)[0].strip()
        if not ключ or ЗАГЛУШКА_ТОКЕНА in ключ:
            return
        self._по_написанию.setdefault(ключ, token)

    def tokens(self) -> dict[str, str]:
        """Свёрнутое написание → токен. Копия: страж собирает по ней автомат на время вызова."""
        return dict(self._по_написанию)

    def __bool__(self) -> bool:
        return bool(self._по_написанию)

    def __len__(self) -> int:
        return len(self._по_написанию)
