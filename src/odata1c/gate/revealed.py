"""Значения, раскрытые гейтом в пределах ОДНОГО вызова тула (задача N1 M1d, инвариант 1).

Зачем. Раскрытие токена бывает законным: токен класса `addr` в поле класса `addr` — ровно то,
что разрешает Ruling 20, и реальное значение при этом уходит в 1С, так и задумано. Обратно оно
может вернуться чем угодно: 1С повторяет выражение отбора в тексте ошибки, значение приходит
данными соседнего поля, попадает в подсказку. Собрать его обратно страж умеет только у классов
с детектором (`detectors.SCAN_ORDER`), у цифровых серий словаря и у названий (`org`/`person`) —
у `addr`, `dob` и свободнотекстового `doc` последнего рубежа нет вовсе. Набор закрывает дыру
принципиально, не перечислением классов: страж обязан видеть ВСЁ, что гейт раскрыл в этом
вызове, каким бы ни был класс.

Почему отдельный объект, а не поле гейта. `BaseGate` кэшируется на базу и делится между
сессиями (`ToolService._gate_for`), поэтому «что раскрыли» на нём хранить нельзя: получилось бы
пересечение сессий — утечка данных одной сессии в другую, лекарство хуже болезни. Набор
создаётся на вызов (`ToolService._run`), протаскивается через вызов и умирает вместе с ним.

Что хранится. Свёрнутое написание значения → токен, которым его заменят обратно. Свёртка —
та же, что у слоя названий (`dictionary.normalize_text_with_map`: регистр, кавычки, «ё», любые
пробелы, невидимые символы форматирования), поэтому значение узнаётся и в другом написании,
чем ушло в 1С. Ищется оно потом точным вхождением свёрнутой формы, а не эвристикой — суммы,
даты, GUID, коды и номера документов не задеваются (инвариант 6).
"""

from __future__ import annotations

import json
import json.decoder
import json.scanner
import urllib.parse

from odata1c.gate.dictionary import normalize_text_with_map, searchable
from odata1c.gate.tokens import TOKEN_RE, ЗАГЛУШКА_ТОКЕНА

# Формы, В КОТОРЫХ ЗНАЧЕНИЕ ОТПРАВЛЯЕТ САМ ШЛЮЗ (N1-A ревью 2026-09-11) — не догадки о том, как
# его перепишет платформа (за нормализациями не гоняемся, Ruling 21), а ровно те записи, которые
# шлюз создаёт своими руками и которые поэтому обязан узнавать обратно:
#   - удвоенный апостроф — экранирование литерала `$filter` (`unmasking._экранировать`);
#   - процентная запись — кодирование значения в строке запроса (`client1c._собрать_запрос`,
#     `safe=""`) и в пути (`client1c._экранировать_путь`). Веб-сервер перед 1С (IIS, Apache,
#     nginx) повторяет адрес запроса в теле своей страницы ошибки — обычное поведение, не
#     экзотика, — и одного `unquote` хватает, чтобы прочитать значение целиком.
# Наборы `safe` должны совпадать с клиентскими; расхождение ловит тест исполнением, а не сверкой
# констант (`test_формы_возврата_покрывают_кодирование_клиента`).
_БЕЗОПАСНЫЕ_В_ЗАПРОСЕ = ""
_БЕЗОПАСНЫЕ_В_ПУТИ = "/():,='$"

# Обрамление литерала, которое шлюз ставит СВОИМИ руками: одинарная кавычка литерала `$filter`
# (`unmasking._экранировать`) и её удвоенная форма, встречающаяся во вложенном экранировании.
_РАМКИ = ("'", "''")


def _обрамления(value: str) -> list[str]:
    """Значение вместе с обрамлением, в котором его отправил САМ шлюз, — и голым, и процентно
    закодированным. Набор закрытый и известный по той же причине, что и формы в `add`: это
    записи шлюза, а не догадки о том, как значение перепишет платформа (Ruling 21)."""
    формы: list[str] = []
    for сердцевина in dict.fromkeys((value, value.replace("'", "''"))):
        for рамка in _РАМКИ:
            обрамлённая = f"{рамка}{сердцевина}{рамка}"
            формы.append(обрамлённая)
            формы.append(urllib.parse.quote(обрамлённая, safe=_БЕЗОПАСНЫЕ_В_ЗАПРОСЕ))
            формы.append(urllib.parse.quote(обрамлённая, safe=_БЕЗОПАСНЫЕ_В_ПУТИ))
    return формы


def _класс(token: str) -> str:
    """Класс значения по токену: он в самом токене (`[[kpp:…]]`), отдельным аргументом его
    тащить незачем. Испорченный токен — пустой класс, и тогда работает общий минимум."""
    совпадение = TOKEN_RE.fullmatch(token)
    return совпадение.group("type") if совпадение else ""


class ScrubbedText(str):
    """Строка ответа 1С, в которой ранний проход (`Guard.scrub_revealed_json`, Ruling 25) заменил
    раскрытое значение, — вместе с тем, что стояло на ЭТОМ месте до замены (Ruling 32, последний
    раунд M1d).

    Зачем. Поле с классом маскировщик закрывает целиком токеном своего содержимого, а ранний проход
    к этому моменту уже поставил на место раскрытого значения токен: `ИНН` приходит строкой
    `[[inn:…]]`, `НаименованиеПолное` — строкой с токеном внутри. Выдать токен тому, что видно
    (цифрам хвоста чужого токена, строке с токеном внутри), значит дать записи с отбором другой
    токен, чем без него (находка П2, инвариант 5). Токен обязан строиться по настоящему содержимому
    поля.

    Почему по месту, а не по токену. Первая правка П2 копила куски под токеном во всём ответе и
    подставляла первый (находка C-1 ревью 6). Ранний проход сворачивает шире, чем нормализация
    токена (невидимые символы, обрамление короткого значения апострофами), поэтому под одним
    токеном оказывались разные написания, и кусок из ЧУЖОГО поля давал этому полю чужой токен.
    Карта «строка после замены → строка до» от этого почти спасает, но не совсем: два поля,
    одинаковые после замены и разные до неё (дубли контрагента, один скопирован из PDF с мягким
    переносом), по содержимому не различить. Очередь по порядку обхода различает, но маскировщик
    часть литералов не обходит (служебные поля, изъятые скрытые объекты), и порядок расходится.
    Позиция литерала в тексте ответа однозначна всегда: разбор JSON (`load_scrubbed`) помечает
    строку по её смещению, и значение приезжает к маскировщику вместе со своим исходным.

    Где лежит исходное (Б-3, находка M-6 ревью 7). Исходное значение — реальное, и в открытом
    атрибуте строки ему не место: строку может положить в выдачу мимо маскировщика любой будущий
    тул (ответ на запись — первый кандидат), любая отладочная печать `vars()`. Поэтому у строки —
    только непрозрачная метка (`object()`, в ней ничего нет), а само значение хранит набор
    раскрытого ВЫЗОВА (`RevealedValues.scrubbed` / `original_of`) и умирает вместе с ним. Метка
    сверяется по тождеству: строка чужого вызова в этом наборе исходного не найдёт. Прочитать его
    может только тот, у кого в руках набор этого вызова, — маскировщик в ветке поля с классом (и
    разрешение токена для записи, когда разворачивает текущее состояние объекта). Что строка до
    выдачи обязана пройти маскировщик, проверяет `BaseGate.finish` (сторож Б-3).

    `hits` — сколько замен раннего прохода в этой строке засчитано стражу (`note`): маскировщик
    снимает их со счётчика, если поле закрыл бы и сам (`absorb`). Это число, не данные."""

    _метка: object
    hits: int


# Смещение открывающей кавычки строкового литерала в тексте ПОСЛЕ раннего прохода → (что стояло в
# литерале до замены, сколько замен засчитано стражу, места вставленных токенов в значении
# литерала после замены). Заполняет `Guard.scrub_revealed_json`.
Вставки = tuple[tuple[int, int], ...]
МестаЗамен = dict[int, tuple[str, int, Вставки]]


class _РазборПоМестам(json.JSONDecoder):
    """Разбор JSON, который помечает строки по месту в тексте (Ruling 32).

    Разбор на чистом Python (`json.scanner.py_make_scanner`): в нём строковое ЗНАЧЕНИЕ читается
    через `parse_string` контекста, и `scanstring(s, end)` знает смещение литерала. Ускоренный
    разбор на C этого крючка не даёт. Ключи объектов читаются мимо крючка — их маскировщик не
    токенизирует по классу, и исходное им не нужно."""

    def __init__(self, места: МестаЗамен, набор: RevealedValues) -> None:
        super().__init__()

        def разобрать_строку(текст: str, конец: int, strict: bool = True):
            значение, после = json.decoder.scanstring(текст, конец, strict)
            место = места.get(конец - 1)
            if место is None:
                return значение, после
            исходное, засчитано, вставки = место
            строка = набор.scrubbed(значение, original=исходное, hits=засчитано, inserted=вставки)
            return строка, после

        self.parse_string = разобрать_строку
        self.scan_once = json.scanner.py_make_scanner(self)


def load_scrubbed(text: str, places: МестаЗамен, revealed: RevealedValues):
    """Разобрать тело ответа после раннего прохода: строки, которые он переписал, приходят
    `ScrubbedText`, а их исходные значения ложатся в набор раскрытого вызова (Б-3). Ранний проход
    ничего не заменил (обычный ответ, вызов без раскрытия) — обычный быстрый `json.loads`:
    медленный разбор нужен только ответу, в котором есть что возвращать на место."""
    if not places:
        return json.loads(text)
    return _РазборПоМестам(places, revealed).decode(text)


class RevealedValues:
    """Раскрытое в одном вызове: `add` при каждом раскрытии, `tokens` — стражу перед выдачей.

    Вдобавок — исходные значения строк, которые переписал ранний проход (`scrubbed`,
    `original_of`; Б-3): набор живёт ровно один вызов, и реальное значение места живёт вместе с
    ним, а не в атрибуте строки, которую можно унести куда угодно."""

    __slots__ = ("_по_написанию", "_по_границам", "_замен", "_исходные")

    def __init__(self) -> None:
        self._по_написанию: dict[str, str] = {}
        self._по_границам: set[str] = set()
        self._замен = 0
        self._исходные: dict[object, tuple[str, Вставки]] = {}

    def scrubbed(
        self, text: str, *, original: str, hits: int, inserted: Вставки = ()
    ) -> ScrubbedText:
        """Строка, переписанная ранним проходом: у неё — метка места и число засчитанных стражу
        замен, исходное значение и места вставленных токенов остаются здесь (см. `ScrubbedText`,
        `inserted_of`)."""
        строка = ScrubbedText(text)
        метка = object()
        строка._метка = метка
        строка.hits = hits
        self._исходные[метка] = (original, tuple(inserted))
        return строка

    def original_of(self, text: ScrubbedText) -> str | None:
        """Что стояло на месте этой строки до раннего прохода. `None` — строка переписана не в
        этом вызове (или вовсе не ранним проходом): чужое исходное подставлять нельзя."""
        запись = self._запись(text)
        return None if запись is None else запись[0]

    def inserted_of(self, text: ScrubbedText) -> Вставки:
        """Где в строке стоят токены, которые поставил ранний проход (Б-2): `(начало, конец)` в
        координатах самой строки. Токен вне этих мест пришёл из 1С как текст — маскировщик выдаёт
        его токеном `lit`. Строка чужого вызова — мест нет: все токены в ней считаются текстом,
        отказ в сторону «не выдать строку из 1С за токен шлюза»."""
        запись = self._запись(text)
        return () if запись is None else запись[1]

    def _запись(self, text) -> tuple[str, Вставки] | None:
        метка = getattr(text, "_метка", None)
        return None if метка is None else self._исходные.get(метка)

    def add(self, value: str, *, token: str) -> None:
        """Запомнить, что вместо `token` в 1С ушло `value`.

        Вместе с самим значением запоминаются формы, в которых его отправляет сам шлюз
        (см. `_БЕЗОПАСНЫЕ_В_ЗАПРОСЕ` выше): экранированная для `$filter` и процентные — для
        строки запроса и для пути.

        Не запоминается: не строка (раскрытие отдаёт строку, но вход обратной подмены общий на
        любые значения тела записи); строка, в которой после свёртки не остаётся ничего, кроме
        пустоты, — пустой или однопробельный ключ совпал бы с любым пробелом ответа, то есть
        превратил бы поиск в замену всего подряд; строка с заглушкой токенов внутри (страж ищет
        по копии, где токены и GUID закрыты `ЗАГЛУШКА_ТОКЕНА`, — такой ключ совпал бы с любой
        заглушкой и испортил бы чужой токен; та же оговорка, что у `dictionary.name_variants_of`).

        Значение короче формы своего класса (Ruling 26 и Ruling 27) искать голым нельзя: цифра
        «1» из поля `КПП` рвёт номера документов, даты и коды, а защищает ноль. Но и перестать
        искать его, как в словаре, тоже нельзя: здесь на другой чаше инвариант 1 — это значение
        модель в ЭТОМ вызове сама попросила использовать, и эхо она прочитает как ответ на свой
        вопрос. Поэтому Ruling 26 переносится сюда духом, а не буквой: игла не выбрасывается, а
        удлиняется обрамлением, которое шлюз поставил своими руками (`'1'`, `''1''`, `%271%27`),
        а голая форма ищется только по границам (см. `bounded`). Голая форма нужна потому, что
        обрамления у эха может не быть вовсе: проба P7 — 1С повторяет число без кавычек.

        Одно и то же написание, раскрытое дважды под разными токенами, остаётся за первым:
        спрятать значение обязаны оба, а чередование токенов сделало бы ответ невоспроизводимым.
        """
        if not isinstance(value, str):
            return
        # Пустота проверяется по САМОМУ значению, а не по каждой форме отдельно: у пробела
        # процентная запись — «%20», ключ непустой, и требование «пустое не ищем» обошлось бы
        # само собой через побочную форму.
        ключ = self._ключ(value)
        if not ключ:
            return
        короткое = not searchable(_класс(token), ключ)
        for форма in (
            value,
            value.replace("'", "''"),
            urllib.parse.quote(value, safe=_БЕЗОПАСНЫЕ_В_ЗАПРОСЕ),
            urllib.parse.quote(value, safe=_БЕЗОПАСНЫЕ_В_ПУТИ),
        ):
            self._запомнить(форма, token, по_границам=короткое)
        if короткое:
            for обрамлённая in _обрамления(value):
                self._запомнить(обрамлённая, token)

    @staticmethod
    def _ключ(форма: str) -> str:
        ключ = normalize_text_with_map(форма)[0].strip()
        return "" if ЗАГЛУШКА_ТОКЕНА in ключ else ключ

    def _запомнить(self, форма: str, token: str, *, по_границам: bool = False) -> None:
        ключ = self._ключ(форма)
        if not ключ:
            return
        if ключ not in self._по_написанию:
            self._по_написанию[ключ] = token
            if по_границам:
                self._по_границам.add(ключ)
        elif not по_границам:
            # Это же написание уже кто-то положил как требующее границ, а теперь оно пришло
            # безусловным (например, длинное значение совпало с обрамлением короткого): условие
            # снимается. Отказ инварианта — в сторону защиты.
            self._по_границам.discard(ключ)

    def carry(self) -> RevealedValues:
        """Новый набор с написаниями этого — для вызова, который отправит в 1С значения,
        раскрытые здесь (задача 7 плана M2: подготовка записи раскрывает токены тела и ключа, а
        запрос к 1С уходит на `commit`, другим вызовом тула со своим набором).

        Без переноса ранний проход `commit` не знал бы, что в теле запроса стоят раскрытые
        значения: эхо «Не удалось разобрать строку '<значение>'…» (P7, P8) и ответ записи
        приходили бы мимо него, а у адреса, даты рождения, свободного `doc` детектора нет — страж
        их не узнаёт. Переносятся только написания и признак границ (`_запомнить`): исходные
        значения строк раннего прохода (`scrubbed`) принадлежат вызову, где их разобрали, их
        метки в другом вызове не встретятся, а держать реальные значения дольше незачем.
        Счётчик замен тоже не переносится: он о выдаче ТОГО вызова."""
        перенос = RevealedValues()
        перенос._по_написанию = dict(self._по_написанию)
        перенос._по_границам = set(self._по_границам)
        return перенос

    def adopt(self, other: RevealedValues) -> None:
        """Принять написания набора `other` (см. `carry`) по правилам `_запомнить`: написание,
        уже известное этому набору, остаётся за своим токеном; условие границ снимается, если
        одна из сторон требует искать написание безусловно (отказ — в сторону защиты)."""
        for ключ, токен in other._по_написанию.items():
            по_границам = ключ in other._по_границам
            if ключ not in self._по_написанию:
                self._по_написанию[ключ] = токен
                if по_границам:
                    self._по_границам.add(ключ)
            elif not по_границам:
                self._по_границам.discard(ключ)

    def bounded(self) -> frozenset[str]:
        """Написания, которые страж заменяет только при границах с обеих сторон (Ruling 27).

        Граница — начало строки, конец строки или неалфавитно-цифровой символ, причём
        процентная запись `%XX` рядом тоже считается границей: в эхе адреса запроса
        (`…%20eq%20%271%27`) значение окружено шестнадцатеричными цифрами кодировки кавычки, и
        без этой оговорки та самая форма N1-A, ради которой слой раскрытого и переносили на сырой
        текст, осталась бы непокрытой."""
        return frozenset(self._по_границам)

    def note(self, count: int) -> None:
        """Отметить замены, сделанные проходом по сырому ответу (`Guard.scrub_revealed`).

        Проход идёт до сборки конверта, и его замены иначе потерялись бы для `warnings`: к
        моменту `finish` заменять уже нечего. Получателю ответа безразлично, на каком шаге
        конвейера сработал страж, — `guard_replaced` обязан стоять в обоих случаях."""
        self._замен += count

    def absorb(self, count: int) -> None:
        """Снять с `replacements` замены раннего прохода, которые пришлись на поле с классом
        (находка П2): такое поле маскировщик закрыл бы и сам, и `guard_replaced` («маскировщик
        пропустил, страж поймал») на каждом отборе по токену был бы ложной тревогой. Сколько
        снимать, маскировщик знает из самой строки (`ScrubbedText.hits`). Замены в полях без
        класса и в тексте ошибок остаются — там ранний проход и есть единственная защита
        (Ruling 25). Ниже нуля счётчик не опускается: отказ здесь — в сторону «предупредить», а
        не «соврать отрицательным числом»."""
        self._замен = max(0, self._замен - count)

    @property
    def replacements(self) -> int:
        """Сколько раз значения из набора уже заменены обратно на токены в этом вызове."""
        return self._замен

    def tokens(self) -> dict[str, str]:
        """Свёрнутое написание → токен. Копия: страж собирает по ней автомат на время вызова."""
        return dict(self._по_написанию)

    def __bool__(self) -> bool:
        return bool(self._по_написанию)

    def __len__(self) -> int:
        return len(self._по_написанию)
