# GUID и даты не трогаем ни при каких условиях (инвариант 6).
#
# Коды классификаторов под подписью — тоже (инвариант 6). Подпись бывает не только текстом
# («ОКТМО 45379000»), но и ключом структуры, в которой 1С хранит адрес (Ruling 33, рубеж 2): JSON
# поля `Значение` (`"oktmo": "73701000001"`, `"okato"`, `"oktmoBudget"`, `"codeKLADR"`,
# `"ifnsFLCode"`), XML `ЗначенияПолей` (`<ОКТМО>73701000001</ОКТМО>`) и старая запись
# «Ключ=Значение». Одиннадцатизначный ОКТМО/ОКАТО региона 73, 78, 79 неотличим по форме от номера
# «7 + код + абонент», и без подписи расширенный шаблон телефона принял бы его за номер — адрес
# юрлица, открытый политикой, сканируется детекторами целиком. Отсюда латинские ключи БСП и
# разделители `"`, `=`, `>` между подписью и кодом. Та же подпись закрыла и старую ошибку: ОКТМО и
# ОКАТО региона 84 имеют форму «8 + 10 цифр», и прежний шаблон телефона токенизировал их в адресах
# складов и контрагентов (живая база, 10 случаев в выборке из 763 тысяч строк).
ИСКЛЮЧЕНИЯ = re.compile(
    r"\b[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\b"
    r"|\b\d{4}-\d{2}-\d{2}(?:T[\d:.]+)?\b"
    r"|\b\d{2}\.\d{2}\.\d{4}\b"
    r"|(?:ОКПО|ОКВЭД|ОКТМО|ОКАТО|ОКОПФ|SWIFT|(?i:oktmo|okato|okpo|kladr|ifns)\w*)"
    r"[\"'\s:№=>]*[\w.]+",
)


@dataclasses.dataclass(slots=True, frozen=True)
class Match:
    start: int
    end: int
    type: str
    value: str


def inn_valid(digits: str) -> bool:
    if not digits.isdigit():
        return False
    цифры = [int(символ) for символ in digits]
    if len(digits) == 10:
        return _контроль(цифры[:9], ВЕСА_ИНН10) == цифры[9]
    if len(digits) == 12:
        return (
            _контроль(цифры[:10], ВЕСА_ИНН12_1) == цифры[10]
            and _контроль(цифры[:11], ВЕСА_ИНН12_2) == цифры[11]
        )
    return False


def ogrn_valid(digits: str) -> bool:
    if not digits.isdigit():
        return False
    if len(digits) == 13:
        return int(digits[:12]) % 11 % 10 == int(digits[12])
    if len(digits) == 15:
        return int(digits[:14]) % 13 % 10 == int(digits[14])
    return False


def snils_valid(digits: str) -> bool:
    if not digits.isdigit() or len(digits) != 11:
        return False
    сумма = sum(int(цифра) * (9 - позиция) for позиция, цифра in enumerate(digits[:9]))
    контроль = сумма if сумма < 100 else (0 if сумма in (100, 101) else сумма % 101 % 100)
    return контроль == int(digits[9:])


def luhn_valid(digits: str) -> bool:
    if not digits.isdigit() or not 13 <= len(digits) <= 19:
        return False
    сумма = 0
    for позиция, символ in enumerate(reversed(digits)):
        цифра = int(символ)
        if позиция % 2 == 1:
            цифра *= 2
            цифра = цифра - 9 if цифра > 9 else цифра
        сумма += цифра
    return сумма % 10 == 0


def iban_valid(value: str) -> bool:
    сжатое = re.sub(r"\s", "", value).upper()
    if not re.fullmatch(r"[A-Z]{2}\d{2}[A-Z0-9]{11,30}", сжатое):
        return False
    переставленное = сжатое[4:] + сжатое[:4]
    число = "".join(
        str(ord(символ) - 55) if символ.isalpha() else символ for символ in переставленное
    )
    return int(число) % 97 == 1


def account_prefix_known(digits: str) -> bool:
    """Первые разряды счёта из групп, перечисленных в SPEC §6.4."""
    if len(digits) != 20 or not digits.isdigit():
        return False
    return digits[:3] in ПРЕФИКСЫ_СЧЕТА or digits[:5] in ПРЕФИКСЫ_СЧЕТА_5


def _карта_bin_valid(digits: str) -> bool:
    """Первые разряды из диапазона реально существующей платёжной системы (SPEC §6.4)."""
    return any(
        digits[:длина].isdigit() and нижняя <= int(digits[:длина]) <= верхняя
        for длина, нижняя, верхняя in КАРТА_ДИАПАЗОНЫ
    )


def scan_value(text: str, *, context_window: int = 40) -> list[Match]:
    """Найти реквизиты в строке. Порядок SCAN_ORDER, перекрытия отбрасываются."""
    запрещённые = [
        (совпадение.start(), совпадение.end()) for совпадение in ИСКЛЮЧЕНИЯ.finditer(text)
    ]
    найденное: list[Match] = []
    занято: list[tuple[int, int]] = list(запрещённые)

    for класс in SCAN_ORDER:
        # Конец последнего ПОДТВЕРЖДЁННОГО номера — для перечня через запятую (раунд 3, I-2):
        # соседство подтверждает только от номера, подтверждённого своим признаком, иначе цепочка
        # номеров заказов подтверждала бы сама себя.
        конец_телефона: int | None = None
        for совпадение in ШАБЛОНЫ[класс].finditer(text):
            начало, конец = совпадение.start(), совпадение.end()
            if _перекрывается(начало, конец, занято):
                continue
            значение = совпадение.group()
            перечень = конец_телефона is not None and bool(
                _РАЗДЕЛИТЕЛЬ_ПЕРЕЧНЯ.fullmatch(text, конец_телефона, начало)
            )
            if not _подтверждено(
                класс, значение, text, начало, конец, context_window, перечень=перечень
            ):
                continue
            занято.append((начало, конец))
            найденное.append(Match(start=начало, end=конец, type=класс, value=значение))
            if класс == "phone":
                конец_телефона = конец

    найденное.sort(key=lambda совпадение: совпадение.start)
    return найденное


def _подтверждено(
    класс: str,
    значение: str,
    текст: str,
    начало: int,
    конец: int,
    окно: int,
    *,
    перечень: bool = False,
) -> bool:
    цифры = re.sub(r"\D", "", значение)
    if класс == "inn":
        if not inn_valid(цифры):
            return False
        # 10-значный ИНН неотличим от номера документа: требуется слово «ИНН» рядом.
        return len(цифры) == 12 or _есть_контекст("inn", текст, начало, конец, окно=20)
    if класс == "ogrn":
        return ogrn_valid(цифры)
    if класс == "snils":
        return snils_valid(цифры)
    if класс == "card":
        if not (luhn_valid(цифры) and _карта_bin_valid(цифры)):
            return False
        # 13–15 цифр — устаревший (или короче обычного) формат карты; на этой длине массовый
        # конкурент — штрихкод номенклатуры EAN-13 (~10% случайных штрихкодов проходят Luhn,
        # а типичный префикс страны 460–469 попадает в диапазон Visa «начинается на 4»).
        # Современные карты (16–19 цифр) подсказки не требуют — коллизии на этой длине на
        # порядок реже (SPEC §6.4, поправка 2026-09-09).
        if len(цифры) <= 15:
            return _есть_контекст("card", текст, начало, конец, окно)
        return True
    if класс == "iban":
        return iban_valid(значение)
    if класс == "acc":
        return account_prefix_known(цифры)
    if класс == "corr":
        return len(цифры) == 20 and цифры.startswith("301")
    if класс in ("doc", "kpp"):
        return _есть_контекст(класс, текст, начало, конец, окно)
    if класс == "phone":
        if not _телефон_подтверждён(значение, цифры, текст, конец):
            return False
        return not _слитный_номер(значение) or (
            значение[1] == "9" or перечень or _есть_контекст("phone", текст, начало, конец, окно)
        )
    return True


# Число с разбивкой разрядов (тысячи через пробел или неразрывный пробел): «12 345 678»,
# «81 234 567 890», «+12 345 678». Это сумма или количество, а не номер (инвариант 6).
_РАЗБИВКА_РАЗРЯДОВ = re.compile(r"\+?\d{1,3}(?:[ \u00a0]\d{3})+")
# Дробная часть суммы — до четырёх знаков (копейки, курс). Длиннее — не дробь, а следующее число:
# на живой базе номера телефонов перечисляют через запятую без пробела
# («89161234567,89161234568»), и отсев «любая цифра после запятой» терял оба номера.
_ДРОБНАЯ_ЧАСТЬ = re.compile(r"[.,]\d{1,4}(?!\d)")


def _телефон_подтверждён(значение: str, цифры: str, текст: str, конец: int) -> bool:
    """Отсев того, что похоже на номер только числом цифр (Ruling 33, рубеж 2; инвариант 6):

    - разбивка разрядов — сумма, записанная группами по три («81 234 567 890» — 11 цифр с
      ведущей 8, «+12 345 678» — сумма со знаком);
    - сразу за совпадением дробная часть («79161234567,00») — сумма;
    - номер со знаком «+» — от 8 до 15 цифр (E.164), короче — не номер;
    - 11 цифр с ведущей 7 без знака, сходящиеся по контрольной сумме СНИЛС, — СНИЛС: оба класса
      закрываются, но токен должен быть своего класса (СНИЛС сканируется после телефона)."""
    if _РАЗБИВКА_РАЗРЯДОВ.fullmatch(значение):
        return False
    if _ДРОБНАЯ_ЧАСТЬ.match(текст, конец):
        return False
    if значение.startswith("+"):
        return 8 <= len(цифры) <= 15
    if значение.startswith("7") and значение.isdigit():
        return not snils_valid(цифры)
    return True


# Между соседними номерами перечня — запятая или точка с запятой и пробелы (раунд 3, I-2).
_РАЗДЕЛИТЕЛЬ_ПЕРЕЧНЯ = re.compile(r"\s*[,;]\s*")


def _слитный_номер(значение: str) -> bool:
    """11 цифр подряд с ведущей 7 или 8, без «+», скобок и разделителей (раунд 3, I-2).

    В этой записи номер неотличим от штрихкода, номера заказа или кода классификатора
    («EAN 76123456789», «Заказ №81234567890», «код 73701000001» — ревью 8), поэтому телефоном
    она считается только с признаком номера (`_подтверждено`): вторая цифра 9 (мобильный код
    России), слово-подсказка рядом (`КОНТЕКСТ["phone"]`) или соседство в перечне с уже
    подтверждённым номером. Мобильный код выбран признаком, а не единственным правилом: городской
    номер в комментарии пишут со словом «тел.», а голый мобильный — самый частый вид номера в
    комментариях, и требовать для него подсказку значило бы терять его. Цена правила —
    городской или казахстанский мобильный (`7 70x`, `7 77x`) номер слитно, без подсказки и не в
    перечне, в свободном тексте больше не узнаётся; поля контактной информации это не задевает —
    там класс задаёт тип строки (Ruling 33), а не детектор."""
    return len(значение) == 11 and значение.isdigit() and значение[0] in "78"


def _есть_контекст(класс: str, текст: str, начало: int, конец: int, окно: int) -> bool:
    шаблон = КОНТЕКСТ.get(класс)
    if шаблон is None:
        return True
    слева = текст[max(0, начало - окно) : начало]
    справа = текст[конец : конец + окно]
    return bool(шаблон.search(слева) or шаблон.search(справа))


def _перекрывается(начало: int, конец: int, занято: list[tuple[int, int]]) -> bool:
    return any(
        начало < чужой_конец and чужое_начало < конец for чужое_начало, чужой_конец in занято
    )


def _контроль(цифры: list[int], веса: tuple[int, ...]) -> int:
    return sum(цифра * вес for цифра, вес in zip(цифры, веса, strict=True)) % 11 % 10
