# Разделители цифровой серии (ревью 2026-09-09, дыры 3-5): пробелы всех видов, дефис, точка,
# косая черта, скобки, обратная косая — включая двузнаковый экранированный перевод строки
# `\n`. В JSON-документе строки теперь проверяются раскодированными, и перевод строки там —
# обычный пробельный символ; двузнаковая запись остаётся нужна для не-JSON текста, в котором
# уже сериализованный фрагмент может встретиться как есть. Старое ограничение снизу («минимум
# девять знаков в серии», `{7,}`) убрано — оно было не защитой, а обходом отсутствия проверки
# по факту: реальный отбор теперь идёт по точному совпадению скользящего окна со словарём
# (`_найти_числовые_окна`), а не по длине регулярного выражения, так что регэксп-порог только
# отсеивал часть настоящих значений заодно с мусором.
_ЧИСЛОВОЙ_РАЗДЕЛИТЕЛЬ = r"(?:\\n|[\s\-./()\\])"
ЦИФРОВАЯ_СЕРИЯ = re.compile(rf"\d(?:\d|{_ЧИСЛОВОЙ_РАЗДЕЛИТЕЛЬ})*\d")
# Строковый литерал JSON с учётом экранирования. В ВАЛИДНОМ JSON вне строк кавычек нет, поэтому
# проход этим выражением с начала текста находит ровно строковые литералы — ключи и значения.
_СТРОКА_JSON = re.compile(r'"(?:[^"\\]|\\.)*"', re.DOTALL)
_МЕТКА_ПОРЯДКА_БАЙТОВ = "\ufeff"

# Пусто для слоя названий: требование границ Ruling 27 (неалфавитно-цифровой сосед с обеих сторон)
# несёт только слой раскрытого. У слоя названий своё, мягче, — граница слова (Ruling 106).
_БЕЗ_ГРАНИЦ: frozenset[str] = frozenset()

# Четвёрка «автомат Aho-Corasick + таблица свёрнутое написание → токен + написания, требующие
# границ + какие написания ищутся только целым словом» (`overlaps.все_вхождения`, `целые_слова`:
# `True` — все, у слоя названий; множество — у слоя раскрытого, Ruling 106). Слой названий держит
# её на процесс (пересобирается по словарю), слой раскрытого — на один вызов (`_собрать_автомат`).
_Автомат = tuple[AhoCorasick, dict[str, str], frozenset[str], bool | frozenset[str]]

# Вид текста для стража (см. docstring модуля).
_JSON = "json"
_СКАЛЯР_ЧИСЛО = "число"
_ТЕКСТ = "текст"


def _вид(текст: str) -> str:
    try:
        документ = json.loads(текст.removeprefix(_МЕТКА_ПОРЯДКА_БАЙТОВ))
    except (ValueError, RecursionError):
        return _ТЕКСТ
    if isinstance(документ, (dict, list, str)):
        return _JSON
    if isinstance(документ, (int, float)) and not isinstance(документ, bool):
        return _СКАЛЯР_ЧИСЛО
    return _ТЕКСТ


_СУРРОГАТНАЯ_ПОЛОВИНА = re.compile("[\ud800-\udfff]")


def _записать_литерал(значение: str) -> str:
    """Строковый литерал JSON без экранирования `\\uXXXX` — кроме одиночной суррогатной
    половины (её допускает только JSON-запись `\\ud800`): её нельзя записать в UTF-8 как есть,
    и экранируется ровно она, а не весь литерал — иначе вместе с ней в `\\u` ушла бы и
    кириллица, вопреки SPEC §6.8 (Ruling 21 M1c, хвост 1)."""
    литерал = json.dumps(значение, ensure_ascii=False)
    return _СУРРОГАТНАЯ_ПОЛОВИНА.sub(lambda половина: f"\\u{ord(половина.group()):04x}", литерал)


@dataclasses.dataclass(slots=True)
class GuardResult:
    text: str
    replacements: list[dict]
    warnings: list[str]


class Guard:
    def __init__(self, dictionary: Dictionary) -> None:
        self._dictionary = dictionary
        self._revision = -1
        self._numbers: dict[str, str] = {}
        self._числовые_длины: list[int] = []
        self._все_названия: AhoCorasick | None = None
        self._variants: dict[str, str] = {}
        self.rebuild()

    def rebuild(self) -> None:
        """Пересобрать множество чисел (и длин, встречающихся среди них) и автомат названий по
        текущему словарю."""
        self._numbers = self._dictionary.number_tokens()
        # Длины по убыванию: на каждой позиции скользящего окна сначала пробуем самое длинное
        # известное значение — то же соглашение, что и у LeftmostLongest автомата названий.
        self._числовые_длины = sorted({len(значение) for значение in self._numbers}, reverse=True)
        self._variants = self._dictionary.name_variants()
        ключи = list(self._variants)
        # Автомат названий ищет ВСЕ совпадения, в том числе пересекающиеся (Б-4,
        # `gate/overlaps.py`): `overlapping=True` умеет только `MatchKind.Standard`. Им пользуются
        # и слой названий последнего рубежа, и правило вложенности раннего прохода — одним и тем
        # же набором совпадений, как маскировщик: иначе ответ с отбором и без расходился бы на
        # пересекающихся названиях (инвариант 5).
        self._все_названия = AhoCorasick(ключи, matchkind=MatchKind.Standard) if ключи else None
        self._revision = self._dictionary.revision()

    def check(
        self, serialized: str, *, mode: str, revealed: RevealedValues | None = None
    ) -> GuardResult:
        """`revealed` — что гейт раскрыл при обработке ЭТОГО вызова (задача N1 M1d): значения,
        законно ушедшие в 1С вместо токенов. Страж ищет их в ответе наравне со своими слоями —
        независимо от класса, в том числе у классов, для которых нет ни детектора, ни цифровой
        серии, ни автомата названий (`addr`, `dob`, свободнотекстовый `doc`). Набор живёт ровно
        один вызов: ни `Guard`, ни `BaseGate` его не запоминают (см. `revealed.py`).

        Автомат по набору собирается здесь один раз на вызов, а не на каждый строковый литерал:
        в наборе единицы значений, но литералов в ответе тысячи.
        """
        if mode == "off":
            return GuardResult(text=serialized, replacements=[], warnings=[])
        if self._revision != self._dictionary.revision():
            self.rebuild()

        раскрытое = _автомат_раскрытого(revealed)
        замены: list[dict] = []

        def проверка(текст: str, копилка: list[dict]) -> str:
            return self._проверить_текст(текст, копилка, mode=mode, раскрытое=раскрытое)

        текст = self._пройти(serialized, замены, проверка)
        предупреждения = ["guard_replaced"] if замены else []
        return GuardResult(text=текст, replacements=замены, warnings=предупреждения)

    def scrub_revealed(
        self, text: str, revealed: RevealedValues, *, mode: str = "identifiers+names"
    ) -> str:
        """ТОЛЬКО слой раскрытого и только он — по сырому тексту, каким тот пришёл от 1С
        (Ruling 25, раунд правок 1).

        Первым внутри стража этому слою быть мало: до стража текст успевают переписать
        `mask_text` (заменит телефон внутри адреса), `truncate_strings` и `map_error` (обрежут
        значение посередине) — и точное вхождение, на котором держится весь слой, рушится.
        Поэтому проход делается раньше всех преобразований, на сыром теле ответа; обычный
        `check` остаётся последним рубежом и работает как работал.

        Число замен копится в самом наборе (`RevealedValues.note`), а не возвращается: набор
        доезжает до `finish`, и `guard_replaced` в ответе остаётся на месте — для получателя
        ничего не меняется от того, на каком шаге конвейера сработал страж.

        `mode` — уровень базы: от него зависит, спорят ли с раскрытым известные названия (правило
        вложенности, `_заменить_раскрытое`). Умолчание — самый строгий уровень, как у стража
        для неизвестного уровня; гейт передаёт свой уровень явно.
        """
        return self._ранний_проход(text, revealed, mode=mode, места=None)

    def scrub_revealed_json(self, text: str, revealed: RevealedValues, *, mode: str):
        """Ранний проход по сырому телу УСПЕШНОГО ответа и его разбор (Ruling 25 и Ruling 32).

        Проход тот же, что у `scrub_revealed`, — по сырому тексту до любых преобразований. Вдобавок
        он запоминает, по какому смещению в своём выходе стоит каждый переписанный литерал и что в
        нём было, а разбор (`revealed.load_scrubbed`) отдаёт такие строки `ScrubbedText`, а их
        исходные значения кладёт в набор вызова (Б-3): маскировщик токенизирует поле с классом по
        содержимому ЭТОГО места, а не по токену и не по порядку обхода."""
        места: МестаЗамен = {}
        текст = self._ранний_проход(text, revealed, mode=mode, места=места)
        return load_scrubbed(текст, места, revealed)

    def _ранний_проход(
        self, text: str, revealed: RevealedValues, *, mode: str, места: МестаЗамен | None
    ) -> str:
        раскрытое = _автомат_раскрытого(revealed)
        if раскрытое is None:
            return text
        if self._revision != self._dictionary.revision():
            self.rebuild()
        названия = self._автомат_названий(mode)
        замены: list[dict] = []

        def проверка(текст: str, копилка: list[dict]) -> str:
            return _заменить_раскрытое(текст, копилка, раскрытое, названия)

        текст = self._пройти(text, замены, проверка, места=места)
        # Замену всего накрывающего названия сделал бы и маскировщик: стражу она не засчитывается,
        # иначе отбор по токену давал бы `guard_replaced` там, где ответ без отбора молчит.
        revealed.note(_засчитано(замены))
        return текст

    def _автомат_названий(self, mode: str) -> _Автомат | None:
        """Автомат названий для правила вложенности — на любом уровне, кроме `identifiers`: там
        названия не защищаются (SPEC §6.2). Условие то же, что у слоя названий стража (неизвестный
        уровень трактуется как требующий защиты), а не маскировщика (`== identifiers+names`):
        отказ здесь обязан быть в сторону защиты."""
        if mode == "identifiers" or self._все_названия is None:
            return None
        return self._все_названия, self._variants, _БЕЗ_ГРАНИЦ, True

    def _пройти(
        self, текст: str, замены: list[dict], проверка, *, места: МестаЗамен | None = None
    ) -> str:
        """Общий обход текста для `check` и раннего прохода: JSON-документ — по строковым
        литералам, всё прочее — целиком (см. docstring модуля). `проверка` — что именно
        применяется к содержимому литерала или к тексту. `места` — куда записать смещения
        переписанных литералов (только ранний проход по успешному ответу, Ruling 32)."""
        вид = _вид(текст)
        if вид == _JSON:
            return self._проверить_литералы(текст, замены, проверка, места=места)
        проверено = проверка(текст, замены)
        if вид == _СКАЛЯР_ЧИСЛО and замены:
            # Скаляр с заменой становится строковым литералом с начала текста — и он тоже место,
            # где стояло своё значение (ответ `…/ИНН/$value` из одних цифр).
            if места is not None:
                места[0] = (текст, _засчитано(замены), _места(замены))
            return json.dumps(проверено, ensure_ascii=False)
        return проверено

    def _проверить_литералы(
        self, текст: str, замены: list[dict], проверка, *, места: МестаЗамен | None = None
    ) -> str:
        """JSON-документ: каждый строковый литерал проверяется отдельно в раскодированном виде
        (см. docstring модуля). В валидном JSON вне строк кавычек нет, поэтому `_СТРОКА_JSON`,
        пройденное с начала текста, находит ровно литералы — ключи и значения.

        `места` — смещение открывающей кавычки каждого литерала, в котором что-то заменено, в
        ВЫХОДНОМ тексте → что стояло в литерале до замены и сколько замен засчитано стражу
        (Ruling 32). Смещение считается по выходу, а не по входу: разбирается уже выход."""
        куски: list[str] = []
        позиция = 0
        длина_выхода = 0
        for литерал in _СТРОКА_JSON.finditer(текст):
            сырой = литерал.group()
            экранирован = "\\" in сырой
            значение = json.loads(сырой) if экранирован else сырой[1:-1]
            было = len(замены)
            проверено = проверка(значение, замены)
            if len(замены) == было and not (экранирован and "\\u" in сырой):
                continue
            перед = текст[позиция : литерал.start()]
            записанный = _записать_литерал(проверено)
            куски.append(перед)
            длина_выхода += len(перед)
            if места is not None and len(замены) != было:
                места[длина_выхода] = (
                    значение,
                    _засчитано(замены[было:]),
                    _места(замены[было:]),
                )
            куски.append(записанный)
            длина_выхода += len(записанный)
            позиция = литерал.end()
        куски.append(текст[позиция:])
        return "".join(куски)

    def _проверить_текст(
        self, текст: str, замены: list[dict], *, mode: str, раскрытое: _Автомат | None = None
    ) -> str:
        # Раскрытое в этом вызове — ПЕРВЫМ слоем (задача N1 M1d). Порядок обязателен: слой чисел
        # заменяет цифровое окно, известное словарю, и внутри раскрытого значения («45 03 123456»,
        # «+7 916 123-45-67») он оставил бы токен посреди строки — точное вхождение раскрытого
        # после этого не совпало бы, и остаток значения вышел бы наружу. Обратного риска нет:
        # что бы ни заменил этот слой, оно заменено на токен того же значения. С названиями спор
        # решает правило вложенности (`_заменить_раскрытое`) — то же, что в раннем проходе:
        # последний рубеж не должен оставлять обрывок чужого названия, который ранний проход не
        # оставил бы.
        if раскрытое is not None:
            текст = _заменить_раскрытое(текст, замены, раскрытое, self._автомат_названий(mode))
        текст = self._заменить_числа(текст, замены)
        # Названия проверяются на любом режиме, кроме "off" (уже отсечён выше) и явного
        # "identifiers" (SPEC §6.2: названия защищаются только на верхнем уровне) — неизвестное
        # или искажённое значение режима трактуется как требующее максимальной защиты, а не как
        # молчаливое «названия не проверять» (ревью 2026-09-09, дыра 8: отказ инварианта обязан
        # быть в сторону защиты).
        if mode != "identifiers":
            текст = self._заменить_названия(текст, замены)
        return текст

    def _заменить_числа(self, текст: str, замены: list[dict]) -> str:
        if not self._numbers:
            return текст

        # Числовые серии ищутся по копии, где токены и GUID закрыты заглушкой той же длины
        # (`blank_tokens`), а заменяются в ИСХОДНОМ тексте по абсолютным смещениям — как слой
        # названий. C1 финального ревью 2026-09-10: дефис — разделитель серии, поэтому цифры
        # соседних hex-сегментов GUID сливались в длинную серию, и короткое значение класса doc
        # (Серия — 4 цифры, КодПодразделения — 6) заменялось токеном ВНУТРИ `Ref_Key` (порча
        # идентификатора и JSON, инвариант 6). NUL (не цифра и не разделитель) рвёт серию, поэтому
        # цифры внутри заглушённого GUID в серию не попадают; оба слоя стража смотрят на одну
        # заглушённую копию.
        заглушённый = blank_tokens(текст)
        куски: list[str] = []
        позиция = 0
        for серия in ЦИФРОВАЯ_СЕРИЯ.finditer(заглушённый):
            фрагмент = текст[серия.start() : серия.end()]
            цифры, позиции_цифр = _цифры_с_позициями(фрагмент)
            окна = self._найти_числовые_окна(
                цифры,
                паспортные=_окна_паспортной_формы(фрагмент, позиции_цифр, текст, серия.start()),
            )
            if not окна:
                continue
            куски.append(текст[позиция : серия.start()])
            местная_позиция = 0
            for начало, конец, токен in окна:
                фрагмент_начало = позиции_цифр[начало]
                фрагмент_конец = позиции_цифр[конец - 1] + 1
                куски.append(фрагмент[местная_позиция:фрагмент_начало])
                куски.append(токен)
                хинт_с = max(0, конец - 4)
                замены.append({"value_hint": f"…{цифры[хинт_с:конец]}", "token": токен})
                местная_позиция = фрагмент_конец
            куски.append(фрагмент[местная_позиция:])
            позиция = серия.end()
        куски.append(текст[позиция:])
        return "".join(куски)

    def _найти_числовые_окна(
        self, цифры: str, *, паспортные: frozenset[tuple[int, int]] = frozenset()
    ) -> list[tuple[int, int, str]]:
        """Скользящие окна по цифрам серии, а не серия целиком (ревью 2026-09-09, дыры 3-5):
        два известных значения подряд через один разделитель нормализовались бы в общую,
        никому не известную строку — здесь каждая длина, реально встречающаяся в словаре,
        проверяется на каждой позиции независимо, поэтому оба значения находятся, даже если
        разделитель между ними исчез при извлечении одних цифр, и известное значение находится,
        даже если оно — часть более длинной цифровой последовательности."""
        окна: list[tuple[int, int, str]] = []
        n = len(цифры)
        i = 0
        while i < n:
            найдено = None
            for длина in self._числовые_длины:
                if длина > n - i:
                    continue
                токен = self._numbers.get(цифры[i : i + длина])
                if (
                    токен is not None
                    and _короткий_документ(токен, длина)
                    and длина != n
                    and (i, i + длина) not in паспортные
                ):
                    # Номер документа без серии и код подразделения — только вся серия целиком
                    # или номер в записи паспортной формы (`_окна_паспортной_формы`).
                    continue
                if токен is not None:
                    найдено = (i, i + длина, токен)
                    break
            if найдено is None:
                i += 1
                continue
            окна.append(найдено)
            i = найдено[1]
        return окна

    def _заменить_названия(self, текст: str, замены: list[dict]) -> str:
        """Слой названий последнего рубежа — с тем же правилом пересечений, что у маскировщика
        (Б-4): сцепленные пересечениями названия заменяются одной группой, накрывающим названием
        или токенами всех участников подряд. Одна запись о замене на группу."""
        if self._все_названия is None:
            return текст
        заменено, найденные = заменить_названия(текст, self._все_названия, self._variants)
        for группа in найденные:
            первое = min(группа, key=lambda в: в.начало)
            замены.append({"value_hint": первое.подсказка, "token": первое.токен})
        return заменено


# Значение класса `doc` короче серии и номера паспорта (10 цифр) — номер документа без серии,
# код подразделения, номер свидетельства — страж заменяет, только если оно составляет всю
# цифровую серию текста, а не её часть (ревью атакующим ветки bp-gate, находка 1; инвариант 6).
# Каталог правил (ADR-0016) закрыл номер документа физлица классом `doc`, и в словаре оказалось по
# случайному шестизначному числу на каждое физлицо: окном внутри более длинной серии они
# заменяли номера документов (`0000-000123`), коды и даты (`2026-08-26` содержит `260826`) в
# ответах всех баз домашнего каталога. Серия и номер паспорта целиком (10 цифр) ищутся по-прежнему
# и внутри текста; код подразделения «770-001» — одна серия и находится как прежде.
ДЛИНА_СЕРИИ_И_НОМЕРА = 10


def _короткий_документ(токен: str, длина: int) -> bool:
    return длина < ДЛИНА_СЕРИИ_И_НОМЕРА and токен.startswith("[[doc:")


# Серия и номер паспорта в тексте — две и две цифры серии и шесть номера (повторное ревью
# атакующим, находка 1: номер из регистра документов физлиц хранится шестью цифрами, а в
# комментарии стоит рядом с серией, и правило «только вся серия» его пропускало — инвариант 1).
# Запись с пробелами («45 03 123456», «4503 123456») — паспортная сама по себе. Слитная
# («4503123456») и через дефис («4503-123456») — только со словом паспорта перед ней: слитно
# пишутся ИНН юрлица и телефон той же длины, через дефис — номера документов 1С (`0000-000123`),
# и их последние шесть цифр закрывались бы по совпадению с чьим-то номером паспорта (инвариант 6).
#
# Третий раунд ревью: пробел перед номером — любой пробельный символ (перевод строки, табуляция,
# неразрывный пробел из Word, несколько подряд) или экранированный `\n` сериализованного ответа;
# внутри серии допустимы точка и дефис («45-03 123456»). Форма номера документа `0000-000123`
# сюда не попадает: перед его шестью цифрами пробела нет. «Серия» словом паспорта не считается:
# в УТ это и серия номенклатуры, чьё написание рядом с цифрами вида `0000-000123` обычно.
_ПРОБЕЛ = r"(?:\s|\\n)+"
_ПАСПОРТ_С_ПРОБЕЛАМИ = re.compile(
    rf"(?<![\d\-./])\d{{2}}[\s.\-]?\d{{2}}{_ПРОБЕЛ}(\d{{6}})(?![\d\-./]?\d)"
)
_ПАСПОРТ_СЛИТНО = re.compile(r"(?<![\d\-./])\d{4}-?(\d{6})(?![\d\-./]?\d)")
_СЛОВО_ПАСПОРТА = re.compile(r"пасп|удостовер", re.IGNORECASE)
_ОКНО_СЛОВА = 40


def _окна_паспортной_формы(
    фрагмент: str, позиции_цифр: list[int], текст: str = "", начало_фрагмента: int = 0
) -> frozenset[tuple[int, int]]:
    """Окна `[начало, конец)` в индексах цифр серии, где стоит номер паспортной формы: короткое
    значение `doc` в таком окне засчитывается, даже если серия цифр длиннее его. `текст` и
    `начало_фрагмента` — чтобы увидеть слово паспорта перед слитной записью."""
    индекс = {позиция: номер for номер, позиция in enumerate(позиции_цифр)}
    окна = set()
    совпадения = list(_ПАСПОРТ_С_ПРОБЕЛАМИ.finditer(фрагмент))
    for совпадение in _ПАСПОРТ_СЛИТНО.finditer(фрагмент):
        левее = начало_фрагмента + совпадение.start()
        if _СЛОВО_ПАСПОРТА.search(текст, max(0, левее - _ОКНО_СЛОВА), левее):
            совпадения.append(совпадение)
    for совпадение in совпадения:
        начало, конец = совпадение.start(1), совпадение.end(1) - 1
        if начало in индекс and конец in индекс:
            окна.add((индекс[начало], индекс[конец] + 1))
    return frozenset(окна)


def _засчитано(замены: list[dict]) -> int:
    """Сколько замен засчитывается стражу: все, кроме накрытых названием (см. `_НАКРЫТО`)."""
    return sum(1 for замена in замены if not замена.get(_НАКРЫТО))


def _автомат_раскрытого(revealed: RevealedValues | None) -> _Автомат | None:
    """Автомат слоя раскрытого на один вызов: написания набора и те из них, что заменяются
    только при границах (Ruling 27)."""
    if revealed is None:
        return None
    return _собрать_автомат(revealed.tokens(), revealed.bounded(), revealed.whole_words())


def _собрать_автомат(
    варианты: dict[str, str],
    границы: frozenset[str] = _БЕЗ_ГРАНИЦ,
    целые_слова: frozenset[str] = frozenset(),
) -> _Автомат | None:
    """Автомат по свёрнутым написаниям, та же таблица «написание → токен» и множество написаний,
    которые заменяются только при границах (Ruling 27, только слой раскрытого). `None` — искать
    нечего (пустой набор): вызывающий тогда слой пропускает целиком.

    `MatchKind.Standard`: слой раскрытого ищет все совпадения, в том числе пересекающиеся
    (`overlaps.все_вхождения`), — иначе из двух раскрытых значений, сцепленных в тексте, второе
    не находилось бы вовсе."""
    if not варианты:
        return None
    автомат = AhoCorasick(list(варианты), matchkind=MatchKind.Standard)
    return автомат, варианты, границы, целые_слова


def _вставить(текст: str, замены: list[tuple[int, int, str]]) -> str:
    """Заменить непересекающиеся отрезки исходного текста (по возрастанию начала) на токены."""
    if not замены:
        return текст
    куски: list[str] = []
    позиция = 0
    for начало, конец, токен in замены:
        куски.append(текст[позиция:начало])
        куски.append(токен)
        позиция = конец
    куски.append(текст[позиция:])
    return "".join(куски)


# Пометка записи о замене: раскрытое лежало внутри известного названия, и заменено всё название
# целиком (правило вложенности). Такую замену сделал бы и маскировщик — ранний проход её стражу не
# засчитывает (`Guard._ранний_проход`); последний рубеж (`check`) засчитывает любую.
_НАКРЫТО = "covered_by_name"


def _заменить_раскрытое(
    текст: str, замены: list[dict], раскрытое: _Автомат, названия: _Автомат | None
) -> str:
    """Слой раскрытого с правилом вложенности интервалов (последний раунд M1d, находка I-1
    ревью 6).

    Слой раскрытого идёт раньше слоя названий (Ruling 25 и задача N1: иначе чужой слой рвёт
    раскрытое значение, дефект N1-B). Но и раскрытое, заменённое первым, рвёт чужое: «Альфа»
    внутри известного словарю названия «ООО Альфа-Строй Инвест» становилась токеном, а автомат
    названий по тексту с заглушкой на месте токена длинное название уже не находил — модель видела
    `ООО [[org:2]]-Строй Инвест`, обрывок названия третьего лица. Правило порядка не спасает ни в
    одну сторону, поэтому здесь не порядок, а вложенность: вхождения обоих слоёв ищутся по одному
    тексту, и спор решается по отрезкам.

    - Название, ЦЕЛИКОМ накрывающее вхождение раскрытого (в том числе совпадающее с ним по
      отрезку — раскрытое само известно словарю как название, обычный случай для `org`/`person`),
      побеждает: заменяется всё название своим токеном — ровно то, что сделал бы маскировщик без
      отбора. При совпадении отрезков это тот же токен, что у раскрытого: неоднозначные варианты
      в автомат названий не входят (`Dictionary.name_variants`). Разойтись они могут только между
      классами (раскрыт адрес, текстом совпавший с известной организацией) — и тогда токен
      названия и есть то, что пришло бы в ответе без отбора (инвариант 5). Замену сделал бы и
      маскировщик, поэтому стражу она не засчитывается (`_НАКРЫТО`): иначе отбор по токену давал
      бы `guard_replaced` там, где ответ без отбора молчит.
    - Название строго внутри раскрытого раскрытое не отменяет: заменяется раскрытое целиком.
      Иначе остаток самого раскрытого значения («ТЦ [[org:1]], д. 5») вышел бы модели открытым —
      это и был N1-B.
    - Частичное пересечение (ни один отрезок не накрывает другой: «Гамма Альфа» раскрыто,
      «Альфа Бета» известно, текст «Гамма Альфа Бета») — вся сцепленная область заменяется
      токенами всех участников подряд. Уступить названию значит открыть остаток раскрытого,
      уступить раскрытому — остаток третьего лица; токены подряд не открывают ничего, ценой того,
      что общая часть в тексте не повторена. Инвариант 1 важнее буквальности текста.

    Все три случая — одно правило (`gate/overlaps.py`, общее со слоем названий маскировщика и
    стража с правки Б-4): сцепленные пересечениями вхождения — группа; её участники — вхождения,
    не лежащие внутри другого вхождения группы (из раскрытого и названия с одним отрезком —
    название); группа заменяется токенами участников подряд. Названия ищутся ВСЕ, в том числе
    пересекающиеся между собой (Б-4): прежний поиск без пересечений видел из двух перекрытых
    названий только первое, и «Альфа-Бета-Гамма» при раскрытом «Бета» давало `[[org:1]]-Гамма`.

    Названия участвуют только те, что сцеплены с раскрытым — напрямую или через другое название:
    группы без раскрытого — работа маскировщика и последнего рубежа, ранний проход их не трогает.
    `названия=None` — уровень `identifiers` (там названия не защищаются) или словарь без названий:
    работает одно раскрытое, как раньше."""
    автомат, варианты, границы, целые_слова = раскрытое
    # Раскрытое — тоже ВСЕ совпадения: два раскрытых значения, частично пересекающиеся в тексте,
    # — случай 3 того же правила, и поиск без пересечений второе из них пропускал целиком.
    # Значения `org`/`person` — только целым словом, как у слоя названий (Ruling 106).
    свои = все_вхождения(
        текст,
        автомат,
        варианты,
        границы=границы,
        заглушать_guid=False,
        раскрытое=True,
        целые_слова=целые_слова,
    )
    if not свои:
        return текст
    # Названия — ВСЕ совпадения, в том числе пересекающиеся между собой (Б-4): прежний поиск без
    # пересечений видел из двух перекрытых названий только первое, и хвост второго выходил
    # открытым («Альфа-Бета-Гамма» при раскрытом «Бета» → `[[org:1]]-Гамма`, ревью 7). Названия
    # идут в список ПЕРВЫМИ: из раскрытого и названия с одним отрезком участником остаётся
    # название (`overlaps.участники`) — то, что выдал бы маскировщик без отбора.
    чужие = (
        все_вхождения(текст, названия[0], названия[1], целые_слова=названия[3])
        if названия is not None
        else []
    )
    куски: list[tuple[int, int, str]] = []
    for группа in группы(чужие + свои):
        # Группа без раскрытого — работа маскировщика и последнего рубежа: ранний проход её не
        # трогает. Названия участвуют те, что сцеплены с раскрытым пересечениями — напрямую или
        # через другое название (иначе остаток цепочки выходил бы открытым).
        if not any(в.раскрытое for в in группа):
            continue
        начало = min(в.начало for в in группа)
        конец = max(в.конец for в in группа)
        участвуют = участники(группа)
        куски.append((начало, конец, токены_подряд(участвуют)))
        раскрытые = [в for в in участвуют if в.раскрытое]
        if not раскрытые:
            # Раскрытое целиком внутри названий группы: замену сделал бы и маскировщик.
            первое = участвуют[0]
            замены.append({"value_hint": первое.подсказка, "token": первое.токен, _НАКРЫТО: True})
        else:
            замены.append({"value_hint": раскрытые[0].подсказка, "token": раскрытые[0].токен})
    _отметить_места(замены[len(замены) - len(куски) :], куски)
    return _вставить(текст, куски)


# Ключ записи о замене: где в ВЫХОДНОМ тексте стоит вставленный токен (Б-2). Нужен разбору с
# пометками (`revealed.load_scrubbed`): токен, который поставил ранний проход, маскировщик
# оставляет собой, а строку с токеном, пришедшую из 1С, выдаёт токеном `lit`. Отличить их по
# тексту нельзя — в 1С дословно вписан может быть ровно тот же токен, — только по месту.
_МЕСТО = "_место"


def _отметить_места(замены: list[dict], куски: list[tuple[int, int, str]]) -> None:
    """Записать в каждую замену место её вставки в выходном тексте (`_МЕСТО`). `куски` — в
    порядке возрастания начала, как их применит `_вставить`; `замены` — по одной на кусок, в том
    же порядке."""
    сдвиг = 0
    for замена, (начало, конец, вставка) in zip(замены, куски, strict=True):
        замена[_МЕСТО] = (начало + сдвиг, начало + сдвиг + len(вставка))
        сдвиг += len(вставка) - (конец - начало)


def _места(замены: list[dict]) -> tuple[tuple[int, int], ...]:
    return tuple(замена[_МЕСТО] for замена in замены if _МЕСТО in замена)


def _цифры_с_позициями(текст: str) -> tuple[str, list[int]]:
    """Только цифры фрагмента (приведённые к обычным ASCII-цифрам) и позиция каждой из них в
    исходном фрагменте — разделители (пробелы, дефисы, точки, косые черты, скобки) в результат не
    попадают, но по позиции всегда можно вернуться к месту, откуда цифра взята.

    Приведение к ASCII обязательно (ревью 2026-09-09, обход A): `str.isdigit()` истинен и для
    цифр в других системах записи (например, полноширинные ０-９ или деванагари ०-९), а словарь
    хранит значения обычными цифрами (`tokens.normalize_value`) — без приведения символ остаётся
    тем же самым знаком в другой кодовой точке и не совпадает ни с одним ключом словаря, хотя
    само число то же самое. `str.isdigit()` истинен ровно тогда, когда у символа определено
    числовое значение цифры (`unicodedata.digit`) — тем же тестом пользуется и сравнение."""
    цифры: list[str] = []
    позиции: list[int] = []
    for индекс, символ in enumerate(текст):
        if символ.isdigit():
            цифры.append(str(unicodedata.digit(символ)))
            позиции.append(индекс)
    return "".join(цифры), позиции
