"""Страж утечек: последний проход по сериализованному ответу любого тула (SPEC §6.8).

Инвариант, а не тест: ответ, в котором осталось известное словарю значение, наружу не выходит.
Работает независимо от политики базы и уровня — кроме off.

Где ищутся совпадения (F2 итогового ревью M1c и раунд 2 перепроверки, 2026-09-10). Раньше
страж шёл по сериализованному тексту целиком и заменял цифровую серию и в числовом литерале
JSON: `"Сумма": 79161234567` становилось `"Сумма": [[phone:…]]` — ответ переставал быть JSON, а
сумма молча превращалась в токен вопреки инварианту 6. Теперь, если текст — JSON-документ,
проверяется содержимое каждого строкового литерала (значения и ключа) отдельно; числа,
true/false/null и сама разметка не трогаются никогда. Охват по утечкам не теряется: реквизит
1С, который гейт защищает, приходит строкой (классы размечаются только у строковых полей, SPEC
§6.4), а числовой литерал JSON — это суммы и количества.

Почему каждый литерал отдельно и раскодированным (раунд 2, C1). Первая версия правки искала по
всему сырому тексту и отбрасывала совпадения, не лежащие внутри одного литерала. Но автомат
(LeftmostLongest) отдаёт непересекающиеся совпадения ДО такой проверки: длинный вариант
`ооо "ромашка"`, зацепивший закрывающую кавычку JSON (1С обрезала название без закрывающей
«ёлочки») или экранированную `\\"`, отбрасывался — и вместе с ним пропадал короткий `ромашка`,
который автомат уже не вернул. Название выходило при валидном JSON. Когда поиск идёт внутри
одной раскодированной строки, совпадению нечего пересекать по построению: границ литерала в
тексте поиска нет, `\\"` — просто кавычка, `\\n` и `\\t` — пробельные символы, а `\\uXXXX` —
тот символ, который увидит модель (сериализация с `ensure_ascii=True` больше не прячет кириллицу
и полноширинные цифры). Все прежние защиты — нормализация, скользящие окна, полноширинные цифры,
невидимые символы — работают на каждой строке тем же кодом, что и на тексте целиком.

Литерал, в котором ничего не заменено и нет экранирования `\\u`, остаётся побайтово прежним;
изменённый (или записанный через `\\u`) пишется заново `json.dumps(ensure_ascii=False)`. Текст
вне литералов — порядок ключей, пробелы, запись чисел (`1234567.890` не превращается в
`1234567.89`) — не меняется никогда.

Что считается JSON. Текст, который `json.loads` разбирает в объект, массив или строку (метка
порядка байтов в начале допускается). Всё прочее проверяется целиком, как до правки, — поведение
для не-JSON не меняется: обрезанный или просто текстовый ответ. Отдельный случай — JSON-документ
из одного числа: он неотличим от текстового ответа `$value` из одних цифр (`…/ИНН/$value`), и
пропустить его значило бы открыть дыру в инварианте 1. Такой скаляр проверяется как текст, а
результат с заменой обёртывается в строку JSON — чтобы и значение не вышло, и документ остался
валидным.
"""

from __future__ import annotations

import dataclasses
import json
import re
import unicodedata

from ahocorasick_rs import AhoCorasick, MatchKind

from odata1c.gate.dictionary import Dictionary, normalize_text_with_map
from odata1c.gate.tokens import blank_tokens

# Разделители цифровой серии (ревью 2026-09-09, дыры 3-5): пробелы всех видов, дефис, точка,
# косая черта, скобки, обратная косая — включая двузнаковый экранированный перевод строки
# `\n`. В JSON-документе строки теперь проверяются раскодированными, и перевод строки там —
# обычный пробельный символ; двузнаковая запись остаётся нужна для не-JSON текста, в котором
# уже сериализованный фрагмент может встретиться как есть. Старое ограничение снизу («минимум
# девять знаков в серии», `{7,}`) убрано — оно было не защитой, а обходом отсутствия проверки
# по факту: реальный отбор теперь идёт по точному совпадению скользящего окна со словарём
# (`_найти_числовые_окна`), а не по длине регулярного выражения, так что регэксп-порог только
# отсеивал часть настоящих значений заодно с мусором.
_ЧИСЛОВОЙ_РАЗДЕЛИТЕЛЬ = r"(?:\\n|[\s\-./()\\])"
ЦИФРОВАЯ_СЕРИЯ = re.compile(rf"\d(?:\d|{_ЧИСЛОВОЙ_РАЗДЕЛИТЕЛЬ})*\d")
# Строковый литерал JSON с учётом экранирования. В ВАЛИДНОМ JSON вне строк кавычек нет, поэтому
# проход этим выражением с начала текста находит ровно строковые литералы — ключи и значения.
_СТРОКА_JSON = re.compile(r'"(?:[^"\\]|\\.)*"', re.DOTALL)
_МЕТКА_ПОРЯДКА_БАЙТОВ = "\ufeff"

# Вид текста для стража (см. docstring модуля).
_JSON = "json"
_СКАЛЯР_ЧИСЛО = "число"
_ТЕКСТ = "текст"


def _вид(текст: str) -> str:
    try:
        документ = json.loads(текст.removeprefix(_МЕТКА_ПОРЯДКА_БАЙТОВ))
    except (ValueError, RecursionError):
        return _ТЕКСТ
    if isinstance(документ, (dict, list, str)):
        return _JSON
    if isinstance(документ, (int, float)) and not isinstance(документ, bool):
        return _СКАЛЯР_ЧИСЛО
    return _ТЕКСТ


_СУРРОГАТНАЯ_ПОЛОВИНА = re.compile("[\ud800-\udfff]")


def _записать_литерал(значение: str) -> str:
    """Строковый литерал JSON без экранирования `\\uXXXX` — кроме одиночной суррогатной
    половины (её допускает только JSON-запись `\\ud800`): её нельзя записать в UTF-8 как есть,
    и экранируется ровно она, а не весь литерал — иначе вместе с ней в `\\u` ушла бы и
    кириллица, вопреки SPEC §6.8 (Ruling 21 M1c, хвост 1)."""
    литерал = json.dumps(значение, ensure_ascii=False)
    return _СУРРОГАТНАЯ_ПОЛОВИНА.sub(lambda половина: f"\\u{ord(половина.group()):04x}", литерал)


@dataclasses.dataclass(slots=True)
class GuardResult:
    text: str
    replacements: list[dict]
    warnings: list[str]


class Guard:
    def __init__(self, dictionary: Dictionary) -> None:
        self._dictionary = dictionary
        self._revision = -1
        self._numbers: dict[str, str] = {}
        self._числовые_длины: list[int] = []
        self._automaton: AhoCorasick | None = None
        self._variants: dict[str, str] = {}
        self.rebuild()

    def rebuild(self) -> None:
        """Пересобрать множество чисел (и длин, встречающихся среди них) и автомат названий по
        текущему словарю."""
        self._numbers = self._dictionary.number_tokens()
        # Длины по убыванию: на каждой позиции скользящего окна сначала пробуем самое длинное
        # известное значение — то же соглашение, что и у LeftmostLongest автомата названий.
        self._числовые_длины = sorted({len(значение) for значение in self._numbers}, reverse=True)
        self._variants = self._dictionary.name_variants()
        ключи = list(self._variants)
        self._automaton = AhoCorasick(ключи, matchkind=MatchKind.LeftmostLongest) if ключи else None
        self._revision = self._dictionary.revision()

    def check(self, serialized: str, *, mode: str) -> GuardResult:
        if mode == "off":
            return GuardResult(text=serialized, replacements=[], warnings=[])
        if self._revision != self._dictionary.revision():
            self.rebuild()

        замены: list[dict] = []
        вид = _вид(serialized)
        if вид == _JSON:
            текст = self._проверить_литералы(serialized, замены, mode=mode)
        else:
            текст = self._проверить_текст(serialized, замены, mode=mode)
            if вид == _СКАЛЯР_ЧИСЛО and замены:
                текст = json.dumps(текст, ensure_ascii=False)
        предупреждения = ["guard_replaced"] if замены else []
        return GuardResult(text=текст, replacements=замены, warnings=предупреждения)

    def _проверить_литералы(self, текст: str, замены: list[dict], *, mode: str) -> str:
        """JSON-документ: каждый строковый литерал проверяется отдельно в раскодированном виде
        (см. docstring модуля). В валидном JSON вне строк кавычек нет, поэтому `_СТРОКА_JSON`,
        пройденное с начала текста, находит ровно литералы — ключи и значения."""
        куски: list[str] = []
        позиция = 0
        for литерал in _СТРОКА_JSON.finditer(текст):
            сырой = литерал.group()
            экранирован = "\\" in сырой
            значение = json.loads(сырой) if экранирован else сырой[1:-1]
            было = len(замены)
            проверено = self._проверить_текст(значение, замены, mode=mode)
            if len(замены) == было and not (экранирован and "\\u" in сырой):
                continue
            куски.append(текст[позиция : литерал.start()])
            куски.append(_записать_литерал(проверено))
            позиция = литерал.end()
        куски.append(текст[позиция:])
        return "".join(куски)

    def _проверить_текст(self, текст: str, замены: list[dict], *, mode: str) -> str:
        текст = self._заменить_числа(текст, замены)
        # Названия проверяются на любом режиме, кроме "off" (уже отсечён выше) и явного
        # "identifiers" (SPEC §6.2: названия защищаются только на верхнем уровне) — неизвестное
        # или искажённое значение режима трактуется как требующее максимальной защиты, а не как
        # молчаливое «названия не проверять» (ревью 2026-09-09, дыра 8: отказ инварианта обязан
        # быть в сторону защиты).
        if mode != "identifiers":
            текст = self._заменить_названия(текст, замены)
        return текст

    def _заменить_числа(self, текст: str, замены: list[dict]) -> str:
        if not self._numbers:
            return текст

        куски: list[str] = []
        позиция = 0
        for серия in ЦИФРОВАЯ_СЕРИЯ.finditer(текст):
            фрагмент = серия.group()
            цифры, позиции_цифр = _цифры_с_позициями(фрагмент)
            окна = self._найти_числовые_окна(цифры)
            if not окна:
                continue
            куски.append(текст[позиция : серия.start()])
            местная_позиция = 0
            for начало, конец, токен in окна:
                фрагмент_начало = позиции_цифр[начало]
                фрагмент_конец = позиции_цифр[конец - 1] + 1
                куски.append(фрагмент[местная_позиция:фрагмент_начало])
                куски.append(токен)
                хинт_с = max(0, конец - 4)
                замены.append({"value_hint": f"…{цифры[хинт_с:конец]}", "token": токен})
                местная_позиция = фрагмент_конец
            куски.append(фрагмент[местная_позиция:])
            позиция = серия.end()
        куски.append(текст[позиция:])
        return "".join(куски)

    def _найти_числовые_окна(self, цифры: str) -> list[tuple[int, int, str]]:
        """Скользящие окна по цифрам серии, а не серия целиком (ревью 2026-09-09, дыры 3-5):
        два известных значения подряд через один разделитель нормализовались бы в общую,
        никому не известную строку — здесь каждая длина, реально встречающаяся в словаре,
        проверяется на каждой позиции независимо, поэтому оба значения находятся, даже если
        разделитель между ними исчез при извлечении одних цифр, и известное значение находится,
        даже если оно — часть более длинной цифровой последовательности."""
        окна: list[tuple[int, int, str]] = []
        n = len(цифры)
        i = 0
        while i < n:
            найдено = None
            for длина in self._числовые_длины:
                if длина > n - i:
                    continue
                токен = self._numbers.get(цифры[i : i + длина])
                if токен is not None:
                    найдено = (i, i + длина, токен)
                    break
            if найдено is None:
                i += 1
                continue
            окна.append(найдено)
            i = найдено[1]
        return окна

    def _заменить_названия(self, текст: str, замены: list[dict]) -> str:
        if self._automaton is None:
            return текст
        # Поиск идёт по копии, где уже стоящие токены (из ответа и от замены чисел выше) закрыты
        # заглушкой той же длины: совпадение с токеном невозможно по построению, и вариант,
        # зацепивший скобку токена, не подавляет более короткий вариант названия рядом
        # (`tokens.blank_tokens`; Ruling 21 M1c, хвост 2).
        нормализованный, карта = normalize_text_with_map(blank_tokens(текст))
        совпадения = self._automaton.find_matches_as_indexes(нормализованный)
        if not совпадения:
            return текст
        куски: list[str] = []
        норм_позиция = 0
        текст_позиция = 0
        for _, начало, конец in совпадения:
            if начало < норм_позиция:
                continue
            вариант = нормализованный[начало:конец]
            токен = self._variants.get(вариант)
            if токен is None:
                continue
            текст_начало = карта[начало][0]
            текст_конец = карта[конец - 1][1]
            куски.append(текст[текст_позиция:текст_начало])
            куски.append(токен)
            # Подсказка — не длиннее нескольких символов и с конца значения, а не с начала
            # (ревью 2026-09-09, дыра 7): журнал не должен получать защищённое значение
            # целиком — то же ограничение, что уже действовало для чисел.
            замены.append({"value_hint": f"…{вариант[-4:]}", "token": токен})
            норм_позиция = конец
            текст_позиция = текст_конец
        куски.append(текст[текст_позиция:])
        return "".join(куски)


def _цифры_с_позициями(текст: str) -> tuple[str, list[int]]:
    """Только цифры фрагмента (приведённые к обычным ASCII-цифрам) и позиция каждой из них в
    исходном фрагменте — разделители (пробелы, дефисы, точки, косые черты, скобки) в результат не
    попадают, но по позиции всегда можно вернуться к месту, откуда цифра взята.

    Приведение к ASCII обязательно (ревью 2026-09-09, обход A): `str.isdigit()` истинен и для
    цифр в других системах записи (например, полноширинные ０-９ или деванагари ०-९), а словарь
    хранит значения обычными цифрами (`tokens.normalize_value`) — без приведения символ остаётся
    тем же самым знаком в другой кодовой точке и не совпадает ни с одним ключом словаря, хотя
    само число то же самое. `str.isdigit()` истинен ровно тогда, когда у символа определено
    числовое значение цифры (`unicodedata.digit`) — тем же тестом пользуется и сравнение."""
    цифры: list[str] = []
    позиции: list[int] = []
    for индекс, символ in enumerate(текст):
        if символ.isdigit():
            цифры.append(str(unicodedata.digit(символ)))
            позиции.append(индекс)
    return "".join(цифры), позиции
