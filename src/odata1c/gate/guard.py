"""Страж утечек: последний проход по сериализованному ответу любого тула (SPEC §6.8).

Инвариант, а не тест: ответ, в котором осталось известное словарю значение, наружу не выходит.
Работает независимо от политики базы и уровня — кроме off.
"""

from __future__ import annotations

import dataclasses
import re

from ahocorasick_rs import AhoCorasick, MatchKind

from odata1c.gate.dictionary import Dictionary, normalize_text_with_map
from odata1c.gate.tokens import find_tokens, overlaps_token

# Разделители цифровой серии (ревью 2026-09-09, дыры 3-5): пробелы всех видов, дефис, точка,
# косая черта, скобки, обратная косая — включая двузнаковый экранированный перевод строки
# `\n`, которым он всегда представлен в уже сериализованном JSON-ответе (сам перевод строки
# как один байт туда попасть не может — сериализация экранирует его раньше, чем текст дойдёт
# до стража). Старое ограничение снизу («минимум девять знаков в серии», `{7,}`) убрано — оно
# было не защитой, а обходом отсутствия проверки по факту: реальный отбор теперь идёт по точному
# совпадению скользящего окна со словарём (`_найти_числовые_окна`), а не по длине регулярного
# выражения, так что регэксп-порог только отсеивал часть настоящих значений заодно с мусором.
_ЧИСЛОВОЙ_РАЗДЕЛИТЕЛЬ = r"(?:\\n|[\s\-./()\\])"
ЦИФРОВАЯ_СЕРИЯ = re.compile(rf"\d(?:\d|{_ЧИСЛОВОЙ_РАЗДЕЛИТЕЛЬ})*\d")


@dataclasses.dataclass(slots=True)
class GuardResult:
    text: str
    replacements: list[dict]
    warnings: list[str]


class Guard:
    def __init__(self, dictionary: Dictionary) -> None:
        self._dictionary = dictionary
        self._revision = -1
        self._numbers: dict[str, str] = {}
        self._числовые_длины: list[int] = []
        self._automaton: AhoCorasick | None = None
        self._variants: dict[str, str] = {}
        self.rebuild()

    def rebuild(self) -> None:
        """Пересобрать множество чисел (и длин, встречающихся среди них) и автомат названий по
        текущему словарю."""
        self._numbers = self._dictionary.number_tokens()
        # Длины по убыванию: на каждой позиции скользящего окна сначала пробуем самое длинное
        # известное значение — то же соглашение, что и у LeftmostLongest автомата названий.
        self._числовые_длины = sorted({len(значение) for значение in self._numbers}, reverse=True)
        self._variants = self._dictionary.name_variants()
        ключи = list(self._variants)
        self._automaton = AhoCorasick(ключи, matchkind=MatchKind.LeftmostLongest) if ключи else None
        self._revision = self._dictionary.revision()

    def check(self, serialized: str, *, mode: str) -> GuardResult:
        if mode == "off":
            return GuardResult(text=serialized, replacements=[], warnings=[])
        if self._revision != self._dictionary.revision():
            self.rebuild()

        замены: list[dict] = []
        текст = self._заменить_числа(serialized, замены)
        # Названия проверяются на любом режиме, кроме "off" (уже отсечён выше) и явного
        # "identifiers" (SPEC §6.2: названия защищаются только на верхнем уровне) — неизвестное
        # или искажённое значение режима трактуется как требующее максимальной защиты, а не как
        # молчаливое «названия не проверять» (ревью 2026-09-09, дыра 8: отказ инварианта обязан
        # быть в сторону защиты).
        if mode != "identifiers":
            текст = self._заменить_названия(текст, замены)
        предупреждения = ["guard_replaced"] if замены else []
        return GuardResult(text=текст, replacements=замены, warnings=предупреждения)

    def _заменить_числа(self, текст: str, замены: list[dict]) -> str:
        if not self._numbers:
            return текст

        куски: list[str] = []
        позиция = 0
        for серия in ЦИФРОВАЯ_СЕРИЯ.finditer(текст):
            фрагмент = серия.group()
            цифры, позиции_цифр = _цифры_с_позициями(фрагмент)
            окна = self._найти_числовые_окна(цифры)
            if not окна:
                continue
            куски.append(текст[позиция : серия.start()])
            местная_позиция = 0
            for начало, конец, токен in окна:
                фрагмент_начало = позиции_цифр[начало]
                фрагмент_конец = позиции_цифр[конец - 1] + 1
                куски.append(фрагмент[местная_позиция:фрагмент_начало])
                куски.append(токен)
                хинт_с = max(0, конец - 4)
                замены.append({"value_hint": f"…{цифры[хинт_с:конец]}", "token": токен})
                местная_позиция = фрагмент_конец
            куски.append(фрагмент[местная_позиция:])
            позиция = серия.end()
        куски.append(текст[позиция:])
        return "".join(куски)

    def _найти_числовые_окна(self, цифры: str) -> list[tuple[int, int, str]]:
        """Скользящие окна по цифрам серии, а не серия целиком (ревью 2026-09-09, дыры 3-5):
        два известных значения подряд через один разделитель нормализовались бы в общую,
        никому не известную строку — здесь каждая длина, реально встречающаяся в словаре,
        проверяется на каждой позиции независимо, поэтому оба значения находятся, даже если
        разделитель между ними исчез при извлечении одних цифр, и известное значение находится,
        даже если оно — часть более длинной цифровой последовательности."""
        окна: list[tuple[int, int, str]] = []
        n = len(цифры)
        i = 0
        while i < n:
            найдено = None
            for длина in self._числовые_длины:
                if длина > n - i:
                    continue
                токен = self._numbers.get(цифры[i : i + длина])
                if токен is not None:
                    найдено = (i, i + длина, токен)
                    break
            if найдено is None:
                i += 1
                continue
            окна.append(найдено)
            i = найдено[1]
        return окна

    def _заменить_названия(self, текст: str, замены: list[dict]) -> str:
        if self._automaton is None:
            return текст
        нормализованный, карта = normalize_text_with_map(текст)
        совпадения = self._automaton.find_matches_as_indexes(нормализованный)
        if not совпадения:
            return текст
        занятые_токенами = find_tokens(текст)
        куски: list[str] = []
        норм_позиция = 0
        текст_позиция = 0
        for _, начало, конец in совпадения:
            if начало < норм_позиция:
                continue
            вариант = нормализованный[начало:конец]
            токен = self._variants.get(вариант)
            if токен is None:
                continue
            текст_начало = карта[начало][0]
            текст_конец = карта[конец - 1][1]
            # Хвост уже поставленного токена набран из тех же символов, что и приведённое к
            # нижнему регистру латинское название — совпадение внутри такого токена пропускается,
            # а не разрезает его (ревью 2026-09-09, дыра 8).
            if overlaps_token(текст_начало, текст_конец, занятые_токенами):
                норм_позиция = конец
                continue
            куски.append(текст[текст_позиция:текст_начало])
            куски.append(токен)
            # Подсказка — не длиннее нескольких символов и с конца значения, а не с начала
            # (ревью 2026-09-09, дыра 7): журнал не должен получать защищённое значение
            # целиком — то же ограничение, что уже действовало для чисел.
            замены.append({"value_hint": f"…{вариант[-4:]}", "token": токен})
            норм_позиция = конец
            текст_позиция = текст_конец
        куски.append(текст[текст_позиция:])
        return "".join(куски)


def _цифры_с_позициями(текст: str) -> tuple[str, list[int]]:
    """Только цифры фрагмента и позиция каждой из них в исходном фрагменте — разделители
    (пробелы, дефисы, точки, косые черты, скобки) в результат не попадают, но по позиции всегда
    можно вернуться к месту, откуда цифра взята."""
    цифры: list[str] = []
    позиции: list[int] = []
    for индекс, символ in enumerate(текст):
        if символ.isdigit():
            цифры.append(символ)
            позиции.append(индекс)
    return "".join(цифры), позиции
