"""Страж утечек: последний проход по сериализованному ответу любого тула (SPEC §6.8).

Инвариант, а не тест: ответ, в котором осталось известное словарю значение, наружу не выходит.
Работает независимо от политики базы и уровня — кроме off.

Где ищутся совпадения (F2 итогового ревью M1c, 2026-09-10). Раньше страж шёл по
сериализованному тексту целиком и заменял цифровую серию и в числовом литерале JSON:
`"Сумма": 79161234567` становилось `"Сумма": [[phone:…]]` — ответ переставал быть JSON, а сумма
молча превращалась в токен вопреки инварианту 6. Теперь, если текст — JSON-документ (объект или
массив), совпадения принимаются только внутри строковых литералов — значений и ключей; числа,
true/false/null и сама разметка не трогаются никогда. Охват по утечкам не теряется: реквизит
1С, который гейт защищает, приходит строкой (классы размечаются только у строковых полей, SPEC
§6.4), а числовой литерал JSON — это суммы и количества.

Почему фильтр диапазонов, а не разбор в объекты и обратная сериализация. Замена идёт по
исходному тексту, как и прежде, а совпадение отбрасывается, если оно не лежит целиком внутри
одного строкового литерала. Текст вне замен остаётся побайтово тем же — порядок ключей,
пробелы, запись чисел (`1234567.890` не превращается в `1234567.89`) и экранирование не
меняются, а все прежние защиты (нормализация, скользящие окна, полноширинные цифры, невидимые
символы) работают без изменений на том же тексте. Токен `[[class:tail]]` не содержит символов,
которые в строке JSON требуют экранирования, поэтому замена внутри литерала сохраняет валидность.

Что считается JSON. Текст, который `json.loads` разбирает в объект, массив или строку. Всё
прочее проверяется целиком, как до правки, — поведение для не-JSON не меняется: обрезанный или
просто текстовый ответ. Отдельный случай — JSON-документ из одного числа: он неотличим от
текстового ответа `$value` из одних цифр (`…/ИНН/$value`), и пропустить его значило бы открыть
дыру в инварианте 1. Такой скаляр проверяется как текст, а результат с заменой обёртывается в
строку JSON — чтобы и значение не вышло, и документ остался валидным.
"""

from __future__ import annotations

import bisect
import dataclasses
import json
import re
import unicodedata

from ahocorasick_rs import AhoCorasick, MatchKind

from odata1c.gate.dictionary import Dictionary, normalize_text_with_map
from odata1c.gate.tokens import find_tokens, overlaps_token

# Разделители цифровой серии (ревью 2026-09-09, дыры 3-5): пробелы всех видов, дефис, точка,
# косая черта, скобки, обратная косая — включая двузнаковый экранированный перевод строки
# `\n`, которым он всегда представлен в уже сериализованном JSON-ответе (сам перевод строки
# как один байт туда попасть не может — сериализация экранирует его раньше, чем текст дойдёт
# до стража). Старое ограничение снизу («минимум девять знаков в серии», `{7,}`) убрано — оно
# было не защитой, а обходом отсутствия проверки по факту: реальный отбор теперь идёт по точному
# совпадению скользящего окна со словарём (`_найти_числовые_окна`), а не по длине регулярного
# выражения, так что регэксп-порог только отсеивал часть настоящих значений заодно с мусором.
_ЧИСЛОВОЙ_РАЗДЕЛИТЕЛЬ = r"(?:\\n|[\s\-./()\\])"
ЦИФРОВАЯ_СЕРИЯ = re.compile(rf"\d(?:\d|{_ЧИСЛОВОЙ_РАЗДЕЛИТЕЛЬ})*\d")
# Строковый литерал JSON с учётом экранирования. В ВАЛИДНОМ JSON вне строк кавычек нет, поэтому
# проход этим выражением с начала текста находит ровно строковые литералы — ключи и значения.
_СТРОКА_JSON = re.compile(r'"(?:[^"\\]|\\.)*"', re.DOTALL)


class _Области:
    """Диапазоны содержимого строковых литералов JSON (без самих кавычек) — отсортированы и не
    пересекаются; `содержит` отвечает, лежит ли отрезок целиком внутри одного из них."""

    __slots__ = ("_начала", "_концы")

    def __init__(self, текст: str) -> None:
        self._начала: list[int] = []
        self._концы: list[int] = []
        for литерал in _СТРОКА_JSON.finditer(текст):
            self._начала.append(литерал.start() + 1)
            self._концы.append(литерал.end() - 1)

    def содержит(self, начало: int, конец: int) -> bool:
        индекс = bisect.bisect_right(self._начала, начало) - 1
        return индекс >= 0 and конец <= self._концы[индекс]


def _разметить(текст: str) -> tuple[_Области | None, bool]:
    """Области строк, если текст — JSON-документ (объект, массив, строка), иначе None; второй
    элемент — признак JSON-скаляра-числа (см. docstring модуля, случай `$value`)."""
    try:
        документ = json.loads(текст)
    except (ValueError, RecursionError):
        return None, False
    if isinstance(документ, (dict, list, str)):
        return _Области(текст), False
    return None, isinstance(документ, (int, float)) and not isinstance(документ, bool)


def _после_экранирующей_косой(текст: str, позиция: int) -> bool:
    """Символ на `позиции` экранирован обратной косой (перед ним нечётная серия «\\»): в JSON он
    часть управляющей последовательности (`\\n`, `\\t`, `\\u…`), а не буква текста. Совпадение
    названия, начинающееся с такой буквы (`\\nestle` → «nestle»), — ложное: в настоящем тексте
    там перевод строки и «estle»; замена с этой позиции разорвала бы последовательность и
    испортила JSON."""
    косых = 0
    while позиция - косых - 1 >= 0 and текст[позиция - косых - 1] == "\\":
        косых += 1
    return косых % 2 == 1


@dataclasses.dataclass(slots=True)
class GuardResult:
    text: str
    replacements: list[dict]
    warnings: list[str]


class Guard:
    def __init__(self, dictionary: Dictionary) -> None:
        self._dictionary = dictionary
        self._revision = -1
        self._numbers: dict[str, str] = {}
        self._числовые_длины: list[int] = []
        self._automaton: AhoCorasick | None = None
        self._variants: dict[str, str] = {}
        self.rebuild()

    def rebuild(self) -> None:
        """Пересобрать множество чисел (и длин, встречающихся среди них) и автомат названий по
        текущему словарю."""
        self._numbers = self._dictionary.number_tokens()
        # Длины по убыванию: на каждой позиции скользящего окна сначала пробуем самое длинное
        # известное значение — то же соглашение, что и у LeftmostLongest автомата названий.
        self._числовые_длины = sorted({len(значение) for значение in self._numbers}, reverse=True)
        self._variants = self._dictionary.name_variants()
        ключи = list(self._variants)
        self._automaton = AhoCorasick(ключи, matchkind=MatchKind.LeftmostLongest) if ключи else None
        self._revision = self._dictionary.revision()

    def check(self, serialized: str, *, mode: str) -> GuardResult:
        if mode == "off":
            return GuardResult(text=serialized, replacements=[], warnings=[])
        if self._revision != self._dictionary.revision():
            self.rebuild()

        замены: list[dict] = []
        # F2 итогового ревью: в JSON-документе совпадения принимаются только внутри строковых
        # литералов (см. docstring модуля); для не-JSON области — None, текст целиком.
        области, скаляр_число = _разметить(serialized)
        текст = self._заменить_числа(serialized, замены, области)
        # Названия проверяются на любом режиме, кроме "off" (уже отсечён выше) и явного
        # "identifiers" (SPEC §6.2: названия защищаются только на верхнем уровне) — неизвестное
        # или искажённое значение режима трактуется как требующее максимальной защиты, а не как
        # молчаливое «названия не проверять» (ревью 2026-09-09, дыра 8: отказ инварианта обязан
        # быть в сторону защиты).
        if mode != "identifiers":
            if области is not None and текст is not serialized:
                области = _Области(текст)  # числовой проход сдвинул позиции
            текст = self._заменить_названия(текст, замены, области)
        if скаляр_число and замены:
            текст = json.dumps(текст, ensure_ascii=False)
        предупреждения = ["guard_replaced"] if замены else []
        return GuardResult(text=текст, replacements=замены, warnings=предупреждения)

    def _заменить_числа(
        self, текст: str, замены: list[dict], области: _Области | None = None
    ) -> str:
        if not self._numbers:
            return текст

        куски: list[str] = []
        позиция = 0
        for серия in ЦИФРОВАЯ_СЕРИЯ.finditer(текст):
            # Серия не пересекает кавычку (её нет среди разделителей), поэтому она либо целиком
            # внутри строкового литерала, либо целиком снаружи — числовой литерал JSON.
            if области is not None and not области.содержит(серия.start(), серия.end()):
                continue
            фрагмент = серия.group()
            цифры, позиции_цифр = _цифры_с_позициями(фрагмент)
            окна = self._найти_числовые_окна(цифры)
            if not окна:
                continue
            куски.append(текст[позиция : серия.start()])
            местная_позиция = 0
            for начало, конец, токен in окна:
                фрагмент_начало = позиции_цифр[начало]
                фрагмент_конец = позиции_цифр[конец - 1] + 1
                куски.append(фрагмент[местная_позиция:фрагмент_начало])
                куски.append(токен)
                хинт_с = max(0, конец - 4)
                замены.append({"value_hint": f"…{цифры[хинт_с:конец]}", "token": токен})
                местная_позиция = фрагмент_конец
            куски.append(фрагмент[местная_позиция:])
            позиция = серия.end()
        куски.append(текст[позиция:])
        return "".join(куски)

    def _найти_числовые_окна(self, цифры: str) -> list[tuple[int, int, str]]:
        """Скользящие окна по цифрам серии, а не серия целиком (ревью 2026-09-09, дыры 3-5):
        два известных значения подряд через один разделитель нормализовались бы в общую,
        никому не известную строку — здесь каждая длина, реально встречающаяся в словаре,
        проверяется на каждой позиции независимо, поэтому оба значения находятся, даже если
        разделитель между ними исчез при извлечении одних цифр, и известное значение находится,
        даже если оно — часть более длинной цифровой последовательности."""
        окна: list[tuple[int, int, str]] = []
        n = len(цифры)
        i = 0
        while i < n:
            найдено = None
            for длина in self._числовые_длины:
                if длина > n - i:
                    continue
                токен = self._numbers.get(цифры[i : i + длина])
                if токен is not None:
                    найдено = (i, i + длина, токен)
                    break
            if найдено is None:
                i += 1
                continue
            окна.append(найдено)
            i = найдено[1]
        return окна

    def _заменить_названия(
        self, текст: str, замены: list[dict], области: _Области | None = None
    ) -> str:
        if self._automaton is None:
            return текст
        нормализованный, карта = normalize_text_with_map(текст)
        совпадения = self._automaton.find_matches_as_indexes(нормализованный)
        if not совпадения:
            return текст
        занятые_токенами = find_tokens(текст)
        куски: list[str] = []
        норм_позиция = 0
        текст_позиция = 0
        for _, начало, конец in совпадения:
            if начало < норм_позиция:
                continue
            вариант = нормализованный[начало:конец]
            токен = self._variants.get(вариант)
            if токен is None:
                continue
            текст_начало = карта[начало][0]
            текст_конец = карта[конец - 1][1]
            # Хвост уже поставленного токена набран из тех же символов, что и приведённое к
            # нижнему регистру латинское название — совпадение внутри такого токена пропускается,
            # а не разрезает его (ревью 2026-09-09, дыра 8).
            if overlaps_token(текст_начало, текст_конец, занятые_токенами):
                норм_позиция = конец
                continue
            # F2 итогового ревью: в JSON-документе название заменяется только внутри одного
            # строкового литерала — не в числе (вариант «2026» от «ООО 2026» против `"Год": 2026`),
            # не поперёк разметки и не с буквы управляющей последовательности.
            if области is not None and (
                not области.содержит(текст_начало, текст_конец)
                or _после_экранирующей_косой(текст, текст_начало)
            ):
                continue
            куски.append(текст[текст_позиция:текст_начало])
            куски.append(токен)
            # Подсказка — не длиннее нескольких символов и с конца значения, а не с начала
            # (ревью 2026-09-09, дыра 7): журнал не должен получать защищённое значение
            # целиком — то же ограничение, что уже действовало для чисел.
            замены.append({"value_hint": f"…{вариант[-4:]}", "token": токен})
            норм_позиция = конец
            текст_позиция = текст_конец
        куски.append(текст[текст_позиция:])
        return "".join(куски)


def _цифры_с_позициями(текст: str) -> tuple[str, list[int]]:
    """Только цифры фрагмента (приведённые к обычным ASCII-цифрам) и позиция каждой из них в
    исходном фрагменте — разделители (пробелы, дефисы, точки, косые черты, скобки) в результат не
    попадают, но по позиции всегда можно вернуться к месту, откуда цифра взята.

    Приведение к ASCII обязательно (ревью 2026-09-09, обход A): `str.isdigit()` истинен и для
    цифр в других системах записи (например, полноширинные ０-９ или деванагари ०-९), а словарь
    хранит значения обычными цифрами (`tokens.normalize_value`) — без приведения символ остаётся
    тем же самым знаком в другой кодовой точке и не совпадает ни с одним ключом словаря, хотя
    само число то же самое. `str.isdigit()` истинен ровно тогда, когда у символа определено
    числовое значение цифры (`unicodedata.digit`) — тем же тестом пользуется и сравнение."""
    цифры: list[str] = []
    позиции: list[int] = []
    for индекс, символ in enumerate(текст):
        if символ.isdigit():
            цифры.append(str(unicodedata.digit(символ)))
            позиции.append(индекс)
    return "".join(цифры), позиции
