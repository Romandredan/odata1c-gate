# Форма телефона для вывода класса из содержимого у строк без известного типа: только цифры и
# знаки записи номера, и цифр не меньше пяти.
_ФОРМА_ТЕЛЕФОНА = re.compile(r"[\d\s()+\-.,/]+")
_ФОРМА_ПОЧТЫ = re.compile(r"[^\s@]+@[^\s@]+\.[^\s@]+")
# Добавочный номер в конце представления телефона: «, доб. 123», « доб 12», «, ext. 45»,
# «, вн. 7» (раунд 3, I-1).
_ДОБАВОЧНЫЙ = re.compile(r"[\s,;]*(?:доб(?:авочный)?|ext|вн)\.?\s*\d{1,6}$", re.IGNORECASE)


@dataclasses.dataclass(frozen=True, slots=True)
class EntityShape:
    """Строение сущности по индексу метаданных: имена полей, родитель (для табличной части —
    объект-владелец) и навигации (имя навигационного свойства → сущность-цель). Гейт индекс не
    читает — строение ему отдаёт слой тулов (`Shape`).

    Навигации нужны входному пути (Ruling 37): отбор `Контрагент/КонтактнаяИнформация/Представление`
    от документа доходит до табличной части контактной информации через навигацию `Контрагент`,
    и понять, куда он пришёл, можно, только зная цель навигации (`entity_of_path`)."""

    fields: frozenset[str]
    parent: str | None = None
    navigations: Mapping[str, str] = dataclasses.field(default_factory=dict)


# Имя сущности → её строение, либо `None`, если индекс о сущности не знает.
Shape = Callable[[str], EntityShape | None]

# Запасной признак табличной части контактной информации — суффикс имени (опасение 9 раунда 1,
# решение координатора): действует ТОЛЬКО когда строения нет вовсе (индекс устарел — табличная
# часть появилась после реиндекса — или путь `raw_get` не разрешён). Сущность, которую индекс
# знает и чьё строение не контактная информация, по имени не перечисляется: строение главнее.
СУФФИКС_ТАБЛИЧНОЙ_ЧАСТИ = "_КонтактнаяИнформация"

# Ruling 35: класс поля значения контактной информации на ВХОДНОМ пути. Тип строки на входе
# неизвестен — выражение отбора строки не несёт, — поэтому класс не phone/email/addr, а общий, и
# правила у него строже любого из них: в отборе допустим только целый токен из ответа (открытый
# литерал в сравнении, поиск подстроки, упорядоченное сравнение, сортировка — отказ). В словарь
# этот класс не попадает никогда: токены выдаёт маскировщик классами строки (`КЛАССЫ_ТОКЕНОВ`).
КЛАСС_НА_ВХОДЕ = "contact"
# Классы, которыми маскировщик закрывает значения контактной информации: по типу строки
# (`КЛАСС_ПО_ТИПУ`) и по содержимому у прочих типов (`класс_по_содержимому`). Токен любого из них
# раскрывается в поле класса `КЛАСС_НА_ВХОДЕ`.
КЛАССЫ_ТОКЕНОВ = frozenset({"phone", "email", "addr"})


def is_contact_info_entity(
    entity: str, shape: Shape | None, keys: Collection[str] | None = None
) -> bool:
    """Табличная часть контактной информации ли `entity` — единое правило маскировщика и входного
    пути (Ruling 33, 35), чтобы они не разошлись.

    1. Строение по индексу есть — решает оно (`is_contact_info_table`).
    2. Строения нет (`shape is None` или индекс сущность не знает) — суффикс имени
       `СУФФИКС_ТАБЛИЧНОЙ_ЧАСТИ` (неизвестность — в строгую сторону, Ruling 18), а у маскировщика,
       у которого в руках строка ответа, ещё и ключи самой строки (`keys`): нужны все три поля
       строения, иначе чужая сущность с полями `Тип` и `Значение` получила бы маскировку, которой
       не заслужила (инвариант 6)."""
    строение = shape(entity) if shape is not None else None
    if строение is not None:
        return is_contact_info_table(строение.fields)
    if entity.endswith(СУФФИКС_ТАБЛИЧНОЙ_ЧАСТИ):
        return True
    return keys is not None and is_contact_info_table(keys)


def entity_of_path(entity: str, containers: Collection[str], shape: Shape | None) -> str:
    """Сущность, в которую приходит путь отбора, пройдя звенья `containers` от `entity`
    (Ruling 37): от `Document_ЗаказКлиента` звенья `Контрагент`, `КонтактнаяИнформация` приводят
    в `Catalog_Контрагенты_КонтактнаяИнформация`.

    Звено — либо навигация (цель по строению из индекса), либо табличная часть: табличная часть
    навигацией в `$metadata` 1С не приходит вовсе (проба P4), она дочерняя сущность с именем
    `<владелец>_<звено>` — то же правило, что у резолвера маскировщика (`ToolService._навигации`).

    Звено, которое строение навигацией не объясняет (строения нет: индекс устарел, путь `raw_get`
    не разрешён, у виртуальной таблицы навигаций нет), толкуется как табличная часть — имя
    дочерней сущности составляется по правилу 1С. Это не угадывание в мягкую сторону: дальше
    решает `is_contact_info_entity`, а у неё для имени, которого индекс не знает, действует
    запасной признак по суффиксу `СУФФИКС_ТАБЛИЧНОЙ_ЧАСТИ` (неизвестность — в строгую сторону,
    Ruling 18). Дочернюю сущность, которую индекс знает, решает её строение: `Товары/Сумма` —
    табличная часть, но не контактная информация."""
    текущая = entity
    for звено in containers:
        строение = shape(текущая) if shape is not None else None
        цель = строение.navigations.get(звено) if строение is not None else None
        текущая = цель if цель is not None else f"{текущая}_{звено}"
    return текущая


def select_with_type(entity: str, select: list[str], shape: Shape | None) -> list[str]:
    """`$select` с полем `Тип` у каждой табличной части контактной информации, из которой выбрано
    поле значения (раунд 3, I-1; инвариант 5 — одно значение, один токен).

    Класс строки задаёт `Тип` (Ruling 33). Когда модель выбирает `Представление` без `Тип`, класс
    выводился из содержимого, и тот же номер получал другой токен, чем при выборе с `Тип`:
    «+7 (4912) 12-34-56, доб. 123» — `addr` вместо `phone`, одно `НомерТелефона` — `addr`,
    одно `АдресЭП` — `addr` вместо `email`. Поэтому шлюз сам добавляет `Тип` в запрос к 1С:
    к выбору корня (запрос прямо в табличную часть) — `Тип`, к пути через владельца
    (`КонтактнаяИнформация/Представление`, `Контрагент/КонтактнаяИнформация/Представление`) —
    `Тип` того же контейнера. Табличная часть выбрана целиком (`КонтактнаяИнформация`) или `*` —
    1С и так вернёт все поля.

    `Тип` дописывается только там, где индекс знает сущность и её строение — контактная
    информация (а значит, поле `Тип` у неё есть: `is_contact_info_table` требует его в составе).
    Сущность, узнанная лишь по суффиксу имени (индекс её не знает: устарел, путь `raw_get` не
    разрешён), `Тип` в запрос не получает ни в корне, ни в конце пути: дописать поле, которого у
    сущности нет, — это 400 от 1С, то есть отказ вместо ответа. Защиту это не ослабляет:
    суффиксный признак остаётся у МАСКИРОВЩИКА, который решает по содержимому строки ответа, а не
    по составу запроса.

    Цена (I-1 ревью задачи 3): у сущности, которой индекс не знает, класс строки снова зависит от
    набора выбранных полей — то самое, ради чего `Тип` и дописывается. Строка, в которой выбрана
    одна колонка поиска (`НомерТелефона`, `АдресЭП`) без `Представление`, закрывается классом по
    содержимому и может получить `addr` вместо `phone`/`email`, то есть другой токен, чем та же
    строка вместе с `Тип`. Значение закрыто в обоих случаях — страдает инвариант 5, а не защита, и
    только до реиндекса.

    Из ответа добавленный `Тип` НЕ вырезается: это открытое поле по замыслу (`ОТКРЫТЫЕ_ПОЛЯ` —
    модель видит тип строки рядом с токеном), и тот же приём уже есть у построителя запроса — он
    добавляет в `$select` поля представления цели раскрытия и оставляет их в ответе
    (`odata_query._ПОЛЯ_ПРЕДСТАВЛЕНИЯ`). Вырезание было бы лишним обходом ответа ради того, чтобы
    спрятать от модели открытое поле."""
    результат = list(select)
    выбрано = set(результат)
    for поле in select:
        *звенья, имя = поле.split("/")
        if имя == "*" or not is_value_field(имя):
            continue
        цель = entity_of_path(entity, звенья, shape)
        строение_цели = shape(цель) if shape is not None else None
        # Проект M3b §3.5: `Тип` дописывается в запрос ТОЛЬКО когда индекс знает сущность и её
        # строение — это контактная информация (а значит, поле `Тип` у неё есть:
        # `is_contact_info_table` требует его в составе). Запасной признак по суффиксу имени
        # (`is_contact_info_entity` для сущности, которой индекс не знает) здесь не годится:
        # дописать несуществующее поле в `$select` — это 400 от 1С, то есть отказ вместо ответа.
        # На защиту это не влияет: суффиксный путь остаётся у МАСКИРОВЩИКА, который решает по
        # содержимому строки, а не по составу запроса.
        if строение_цели is None or not is_contact_info_table(строение_цели.fields):
            continue
        тип = "/".join([*звенья, ПОЛЕ_ТИПА])
        if тип not in выбрано:
            результат.append(тип)
            выбрано.add(тип)
    return результат


def is_contact_info_table(fields: Collection[str]) -> bool:
    """Строение табличной части контактной информации (см. докстринг модуля)."""
    поля = set(fields)
    return (
        ПОЛЕ_ТИПА in поля and ПОЛЕ_ПРЕДСТАВЛЕНИЯ in поля and any(п in поля for п in ПОЛЯ_СТРУКТУРЫ)
    )


def is_value_field(field: str) -> bool:
    """Поле строки контактной информации, несущее значение (или его производную), — не тип,
    не номер строки, не дата действия и не ссылка."""
    return field not in ОТКРЫТЫЕ_ПОЛЯ and not field.endswith(("_Key", "_Type")) and "@" not in field


def is_structure_field(field: str) -> bool:
    """Поле, в котором значение контактной информации хранится структурой БСП (JSON или XML), —
    по имени: `Значение` и `ЗначенияПолей` табличной части и одноимённые хвосты полей вне неё
    (`АдресДоставкиЗначение`, `…ЗначенияПолей`). Ruling 38: в такое поле токен записывается,
    только если это значение в поле объекта уже лежит (`Unmasker.write`); собирать структуру по
    токену шлюз не берётся. Имя — не единственный признак: структура в текущем значении или в
    своих написаниях поля делает поле структурным при любом имени (`Unmasker._структурное`)."""
    return field.endswith(ПОЛЯ_СТРУКТУРЫ)


def self_type(text: str) -> str | None:
    """Тип контактной информации, записанный в самом значении: `type` в JSON поля `Значение`
    или xsi:type элемента `Состав` в XML поля `ЗначенияПолей` (JSON бывает и там — у записей,
    перенесённых из новой версии БСП). `None` — строка не является значением контактной
    информации или тип в ней не распознан (см. `is_contact_value`)."""
    текст = text.strip() if isinstance(text, str) else ""
    if текст.startswith("{"):
        документ = _json_объект(текст)
        if документ is not None:
            тип = документ.get("type")
            if isinstance(тип, str) and тип.strip() in ТИПЫ_ПЕРЕЧИСЛЕНИЯ:
                return тип.strip()
        return None
    if текст.startswith("<"):
        корень = _xml_корень(текст)
        if корень is None:
            return None
        for элемент in корень.iter():
            if etree.QName(элемент).localname == "Состав":
                тип = ТИП_ПО_XSI.get(_локальное_имя_типа(элемент.get(_XSI_TYPE)))
                if тип:
                    return тип
    return None


def is_contact_value(text: str) -> bool:
    """Строка — значение контактной информации: JSON с `type` из перечисления типов или XML с
    корнем `КонтактнаяИнформация` в пространстве имён БСП, даже если тип элемента `Состав` в нём
    неизвестен (тогда класс выводится из содержимого, но значение закрывается всё равно)."""
    текст = text.strip() if isinstance(text, str) else ""
    if текст.startswith("{"):
        return self_type(текст) is not None
    if текст.startswith("<"):
        return _xml_корень(текст) is not None
    return False


def is_structure(text: str) -> bool:
    """Формат написания для лестницы обратной подмены (Ruling 38, Р2-2 повторного ревью):
    структура — строка, из которой извлекается представление (`representation` — та же основа,
    по которой строится токен), или значение контактной информации БСП (`is_contact_value`, в
    том числе без представления). Иначе — текст.

    Почему не только `is_contact_value`. Маскировщик строит токен поля строки контактной
    информации по представлению ВСЕГДА, без проверки `type`; JSON `{"value": …}` без `type` из
    перечисления получал токен текстового представления, а лестница считала его текстом — и в
    текстовое поле уходил JSON целиком. Один признак на обе стороны: что даёт основу токена, то и
    структура. Маскировщик и основа токена не меняются — иначе изменились бы уже выданные токены
    (инвариант 5)."""
    if not isinstance(text, str):
        return False
    return is_contact_value(text) or representation(text) != text


def representation(text: str) -> str:
    """Текст значения, по которому строится токен: одно и то же значение в `Представление`
    (текст), в `Значение` (JSON с этим текстом в `value`) и в `ЗначенияПолей` (XML с ним в
    атрибуте `Представление` корня) должно получить ОДИН токен — иначе модель не сопоставит
    номер в двух полях одной строки. Поэтому основа токена — именно представление значения, а
    нормализация класса (`tokens.normalize_value`: у телефона — цифры, у почты — нижний регистр)
    применяется к нему, а не к JSON или XML целиком (цифры JSON целиком — это ещё и `version`,
    `countryCode`, `areaCode`, и токен вышел бы другим).

    Если представления в структуре нет (JSON без `value`, XML без атрибута, запись в старом
    формате «Ключ=Значение»), основа — сама строка: токен останется детерминированным, просто
    не совпадёт с токеном текстового поля."""
    if not isinstance(text, str):
        return text
    текст = text.strip()
    if текст.startswith("{"):
        документ = _json_объект(текст)
        if документ is not None:
            значение = документ.get("value")
            if isinstance(значение, str) and значение.strip():
                return значение
        return text
    if текст.startswith("<"):
        корень = _xml_корень(текст)
        if корень is not None:
            значение = корень.get(ПОЛЕ_ПРЕДСТАВЛЕНИЯ)
            if значение and значение.strip():
                return значение
    return text


def класс_по_содержимому(text: str) -> str:
    """Класс строки, тип которой неизвестен (см. `КЛАСС_ПО_ТИПУ`). Маскируется такая строка в
    любом случае — содержимое выбирает только КЛАСС токена: почта, если в представлении есть
    адрес почты; телефон, если в нём одни цифры и знаки записи номера (цифр от пяти); иначе
    `addr` — самый общий класс свободного текста (нормализация — только пробелы, регистр и
    знаки сохраняются). Детектор формы здесь не решает, закрыть или открыть, — только как
    назвать токен."""
    основа = representation(text) if isinstance(text, str) else ""
    if _ФОРМА_ПОЧТЫ.search(основа):
        return "email"
    # Раунд 3, I-1: БСП пишет добавочный номер в представление телефона словом
    # («+7 (4912) 12-34-56, доб. 123»), и прежде такая строка без `Тип` получала `addr`, а с
    # `Тип` — `phone`: один номер, два токена (инвариант 5). Хвост добавочного номера
    # отрезается ТОЛЬКО с конца и только за номером, который и без него — телефон.
    номер = _ДОБАВОЧНЫЙ.sub("", основа.strip())
    if _ФОРМА_ТЕЛЕФОНА.fullmatch(номер) and len(re.findall(r"\d", номер)) >= 5:
        return "phone"
    return "addr"


def row_type(row: Mapping) -> str | None:
    """Тип строки: поле `Тип`, а если его нет в ответе (не выбрано в `$select`) или оно пустое
    (сводная строка «вид для списка») — тип, записанный в самом значении (`self_type`).
    Считается по ВСЕЙ строке до маскировки её полей: иначе результат зависел бы от порядка
    ключей в ответе 1С."""
    тип = row.get(ПОЛЕ_ТИПА)
    if isinstance(тип, str) and тип.strip():
        return тип.strip()
    for поле in ПОЛЯ_СТРУКТУРЫ:
        найденный = self_type(row.get(поле))
        if найденный:
            return найденный
    return None


def _json_объект(текст: str) -> dict | None:
    try:
        документ = json.loads(текст)
    except (ValueError, RecursionError):
        return None
    return документ if isinstance(документ, dict) else None


# Разбор без сетевых обращений и без раскрытия сущностей: значение пришло из базы, это данные.
_ПАРСЕР_XML = etree.XMLParser(resolve_entities=False, no_network=True, huge_tree=False)


def _xml_корень(текст: str):
    try:
        корень = etree.fromstring(текст.encode("utf-8"), parser=_ПАРСЕР_XML)
    except (etree.XMLSyntaxError, ValueError):
        return None
    имя = etree.QName(корень)
    if имя.localname != "КонтактнаяИнформация" or имя.namespace != ПРОСТРАНСТВО_КИ:
        return None
    return корень


def _локальное_имя_типа(значение: str | None) -> str:
    """`xsi:type="НомерТелефона"` или с префиксом пространства имён (`d3p1:НомерТелефона`)."""
    if not значение:
        return ""
    return значение.rsplit(":", 1)[-1]
