"""Контактная информация БСП: класс защиты — по типу строки, а не по форме значения (Ruling 33).

Что это за данные. Любой справочник БСП, у которого есть телефоны, почта и адреса (контрагенты,
партнёры, физлица, пользователи, организации, склады, контактные лица партнёров), хранит их в
табличной части `КонтактнаяИнформация`. Одно и то же значение там лежит несколько раз и в разных
формах: текстом в `Представление`, JSON-объектом в `Значение` (`{"value": …, "type": "Телефон",
"countryCode": …, "areaCode": …, "number": …}`; у адреса — `ZIPcode`, `street`, `houseNumber`,
`apartments[]`), XML-документом в `ЗначенияПолей` (`<КонтактнаяИнформация Представление="…">`
с элементом `Состав`), а ещё служебными колонками для поиска: `НомерТелефона`,
`НомерТелефонаБезКодов`, `АдресЭП`, `ДоменноеИмяСервера`, `Страна`, `Регион`, `Город`.

Почему не детектор формы. До этой правки защищены были только колонки, чьё имя похоже на
телефон или почту (`НомерТелефона`, `АдресЭП` — класс по имени поля при реиндексе), а
`Представление`, `Значение`, `ЗначенияПолей` класса не имели и полагались на поиск по значению.
Поиск по значению угадывает форму номера и проигрывает всегда: форм у телефона больше, чем
шаблонов, а номер, разнесённый по ключам JSON (`areaCode: "4912"`, `number: "12-34-56"`), не
похож на телефон ни одной своей частью. На живой базе 13 телефонов из 87 доходили до модели
открытыми именно так (находка владельца, 2026-09-12).

Решение (Ruling 33, рубеж 1). Строка табличной части сама говорит, что в ней лежит, — полем
`Тип` (перечисление `ТипыКонтактнойИнформации`). Все поля значения строки маскируются ЦЕЛИКОМ
классом, который задан типом строки; модель видит тип в открытом поле `Тип` и значение токеном.

Распознавание — по строению, а не по списку имён сущностей: табличная часть контактной
информации — это сущность с полями `Тип`, `Представление` и хотя бы одним из `Значение` /
`ЗначенияПолей` (на полном `$metadata` УТ таких восемь, и больше ни одна сущность этой пары полей
не имеет). Строение берётся из индекса метаданных (`EntityShape`), а без него — по ключам самой
строки, когда в ней есть все три поля.
"""

from __future__ import annotations

import dataclasses
import json
import re
from collections.abc import Callable, Collection, Mapping

from lxml import etree

# Поле типа строки и поля, по которым табличная часть узнаётся (см. докстринг модуля).
ПОЛЕ_ТИПА = "Тип"
ПОЛЕ_ПРЕДСТАВЛЕНИЯ = "Представление"
ПОЛЯ_СТРУКТУРЫ = ("Значение", "ЗначенияПолей")

# Тип строки → класс гейта. Факс — телефонный номер. Адрес — `addr`, но открыт он или закрыт,
# решает политика адресов (`Policy.addr_masked`, Ruling 34) — у юрлица адрес открыт.
КЛАСС_ПО_ТИПУ: Mapping[str, str] = {
    "Телефон": "phone",
    "Факс": "phone",
    "АдресЭлектроннойПочты": "email",
    "Адрес": "addr",
}
# Прочие типы перечисления (`ВебСтраница`, `Skype`, `Другое`) и любое значение, которого нет в
# таблице выше (пустой `Тип` у сводных строк «вид для списка», тип из будущей версии БСП),
# маскируются ВСЕГДА — классом, выведенным из содержимого (`класс_по_содержимому`). Причина:
# веб-страница юрлица на уровне названий выдаёт само название (домен), учётная запись Skype и
# «Другое» — личные идентификаторы или тот же телефон, записанный свободным текстом. Открыть
# такое значение по правилу «адрес юрлица открыт» нельзя: это правило — про почтовый адрес из
# ЕГРЮЛ, а не про любой способ связи.

# Все члены перечисления `ТипыКонтактнойИнформации` (полный `$metadata` УТ, `EnumType`). По ним
# JSON значения узнаётся как значение контактной информации: ключ `type` с другим содержимым —
# чужой JSON, и правило к нему не применяется.
ТИПЫ_ПЕРЕЧИСЛЕНИЯ = frozenset(
    {"Телефон", "Факс", "АдресЭлектроннойПочты", "Адрес", "ВебСтраница", "Skype", "Другое"}
)

# Тип элемента `Состав` в XML `ЗначенияПолей` (xsi:type) → тип строки. Проверено на живой базе:
# у адреса два элемента `Состав` — внешний `Адрес` и вложенный `АдресРФ`.
ТИП_ПО_XSI: Mapping[str, str] = {
    "НомерТелефона": "Телефон",
    "НомерФакса": "Факс",
    "ЭлектроннаяПочта": "АдресЭлектроннойПочты",
    "Адрес": "Адрес",
    "АдресРФ": "Адрес",
}
ПРОСТРАНСТВО_КИ = "http://www.v8.1c.ru/ssl/contactinfo"
_XSI_TYPE = "{http://www.w3.org/2001/XMLSchema-instance}type"

# Поля строки, которые остаются открытыми: тип строки (без него модель не знает, что за токен
# перед ней), номер строки и дата начала действия (дата — инвариант 6). Ключи ссылок (`Вид_Key`,
# `ВидДляСписка_Key`, `Ref_Key`) и типы составных ссылок (`…_Type`) — GUID и имя набора, тоже
# инвариант 6; аннотации OData (`Имя@navigationLinkUrl`) вырезаются раньше, но и здесь не
# трогаются. ВСЁ ОСТАЛЬНОЕ строковое в строке — значение или его производная и маскируется: список
# открытых полей закрытый, а не список закрываемых, — поле, которое добавит следующая версия БСП,
# окажется закрытым, а не открытым.
ОТКРЫТЫЕ_ПОЛЯ = frozenset({ПОЛЕ_ТИПА, "LineNumber", "Ref_Key", "ДействуетС"})

# Форма телефона для вывода класса из содержимого у строк без известного типа: только цифры и
# знаки записи номера, и цифр не меньше пяти.
_ФОРМА_ТЕЛЕФОНА = re.compile(r"[\d\s()+\-.,/]+")
_ФОРМА_ПОЧТЫ = re.compile(r"[^\s@]+@[^\s@]+\.[^\s@]+")


@dataclasses.dataclass(frozen=True, slots=True)
class EntityShape:
    """Строение сущности по индексу метаданных: имена полей и родитель (для табличной части —
    объект-владелец). Гейт индекс не читает — строение ему отдаёт слой тулов (`Shape`)."""

    fields: frozenset[str]
    parent: str | None = None


# Имя сущности → её строение, либо `None`, если индекс о сущности не знает.
Shape = Callable[[str], EntityShape | None]


def is_contact_info_table(fields: Collection[str]) -> bool:
    """Строение табличной части контактной информации (см. докстринг модуля)."""
    поля = set(fields)
    return (
        ПОЛЕ_ТИПА in поля and ПОЛЕ_ПРЕДСТАВЛЕНИЯ in поля and any(п in поля for п in ПОЛЯ_СТРУКТУРЫ)
    )


def is_value_field(field: str) -> bool:
    """Поле строки контактной информации, несущее значение (или его производную), — не тип,
    не номер строки, не дата действия и не ссылка."""
    return field not in ОТКРЫТЫЕ_ПОЛЯ and not field.endswith(("_Key", "_Type")) and "@" not in field


def self_type(text: str) -> str | None:
    """Тип контактной информации, записанный в самом значении: `type` в JSON поля `Значение`
    или xsi:type элемента `Состав` в XML поля `ЗначенияПолей` (JSON бывает и там — у записей,
    перенесённых из новой версии БСП). `None` — строка не является значением контактной
    информации или тип в ней не распознан (см. `is_contact_value`)."""
    текст = text.strip() if isinstance(text, str) else ""
    if текст.startswith("{"):
        документ = _json_объект(текст)
        if документ is not None:
            тип = документ.get("type")
            if isinstance(тип, str) and тип.strip() in ТИПЫ_ПЕРЕЧИСЛЕНИЯ:
                return тип.strip()
        return None
    if текст.startswith("<"):
        корень = _xml_корень(текст)
        if корень is None:
            return None
        for элемент in корень.iter():
            if etree.QName(элемент).localname == "Состав":
                тип = ТИП_ПО_XSI.get(_локальное_имя_типа(элемент.get(_XSI_TYPE)))
                if тип:
                    return тип
    return None


def is_contact_value(text: str) -> bool:
    """Строка — значение контактной информации: JSON с `type` из перечисления типов или XML с
    корнем `КонтактнаяИнформация` в пространстве имён БСП, даже если тип элемента `Состав` в нём
    неизвестен (тогда класс выводится из содержимого, но значение закрывается всё равно)."""
    текст = text.strip() if isinstance(text, str) else ""
    if текст.startswith("{"):
        return self_type(текст) is not None
    if текст.startswith("<"):
        return _xml_корень(текст) is not None
    return False


def representation(text: str) -> str:
    """Текст значения, по которому строится токен: одно и то же значение в `Представление`
    (текст), в `Значение` (JSON с этим текстом в `value`) и в `ЗначенияПолей` (XML с ним в
    атрибуте `Представление` корня) должно получить ОДИН токен — иначе модель не сопоставит
    номер в двух полях одной строки. Поэтому основа токена — именно представление значения, а
    нормализация класса (`tokens.normalize_value`: у телефона — цифры, у почты — нижний регистр)
    применяется к нему, а не к JSON или XML целиком (цифры JSON целиком — это ещё и `version`,
    `countryCode`, `areaCode`, и токен вышел бы другим).

    Если представления в структуре нет (JSON без `value`, XML без атрибута, запись в старом
    формате «Ключ=Значение»), основа — сама строка: токен останется детерминированным, просто
    не совпадёт с токеном текстового поля."""
    if not isinstance(text, str):
        return text
    текст = text.strip()
    if текст.startswith("{"):
        документ = _json_объект(текст)
        if документ is not None:
            значение = документ.get("value")
            if isinstance(значение, str) and значение.strip():
                return значение
        return text
    if текст.startswith("<"):
        корень = _xml_корень(текст)
        if корень is not None:
            значение = корень.get(ПОЛЕ_ПРЕДСТАВЛЕНИЯ)
            if значение and значение.strip():
                return значение
    return text


def класс_по_содержимому(text: str) -> str:
    """Класс строки, тип которой неизвестен (см. `КЛАСС_ПО_ТИПУ`). Маскируется такая строка в
    любом случае — содержимое выбирает только КЛАСС токена: почта, если в представлении есть
    адрес почты; телефон, если в нём одни цифры и знаки записи номера (цифр от пяти); иначе
    `addr` — самый общий класс свободного текста (нормализация — только пробелы, регистр и
    знаки сохраняются). Детектор формы здесь не решает, закрыть или открыть, — только как
    назвать токен."""
    основа = representation(text) if isinstance(text, str) else ""
    if _ФОРМА_ПОЧТЫ.search(основа):
        return "email"
    if _ФОРМА_ТЕЛЕФОНА.fullmatch(основа.strip()) and len(re.findall(r"\d", основа)) >= 5:
        return "phone"
    return "addr"


def row_type(row: Mapping) -> str | None:
    """Тип строки: поле `Тип`, а если его нет в ответе (не выбрано в `$select`) или оно пустое
    (сводная строка «вид для списка») — тип, записанный в самом значении (`self_type`).
    Считается по ВСЕЙ строке до маскировки её полей: иначе результат зависел бы от порядка
    ключей в ответе 1С."""
    тип = row.get(ПОЛЕ_ТИПА)
    if isinstance(тип, str) and тип.strip():
        return тип.strip()
    for поле in ПОЛЯ_СТРУКТУРЫ:
        найденный = self_type(row.get(поле))
        if найденный:
            return найденный
    return None


def _json_объект(текст: str) -> dict | None:
    try:
        документ = json.loads(текст)
    except (ValueError, RecursionError):
        return None
    return документ if isinstance(документ, dict) else None


# Разбор без сетевых обращений и без раскрытия сущностей: значение пришло из базы, это данные.
_ПАРСЕР_XML = etree.XMLParser(resolve_entities=False, no_network=True, huge_tree=False)


def _xml_корень(текст: str):
    try:
        корень = etree.fromstring(текст.encode("utf-8"), parser=_ПАРСЕР_XML)
    except (etree.XMLSyntaxError, ValueError):
        return None
    имя = etree.QName(корень)
    if имя.localname != "КонтактнаяИнформация" or имя.namespace != ПРОСТРАНСТВО_КИ:
        return None
    return корень


def _локальное_имя_типа(значение: str | None) -> str:
    """`xsi:type="НомерТелефона"` или с префиксом пространства имён (`d3p1:НомерТелефона`)."""
    if not значение:
        return ""
    return значение.rsplit(":", 1)[-1]
