ОТКРЫТЫЕ_ПОЛЯ = frozenset({ПОЛЕ_ТИПА, "LineNumber", "Ref_Key", "ДействуетС"})

# Ruling 34, пункт 2: адрес лица, которое ведётся как физическое (контрагент вида
# `ИндивидуальныйПредприниматель` или `ФизЛицо`, партнёр `ЧастноеЛицо`), — это домашний адрес
# человека, и он закрыт, как адрес физлица. Открыт адрес только у лица, которое ЯВНО юридическое:
# перечислены открытые виды, а не закрытые — пустое значение, вид из будущей версии конфигурации
