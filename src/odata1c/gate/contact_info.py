"""Контактная информация БСП: класс защиты — по типу строки, а не по форме значения (Ruling 33).

Что это за данные. Любой справочник БСП, у которого есть телефоны, почта и адреса (контрагенты,
партнёры, физлица, пользователи, организации, склады, контактные лица партнёров), хранит их в
табличной части `КонтактнаяИнформация`. Одно и то же значение там лежит несколько раз и в разных
формах: текстом в `Представление`, JSON-объектом в `Значение` (`{"value": …, "type": "Телефон",
"countryCode": …, "areaCode": …, "number": …}`; у адреса — `ZIPcode`, `street`, `houseNumber`,
`apartments[]`), XML-документом в `ЗначенияПолей` (`<КонтактнаяИнформация Представление="…">`
с элементом `Состав`), а ещё служебными колонками для поиска: `НомерТелефона`,
`НомерТелефонаБезКодов`, `АдресЭП`, `ДоменноеИмяСервера`, `Страна`, `Регион`, `Город`.

Почему не детектор формы. До этой правки защищены были только колонки, чьё имя похоже на
телефон или почту (`НомерТелефона`, `АдресЭП` — класс по имени поля при реиндексе), а
`Представление`, `Значение`, `ЗначенияПолей` класса не имели и полагались на поиск по значению.
Поиск по значению угадывает форму номера и проигрывает всегда: форм у телефона больше, чем
шаблонов, а номер, разнесённый по ключам JSON (`areaCode: "4912"`, `number: "12-34-56"`), не
похож на телефон ни одной своей частью. На живой базе 13 телефонов из 87 доходили до модели
открытыми именно так (находка владельца, 2026-09-12).

Решение (Ruling 33, рубеж 1). Строка табличной части сама говорит, что в ней лежит, — полем
`Тип` (перечисление `ТипыКонтактнойИнформации`). Все поля значения строки маскируются ЦЕЛИКОМ
классом, который задан типом строки; модель видит тип в открытом поле `Тип` и значение токеном.

Распознавание — по строению, а не по списку имён сущностей: табличная часть контактной
информации — это сущность с полями `Тип`, `Представление` и хотя бы одним из `Значение` /
`ЗначенияПолей` (на полном `$metadata` УТ таких восемь, и больше ни одна сущность этой пары полей
не имеет). Строение берётся из индекса метаданных (`EntityShape`), а без него — по ключам самой
строки, когда в ней есть все три поля.
"""

